ഞാൻ എന്റെ സിനമൺ റോളിന്റെ അവസാന കഷ്ണം കഴിക്കുന്നു.
അതിന് വളരെ നല്ല രുചിയുണ്ട്.
പക്ഷേ അത് വളരെ മധുരമുള്ളതുമാണ്.
എന്റെ കോഫി കപ്പ് പൂർണ്ണമായും കാലിയാണ്.
എനിക്ക് പെട്ടെന്ന് നല്ല ദാഹം തോന്നുന്നു.
എനിക്ക് കുറച്ചു തണുത്ത വെള്ളം വേണം.
ഒരു ചെറുപ്പക്കാരൻ എന്റെ ടേബിളിനരികിലൂടെ നടന്നുപോകുന്നു.
അയാൾ ഈ കഫേയിലാണ് ജോലി ചെയ്യുന്നത്.
അയാൾ ഒഴിഞ്ഞ കപ്പുകളും പ്ലേറ്റുകളും ശേഖരിക്കുന്നു.
ഞാൻ അയാളുടെ ശ്രദ്ധ പിടിച്ചുപറ്റുന്നു.
അയാൾ എന്റെ ടേബിളിനടുത്ത് നിന്നിട്ട് പുഞ്ചിരിക്കുന്നു.
"ക്ഷമിക്കണം," ഞാൻ വിനയത്തോടെ പറയുന്നു.
"എന്താണ്?" ആ ചെറുപ്പക്കാരൻ മറുപടി പറയുന്നു.
"എനിക്ക് ഒരു ഗ്ലാസ് ടാപ്പ് വെള്ളം കിട്ടുമോ?" ഞാൻ ചോദിക്കുന്നു.
"അതെ, തീർച്ചയായും," അയാൾ പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
അയാൾ എന്റെ ഒഴിഞ്ഞ പ്ലേറ്റും കപ്പും എടുക്കുന്നു.
അയാൾ കൗണ്ടറിലേക്ക് തിരികെ നടക്കുന്നു.
കുറച്ചുകഴിഞ്ഞ് അയാൾ ഒരു ഗ്ലാസ് തണുത്ത വെള്ളവുമായി വരുന്നു.
