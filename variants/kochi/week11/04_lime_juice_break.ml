ഇപ്പോൾ ഉച്ചഭക്ഷണത്തിന്റെ സമയമാണ്.
ഞാൻ ഓഫീസിൽ നിന്ന് പുറത്തിറങ്ങുന്നു.
പുറത്ത് നല്ല വെയിലാണ്.
റോഡിൽ നല്ല ചൂടാണ്.
ഞാൻ അടുത്തുള്ള ഒരു ജ്യൂസ് കടയിൽ പോകുന്നു.
ഞാൻ കടക്കാരനോട് ഒരു നാരങ്ങാവെള്ളം ചോദിക്കുന്നു.
"ഒരു തണുത്ത നാരങ്ങാവെള്ളം വേണം," ഞാൻ പറയുന്നു.
"മധുരം വേണോ ഉപ്പ് വേണോ?" അദ്ദേഹം ചോദിക്കുന്നു.
"മധുരം മതി," ഞാൻ മറുപടി പറയുന്നു.
അദ്ദേഹം എനിക്ക് നാരങ്ങാവെള്ളം തരുന്നു.
ഞാൻ അത് കുടിക്കുന്നു.
അതിന് നല്ല തണുപ്പാണ്.
ഈ ചൂടിൽ ഇത് വളരെ നല്ലതാണ്.
ഇതിന് ഇരുപത് രൂപയാണ്.
ഞാൻ ഇരുപത് രൂപ കൊടുക്കുന്നു.
ഞാൻ വീണ്ടും ഓഫീസിലേക്ക് നടക്കുന്നു.
