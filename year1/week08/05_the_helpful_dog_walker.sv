Jag står på en lugn gata.
Jag har gått vilse.
Framför mig ser jag en ung kvinna.
Hon går en promenad med en liten hund.
Hunden liknar min familjs hund, Lola.
Jag går fram till kvinnan.
"Ursäkta," säger jag.
"Jag letar efter hamnen."
Kvinnan stannar och lyssnar.
Hon pekar tillbaka uppför gatan.
"Gå rakt fram, tillbaka till torget," säger hon.
"Och sväng höger vid museet."
"Tack så mycket för hjälpen," säger jag.
"Det var så lite," svarar kvinnan.
Jag tittar ner på den lilla hunden.
Den tittar på mig.
Jag går tillbaka mot torget.
Nu vet jag var jag är.
