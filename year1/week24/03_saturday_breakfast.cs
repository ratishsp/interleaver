Je sobota ráno, sedm hodin.
Ještě tvrdě spím.
Najednou na paži ucítím něco studeného.
Otevřu oči a vidím Ludwiga.
Šťouchne do mě čenichem.
„Dobré ráno, Ludwigu,“ řeknu a vstanu.
Jdeme spolu do kuchyně.
Má velký hlad a skáče na mě.
„Klid, Ludwigu,“ řeknu mu.
„Sedni,“ řeknu klidně.
Podívá se na mě a sedne si na zem.
Vezmu pytel s psím krmivem a otevřu ho.
Nasypu krmivo do jeho misky.
Zvedne se, protože to chce hned.
„Ne, počkej,“ řeknu.
Znovu si sedne a hezky čeká.
Položím misku před něj.
Jemně ho pohladím po hlavě.
„Tady máš, jez,“ řeknu s úsměvem.
Zavrtí ocasem a začne jíst.
