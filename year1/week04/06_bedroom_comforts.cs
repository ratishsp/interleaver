Jdu do ložnice.
Nesu si kufr z obývacího pokoje.
Otevírám kufr.
Vyndávám své oblečení.
Skládám oblečení.
Dávám ho do skříně.
Teď leží moje svetry ve skříni.
V pokoji je velká postel.
Na posteli leží silná deka.
Ta deka je z Mexika.
Také nacházím pár bačkor.
Jsou velmi měkké.
U zdi stojí malá židle.
Pokládám své bačkory na podlahu.
Teď leží pod židlí.
Teď je kufr prázdný.
Zavírám ho a dávám ho pod postel.
