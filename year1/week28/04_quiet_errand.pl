W piątek po południu idę na spokojny spacer w słońcu.
Niosę moją ciężką zimową kurtkę.
Wcale jej już nie potrzebuję.
Zatrzymuję się przed lokalną pralnią chemiczną.
Otwieram drzwi i wchodzę do środka.
W małym sklepie pachnie czystymi ubraniami i mydłem.
Za ladą stoi starszy mężczyzna.
"Dzień dobry, chciałabym oddać tę kurtkę do czyszczenia", mówię.
Podaję dużą kurtkę przez ladę.
"Oczywiście", odpowiada mężczyzna i ogląda materiał.
"Będzie gotowa w środę", mówi.
"To będzie dwieście pięćdziesiąt koron."
Wyciągam z torby moją kartę płatniczą.
Płacę przy kasie i dostaję mały żółty paragon.
"Bardzo dziękuję, miłego weekendu", mówię.
"Nawzajem", odpowiada z uśmiechem.
Wkładam paragon do torby.
Potem znów wychodzę na ruchliwy chodnik.
Cieszę się spacerem w ciepłym popołudniowym słońcu.
