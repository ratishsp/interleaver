ഞാൻ എന്റെ കഥ തുടർന്നു.
"അടുത്ത ആഴ്ച ഞാൻ ഇൻഫോപാർക്കിലെ ഓഫീസിൽ പോയി," ഞാൻ പറഞ്ഞു.
"അന്ന് എനിക്ക് വലിയ പേടി ഉണ്ടായിരുന്നു."
"ഞാൻ പതുക്കെ ഓഫീസിന് ഉള്ളിലേക്ക് നടന്നു."
"എനിക്ക് ഓഫീസിൽ ആരെയും പരിചയം ഇല്ലായിരുന്നു."
"പക്ഷേ വാതിൽക്കൽ വെച്ച് ഒരു സഹപ്രവർത്തകൻ എന്നെ സ്വാഗതം ചെയ്തു."
"അദ്ദേഹത്തിന്റെ പേര് പ്രകാശ് എന്നായിരുന്നു."
"അദ്ദേഹം എന്നെ എന്റെ പുതിയ ഡെസ്കിലേക്ക് കൂട്ടിക്കൊണ്ടുപോയി."
"പ്രകാശ് വളരെ സ്നേഹത്തോടെ എന്നോട് സംസാരിച്ചു."
"എന്റെ പുതിയ കമ്പ്യൂട്ടർ ഉപയോഗിക്കാൻ അദ്ദേഹം എന്നെ സഹായിച്ചു."
"അതുകൊണ്ട് എന്റെ പേടി പെട്ടെന്ന് മാറി."
സാറ ഇത് കേട്ട് തലയാട്ടി.
"എന്റെ ആദ്യത്തെ ജോലി ദിവസവും ഇതുപോലെ തന്നെ ആയിരുന്നു," സാറ പറഞ്ഞു.
"ഞാനും അന്ന് ഒരുപാട് പേടിച്ചു."
ഞാനും കിരണും അത് കേട്ട് ചിരിച്ചു.
