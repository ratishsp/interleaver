Beru si telefon.
Otevírám svůj kalendář.
Dívám se na čtvrtek.
Najednou vidím problém.
Mám termín u kadeřníka v půl páté.
Moje káva s Ninou je také v půl páté!
Okamžitě posílám Nině SMS.
Píšu: „Ahoj Nino, promiň.“
„Mám termín u kadeřníka ve čtvrtek v půl páté.“
„Máš místo toho čas v šest hodin?“
Nina odpovídá velmi rychle.
Píše: „Žádný problém!“
„Uvidíme se v šest hodin.“
Usmívám se a měním čas v kalendáři.
Teď můj čtvrtek vychází perfektně.
