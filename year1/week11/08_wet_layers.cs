Odemykám dveře.
Konečně jsem doma ve svém bytě.
Venku je mokro a větrno.
Ale tady uvnitř je teplo.
Moje zimní bunda je velmi mokrá.
Sundávám si bundu.
Z mého deštníku také kape voda.
Jdu do koupelny.
Pokládám deštník na podlahu.
Voda kape dolů na dlaždice.
Pak jdu do obývacího pokoje.
Tady uvnitř je úplná tma.
Skoro nic nevidím.
V rohu stojí malá lampa.
Rozsvěcím lampu.
Světlo je žluté a měkké.
V obývacím pokoji je okamžitě světleji.
Teď je v obývacím pokoji teplo a světlo.
Je příjemné být teď uvnitř.
