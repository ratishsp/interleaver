ഞാൻ ഒരു ചെറിയ സ്റ്റാളിന് മുന്നിലൂടെ നടക്കുന്നു.
അവിടെ പുതിയ ബ്രെഡിന്റെ മണമുണ്ട്.
ഞാൻ സ്റ്റാളിന്റെ അടുത്തേക്ക് നടക്കുന്നു.
ബേക്കർ ഒരു വലിയ മേശയ്ക്ക് പിന്നിൽ നിൽക്കുന്നു.
മേശ നിറയെ ബേക്ക് ചെയ്ത വിഭവങ്ങളാണ്.
ഞാൻ ഒരു ഇരുണ്ട റൈ ബ്രെഡ് കാണുന്നു.
അത് വളരെ പുതിയതാണെന്ന് തോന്നുന്നു.
ഞാൻ ആ റൈ ബ്രെഡിലേക്ക് വിരൽ ചൂണ്ടുന്നു.
"ആ ഇരുണ്ട റൈ ബ്രെഡിന് എത്രയാണ് വില?" ഞാൻ ചോദിക്കുന്നു.
ബേക്കർ തന്റെ കൈകൾ തുടയ്ക്കുന്നു.
"അതിന് മുപ്പത്തിയഞ്ച് ക്രോണർ ആണ് വില," അയാൾ മറുപടി നൽകുന്നു.
"ഞാനത് വാങ്ങുകയാണ്," ഞാൻ പറയുന്നു.
ഞാൻ എന്റെ പേയ്‌മെന്റ് കാർഡ് പുറത്തെടുക്കുന്നു.
ഞാൻ കാർഡ് ഉപയോഗിച്ച് പണമടയ്ക്കുന്നു.
ബേക്കർ ഒരു പേപ്പർ ബാഗിലാക്കി എനിക്ക് ബ്രെഡ് തരുന്നു.
ഞാൻ ആ ബാഗിൽ തൊടുന്നു.
ബ്രെഡിന് ഇപ്പോഴും ചൂടുണ്ട്.
അത് കഴിക്കാൻ ഞാൻ കാത്തിരിക്കുകയാണ്.
