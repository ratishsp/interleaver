Vi sätter oss vid mitt lilla bord.
Det är lite trångt, men vi sitter tätt och bra.
Först ställer jag skålarna med mat på bordet.
Därefter tar Kasper och Sara en stor portion.
De smakar på köttbullarna och potatisen.
"Det smakar verkligen jättegott, Maya!" säger Sara.
"Ja, de är verkligen goda," säger Kasper.
Han tar snabbt en tugga till.
Kasper öppnar också de kalla ölen.
Sedan häller han upp dem i våra glas.
"Skål!" säger vi alla tre och dricker.
Kasper tar fler köttbullar från fatet.
Sara tar också en extra portion potatis.
"Jag är så glad att ni tycker om det," säger jag.
"Det finns rikligt till alla," ler jag.
De berömmer den autentiska smaken.
Vi pratar och skrattar runt bordet.
Vi äter och pratar länge.
