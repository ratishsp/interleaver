ഒമ്പത് മണിക്ക് അല്പം ശേഷം ഞാൻ ഓഡൻസിൽ എത്തി.
ഞാൻ സ്റ്റേഷനിൽ നിന്ന് ഇറങ്ങി നേരെ പഴയ നഗരഭാഗത്തേക്ക് നടന്നു.
നല്ല വെയിലുണ്ടായിരുന്നു, ഞാൻ ശുദ്ധമായ വസന്തകാലവായു ആസ്വദിച്ചു.
ചെറിയൊരു നടത്തത്തിന് ശേഷം നഗരത്തിന് മാറ്റം വന്നു.
പെട്ടെന്ന്, കരിങ്കല്ലുകൾ പാകിയ ഒരു ഇടുങ്ങിയ തെരുവിൽ ഞാൻ നിന്നു.
ആ കരിങ്കല്ലുകൾ പഴകി തേഞ്ഞതായിരുന്നു.
ഞാൻ അവിടെയുണ്ടായിരുന്ന ഒരുപാട് ചെറിയ വീടുകളിലേക്ക് നോക്കി.
അവ തെരുവിലൂടെ ഒന്നിനൊന്ന് ചേർന്ന് ഒരു വരിയായി സ്ഥിതി ചെയ്തിരുന്നു.
മിക്കവാറും എല്ലാ വീടുകളും കാണാൻ രസമുള്ളതും വളരെ ചെരിഞ്ഞതുമായിരുന്നു.
ഓരോ വീടും അതിന്റേതായ വ്യക്തിത്വം പ്രകടിപ്പിച്ചിരുന്നു.
അവയിൽ പലതിലും മനോഹരവും തിളക്കമുള്ളതുമായ നിറങ്ങൾ അടിച്ചിരുന്നു.
ഞാൻ പ്രത്യേകിച്ച് മഞ്ഞയും ചുവപ്പും നിറത്തിലുള്ള വീടുകൾ ശ്രദ്ധിച്ചു.
ആ വർണ്ണാഭമായ ചുവരുകൾ വസന്തകാലത്തെ വെയിലിൽ തിളങ്ങിനിന്നു.
നഗരത്തിന്റെ ആ പഴയ ഭാഗം എനിക്ക് ശരിക്കും ഇഷ്ടമായി.
ഞാൻ ആ ചെരിഞ്ഞ വീടുകൾ നോക്കിക്കൊണ്ട് ഒരുപാട് നേരം നിന്നു.
ഓരോ വീടിനും അതിന്റേതായ ഉന്മേഷം നൽകുന്ന നിറമുണ്ടായിരുന്നു.
ഈ തെരുവ് എന്നെന്നേക്കുമായി ഓർത്തിരിക്കാൻ ഞാൻ ആഗ്രഹിച്ചു.
അതിനുശേഷം, ഞാൻ പതുക്കെ ആ തെരുവിലൂടെ മുന്നോട്ട് നടന്നു.
