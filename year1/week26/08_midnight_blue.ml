രാത്രി ഏകദേശം പന്ത്രണ്ട് മണിയായി, എങ്കിലും ആകാശം ഇപ്പോഴും പ്രകാശമാനമാണ്.
അതിന് മൃദുവായ, നീല നിറമാണ്.
ഞാൻ ഈവയ്ക്കും പീറ്ററിനുമൊപ്പം തെരുവിലൂടെ നടക്കുകയാണ്.
ഞങ്ങൾ അധികം സംസാരിക്കുന്നില്ല.
രാത്രിയിൽ ഞങ്ങളുടെ കാൽച്ചുവടുകളുടെ ശബ്ദം മാത്രമേ കേൾക്കുന്നുള്ളൂ.
ഞാൻ എൻ്റെ സുഹൃത്തുക്കളെ നോക്കുന്നു.
ഈവ ചിരിക്കുന്നുണ്ട്, പീറ്റർ ക്ഷീണിതനാണെങ്കിലും സന്തോഷവാനാണെന്ന് തോന്നുന്നു.
ഞാൻ ഇവിടെ വന്നപ്പോൾ എനിക്ക് ആരെയും പരിചയമുണ്ടായിരുന്നില്ല.
എന്നാൽ അതിനുശേഷം ഒരുപാട് കാര്യങ്ങൾ മാറി.
എനിക്ക് നല്ലൊരു നിത്യജീവിതം ലഭിച്ചു, കൂടാതെ ഞാൻ ഒരുപാട് ആളുകളെ കണ്ടുമുട്ടുകയും ചെയ്തു.
സത്യത്തിൽ എനിക്ക് യഥാർത്ഥ സുഹൃത്തുക്കളെ കണ്ടെത്താൻ കഴിഞ്ഞു.
ഞാൻ ആദ്യം സംസാരിച്ച സഹപ്രവർത്തകൻ പീറ്ററായിരുന്നു.
ഈയിടെ ഈവ എന്നെ അവളുടെ വീട്ടിലേക്ക് ക്ഷണിക്കുകയും ചെയ്തു.
ഇപ്പോൾ ഞങ്ങൾ ഈ പ്രകാശമാനമായ വേനൽക്കാല ആകാശത്തിന് കീഴിൽ ഒരുമിച്ച് നടക്കുകയാണ്.
എനിക്കിപ്പോൾ മുപ്പത്തിരണ്ട് വയസ്സ് തികഞ്ഞതേയുള്ളൂ.
ഞാൻ ഇഷ്ടപ്പെടുന്ന ഒരു ജീവിതം ഞാൻ പടുത്തുയർത്തിയിരിക്കുന്നു.
ഒടുവിൽ എൻ്റെ പുതിയ നഗരം തികച്ചും സ്വന്തം വീടുപോലെ എനിക്ക് തോന്നുന്നു.
