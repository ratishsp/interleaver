Jdu k pekařskému pultu.
Ta vůně je velmi dobrá.
Mám ráda sladké pečivo.
A opravdu mám ráda skořicové šneky.
Za pultem stojí pekař.
Pekař se na mě dívá.
Usmívá se.
„Co byste si přála?“ ptá se pekař.
Ukazuji na skořicového šneka.
To pečivo vypadá lahodně.
„Chtěla bych jednoho skořicového šneka, prosím,“ říkám.
„Ano, samozřejmě,“ říká pekař.
Bere to pečivo.
Dává pečivo do sáčku.
Podává sáček přes pult.
„Tady máte,“ říká.
Beru si sáček.
„Moc děkuji,“ říkám.
Dávám sáček do košíku.
