ഞാൻ നഗരത്തിലെ ഒരു വലിയ ചത്വരത്തിലൂടെ നടക്കാൻ പോകുന്നു.
ഇവിടെ എല്ലാ ഞായറാഴ്ചയും ഒരു വലിയ ഫ്ലീ മാർക്കറ്റ് ഉണ്ട്.
സൂര്യൻ പ്രകാശിക്കുന്നു, കൂടാതെ മേശകൾക്കിടയിലൂടെ ധാരാളം ആളുകൾ നടക്കുന്നുണ്ട്.
പലവിധത്തിലുള്ള ധാരാളം സാധനങ്ങളുള്ള ഒരു ചെറിയ മേശയ്ക്കരികിൽ ഞാൻ നിൽക്കുന്നു.
മേശയ്ക്ക് പിന്നിലായി വളരെ സൗഹാർദ്ദപരമായ ഒരു കച്ചവടക്കാരൻ നിൽക്കുന്നു.
പെട്ടെന്ന് ഞാൻ രണ്ട് നീല സെറാമിക് പ്ലേറ്റുകൾ കാണുന്നു.
ഞാൻ അവ കൈയിലെടുത്ത് സൂക്ഷ്മമായി നോക്കുന്നു.
"ഈ പ്ലേറ്റുകൾക്ക് എന്താണ് വില?" ഞാൻ കച്ചവടക്കാരനോട് ചോദിക്കുന്നു.
കച്ചവടക്കാരൻ എന്നെ നോക്കി പുഞ്ചിരിക്കുന്നു.
"അവയ്ക്ക് വെറും നാൽപ്പത് ക്രോണർ മാത്രമേ വിലയുള്ളൂ," അദ്ദേഹം മറുപടി നൽകുന്നു.
അത് വളരെ നല്ലൊരു വിലയാണ്.
ഒരു മാസം മുൻപ് ഞാൻ എൻ്റെ അടുക്കളയ്ക്കായി ഒരു ചെറിയ മേശ വാങ്ങിയിരുന്നു.
ഈ പ്ലേറ്റുകൾ ഈ മേശയ്ക്ക് തികച്ചും അനുയോജ്യമായിരിക്കും.
"ഇവ വാങ്ങാൻ ഞാൻ വളരെയധികം ആഗ്രഹിക്കുന്നു," ഞാൻ പറയുന്നു.
ഞാൻ കച്ചവടക്കാരന് നാൽപ്പത് ക്രോണർ നൽകുകയും പ്ലേറ്റുകൾ ശ്രദ്ധാപൂർവ്വം എൻ്റെ ബാഗിൽ വെക്കുകയും ചെയ്യുന്നു.
ശാന്തമായ ഒരു ഞായറാഴ്ചയിൽ സവിശേഷമായ എന്തെങ്കിലും കണ്ടെത്തുന്നത് എപ്പോഴും സന്തോഷകരമാണ്.
