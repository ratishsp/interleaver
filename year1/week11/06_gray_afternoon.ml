ഞാൻ ഓഫീസിൽ എൻ്റെ ഡെസ്കിൽ ഇരിക്കുന്നു.
ഞാൻ എൻ്റെ കമ്പ്യൂട്ടറിൽ കോഡ് എഴുതുന്നു.
ഞാൻ ജനലിലൂടെ പുറത്തേക്ക് നോക്കുന്നു.
ഇന്ന് കാലാവസ്ഥ വളരെ മോശമാണ്.
ആകാശം ഇരുണ്ടതും കനത്തതുമാണ്.
പുറത്ത് പൂർണ്ണമായും ചാരനിറമാണ്.
ഗ്ലാസ്സിൽ തുടർച്ചയായി മഴ പതിക്കുന്നു.
നല്ല കാറ്റും വീശുന്നുണ്ട്.
ഞാൻ ചുവരിലെ ക്ലോക്കിലേക്ക് നോക്കുന്നു.
സമയം ഉച്ച കഴിഞ്ഞതേയുള്ളൂ.
എന്നാൽ വളരെ വേഗം അന്തരീക്ഷം മ്ലാനമാകുന്നു.
ചാരനിറത്തിലുള്ള ആകാശത്തേക്ക് വെളിച്ചം മറയുന്നു.
ഈ സീസണിൽ നേരത്തെ തന്നെ ഇരുട്ടാകുന്നു.
ഡെന്മാർക്കിലെ ഒരു സാധാരണ ശീതകാല ഉച്ചതിരിഞ്ഞ സമയമാണിത്.
പുറത്ത് കാറ്റിൽ നല്ല തണുപ്പുണ്ട്.
എന്നാൽ ഇവിടെ അകത്ത് സുഖകരമായ ചൂടുണ്ട്.
ഞാൻ എൻ്റെ കപ്പിൽ നിന്ന് കുറച്ചു ചൂട് കോഫി കുടിക്കുന്നു.
ഞാൻ ഒരു മിനിറ്റ് മഴയുടെ ശബ്ദം ശ്രദ്ധിക്കുന്നു.
പിന്നീട് ഞാൻ വീണ്ടും എൻ്റെ കമ്പ്യൂട്ടർ സ്ക്രീനിലേക്ക് നോക്കുന്നു.
ഞാൻ എൻ്റെ കോഡ് എഴുതുന്നത് തുടരുന്നു.
