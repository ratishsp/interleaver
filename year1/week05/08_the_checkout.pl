Podchodzę do kasy.
Mam w ręku koszyk.
Kładę jedzenie na taśmie.
Najpierw wyjmuję chleb żytni z koszyka.
Potem wyjmuję mleko i pasternak.
Biorę też marchewki i czarną fasolę.
Na koniec kładę ciastko na taśmie.
Kasjer siedzi za kasą.
Uśmiecha się do mnie.
„Dzień dobry” – mówi.
„Dzień dobry” – odpowiadam.
Szybko skanuje jedzenie.
Wyciągam kartę.
Trzymam kartę nad terminalem.
Terminal pika.
„Czy chciałaby pani paragon?” – pyta.
„Tak, poproszę, chciałabym paragon” – mówię.
Otwieram torbę.
Szybko pakuję torbę.
„Miłego dnia” – mówi.
