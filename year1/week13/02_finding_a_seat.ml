ഞാൻ ഇപ്പോൾ കഫേയ്ക്കുള്ളിലാണ്.
ഇവിടെ നല്ല ചൂടുണ്ട്.
ഞാൻ എൻ്റെ കട്ടിയുള്ള വിൻ്റർ കോട്ട് ഊരി മാറ്റുന്നു.
അതിന് നല്ല ഭാരമുണ്ട്.
ചുമരിൽ ഞാൻ ഒരു കൊളുത്ത് കണ്ടെത്തുന്നു.
ഞാൻ ആ കൊളുത്തിൽ എൻ്റെ കോട്ട് തൂക്കിയിടുന്നു.
ഞാൻ എൻ്റെ സ്കാർഫും കയ്യുറകളും കൂടി ഊരി മാറ്റുന്നു.
ഈ കഫേ ചെറുതും സുഖകരവുമാണ്.
ഞാൻ ഇരിക്കാൻ നല്ലൊരു സ്ഥലം തിരയുന്നു.
ജനലിനരികിൽ ഒരു ചെറിയ മേശയുണ്ട്.
മേശ ഒരു റേഡിയേറ്ററിന് അടുത്താണ്.
ഞാൻ ആ മേശയുടെ അടുത്തേക്ക് നടക്കുന്നു.
ഞാൻ ആ കസേരയിൽ ഇരിക്കുന്നു.
എൻ്റെ കൈകൾക്ക് ഇപ്പോഴും തണുപ്പുണ്ട്.
ഞാൻ അവ തമ്മിൽ തിരുമ്മുന്നു.
എൻ്റെ കൈകൾക്ക് കൂടുതൽ ചൂട് വരുന്നു.
അത് വളരെ മികച്ചതായി തോന്നുന്നു.
ഇപ്പോൾ എനിക്ക് ഏകദേശം ചൂടായി.
എനിക്ക് വിശപ്പും ദാഹവുമുണ്ട്.
എനിക്ക് ഇപ്പോൾ എന്തെങ്കിലും ഓർഡർ ചെയ്യണം.
