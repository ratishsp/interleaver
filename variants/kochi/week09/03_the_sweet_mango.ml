അടുത്ത് ഒരു പഴക്കട ഞാൻ കാണുന്നു.
അവിടെ ഒരു സ്ത്രീ നല്ല പുതിയ മാമ്പഴം വിൽക്കുന്നുണ്ട്.
മാമ്പഴം കാണാൻ നല്ല ഭംഗിയുണ്ട്.
അവർ എന്നെ നോക്കി ചിരിക്കുന്നു.
അവർ ഒരു മഞ്ഞ മാമ്പഴത്തിന്റെ ചെറിയ കഷ്ണം മുറിക്കുന്നു.
എന്നിട്ട് അവർ അത് എനിക്ക് തരുന്നു.
"ഇതൊന്ന് കഴിച്ചു നോക്കൂ," അവർ പറയുന്നു.
ഞാൻ ആ മാമ്പഴം രുചിച്ചു നോക്കുന്നു.
ഇതിന് നല്ല മധുരമുണ്ട്!
"ഇത് വളരെ രുചികരമാണ്," ഞാൻ പറയുന്നു.
"ഒരു കിലോയ്ക്ക് എൺപതു രൂപയാണ്," ആ സ്ത്രീ പറയുന്നു.
ഞാൻ എന്റെ തുണിസഞ്ചി തുറക്കുന്നു.
"എനിക്ക് ഒരു കിലോ മാമ്പഴം വേണം," ഞാൻ പറയുന്നു.
"ഒരു കിലോ പായ്ക്ക് ചെയ്തു തരൂ."
അവർ മാമ്പഴം നന്നായി പായ്ക്ക് ചെയ്യുന്നു.
ഞാൻ പഴ്സിൽ നിന്ന് ഒരു നൂറു രൂപയുടെ നോട്ട് എടുക്കുന്നു.
ഞാൻ ആ പണം അവർക്ക് കൊടുക്കുന്നു.
അവർ എനിക്ക് ബാക്കി ഇരുപതു രൂപ തിരികെ തരുന്നു.
ഞാൻ അവർക്ക് നന്ദി പറയുന്നു.
ഞാൻ സന്തോഷത്തോടെ മാമ്പഴം വാങ്ങുന്നു.
