ഞാൻ എന്റെ മുറിയിലേക്ക് തിരികെ വരുന്നു.
എന്റെ കയ്യിൽ ഒരു പെട്ടി മധുരപലഹാരങ്ങൾ ഉണ്ട്.
ഞാൻ ആ പെട്ടി ഒരു ചെറിയ മേശപ്പുറത്ത് വെക്കുന്നു.
അതിനുശേഷം, ഞാൻ എന്റെ ലാപ്ടോപ്പ് തുറക്കുന്നു.
ഞാൻ എന്റെ കുടുംബത്തിന് വീഡിയോ കോൾ ചെയ്യുന്നു.
ഇപ്പോൾ കൊച്ചിയിൽ ഞായറാഴ്ച രാവിലെ ആണ്.
പക്ഷേ മെക്സിക്കോയിൽ ഇത് ശനിയാഴ്ച രാത്രി ആണ്.
ലാപ്ടോപ്പിൽ സ്ക്രീൻ തെളിയുന്നു.
ഞാൻ എന്റെ അമ്മയെയും അച്ഛനെയും കാണുന്നു.
അവർ അവരുടെ സ്വീകരണമുറിയിൽ ആണ്.
അവരുടെ മുഖത്ത് വലിയ ചിരി ഉണ്ട്.
അമ്മ ചോദിക്കുന്നു, "മായ, നിനക്ക് സുഖമാണോ?"
ഞാൻ ചിരിച്ചുകൊണ്ട് പറയുന്നു, "എനിക്ക് സുഖമാണ്, അമ്മേ."
അച്ഛൻ ചോദിക്കുന്നു, "നിന്റെ പുതിയ മുറി നല്ലതാണോ?"
ഞാൻ പറയുന്നു, "അതെ അച്ഛാ, നല്ല മുറിയാണ്."
പിന്നെ ഞാൻ അവരോട് ചോദിക്കുന്നു, "ഇപ്പോൾ വീട്ടിൽ വേറെ ആര് ഉണ്ട്?"
അമ്മ പറയുന്നു, "നിന്റെ ചേട്ടനും അനിയത്തിയും ഇവിടെ ഉണ്ട്."
ഞാൻ വളരെ സന്തോഷത്തിലാണ്.
