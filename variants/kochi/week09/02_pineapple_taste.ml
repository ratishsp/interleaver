ഞാൻ പഴക്കടകളുടെ അടുത്തേക്ക് നടന്നു.
അവിടെ ഒരുപാട് പുതിയ കൈതച്ചക്കകൾ ഉണ്ടായിരുന്നു.
ഒരു കച്ചവടക്കാരൻ എന്നെ നോക്കി ചിരിച്ചു.
അയാൾ ഒരു ചെറിയ കഷ്ണം കൈതച്ചക്ക മുറിച്ചു.
അയാൾ അത് കത്തിയുടെ തുമ്പിൽ എനിക്ക് തന്നു.
ഞാൻ ആ കഷ്ണം വാങ്ങി.
ഞാൻ അത് കഴിച്ചു.
അതിന് നല്ല മധുരം ഉണ്ടായിരുന്നു.
ഞാൻ വില ചോദിച്ചില്ല.
കച്ചവടക്കാരൻ പെട്ടെന്ന് വില പറഞ്ഞു.
"ഒരു കൈതച്ചക്കയ്ക്ക് അറുപതു രൂപയാണ്," അയാൾ പറഞ്ഞു.
എനിക്ക് അത് ഇഷ്ടമായി.
"എനിക്ക് ഒരു കൈതച്ചക്ക വേണം," ഞാൻ പറഞ്ഞു.
അയാൾ വലിയ ഒരു കൈതച്ചക്ക എടുത്തു.
അയാൾ അത് എനിക്ക് തന്നു.
ഞാൻ അറുപതു രൂപ കൊടുത്തു.
ഞാൻ കച്ചവടക്കാരനോട് നന്ദി പറഞ്ഞു.
ഞാൻ മുന്നോട്ട് നടന്നു.
