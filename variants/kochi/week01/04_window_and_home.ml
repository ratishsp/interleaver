ഞാൻ ജനാലയ്ക്കരികിൽ നിൽക്കുകയാണ്.
ഗ്ലാസിന് ചൂടുണ്ട്.
ഇത് ജൂലൈ മാസമാണ്.
ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
കൊച്ചി ഇന്ന് ചാരനിറമാണ്.
പുറത്ത് മഴ പെയ്യുകയാണ്.
തെരുവിൽ വെള്ളമുണ്ട്.
പക്ഷേ ഇവിടെ തണുപ്പാണ്.
അപ്പാർട്ട്മെന്റ് നല്ലതാണ്.
ഞാൻ മെക്സിക്കോയെക്കുറിച്ച് ചിന്തിക്കുന്നു.
മെക്സിക്കോയിൽ വെയിലുണ്ട്.
അവിടെ ചൂടുമുണ്ട്.
ഞാൻ ആ വെയിൽ അല്പം മിസ്സ് ചെയ്യുന്നു.
എങ്കിലും ഞാൻ പുഞ്ചിരിക്കുന്നു.
ഇതൊരു പുതിയ നഗരമാണ്.
ഞാൻ ഇപ്പോൾ ഇന്ത്യയിലാണ്.
ഇതൊരു നല്ല തുടക്കമാണ്.
