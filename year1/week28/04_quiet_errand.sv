På fredagseftermiddagen tar jag en lugn promenad i solen.
Jag bär på min tunga vinterjacka.
Jag behöver den inte alls längre.
Jag stannar framför den lokala kemtvätten.
Jag öppnar dörren och går in.
Det doftar av rena kläder och tvål i den lilla butiken.
En äldre man står bakom disken.
"Hej, jag skulle vilja få den här jackan kemtvättad", säger jag.
Jag räcker fram den stora jackan över disken.
"Självklart", svarar mannen och undersöker tyget.
"Den är klar på onsdag", säger han.
"Det blir tvåhundrafemtio kronor."
Jag tar upp mitt betalkort ur väskan.
Jag betalar i kassan och får ett litet gult kvitto.
"Tack så mycket, ha en trevlig helg", säger jag.
"Detsamma", svarar han med ett leende.
Jag lägger ner kvittot i väskan.
Sedan kliver jag ut på den livliga trottoaren igen.
Jag njuter av att gå i den varma eftermiddagssolen.
