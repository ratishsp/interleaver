W sobotę wieczorem Ludwig śpi obok mnie na kanapie.
Jest bardzo zmęczony po naszym spacerze w lesie.
Otwieram komputer i dzwonię przez wideo do mojej rodziny w Meksyku.
Moja siostra Sofía i mój brat Diego siedzą już gotowi przed ekranem.
– Po prostu musicie zobaczyć mojego małego gościa – mówię do nich.
Biorę komputer i kieruję kamerę w dół na psa.
Sofía uśmiecha się radośnie.
– Spójrzcie tylko na niego!
– Jest naprawdę uroczy – mówi Diego.
Ludwig otwiera jedno oko, ale po prostu leży dalej.
– Spójrzcie na niego.
– Jest tak samo spokojny jak nasz pies Lola w domu – mówię.
Diego pyta mnie, czy łatwo się nim opiekować.
– Tak, bardzo lubię się nim opiekować – odpowiadam.
– Na ulicy musi po prostu chodzić na smyczy.
– I zdecydowanie nie może jeść ludzkiego jedzenia.
– Więc daję mu tylko jego własne smakołyki.
Nagle słyszymy, jak Lola głośno szczeka w tle na wideo.
Ludwig podnosi głowę i patrzy bardzo zdezorientowany na ekran.
– Połóż się z powrotem, mój przyjacielu – mówię łagodnie i głaszczę go.
Mówię mojej rodzinie dobranoc, żeby miał trochę spokoju.
Zamyka oczy i szybko ponownie zasypia.
