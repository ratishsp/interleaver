ഞാൻ വെളിച്ചമുള്ള ഒരു പലഹാരക്കടയുടെ മുന്നിൽ നിൽക്കുന്നു.
സോഫ്റ്റ്‌വെയർ കമ്പനിയിലെ എന്റെ സഹപ്രവർത്തകർക്ക് പലഹാരങ്ങൾ വാങ്ങണം.
"ഒരു പാക്കറ്റ് ഏത്തയ്ക്കാ ചിപ്സ് തരൂ," ഞാൻ കടക്കാരനോട് പറയുന്നു.
"ഒരു പാക്കറ്റ് ശർക്കരവരട്ടിയും വേണം."
അദ്ദേഹം രണ്ട് പാക്കറ്റുകൾ എടുക്കുന്നു.
"ആകെ എത്ര രൂപ ആയി?" ഞാൻ ചോദിക്കുന്നു.
കടക്കാരൻ വില കണക്കുകൂട്ടുന്നു.
"ചിപ്സിന് അറുപത് രൂപ," അദ്ദേഹം പറയുന്നു.
"ശർക്കരവരട്ടിക്ക് എഴുപത് രൂപ."
"ആകെ നൂറ്റിമുപ്പത് രൂപ."
ഞാൻ എന്റെ പഴ്സ് തുറക്കുന്നു.
ഞാൻ അദ്ദേഹത്തിന് അഞ്ഞൂറ് രൂപയുടെ നോട്ട് കൊടുക്കുന്നു.
അദ്ദേഹം ആ നോട്ട് വാങ്ങുന്നു.
അദ്ദേഹം ബാക്കി തുക ശ്രദ്ധയോടെ എണ്ണുന്നു.
"ഇതാ ബാക്കി മുന്നൂറ്റിയെഴുപത് രൂപ," അദ്ദേഹം പറയുന്നു.
ഞാൻ ആ പണവും പലഹാരങ്ങളും വാങ്ങുന്നു.
ഇത് പ്രകാശിനും മറ്റ് സഹപ്രവർത്തകർക്കും ഉള്ളതാണ്.
