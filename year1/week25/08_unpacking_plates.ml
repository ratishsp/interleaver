ഞാൻ എന്റെ അപ്പാർട്ട്മെന്റിൽ തിരികെയെത്തി.
ഇന്ന് ഞായറാഴ്ച വൈകുന്നേരമാണ്, ഇവിടെ വളരെ ശാന്തമാണ്.
ഞാൻ അടുക്കളയിൽ നിൽക്കുകയാണ്.
ഞാൻ എന്റെ പുതിയ പ്ലേറ്റുകൾ സിങ്കിൽ കഴുകുന്നു.
ഈ പ്ലേറ്റുകൾ ശരിക്കും മനോഹരമാണ്.
അവ നീല നിറമുള്ളതും അല്പം ഭാരമുള്ളതുമാണ്.
ഞാൻ അവ ഒരു ടീ ടവ്വൽ ഉപയോഗിച്ച് തുടച്ചുണക്കുന്നു.
അതിന് ശേഷം ഞാൻ അവ അലമാരയിൽ വെക്കുന്നു.
ഞാൻ സ്വീകരണമുറിയിലേക്ക് നടന്ന് ജനലിലൂടെ പുറത്തേക്ക് നോക്കുന്നു.
നഗരത്തിലെ മേൽക്കൂരകൾക്ക് മുകളിലൂടെ സൂര്യൻ പതുക്കെ അസ്തമിക്കുകയാണ്.
ഈ വേനൽക്കാല സായാഹ്നം മനോഹരവും പ്രകാശപൂരിതവുമാണ്.
എനിക്ക് ഈ അയൽപക്കം വളരെ ഇഷ്ടമാണ്.
ഞാനിപ്പോൾ ഇവിടെ താമസിക്കാൻ തുടങ്ങിയിട്ട് അരവർഷമായി.
ജനുവരിക്ക് ശേഷം ഒരുപാട് കാര്യങ്ങൾ സംഭവിച്ചു.
അന്ന് എനിക്ക് ഈ നഗരത്തിൽ ആരെയും അറിയില്ലായിരുന്നു.
ഇപ്പോൾ എനിക്ക് ഇവിടുത്തെ തെരുവുകളും ദൈനംദിന ജീവിതവും കൂടുതൽ നന്നായി അറിയാം.
എനിക്ക് ഈ നഗരം പൂർണ്ണമായും സ്വന്തം വീടുപോലെ തോന്നുന്നു.
നാളെ തിങ്കളാഴ്ചയാണ്, ഞാൻ ബസ്സിലാണ് ജോലിക്ക് പോകുന്നത്.
പക്ഷേ ഇപ്പോൾ ഞാൻ വെറുതെ വിശ്രമിക്കുകയാണ്.
ഇവിടുത്തെ എന്റെ ജീവിതത്തിൽ ഞാൻ പൂർണ്ണമായും തൃപ്തയാണ്.
