Otevírám své dveře.
Stojím na chodbě.
Je tu ticho.
Otevírají se dveře.
Nějaká žena se na mě usmívá.
„Ahoj,“ říká.
„Jak se jmenuješ?“ ptá se.
„Jmenuji se Maya,“ odpovídám.
„Odkud jsi?“ ptá se.
„Jsem z Mexika,“ říkám.
„Vítej v tomto domě,“ říká ta žena.
„Jmenuji se Nina,“ říká.
„Jsem tvoje sousedka.“
Nina je velmi přátelská.
Mluví pomalu a zřetelně.
„Tady jsou moje dveře,“ říká.
„Ráda ti pomůžu.“
„Stačí jen zaklepat,“ říká Nina.
„Moc děkuji, Nino,“ odpovídám.
Jsem moc ráda.
Teď mám v Kodani kamarádku.
