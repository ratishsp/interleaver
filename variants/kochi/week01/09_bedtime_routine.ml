ഇപ്പോൾ രാത്രി ആണ്.
എനിക്ക് നല്ല ക്ഷീണം ഉണ്ട്.
ഇത് എന്റെ ചെറിയ ബാത്ത്റൂം ആണ്.
ഇവിടെ ഒരു കണ്ണാടി ഉണ്ട്.
ഞാൻ പല്ല് തേക്കുന്നു.
ഞാൻ മുഖം കഴുകുന്നു.
വെള്ളത്തിന് നല്ല തണുപ്പ് ഉണ്ട്.
ഞാൻ കിടപ്പുമുറിയിൽ പോകുന്നു.
ഇവിടെ ഒരു നല്ല കട്ടിൽ ഉണ്ട്.
ഞാൻ കട്ടിലിൽ കിടക്കുന്നു.
മുകളിൽ ഒരു സീലിംഗ് ഫാൻ ഉണ്ട്.
ഞാൻ ഫാനിന്റെ ശബ്ദം കേൾക്കുന്നു.
ഞാൻ എന്റെ ഫോൺ എടുക്കുന്നു.
ഞാൻ രാവിലത്തെ അലാറം വെക്കുന്നു.
നാളെ കൊച്ചിയിൽ എന്റെ രണ്ടാമത്തെ ദിവസം ആണ്.
നാളെ ഒരു പുതിയ ദിവസം ആണ്.
എനിക്ക് ഇവിടെ വളരെ ഇഷ്ടം ആണ്.
ഞാൻ ഇപ്പോൾ ഉറങ്ങുന്നു.
