ഞാൻ കൗണ്ടറിന് മുന്നിൽ നിൽക്കുന്നു.
'ആകെ എത്രയായി?' ഞാൻ ചോദിക്കുന്നു.
കൗണ്ടറിലുള്ള ആൾ എന്നെ നോക്കി ചിരിക്കുന്നു.
'ഇരുന്നൂറ്റി അൻപത് രൂപ,' അയാൾ പറയുന്നു.
ഞാൻ എൻ്റെ ബാഗിൽ നിന്ന് പണം എടുക്കുന്നു.
ഞാൻ അയാൾക്ക് ഇരുന്നൂറ്റി അൻപത് രൂപ കൊടുക്കുന്നു.
അയാൾ എനിക്ക് ബിൽ തരുന്നു.
'ഐസ് ടീക്ക് നല്ല രുചിയുണ്ട്,' ഞാൻ പറയുന്നു.
'വളരെ നന്ദി.'
'നന്ദി.'
'വീണ്ടും വരണം,' അയാൾ സന്തോഷത്തോടെ പറയുന്നു.
ഞാൻ കഫേയുടെ ഗ്ലാസ് വാതിൽ തുറക്കുന്നു.
ഞാൻ പുറത്തേക്ക് ഇറങ്ങുന്നു.
പുറത്ത് ഇപ്പോഴും നല്ല വെയിലാണ്.
മാർച്ച് മാസത്തിലെ ചൂട് എനിക്ക് വീണ്ടും അനുഭവപ്പെടുന്നു.
പക്ഷേ, ഇപ്പോൾ എനിക്ക് നല്ല ഉന്മേഷമുണ്ട്.
ഞാൻ റോഡിലൂടെ മുന്നോട്ട് നടക്കുന്നു.
