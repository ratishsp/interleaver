Kasper chtěl slyšet o mém úplně prvním odpoledni.
Bylo to chladné odpoledne v lednu.
Vyšla jsem po schodech do svého nového bytu.
Měla jsem jeden velmi těžký kufr.
Byla jsem po té dlouhé cestě velmi unavená.
Sama jsem vynesla svůj kufr nahoru a dovnitř.
O chvíli později jsem vyšla na schodiště.
Otevřely se dveře vedle mých.
Vyšla ven mladá žena a usmála se na mě.
„Ahoj, jmenuji se Nina,“ řekla.
„Taky bydlím tady v budově.“
Úsměv jsem jí oplatila a řekla své jméno.
Nina bydlela hned vedle mě.
Chvíli jsme si spolu povídaly na schodišti.
Bylo milé hned potkat sousedku.
„Vítej v Dánsku,“ řekla Nina.
Byl to můj první den tady.
Byla jsem ráda, protože jsem už měla kamarádku.
