Jdu k Nininým dveřím.
Zaklepu na dveře.
Nina otevře a usměje se.
Ukážu jí čokoládový dort.
„Ahoj Nino,“ říkám.
„Mám dort z pekárny.“
„Ahoj Mayo, to je milé!“ říká Nina.
Jdeme do jejího obývacího pokoje.
Obývací pokoj je velmi teplý a útulný.
Sedíme na měkké pohovce.
Nina nám připravuje horký čaj.
Pijeme čaj a jíme ten sladký dort.
Čokoládový dort chutná opravdu dobře.
Povídáme si o našem dni ve městě.
Nina se ptá na mou práci.
Vyprávím o kanceláři a svém kolegovi Peterovi.
Nina také vypráví o svém dni.
Celý večer se smějeme a povídáme si.
Je to opravdu dobrý večer.
Cítím se tady ve svém novém městě jako doma.
