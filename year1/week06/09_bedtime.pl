Teraz jestem zmęczona.
Kładę książkę na stole.
Idę do łazienki.
Tutaj przygotowuję się do snu.
Biorę szczoteczkę do zębów.
Myję zęby.
Potem myję twarz.
Wycieram się ręcznikiem.
Wchodzę do sypialni.
Zakładam piżamę.
Następnie gaszę światło.
Teraz w mieszkaniu jest zupełnie ciemno.
Kładę się do łóżka.
Łóżko jest ciepłe i miękkie.
Naciągam na siebie kołdrę.
Zamykam oczy.
Jestem gotowa na nowy dzień.
Śpię dobrze.
