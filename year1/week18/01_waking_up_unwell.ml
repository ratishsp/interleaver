വ്യാഴാഴ്ച രാവിലെയാണ്, എന്റെ അലാറം അടിക്കുന്നു.
ഞാൻ ഉണരുന്നു, എനിക്ക് ശരിക്കും തീരെ സുഖമില്ലെന്ന് തോന്നുന്നു.
എന്റെ തലയ്ക്ക് നല്ല ഭാരമുണ്ട്, എനിക്ക് വല്ലാത്ത ക്ഷീണവുമുണ്ട്.
ഞാൻ കണ്ണുകൾ തുറക്കുന്നു, പക്ഷേ അവ വല്ലാതെ ചൊറിയുന്നുണ്ട്.
കണ്ണ് ചിമ്മുമ്പോൾ ശരിക്കും ചെറിയ വേദനയുണ്ട്.
മേശപ്പുറത്തിരിക്കുന്ന ഗ്ലാസിൽ നിന്ന് ഞാൻ കുറച്ചു വെള്ളം കുടിക്കാൻ ശ്രമിക്കുന്നു.
പക്ഷേ എന്റെ തൊണ്ട പൂർണ്ണമായും ഉണങ്ങിയിരിക്കുകയാണ്.
വിഴുങ്ങുമ്പോൾ എന്റെ തൊണ്ടയിൽ വേദനിക്കുന്നുണ്ട്.
സമയം എത്രയായെന്ന് നോക്കാൻ ഞാൻ എന്റെ ഫോണിലേക്ക് നോക്കുന്നു.
സമയം ഏഴരയായി, സാധാരണയായി ഞാൻ ഈ സമയത്താണ് ബസ്സ് കയറാറുള്ളത്.
എന്നാൽ ഇന്ന് എനിക്ക് തീരെ ഊർജ്ജമില്ല.
എനിക്ക് ക്ഷീണം മാത്രമല്ല, ശരിക്കും അസുഖമുണ്ടെന്നാണ് തോന്നുന്നത്.
ഇന്ന് ഞാൻ തീർച്ചയായും ജോലിക്ക് പോകാതെ വീട്ടിൽ തന്നെ ഇരിക്കണം.
ഞാൻ എന്റെ സഹപ്രവർത്തകനായ പീറ്ററിന് ഒരു ചെറിയ സന്ദേശം എഴുതുന്നു.
എനിക്ക് അസുഖമാണെന്നും ഓഫീസിലേക്ക് വരുന്നില്ലെന്നും ഞാൻ വിശദീകരിക്കുന്നു.
ഞാൻ വെറുതെ വിശ്രമിച്ച് സുഖം പ്രാപിക്കണമെന്ന് അവൻ പെട്ടെന്ന് തന്നെ മറുപടി നൽകുന്നു.
മെഡിക്കൽ ക്ലിനിക്ക് തുറക്കുമ്പോൾ ഞാൻ അവിടേക്ക് വിളിക്കേണ്ടതുണ്ട്.
എന്നാൽ ഇപ്പോൾ എനിക്ക് കണ്ണുകൾ അടച്ച് ഭാരമുള്ള എന്റെ തലയ്ക്ക് അല്പം വിശ്രമം നൽകാൻ മാത്രമാണ് ആഗ്രഹമുള്ളത്.
