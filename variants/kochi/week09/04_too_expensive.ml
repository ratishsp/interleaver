ഞാൻ ഭക്ഷണക്കടകൾ പിന്നിട്ട് നടക്കുന്നു.
അവിടെ ഞാൻ ഒരു ചെറിയ കട കാണുന്നു.
കടയിൽ മനോഹരമായ തവികൾ ഉണ്ട്.
അവ തടി കൊണ്ടുള്ള തവികളാണ്.
ഞാൻ ഒരു തവി കയ്യിൽ എടുക്കുന്നു.
അത് കൈകൊണ്ട് ഉണ്ടാക്കിയതാണ്.
കച്ചവടക്കാരൻ എന്നെ നോക്കുന്നു.
"ഇതിന് വില എത്ര?" ഞാൻ ചോദിക്കുന്നു.
"അതിന് നാനൂറ്റി അൻപത് രൂപയാണ്," അദ്ദേഹം പറയുന്നു.
നാനൂറ്റി അൻപത് രൂപയോ!
അത് വളരെ കൂടിയ വിലയാണ്.
എനിക്ക് ഇപ്പോൾ അത് വേണ്ട.
ഞാൻ അദ്ദേഹത്തെ നോക്കി ചിരിക്കുന്നു.
"വില കൂടുതലാണ്," ഞാൻ പറയുന്നു.
ഞാൻ തവി പതുക്കെ തിരികെ വെക്കുന്നു.
അദ്ദേഹം ചിരിച്ച് തലയാട്ടുന്നു.
