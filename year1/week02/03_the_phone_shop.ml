ഇതെന്റെ ഉച്ചഭക്ഷണ ഇടവേളയാണ്.
ഞാൻ ഒരു ഫോൺ കടയിലാണ്.
എന്റെ പക്കൽ മെക്സിക്കോയിൽ നിന്നുള്ള ഒരു ഫോണുണ്ട്.
ആ ജീവനക്കാരൻ ഒരു ചെറുപ്പക്കാരനാണ്.
"നിങ്ങളുടെ പക്കൽ ഡാനിഷ് സിം കാർഡ് ഉണ്ടോ?" ഞാൻ ചോദിക്കുന്നു.
"അതെ, തീർച്ചയായും," അയാൾ മറുപടി പറയുന്നു.
ഞാൻ എന്റെ ഫോൺ അയാൾക്ക് നൽകുന്നു.
അയാൾ ഫോണിൽ സിം കാർഡ് ഇടുന്നു.
ഫോൺ ഇപ്പോൾ തയ്യാറാണ്.
"നിങ്ങളുടെ പുതിയ നമ്പർ പന്ത്രണ്ട്, മുപ്പത്തിനാല്, അമ്പത്താറ്, എഴുപത്തിയെട്ട് ആണ്," അയാൾ പറയുന്നു.
എന്റെ ബാഗിൽ ഒരു നോട്ട്ബുക്ക് ഉണ്ട്.
ഞാൻ ആ നമ്പർ എഴുതുന്നു.
"പന്ത്രണ്ട്, മുപ്പത്തിനാല്, അമ്പത്താറ്, എഴുപത്തിയെട്ട്," ഞാൻ ആവർത്തിക്കുന്നു.
"അതെ, കൃത്യം," ജീവനക്കാരൻ പറയുന്നു.
"സഹായിച്ചതിന് നന്ദി," ഞാൻ പറയുന്നു.
എനിക്കിപ്പോൾ ഒരു ഡാനിഷ് നമ്പർ ഉണ്ട്!
ഞാൻ ഫോൺ എന്റെ പോക്കറ്റിലിടുന്നു.
