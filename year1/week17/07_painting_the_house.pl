Szłam dalej wąską ulicą.
Zatrzymałam się przed bardzo starym domem.
Starsze małżeństwo było na zewnątrz w wiosennym słońcu.
Mężczyzna stał w swoim ogrodzie.
Malował swój stary płot pędzlem.
Nowy kolor był jasnożółty.
Jego żona siedziała na drewnianej ławce w pobliżu.
Odpoczywała i piła swoją ciepłą herbatę.
Mężczyzna zobaczył mnie i zatrzymał się na chwilę.
Przyjaźnie pomachał swoim pędzlem.
„Dzień dobry!” – powiedział do mnie.
„Państwa ogród wygląda pięknie” – powiedziałam.
Jego żona uśmiechnęła się do mnie ze swojej ławki.
„Dziękuję, cieszymy się wiosną” – odpowiedziała.
Mężczyzna spokojnie malował dalej swój płot.
Ptaki śpiewały w ich ogrodzie.
Z radością kontynuowałam swój spacer.
