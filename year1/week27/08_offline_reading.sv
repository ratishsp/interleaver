Jag brukar titta på en skärm hela dagen på jobbet.
Därför vill jag gärna vara helt offline nu.
Jag går in i mitt vardagsrum.
Här tänder jag min varma läslampa.
Ljuset är varmt och mjukt i rummet.
Jag sätter mig i min mjuka fåtölj.
Jag tar fram min nya bok.
Det är en riktig pappersbok.
Boken öppnas, och den verkliga världen försvinner.
Kaffebönorna från Nina ska sparas till i morgon bitti.
I kväll dricker jag bara ett glas vatten.
Telefonen ignoreras resten av kvällen.
Jag slappnar av fullständigt.
En så lugn avslutning på dagen är helt perfekt.
