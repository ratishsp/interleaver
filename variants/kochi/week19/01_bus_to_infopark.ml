ഇന്ന് ഒരു പ്രധാനപ്പെട്ട ദിവസമാണ്.
ഓഫീസിലെ ഞങ്ങളുടെ പുതിയ പ്രോജക്റ്റ് ഇന്ന് ഔദ്യോഗികമായി തുടങ്ങുകയാണ്.
ഇപ്പോൾ ഞാൻ ഇൻഫോപാർക്കിലേക്കുള്ള ബസ്സിലാണ് ഉള്ളത്.
പുറത്ത് തുടർച്ചയായി മഴ പെയ്യുന്നുണ്ട്.
ഇത് കൊച്ചിയിലെ മഴക്കാലമാണ്.
ഞാൻ എപ്പോഴും ഈ ബസ്സിലാണ് ഓഫീസിൽ പോകുന്നത്.
ഞാൻ പലതവണ ഈ ബസ്സിൽ യാത്ര ചെയ്തിട്ടുണ്ട്.
ബസ് കണ്ടക്ടർ ടിക്കറ്റിനുള്ള പണം ചോദിക്കുന്നു.
"ഇരുപത് രൂപ തരൂ," അയാൾ പറയുന്നു.
ഞാൻ ഇരുപത് രൂപ കൊടുത്ത് ടിക്കറ്റ് വാങ്ങുന്നു.
പുതിയ പ്രോജക്റ്റിനെക്കുറിച്ച് ഓർക്കുമ്പോൾ എനിക്ക് ചെറിയ പേടിയും വലിയ സന്തോഷവുമുണ്ട്.
ഇന്നത്തെ മീറ്റിംഗിനായി ഞാൻ ചില നോട്ടുകൾ തയ്യാറാക്കിയിട്ടുണ്ട്.
കഴിഞ്ഞ അവധിദിവസങ്ങളിലാണ് ഞാൻ അത് എഴുതിയത്.
ഞാൻ എന്റെ ബാഗ് തുറന്ന് പുസ്തകം പുറത്തെടുക്കുന്നു.
ഞാൻ ഇപ്പോൾ ആ നോട്ടുകൾ വായിക്കുകയാണ്.
ചെയ്യേണ്ട കാര്യങ്ങൾ ഞാൻ അതിൽ വ്യക്തമായി എഴുതിയിട്ടുണ്ട്.
മഴയിലൂടെ ബസ് പതുക്കെ മുന്നോട്ട് പോവുകയാണ്.
കുറച്ചു കഴിയുമ്പോൾ ഞങ്ങൾ ഇൻഫോപാർക്കിൽ എത്തും.
ഇന്നത്തെ മീറ്റിംഗ് നന്നായി നടക്കുമെന്ന് ഞാൻ പ്രതീക്ഷിക്കുന്നു.
