ഞാൻ മാർക്കറ്റിലൂടെ നടന്നു.
എനിക്ക് സുഗന്ധവ്യഞ്ജനങ്ങളുടെ നല്ല മണം കിട്ടി.
ഞാൻ ഒരു ചെറിയ കട കണ്ടു.
മേശപ്പുറത്ത് ഒരു ചെറിയ കാർഡ്ബോർഡ് ബോർഡ് ഉണ്ടായിരുന്നു.
അതിൽ വിലകൾ ഉണ്ട്.
ഞാൻ ഏലക്കയുടെ വില നോക്കി.
ഏലക്കയുടെ വില നൂറ്റിയൻപത് രൂപ ആണ്.
കച്ചവടക്കാരൻ എന്നെ നോക്കി.
"എന്ത് വേണം?" അയാൾ ചോദിച്ചു.
"എനിക്ക് ഒരു ചെറിയ പാക്കറ്റ് ഏലക്ക വേണം," ഞാൻ പറഞ്ഞു.
"ഒരു പാക്കറ്റ് തരൂ."
അയാൾ എനിക്ക് ഒരു പാക്കറ്റ് ഏലക്ക തന്നു.
ഞാൻ എന്റെ ബാഗിൽ നിന്ന് അഞ്ഞൂറ് രൂപ എടുത്തു.
ഞാൻ അത് കച്ചവടക്കാരന് കൊടുത്തു.
അയാൾ പണം വാങ്ങി ബാക്കി എണ്ണി.
"ഏലക്കയ്ക്ക് നൂറ്റിയൻപത് രൂപ," അയാൾ പറഞ്ഞു.
"ബാക്കി മുന്നൂറ്റിയൻപത് രൂപ ഇതാ."
അയാൾ എനിക്ക് ബാക്കി പണം തന്നു.
ഞാൻ പാക്കറ്റും പണവും ബാഗിൽ വെച്ചു.
ഞാൻ അയാൾക്ക് നന്ദി പറഞ്ഞു.
