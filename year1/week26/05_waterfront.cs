Jsem doma ve svém bytě.
Je sobota večer, ale slunce stále svítí.
Chystám se na táborák na pláži.
Sbalila jsem si tašku.
Dala jsem do tašky teplý svetr.
Ten svetr jsem koupila v únoru.
Večery jsou teď světlé, ale později se často ochladí.
Také jsem připravila nějaké občerstvení.
Nakoupila jsem dnes ráno před svou směnou v kavárně.
Zvoní mi telefon a já to zvedám.
Je to Eva.
„Jsi připravená, Mayo?“ ptá se.
„Ano, jsem skoro připravená,“ odpovídám.
„Zrovna jsem našla své sluneční brýle,“ říkám.
„Hledala jsem je dvacet minut,“ směju se.
„Perfektní, uvidíme se u vody za půl hodiny,“ říká Eva.
Obouvám si boty a dávám si tašku přes rameno.
Zamykám dveře a jdu dolů po schodech.
Moc se těším na svůj první dánský letní večer.
