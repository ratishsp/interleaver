ഞാൻ ഓഫീസിൽ നിന്ന് പുറത്തിറങ്ങുന്നു.
പുറത്ത് ചെറിയ മഴയുണ്ട്.
ഞാൻ റോഡരികിൽ നിൽക്കുന്നു.
അപ്പോൾ ഒരു ഓട്ടോ വരുന്നു.
ഞാൻ കൈ കാണിച്ച് ആ ഓട്ടോ നിർത്തുന്നു.
"ചേട്ടാ, പാലാരിവട്ടം വരെ പോകുമോ?" ഞാൻ അയാളോട് ചോദിക്കുന്നു.
"പാലാരിവട്ടത്ത് എവിടെയാണ്?" അയാൾ ചോദിക്കുന്നു.
"പാലാരിവട്ടം മെയിൻ ജംഗ്ഷനിൽ നിർത്താം," ഞാൻ പറയുന്നു.
അവിടെ നിന്ന് ദീപയുടെ വീട് എളുപ്പം കണ്ടുപിടിക്കാം എന്ന് ഞാൻ കരുതുന്നു.
"ശരി, കയറിക്കോളൂ," അയാൾ പറയുന്നു.
ഞാൻ ഓട്ടോയിൽ കയറുന്നു.
മഴ വേഗം കൂടും എന്ന് എനിക്ക് തോന്നുന്നു.
"നമുക്ക് വേഗം പോകാം ചേട്ടാ," ഞാൻ പറയുന്നു.
അയാൾ വണ്ടി മുന്നോട്ട് എടുക്കുന്നു.
കൃത്യസമയത്ത് അവിടെ എത്തും എന്ന് ഞാൻ വിശ്വസിക്കുന്നു.
