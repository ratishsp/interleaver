വെള്ളിയാഴ്ച വൈകുന്നേരമാണ്.
അനിത എൻ്റെ ഫ്ലാറ്റിലേക്ക് വരുന്നു.
അവരുടെ നായ ടോമിയും ഒപ്പമുണ്ട്.
അവർ എനിക്ക് അവൻ്റെ ഭക്ഷണവും ലീഷും തരുന്നു.
അവർ എനിക്ക് ചില നിയമങ്ങൾ വിശദീകരിച്ചു തരുന്നു.
"മായ, രാവിലെ എട്ടു മണിക്ക് അവന് ഭക്ഷണം കൊടുക്കണം," അനിത പറയുന്നു.
"വൈകുന്നേരം ഏഴു മണിക്ക് അത്താഴം കൊടുക്കണം."
"മറ്റ് ഭക്ഷണങ്ങൾ ഒന്നും അവന് കൊടുക്കാൻ പാടില്ല."
"അവന് മധുരമുള്ള പലഹാരങ്ങൾ വളരെ ഇഷ്ടമാണ്."
"പക്ഷേ, മധുരമുള്ള സാധനങ്ങൾ അവന് കൊടുക്കാനേ പാടില്ല."
"അത് അവന് വളരെ മോശമാണ്."
"പിന്നെ, അവനെ ഒറ്റയ്ക്ക് പുറത്ത് വിടാൻ പാടില്ല."
"പുറത്ത് പോകുമ്പോൾ അവനെ എപ്പോഴും ശ്രദ്ധിക്കണം."
ഞാൻ അനിതയോട് പറയുന്നു: "വിഷമിക്കേണ്ട അനിത."
"ഞാൻ അവനെ നന്നായി നോക്കിക്കോളാം."
അനിത സന്തോഷത്തോടെ യാത്ര പറഞ്ഞ് പോകുന്നു.
ഞാൻ വാതിൽ അടയ്ക്കുന്നു.
"ഇവിടെ വാ, ടോമി," ഞാൻ അവനെ വിളിക്കുന്നു.
