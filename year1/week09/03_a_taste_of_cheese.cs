Přede mnou je velký stánek se sýry.
Ve stánku mají mnoho velkých sýrů.
Přátelský prodavač se na mě usmívá.
Na dřevěném párátku má malý kousek sýra.
„Tady máte, malá ochutnávka,“ říká.
Dává mi to párátko.
Jím ten žlutý sýr.
Chutná opravdu dobře.
Dívám se na malý sýr.
„Kolik stojí tenhle sýr?“ ptám se.
„Stojí padesát pět korun,“ odpovídá prodavač.
To je dobrá cena.
Ukazuji na ten malý sýr.
„Koupím si ho,“ říkám.
Balí ten sýr do papíru.
Dávám mu peníze.
„Mockrát děkuji,“ říká.
Ten sýr voní silně a dobře.
