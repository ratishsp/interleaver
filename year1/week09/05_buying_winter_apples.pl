Na targu jest dzisiaj dużo ludzi.
Znajduję małe stoisko z owocami.
Na stoisku jest dużo koszy.
Kosze są pełne ciemnoczerwonych zimowych jabłek.
Patrzę na małą torebkę z jabłkami.
„Ile kosztuje mała torebka?” – pytam sprzedawcę.
On patrzy do kosza.
„Cena to dwadzieścia koron” – odpowiada.
Szukam pieniędzy w mojej torbie.
Daję mu banknot pięćdziesięciokoronowy.
Sprzedawca podaje mi torebkę z jabłkami.
Potem wydaje mi resztę.
Dostaję z powrotem dokładnie trzydzieści koron w monetach.
Monety są grube i ciężkie.
Wkładam ciężkie monety do kieszeni płaszcza.
Jabłka pachną bardzo świeżo.
Wkładam torebkę do mojej dużej torby na zakupy.
