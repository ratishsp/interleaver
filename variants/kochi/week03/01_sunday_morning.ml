ഇന്ന് ഞായറാഴ്ചയാണ്.
കൊച്ചി ഇന്ന് വളരെ ശാന്തമാണ്.
ഇത് ജനുവരി മാസമാണ്.
രാവിലെ കാലാവസ്ഥ വളരെ നല്ലതാണ്.
ഇന്ന് എല്ലാവരുമായും എന്റെ ആദ്യത്തെ വീഡിയോ കോൾ ആണ്.
എന്റെ കുടുംബം മെക്സിക്കോയിലാണ്.
എന്റെ വീട്ടിൽ ഇപ്പോൾ ആരാണ് ഉള്ളത്?
എന്റെ അച്ഛൻ, എന്റെ അമ്മ, എന്റെ ചേട്ടൻ ഡീഗോ, എന്റെ അനിയത്തി സോഫിയ.
പിന്നെ എന്റെ നായ, ലോല!
എനിക്ക് ഇന്ന് വളരെ സന്തോഷമുണ്ട്.
ഞാൻ ആ കോളിനായി കാത്തിരിക്കുന്നു.
അതിനുമുമ്പ് എനിക്ക് ഒരു ചെറിയ പലഹാരം വേണം.
ഞാൻ അത് അവർക്ക് കാണിക്കും.
എന്റെ ഫ്ലാറ്റിനടുത്ത് ഒരു ബേക്കറി ഉണ്ട്.
ഞാൻ ഇപ്പോൾ പുറത്തേക്ക് പോകുന്നു.
