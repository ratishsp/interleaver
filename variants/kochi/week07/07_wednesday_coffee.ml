ഇന്ന് ബുധനാഴ്ചയാണ്.
സമയം വൈകുന്നേരം അഞ്ചര മണിയാണ്.
ഞാനും അനിതയും പനമ്പിള്ളി നഗറിലെ ഒരു കഫേയിലാണ്.
ഞാൻ ജനുവരിയിലാണ് കൊച്ചിയിൽ വന്നത്.
ഇതൊരു ചെറിയ ആഘോഷമാണ്.
ഞങ്ങൾ കഫേയിൽ ഇരുന്ന് ചൂട് കാപ്പി കുടിക്കുന്നു.
അനിത കട്ടൻ കാപ്പി കുടിക്കുന്നു.
ചിലപ്പോൾ ഞാൻ ചായ കുടിക്കുന്നു.
പക്ഷേ, ഇന്ന് ഞാനും കാപ്പി കുടിക്കുന്നു.
കഫേയിൽ നല്ല തിരക്കാണ്.
എല്ലാ ദിവസവും വൈകുന്നേരം ഇവിടെ ധാരാളം ആളുകൾ വരുന്നു.
അനിത ചോദിക്കുന്നു, "മായയ്ക്ക് ഇപ്പോൾ കൊച്ചി ഇഷ്ടമാണോ?"
ഞാൻ ചിരിക്കുന്നു.
"അതെ, എനിക്ക് കൊച്ചി വളരെ ഇഷ്ടമാണ്," ഞാൻ മറുപടി പറയുന്നു.
ഞങ്ങൾ ഒരുപാട് കാര്യങ്ങൾ സംസാരിക്കുന്നു.
രാത്രി ഏഴ് മണിക്ക് എനിക്ക് എൻ്റെ സൈക്കിൾ എടുക്കാൻ പോകണം.
അതിനാൽ ഞങ്ങൾ ആറര മണിക്ക് കഫേയിൽ നിന്ന് ഇറങ്ങുന്നു.
ഈ സമയം എനിക്ക് വളരെ സന്തോഷം നൽകുന്നു.
