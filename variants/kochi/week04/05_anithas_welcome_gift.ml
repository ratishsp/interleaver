ഞാൻ ജനലിന്റെ അടുത്താണ്.
ഫ്ലാറ്റിന്റെ വാതിൽ തുറന്നു കിടക്കുന്നു.
പെട്ടെന്ന് അനിത വാതിലിൽ മുട്ടുന്നു.
അവർ മുറിയിലേക്ക് വരുന്നു.
അവരുടെ മുഖത്ത് നല്ല ഒരു പുഞ്ചിരി ഉണ്ട്.
അനിതയുടെ കയ്യിൽ ഒരു ചെറിയ ചെടി ഉണ്ട്.
അതൊരു മനോഹരമായ പച്ച ചെടിയാണ്.
"പുതിയ വീട്ടിലേക്ക് സ്വാഗതം, മായ," അനിത പറയുന്നു.
അവർ എന്റെ മേശയുടെ അടുത്ത് വരുന്നു.
അവർ ആ ചെടി ജനൽപ്പടിയിൽ വെക്കുന്നു.
ഇപ്പോൾ ആ ചെടി മേശയുടെ അടുത്ത് ഇരിക്കുന്നു.
മുറിയിൽ ആ ചെടി കാണാൻ നല്ല ഭംഗിയുണ്ട്.
"വളരെ നന്ദി, അനിത," ഞാൻ സന്തോഷത്തോടെ പറയുന്നു.
എന്റെ ലാപ്ടോപ്പ് മേശയുടെ മുകളിൽ ഇരിക്കുന്നു.
മേശയുടെ അടിയിൽ എന്റെ ഒരു ബാഗ് കിടക്കുന്നു.
അനിത ലാപ്ടോപ്പിൽ നോക്കുന്നു.
"മായയുടെ പുതിയ ജോലി എങ്ങനെ ഉണ്ട്?" അവർ ചോദിക്കുന്നു.
"ജോലി വളരെ നന്നായി പോകുന്നു," ഞാൻ മറുപടി പറയുന്നു.
മുറിയിൽ ജനുവരിയിലെ നല്ല കാറ്റ് വരുന്നുണ്ട്.
