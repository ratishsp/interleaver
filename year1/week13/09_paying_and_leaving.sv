Baristan ler mot mig.
Jag håller mitt kort över terminalen.
Maskinen piper.
"Vill du ha ett kvitto?" frågar han.
"Nej tack", svarar jag.
Jag går bort till väggen.
Jag tar min tjocka vinterjacka från en krok.
Jag tar på mig jackan.
Jag tar också på mig min halsduk.
Jag tar också på mig mina handskar.
Nu är jag redo för kylan.
Jag tittar på baristan igen.
"Tack så mycket för kaffet", säger jag.
"Tack själv", säger han med ett leende.
"Ha en bra dag."
"Detsamma", säger jag.
Jag går fram till ytterdörren.
Jag skjuter upp den tunga dörren.
Vinden är kall, men jag mår bra.
