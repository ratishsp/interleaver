Stoję w kuchni, kiedy dzwoni dzwonek do drzwi.
Wychodzę na korytarz i otwieram drzwi.
To Nina, ma szeroki uśmiech na twarzy.
„Cześć Maya, bardzo dziękuję za zaproszenie” – mówi.
Wchodzi do środka i śmieje się, zdejmując buty.
Serdecznie ją przytulam.
Nina trzyma w dłoniach piękną, zieloną roślinę doniczkową.
„To dla ciebie” – mówi i wręcza mi roślinę.
„Idealnie pasuje do twojego salonu”.
„Dziękuję, jest naprawdę śliczna” – odpowiadam radośnie.
Stawiam zieloną roślinę na małym stoliku obok drzwi.
Nagle Nina bierze głęboki oddech.
„Wow, pachnie tu absolutnie wspaniale” – mówi.
„Czy to te meksykańskie przyprawy?” – pyta z ciekawością.
Kiwam głową i wyjaśniam, że przygotowałam tradycyjny gulasz.
„Ten pikantny zapach sprawia, że jestem strasznie głodna” – śmieje się Nina.
„Na szczęście jedzenie jest już w pełni gotowe” – mówię z uśmiechem.
Siadamy razem do stołu, żeby zjeść.
