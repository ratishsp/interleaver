Mám přestávku na oběd.
Jsem v obchodě s telefony.
Mám telefon z Mexika.
Prodavač je mladý muž.
„Máte dánskou SIM kartu?“ ptám se.
„Ano, samozřejmě,“ odpovídá.
Dávám mu svůj telefon.
Vkládá SIM kartu do telefonu.
Telefon je teď připravený.
„Vaše nové číslo je dvanáct, třicet čtyři, padesát šest, sedmdesát osm,“ říká.
Mám v tašce zápisník.
Zapisuji si to číslo.
„Dvanáct, třicet čtyři, padesát šest, sedmdesát osm,“ opakuji.
„Ano, přesně tak,“ říká prodavač.
„Děkuji za pomoc,“ říkám.
Teď mám dánské číslo!
Dávám si telefon do kapsy.
