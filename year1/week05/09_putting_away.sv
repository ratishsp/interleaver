Jag är hemma i lägenheten igen.
Jag står i köket.
Jag tömmer påsen på köksbänken.
Jag packar upp maten.
Jag tar mjölken.
Jag ställer mjölken i kylskåpet.
Sedan tittar jag på palsternackan.
Det är en rolig rot.
Jag ska använda den i min soppa.
Jag lägger palsternackan i kylskåpet.
Nu är kylskåpet inte tomt.
Jag tar brödet.
Rågbrödet är väldigt tungt.
Jag lägger brödet i skåpet.
Sedan tar jag burken med bönor.
Bönor håller länge.
Jag ställer burken i skåpet.
Nu finns det mat i skåpet.
Jag är ganska hungrig.
Jag vill gärna ha middag nu.
