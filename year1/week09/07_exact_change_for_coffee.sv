Jag fryser mycket nu.
Mina händer är kalla.
Jag tittar runt på marknaden.
Jag ser en liten kaffevagn.
En ung man står bakom vagnen.
Jag går fram till honom.
Jag säger hej till baristan.
"Hej, hur mycket kostar en svart kaffe?" frågar jag.
Baristan ler.
"En varm, svart kaffe kostar trettio kronor," svarar han.
Jag har mynt i min rockficka.
Det är mina växelpengar från äpplena.
Jag tar fram mynten.
Jag räknar dem.
Jag har precis trettio kronor.
"Varsågod, här är trettio kronor," säger jag.
Han tar pengarna.
Han ger mig det varma kaffet.
Kaffet doftar underbart.
Jag värmer mina händer på koppen.
