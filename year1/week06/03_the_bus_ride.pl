Na ulicy czekam na mój autobus.
Dzisiaj jest zimno.
Wiele osób stoi na przystanku.
Nadjeżdża czerwony autobus.
Drzwi się otwierają.
Wsiadam do autobusu.
Tutaj skanuję moją kartę miejską.
Kierowca autobusu patrzy na mnie.
„Dzień dobry” – mówi kierowca.
„Dzień dobry” – odpowiadam.
Przechodzę w głąb autobusu.
Znajduję wolne miejsce przy oknie.
Siadam.
Autobus jedzie przez miasto.
Za oknem widzę wielu ludzi.
Jadą szybko na rowerach po ścieżce rowerowej.
Przejeżdżamy obok pięknego parku.
W parku ludzie spacerują.
Teraz autobus zatrzymuje się przy moim miejscu pracy.
Wysiadam i wchodzę do biura.
