സാറയും ഞാനും സ്പോർട്സ് ഹാളിൽ നിന്ന് പുറത്തേക്ക് നടക്കുന്നു.
നേരം വൈകി, തണുപ്പുള്ള ഒരു ശൈത്യകാല സായാഹ്നമാണിത്.
പക്ഷേ മത്സരത്തിന് ശേഷം എനിക്ക് ഇപ്പോഴും ചൂട് തോന്നുന്നുണ്ട്.
ഞങ്ങൾ ഒരുമിച്ച് ബസ് സ്റ്റോപ്പിലേക്ക് നടക്കുന്നു.
കാറ്റടിക്കുന്നുണ്ട്, തെരുവിൽ നല്ല ഇരുട്ടാണ്.
"വാരാന്ത്യത്തിലും ബാഡ്മിൻ്റൺ കളിക്കാൻ നിനക്ക് ഇഷ്ടമാണോ?" ഞാൻ ചോദിക്കുന്നു.
"ഇല്ല, ഞാൻ വ്യാഴാഴ്ചകളിൽ മാത്രമേ ബാഡ്മിൻ്റൺ കളിക്കാറുള്ളൂ," സാറ മറുപടി നൽകുന്നു.
"പക്ഷേ എനിക്ക് കായിക വിനോദങ്ങളിൽ ഏർപ്പെടാൻ ഇഷ്ടമാണ്," അവൾ പറയുന്നു.
"ഞാൻ സാധാരണയായി പാർക്കിൽ ഓടാൻ പോകാറുണ്ട്," അവൾ തുടരുന്നു.
വളരെ ഊർജ്ജസ്വലയും രസകരവുമായ ഒരു വ്യക്തിയാണവൾ.
ആ തണുപ്പത്ത് ഞങ്ങൾ ബസ്സിനായി കാത്തുനിൽക്കുന്നു.
"എൻ്റെ ബസ് പത്ത് മിനിറ്റിനുള്ളിൽ വരും," ഞാൻ പറയുന്നു.
"നമ്മൾ ഒരേ ബസ്സിലാണ് പോകുന്നത്," സാറ പുഞ്ചിരിക്കുന്നു.
അതിൽ എനിക്ക് വലിയ സന്തോഷമുണ്ട്.
അവളോട് സംസാരിക്കുന്നത് എനിക്കിഷ്ടമാണ്.
കാസ്പറും സാറയും വളരെ രസകരവും നല്ലവരുമായ ആളുകളാണ്.
ഇപ്പോൾ വ്യാഴാഴ്ചകളിൽ എനിക്കൊരു നല്ല ദിനചര്യയുണ്ട്.
എനിക്ക് ക്ഷീണമുണ്ട്, പക്ഷേ ഞാൻ നല്ല മൂഡിലാണ്.
ഒടുവിൽ ബസ് എത്തുന്നു.
അടുത്ത വ്യാഴാഴ്ചയ്ക്കായി ഞാൻ ഇപ്പോഴേ കാത്തിരിക്കുകയാണ്.
