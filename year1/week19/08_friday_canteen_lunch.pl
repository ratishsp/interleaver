W końcu jest piątek, a pracowity tydzień prawie się skończył.
Jemy razem lunch w jasnej stołówce.
Siedzę przy dużym stole razem z moim zespołem.
Są tu też Peter, nasza projektantka Eva i nasz tester Mads.
Wszyscy jesteśmy zmęczeni, ale bardzo zadowoleni.
Nowy projekt był ekscytujący.
„Naprawdę ciężko pracowaliśmy” – mówi Peter i uśmiecha się.
„Tak, rozwiązaliśmy wiele złożonych problemów” – odpowiadam.
Jako inżynierowie oprogramowania napisaliśmy w tym tygodniu dużo kodu.
„A ja to wszystko przetestowałem” – śmieje się Mads.
„Na szczęście nie znalazłeś wielu błędów” – droczy się Peter.
Eva pokazuje nam swój piękny projekt na telefonie.
Od wielu lat pracuje jako projektantka.
Rozmawiamy o naszych różnych zadaniach podczas jedzenia.
Bardzo miło jest lepiej poznać moich kolegów z pracy.
Staliśmy się naprawdę dobrym zespołem.
Biorę kęs jedzenia i patrzę na nich.
Nie mogę się doczekać kontynuowania z nimi tego projektu.
