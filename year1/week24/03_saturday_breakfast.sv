Det är lördag morgon klockan sju.
Jag sover fortfarande tungt.
Plötsligt känner jag något kallt på min arm.
Jag öppnar ögonen och ser Ludwig.
Han puffar på mig med sin nos.
"God morgon, Ludwig", säger jag och stiger upp.
Vi går ut i köket tillsammans.
Han är väldigt hungrig och hoppar upp på mig.
"Lugn nu, Ludwig", säger jag till honom.
"Sitt", säger jag lugnt.
Han tittar på mig och sätter sig ner på golvet.
Jag tar påsen med hundmat och öppnar den.
Jag häller upp maten i hans skål.
Han reser sig för att han vill ha den direkt.
"Nej, vänta", säger jag.
Han sätter sig igen och väntar snällt.
Jag ställer ner skålen framför honom.
Jag klappar honom mjukt på huvudet.
"Varsågod, ät", säger jag med ett leende.
Han viftar på svansen och börjar äta.
