ഞാൻ സർക്കാർ ഓഫീസിൽ ഇരിക്കുന്നു.
ഒരു ഉദ്യോഗസ്ഥൻ എന്റെ പേര് വിളിക്കുന്നു.
ഞാൻ ഡെസ്കിന്റെ അടുത്തേക്ക് പോകുന്നു.
അദ്ദേഹം എന്റെ അപേക്ഷ നോക്കുന്നു.
അദ്ദേഹം എന്നോട് ചോദിക്കുന്നു.
"നിങ്ങളുടെ ഫോൺ നമ്പർ എന്താണ്?"
ഞാൻ എന്റെ പുതിയ നമ്പർ പറയുന്നു.
"ഒമ്പത്, എട്ട്, ഏഴ്, ആറ്, അഞ്ച്..."
"...നാല്, മൂന്ന്, രണ്ട്, ഒന്ന്, പൂജ്യം," ഞാൻ പറയുന്നു.
അദ്ദേഹം ആ നമ്പർ എഴുതുന്നു.
പിന്നെ അദ്ദേഹം വീണ്ടും ചോദിക്കുന്നു.
"നിങ്ങൾക്ക് ഇവിടുത്തെ ഡ്രൈവിംഗ് ലൈസൻസ് ഉണ്ടോ?"
ഞാൻ മറുപടി പറയുന്നു.
"ഇല്ല, എനിക്ക് ഡ്രൈവിംഗ് ലൈസൻസ് ഇല്ല."
അദ്ദേഹം തല ആട്ടുന്നു.
അദ്ദേഹം ഒരു പേപ്പർ എനിക്ക് തരുന്നു.
ഞാൻ പേപ്പറിൽ ഒപ്പിടുന്നു.
എന്റെ രജിസ്ട്രേഷൻ പൂർത്തിയാകുന്നു.
