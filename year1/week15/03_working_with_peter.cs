Přicházím do kanceláře.
Je to velká softwarová firma.
Jdu dovnitř.
Můj kolega Peter už tam je.
Je velmi přátelský.
„Dobré ráno, Mayo,“ říká Peter.
„Dobré ráno, Petere,“ říkám.
Jdu na své místo.
Sedím u svého stolu.
Zapínám svůj počítač.
Mám šálek kávy.
Je černá a horká.
Piju kávu.
Pracuji jako softwarová inženýrka.
Dívám se na obrazovku.
Píšu kód na svém počítači.
Ta práce je velmi zajímavá.
Jsem se svou prací spokojená.
