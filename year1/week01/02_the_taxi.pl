Jestem teraz na zewnątrz.
Moja walizka jest duża i ciężka.
Tam jest taksówka.
Wkładam moją walizkę do taksówki.
Kierowca to przyjazny mężczyzna.
„Jaki jest adres?” – pyta.
„To Parkvej numer dwanaście” – mówię.
Kiwa głową i rusza.
„Jesteś turystką?” – pyta kierowca.
„Nie, nie jestem turystką” – odpowiadam.
„Skąd pochodzisz?” – pyta.
„Pochodzę z Meksyku” – mówię.
Wyglądam przez okno.
Jestem bardzo dumna.
„Jestem inżynierem oprogramowania” – mówię.
„Moja nowa praca jest tutaj, w Kopenhadze.”
Uśmiecha się.
„Jakie to ekscytujące.”
„Powodzenia w Danii” – mówi.
„Bardzo dziękuję” – mówię.
