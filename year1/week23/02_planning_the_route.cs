Dávám si malou přestávku od práce.
Vytahuji telefon, abych se podívala na mapu.
Chci najít Evinu adresu.
Bydlí úplně na druhé straně města.
Pozorně si prohlížím trasu na obrazovce.
Je to vlastně docela daleko.
Peter vchází do kuchyňky pro šálek kávy.
Dívá se mi přes rameno a ptá se, co dělám.
„V pátek jedu navštívit Evu,“ vysvětluji.
„Pojedeš tam na kole?“ ptá se.
Na chvíli se nad tím zamyslím.
Myslím, že asi pojedu autobusem.
Mám pocit, že je to na kolo prostě moc daleko.
„Ne, mám v plánu jet autobusem,“ odpovídám mu.
„Tak si cestou můžeš i odpočinout,“ říká Peter s úsměvem.
Má naprostou pravdu.
Zavírám aplikaci a dávám telefon zpátky do kapsy.
Teď je moje trasa naplánovaná.
Těším se na příjemný večer.
