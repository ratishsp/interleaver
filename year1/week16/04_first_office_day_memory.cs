Kasper se zeptal:
„A co tvoje práce?“
Na chvíli jsem se zamyslela.
Pak se Sara zeptala na můj první den v té softwarové firmě.
To ráno jsem byla docela nervózní.
Jela jsem do práce autobusem.
Dívala jsem se z okna a přemýšlela o svých nových kolezích.
Vešla jsem do té velké budovy.
Stála jsem v nové kanceláři a řekla ahoj.
Rychle ke mně přišel nějaký muž.
„Vítej v Dánsku, jmenuji se Peter,“ řekl vlídně.
Peter se široce usmál a ukázal mi můj nový stůl.
Byl to můj nový kolega.
Vypili jsme spolu šálek kávy.
Zeptal se na mou dlouhou cestu z Mexika.
Bylo to velmi příjemné a já se uvolnila.
Sara přikývla a podívala se na mě.
„Dobří kolegové jsou nesmírně důležití,“ řekla.
Naprosto jsem souhlasila.
