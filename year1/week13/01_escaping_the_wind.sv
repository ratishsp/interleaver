Det är vinter i Köpenhamn.
Jag går nerför gatan.
Vinden är mycket kall.
Det blåser hårt i dag.
Jag lutar mig mot den kalla blåsten.
Jag drar upp min halsduk.
Jag fryser om ansiktet.
Jag tittar mig omkring.
Jag vill gärna komma in i värmen.
Jag ser ett litet café på hörnet.
Fönstren är immiga.
Det ser varmt ut där inne.
Jag går fram till caféet.
Jag öppnar den tunga dörren.
Jag stiger in.
Det doftar kaffe här.
Luften är härligt varm.
Jag stänger dörren bakom mig.
Den kalla vinden stannar utanför.
