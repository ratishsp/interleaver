ഞാൻ അപ്പാർട്ട്മെൻ്റിൻ്റെ അടുത്തേക്ക് നടക്കുന്നു.
എൻ്റെ കൈയിൽ പലചരക്ക് സാധനങ്ങളുടെ സഞ്ചികൾ ഉണ്ട്.
ഈ സഞ്ചികൾക്ക് നല്ല ഭാരമുണ്ട്.
ഞാൻ പടികൾക്ക് അടുത്ത് അനിതയെ കാണുന്നു.
അവർ എന്നെ കാണുന്നു.
അനിത പ്രധാന വാതിലിൻ്റെ അടുത്തേക്ക് വരുന്നു.
അവർ എനിക്കായി വാതിൽ തുറന്നു പിടിക്കുന്നു.
"നന്ദി, അനിത," ഞാൻ പറയുന്നു.
"സഞ്ചികൾക്ക് നല്ല ഭാരമുണ്ടോ?" അവർ ചോദിക്കുന്നു.
"അതെ, നല്ല ഭാരമുണ്ട്," ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ മെല്ലെ അകത്തേക്ക് നടക്കുന്നു.
അനിത എൻ്റെ സഞ്ചികളിലെ പച്ചക്കറികൾ കാണുന്നു.
"മായയ്ക്ക് പാചകം ഇഷ്ടമാണോ?" അവർ ചോദിക്കുന്നു.
"അതെ, എനിക്ക് പാചകം ഇഷ്ടമാണ്," ഞാൻ പറയുന്നു.
"രാത്രി ഭക്ഷണത്തിന് ഇന്ന് എന്ത് വേണം?" അനിത ചോദിക്കുന്നു.
"എനിക്ക് ഇന്ന് ഒരു വെജിറ്റബിൾ കറി വേണം," ഞാൻ പറയുന്നു.
"എൻ്റെ കൈയിൽ പുതിയ പച്ചക്കറികൾ ഉണ്ട്."
"അത് വളരെ നല്ലതാണ്," അവർ പറയുന്നു.
ഞാൻ അവരെ നോക്കി ചിരിക്കുന്നു.
ഞാൻ പതുക്കെ എൻ്റെ ഫ്ലാറ്റിലേക്ക് പോകുന്നു.
