Patrzę na mój komputer.
Trochę tęsknię za moim domem w Meksyku.
„Tato, jak tam twój ogród?” – mówię.
Mój tata uśmiecha się do mnie.
Wychodzi na zewnątrz z telefonem.
Jest tam duży ogród.
Słońce mocno tam świeci.
„Spójrz, Maya” – mówi mój tata.
„Tutaj jest ogród i drzewo”.
To bardzo duże drzewo.
To piękne drzewo.
Uśmiecham się do mojego ekranu.
Czuję się dobrze i jest mi ciepło na sercu.
Moja mama, moja siostra i mój brat też wychodzą na zewnątrz.
Mój pies biega pod drzewem.
Cała moja rodzina macha do mnie.
„Pa wszystkim!” – mówię.
„Pa, Maya” – mówią.
Zamykam mój komputer.
