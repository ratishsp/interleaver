Podchodzę do kasy z moimi nowymi rzeczami.
Ekspedientka podnosi wzrok i mówi cześć.
„Cześć” – mówi.
„Cześć” – odpowiadam.
Kładę jasnozieloną kurtkę i niebieską koszulę na ladzie.
Skanuje obie rzeczy.
„To będzie sześćset pięćdziesiąt koron” – mówi.
Płacę kartą.
„Czy chce pani paragon?” – pyta ekspedientka.
„Tak, poproszę” – odpowiadam szybko.
„Nie przymierzałam tej koszuli” – wyjaśniam.
„Mam nadzieję, że nie będę potrzebować większej.”
„Zawsze może ją pani wymienić” – mówi uprzejmie ekspedientka.
Drukuje paragon i podaje mi go.
„Proszę pamiętać, żeby go zachować” – mówi.
Biorę paragon.
Składam ten mały kawałek papieru.
Potem wkładam go bezpiecznie do portfela.
„Miłego weekendu” – mówię do niej.
„Wzajemnie” – odpowiada.
