Teraz muszę ugotować ziemniaki.
Znowu patrzę na mój przepis.
Ma kilka bardzo krótkich instrukcji.
Najpierw jest napisane: „Wyszoruj małe ziemniaki do czysta”.
Robię to małą szczoteczką pod zimną wodą.
Potem czytam kolejną linijkę.
Następnie jest napisane: „Włóż ziemniaki do garnka z wodą”.
Wyciągam swój duży garnek z szafki.
Wkładam cały kilogram do garnka.
Garnek jest prawie całkowicie pełny.
Jaki jest następny krok?
Przepis mówi: „Dodaj dużą łyżkę gruboziarnistej soli do wody”.
Wyjmuję sól i łyżkę.
Nasypuję sól na łyżkę.
Dodaję tę dużą łyżkę do ziemniaków.
Na koniec jest napisane: „Włącz kuchenkę”.
Stawiam garnek na kuchence i włączam ją.
Teraz ziemniaki muszą się tylko gotować przez dwadzieścia minut.
