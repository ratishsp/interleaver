Det är lördag och jag kopplar av i min soffa.
Jag startar ett videosamtal till min familj i Mexiko.
Min mamma svarar nästan med detsamma.
"Hej Maya, min älskling," säger hon med ett stort leende.
Jag kan se min syster Sofía, min bror Diego och vår hund Lola i bakgrunden.
"Hej mamma."
"Det går riktigt bra här," säger jag glatt.
Vi pratar lite om deras vecka hemma i Mexiko.
Sedan frågar min mamma om något var svårt i början.
Jag tänker tillbaka på min första tid i staden.
Allting var nytt, och dagarna var ibland svåra.
"Början var inte alltid lätt," berättar jag för henne.
"Jag väntade i en lång kö en hel förmiddag."
"Jag satt i ett tomt kök och saknade er."
"En lördag gick jag fel och gick vilse."
"Och i början hade jag inte en tillräckligt varm jacka," tillägger jag.
Min mamma lyssnar uppmärksamt och nickar.
Hon vill väldigt gärna höra alla historierna från min start i Danmark.
Jag tar en klunk av mitt te och berättar vidare.
