ഞാൻ ഓഫീസിൽ എത്തുന്നു.
ഞാൻ വലിയ ചില്ലുവാതിൽ തുറക്കുന്നു.
ഞാൻ ഉള്ളിലേക്ക് നടക്കുന്നു.
ഓഫീസിൽ നല്ല തണുപ്പാണ്.
എസി പ്രവർത്തിക്കുകയാണ്.
എൻ്റെ സഹപ്രവർത്തകർ ഇവിടെ ഉണ്ട്.
അവർ അവരുടെ ഡെസ്കുകളിൽ ഇരിക്കുകയാണ്.
ചിലർ സംസാരിക്കുകയാണ്.
ഞാൻ എൻ്റെ സഹപ്രവർത്തകൻ പ്രകാശിനെ കാണുന്നു.
പ്രകാശ് കമ്പ്യൂട്ടറിൽ നോക്കുകയാണ്.
"ഗുഡ് മോണിംഗ് മായാ," പ്രകാശ് പറയുന്നു.
ഞാൻ ചിരിക്കുന്നു.
"ഗുഡ് മോണിംഗ്," ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ എല്ലാവർക്കും ഗുഡ് മോണിംഗ് പറയുന്നു.
ഞാൻ എൻ്റെ സീറ്റിലേക്ക് നടക്കുന്നു.
ഞാൻ ബാഗ് മേശപ്പുറത്ത് വെക്കുന്നു.
ഞാൻ എൻ്റെ കസേരയിൽ ഇരിക്കുന്നു.
ഞാൻ കമ്പ്യൂട്ടർ ഓൺ ചെയ്യുന്നു.
ഞാൻ ഇപ്പോൾ എൻ്റെ ജോലി തുടങ്ങുകയാണ്.
