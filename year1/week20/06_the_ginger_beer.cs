Byla to moje druhá sobotní směna v kavárně.
Už jsem se naučila dělat velkou část práce.
To dopoledne bylo venku krásně teplo.
K pultu přišla žena.
„Chtěla bych poprosit o jedno zázvorové pivo,“ řekla.
„Samozřejmě, moment,“ odpověděla jsem.
Přešla jsem k velké prosklené lednici za pultem.
Podívala jsem se na třetí polici.
Tam stály studené láhve se zázvorovým pivem.
Našla jsem jednu láhev a vyndala ji.
Zázvor ležel jako hustý mrak dole na dně.
Naučila jsem se ho promíchat, než láhev otevřu.
Takže jsem láhev velmi opatrně otočila dnem vzhůru.
Držela jsem ji tak pár sekund.
Zázvor se pomalu smíchal se zbytkem tekutiny.
Teď už nápoj vypadal naprosto správně.
Znovu jsem láhev otočila a postavila ji na pult.
„Prosím, bude to třicet pět korun,“ řekla jsem jí.
Zaplatila a pravděpodobně si svůj studený nápoj vychutnala.
