ഇപ്പോൾ വൈകുന്നേരമാണ്.
ഞാൻ അടുത്തുള്ള ബസ് സ്റ്റാൻഡിലേക്ക് നടക്കുന്നു.
അവിടെ എന്റെ സ്ഥലത്തേക്കുള്ള ഒരു ബസ്സുണ്ട്.
ഞാൻ ബസ്സിൽ കയറുന്നു.
ഞാൻ കണ്ടക്ടറോട് ചോദിക്കുന്നു.
"ഈ ബസ് കാക്കനാട്ടേക്ക് പോകുമോ?"
അദ്ദേഹം പറയുന്നു, "അതെ, അകത്തേക്ക് വരൂ."
"ആ ജനലിന്റെ അടുത്ത് ഇരിക്കൂ."
ഞാൻ അവിടെ ഇരിക്കുന്നു.
ബസ് നേരെ പോകുന്നു.
പിന്നെ വലത്തോട്ട് തിരിയുന്നു.
ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
ഈ റോഡുകൾ എനിക്ക് പരിചിതമാണ്.
കുറച്ച് കഴിഞ്ഞ് ബസ് ഇടത്തോട്ട് തിരിയുന്നു.
ഇപ്പോൾ എനിക്ക് ഈ നഗരം മനസ്സിലാകുന്നു.
എന്റെ സ്ഥലവും കായൽത്തീരവും തമ്മിൽ നന്നായി ബന്ധിപ്പിച്ചിരിക്കുന്നു.
മറൈൻ ഡ്രൈവിൽ നിന്ന് എന്റെ വീട്ടിലേക്കുള്ള വഴി എളുപ്പമാണ്.
കൊച്ചി എനിക്ക് വളരെ ഇഷ്ടമാണ്.
ഞാൻ സന്തോഷത്തോടെ വീട്ടിലേക്ക് പോകുന്നു.
