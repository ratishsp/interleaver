Krátce nato přišla další objednávka.
Dnes už jsem udělala svou první kávu.
Ale tento zákazník chtěl jen jídlo.
Objednal si bulku se sýrem.
Vzala jsem z košíku teplou kváskovou bulku.
Kváskový chléb má často tvrdou kůrku.
Ale naučila jsem se chléb rychle rozkrojit napůl.
Poté jsem na bulku položila silný plátek sýra.
Jídlo jsem pěkně naaranžovala na malý talířek.
Teď jsem to musela odnést zákazníkovi.
Uprostřed kavárny stálo mnoho lidí.
Balancovala jsem s talířkem a opatrně šla vpřed.
Šla jsem pomalu kolem ostatních hostů.
Zákazník naštěstí seděl úplně vzadu v rohu.
Čekal u čtvrtého stolu.
Položila jsem talířek na stůl před něj.
„Tady máte, teplá bulka se sýrem,“ řekla jsem.
„Moc děkuji,“ odpověděl muž.
Je krásné vidět spokojeného hosta.
