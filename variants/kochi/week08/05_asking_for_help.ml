ഞാൻ ഈ വലിയ മാർക്കറ്റിലാണ്.
എനിക്ക് വഴി അറിയില്ല.
ഞാൻ ഒരു സ്ത്രീയെ കാണുന്നു.
അവരുടെ കയ്യിൽ ഷോപ്പിംഗ് ബാഗുകൾ ഉണ്ട്.
ഞാൻ അവരുടെ അടുത്തേക്ക് നടക്കുന്നു.
"ക്ഷമിക്കണം," ഞാൻ പറയുന്നു.
"വാക്ക്‌വേയിലേക്ക് ഏതാണ് വഴി?" ഞാൻ ചോദിക്കുന്നു.
ആ സ്ത്രീ ചിരിക്കുന്നു.
"നിങ്ങൾ ഇപ്പോൾ മാർക്കറ്റിലാണ്," അവർ പറയുന്നു.
"ആദ്യം ഇവിടെ നിന്ന് പുറത്തേക്ക് നടക്കൂ."
"മെയിൻ റോഡിലേക്ക് തിരികെ പോകൂ."
"അവിടെ നിന്ന് നേരെ പോകൂ."
"റോഡിന്റെ അവസാനം വരെ നേരെ നടക്കൂ."
"അവിടെ നിന്ന് വലത്തോട്ട് തിരിയൂ."
"ആ റോഡ് നേരെ വാക്ക്‌വേയിലേക്ക് പോകുന്നു," അവർ പറയുന്നു.
എനിക്ക് വഴി മനസ്സിലാകുന്നു.
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
അവർ സന്തോഷത്തോടെ തലയാട്ടുന്നു.
ഞാൻ മെയിൻ റോഡിലേക്ക് തിരികെ നടക്കുന്നു.
