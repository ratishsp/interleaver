ബോട്ട് വെള്ളത്തിന്റെ മറുകരയിൽ എത്തിച്ചേരുന്നു.
ഹാർബർ ബസ് ഒരു ചെറിയ ജെട്ടിയിൽ നിർത്തുന്നു.
ഞാൻ ബോട്ടിൽ നിന്ന് ഇറങ്ങുന്നു.
ബോട്ടിലുള്ള യാത്ര ഇപ്പോൾ അവസാനിച്ചു.
ഞാൻ എന്റെ ഫോണിലെ മാപ്പ് പരിശോധിക്കുന്നു.
ഞാൻ ഒരു ചെറിയ കിയോസ്കിലേക്കാണ് പോകുന്നത്.
ആ കിയോസ്ക് അവിടെയൊരു മൂലയിലാണ് ഉള്ളത്.
ഞാൻ ആ തെരുവിലൂടെ മുന്നോട്ട് നടക്കുന്നു.
റോഡിന്റെ അവസാനത്തിൽ ഞാൻ ആ കട കാണുന്നു.
ഞാൻ വാതിൽ തുറന്ന് അകത്തേക്ക് കയറുന്നു.
ഒരു ചെറുപ്പക്കാരൻ ക്യാഷ് കൗണ്ടറിന് പിന്നിൽ നിൽപ്പുണ്ട്.
"ഹായ്," അവൻ സ്നേഹത്തോടെ പറയുന്നു.
"ഹായ്, ഞാനൊരു പാഴ്സൽ എടുക്കാൻ വന്നതാണ്," ഞാൻ പറയുന്നു.
അയാൾ തലകുലുക്കി പുഞ്ചിരിക്കുന്നു.
അയാൾ എന്റെ പേര് ചോദിക്കുന്നു.
"എന്റെ പേര് മായ," ഞാൻ മറുപടി നൽകുന്നു.
അയാൾ ഷെൽഫിൽ ഒരു വലിയ പെട്ടി കണ്ടെത്തുന്നു.
അയാൾ ആ പാഴ്സൽ എനിക്ക് തരുന്നു.
"സഹായിച്ചതിന് വളരെ നന്ദി," ഞാൻ പറയുന്നു.
ഇപ്പോൾ എന്റെ പാഴ്സലുമായി ഞാൻ വീണ്ടും വീട്ടിലേക്ക് നീണ്ട യാത്ര തിരിക്കുന്നു.
