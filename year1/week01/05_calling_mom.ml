ഞാൻ ഇപ്പോൾ സ്വീകരണമുറിയിലാണ്.
അവിടെ ഒരു ചെറിയ സോഫയുണ്ട്.
ഞാൻ മെക്സിക്കോയിലുള്ള എന്റെ അമ്മയെ വിളിക്കുന്നു.
"ഹായ് അമ്മേ," ഞാൻ പറയുന്നു.
"ഹായ് മായാ," എന്റെ അമ്മ പറയുന്നു.
"നീ എവിടെയാണ്?" അവർ ചോദിക്കുന്നു.
"ഞാൻ കോപ്പൻഹേഗനിലാണ്," ഞാൻ മറുപടി നൽകുന്നു.
"ഞാൻ ഇപ്പോൾ അപ്പാർട്ട്മെന്റിലാണ്."
"അത് വളരെ നല്ലതാണ്," എന്റെ അമ്മ പറയുന്നു.
"അത് വലുതാണോ?" അവർ ചോദിക്കുന്നു.
"അല്ല, അത് ചെറുതാണ്," ഞാൻ മറുപടി നൽകുന്നു.
"പക്ഷേ ഇത് സുഖപ്രദമാണ്, ഞാൻ സന്തോഷവതിയുമാണ്."
"തണുപ്പാണോ?" അവർ ചോദിക്കുന്നു.
"അതെ, പുറത്ത് തണുപ്പാണ്," ഞാൻ പറയുന്നു.
"പക്ഷേ ഇവിടെ ചൂടുണ്ട്."
"ഞാൻ സുരക്ഷിതയാണ്."
"അത് നല്ലതാണ്," എന്റെ അമ്മ പറയുന്നു.
ഞാൻ പുഞ്ചിരിക്കുന്നു.
ഡെന്മാർക്കാണ് എന്റെ പുതിയ വീട്.
