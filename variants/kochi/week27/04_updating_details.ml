ഞാൻ ലോഗിൻ ചെയ്ത് പ്രൊഫൈൽ സെക്ഷൻ എടുക്കുന്നു.
സ്ക്രീനിൽ ഒരു ഡിജിറ്റൽ ഫോം ഉണ്ട്.
ഞാൻ ഓരോ വിവരങ്ങളും പതുക്കെ പൂരിപ്പിക്കുന്നു.
ഇവിടെ ഒരു ഔദ്യോഗിക തിരിച്ചറിയൽ രേഖ ആവശ്യപ്പെടുന്നു.
ഞാൻ ബാഗിൽ നിന്ന് എൻ്റെ വർക്ക് വിസ എടുക്കുന്നു.
അത് മേശപ്പുറത്ത് വെച്ച് ഞാൻ ഒരു വ്യക്തമായ ഫോട്ടോ എടുക്കുന്നു.
അതിനുശേഷം ഞാൻ ആ ഫോട്ടോ വെബ്സൈറ്റിൽ അപ്‌ലോഡ് ചെയ്യുന്നു.
ഞാൻ വീണ്ടും സ്ക്രീനിലേക്ക് നോക്കുന്നു.
അപ്‌ലോഡ് ബാർ വളരെ പതുക്കെയാണ് നീങ്ങുന്നത്.
ജനുവരിയിൽ ഇത്തരം കാര്യങ്ങൾ എനിക്ക് വലിയ ബുദ്ധിമുട്ടായിരുന്നു.
പക്ഷേ ഇപ്പോൾ ഞാൻ ഇവയെല്ലാം വേഗത്തിൽ ചെയ്തു തീർക്കാറുണ്ട്.
എനിക്ക് ഇപ്പോൾ ഇത്തരം വെബ്സൈറ്റുകൾ എളുപ്പത്തിൽ ഉപയോഗിക്കാൻ അറിയാം.
അവസാനം, ഫോട്ടോ വിജയകരമായി അപ്‌ലോഡ് ചെയ്യപ്പെടുന്നു.
തുടർന്ന് ഞാൻ ഫോമിലെ അടുത്ത ഭാഗത്തേക്ക് പോകുന്നു.
