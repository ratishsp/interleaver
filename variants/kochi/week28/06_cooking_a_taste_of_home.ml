ഇന്ന് ശനിയാഴ്ച ഉച്ചകഴിഞ്ഞാണ്.
ഞാൻ എൻ്റെ ഫ്ലാറ്റിലെ അടുക്കളയിലാണ്.
മഴയുടെ ശബ്ദം കേൾക്കാൻ നല്ല രസമാണ്.
ഞാൻ ഇന്ന് എൻ്റെ നാട്ടിലെ ഭക്ഷണമാണ് ഉണ്ടാക്കുന്നത്.
ഞാൻ സൽസയും എരിവുള്ള ഒരു ബീൻസ് വിഭവവും ആണ് തയ്യാറാക്കുന്നത്.
ഇതിനുള്ള പച്ചക്കറികൾ ഞാൻ ഇന്നലെ വാങ്ങിയിരുന്നു.
ഞാൻ തക്കാളിയും ഉള്ളിയും പച്ചമുളകും എടുക്കുന്നു.
ഞാൻ അവ നന്നായി കഴുകി വൃത്തിയാക്കുന്നു.
സൽസ ഉണ്ടാക്കാൻ ഞാൻ അവ ചെറിയ കഷ്ണങ്ങളായി മുറിക്കുന്നു.
പിന്നീട് ഞാൻ ബീൻസ് വേവിക്കാൻ തുടങ്ങുന്നു.
ഞാൻ അതിൽ കുറച്ച് മസാലകൾ ചേർക്കുന്നു.
അടുക്കളയിൽ ഇപ്പോൾ മെക്സിക്കോയിലെ എൻ്റെ വീടിൻ്റെ മണമാണ്.
ആ ഗന്ധം എനിക്ക് വളരെ പരിചിതമാണ്.
ഞാൻ ഒരു മണിക്കൂറോളം അടുക്കളയിൽ ചിലവഴിക്കുന്നു.
ഇപ്പോൾ ഭക്ഷണം തയ്യാറായി.
ഇന്ന് രാത്രി അനിത ഇവിടെ അത്താഴം കഴിക്കാൻ വരുന്നുണ്ട്.
ഈ ഭക്ഷണം അവർക്ക് ഇഷ്ടമാകുമെന്ന് ഞാൻ കരുതുന്നു.
