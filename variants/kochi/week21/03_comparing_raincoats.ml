ഞാൻ മഴക്കോട്ട് കിട്ടുന്ന ഭാഗത്തേക്ക് നടക്കുന്നു.
ഇവിടെ പലതരം മഴക്കോട്ടുകൾ ഉണ്ട്.
ഞാൻ അതിൽ നിന്ന് രണ്ട് കോട്ടുകൾ എടുക്കുന്നു.
ഒന്ന് ഒരു കടും നീല കോട്ടാണ്.
ഇതിന് നല്ല ഭാരമുണ്ട്.
രണ്ടാമത്തേത് തിളങ്ങുന്ന മഞ്ഞ നിറത്തിലുള്ള കോട്ടാണ്.
ഇതിന് അധികം ഭാരമില്ല.
ഞാൻ രണ്ട് കോട്ടുകളും നോക്കുന്നു.
നീല കോട്ടിനെക്കാൾ നല്ലത് മഞ്ഞ കോട്ടാണ്.
കാരണം, ഞാൻ ചിലപ്പോൾ പുറത്ത് പോകുമ്പോൾ സൈക്കിൾ ഓടിക്കാറുണ്ട്.
മഴയത്ത് മഞ്ഞ നിറം മറ്റുള്ളവർക്ക് എളുപ്പം കാണാം.
അതുപോലെ, ഈ മഞ്ഞ കോട്ട് അത്യാവശ്യം വലുതാണ്.
ഇത് നീല കോട്ടിനെക്കാൾ വലുതാണോ?
അതെ, ഇത് നീല കോട്ടിനെക്കാൾ വളരെ വലുതാണ്.
എന്റെ ബാക്ക്പാക്കും വലുതാണ്.
ഈ മഞ്ഞ കോട്ട് എന്റെ ബാക്ക്പാക്കും മൂടും.
അതുകൊണ്ട്, ഞാൻ ഈ മഞ്ഞ മഴക്കോട്ട് വാങ്ങാൻ തീരുമാനിക്കുന്നു.
ഞാൻ ആ നീല മഴക്കോട്ട് തിരികെ വെക്കുന്നു.
