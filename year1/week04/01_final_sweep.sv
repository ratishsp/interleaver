Det är januari i Köpenhamn.
Jag står i mitt tillfälliga rum.
Idag flyttar jag till en ny lägenhet.
Den ligger i samma byggnad.
Min stora resväska står på golvet.
Jag stänger den.
Jag tittar runt i rummet en sista gång.
Jag tittar under den lilla sängen.
Det ligger en bok under sängen.
Den är från Mexiko.
Jag lägger boken i min väska.
Jag öppnar garderoben.
Det står ett par skor i garderoben.
Jag tar skorna.
Nu finns det ingenting i garderoben.
Jag går fram till skrivbordet vid fönstret.
Det ligger en kabel på bordet.
Jag tar kabeln.
Jag lägger kabeln i min väska.
Jag tar mina två väskor.
Jag släcker ljuset och stänger dörren.
