Jag står vid fönstret i vardagsrummet.
Jag tittar ut över staden.
Himlen är inte svart längre.
Den blir långsamt grå.
Solen går upp sent.
Jag tar min telefon.
Jag läser väderprognosen för idag.
Just nu är det mycket kallt.
Det är bara två grader.
Men det är fortfarande torrt ute.
Senare blir det mycket blött.
Det regnar snart.
Det blir också blåsigt.
Det blåser hårt senare på dagen.
Det blir en riktig vinterdag.
Jag lägger telefonen på bordet.
Jag tittar på himlen en gång till.
