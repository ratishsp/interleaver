ഇപ്പോൾ വലിയ മഴ ഇല്ല.
ചെറിയ കാറ്റ് വീശുന്നു.
ഞാൻ വാതിൽ തുറക്കുന്നു.
ഞാൻ അകത്തേക്ക് കയറുന്നു.
ഞാൻ നേരെ ജനലിൻ്റെ അടുത്തേക്ക് നടക്കുന്നു.
ഞാൻ ജനൽ തുറക്കുന്നു.
നല്ല തണുത്ത കാറ്റ് അകത്തേക്ക് വരുന്നു.
പകൽ വലിയ ചൂടായിരുന്നു.
ഇപ്പോൾ ആ ചൂട് തീരെ ഇല്ല.
മുറിയിൽ നല്ല തണുപ്പാണ്.
ഞാൻ വെളിയിലേക്ക് നോക്കുന്നു.
വഴിയിൽ മുഴുവൻ വെള്ളമാണ്.
രാത്രിയും മഴ പെയ്യും.
എനിക്ക് ഈ കാലാവസ്ഥ വളരെ ഇഷ്ടമാണ്.
ഞാൻ കുറച്ചു സമയം അവിടെ നിൽക്കുന്നു.
ഈ വൈകുന്നേരം വളരെ മനോഹരമാണ്.
ഈ ദിവസം സമാധാനമായി ഇവിടെ അവസാനിക്കുന്നു.
