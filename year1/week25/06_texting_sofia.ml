ഞാൻ മ്യൂസിയത്തിലെ കഫേയിൽ ഇരുന്ന് ഒരു ഇടവേള എടുക്കുകയാണ്.
ഞാൻ ഒരു കപ്പ് കാപ്പി കുടിച്ച് വിശ്രമിക്കുന്നു.
ഞാൻ എന്റെ ബാഗിൽ നിന്ന് ആ നീല പ്ലേറ്റുകൾ പുറത്തെടുക്കുന്നു.
ഈ പ്ലേറ്റുകൾ എന്റെ അടുക്കളയ്ക്ക് തികച്ചും അനുയോജ്യമാണ്.
എന്റെ ഫോൺ ഉപയോഗിച്ച് ഞാൻ അവയുടെ ഒരു ചിത്രമെടുക്കുന്നു.
ഞാൻ ആ ചിത്രം എന്റെ സഹോദരി സോഫിയയ്ക്ക് അയച്ചുകൊടുക്കുന്നു.
"ഈ മനോഹരമായ പ്ലേറ്റുകൾ ഒന്നു നോക്കൂ," എന്ന് ഞാൻ എഴുതുന്നു.
"ഒരു മണിക്കൂർ മുമ്പ് ഒരു മാർക്കറ്റിൽ നിന്നാണ് എനിക്കിവ കിട്ടിയത്."
സോഫിയ എനിക്ക് പെട്ടെന്നുതന്നെ മറുപടി നൽകുന്നു.
അവൾ എനിക്ക് ഒരു പഴയ ചിത്രം തിരികെ അയക്കുന്നു.
ഈ സന്ദേശം എന്നെ വളരെ സന്തോഷിപ്പിക്കുന്നു.
മെക്സിക്കോയിലെ ഒരു വലിയ ഫ്ലീ മാർക്കറ്റിൽ നിൽക്കുന്ന ഞങ്ങളെ രണ്ടുപേരെയുമാണ് ആ ചിത്രം കാണിക്കുന്നത്.
"ഈ മാർക്കറ്റ് നിനക്ക് ഓർമ്മയുണ്ടോ?"
അടുത്ത സന്ദേശത്തിൽ സോഫിയ ചോദിക്കുന്നു.
"കൃത്യം രണ്ടു വർഷം മുമ്പ് നമ്മൾ അവിടെ ഉണ്ടായിരുന്നു!" അവൾ എഴുതുന്നു.
ചിത്രത്തിലെ ഞങ്ങളുടെ സന്തോഷം നിറഞ്ഞ മുഖങ്ങളിലേക്ക് ഞാൻ നോക്കുന്നു.
അത് വളരെക്കാലം മുമ്പുള്ള കാര്യമാണെന്ന് തോന്നുന്നു.
രണ്ടു വർഷം മുമ്പ് ഞാൻ മെക്സിക്കോയിൽ തന്നെയാണ് താമസിച്ചിരുന്നത്.
ഞാൻ പുഞ്ചിരിച്ചുകൊണ്ട് ഒരു സന്തോഷകരമായ സന്ദേശം തിരികെ എഴുതുന്നു.
