ഞാൻ ബസ്സിൽ നഗരത്തിലേക്ക് പോകുന്നു.
ഞാൻ ആ വലിയ കടയിൽ എത്തുന്നു.
ഞാൻ സ്ത്രീകളുടെ സെക്ഷനിലേക്ക് പോകുന്നു.
അവിടെ ഒരുപാട് വസ്ത്രങ്ങൾ ഉണ്ട്.
ഞാൻ കോട്ടൺ വസ്ത്രങ്ങൾ നോക്കുന്നു.
ഞാൻ നല്ല ഒരു നീല കുർത്ത കാണുന്നു.
ഈ നീല കുർത്ത വളരെ നല്ലതാണ്.
ഞാൻ കടയിലെ ഒരാളോട് വില ചോദിക്കുന്നു.
"ഈ കുർത്തയ്ക്ക് എന്താണ് വില?" ഞാൻ ചോദിക്കുന്നു.
"അറുനൂറ് രൂപ," അയാൾ പറയുന്നു.
അറുനൂറ് രൂപ വലിയ വിലയല്ല.
ഞാൻ മീഡിയം സൈസ് കുർത്ത എടുക്കുന്നു.
ഞാൻ ഫിറ്റിംഗ് റൂമിലേക്ക് പോകുന്നു.
ഞാൻ ആ നീല കുർത്ത ഇടുന്നു.
മീഡിയം സൈസ് എനിക്ക് കൃത്യമാണ്.
എനിക്ക് ഈ കുർത്ത വളരെ ഇഷ്ടമാണ്.
ഞാൻ ഇത് വാങ്ങാൻ തീരുമാനിക്കുന്നു.
