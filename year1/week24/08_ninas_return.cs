Je nedělní odpoledne a někdo klepe na dveře.
Ludwig vyběhne na chodbu a radostně štěká.
Otevřu dveře a venku stojí Nina se svou víkendovou taškou.
„Ahoj Mayo, moc děkuju za pomoc,“ říká a usmívá se.
Vrtí ocasem a skáče na ni.
„Dolů, Ludwigu,“ říká Nina a hladí ho.
„Byl to opravdu hodný pes,“ říkám jí.
Nina se směje a bere z malého stolku jeho vodítko.
„Byla jsi s ním na procházce v psím lese?“ ptá se.
„Ano, a moc se mu to líbilo,“ odpovídám.
Dávám jí zbytek psího krmiva.
„Prosím, tady je zbytek.“
„Moc ráda ho zase někdy pohlídám.“
„Jasně,“ říká Nina.
„Pojď, Ludwigu, musíme domů,“ říká Nina psovi.
Mávám jim oběma na rozloučenou.
Byt je bez něj najednou velmi tichý.
