Jag går hem genom en stor park.
För en timme sedan var jag på museum.
Nu vill jag bara njuta av det fina vädret.
Jag stannar vid en liten kiosk för att köpa en strutglass.
"Varsågod, här är din glass," säger mannen i kiosken.
"Tack så mycket," svarar jag och tar glassen.
Jag går långsamt längs sjön i parken.
Den här strutglassen ser verkligen god ut.
Plötsligt hör jag ett högt ljud ovanför mig.
En stor fiskmås dyker rakt ner mot mig.
Den vill stjäla min glass!
Jag duckar snabbt och skyddar min glass med handen.
Fågeln ska inte stjäla min mat.
Fiskmåsen flyger förbi och landar på gräset.
En kvinna på en bänk skrattar.
"De är väldigt fräcka i dag," säger hon.
"Ja, det är de verkligen," skrattar jag tillbaka.
Jag äter snabbt upp min glass medan jag går vidare.
