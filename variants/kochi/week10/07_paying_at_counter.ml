ഞാൻ ബില്ലിംഗ് കൗണ്ടറിലേക്ക് പോകുന്നു.
എന്റെ കയ്യിൽ മൂന്ന് സാധനങ്ങൾ ഉണ്ട്.
ഒരു മഞ്ഞ കുർത്തി, ഒരു വലിയ വെള്ള ഷാൾ, പിന്നെ ചുവന്ന പാന്റ്സ്.
ഞാൻ ഈ തുണികൾ കൗണ്ടറിൽ വെക്കുന്നു.
ക്യാഷ്യർ തുണികൾ നോക്കുന്നു.
അദ്ദേഹം ആകെ വില കണക്കുകൂട്ടുന്നു.
ക്യാഷ്യർ എന്നോട് പറയുന്നു.
"ആകെ ആയിരത്തി അറുന്നൂറ് രൂപയാണ്."
ഞാൻ അദ്ദേഹത്തിന് പണം കൊടുക്കുന്നു.
അദ്ദേഹം തുണികൾ ഒരു വലിയ ബാഗിൽ വെക്കുന്നു.
ക്യാഷ്യർ എനിക്ക് ബാഗ് തരുന്നു.
ഞാൻ എന്റെ ബാഗ് എടുക്കുന്നു.
ഈ പുതിയ തുണികൾ ധരിക്കാൻ നല്ലതാണ്.
ഞാൻ കടയിൽ നിന്ന് പുറത്തേക്ക് നടക്കുന്നു.
