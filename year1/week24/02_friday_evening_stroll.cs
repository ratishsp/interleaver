Je pozdní páteční večer.
Než jdeme spát, beru Ludwiga ven.
Jdeme na krátkou procházku po okolí.
Ulice jsou teď velmi tiché.
Ludwig jde pěkně vedle mě.
Najednou se zastaví.
Dychtivě něco očichává na chodníku.
Je to špinavý pytlík se zbytky jídla.
Otevírá tlamu, aby to vzal.
„Ne, pusť to!“ říkám mu rázně.
Jemně ho odtáhnu od pytlíku.
„Odpadky nejsou jídlo, Ludwigu,“ vysvětluji.
„Pojď sem, Ludwigu,“ volám na něj.
Pustí pytlík a podívá se na mě.
Rychle začne vrtět ocasem.
„Hodný kluk,“ říkám a pohladím ho.
Pokračujeme v naší procházce ulicí.
Teď už musíme jen domů a spát.
