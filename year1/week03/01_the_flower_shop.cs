Je leden a je velmi chladno.
Jdu domů z autobusové zastávky v Kodani.
Vidím na ulici květinářství.
Uvnitř je světlo a teplo.
Jdu do teplého obchodu.
Dívám se na malou zelenou rostlinu.
Prodavač se na mě usmívá.
„Dobrý den,“ říká.
„Dobrý den,“ říkám.
„Hledám nějakou rostlinu.“
„Je to dárek?“ ptá se.
„Ne, je to do mého pokoje,“ odpovídám.
„To je opravdu dobrá rostlina,“ říká.
„Kolik stojí?“ ptám se.
„Stojí padesát pět korun,“ odpovídá.
Platím za svou novou rostlinu.
Dává rostlinu do papírové tašky.
„Prosím, tady je vaše taška,“ říká.
„Moc děkuji,“ říkám radostně.
Vycházím ven do chladného večera.
Moje malá rostlina mi dělá velkou radost.
