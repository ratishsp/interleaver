Han tittar över min axel och frågar vad jag gör.
"Jag ska besöka Eva på fredag", förklarar jag.
"Ska du cykla dit?" frågar han.
Jag funderar på det ett ögonblick.
Jag tror att jag nog tar bussen.
Jag känner att det helt enkelt är för långt på cykel.
"Nej, jag har tänkt ta bussen", svarar jag honom.
"Då kan du också slappna av på resan", säger Peter med ett leende.
Han har helt rätt.
Jag stänger appen och lägger tillbaka telefonen i fickan.
