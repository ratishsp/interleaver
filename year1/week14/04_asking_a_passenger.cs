Sedím v autobusu.
Dívám se z okna.
Nejsem si úplně jistá trasou.
Blízko mě sedí starší žena.
Podívám se na ni.
„Promiňte,“ říkám zdvořile.
„Jede tento autobus ke stanici metra?“
Žena se na mě podívá.
Přikývne s přátelským úsměvem.
„Ano, jede ke stanici metra,“ odpovídá.
„Pojedete metrem?“ ptá se žena.
„Ano, pojedu metrem,“ říkám.
„Tímto autobusem jezdím často,“ říká žena.
„Je to jednoduchá trasa,“ dodává.
„Moc děkuji za pomoc,“ říkám.
„Je to moje první cesta na této trase.“
Žena znovu přikývne.
Uvolním se na sedadle.
Jedeme dál městem.
