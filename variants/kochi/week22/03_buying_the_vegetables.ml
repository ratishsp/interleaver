പുറത്ത് നിർത്താതെ മഴ പെയ്യുന്നുണ്ട്.
ഞാൻ കുട എടുത്ത് അടുത്തുള്ള മാർക്കറ്റിലേക്ക് നടക്കുന്നു.
കറി ഉണ്ടാക്കാൻ എനിക്ക് കുറച്ച് പച്ചക്കറികൾ വേണം.
ഞാൻ പതിവായി പോകുന്ന പച്ചക്കറിക്കടയിൽ എത്തുന്നു.
ഞാൻ എന്റെ ലിസ്റ്റ് നോക്കുന്നു.
ഞാൻ കടക്കാരനോട് പച്ചക്കറികൾ ചോദിക്കുന്നു.
"ആദ്യം, എനിക്ക് രണ്ട് വലിയ സവാള തരൂ," ഞാൻ പറയുന്നു.
"പിന്നെ, മൂന്ന് തക്കാളിയും," ഞാൻ കൂട്ടിച്ചേർക്കുന്നു.
അയാൾ സവാളയും തക്കാളിയും എടുക്കുന്നു.
"അതിനുശേഷം, കുറച്ച് ഇഞ്ചിയും പച്ചമുളകും വേണം."
അയാൾ അതെല്ലാം ഒരു കവറിലാക്കുന്നു.
"വേറെ എന്തെങ്കിലും വേണമോ?" അയാൾ ചോദിക്കുന്നു.
"ഒരു ചെറിയ പാക്കറ്റ് മല്ലിപ്പൊടിയും വേണം," ഞാൻ പറയുന്നു.
അയാൾ ആ പാക്കറ്റും സഞ്ചിയിൽ ഇടുന്നു.
"ആകെ എത്ര രൂപയായി?" ഞാൻ ചോദിക്കുന്നു.
"അറുപത് രൂപ," അയാൾ പറയുന്നു.
ഞാൻ അയാൾക്ക് പണം കൊടുക്കുന്നു.
പിന്നെ, ഞാൻ ആ പച്ചക്കറികൾ വാങ്ങുന്നു.
ഇനി എനിക്ക് ഇറച്ചിക്കടയിൽ പോയി ചിക്കൻ വാങ്ങണം.
ഞാൻ വീണ്ടും കുട തുറന്ന് മുന്നോട്ട് നടക്കുന്നു.
