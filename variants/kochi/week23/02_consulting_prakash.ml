ഞാൻ ഓഫീസിൽ പ്രകാശിനൊപ്പം ചായ കുടിക്കുകയാണ്.
ഞാൻ വെള്ളിയാഴ്ചത്തെ പ്ലാനിനെക്കുറിച്ച് പ്രകാശിനോട് പറയുന്നു.
"ദീപ എന്നെ അവരുടെ വീട്ടിലേക്ക് അത്താഴത്തിന് വിളിച്ചു," ഞാൻ പറയുന്നു.
ഇതൊരു നല്ല അവസരമാണെന്ന് ഞാൻ കരുതുന്നു.
"അത് വളരെ നല്ലതാണ് മായ," പ്രകാശ് പറയുന്നു.
"ഇതാദ്യമായാണ് ഞാൻ ദീപയുടെ വീട്ടിൽ പോകുന്നത്."
"അതുകൊണ്ട് ഞാൻ അവർക്ക് എന്തെങ്കിലും വാങ്ങാം എന്ന് കരുതുന്നു."
"ഞാൻ എന്താണ് കൊണ്ടുപോകേണ്ടത്?" എന്ന് ഞാൻ ചോദിക്കുന്നു.
"നിനക്ക് കുറച്ച് നാടൻ മധുരപലഹാരങ്ങൾ കൊണ്ടുപോകാം," പ്രകാശ് പറയുന്നു.
"അടുത്തുള്ള ഒരു നല്ല ബേക്കറി എനിക്കറിയാം."
"അത് എപ്പോഴും ഒരു നല്ല സമ്മാനമാണ്," അദ്ദേഹം പറയുന്നു.
"ദീപയ്ക്ക് അത് തീർച്ചയായും ഇഷ്ടപ്പെടും."
ആ ബേക്കറിയിൽ നല്ല ഹൽവ കിട്ടുമെന്ന് അദ്ദേഹം പറയുന്നു.
"എങ്കിൽ, ഞാൻ വെള്ളിയാഴ്ച അവിടെ പോകാം," ഞാൻ പറയുന്നു.
"ഞാൻ അവർക്കായി ഒരു പെട്ടി ഹൽവ വാങ്ങും."
"ഞാൻ ആ ബേക്കറിയുടെ സ്ഥലം മാപ്പിൽ അയക്കാം," പ്രകാശ് പറയുന്നു.
ഞാൻ പ്രകാശിനോട് വളരെ നന്ദി പറയുന്നു.
ഇപ്പോൾ എനിക്ക് ഈ യാത്രയെക്കുറിച്ച് നല്ല ആത്മവിശ്വാസമുണ്ട്.
