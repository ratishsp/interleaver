Jest dwunasta.
Pora na lunch.
Peter i ja schodzimy do stołówki.
Stołówka jest duża i jasna.
Jesteśmy bardzo głodni.
Patrzymy na dobre jedzenie.
Dzisiaj jest wiele opcji.
Wybieram klasyczną kanapkę.
Jest z rybą i cytryną.
Peter bierze dużą sałatkę.
Podchodzimy do kasy.
Przy kasie stoi miły mężczyzna.
„To będzie czterdzieści koron” – mówi do mnie.
Płacę kartą.
„Proszę bardzo” – mówię.
„Dziękuję i smacznego” – odpowiada.
Znajdujemy wolny stolik w rogu.
Siadamy.
Jedzenie smakuje naprawdę dobrze.
Rozmawiamy o naszym dniu.
