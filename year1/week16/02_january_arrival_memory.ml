ഞാൻ കാസ്പറിനെയും സാറയെയും നോക്കി പുഞ്ചിരിച്ചു.
"എന്റെ ആദ്യ ദിവസം ഒരു വലിയ സാഹസിക യാത്രയായിരുന്നു," ഞാൻ പറഞ്ഞു.
വിമാനത്താവളത്തിലെ തണുത്ത കാറ്റ് ഞാൻ ഓർത്തു.
കാസ്പർ ചോദിച്ചു:
"കാലാവസ്ഥ എങ്ങനെയുണ്ടായിരുന്നു?"
"ആകാശം പൂർണ്ണമായും ചാരനിറമായിരുന്നു," ഞാൻ മറുപടി പറഞ്ഞു.
എന്റെ വലിയ സ്യൂട്ട്കേസുമായി ഞാൻ വിമാനത്താവളത്തിന് പുറത്ത് നിന്നു.
കാറ്റ് വീശുന്നുണ്ടായിരുന്നു, എങ്കിലും ഇവിടെ എത്തിയതിൽ ഞാൻ ആവേശഭരിതയായിരുന്നു.
സാറ കുറച്ചു വെള്ളം കുടിച്ചിട്ട് തലകുലുക്കി.
"മെക്സിക്കോയിൽ നിന്ന് വലിയൊരു മാറ്റമാണെന്ന് തോന്നുന്നുവല്ലോ," അവൾ പറഞ്ഞു.
കെട്ടിടത്തിന് മുന്നിൽ എനിക്കൊരു ടാക്സി കിട്ടി.
ടാക്സി ഡ്രൈവർ സൗഹാർദ്ദപരമായി പെരുമാറുകയും എന്നെ സഹായിക്കുകയും ചെയ്തു.
അദ്ദേഹം എന്റെ പുതിയ വിലാസത്തെക്കുറിച്ച് ചോദിച്ചു.
ഞാൻ എന്റെ വിലാസം ഉറക്കെ പറഞ്ഞു.
"എനിക്ക് ഈ തെരുവ് നന്നായി അറിയാം," ഡ്രൈവർ പറഞ്ഞു.
ഞങ്ങൾ നഗരത്തിന് നേരെ വണ്ടിയോടിച്ചു.
യാത്രയ്ക്കിടയിൽ ഞാൻ ജനലിലൂടെ പുറത്തേക്ക് നോക്കി.
ആളുകളെല്ലാം ചൂടുള്ള കോട്ടുകളും സ്കാർഫുകളും ധരിച്ചിരുന്നു.
സാറ ചോദിച്ചു:
"നിനക്ക് പരിഭ്രമമുണ്ടായിരുന്നോ?"
"അതെ, കുറച്ചുണ്ടായിരുന്നു," ഞാൻ മറുപടി പറഞ്ഞു.
പക്ഷേ എന്റെ പുതിയ അപ്പാർട്ട്മെന്റിൽ എത്താനും ഞാൻ ആകാംക്ഷയോടെ കാത്തിരിക്കുകയായിരുന്നു.
