"നേരെ പോകൂ, ഇടത്തോട്ട് തിരിയൂ," ഞാൻ ഓർക്കുന്നു.
പോലീസുകാരൻ പറഞ്ഞത് അതാണ്.
ഞാൻ ആദ്യം നേരെ നടക്കുന്നു.
പിന്നെ ഞാൻ നേരത്തെ ഇടത്തോട്ട് തിരിയുന്നു.
അത് തെറ്റായ വഴിയാണ്.
ഇതൊരു ചെറിയ തെരുവാണ്.
ഇതൊരു വലിയ മാർക്കറ്റ് ആണ്.
ഇവിടെ ഒരുപാട് പച്ചക്കറി കടകൾ ഉണ്ട്.
തെരുവിൽ നല്ല തിരക്കാണ്.
ഞാൻ ചുറ്റും നോക്കുന്നു.
എനിക്ക് വഴി തെറ്റി.
ഞാൻ മറൈൻ ഡ്രൈവ് കാണുന്നില്ല.
ഞാൻ അവിടെ ഒരു സ്ത്രീയെ കാണുന്നു.
അവരുടെ കയ്യിൽ ഒരു തുണിസഞ്ചി ഉണ്ട്.
ഞാൻ അവരുടെ അടുത്തേക്ക് പോകുന്നു.
"ക്ഷമിക്കണം, എനിക്ക് വഴി തെറ്റി," ഞാൻ പറയുന്നു.
"മറൈൻ ഡ്രൈവിലേക്ക് ഏതാണ് വഴി?"
"ഞാൻ വലത്തോട്ട് തിരിയണോ?"
ആ സ്ത്രീ എന്നെ നോക്കുന്നു.
അവർ സ്നേഹത്തോടെ ചിരിക്കുന്നു.
