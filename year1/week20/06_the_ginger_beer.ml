കഫേയിലെ എൻ്റെ രണ്ടാമത്തെ ശനിയാഴ്ച ഷിഫ്റ്റായിരുന്നു അത്.
ജോലിയുടെ ഭൂരിഭാഗവും ചെയ്യാൻ ഞാൻ ഇതിനകം പഠിച്ചുകഴിഞ്ഞു.
അന്ന് രാവിലെ പുറത്ത് നല്ല സുഖകരമായ ചൂടുണ്ടായിരുന്നു.
ഒരു സ്ത്രീ കൗണ്ടറിന് അടുത്തേക്ക് വന്നു.
"എനിക്കൊരു ജിഞ്ചർ ബിയർ വേണമായിരുന്നു," അവർ പറഞ്ഞു.
"തീർച്ചയായും, ഒരു നിമിഷം," ഞാൻ മറുപടി നൽകി.
കൗണ്ടറിന് പിന്നിലുള്ള വലിയ ഗ്ലാസ് ഫ്രിഡ്ജിനടുത്തേക്ക് ഞാൻ ചെന്നു.
ഞാൻ മൂന്നാമത്തെ ഷെൽഫിൽ നോക്കി.
തണുത്ത ജിഞ്ചർ ബിയർ കുപ്പികൾ അവിടെ വെച്ചിട്ടുണ്ടായിരുന്നു.
ഞാനൊരു കുപ്പി കണ്ടെത്തി അത് പുറത്തെടുത്തു.
അതിൻ്റെ അടിഭാഗത്ത് ഇഞ്ചി ഒരു കട്ടിയുള്ള മേഘം പോലെ കിടപ്പുണ്ടായിരുന്നു.
കുപ്പി തുറക്കുന്നതിന് മുമ്പ് അത് കലർത്താൻ ഞാൻ പഠിച്ചിട്ടുണ്ട്.
അതിനാൽ ഞാൻ കുപ്പി വളരെ ശ്രദ്ധയോടെ തലകീഴായി തിരിച്ചു.
കുറച്ച് സെക്കൻഡുകൾ ഞാൻ അത് അങ്ങനെ തന്നെ പിടിച്ചു.
ഇഞ്ചി പതുക്കെ ബാക്കിയുള്ള ദ്രാവകവുമായി കലർന്നു.
ഇപ്പോൾ ആ പാനീയം കാണാൻ കൃത്യമായ പരുവത്തിലായിരുന്നു.
ഞാൻ കുപ്പി വീണ്ടും നേരെയാക്കി കൗണ്ടറിൽ വെച്ചു.
"ഇതാ, ഇതിന് മുപ്പത്തിയഞ്ച് ക്രോണർ ആകും," ഞാൻ അവരോട് പറഞ്ഞു.
അവർ പണം നൽകി, ആ തണുത്ത പാനീയം അവർ മിക്കവാറും ആസ്വദിച്ചിട്ടുണ്ടാകാം.
