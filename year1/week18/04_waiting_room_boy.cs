Sedám si na židli v čekárně.
V místnosti je téměř úplné ticho.
Trpělivě čekám.
Hlavu mám stále velmi těžkou.
Naproti mně sedí matka a malý chlapec.
Chlapci je možná pět let.
Drží si ruku na pravém uchu.
„Au, bolí mě ucho!“ říká nahlas.
Jeho matka se na něj dívá.
„Já vím, zlatíčko,“ říká jemně.
„Ale hrozně to bolí!“ stěžuje si chlapec.
„Lékař by nás měl brzy zavolat,“ říká matka.
Položí mu ruku kolem ramen.
Chlapec si hlasitě povzdychne.
Vypadá velmi unaveně.
Dobře ho chápu.
Mě samotnou taky hrozně bolí v krku.
Chci jen, aby mi bylo zase dobře.
