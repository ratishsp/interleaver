Znowu jestem w domu, w mieszkaniu.
Stoję w kuchni.
Opróżniam torbę na blat kuchenny.
Rozpakowuję jedzenie.
Biorę mleko.
Wstawiam mleko do lodówki.
Potem patrzę na pasternak.
To śmieszny korzeń.
Użyję go do mojej zupy.
Wkładam pasternak do lodówki.
Teraz lodówka nie jest pusta.
Biorę chleb.
Chleb żytni jest bardzo ciężki.
Wkładam chleb do szafki.
Potem biorę puszkę fasoli.
Fasola może długo stać.
Wstawiam puszkę do szafki.
Teraz w szafce jest jedzenie.
Jestem dość głodna.
Chciałabym teraz zjeść kolację.
