Moja mama patrzy na ekran.
„Czy to twój pokój, Maya?” – pyta.
„Tak, to mój pokój” – odpowiadam.
„Ale to tymczasowy pokój”.
Podnoszę komputer.
Pokazuję rodzinie mój mały pokój.
„Tu jest łóżko” – mówię.
„A tu jest moja nowa roślina”.
„To bardzo ładna roślina” – mówi moja mama.
Obracam komputer.
„A tu jest okno” – mówię.
Moja siostra Sofía patrzy na moje okno.
„Ale jest bardzo ciemno” – mówi.
„Tak, tam na zewnątrz jest zupełnie czarno” – odpowiadam.
„Ale latem jest mnóstwo słońca”.
Jest wieczór i jest zimno.
„Ale mam swoją lampę” – uśmiecham się.
„Więc to dobry pokój”.
