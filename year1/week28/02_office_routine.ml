ഞാൻ ഓഫീസിൽ എൻ്റെ ഡെസ്കിൽ ഇരിക്കുന്നു.
ഈവ ഒരു കപ്പ് കാപ്പിയുമായി എൻ്റെ അടുത്തേക്ക് വരുന്നു.
ഈ ആഴ്‌ച ഞങ്ങൾ ഒരുമിച്ച് വളരെ അടുത്ത് പ്രവർത്തിക്കുകയാണ്.
"പുതിയ ലേഔട്ട് നോക്കാൻ നീ തയ്യാറാണോ?" അവൾ ചോദിക്കുന്നു.
"അതെ, എനിക്ക് പ്രോഗ്രാം ഒന്ന് തുറക്കണം," ഞാൻ മറുപടി പറയുന്നു.
ഞങ്ങൾ ഒരുമിച്ച് ആ വലിയ സ്ക്രീനിൽ നോക്കുന്നു.
ആ വലിയ ഡിജിറ്റൽ പ്രോജക്റ്റ് ഒടുവിൽ കാണാൻ നന്നായിട്ടുണ്ട്.
എന്നാൽ പെട്ടെന്ന് ഈവ മൂലയിൽ ഒരു ചെറിയ തെറ്റ് കാണുന്നു.
ഒരു നീല ബട്ടൺ ഇടത്തേക്ക് കുറച്ചു കൂടുതലായി മാറിയാണ് ഇരിക്കുന്നത്.
"അവിടെ നോക്കൂ, അതിൻ്റെ സ്ഥാനം തെറ്റാണ്," അവൾ പറയുന്നു.
"നീ പറയുന്നത് ശരിയാണ്, എനിക്കത് വലത്തേക്ക് മാറ്റണം," ഞാൻ പറയുന്നു.
ഞാൻ വേഗത്തിൽ കോഡിന്റെ കുറച്ചു വരികൾ എഴുതുന്നു.
ബട്ടൺ ശരിയായ സ്ഥാനത്തേക്ക് മാറുന്നു.
"പെർഫെക്റ്റ്, സഹായിച്ചതിന് നന്ദി," ഈവ പറയുന്നു, ഒപ്പം ഹൃദ്യമായി പുഞ്ചിരിക്കുകയും ചെയ്യുന്നു.
വാരാന്ത്യത്തേക്കുള്ള ഞങ്ങളുടെ പ്ലാനുകളെക്കുറിച്ച് ഞങ്ങൾ ഒരുമിച്ച് സംസാരിക്കുകയും ചിരിക്കുകയും ചെയ്യുന്നു.
ഇപ്പോൾ എനിക്ക് ഓഫീസിലെ എല്ലാവരെയും നന്നായി അറിയാം.
