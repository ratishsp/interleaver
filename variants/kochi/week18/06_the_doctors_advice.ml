ഡോക്ടർ സ്റ്റെതസ്കോപ്പ് വെച്ച് എന്നെ പരിശോധിക്കുന്നു.
അദ്ദേഹം എന്നോട് ദീർഘശ്വാസം എടുക്കാൻ പറയുന്നു.
എനിക്ക് നെഞ്ചിൽ ചെറിയ വേദന ഉണ്ട്.
"നിങ്ങൾക്ക് നല്ല ജലദോഷം ഉണ്ട്," അദ്ദേഹം പറയുന്നു.
"അതുകൊണ്ടാണ് തൊണ്ട വേദനിക്കുന്നത്."
അദ്ദേഹം എനിക്കുള്ള ഒരു കുറിപ്പടി എഴുതുന്നു.
അദ്ദേഹം എനിക്ക് ചില നിർദ്ദേശങ്ങൾ നൽകുന്നു.
"നിങ്ങൾ എപ്പോഴും ചൂടുവെള്ളം കുടിക്കണം."
"തണുത്ത വെള്ളം കുടിക്കരുത്," അദ്ദേഹം പറയുന്നു.
"ഭക്ഷണത്തിന് ശേഷം ഈ മരുന്ന് കഴിക്കണം."
"ഈ ദിവസങ്ങളിൽ നല്ല മഴയുണ്ട്."
"അതുകൊണ്ട് നിങ്ങൾ പുറത്ത് പോകരുത്."
"നിങ്ങൾ വീട്ടിൽ നന്നായി വിശ്രമിക്കണം."
ഞാൻ എല്ലാം ശ്രദ്ധയോടെ കേൾക്കുന്നു.
"ഇത് കഴിച്ചാൽ വേഗം സുഖമാകും," അദ്ദേഹം പറയുന്നു.
"രണ്ട് ദിവസം കഴിഞ്ഞിട്ടും സുഖമില്ലെങ്കിൽ വീണ്ടും വരണം."
ഞാൻ ഡോക്ടർക്ക് നന്ദി പറയുന്നു.
ഞാൻ കുറിപ്പടി വാങ്ങി മുറിക്ക് പുറത്തേക്ക് നടക്കുന്നു.
