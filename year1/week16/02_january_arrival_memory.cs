Podívala jsem se na Kaspera a Saru a usmála se.
„Můj první den byl velké dobrodružství,“ řekla jsem.
Vzpomněla jsem si na ten studený vzduch na letišti.
Kasper se zeptal:
„Jaké bylo počasí?“
„Nebe bylo úplně šedé,“ odpověděla jsem.
Stála jsem před letištěm se svým velkým kufrem.
Foukal vítr, ale byla jsem nadšená, že jsem tady.
Sara se napila trochu vody a přikývla.
„To zní jako velká změna oproti Mexiku,“ řekla.
Našla jsem taxík před budovou.
Taxikář byl přátelský a pomohl mi.
Zeptal se na mou novou adresu.
Řekla jsem svou adresu nahlas.
„Tu ulici dobře znám,“ řekl řidič.
Jeli jsme směrem do města.
Během cesty jsem se dívala z okna.
Všichni lidé měli na sobě teplé kabáty a šály.
Sara se zeptala:
„Byla jsi nervózní?“
„Ano, trochu,“ odpověděla jsem.
Ale také jsem se těšila na svůj nový byt.
