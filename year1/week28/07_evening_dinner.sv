Jag står i mitt kök när det ringer på dörren.
Jag går ut i hallen och öppnar dörren.
Det är Nina, och hon har ett stort leende på läpparna.
"Hej Maya, tusen tack för inbjudan", säger hon.
Hon kliver in och skrattar medan hon tar av sig skorna.
Jag ger henne en varm kram.
Nina håller en vacker, grön krukväxt i händerna.
"Den här är till dig", säger hon och räcker mig växten.
"Den passar perfekt i ditt vardagsrum."
"Tack så mycket, den är verkligen fin", svarar jag glatt.
Jag ställer den gröna växten på ett litet bord bredvid dörren.
Plötsligt tar Nina ett djupt andetag.
"Wow, här doftar det helt fantastiskt", säger hon.
"Är det de mexikanska kryddorna?", frågar hon nyfiket.
Jag nickar och förklarar att jag har lagat en traditionell gryta.
"Den kryddiga doften gör mig vrålhungrig", skrattar Nina.
"Maten är som tur är helt klar", säger jag med ett leende.
Vi sätter oss tillsammans vid bordet för att äta.
