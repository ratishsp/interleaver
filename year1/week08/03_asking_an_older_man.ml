ഞാൻ ഒരു വലിയ ചത്വരത്തിൽ എത്തിച്ചേരുന്നു.
അവിടെ ധാരാളം ആളുകൾ ഉണ്ട്.
പക്ഷേ എനിക്ക് വെള്ളം കാണാൻ കഴിയുന്നില്ല.
ഞാൻ തുറമുഖം അന്വേഷിക്കുകയാണ്.
നടപ്പാതയിൽ പ്രായമായ ഒരു മനുഷ്യനെ ഞാൻ കാണുന്നു.
ഞാൻ അദ്ദേഹത്തെ തടഞ്ഞുനിർത്തുന്നു.
"ക്ഷമിക്കണം," ഞാൻ പറയുന്നു.
"തുറമുഖം എവിടെയാണ്?"
ആ പ്രായമായ മനുഷ്യൻ തലകുലുക്കുന്നു.
അദ്ദേഹം മുന്നോട്ട് ചൂണ്ടിക്കാണിക്കുന്നു.
"ചത്വരത്തിന് കുറുകെ നേരെ നടക്കുക," അദ്ദേഹം പറയുന്നു.
"മ്യൂസിയം കടന്ന് പോവുക."
"എന്നിട്ട് വലത്തോട്ട് തിരിയുക."
ഞാൻ ചത്വരത്തിന് കുറുകെ നോക്കുന്നു.
ഞാൻ വലിയൊരു കെട്ടിടം കാണുന്നു.
അത് മ്യൂസിയമാണ്.
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
"സാരമില്ല," അദ്ദേഹം മറുപടി പറയുന്നു.
ഞാൻ തുടർന്ന് നടക്കുന്നു.
