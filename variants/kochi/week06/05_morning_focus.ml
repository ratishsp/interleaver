ഞാൻ എൻ്റെ ഡെസ്കിൽ ഇരിക്കുകയാണ്.
ഞാൻ എൻ്റെ കമ്പ്യൂട്ടർ സ്ക്രീനിൽ നോക്കുന്നു.
സ്ക്രീനിന് നല്ല വെളിച്ചം ഉണ്ട്.
ഞാൻ ഒരു പുതിയ പ്രോജക്റ്റിൽ ജോലി ചെയ്യുകയാണ്.
അതൊരു വലിയ ഡോക്യുമെൻ്റ് ആണ്.
ഞാൻ വേഗത്തിൽ ടൈപ്പ് ചെയ്യുകയാണ്.
ഈ ജോലി ബുദ്ധിമുട്ടാണ്.
ഞാൻ ഡോക്യുമെൻ്റ് ശ്രദ്ധിച്ച് വായിക്കുകയാണ്.
എൻ്റെ സഹപ്രവർത്തകൻ പ്രകാശ് എൻ്റെ അടുത്ത് ഇരിക്കുകയാണ്.
അവനും കമ്പ്യൂട്ടറിൽ ജോലി ചെയ്യുകയാണ്.
ഇപ്പോൾ ഓഫീസിൽ നല്ല നിശബ്ദതയാണ്.
ഞാൻ എല്ലാം വീണ്ടും പരിശോധിക്കുകയാണ്.
ഒടുവിൽ, ഞാൻ ജോലി തീർക്കുന്നു.
ഞാൻ ഫയൽ സേവ് ചെയ്യുകയാണ്.
ഇപ്പോൾ ഡോക്യുമെൻ്റ് തയ്യാറാണ്.
ഞാൻ കമ്പ്യൂട്ടർ വിൻഡോ അടയ്ക്കുന്നു.
ഞാൻ ഇപ്പോൾ ചിരിക്കുകയാണ്.
എനിക്ക് വലിയ ആശ്വാസം തോന്നുന്നു.
