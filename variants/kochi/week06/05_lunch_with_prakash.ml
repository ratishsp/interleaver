ഇപ്പോൾ ഉച്ചയാണ്.
ഞാനും പ്രകാശും കഫറ്റീരിയയിലേക്ക് നടക്കുകയാണ്.
ഞങ്ങൾ കഫറ്റീരിയയുടെ അകത്തേക്ക് പോകുന്നു.
അവിടെ ഒരുപാട് ആളുകൾ ഉണ്ട്.
ഞങ്ങൾ ഒരു മേശയ്ക്ക് അടുത്ത് ഇരിക്കുന്നു.
പ്രകാശ് ഭക്ഷണം വാങ്ങുകയാണ്.
അദ്ദേഹം മേശയ്ക്ക് അടുത്തേക്ക് വരുന്നു.
അദ്ദേഹം കേരളത്തിലെ ഊണ് കഴിക്കുകയാണ്.
ചോറും കറികളും പ്ലേറ്റിൽ ഉണ്ട്.
ഞാൻ എൻ്റെ ചോറ്റുപാത്രം തുറക്കുകയാണ്.
ഞാൻ വീട്ടിൽ നിന്നാണ് ഉച്ചഭക്ഷണം കൊണ്ടുവരുന്നത്.
ഇന്ന് എനിക്ക് ചോറും പച്ചക്കറികളുമാണ് ഉള്ളത്.
ഞാൻ എൻ്റെ ഭക്ഷണം കഴിക്കുകയാണ്.
"ഭക്ഷണം രുചികരമാണോ?" പ്രകാശ് ചോദിക്കുന്നു.
"അതെ, നല്ല രുചിയുണ്ട്," ഞാൻ പറയുന്നു.
ഞങ്ങൾ ഓഫീസിലെ കാര്യങ്ങൾ സംസാരിക്കുകയാണ്.
ഞങ്ങൾ ഭക്ഷണം കഴിച്ചു തീർക്കുന്നു.
ഞങ്ങൾ കഫറ്റീരിയയിൽ നിന്ന് പുറത്തേക്ക് പോകുകയാണ്.
ഞങ്ങൾ വീണ്ടും ഓഫീസിലേക്ക് നടക്കുന്നു.
