ഞായറാഴ്ച വൈകുന്നേരമാണ്.
അനിത എന്റെ ഫ്ലാറ്റിലേക്ക് വരുന്നു.
അനിതയെ കാണുമ്പോൾ ടോമിക്ക് വളരെ സന്തോഷമാണ്.
അവൻ ഓടി അവരുടെ അടുത്തേക്ക് പോകുന്നു.
"ടോമി ഒരു കുഴപ്പവും ഉണ്ടാക്കിയില്ലല്ലോ?" അനിത ചോദിക്കുന്നു.
"ഇല്ല, അവൻ വളരെ നല്ല കുട്ടിയായിരുന്നു," ഞാൻ ചിരിച്ചുകൊണ്ട് പറയുന്നു.
"അവൻ എല്ലാ നിയമങ്ങളും കൃത്യമായി അനുസരിച്ചു."
"അവന് മധുരപലഹാരങ്ങൾ കൊടുക്കാൻ പാടില്ലല്ലോ."
"അതുകൊണ്ട് ഞാൻ അവന് ഒന്നും കൊടുത്തില്ല."
"പുറത്ത് പോകുമ്പോൾ അവനെ എപ്പോഴും ലീഷിൽ വേണം കൊണ്ടുപോകാൻ."
"ഞാൻ അവനെ എപ്പോഴും അങ്ങനെയാണ് കൊണ്ടുപോയത്."
"പിന്നെ, അവൻ സോഫയിൽ കയറാൻ പാടില്ല."
"അവൻ അവന്റെ കിടക്കയിൽ മാത്രമാണ് ഉറങ്ങിയത്."
"'ടോമി, ഇവിടെ വരൂ' എന്ന് പറഞ്ഞാൽ അവൻ പെട്ടെന്ന് വരും."
ഞാൻ ടോമിയുടെ ലീഷ് അനിതയ്ക്ക് തിരികെ കൊടുക്കുന്നു.
"മായയ്ക്ക് അവനെ നോക്കാൻ ബുദ്ധിമുട്ടായോ?" അവർ ചോദിക്കുന്നു.
"ഏയ്, എനിക്ക് ഒരു ബുദ്ധിമുട്ടും ഉണ്ടായില്ല," ഞാൻ പറയുന്നു.
അനിത സന്തോഷത്തോടെ എന്നോട് നന്ദി പറയുന്നു.
അവരും ടോമിയും തിരികെ പോകുന്നു.
