രാവിലെ പത്ത് മണി ആയപ്പോൾ കഫേയിൽ നല്ല തിരക്കായി.
ഇവിടെ എന്റെ ഒന്നാമത്തെ വലിയ തിരക്കായിരുന്നു അത്.
ആളുകൾ വരി നിൽക്കാൻ തുടങ്ങി.
ആ തിരക്കിൽ കാപ്പി ഉണ്ടാക്കാൻ എനിക്ക് കഴിഞ്ഞില്ല.
ഒരു തുടക്കക്കാരിക്ക് അത് വളരെ വേഗത്തിലായിരുന്നു.
അതിനാൽ ജെസ്സി വേഗത്തിൽ കാപ്പി ഉണ്ടാക്കാൻ തുടങ്ങി.
ഞാൻ രജിസ്റ്ററിന് അടുത്ത് നിന്നു.
ഞാൻ ആളുകൾക്ക് പലഹാരങ്ങൾ എടുത്തു കൊടുക്കാൻ പഠിക്കുകയാണ്.
ഒരാൾ ഒരു കാപ്പിയും ഒരു കഷ്ണം കേക്കും വാങ്ങി.
ആകെ നൂറ്റിയൻപത് രൂപയായി.
അയാൾ എനിക്ക് അഞ്ഞൂറ് രൂപയുടെ നോട്ട് തന്നു.
ഞാൻ ബാക്കി തുക ശ്രദ്ധയോടെ എണ്ണി.
ഞാൻ മുന്നൂറ്റിയൻപത് രൂപ അയാൾക്ക് തിരികെ കൊടുത്തു.
ഈ സമയത്ത് ജെസ്സി അയാളുടെ കാപ്പി കൊടുത്തു.
വരിയിലെ രണ്ടാമത്തെ ആൾക്ക് രണ്ട് കാപ്പി വേണമായിരുന്നു.
ഞാൻ അവർക്ക് പെട്ടെന്ന് തന്നെ ബിൽ കൊടുത്തു.
ജെസ്സിക്കൊപ്പം ഇങ്ങനെ ജോലി ചെയ്യാൻ ഞാൻ പഠിക്കുകയാണ്.
