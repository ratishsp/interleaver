ഇന്ന് ബുധനാഴ്ച ആണ്.
ഞാൻ അനിതയോട് യാത്ര പറയുന്നു.
ഞാൻ സൈക്കിൾ കടയിലേക്ക് നടക്കുന്നു.
ഞാൻ കൃത്യം ഏഴ് മണിക്ക് അവിടെ എത്തുന്നു.
കടയിൽ മെക്കാനിക്ക് ഉണ്ട്.
അദ്ദേഹം എൻ്റെ സൈക്കിളിന്റെ പണി തീർക്കുന്നു.
"ഇപ്പോൾ സൈക്കിൾ റെഡി ആണ്," അദ്ദേഹം എന്നോട് പറയുന്നു.
ഞാൻ അദ്ദേഹത്തിന് നന്ദി പറയുന്നു.
എൻ്റെ സൈക്കിൾ പുതിയത് പോലെ ഉണ്ട്.
എനിക്ക് വളരെ സന്തോഷം തോന്നുന്നു.
ഞാൻ അപ്പാർട്ട്മെൻ്റിലേക്ക് സൈക്കിൾ ഓടിക്കുന്നു.
ഞാൻ എപ്പോഴും ബസ്സിൽ ഓഫീസിലേക്ക് പോകുന്നു.
പക്ഷേ, ഇനി ചിലപ്പോൾ ഞാൻ സൈക്കിൾ ഓടിക്കും.
