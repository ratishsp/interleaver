Jag går uppför trappan.
Jag är trött efter gymmet.
På andra våningen möter jag Nina.
Hon ler mot mig.
"Hej Maya", säger hon.
"Hej Nina, hur går det?" frågar jag.
"Det går mycket bra", svarar Nina.
"Du ser lite trött ut."
"Ja, jag tränar alltid på onsdagar", förklarar jag.
"Vi dricker sällan kaffe tillsammans nu för tiden", säger Nina.
"Har du tid i morgon?" frågar hon.
Jag tänker på vad jag ska göra på torsdag.
"Ja, torsdag är en riktigt bra dag", säger jag.
"Vilken tid?" frågar jag.
"Kanske klockan halv fem?"
"Klockan halv fem låter perfekt", svarar jag glatt.
"Vi ses i morgon eftermiddag", säger Nina.
Vi säger hejdå ute i trappuppgången.
Jag går in i min lägenhet.
Jag ser fram emot vår kaffeträff.
