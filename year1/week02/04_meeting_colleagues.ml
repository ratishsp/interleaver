ഞാൻ ഓഫീസിലെ അടുക്കളയിലാണ്.
എന്റെ കയ്യിൽ ഒരു കപ്പ് ചൂട് കാപ്പിയുണ്ട്.
രണ്ട് പുതിയ സഹപ്രവർത്തകരും അടുക്കളയിലുണ്ട്.
ഒരു പുരുഷൻ എന്നെ നോക്കി പുഞ്ചിരിക്കുന്നു.
"ഹലോ, സ്വാഗതം," അദ്ദേഹം പറയുന്നു.
"വളരെ നന്ദി."
"ഞാൻ മായ," ഞാൻ പറയുന്നു.
"മായ, നിങ്ങൾ എവിടെ നിന്നാണ് വരുന്നത്?" ഒരു സ്ത്രീ ചോദിക്കുന്നു.
"ഞാൻ മെക്സിക്കോയിൽ നിന്നാണ് വരുന്നത്," ഞാൻ പറയുന്നു.
"ഞാനൊരു സോഫ്റ്റ്‌വെയർ എഞ്ചിനീയറുമാണ്."
ആ പുരുഷൻ തലയാട്ടുന്നു.
"ടീമിലേക്ക് സ്വാഗതം," അദ്ദേഹം പറയുന്നു.
അവർ വളരെ നല്ലവരാണ്.
ഇത് ശരിക്കും ഒരു നല്ല തുടക്കമാണ്.
