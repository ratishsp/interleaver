വേഗത്തിലുള്ള ആ മത്സരം അവസാനിച്ചു.
ഞങ്ങൾ ഒരുമിച്ച് കോർട്ടിൽ നിന്ന് പുറത്തേക്ക് നടക്കുന്നു.
ഞാൻ വല്ലാതെ ക്ഷീണിച്ചു.
കാസ്പറും സാറയും ക്ഷീണിച്ചിട്ടുണ്ട്.
ഞങ്ങൾ കുറച്ച് വെള്ളം കുടിക്കുന്നു.
"നിങ്ങൾ വളരെ നന്നായി കളിക്കുന്നുണ്ട്," സാറ പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
"ഇത് വളരെ രസകരമാണെന്ന് എനിക്ക് തോന്നുന്നു."
"നിങ്ങൾ ഇടയ്ക്കിടെ കളിക്കാറുണ്ടോ?" കാസ്പർ ചോദിക്കുന്നു.
"അതെ, എന്റെ നാടായ മെക്സിക്കോയിൽ ഞാൻ ധാരാളം കളിക്കാറുണ്ട്," ഞാൻ മറുപടി നൽകുന്നു.
"ഞാൻ സാധാരണയായി എന്റെ സഹോദരിക്കൊപ്പമാണ് കളിക്കാറുള്ളത്."
"ഇതൊരു രസകരമായ സ്പോർട്സാണ്," സാറ പറയുന്നു.
"ഇവിടുത്തെ ക്ലബ്ബിൽ കളിക്കുന്നത് ഞങ്ങൾക്ക് വളരെ ഇഷ്ടമാണ്."
"ഇവിടെ ഡെൻമാർക്കിൽ എനിക്ക് ഇനിയും കളിക്കണമെന്നുണ്ട്," ഞാൻ പറയുന്നു.
"നിങ്ങൾക്ക് തീർച്ചയായും നല്ല വേഗതയുണ്ട്," കാസ്പർ ചിരിക്കുന്നു.
"നന്ദി, പക്ഷേ എനിക്കിപ്പോൾ ഒന്ന് ഇരിക്കണം," ഞാൻ പറയുന്നു.
"നമുക്ക് കഫറ്റീരിയയിലേക്ക് പോയാലോ?" കാസ്പർ ചോദിക്കുന്നു.
"അതെ, വരാൻ എനിക്ക് വളരെ താല്പര്യമുണ്ട്," ഞാൻ മറുപടി നൽകുന്നു.
