Jag hittar telefonnumret till min lokala läkarmottagning.
Numret är trettiotvå, fyrtiofem, sextiosju, åttionio.
Jag ringer till dem och väntar ett par minuter.
En vänlig receptionist svarar i telefonen.
"Läkarmottagningen, du talar med Hanna," säger hon.
Jag förklarar att jag har blivit riktigt sjuk i dag.
"Mitt huvud är tungt, och mina ögon kliar," säger jag.
Jag berättar också för henne att min hals gör ont.
Hon frågar om jag har feber.
Jag svarar att jag inte tror det, men jag är mycket trött.
"Du borde tala med en läkare i dag," säger receptionisten.
Hon tittar i kalendern för att hitta en tid.
"Kan du komma klockan ett?" frågar hon.
"Ja, det passar perfekt," svarar jag.
"Kom ihåg att ta med ditt gula hälsokort," säger hon.
Jag tackar henne och lägger på.
Nu ska jag bara slappna av lite, innan jag går dit.
