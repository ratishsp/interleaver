സമയം ഉച്ചയ്ക്ക് ഒരു മണിയാണ്.
ഞാനും പ്രകാശും കാന്റീനിൽ പോകുന്നു.
ഞങ്ങൾ ഞങ്ങളുടെ പതിവ് മേശയ്ക്കരികിൽ ഇരിക്കുന്നു.
പ്രകാശ് ചോറും മീൻകറിയും കഴിക്കുന്നു.
ഞാൻ ഒരു സാൻഡ്‌വിച്ച് കഴിക്കുന്നു.
ഞങ്ങൾ സന്തോഷത്തോടെ സംസാരിക്കുന്നു.
പ്രകാശ് ഓഫീസിലെ കാപ്പി കുടിക്കുന്നു.
പ്രകാശ് കപ്പിലേക്ക് നോക്കുന്നു.
പ്രകാശ് മെല്ലെ ചിരിക്കുന്നു.
"മായ, ഈ കാപ്പിക്ക് ഒരു സ്വാദും ഇല്ല," പ്രകാശ് പറയുന്നു.
ഞാൻ ചിരിക്കുന്നു.
പിന്നെ ഞാൻ ബാഡ്മിന്റണിനെക്കുറിച്ച് പറയുന്നു.
"ബാഡ്മിന്റൺ നന്നായി പോകുന്നു," ഞാൻ പറയുന്നു.
"വ്യാഴാഴ്ചയിലെ കളിയാണ് എന്റെ ആഴ്ചയിലെ ഏറ്റവും നല്ല സമയം."
"അത് വളരെ നല്ലതാണ്," പ്രകാശ് പറയുന്നു.
ഞങ്ങൾ ഉച്ചഭക്ഷണം വേഗം കഴിക്കുന്നു.
സമയം രണ്ടു മണിയാകുന്നു.
ഞങ്ങൾ തിരികെ ഓഫീസിലേക്ക് നടക്കുന്നു.
