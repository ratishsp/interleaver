ഇപ്പോൾ ഞാൻ സോഫ്റ്റ്‌വെയർ കമ്പനിയിലാണ്.
അതൊരു ഉയരമുള്ള ഗ്ലാസ് കെട്ടിടമാണ്.
ഞാൻ അകത്തേക്ക് പോകുന്നു.
ഒരു സഹപ്രവർത്തക എന്നെ വന്നു കാണുന്നു.
"ഹലോ, സ്വാഗതം!" അവൾ പറയുന്നു.
അവൾ എനിക്കൊരു കീ കാർഡ് തരുന്നു.
"വളരെ നന്ദി, എൻ്റെ പേര് മായ," ഞാൻ പറയുന്നു.
ഞങ്ങൾ ഒരുമിച്ച് അകത്തേക്ക് നടക്കുന്നു.
ഞങ്ങൾ അവിടെയുള്ള ധാരാളം മേശകൾ പിന്നിട്ട് നടക്കുന്നു.
ആളുകൾ അവരുടെ കമ്പ്യൂട്ടറുകൾക്ക് മുന്നിൽ ഇരിക്കുകയാണ്.
ഞാൻ വളരെ ആവേശത്തിലാണ്.
