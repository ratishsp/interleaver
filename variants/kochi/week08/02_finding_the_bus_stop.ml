ഞാൻ എന്റെ ഫ്ലാറ്റിൽ നിന്ന് പുറത്തേക്ക് നടക്കുന്നു.
ഞാൻ ഒരു വലിയ കവലയിൽ എത്തുന്നു.
അവിടെ ധാരാളം വാഹനങ്ങൾ ഉണ്ട്.
പക്ഷേ, ഞാൻ ബസ് സ്റ്റോപ്പ് കാണുന്നില്ല.
വഴിയിൽ ഒരു ചെറിയ ചായക്കട ഉണ്ട്.
ഞാൻ ആ ചായക്കടയിലേക്ക് നടക്കുന്നു.
അവിടെ ഒരാൾ ചായ ഉണ്ടാക്കുന്നു.
ഞാൻ അദ്ദേഹത്തോട് വഴി ചോദിക്കുന്നു.
"ക്ഷമിക്കണം, പ്രധാന ബസ് സ്റ്റോപ്പ് എവിടെയാണ്?" ഞാൻ ചോദിക്കുന്നു.
അദ്ദേഹം മുന്നിലുള്ള റോഡിലേക്ക് കൈ ചൂണ്ടുന്നു.
"ഈ വഴി നേരെ പോകൂ," അദ്ദേഹം പറയുന്നു.
"അവിടെ ഒരു വലിയ ആൽമരം ഉണ്ട്."
ഞാൻ മുന്നോട്ട് നോക്കുന്നു.
അതെ, അവിടെ ഒരു വലിയ മരം ഉണ്ട്.
"ആ മരത്തിന്റെ അവിടെ നിന്ന് വലത്തോട്ട് തിരിയൂ," അദ്ദേഹം പറയുന്നു.
"ബസ് സ്റ്റോപ്പ് അവിടെയാണ്."
"വളരെ നന്ദി," ഞാൻ സന്തോഷത്തോടെ പറയുന്നു.
ഞാൻ ആ മരത്തിലേക്ക് നേരെ നടക്കുന്നു.
എന്നിട്ട്, ഞാൻ വലത്തോട്ട് തിരിയുന്നു.
അപ്പോൾ ഞാൻ ബസ് സ്റ്റോപ്പ് കാണുന്നു.
