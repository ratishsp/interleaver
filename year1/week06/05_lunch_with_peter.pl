W środku dnia schodzę do stołówki.
Sala jest jasna i przyjemna.
Wiele osób stoi przy bufecie.
Widzę mojego kolegę Petera.
Bierze talerz z jedzeniem.
„Cześć Maya” – mówi z uśmiechem.
„Cześć Peter” – odpowiadam.
Bierzemy trochę chleba i sałatki.
Razem znajdujemy stolik numer dziewięć przy oknie.
Siadamy na krzesłach.
Jedzenie smakuje naprawdę dobrze.
Peter opowiada o swoim projekcie.
Pracuje z nowym oprogramowaniem.
Słucham i kiwam głową.
Na koniec mówię o swoim własnym kodzie.
Pijemy szklankę wody.
Bardzo miło spędzam czas podczas przerwy.
Wkrótce wracamy do biura.
