ഞാൻ ജനാലയ്ക്കരികിൽ നിൽക്കുന്നു.
ഞാൻ പുറത്ത് കോപ്പൻഹേഗനിലേക്ക് നോക്കുന്നു.
ഇതൊരു വലിയ നഗരമാണ്.
തെരുവിൽ ഒരുപാട് ആളുകളുണ്ട്.
ശരിക്കും ഒരുപാട് സൈക്കിളുകളും ഉണ്ട്.
ഇന്ന് ആകാശം ചാരനിറമാണ്.
ഇവിടെ തണുപ്പാണ്.
നാട്ടിൽ, മെക്സിക്കോയിൽ ചൂടാണ്.
ഞാൻ എന്റെ കുടുംബത്തെക്കുറിച്ച് ചിന്തിക്കുന്നു.
അവർ വളരെ ദൂരെയാണ്.
പക്ഷേ ഇവിടെ ആയിരിക്കുന്നതിൽ എനിക്ക് സന്തോഷമുണ്ട്.
