Det är januari, och det är väldigt kallt.
Jag går hem från busshållplatsen i Köpenhamn.
Jag ser en blomsterbutik på gatan.
Det är ljust och varmt där inne.
Jag går in i den varma butiken.
Jag tittar på en liten, grön växt.
En expedit ler mot mig.
"Hej", säger han.
"Hej", säger jag.
"Jag letar efter en växt."
"Är det en present?" frågar han.
"Nej, det är till mitt rum", svarar jag.
"Det är en riktigt fin växt", säger han.
"Vad kostar den?" frågar jag.
"Den kostar femtiofem kronor", svarar han.
Jag betalar för min nya växt.
Han lägger ner växten i en papperspåse.
"Varsågod, här är din påse", säger han.
"Tack så mycket", säger jag glatt.
Jag går ut i den kalla kvällen.
Min lilla växt gör mig mycket glad.
