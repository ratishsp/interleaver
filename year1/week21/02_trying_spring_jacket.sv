Jag går in i en stor klädbutik.
Jag tittar på de nya vårkläderna.
Det hänger många lätta jackor och skjortor.
Jag tittar mig långsamt omkring i butiken.
Allt ser fräscht och vårlikt ut.
Plötsligt ser jag en mycket fin jacka.
Den är ljusgrön.
Jag tar ner den från galgen.
Jag vill gärna prova den.
Det står en stor spegel på golvet.
Så jag behöver inget provrum.
Jag tar på mig den ljusgröna jackan.
Jag tittar på mig själv i spegeln.
Jackan sitter riktigt bra.
Den är inte för stor och inte för liten.
Den passar faktiskt perfekt.
Färgen är också fin på mig.
Jag ler mot spegeln.
Jag tar av mig jackan igen.
Jag bestämmer mig för att köpa den.
