ഇത് എന്റെ ഉച്ചഭക്ഷണ ഇടവേളയാണ്.
ഞാൻ ഒരു ഫോൺ കടയിലാണ്.
എനിക്ക് മെക്സിക്കോയിൽ നിന്നുള്ള ഒരു ഫോണുണ്ട്.
കടക്കാരൻ ഒരു ചെറുപ്പക്കാരനാണ്.
"നിങ്ങളുടെ പക്കൽ ഡാനിഷ് സിം കാർഡ് ഉണ്ടോ?" ഞാൻ ചോദിക്കുന്നു.
"അതെ, തീർച്ചയായും," അയാൾ മറുപടി പറയുന്നു.
ഞാൻ എന്റെ ഫോൺ അയാൾക്ക് കൊടുക്കുന്നു.
അയാൾ ഫോണിൽ സിം കാർഡ് ഇടുന്നു.
ഫോൺ ഇപ്പോൾ തയ്യാറാണ്.
"നിങ്ങളുടെ പുതിയ നമ്പർ പന്ത്രണ്ട്, മുപ്പത്തിനാല്, അമ്പത്താറ്, എഴുപത്തിയെട്ട്," അയാൾ പറയുന്നു.
എന്റെ ബാഗിൽ ഒരു നോട്ടുബുക്ക് ഉണ്ട്.
ഞാൻ ആ നമ്പർ എഴുതുന്നു.
"പന്ത്രണ്ട്, മുപ്പത്തിനാല്, അമ്പത്താറ്, എഴുപത്തിയെട്ട്," ഞാൻ ആവർത്തിക്കുന്നു.
"അതെ, കൃത്യം," കടക്കാരൻ പറയുന്നു.
"സഹായിച്ചതിന് നന്ദി," ഞാൻ പറയുന്നു.
എനിക്കിപ്പോൾ ഒരു ഡാനിഷ് നമ്പർ ഉണ്ട്!
ഞാൻ ഫോൺ എന്റെ പോക്കറ്റിൽ വെക്കുന്നു.
