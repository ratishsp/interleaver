ഞാൻ സ്പോർട്സ് ഹാളിലെ ഒരു ചെറിയ കിയോസ്കിന്റെ അടുത്തേക്ക് നടക്കുന്നു.
ഒരു ചെറുപ്പക്കാരൻ കൗണ്ടറിന് പിന്നിൽ നിൽക്കുന്നു.
അവൻ പുഞ്ചിരിച്ചുകൊണ്ട് ഹലോ പറയുന്നു.
"ഹലോ, എനിക്ക് ഇന്ന് ബാഡ്മിന്റൺ കളിക്കണം," ഞാൻ പറയുന്നു.
"നിങ്ങൾ ഈ ക്ലബ്ബിൽ പുതിയതാണോ?" അവൻ ചോദിക്കുന്നു.
"അതെ, എനിക്കൊന്ന് പങ്കുചേർന്ന് നോക്കാൻ ആഗ്രഹമുണ്ട്," ഞാൻ മറുപടി പറയുന്നു.
"സ്വാഗതം," അയാൾ പറയുന്നു.
"നിങ്ങൾക്ക് ഒരു റാക്കറ്റ് വാടകയ്ക്ക് എടുക്കണോ?" അവൻ ചോദിക്കുന്നു.
"അതെ, എനിക്ക് ഇന്ന് വൈകുന്നേരത്തേക്ക് ഒരു റാക്കറ്റ് വാടകയ്ക്ക് വേണം," ഞാൻ പറയുന്നു.
അവൻ എനിക്കായി ഒരു നല്ല റാക്കറ്റ് എടുത്തുതരുന്നു.
"ഇതിന് നാല്പത് ക്രോണർ ആണ്," അവൻ പറയുന്നു.
ഞാൻ എന്റെ പേയ്‌മെന്റ് കാർഡ് പുറത്തെടുക്കുന്നു.
ഞാൻ ആ നാല്പത് ക്രോണർ അടയ്ക്കുന്നു.
അവൻ കൗണ്ടറിലൂടെ എനിക്ക് റാക്കറ്റ് നൽകുന്നു.
"ഇതൊരു രസകരമായ കളിയാണെന്ന് എനിക്ക് തോന്നുന്നു," ഞാൻ സന്തോഷത്തോടെ പറയുന്നു.
"നല്ലൊരു കളി ആശംസിക്കുന്നു."
ഞാൻ നന്ദി പറഞ്ഞിട്ട് കോർട്ടുകളിലേക്ക് നടക്കുന്നു.
