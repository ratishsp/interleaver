Po snídani mám spoustu času.
Normálně v sobotu pracuji jako dobrovolnice v kavárně.
Ale Ludwig by neměl být sám.
Dnes mám naštěstí v kavárně volno.
Domluvila jsem se s nimi minulý týden.
Teď máme s Ludwigem celé ráno pro sebe.
Jdeme ven na dvůr za mým domem.
Vytáhnu jeho malý míček.
„Podívej se na ten míček, Ludwigu!“ říkám mu.
Hodím ho přes trávu.
„Přines!“ křiknu.
Rychle běží a chytí míček.
„Pojď sem!“ volám.
Vesele běží zpátky ke mně.
„Dej mi ho,“ říkám jemně.
Pustí míček a já ho pohladím.
„Jsi šikovný pes,“ říkám a usmívám se.
Znovu ho hodím a on ho přinese.
Musím se o něj celý víkend dobře starat.
Jsem moc ráda, že jsem s ním zůstala doma.
