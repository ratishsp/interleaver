Je středa večer.
Je sedm hodin.
Jsem v místní posilovně.
Moc ráda cvičím.
Ve středu jsem tu vždycky.
Převlékám se.
Nejdřív zvedám činky.
Činky jsou velmi těžké.
Dám si krátkou přestávku.
Potom běhám na běžeckém pásu.
Často běhám rychle.
Vždycky poslouchám hudbu.
Cvičím celkem hodinu.
Teď je osm hodin.
Jsem unavená, ale jsem šťastná.
Beru si tašku.
Jdu domů.
