ഞാൻ കൈവരിയിൽ ചാരി നിൽക്കുന്നു.
ഞാൻ നേരെ നോക്കുന്നു.
എനിക്ക് ദൂരെ വലിയ ഹാർബർ കാണാം.
ബോട്ടുകൾ ഹാർബറിലേക്ക് പോകുന്നു.
അവിടെ ചെറിയ മീൻപിടുത്ത ബോട്ടുകൾ ഉണ്ട്.
വലിയ യാത്രാ ഫെറികളും ഉണ്ട്.
അവ നേരെ വെള്ളത്തിലൂടെ പോകുന്നു.
ഇതൊരു മനോഹരമായ കാഴ്ചയാണ്.
ഞാൻ ബാഗിൽ നിന്ന് എന്റെ ഫോൺ എടുക്കുന്നു.
ഞാൻ ഈ കാഴ്ചയുടെ കുറച്ചു ഫോട്ടോകൾ എടുക്കുന്നു.
ബോട്ടുകളുടെ ഫോട്ടോകളും എടുക്കുന്നു.
ഞാൻ ഫാമിലി ഗ്രൂപ്പ് ചാറ്റ് തുറക്കുന്നു.
എന്റെ കുടുംബം മെക്സിക്കോയിൽ ആണ്.
ഞാൻ അവർക്ക് ഈ ഫോട്ടോകൾ അയക്കുന്നു.
മെക്സിക്കോയിൽ ഇപ്പോൾ അതിരാവിലെയാണ്.
സോഫിയയും ഡീഗോയും ഇപ്പോൾ ഉറങ്ങുകയാണ്.
അവർ പിന്നീട് ഈ ഫോട്ടോകൾ കാണും.
ഞാൻ വീണ്ടും വെള്ളത്തിലേക്ക് നോക്കുന്നു.
ഈ സ്ഥലം എനിക്ക് വളരെ ഇഷ്ടമായി.
