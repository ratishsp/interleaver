ഞാൻ മായ ആണ്.
എന്റെ നാട് മെക്സിക്കോ ആണ്.
ഇപ്പോൾ ഞാൻ കൊച്ചിയിൽ ആണ്.
ഞാൻ എയർപോർട്ടിൽ നിന്ന് പുറത്തേക്ക് നടക്കുന്നു.
ഇത് ജനുവരി മാസം ആണ്.
ഇവിടെ നല്ല കാലാവസ്ഥ ആണ്.
പക്ഷേ ചെറിയ ചൂട് ഉണ്ട്.
എനിക്ക് വളരെ സന്തോഷം ഉണ്ട്.
എന്റെ അടുത്ത് ഒരു സ്ത്രീ ഉണ്ട്.
അവരും ഒരു യാത്രക്കാരി ആണ്.
അവർ എന്നെ നോക്കി ചിരിക്കുന്നു.
"നിങ്ങൾ ഇവിടെ പുതിയ ആളാണോ?" അവർ ചോദിക്കുന്നു.
"അതെ," ഞാൻ പറയുന്നു.
"നിങ്ങളുടെ പേര് എന്താണ്?" അവർ ചോദിക്കുന്നു.
"എന്റെ പേര് മായ ആണ്. നിങ്ങളുടെ പേര് എന്താണ്?" ഞാൻ ചോദിക്കുന്നു.
"എന്റെ പേര് ലക്ഷ്മി ആണ്," അവർ പറയുന്നു.
"നിങ്ങളുടെ നാട് എവിടെയാണ്?" ലക്ഷ്മി ചോദിക്കുന്നു.
"എന്റെ നാട് മെക്സിക്കോ ആണ്," ഞാൻ പറയുന്നു.
"കൊച്ചിയിലേക്ക് സ്വാഗതം!" അവർ പറയുന്നു.
ഞാൻ സന്തോഷത്തോടെ ചിരിക്കുന്നു.
