ലുഡ്‌വിഗ് സന്തോഷത്തോടെ കാട്ടിൽ ഓടിനടക്കുന്നു.
പെട്ടെന്ന് അവൻ ഒരു വലിയ പക്ഷിയെ കാണുന്നു.
അവൻ വേഗത്തിൽ അതിൻ്റെ പിന്നാലെ ഓടുന്നു.
അവൻ നേരെ ആ മരങ്ങളുടെ അടുത്തേക്ക് ഓടുന്നു.
"നിൽക്കൂ, ലുഡ്‌വിഗ്!" ഞാൻ ഉറക്കെ വിളിച്ചുപറയുന്നു.
"ഇങ്ങോട്ട് വരൂ!"
ഞാൻ എൻ്റെ പോക്കറ്റിൽ നിന്ന് ഒരു ചെറിയ പലഹാരം എടുക്കുന്നു.
ഞാൻ പുല്ലിൽ കുത്തിയിരിക്കുന്നു.
"ലുഡ്‌വിഗ്, ഇങ്ങോട്ട് നോക്കൂ," ഞാൻ പതുക്കെ വിളിക്കുന്നു.
അവൻ നിന്നിട്ട് എന്നെ നോക്കുന്നു.
അവന് ആ പലഹാരം കിട്ടണമെന്ന് വളരെ ആഗ്രഹമുണ്ട്.
അവൻ വേഗത്തിൽ എൻ്റെ അടുത്തേക്ക് തിരികെ ഓടിവരുന്നു.
"ഇരിക്കൂ," ഞാൻ ശാന്തമായി പറയുന്നു.
അവൻ ഇരിക്കുന്നു, ഞാൻ അവന് അത് കൊടുക്കുന്നു.
"നല്ല നായ," ഞാൻ പറയുന്നു, എന്നിട്ട് അവനെ തലോടുന്നു.
ഞാൻ വീണ്ടും അവനിൽ ലീഷ് കൊളുത്തുന്നു.
ഇനി നമുക്ക് വീട്ടിൽ പോയി വിശ്രമിക്കണം.
