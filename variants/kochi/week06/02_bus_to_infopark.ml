ഞാൻ ഫ്ലാറ്റിൽ നിന്ന് പുറത്തിറങ്ങുന്നു.
ഞാൻ ബസ് സ്റ്റോപ്പിലേക്ക് നടക്കുകയാണ്.
ബസ് സ്റ്റോപ്പിൽ ധാരാളം ആളുകൾ നിൽക്കുന്നു.
ഇൻഫോപാർക്കിലേക്കുള്ള ബസ് വരുന്നു.
ഞാൻ ബസ്സിൽ കയറുന്നു.
കണ്ടക്ടർ എന്റെ അടുത്തേക്ക് വരുന്നു.
"എങ്ങോട്ടാണ് ടിക്കറ്റ്?" അദ്ദേഹം ചോദിക്കുന്നു.
"ഇൻഫോപാർക്കിലേക്ക്," ഞാൻ പറയുന്നു.
ഞാൻ അദ്ദേഹത്തിന് ഇരുപത് രൂപ കൊടുക്കുന്നു.
അദ്ദേഹം എനിക്ക് ടിക്കറ്റ് തരുന്നു.
ഞാൻ ആ ടിക്കറ്റ് എന്റെ ബാഗിൽ വെക്കുന്നു.
ബസ് നഗരത്തിലൂടെ വേഗത്തിൽ പോവുകയാണ്.
റോഡിലൂടെ ധാരാളം വാഹനങ്ങൾ പോവുകയാണ്.
