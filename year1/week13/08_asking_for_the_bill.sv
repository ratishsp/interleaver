Jag dricker mitt vatten.
Vattnet är kallt och gott.
Jag tar min väska från golvet.
Jag är färdig med min paus.
Jag går fram till disken.
Den vänliga baristan står fortfarande där.
Han tittar på mig med ett leende.
"Vill du ha något annat?" frågar han.
"Nej tack," svarar jag.
"Jag vill gärna betala."
"Ja, självklart," säger han.
Han tittar på sin lilla skärm.
"En svart kaffe och en kanelbulle," säger han.
"Ja, det stämmer," säger jag.
"Vill du betala med kort eller kontanter?" frågar han.
"Jag vill gärna betala med kort," svarar jag.
"Fint."
"Det blir åttiofem kronor," säger han.
Jag tar fram mitt betalkort.
