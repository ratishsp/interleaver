എൻ്റെ ഫോണിൽ ഉടനെ ഒരു ശബ്ദം കേൾക്കുന്നു.
അത് എൻ്റെ ഇമെയിൽ ആപ്പിൽ നിന്നാണ്.
ഞാൻ ആ ഇമെയിൽ തുറക്കുന്നു.
അതിൽ പുതിയ കോഡ് ഉണ്ട്.
ഞാൻ ആ കോഡ് പകർത്തുന്നു.
പിന്നെ ഞാൻ വീണ്ടും ടെലികോം വെബ്സൈറ്റ് എടുക്കുന്നു.
സ്ക്രീനിൽ പുതിയ നിർദ്ദേശം ഉണ്ട്.
"ദയവായി പുതിയ കോഡ് നൽകുക."
ഞാൻ ആ കോഡ് അവിടെ നൽകുന്നു.
ഞാൻ ഫോം പൂർത്തിയാക്കി ബട്ടൺ അമർത്തുന്നു.
ഉടനെ സ്ക്രീനിൽ ഒരു പച്ച അടയാളം വരുന്നു.
അതിനൊപ്പം ഒരു അറിയിപ്പും കാണിക്കുന്നു.
"നിങ്ങളുടെ അക്കൗണ്ട് വിവരങ്ങൾ വിജയകരമായി പുതുക്കപ്പെടുന്നു."
ഞാൻ ആശ്വാസത്തോടെ ചിരിക്കുന്നു.
ഞാൻ സാധാരണയായി ഇത്തരം കാര്യങ്ങൾ നീട്ടിവെക്കാറുണ്ട്.
പക്ഷേ ഇപ്പോൾ ഈ ജോലി കഴിഞ്ഞു.
ഞാൻ ബാക്കിയുള്ള കോഫി കുടിക്കുന്നു.
