ഞാൻ പഴക്കടകളുടെ അടുത്തേക്ക് നടക്കുന്നു.
അവിടെ ഒരുപാട് പുതിയ കൈതച്ചക്കകൾ ഉണ്ട്.
ഒരു കച്ചവടക്കാരൻ എന്നെ നോക്കി ചിരിക്കുന്നു.
അയാൾ ഒരു ചെറിയ കഷ്ണം കൈതച്ചക്ക മുറിക്കുന്നു.
അയാൾ അത് കത്തിയുടെ തുമ്പിൽ എനിക്ക് തരുന്നു.
ഞാൻ ആ കഷ്ണം വാങ്ങുന്നു.
ഞാൻ അത് കഴിക്കുന്നു.
അതിന് നല്ല മധുരം ഉണ്ട്.
ഞാൻ വില ചോദിക്കുന്നില്ല.
കച്ചവടക്കാരൻ പെട്ടെന്ന് വില പറയുന്നു.
"ഒരു കൈതച്ചക്കയ്ക്ക് അറുപതു രൂപയാണ്," അയാൾ പറയുന്നു.
എനിക്ക് അത് ഇഷ്ടമാണ്.
"എനിക്ക് ഒരു കൈതച്ചക്ക വേണം," ഞാൻ പറയുന്നു.
അയാൾ വലിയ ഒരു കൈതച്ചക്ക എടുക്കുന്നു.
അയാൾ അത് എനിക്ക് തരുന്നു.
ഞാൻ അറുപതു രൂപ കൊടുക്കുന്നു.
ഞാൻ കച്ചവടക്കാരനോട് നന്ദി പറയുന്നു.
ഞാൻ മുന്നോട്ട് നടക്കുന്നു.
