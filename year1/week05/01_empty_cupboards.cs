Je šest hodin.
Stojím v kuchyni.
Mám hlad.
Otevírám lednici.
Je úplně prázdná.
Dívám se do skříňky.
Ve skříňce není žádné jídlo.
Nemám žádné jídlo.
Mám jen trochu vody.
Chtěla bych teď jídlo.
Mám ráda zeleninu.
Mám také ráda chleba.
Ale nic tady nemám.
Najdu tašku.
Ta taška je červená.
Je dobrá na nákupy.
Vycházím z bytu.
Zavírám dveře.
Jsem připravená.
Teď jdu do supermarketu.
