എന്റെ ജോലി കഴിഞ്ഞു.
ഞാൻ കാൽനടക്കാർക്കുള്ള തെരുവിലൂടെ നടക്കുന്നു.
കാറ്റിന് ഇപ്പോഴും നല്ല തണുപ്പുണ്ട്.
ഞാൻ വലിയൊരു തുണിക്കട കാണുന്നു.
കടയിൽ നല്ല വെളിച്ചമുണ്ട്.
ഞാൻ കടയ്ക്കുള്ളിലേക്ക് കയറുന്നു.
ഇവിടെ നല്ല സുഖമുള്ള ചൂടുണ്ട്.
കൗണ്ടറിന് പിന്നിലായി കടയിലെ ഒരു സഹായി നിൽക്കുന്നുണ്ട്.
അവർ എന്നെ നോക്കി ചിരിക്കുന്നു.
"ഹലോ," അവർ പറയുന്നു.
"ഹലോ," ഞാൻ മറുപടി നൽകുന്നു.
"എനിക്ക് വല്ലാതെ തണുക്കുന്നുണ്ട്," ഞാൻ പറയുന്നു.
"ഞാൻ നേർത്ത ഒരു ജാക്കറ്റ് മാത്രമേ ധരിച്ചിട്ടുള്ളൂ."
"ചൂടുനൽകുന്ന കുറച്ചു സാധനങ്ങൾ എനിക്ക് കണ്ടെത്തണം."
കടയിലെ സഹായി വീണ്ടും ചിരിക്കുന്നു.
"ഇന്ന് നല്ല തണുപ്പുമുണ്ട്," അവർ പറയുന്നു.
"ഞങ്ങളുടെ പക്കൽ കട്ടിയുള്ള ധാരാളം സ്വെറ്ററുകളുണ്ട്."
"ചൂടുനൽകുന്ന ശൈത്യകാല വസ്ത്രങ്ങളും ഞങ്ങളുടെ പക്കലുണ്ട്."
"നിങ്ങൾ നോക്കിക്കോളൂ," അവർ സ്നേഹത്തോടെ പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ മറുപടി നൽകുന്നു.
