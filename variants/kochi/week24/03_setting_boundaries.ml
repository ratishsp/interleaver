രാത്രിയാണ്.
ഞാൻ എന്റെ ഫ്ലാറ്റിൽ സോഫയിൽ ഇരിക്കുകയാണ്.
ടോമി എന്റെ കൂടെയുണ്ട്.
അവൻ പതുക്കെ സോഫയുടെ അടുത്തേക്ക് വരുന്നു.
അവൻ സോഫയിലേക്ക് ചാടാൻ ശ്രമിക്കുന്നു.
ഞാൻ അവനെ തടയുന്നു.
"ടോമി, സോഫയിൽ വേണ്ട," ഞാൻ സ്നേഹത്തോടെ പറയുന്നു.
"നീ അതിൽ കയറാൻ പാടില്ല എന്ന് അനിത പറഞ്ഞിട്ടുണ്ട്."
അവൻ താഴെ നിൽക്കുന്നു.
അനിത അവന് ഒരു ചെറിയ കിടക്ക കൊണ്ടുവന്നിട്ടുണ്ട്.
ഞാൻ ആ കിടക്ക ചൂണ്ടിക്കാണിക്കുന്നു.
"വാ ടോമി, നിന്റെ കിടക്കയിലേക്ക് പോകൂ," ഞാൻ പതുക്കെ പറയുന്നു.
"നീ അവിടെ കിടക്കണം."
ടോമി എന്നെ നോക്കുന്നു.
പിന്നെ, അവൻ പതുക്കെ അവന്റെ കിടക്കയിലേക്ക് നടക്കുന്നു.
അവൻ അതിൽ ഇരിക്കുന്നു.
"മിടുക്കൻ," ഞാൻ പറയുന്നു.
ഞാൻ അവനെ നോക്കി പുഞ്ചിരിക്കുന്നു.
ഞാൻ അവനെ നന്നായി നോക്കണം.
ടോമി അവന്റെ കിടക്കയിൽ സമാധാനത്തോടെ ഉറങ്ങുന്നു.
