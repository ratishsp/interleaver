ഇന്ന് ഒരു മനോഹരമായ ഞായറാഴ്ച രാവിലെ ആണ്.
ഞാൻ അടുക്കളയിൽ ഒരു ചായ ഉണ്ടാക്കുന്നു.
ഞാൻ വെള്ളം തിളപ്പിക്കുന്നു.
ഞാൻ എന്റെ ഫോൺ അവിടെ വെക്കുന്നു.
ഞാൻ മെക്സിക്കോയിലേക്ക് ഒരു വീഡിയോ കോൾ ചെയ്യുന്നു.
എന്റെ അമ്മ കോൾ എടുക്കുന്നു.
അവർക്ക് അവിടെ ഇപ്പോൾ രാത്രി ആണ്.
അമ്മ ചോദിക്കുന്നു, "മായ, നീ എന്ത് ചെയ്യുന്നു?"
ഞാൻ പറയുന്നു, "അമ്മേ, ഞാൻ ഒരു ചായ ഉണ്ടാക്കുന്നു."
കൊച്ചിയിൽ ഇപ്പോൾ നല്ല വെയിലുണ്ട്.
എന്റെ അടുക്കളയിൽ വളരെ വെളിച്ചം ഉണ്ട്.
അമ്മ ആ വെളിച്ചം കാണുന്നു.
അമ്മ ചോദിക്കുന്നു, "ഇത് ആരുടെ അടുക്കള ആണ്?"
അമ്മ പറയുന്നു, "അവിടെ വളരെ വെളിച്ചം ഉണ്ട്."
ഞാൻ സന്തോഷത്തോടെ ചിരിക്കുന്നു.
ഞാൻ എന്റെ ഫോൺ തിരിക്കുന്നു.
ഞാൻ അമ്മയ്ക്ക് എന്റെ പുതിയ മുറി കാണിക്കുന്നു.
ഞാൻ പറയുന്നു, "ഇത് കൊച്ചിയിലെ എന്റെ പുതിയ വീട് ആണ്."
