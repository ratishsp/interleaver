Seděla jsem na svém sedadle ve vlaku a rozhlížela se.
Naproti mně seděl otec.
Měl s sebou své dvě malé děti.
Otec měl velkou knihu.
Opravdu si chtěl číst svou knihu.
Ale neměl moc klidu.
Jeho dcera měla červený míč.
Jeho syn měl zelené autíčko.
Děti vůbec neseděly v klidu.
Neustále házely své hračky na zem.
Otec si hlasitě povzdechl a zavřel knihu.
Posbíral ty věci ze země.
Dal dětem jejich hračky zpátky.
„Musíte sedět v klidu,“ řekl unaveně.
Znovu otevřel svou knihu.
O dvě minuty později spadl míč na zem.
Zasáhl otcovu levou botu.
Muž ten míč znovu zvedl.
Usmála jsem se na unaveného otce.
Jen zavrtěl hlavou a podíval se dolů do své knihy.
