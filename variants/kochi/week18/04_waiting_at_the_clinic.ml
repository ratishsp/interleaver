ഞാൻ കുട എടുത്ത് പുറത്തേക്ക് ഇറങ്ങുന്നു.
ഞാൻ സൂക്ഷിച്ച് ക്ലിനിക്കിലേക്ക് നടക്കുന്നു.
ക്ലിനിക്ക് എന്റെ വീടിന്റെ അടുത്താണ്.
ഞാൻ ക്ലിനിക്കിന്റെ ഉള്ളിൽ കയറുന്നു.
ഇന്ന് അവിടെ നല്ല തിരക്കാണ്.
വെയ്റ്റിംഗ് റൂമിൽ ഒരുപാട് ആളുകൾ ഉണ്ട്.
ഞാൻ റിസപ്ഷനിൽ പോകുന്നു.
അവിടെ ഒരു നഴ്സ് ഉണ്ട്.
അവർ എന്റെ പേര് ചോദിക്കുന്നു.
"എന്റെ പേര് മായ, എനിക്ക് ഒരു അപ്പോയിന്റ്മെന്റ് ഉണ്ട്," ഞാൻ പറയുന്നു.
നഴ്സ് എന്റെ പനി നോക്കുന്നു.
"നിങ്ങൾക്ക് പനിയുണ്ട്, സുഖമില്ലേ?" അവർ ചോദിക്കുന്നു.
"ഇല്ല," ഞാൻ മറുപടി പറയുന്നു.
"എന്റെ തല നല്ലപോലെ വേദനിക്കുന്നു," ഞാൻ അവരോട് പറയുന്നു.
"നിങ്ങൾക്ക് തൊണ്ട വേദന ഉണ്ടോ?" അവർ ചോദിക്കുന്നു.
"അതെ, എനിക്ക് തൊണ്ട വേദനയും ഉണ്ട്," ഞാൻ പറയുന്നു.
"ഡോക്ടർ ഇപ്പോൾ തിരക്കിലാണ്," അവർ പറയുന്നു.
"നിങ്ങൾ അവിടെ ഇരിക്കണം, കുറച്ചു നേരം കാത്തിരിക്കണം."
ഞാൻ ഒരു കസേരയിൽ ഇരുന്ന് കാത്തിരിക്കുന്നു.
