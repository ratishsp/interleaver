വൈകുന്നേരം വൈകി, ഞാൻ നദിക്കരയിലേക്ക് നടന്നു.
കാലാവസ്ഥ അപ്പോഴും ഇളം ചൂടുള്ളതും മനോഹരവുമായിരുന്നു.
ഒരു ചെറിയ മരത്തോണിക്കുള്ള ടിക്കറ്റ് ഞാൻ വാങ്ങി.
ടിക്കറ്റിന് എഴുപത് ക്രോണർ ആയിരുന്നു വില.
ഞാൻ അതിൽ കയറി, ഡെക്കിൽ ഒരു നല്ല സീറ്റ് കണ്ടെത്തി.
തോണി വളരെ പതുക്കെ നദിയിലൂടെ മുന്നോട്ട് നീങ്ങി.
തോണിയിൽ മറ്റ് യാത്രക്കാർ അധികം ഉണ്ടായിരുന്നില്ല.
പ്രായമായ ഒരു സ്ത്രീ എന്റെ എതിർവശത്ത് ഇരിക്കുന്നുണ്ടായിരുന്നു.
അവർ തന്റെ ഭർത്താവിനൊപ്പം പൊതിഞ്ഞുകൊണ്ടുവന്ന ഉച്ചഭക്ഷണം കഴിക്കുകയായിരുന്നു.
അവരുടെ ഭർത്താവ് സന്തോഷത്തോടെ അവരെ നോക്കി പുഞ്ചിരിച്ചു.
വലിയ, പച്ച നിറമുള്ള ചില മരങ്ങൾക്കടിയിലൂടെ ഞങ്ങൾ നീങ്ങി.
വെള്ളത്തിന് നീല നിറമായിരുന്നു, അത് തികച്ചും ശാന്തവുമായിരുന്നു.
ഞാൻ വിശ്രമിക്കുകയും യാത്ര ആസ്വദിക്കുകയും ചെയ്തു.
സമയം വൈകിയെങ്കിലും ആകാശത്ത് അപ്പോഴും വെളിച്ചമുണ്ടായിരുന്നു.
അത് ശരിക്കും മനോഹരമായ ഒരു ഡാനിഷ് വസന്തകാല സന്ധ്യയായിരുന്നു.
ആ ചെറിയ തോണിയിൽ ഞാൻ പിറകോട്ട് ചാരിയിരുന്നു.
നദിയോരത്തെ പച്ചപ്പ് നിറഞ്ഞ പ്രകൃതി ഞാൻ ആസ്വദിച്ചു.
ഓഡൻസെയിലെ എന്റെ ദിവസത്തിന് അതൊരു മികച്ച അവസാനമായിരുന്നു.
