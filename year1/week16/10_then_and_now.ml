ഞാൻ എൻ്റെ കമ്പ്യൂട്ടർ അടയ്ക്കുന്നു.
എൻ്റെ കുടുംബവുമായുള്ള വീഡിയോ കോൾ കഴിഞ്ഞു.
ഞാൻ പുഞ്ചിരിച്ചുകൊണ്ട് സ്വീകരണമുറിക്ക് ചുറ്റും നോക്കുന്നു.
ഇവിടെ നല്ല ഇളംചൂടും സുഖകരമായ അന്തരീക്ഷവുമാണ്.
ഇപ്പോൾ പല കാര്യങ്ങളും വ്യത്യസ്തമാണ്.
ഞാൻ ഡെന്മാർക്കിലെ എൻ്റെ ആദ്യ ദിനങ്ങളെക്കുറിച്ച് ചിന്തിക്കുന്നു.
ജനുവരി വളരെ തണുപ്പുള്ള ഒരു മാസമായിരുന്നു.
ആദ്യ ആഴ്ചകൾ വലിയൊരു വെല്ലുവിളിയായിരുന്നു.
ഞാൻ എൻ്റെ കുടുംബത്തെ ഒരുപാട് മിസ് ചെയ്തു.
നഗരത്തിലെ എല്ലാം എനിക്ക് പുതിയതായിരുന്നു.
എൻ്റെ അയൽക്കാരി നീന എന്നെ സ്വാഗതം ചെയ്തു.
ഇപ്പോൾ എനിക്ക് മൃദുവായ ഒരു സോഫയും നല്ലൊരു പരവതാനിയും ഉണ്ട്.
എല്ലാ ദിവസവും രാവിലെ ഞാൻ ജോലിക്ക് ബസ്സിലാണ് പോകുന്നത്.
ഞാൻ പീറ്ററുമായും മറ്റ് സഹപ്രവർത്തകരുമായും സംസാരിക്കുന്നു.
ശൈത്യകാലം വളരെ നീണ്ടതായിരുന്നു.
എന്നാൽ ആദ്യ മാസങ്ങളിൽ ഞാൻ ഒരുപാട് കാര്യങ്ങൾ പഠിച്ചു.
ഞാൻ ഇപ്പോൾ ഈ നഗരത്തിൽ വെറുമൊരു അതിഥിയല്ല.
ഞാൻ ജനാലയിലൂടെ പുറത്തേക്ക് നോക്കുന്നു.
ഞാൻ ബാക്കിയുള്ള ചായ കൂടി കുടിക്കുന്നു, എനിക്ക് സന്തോഷമുണ്ട്.
എനിക്കിപ്പോൾ പൂർണ്ണമായും സ്വന്തം വീട് പോലെ തോന്നുന്നു.
