ഞാൻ എന്റെ ഫോണിലെ പാചകക്കുറിപ്പ് വീണ്ടും നോക്കുന്നു.
എനിക്ക് ഇന്ന് മൂന്ന് പേർക്കുള്ള ഭക്ഷണം ഉണ്ടാക്കണം.
ആദ്യം, ഞാൻ ഒരു കടലാസും പേനയും എടുക്കുന്നു.
ഞാൻ ആവശ്യമുള്ള സാധനങ്ങളുടെ പട്ടിക വായിക്കുന്നു.
പിന്നെ, ഞാൻ അടുക്കളയിലെ മസാലകളുടെ അലമാര പരിശോധിക്കുന്നു.
ഇവിടെ ആവശ്യത്തിന് മഞ്ഞൾപ്പൊടിയും മുളകുപൊടിയും ഉണ്ട്.
പക്ഷേ മല്ലിപ്പൊടി ഇല്ല.
അതിനുശേഷം, ഞാൻ കടലാസിൽ മല്ലിപ്പൊടി എന്ന് എഴുതുന്നു.
കറിക്ക് ചിക്കൻ വേണം.
മൂന്ന് പേർക്ക് അര കിലോ ചിക്കൻ മതിയാകും.
ഞാൻ അതും എഴുതുന്നു.
അടുത്തതായി, ഞാൻ പച്ചക്കറികൾ നോക്കുന്നു.
എനിക്ക് കൃത്യം രണ്ട് വലിയ സവാളയും മൂന്ന് തക്കാളിയും വേണം.
ഞാൻ അവ പട്ടികയിൽ ചേർക്കുന്നു.
എനിക്ക് കുറച്ച് ഇഞ്ചിയും പച്ചമുളകും കൂടെ വേണം.
ഇപ്പോൾ സാധനങ്ങൾ വാങ്ങാനുള്ള പട്ടിക തയ്യാറാണ്.
ഞാൻ എന്റെ കുടയും തുണിസഞ്ചിയും എടുക്കുന്നു.
ഞാൻ മാർക്കറ്റിലേക്ക് പുറപ്പെടുന്നു.
