ഞാൻ ഇപ്പോൾ വാട്ടർ മെട്രോ ടെർമിനലിൽ ആണ്.
ഞാൻ പ്രവേശനകവാടത്തിലേക്ക് നടക്കുന്നു.
ഞാൻ അവിടെ എന്റെ പുതിയ കാർഡ് വെക്കുന്നു.
ഉടനെ ഗേറ്റ് തുറക്കുന്നു.
ഞാൻ ഡോക്കിലേക്ക് നടക്കുന്നു.
അവിടെ മനോഹരമായ ഒരു ബോട്ട് ഉണ്ട്.
ഇതൊരു ഇലക്ട്രിക് ബോട്ട് ആണ്.
ഞാൻ ആ ബോട്ടിൽ കയറുന്നു.
ബോട്ടിനകത്ത് നല്ല തണുപ്പാണ്.
ഞാൻ ജനലിനടുത്തുള്ള ഒരു സീറ്റിൽ ഇരിക്കുന്നു.
ബോട്ടിൽ ധാരാളം ആളുകൾ ഉണ്ട്.
കുറച്ചു കഴിയുമ്പോൾ ബോട്ട് പുറപ്പെടുന്നു.
ഈ ബോട്ട് വളരെ നിശബ്ദമാണ്.
എനിക്ക് ഈ യാത്ര വളരെ ഇഷ്ടമാണ്.
