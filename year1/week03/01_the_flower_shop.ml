ഇപ്പോൾ ജനുവരിയാണ്, നല്ല തണുപ്പുമുണ്ട്.
കോപ്പൻഹേഗനിലെ ബസ് സ്റ്റോപ്പിൽ നിന്ന് ഞാൻ വീട്ടിലേക്ക് നടക്കുകയാണ്.
തെരുവിൽ ഞാൻ ഒരു പൂക്കട കാണുന്നു.
അതിനുള്ളിൽ നല്ല വെളിച്ചവും ചൂടുമുണ്ട്.
ഞാൻ ആ ചൂടുള്ള കടയ്ക്കുള്ളിലേക്ക് കയറുന്നു.
ഞാൻ ചെറിയ ഒരു പച്ചച്ചെടി നോക്കുന്നു.
കടയിലെ ഒരു ജീവനക്കാരൻ എന്നെ നോക്കി ചിരിക്കുന്നു.
"ഹലോ," അയാൾ പറയുന്നു.
"ഹലോ," ഞാൻ പറയുന്നു.
"ഞാൻ ഒരു ചെടി അന്വേഷിക്കുകയാണ്."
"ഇതൊരു സമ്മാനമാണോ?" അയാൾ ചോദിക്കുന്നു.
"അല്ല, ഇത് എന്റെ മുറിയിലേക്ക് വേണ്ടിയാണ്," ഞാൻ മറുപടി നൽകുന്നു.
"ഇത് ശരിക്കും നല്ലൊരു ചെടിയാണ്," അയാൾ പറയുന്നു.
"ഇതിന് എന്താണ് വില?" ഞാൻ ചോദിക്കുന്നു.
"ഇതിന് അമ്പത്തഞ്ച് ക്രോണർ ആണ് വില," അയാൾ മറുപടി നൽകുന്നു.
എന്റെ പുതിയ ചെടിക്കുള്ള പണം ഞാൻ നൽകുന്നു.
അയാൾ ആ ചെടി ഒരു പേപ്പർ ബാഗിലേക്ക് വെക്കുന്നു.
"ഇതാ പിടിച്ചോളൂ, ഇതാണ് നിങ്ങളുടെ ബാഗ്," അയാൾ പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ സന്തോഷത്തോടെ പറയുന്നു.
ഞാൻ ആ തണുത്ത വൈകുന്നേരത്തേക്ക് പുറത്തിറങ്ങുന്നു.
എന്റെ ചെറിയ ചെടി എന്നെ വളരെ സന്തോഷിപ്പിക്കുന്നു.
