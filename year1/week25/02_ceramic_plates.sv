Jag tar en promenad över ett stort torg i staden.
Här finns det en stor loppmarknad varje söndag.
Solen skiner och många människor går runt bland borden.
Jag stannar vid ett litet bord med många olika saker.
Bakom bordet står en vänlig säljare.
Plötsligt ser jag två blå keramiktallrikar.
Jag tar upp dem och tittar noga på dem.
"Hur mycket kostar de här tallrikarna?" frågar jag säljaren.
Säljaren ler mot mig.
"De kostar bara fyrtio kronor," svarar han.
Det är ett riktigt bra pris.
Jag köpte ett litet bord till mitt kök för en månad sedan.
De här tallrikarna kommer att passa perfekt till det här bordet.
"Dem vill jag väldigt gärna köpa," säger jag.
Jag ger säljaren fyrtio kronor och lägger försiktigt tallrikarna i min väska.
Det är alltid trevligt att hitta något speciellt på en lugn söndag.
