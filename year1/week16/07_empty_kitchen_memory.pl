Moja mama pyta, czy wszystko było w porządku tego pierwszego wieczoru.
Mieszkanie było umeblowane, ale wciąż dla mnie nowe.
Nie miałam jeszcze żadnego jedzenia w kuchni.
Po drodze do domu kupiłam prostą kolację.
To była kanapka ze sklepu.
Usiadłam na małej sofie.
W mieszkaniu było bardzo cicho.
Zjadłam kolację w ciszy.
Wciąż znałam tylko moją sąsiadkę Ninę.
„Bardzo za wami tęskniłam tamtego wieczoru” – mówię do niej.
Myślałam o mojej siostrze Sofíi i moim bracie Diego.
Tęskniłam nawet za naszym psem Lolą.
Ale cieszyłam się na moje nowe życie.
Moja mama kładzie rękę na sercu.
„Początki zawsze są trudne” – odpowiada.
Kiwam głową i wracam myślami do tamtego dnia.
To był trudny wieczór, ale następny poranek był o wiele lepszy.
