ശനിയാഴ്ചയാണ്, ഞാൻ എന്റെ സോഫയിൽ വിശ്രമിക്കുകയാണ്.
മെക്സിക്കോയിലുള്ള എന്റെ കുടുംബവുമായി ഞാൻ ഒരു വീഡിയോ കോൾ തുടങ്ങുന്നു.
എന്റെ അമ്മ ഏതാണ്ട് അപ്പോൾത്തന്നെ മറുപടി നൽകുന്നു.
"ഹലോ മായാ, എന്റെ പൊന്നേ," വലിയൊരു ചിരിയോടെ അവർ പറയുന്നു.
പശ്ചാത്തലത്തിൽ എന്റെ സഹോദരി സോഫിയയെയും സഹോദരൻ ഡീഗോയെയും ഞങ്ങളുടെ നായ ലോലയെയും എനിക്ക് കാണാൻ കഴിയുന്നുണ്ട്.
"ഹലോ അമ്മേ."
"ഇവിടെ കാര്യങ്ങളൊക്കെ വളരെ നന്നായി പോകുന്നു," ഞാൻ സന്തോഷത്തോടെ പറയുന്നു.
മെക്സിക്കോയിലെ വീട്ടിലെ അവരുടെ ഒരാഴ്ചത്തെ വിശേഷങ്ങളെക്കുറിച്ച് ഞങ്ങൾ അല്പനേരം സംസാരിക്കുന്നു.
തുടർന്ന്, തുടക്കത്തിൽ എന്തെങ്കിലും ബുദ്ധിമുട്ടുണ്ടായിരുന്നോ എന്ന് അമ്മ ചോദിക്കുന്നു.
നഗരത്തിലെ എന്റെ ആദ്യ നാളുകളെക്കുറിച്ച് ഞാൻ ഓർത്തുനോക്കുന്നു.
എല്ലാം പുതിയതായിരുന്നു, ചിലപ്പോഴൊക്കെ ആ ദിവസങ്ങൾ ബുദ്ധിമുട്ടുള്ളതുമായിരുന്നു.
"തുടക്കം എപ്പോഴും എളുപ്പമായിരുന്നില്ല," ഞാൻ അവരോട് പറയുന്നു.
"ഒരു ദിവസം രാവിലെ മുഴുവൻ ഞാൻ ഒരു വലിയ വരിയിൽ കാത്തുനിന്നു."
"ഒഴിഞ്ഞ ഒരു അടുക്കളയിൽ ഇരുന്ന് ഞാൻ നിങ്ങളെ മിസ്സ് ചെയ്തു."
"ഒരു ശനിയാഴ്ച ഞാൻ തെറ്റായ വഴിയിലൂടെ നടന്ന് വഴിതെറ്റിപ്പോയി."
"മാത്രമല്ല, തുടക്കത്തിൽ എന്റെ കൈയിൽ ആവശ്യത്തിന് ചൂടുനൽകുന്ന ഒരു ജാക്കറ്റും ഉണ്ടായിരുന്നില്ല," ഞാൻ കൂട്ടിച്ചേർക്കുന്നു.
എന്റെ അമ്മ ശ്രദ്ധയോടെ കേൾക്കുകയും തലയാട്ടുകയും ചെയ്യുന്നു.
ഡെന്മാർക്കിലെ എന്റെ തുടക്കകാലത്തെ കഥകളെല്ലാം കേൾക്കാൻ അവർ ശരിക്കും ആഗ്രഹിക്കുന്നു.
ഞാൻ ഒരു കവിൾ ചായ കുടിച്ചിട്ട് എന്റെ കഥ തുടരുന്നു.
