Jag sitter vid mitt skrivbord på kontoret en onsdagsmorgon.
Eva går över till mitt skrivbord med en kopp kaffe.
"Hej Maya, har du tid på fredag?" frågar hon med ett stort leende.
Jag tror att jag faktiskt har en ledig kväll.
"Ja, jag har gott om tid," svarar jag henne.
"Jag vill väldigt gärna bjuda hem dig på middag," säger hon.
Jag blir mycket glad för inbjudan.
"Tack, jag vill väldigt gärna komma," säger jag.
"Jag har tänkt laga en vegetarisk rätt," förklarar Eva.
"Det låter helt perfekt," ler jag.
"Vilken tid ska jag vara där?" frågar jag.
"Du kan bara komma klockan sex," svarar hon.
Jag tycker att det alltid är trevligt att besöka nya vänner.
"Jag ska definitivt vara där," bekräftar jag.
Eva skriver sin adress på en liten gul lapp.
Hon ger lappen till mig.
"Jag ser väldigt mycket fram emot fredag," säger jag till henne.
Eva ler igen och går tillbaka till sin dator.
