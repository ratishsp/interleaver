ഇത് ശനിയാഴ്ച രാവിലെയാണ്.
ഞാൻ നേരത്തെ ഉണർന്നു, എനിക്ക് വീണ്ടും നല്ല സുഖം തോന്നുന്നു.
വെള്ളിയാഴ്ച ദിവസം മുഴുവൻ ഞാൻ വീട്ടിൽ വിശ്രമിച്ചു.
ആ വീര്യം കുറഞ്ഞ മരുന്ന് കൃത്യമായി ഫലിച്ചു.
എന്റെ കണ്ണുകൾ തെളിഞ്ഞിട്ടുണ്ട്, അവയ്ക്ക് ഒട്ടും ചൊറിച്ചിലില്ല.
എനിക്ക് തലവേദനയില്ല, ഇനി എന്റെ തൊണ്ട വേദനിക്കുന്നുമില്ല.
ഞാൻ കിടക്കയിൽ നിന്നെഴുന്നേറ്റ് നേരിയ വസന്തകാല കാറ്റിലേക്കായി ജനൽ തുറക്കുന്നു.
യാതൊരു പ്രശ്നവുമില്ലാതെ ശ്വാസമെടുക്കാൻ കഴിയുന്നത് വളരെ സന്തോഷമുള്ള കാര്യമാണ്.
നല്ലൊരു പ്രഭാതഭക്ഷണം ഉണ്ടാക്കാനായി ഞാൻ അടുക്കളയിലേക്ക് പോകുന്നു.
ഞാൻ ചീസിനൊപ്പം ബ്രെഡ് കഴിക്കുകയും ഒരു വലിയ കപ്പ് ചൂട് കാപ്പി കുടിക്കുകയും ചെയ്യുന്നു.
സൂര്യൻ പ്രകാശിക്കുന്നുണ്ട്, അതിനാൽ പാർക്കിൽ ഒന്നു നടക്കാൻ പോകണമെന്ന് ഞാൻ കരുതുന്നു.
ഞാൻ എന്റെ സ്പ്രിംഗ് ജാക്കറ്റ് ധരിച്ച് തെരുവിലേക്ക് ഇറങ്ങുന്നു.
മരങ്ങളെല്ലാം ഇപ്പോൾ പൂർണ്ണമായും പച്ച നിറത്തിലാണ്, കൂടാതെ നിരവധി ആളുകൾ കാലാവസ്ഥ ആസ്വദിക്കുന്നുണ്ട്.
ഒടുവിൽ വസന്തകാലമായപ്പോൾ സുഖമില്ലാതെയിരിക്കുന്നത് ശരിക്കും വിരസമാണ്.
പക്ഷേ ഇന്ന് എന്റെ കാലുകൾക്ക് നല്ല ബലം തോന്നുന്നു, കൂടാതെ എന്റെ ഊർജ്ജം തിരികെ ലഭിക്കുകയും ചെയ്തു.
ഞാൻ പാർക്കിലെ ചെറിയ തടാകത്തിന് ചുറ്റും പതുക്കെ നടക്കുന്നു.
ഭാഗ്യവശാൽ ഞാൻ ഇപ്പോൾ പൂർണ്ണ ആരോഗ്യവതിയാണ്, വാരാന്ത്യം ആസ്വദിക്കാൻ ഞാൻ തയ്യാറുമാണ്.
