വ്യാഴാഴ്ച വൈകുന്നേരം സമയം ആറര കഴിഞ്ഞു.
ഞങ്ങളുടെ ബാഡ്മിന്റൺ കളി ഇപ്പോൾ കഴിഞ്ഞു.
കിരണും സാറയും ഞാനും ഒരുമിച്ച് നന്നായി കളിച്ചു.
ഞങ്ങൾ മൂന്ന് പേരും നന്നായി വിയർക്കുന്നുണ്ട്.
കിരണും സാറയും അവരുടെ റാക്കറ്റുകൾ ബാഗിൽ വച്ചു, ഞാൻ വാടകയ്ക്ക് എടുത്ത റാക്കറ്റ് ഡെസ്കിൽ തിരികെ കൊടുത്തു.
ഞങ്ങൾ ടവ്വൽ കൊണ്ട് മുഖം തുടച്ചു.
മാസം ഏപ്രിൽ ആണ്.
അതിനാൽ വൈകുന്നേരം നല്ല ചൂടുണ്ട്.
"മായ, ഇന്ന് നല്ല ക്ഷീണം ഉണ്ടോ?" സാറ ചോദിക്കുന്നു.
ഞാൻ ചിരിച്ചു.
"അതെ, എനിക്ക് കുറച്ചു ക്ഷീണം ഉണ്ട്," ഞാൻ പറഞ്ഞു.
കിരൺ പറയുന്നു, "നമ്മൾ ഇന്ന് വേഗത്തിൽ കളിച്ചു."
ഞങ്ങൾ കുറച്ചു നേരം അവിടെ മിണ്ടാതെ ഇരിക്കുന്നു.
