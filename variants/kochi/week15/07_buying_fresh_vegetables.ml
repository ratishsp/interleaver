ഞാൻ ഒരു ചെറിയ പച്ചക്കറിക്കട കാണുന്നു.
ഞാൻ ആ കടയുടെ മുന്നിൽ നിൽക്കുന്നു.
കടയിൽ ഒരാൾ നിൽക്കുന്നുണ്ട്.
"നമസ്കാരം," ഞാൻ അയാളോട് പറയുന്നു.
"നമസ്കാരം," അയാൾ എന്നോട് പറയുന്നു.
"നല്ല തക്കാളി ഉണ്ടോ?" ഞാൻ ചോദിക്കുന്നു.
"ഉണ്ട്, നല്ല തക്കാളിയുണ്ട്," അയാൾ പറയുന്നു.
"എനിക്ക് തക്കാളിയും സവാളയും വേണം," ഞാൻ പറയുന്നു.
അയാൾ കുറച്ച് തക്കാളിയും സവാളയും എടുക്കുന്നു.
അയാൾ അത് തൂക്കി നോക്കുന്നു.
"വില എത്രയാണ്?" ഞാൻ ചോദിക്കുന്നു.
"എൺപത് രൂപ," അയാൾ പറയുന്നു.
ഞാൻ എൻ്റെ ബാഗിൽ നിന്ന് പണം എടുക്കുന്നു.
ഞാൻ അയാൾക്ക് എൺപത് രൂപ കൊടുക്കുന്നു.
അയാൾ പച്ചക്കറികൾ എനിക്ക് തരുന്നു.
ഞാൻ ആ പച്ചക്കറികൾ സൂക്ഷിച്ച് എൻ്റെ സഞ്ചിയിൽ വെക്കുന്നു.
ഞാൻ വീട്ടിലേക്ക് നടക്കുന്നു.
