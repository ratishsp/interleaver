Det är kallt i dag.
Det är vinter, och morgonen är mörk.
Jag står i mitt rum och gör mig i ordning.
Jag letar fram mina varma vinterkläder.
Först tar jag på mig en tjock tröja.
Jag drar den över huvudet.
Tröjan är härligt varm och mjuk.
Jag tar också en lång halsduk.
Jag virar den tätt runt halsen.
Därefter går jag ut i min hall.
Det kommer ett kallt drag från trapphuset.
Jag tar min tunga vinterjacka.
Jag drar upp jackan helt.
Den stoppar den kalla luften.
Det är viktigt att hålla värmen i dag.
Då fryser jag inte i kylan.
Jag tar också med mig mitt paraply.
Jag är äntligen redo att ta min buss.
Jag öppnar ytterdörren och går ut i kylan.
