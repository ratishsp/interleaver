Jag väntar vid disken.
Han gör mitt kaffe.
Han ställer en varm kopp kaffe på en träbricka.
Han ställer också en liten tallrik på brickan.
Min kanelbulle ligger på tallriken.
Den doftar ljuvligt.
"Varsågod, din beställning," säger han.
"Tack så mycket," svarar jag.
"Tack för den goda servicen."
"Tack själv," säger han vänligt.
Jag tar brickan med båda händerna.
Jag går mycket försiktigt över golvet.
Jag går tillbaka till mitt bord vid fönstret.
Jag ställer ner brickan på bordet.
Nu vill jag gärna sätta mig ner.
Jag är redo för en bra paus.
