Familjen hade också med sig en liten hund på tåget.
Den var mycket söt, men den var inte tyst.
Hunden låg i sin lilla korg på golvet.
Pappan tittade ner på sin bok igen.
Han ville bara läsa lite.
Men plötsligt hoppade hunden ut ur sin korg.
Den sprang snabbt fram till pappan.
Han satt med sin ena fot uppe på en väska.
Hunden snappade åt sig hans vänstra sko.
Den tog skon i munnen.
Sedan sprang den snabbt iväg.
"Nej, kom tillbaka med min sko!" ropade pappan.
Han reste sig upp i sina strumpor.
Han sprang efter hunden ner längs gången.
De två barnen pekade på honom.
De tittade på varandra och skrattade högt.
Jag tittade på dem från min plats.
Jag skrattade också lite bakom min bok.
Lyckligtvis fångade han till slut sin hund.
Han fick också tillbaka sin sko.
