ഞാൻ പടികൾ കയറുകയാണ്.
ജിമ്മിൽ പോയതിന് ശേഷം ഞാൻ ക്ഷീണിതയാണ്.
രണ്ടാമത്തെ നിലയിൽ വെച്ച് ഞാൻ നീനയെ കണ്ടുമുട്ടുന്നു.
അവൾ എന്നെ നോക്കി ചിരിക്കുന്നു.
"ഹായ് മായ," അവൾ പറയുന്നു.
"ഹായ് നീന, എങ്ങനെയുണ്ട് വിശേഷങ്ങൾ?" ഞാൻ ചോദിക്കുന്നു.
"വളരെ നന്നായി പോകുന്നു," നീന മറുപടി പറയുന്നു.
"നിന്നെ കണ്ടിട്ട് ചെറിയ ക്ഷീണമുള്ളത് പോലെ തോന്നുന്നു."
"അതെ, ഞാൻ ബുധനാഴ്ചകളിൽ എപ്പോഴും വ്യായാമം ചെയ്യാറുണ്ട്," ഞാൻ വിശദീകരിക്കുന്നു.
"ഈയിടെയായി നമ്മൾ വളരെ അപൂർവ്വമായേ ഒരുമിച്ച് കാപ്പി കുടിക്കാറുള്ളൂ," നീന പറയുന്നു.
"നാളെ നിനക്ക് സമയമുണ്ടോ?" അവൾ ചോദിക്കുന്നു.
വ്യാഴാഴ്ച എനിക്ക് എന്തൊക്കെ ചെയ്യാനുണ്ടെന്ന് ഞാൻ ആലോചിക്കുന്നു.
"അതെ, വ്യാഴാഴ്ച വളരെ നല്ലൊരു ദിവസമാണ്," ഞാൻ പറയുന്നു.
"ഏത് സമയത്ത്?" ഞാൻ ചോദിക്കുന്നു.
"ഒരുപക്ഷേ നാലരയ്ക്ക് ആയാലോ?"
"നാലര എന്നത് തികച്ചും അനുയോജ്യമാണ്," ഞാൻ സന്തോഷത്തോടെ മറുപടി പറയുന്നു.
"നാളെ ഉച്ചകഴിഞ്ഞ് കാണാം," നീന പറയുന്നു.
കോണിപ്പടിയിൽ വെച്ച് ഞങ്ങൾ പരസ്പരം യാത്ര പറയുന്നു.
ഞാൻ എന്റെ അപ്പാർട്ട്മെന്റിലേക്ക് പോകുന്നു.
നമ്മുടെ കോഫി ഡേറ്റിനായി ഞാൻ കാത്തിരിക്കുകയാണ്.
