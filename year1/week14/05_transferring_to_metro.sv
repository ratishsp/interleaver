Bussen stannar på ett livligt torg.
Jag kliver av bussen.
Jag säger hejdå till den äldre damen.
Nu ska jag till metron.
Jag går över torget.
Det är många människor här.
Jag går nerför de breda trapporna.
Stationen är under jorden.
Den är väldigt stor och ljus.
Jag måste checka in igen.
Jag tar fram mitt blåa kort.
Jag skannar kortet på maskinen.
Maskinen ger ifrån sig ett högt pip.
Nu kan jag åka med metron.
Jag går ner till perrongen.
Jag tar nästa tåg.
Det går direkt mot hamnen.
Tåget kommer om tre minuter.
