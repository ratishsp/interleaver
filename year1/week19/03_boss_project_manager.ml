രാവിലത്തെ മീറ്റിംഗിന് ശേഷം ഞാൻ എന്റെ ഡെസ്കിൽ ഇരിക്കുന്നു.
പ്രസന്റേഷനിൽ നിന്നുള്ള എന്റെ നോട്ട്സ് ഞാൻ നോക്കുന്നു.
എന്റെ ബോസ് തോമസ് എന്റെ അടുത്തേക്ക് വരുന്നു.
അദ്ദേഹമാണ് ഞങ്ങളുടെ പ്രോജക്റ്റ് മാനേജർ.
അദ്ദേഹം കുറേ വർഷങ്ങളായി ഇവിടെ ജോലി ചെയ്യുന്നു.
"ഗുഡ് മോർണിംഗ്, മായ," ഒരു പുഞ്ചിരിയോടെ അദ്ദേഹം പറയുന്നു.
"അത് ശരിക്കും നല്ലൊരു പ്രസന്റേഷൻ ആയിരുന്നു."
"നന്ദി, തോമസ്," ഞാൻ മറുപടി നൽകുന്നു.
"നിങ്ങളെ ടീമിൽ ലഭിച്ചതിൽ ഞങ്ങൾക്ക് വലിയ സന്തോഷമുണ്ട്," തോമസ് തുടരുന്നു.
"നിങ്ങളോടൊപ്പം ജോലി ചെയ്യാൻ ടീം മുഴുവൻ കാത്തിരിക്കുകയായിരുന്നു."
"ഞാനും അതിനായി കാത്തിരിക്കുകയായിരുന്നു," ഞാൻ സന്തോഷത്തോടെ പറയുന്നു.
"ഇതൊരു ആവേശകരമായ പ്രോജക്റ്റാണ്."
തോമസ് വീണ്ടും പുഞ്ചിരിച്ചുകൊണ്ട് അദ്ദേഹത്തിന്റെ ഓഫീസിലേക്ക് തിരികെ നടക്കുന്നു.
ഞാൻ എന്റെ കമ്പ്യൂട്ടർ സ്ക്രീനിലേക്ക് നോക്കുന്നു.
ടീമിൽ എനിക്ക് ശരിക്കും സ്വീകാര്യത ലഭിച്ചതായി എനിക്ക് തോന്നുന്നു.
