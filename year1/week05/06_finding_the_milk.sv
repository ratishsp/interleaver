Nu behöver jag mjölk.
Jag går längs en lång gång.
Jag tittar på hyllan.
Jag kan se vattnet och juicen.
Men jag kan inte hitta mjölken.
Jag tittar överallt.
Jag ser en man.
Han arbetar i mataffären.
Jag stoppar medarbetaren och ler.
"Ursäkta," säger jag.
"Jag skulle vilja ha mjölk."
"Var är mjölken?"
Mannen pekar mot bakre delen av butiken.
"Mejeriavdelningen är där nere," säger han.
"Tack så mycket," svarar jag.
Jag går dit ner.
Jag hittar äntligen kylskåpet och mjölken.
Jag tar en kartong och lägger den i korgen.
