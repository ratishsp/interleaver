എന്റെ ബാഡ്മിന്റൺ സാധനങ്ങൾ മെക്സിക്കോയിലാണ്.
അതുകൊണ്ട് എനിക്ക് കളിക്കാൻ ഒരു റാക്കറ്റ് വേണം.
ഞാൻ മാനേജറോട് ഒരു റാക്കറ്റ് ചോദിക്കുന്നു.
"എനിക്ക് ഇവിടെനിന്ന് ഒരു റാക്കറ്റ് വാടകയ്ക്ക് എടുക്കാൻ കഴിയുമോ?" ഞാൻ ചോദിക്കുന്നു.
"തീർച്ചയായും എടുക്കാൻ കഴിയും," അദ്ദേഹം പറയുന്നു.
"ഒരു മണിക്കൂറിന് അമ്പതു രൂപയാണ് വാടക."
ഞാൻ അദ്ദേഹത്തിന് അമ്പതു രൂപ കൊടുക്കുന്നു.
അദ്ദേഹം എനിക്ക് ഒരു പുതിയ റാക്കറ്റ് തരുന്നു.
ഞാൻ ആ റാക്കറ്റ് കയ്യിൽ എടുക്കുന്നു.
ഞാൻ അത് പതുക്കെ ഒന്ന് വീശുന്നു.
ഇതിന് അധികം ഭാരമില്ല.
എനിക്ക് ഇതുകൊണ്ട് നന്നായി കളിക്കാൻ കഴിയും.
"ഈ റാക്കറ്റ് കുഴപ്പമില്ലേ?" അദ്ദേഹം ചോദിക്കുന്നു.
"ഇത് വളരെ നല്ലതാണ്."
"എനിക്ക് ഇത് ഇഷ്ടമാണ്," ഞാൻ പറയുന്നു.
"ഞാൻ ഇപ്പോൾ കളിക്കാൻ പോകുന്നു."
അദ്ദേഹം സന്തോഷത്തോടെ ചിരിക്കുന്നു.
ഞാൻ റാക്കറ്റുമായി കോർട്ടിലേക്ക് നടക്കുന്നു.
