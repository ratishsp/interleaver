Lekarz prosi mnie, abym otworzyła usta.
„Powiedz a” – mówi z uśmiechem.
Dokładnie ogląda moje gardło.
Potem słucha mojego oddechu.
Pyta, czy gdzieś jeszcze czuję się źle.
Mówię mu, że boli mnie również głowa.
„To nie jest przeziębienie” – mówi.
„Ma pani zwykłą alergię wiosenną” – wyjaśnia.
Jestem trochę zaskoczona.
Nigdy wcześniej nie miałam alergii.
Mówi mi, że to zupełnie normalne.
Tutejsze drzewa i kwiaty są nowe dla mojego organizmu.
„Powinna pani kupić w aptece jakiś łagodny lek” – mówi lekarz.
Obiecuje, że to szybko pomoże.
„Wtedy znów poczuje się pani dobrze” – dodaje.
Bardzo mi ulżyło.
Boli mnie gardło, ale na szczęście to nic poważnego.
