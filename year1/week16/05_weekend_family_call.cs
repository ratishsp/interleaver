Je sobota a já odpočívám na pohovce.
Začínám videohovor se svou rodinou v Mexiku.
Moje matka odpovídá téměř okamžitě.
„Ahoj Mayo, zlatíčko,“ říká s velkým úsměvem.
V pozadí vidím svou sestru Sofíu, bratra Diega a našeho psa Lolu.
„Ahoj mami.“
„Daří se mi tu opravdu dobře,“ říkám vesele.
Povídáme si trochu o jejich týdnu doma v Mexiku.
Pak se moje matka ptá, jestli bylo na začátku něco těžké.
Vzpomínám na své první dny ve městě.
Všechno bylo nové a dny byly někdy těžké.
„Začátek nebyl vždycky snadný,“ říkám jí.
„Celé dopoledne jsem čekala v dlouhé frontě.“
„Seděla jsem v prázdné kuchyni a chyběli jste mi.“
„Jednu sobotu jsem šla špatným směrem a ztratila se.“
„A zpočátku jsem neměla dostatečně teplou bundu,“ dodávám.
Moje matka pozorně poslouchá a přikyvuje.
Opravdu chce slyšet všechny příběhy z mých začátků v Dánsku.
Napiji se čaje a vyprávím dál.
