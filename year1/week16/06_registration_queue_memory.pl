Patrzę na moją mamę na ekranie.
Chce usłyszeć więcej o długiej kolejce.
Opowiadam jej o długim poranku.
„To był zimny wtorek w styczniu” – mówię.
Pojechałam autobusem do miejskiego biura obsługi obywatela.
W dużym pomieszczeniu było naprawdę dużo ludzi.
Pobrałam numerek z małego automatu.
Mój numer to było pięćdziesiąt dziewięć.
Ale ekran na ścianie pokazywał tylko dwadzieścia jeden.
Kolejka posuwała się niesamowicie wolno.
Siedziałam na twardym krześle i czekałam dwie godziny.
Często spoglądałam na ekran.
W końcu przyjazny mężczyzna wywołał mój numer.
Wstałam i podeszłam do jego biurka.
Dałam mu mój paszport i moje dokumenty z firmy programistycznej.
Przeczytał papiery i pisał na komputerze.
W końcu dostałam mój numer CPR.
Poprosił mnie, żebym bardzo dobrze pilnowała tego ważnego numeru.
„Byłaś bardzo cierpliwa” – uśmiecha się moja mama.
