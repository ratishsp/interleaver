Jest późny piątkowy wieczór.
Zanim pójdziemy spać, wyprowadzam Ludwiga.
Idziemy na krótki spacer po okolicy.
Ulice są teraz bardzo ciche.
Ludwig idzie grzecznie obok mnie.
Nagle się zatrzymuje.
Z zapałem obwąchuje coś na chodniku.
To brudna torba z resztkami jedzenia.
Otwiera pysk, żeby to wziąć.
„Nie, puść to!” – mówię do niego stanowczo.
Delikatnie odciągam go od torby.
„Śmieci to nie jedzenie, Ludwigu” – wyjaśniam.
„Chodź tu, Ludwigu” – wołam go.
Puszcza torbę i spogląda na mnie.
Szybko zaczyna merdać ogonem.
„Dobry pies” – mówię i głaszczę go.
Kontynuujemy nasz spacer wzdłuż ulicy.
Teraz musimy już tylko wrócić do domu i spać.
