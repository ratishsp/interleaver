ജോലിസ്ഥലത്ത് ഞാൻ സാധാരണയായി ദിവസം മുഴുവൻ ഒരു സ്ക്രീനിലാണ് നോക്കാറുള്ളത്.
അതുകൊണ്ട്, ഇപ്പോൾ പൂർണ്ണമായും ഓഫ്‌ലൈനായിരിക്കാൻ ഞാൻ ആഗ്രഹിക്കുന്നു.
ഞാൻ എന്റെ സ്വീകരണമുറിയിലേക്ക് പോകുന്നു.
ഇവിടെ ഞാൻ എന്റെ ഊഷ്മളമായ വായനാവിളക്ക് ഓണാക്കുന്നു.
മുറിയിലെ വെളിച്ചം ഊഷ്മളവും മൃദുലവുമാണ്.
ഞാൻ എന്റെ മൃദുവായ ചാരുകസേരയിൽ ഇരിക്കുന്നു.
ഞാൻ എന്റെ പുതിയ പുസ്തകം പുറത്തെടുക്കുന്നു.
അതൊരു യഥാർത്ഥ പേപ്പർ പുസ്തകമാണ്.
പുസ്തകം തുറക്കുന്നു, യഥാർത്ഥ ലോകം അപ്രത്യക്ഷമാകുന്നു.
നീന നൽകിയ കോഫി ബീൻസ് നാളെ രാവിലത്തേക്ക് മാറ്റിവെക്കണം.
ഇന്ന് രാത്രി ഞാൻ ഒരു ഗ്ലാസ് വെള്ളം മാത്രമേ കുടിക്കുന്നുള്ളൂ.
വൈകുന്നേരത്തിന്റെ ബാക്കി സമയം ഫോൺ അവഗണിക്കുകയാണ്.
ഞാൻ പൂർണ്ണമായും വിശ്രമിക്കുകയാണ്.
ദിവസത്തിന് ഇത്രയും ശാന്തമായ ഒരു അവസാനം തികച്ചും പരിപൂർണ്ണമാണ്.
