En vänlig läkare öppnar dörren och ropar mitt namn.
Jag går in på hans ljusa kontor.
Vi sätter oss vid hans skrivbord.
"Hur mår du i dag?" frågar han.
"Jag mår riktigt dåligt," svarar jag.
Läkaren tittar på mig.
"Var gör det ont?" frågar han vänligt.
Jag pekar på min hals.
"Min hals gör mycket ont," förklarar jag.
"Den är mycket torr."
Läkaren nickar och lyssnar uppmärksamt.
"Mitt huvud är också mycket tungt," fortsätter jag.
Jag rör vid mitt ansikte.
"Och mina ögon är helt röda."
De kliar hela tiden.
"Du borde absolut vila dig," säger han.
Han tänder en liten ficklampa.
"Låt mig titta närmare på dig," säger han.
