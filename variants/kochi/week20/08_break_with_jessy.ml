ഉച്ചയ്ക്ക് മുമ്പ് ഞങ്ങൾക്ക് ഒരു ചെറിയ ഇടവേള കിട്ടി.
ഞാനും ജെസ്സിയും പിന്നിലെ കൗണ്ടറിനടുത്ത് നിന്നു.
അവർ ഒരു കപ്പ് കാപ്പി എടുത്തു.
ഞാൻ ഒരു നാടൻ ചായയാണ് എടുത്തത്.
എനിക്ക് എന്റെ മെക്സിക്കൻ കാപ്പി വീട്ടിൽ ഉണ്ടാക്കാൻ ആണ് കൂടുതൽ ഇഷ്ടം.
"മായ, ഒന്നാമത്തെ ദിവസം എങ്ങനെയുണ്ട്?"
അവർ എന്നോട് ചോദിച്ചു.
"വളരെ നല്ലതാണ്, ജെസ്സി," ഞാൻ പറഞ്ഞു.
"തുടക്കത്തിൽ എനിക്ക് കുറച്ച് തെറ്റുകൾ പറ്റി."
"പക്ഷേ, എന്റെ രണ്ടാമത്തെ കാപ്പി ഞാൻ നന്നായി ഉണ്ടാക്കി."
"അതെ, എസ്പ്രെസ്സോ മെഷീൻ ഉപയോഗിക്കാൻ പഠിക്കുക എളുപ്പമല്ല," അവർ പറഞ്ഞു.
പിന്നെ ഞങ്ങൾ കൊച്ചിയെക്കുറിച്ച് സംസാരിച്ചു.
"നിങ്ങൾക്ക് കൊച്ചിയിൽ ഏറ്റവും ഇഷ്ടമുള്ള കാര്യം എന്താണ്?"
ജെസ്സി ചോദിച്ചു.
"എനിക്ക് ഇവിടുത്തെ മഴയും ഭക്ഷണവും വളരെ ഇഷ്ടമാണ്," ഞാൻ പറഞ്ഞു.
"ഞാൻ ഈ നഗരത്തിലെ ജീവിതം ആസ്വദിക്കാൻ പഠിക്കുകയാണ്."
"നിങ്ങൾ ഇപ്പോൾ ശരിക്കും ഒരു കൊച്ചിക്കാരിയായി," ജെസ്സി ചിരിച്ചുകൊണ്ട് പറഞ്ഞു.
ഞാൻ ചിരിച്ചു, പക്ഷേ ആ വാക്കുകൾ എന്റെ മനസ്സിൽ തങ്ങിനിന്നു.
പന്ത്രണ്ട് മണിക്ക് കഫേയിൽ വീണ്ടും ആളുകൾ വന്നു തുടങ്ങി.
ഞങ്ങൾ വീണ്ടും ജോലി ചെയ്യാൻ തുടങ്ങി.
