എന്റെ വാതിലിൽ ആരോ മുട്ടുന്നു.
അത് എന്റെ അയൽക്കാരിയായ നീനയാണ്.
"സുപ്രഭാതം മായാ, സുഖമാണോ?" അവൾ ചോദിക്കുന്നു.
"എനിക്ക് സുഖമാണ്, നന്ദി," ഞാൻ മറുപടി പറയുന്നു.
"ഇന്ന് ജോലിയിൽ എന്റെ ആദ്യത്തെ ദിവസമാണ്."
നീന വളരെ സ്നേഹത്തോടെ പുഞ്ചിരിക്കുന്നു.
"നല്ലത് വരട്ടെ!" അവൾ പറയുന്നു.
"ഓഫീസ് വളരെ ദൂരെയാണോ?" ഞാൻ ചോദിക്കുന്നു.
"ഇല്ല, അത് ദൂരെയല്ല," അവൾ മറുപടി പറയുന്നു.
"നിനക്ക് നാലാം നമ്പർ ബസ്സിൽ പോകാം," അവൾ പറയുന്നു.
സഹായത്തിന് ഞാൻ നന്ദി പറയുന്നു.
