എനിക്ക് പാചകത്തിന് കുറച്ച് സുഗന്ധവ്യഞ്ജനങ്ങൾ വേണം.
ഞാൻ ഒരു ചെറിയ കടയിലേക്ക് പോകുന്നു.
കടയിൽ നല്ല മണമുണ്ട്.
അവിടെ തുറന്ന ചാക്കുകളിൽ ഒരുപാട് സാധനങ്ങൾ ഉണ്ട്.
കടക്കാരൻ അവിടെ നിൽക്കുന്നു.
"എനിക്ക് നൂറ് ഗ്രാം കുരുമുളകും നൂറ് ഗ്രാം ഏലക്കയും വേണം," ഞാൻ പറയുന്നു.
അദ്ദേഹം അത് ഒരു ത്രാസിൽ തൂക്കുന്നു.
പിന്നെ അദ്ദേഹം അത് പേപ്പറിൽ പൊതിയുന്നു.
"ആകെ എത്ര രൂപ ആയി?" ഞാൻ ചോദിക്കുന്നു.
"ഇരുന്നൂറ്റി അറുപത് രൂപ ആയി," അദ്ദേഹം പറയുന്നു.
ഞാൻ എന്റെ പഴ്സ് എടുക്കുന്നു.
അദ്ദേഹം കൈ വീശുന്നു.
"ഇരുന്നൂറ്റി അമ്പത് രൂപ തരൂ," അദ്ദേഹം പറയുന്നു.
ഞാൻ ചിരിച്ചുകൊണ്ട് അദ്ദേഹത്തിന് പണം കൊടുക്കുന്നു.
അദ്ദേഹം എനിക്ക് ആ പൊതികൾ തരുന്നു.
ഞാൻ അത് എന്റെ ബാഗിൽ വെക്കുന്നു.
