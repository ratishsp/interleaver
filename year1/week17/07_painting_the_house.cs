Pokračovala jsem dál úzkou ulicí.
Zastavila jsem se před velmi starým domem.
Starší manželský pár byl venku na jarním slunci.
Muž stál na své zahradě.
Natíral svůj starý plot štětcem.
Nová barva byla světle žlutá.
Jeho žena seděla na dřevěné lavičce opodál.
Odpočívala a pila svůj teplý čaj.
Muž mě uviděl a na okamžik se zastavil.
Přátelsky zamával štětcem.
„Dobré ráno!“ řekl mi.
„Vaše zahrada vypadá nádherně,“ řekla jsem.
Jeho žena se na mě ze své lavičky usmála.
„Děkujeme, užíváme si jaro,“ odpověděla.
Muž klidně dál natíral svůj plot.
Ptáci zpívali v jejich zahradě.
Radostně jsem pokračovala v procházce.
