Stojím na autobusové zastávce.
Brzy pojedu autobusem.
Dívám se do ulice.
Po pěti minutách přijíždí autobus.
Je to dlouhý a žlutý autobus.
Autobus zastavuje přímo přede mnou.
Dveře se otevírají.
Nastupuji do autobusu.
Mám v ruce svou cestovní kartu.
Skenuji kartu u dveří.
Dnes je tu mnoho cestujících.
Hledám volné místo.
Nacházím dobré místo u okna.
Sedám si.
Dívám se ven na město.
Teď jedu autobusem na stanici metra.
