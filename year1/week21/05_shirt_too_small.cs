Později odpoledne jsem zpátky ve svém bytě.
Po nákupech jsem trochu unavená.
Sednu si na postel a vybalím tašky.
Nejdřív vyndám svou novou světle zelenou jarní bundu.
Pak vyndám tu modrou bavlněnou košili.
Těším se, až si ji vyzkouším.
Sundám si starý svetr a obléknu si košili.
Ale okamžitě cítím problém.
Ta košile je příliš malá.
Přes ramena mě hodně táhne.
Vlastně skoro nemůžu zvednout ruce.
V zrcadle vypadá košile příliš těsná.
Očividně potřebuji větší velikost.
Tento model je mnohem menší než moje běžná velikost.
Je trochu škoda, že jsem si ji v obchodě nevyzkoušela.
Ale fronta na zkušební kabinky byla prostě příliš dlouhá.
Znovu si tu malou košili sundám.
Pěkně ji složím a dám ji zpátky do tašky.
Naštěstí mám stále účtenku.
Můžu tu košili vyměnit za větší, až v pondělí skončím v práci.
