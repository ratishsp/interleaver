ഞാൻ ക്യാഷ് കൗണ്ടറിലേക്ക് നടന്നു പോകുന്നു.
ഒരു യുവാവ് കൗണ്ടറിന് പിന്നിൽ നിൽക്കുന്നു.
അവൻ കഫേയിലെ ഒരു ബാരിസ്റ്റയാണ്.
ഞാൻ അവനെ നോക്കി പുഞ്ചിരിക്കുന്നു.
അവൻ സൗഹാർദ്ദത്തോടെ തലയാട്ടുന്നു.
"ഹായ്," അവൻ പറയുന്നു.
"നിങ്ങൾക്ക് എന്താണ് വേണ്ടത്?" അവൻ ചോദിക്കുന്നു.
"ഹായ്," ഞാൻ മറുപടി പറയുന്നു.
"ദയവായി, എനിക്ക് ഒരു ബ്ലാക്ക് കോഫി വേണം."
"കൂടാതെ എനിക്ക് ഒരു സിനമൺ റോളും കൂടി കിട്ടുമോ?"
"തീർച്ചയായും," അവൻ പറയുന്നു.
"ഒരു ബ്ലാക്ക് കോഫിയും ഒരു സിനമൺ റോളും."
"നിങ്ങൾക്ക് ഇവിടെ ഇരിക്കണമെന്നുണ്ടോ?" അവൻ ചോദിക്കുന്നു.
"അതെ, ഞാൻ അവിടെ ഇരുന്നോളാം," ഞാൻ പറയുന്നു.
"ശരി," ബാരിസ്റ്റ പറയുന്നു.
"ഞാൻ ഇപ്പോൾ തന്നെ നിങ്ങളുടെ കോഫി തയ്യാറാക്കാം."
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
