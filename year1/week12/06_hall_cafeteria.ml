ഞങ്ങൾ ഹാളിലെ ചെറിയ കഫറ്റീരിയയിലേക്ക് നടന്നു കയറുന്നു.
ഞങ്ങൾ ഒരു ടേബിൾ കണ്ടെത്തുന്നു.
എനിക്ക് നല്ല ദാഹമുണ്ട്.
ഞങ്ങൾ തണുത്ത വെള്ളം കുടിച്ച് സംസാരിക്കുന്നു.
"ഇതൊരു വളരെ നല്ല ക്ലബ്ബാണ്," ഞാൻ പറയുന്നു.
"ഇത് കളിക്കാൻ പറ്റിയ നല്ലൊരു കായികവിനോദമാണ്," കാസ്പർ പറയുന്നു.
കാസ്പർ എന്നെ നോക്കുന്നു.
"നിനക്ക് വീണ്ടും ഇതിൽ പങ്കെടുക്കണമെന്നുണ്ടോ?" അവൻ ചോദിക്കുന്നു.
"അതെ, വളരെ ആഗ്രഹമുണ്ട്," ഞാൻ മറുപടി പറയുന്നു.
"എനിക്ക് എല്ലാ വ്യാഴാഴ്ചയും ഇവിടെ കളിക്കണം," ഞാൻ വിശദീകരിക്കുന്നു.
"അത് കൊള്ളാമല്ലോ," സാറ പറയുന്നു.
"ഞങ്ങൾ വ്യാഴാഴ്ചകളിൽ എപ്പോഴും ഇവിടെയാണ് കളിക്കാറുള്ളത്," കാസ്പർ പറയുന്നു.
"എങ്കിൽ നമുക്ക് അടുത്ത ആഴ്ച കാണാം," ഞാൻ സന്തോഷത്തോടെ പറയുന്നു.
ഞങ്ങൾ ബാക്കിയുള്ള വെള്ളം കുടിക്കുന്നു.
പുതിയ ആളുകളെ പരിചയപ്പെടുന്നത് വളരെ സന്തോഷമുള്ള കാര്യമാണ്.
