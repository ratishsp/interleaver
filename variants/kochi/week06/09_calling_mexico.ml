ഞാൻ ഭക്ഷണം കഴിക്കുന്നു.
പിന്നെ ഞാൻ സോഫയിൽ ഇരിക്കുന്നു.
ഞാൻ എന്റെ മൊബൈൽ ഫോൺ എടുക്കുന്നു.
ഞാൻ മെക്സിക്കോയിലുള്ള എന്റെ കുടുംബത്തെ വിളിക്കുന്നു.
ഇതൊരു വീഡിയോ കോൾ ആണ്.
എന്റെ അനിയത്തി സോഫിയ ഫോൺ എടുക്കുന്നു.
അവൾ ഞങ്ങളുടെ നായ ലോലയുമായി കളിക്കുകയാണ്.
ലോല മുറിയിൽ ഓടുകയാണ്.
സോഫിയ ഉറക്കെ ചിരിക്കുകയാണ്.
ഞാൻ അവരെ സ്ക്രീനിൽ കാണുന്നു.
ഞാൻ സന്തോഷത്തോടെ ചിരിക്കുന്നു.
"ചേച്ചീ, സുഖമാണോ?" സോഫിയ ചോദിക്കുന്നു.
"എനിക്ക് സുഖമാണ്," ഞാൻ പറയുന്നു.
"ചേച്ചി ഇപ്പോൾ ജോലി ചെയ്യുകയാണോ?" അവൾ ചോദിക്കുന്നു.
"അല്ല, ഞാൻ വിശ്രമിക്കുകയാണ്," ഞാൻ പറയുന്നു.
അപ്പോൾ എന്റെ അമ്മ ആ മുറിയിലേക്ക് വരുന്നു.
അവർ സ്ക്രീനിലേക്ക് നോക്കുകയാണ്.
"ഹലോ മായാ," അമ്മ പറയുന്നു.
എനിക്ക് ഇപ്പോൾ വളരെ സന്തോഷമുണ്ട്.
