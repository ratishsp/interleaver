Sedíme v zasedací místnosti.
Je čas na naši krátkou ranní poradu.
Rozhlížím se po svých kolezích.
Dnes je pro mě výjimečný den.
Postavím se.
Jsem softwarová inženýrka a budu prezentovat svou část projektu.
Trochu se mi třesou ruce.
Ale dobře jsem se připravila.
„Dobré ráno,“ říkám nahlas.
„Pracovala jsem na technickém plánu,“ říkám jim.
„Přečetla jsem všechny dokumenty.“
„A napsala jsem si poznámky k úkolům na tento týden.“
Vysvětluji plán celému týmu.
Vlastně není těžké mluvit o technice.
Peter sedí naproti mně.
Cítím, že se víc uvolňuji.
Poslouchá a přikyvuje.
Dokončuji svou prezentaci a ostatní se usmívají.
Moje první prezentace v práci dopadla dobře.
