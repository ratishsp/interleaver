Jdu k pokladně se svou novou bundou.
Po cestě vidím opravdu hezkou košili.
Je světle modrá a vyrobená z měkké bavlny.
Vlastně potřebuji novou košili do kanceláře.
Sundávám košili z ramínka.
Podívám se směrem ke zkušebním kabinkám.
V obchodě je dnes opravdu hodně lidí.
Fronta na zkušební kabinky je velmi dlouhá.
Nechce se mi dlouho čekat.
Proto se rozhoduji, že si ji nejdřív nebudu zkoušet.
Obvykle nosím velikost medium.
Zkontroluji velikost košile.
Myslím si však, že vypadá trochu malá.
Ale větší velikost je asi příliš velká.
A menší velikost bude určitě příliš těsná.
Takže si prostě vezmu svou běžnou velikost.
Přehodím si košili přes ruku společně s bundou.
Doufám, že mi doma bude košile sedět.
