ഉച്ചസമയമാണ്.
ഞാനും പ്രകാശും ഓഫീസിൽ നിന്ന് പുറത്തിറങ്ങുന്നു.
ഓഫീസിൽ എസി ഉണ്ട്.
അതുകൊണ്ട് അവിടെ നല്ല തണുപ്പാണ്.
ഞങ്ങൾ പുറത്തേക്ക് വരുന്നു.
പെട്ടെന്ന് ഒരു ചൂട് കാറ്റ് അടിക്കുന്നു.
പ്രകാശ് ആകാശത്തേക്ക് നോക്കുന്നു.
"മായേ, ഇന്ന് വല്ലാത്ത ചൂടാണ്," അദ്ദേഹം പറയുന്നു.
ഞാൻ അത് സമ്മതിക്കുന്നു.
"അതെ, നല്ല ചൂടാണ്," ഞാൻ പറയുന്നു.
"ഇന്ന് മഴ പെയ്യുമോ?" പ്രകാശ് എന്നോട് ചോദിക്കുന്നു.
"വെതർ ആപ്പ് പറയുന്നു, വൈകുന്നേരം മഴ പെയ്യും," ഞാൻ മറുപടി പറയുന്നു.
പ്രകാശ് ചിരിക്കുന്നു.
"ഈ വെയിൽ നോക്കൂ!" അദ്ദേഹം പറയുന്നു.
"ഇന്ന് മഴ പെയ്യുകയില്ല."
എനിക്കും അങ്ങനെ തോന്നുന്നു.
ഞങ്ങൾ കാന്റീനിലേക്ക് വേഗത്തിൽ നടക്കുന്നു.
ഈ ചൂടിൽ എനിക്ക് തണുത്ത വെള്ളം കുടിക്കണം.
