Jest sobota rano.
Budzę się wcześnie i znów czuję się naprawdę dobrze.
W piątek przez cały dzień odpoczywałam w domu.
Łagodne lekarstwo zadziałało idealnie.
Moje oczy są czyste i wcale nie swędzą.
Nie boli mnie głowa, a gardło już mnie nie boli.
Wstaję z łóżka i otwieram okno na łagodne, wiosenne powietrze.
To wspaniałe móc oddychać bez problemów.
Idę do kuchni, żeby zrobić porządne śniadanie.
Jem chleb z serem i piję duży kubek gorącej kawy.
Świeci słońce, więc myślę, że powinnam pójść na spacer do parku.
Zakładam wiosenną kurtkę i schodzę na ulicę.
Drzewa są teraz całkowicie zielone, a wielu ludzi cieszy się pogodą.
To naprawdę nudne czuć się źle, kiedy w końcu jest wiosna.
Ale dzisiaj czuję, że moje nogi są silne, i odzyskałam energię.
Idę na powolny spacer wokół małego jeziora w parku.
Na szczęście jestem już całkowicie zdrowa i jestem gotowa cieszyć się weekendem.
