Jestem teraz w kawiarni.
Jest tu bardzo ciepło.
Zdejmuję moją grubą zimową kurtkę.
Jest ciężka.
Znajduję haczyk na ścianie.
Wieszam kurtkę na haczyku.
Zdejmuję też szalik i rękawiczki.
Kawiarnia jest mała i przytulna.
Szukam dobrego miejsca.
Przy oknie jest mały stolik.
Stolik stoi obok kaloryfera.
Podchodzę do stolika.
Siadam na krześle.
Moje dłonie nadal są zimne.
Pocieram je o siebie.
Moje dłonie stają się cieplejsze.
To fantastyczne uczucie.
Teraz jest mi już prawie ciepło.
Jestem głodna i spragniona.
Chciałabym teraz coś zamówić.
