ഞാൻ ചെറിയ പച്ചക്കറി കടയിൽ ആണ്.
അവിടെ പല പച്ചക്കറികളും ഉണ്ട്.
ഞാൻ പെട്ടെന്ന് ഒരു പുതിയ പച്ചക്കറി കാണുന്നു.
അത് വളരെ നീളമുള്ളതാണ്.
അതിന് ഇളം പച്ച നിറമാണ്.
അതിൽ വെളുത്ത വരകൾ ഉണ്ട്.
എനിക്ക് ആ പച്ചക്കറി അറിയില്ല.
ഞാൻ കടക്കാരനെ നോക്കുന്നു.
"ഇത് എന്താണ്?" ഞാൻ അദ്ദേഹത്തോട് ചോദിക്കുന്നു.
അദ്ദേഹം ചിരിക്കുന്നു.
"ഇത് പടവലങ്ങ ആണ്," അദ്ദേഹം പറയുന്നു.
"പടവലങ്ങ," ഞാൻ പതിയെ പറയുന്നു.
എനിക്ക് പുതിയ പച്ചക്കറികൾ ഇഷ്ടമാണ്.
"എനിക്ക് ഇത് വേണം," ഞാൻ പറയുന്നു.
ഞാൻ ഒരു പടവലങ്ങ എടുക്കുന്നു.
ഞാൻ അത് അദ്ദേഹത്തിന് കൊടുക്കുന്നു.
