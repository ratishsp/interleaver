Nakonec vyprávím své mamince o zimě.
Počasí se najednou změnilo.
Foukal vítr a vzduch byl ledový.
Chlad mě cestou do práce štípal do tváří.
Potřebovala jsem nějaké teplé oblečení.
Po práci jsem spěchala do velkého obchodu.
Uvnitř bylo naštěstí krásně teplo.
V obchodě pracovala příjemná prodavačka.
Přišla ke mně a usmála se.
Zeptala se: „Hledáte něco konkrétního?“
Odpověděla jsem: „Ano, prosím, chtěla bych si koupit vaši nejteplejší zimní bundu.“
Našla pro mě silnou, tmavě modrou bundu.
Hned jsem si ji vyzkoušela.
Byla úžasně teplá a perfektně mi seděla.
Vzala jsem si také měkkou modrou šálu.
Odnesla jsem věci k pokladně a zaplatila.
Oblečení stálo tisíc pět set korun.
Bylo to trochu drahé, ale naprosto nezbytné.
Moje maminka tleská.
Je ráda, že mi bylo konečně teplo.
