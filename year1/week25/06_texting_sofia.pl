Siedzę w muzealnej kawiarni i robię sobie przerwę.
Piję filiżankę kawy i relaksuję się.
Wyciągam z torby niebieskie talerze.
Te talerze idealnie pasują do mojej kuchni.
Robię im zdjęcie telefonem.
Wysyłam zdjęcie do mojej siostry, Sofíi.
„Spójrz tylko na te piękne talerze” – piszę.
„Znalazłam je na targu godzinę temu”.
Sofía odpowiada mi niemal natychmiast.
Odsyła mi stare zdjęcie.
Ta wiadomość bardzo mnie cieszy.
Zdjęcie przedstawia nas dwie na dużym pchlim targu w Meksyku.
„Pamiętasz ten targ?”
Pyta Sofía w kolejnej wiadomości.
„Byłyśmy tam dokładnie dwa lata temu!” – pisze.
Patrzę na nasze radosne twarze na zdjęciu.
Wydaje się, że to było bardzo dawno temu.
Dwa lata temu wciąż mieszkałam w Meksyku.
Uśmiecham się i odpisuję radosną wiadomość.
