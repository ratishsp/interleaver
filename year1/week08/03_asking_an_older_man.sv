Jag kommer fram till ett stort torg.
Det är många människor.
Men jag ser inte vattnet.
Jag letar efter hamnen.
Jag ser en äldre man på trottoaren.
Jag stannar honom.
"Ursäkta," säger jag.
"Var är hamnen?"
Den äldre mannen nickar.
Han pekar framåt.
"Gå rakt över torget," säger han.
"Gå förbi museet."
"Och sväng till höger."
Jag tittar ut över torget.
Jag ser en stor byggnad.
Det är museet.
"Tack så mycket," säger jag.
"Varsågod," svarar han.
Jag går vidare.
