ആ ആദ്യത്തെ ദിവസങ്ങളെക്കുറിച്ച് ഓർത്ത് ഞങ്ങൾ ചിരിക്കുന്നു.
ജനുവരിയിൽ ഇവിടെ എല്ലാം പുതിയതായിരുന്നു.
"ഇപ്പോൾ കൊച്ചി എൻ്റെ വീടാണ്," ഞാൻ പറഞ്ഞു.
"നിങ്ങൾ ഫ്ലാറ്റിലേക്ക് പോകുകയാണോ?"
സാറ ചോദിച്ചു.
"അതെ, പോകുകയാണ്," ഞാൻ മറുപടി പറഞ്ഞു.
"ശരി മായ, അടുത്ത ആഴ്ച കാണാം," കിരൺ പറഞ്ഞു.
ഞാൻ അവർക്ക് നേരെ കൈ വീശുന്നു.
ഞാൻ പാർക്കിംഗ് ഏരിയയിലേക്ക് നടക്കുന്നു.
എൻ്റെ സൈക്കിൾ അവിടെയുണ്ട്.
ഞാൻ ബാഗിൽ നിന്ന് താക്കോൽ എടുക്കുന്നു.
ഞാൻ സൈക്കിളിൻ്റെ ലോക്ക് തുറക്കുന്നു.
ഇതൊരു ചൂടുള്ള ഏപ്രിൽ വൈകുന്നേരമാണ്.
ഞാൻ മെല്ലെ സൈക്കിൾ ഓടിക്കുന്നു.
കഴിഞ്ഞ ആഴ്ച ഞാൻ ഈ വഴിയിലൂടെ നടന്നു.
എന്നാൽ ഇന്ന് ഞാൻ സൈക്കിളിലാണ്.
റോഡുകൾ ഇപ്പോൾ വളരെ ശാന്തമാണ്.
യാത്രക്കിടയിൽ ഞാൻ എൻ്റെ കുടുംബത്തെക്കുറിച്ച് ഓർത്തു.
ഞാൻ വേഗം എൻ്റെ ഫ്ലാറ്റിന് മുന്നിൽ എത്തി.
ഇന്ന് ശരിക്കും ഒരു നല്ല ദിവസമായിരുന്നു.
