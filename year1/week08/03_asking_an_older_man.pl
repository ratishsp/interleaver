Docieram na duży plac.
Jest dużo ludzi.
Ale nie widzę wody.
Szukam portu.
Widzę starszego mężczyznę na chodniku.
Zatrzymuję go.
"Przepraszam" - mówię.
"Gdzie jest port?"
Starszy mężczyzna kiwa głową.
Wskazuje przed siebie.
"Proszę iść prosto przez plac" - mówi.
"Minąć muzeum."
"I skręcić w prawo."
Spoglądam na drugą stronę placu.
Widzę duży budynek.
To muzeum.
"Bardzo dziękuję" - mówię.
"Proszę bardzo" - odpowiada.
Idę dalej.
