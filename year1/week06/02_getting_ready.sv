I sovrummet öppnar jag min garderob.
Jag tittar på mina kläder.
Jag väljer en blå skjorta och svarta byxor.
Sedan klär jag på mig.
Jag kammar mitt hår framför spegeln.
Nu går jag ut i köket.
Jag är hungrig.
Jag hittar en tallrik och en kopp.
Jag gör en snabb frukost.
I dag äter jag bröd med ost.
Jag häller kaffe i koppen.
Kaffet är svart och starkt.
Jag sätter mig vid bordet.
Här äter jag min mat.
Det smakar gott.
Jag dricker mitt kaffe.
Till sist tar jag min väska och min jacka.
Jag låser dörren och går ut.
