Jag går bort mot kassan med min nya jacka.
På vägen ser jag en riktigt snygg skjorta.
Den är ljusblå och gjord av mjuk bomull.
Jag behöver faktiskt en ny skjorta till kontoret.
Jag tar ner skjortan från galgen.
Jag tittar bort mot provrummen.
Det är riktigt många människor i butiken i dag.
Kön till provrummen är väldigt lång.
Jag vill inte vänta länge.
Därför bestämmer jag mig för att inte prova den först.
Jag brukar normalt ha storlek medium.
Jag kollar skjortans storlek.
Jag tycker dock att den ser lite liten ut.
Men en större storlek är nog för stor.
Och en mindre storlek kommer helt säkert att vara för trång.
Så jag tar bara min normala storlek.
Jag lägger skjortan över armen tillsammans med jackan.
Jag hoppas att skjortan passar därhemma.
