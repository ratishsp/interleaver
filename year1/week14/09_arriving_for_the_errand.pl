Łódź dopływa na drugi brzeg.
Tramwaj wodny zatrzymuje się przy małym pomoście.
Wysiadam z łodzi.
Podróż łodzią dobiegła końca.
Sprawdzam mapę w telefonie.
Idę do małego kiosku.
Kiosk znajduje się tam na rogu.
Idę w górę ulicy.
Widzę sklep na końcu drogi.
Otwieram drzwi i wchodzę do środka.
Młody mężczyzna stoi za kasą.
"Cześć" – mówi uprzejmie.
"Cześć, przyszłam odebrać paczkę" – mówię.
Mężczyzna kiwa głową i uśmiecha się.
Pyta o moje imię.
"Mam na imię Maya" – odpowiadam.
Znajduje duże pudełko na półce.
Podaje mi paczkę.
"Bardzo dziękuję za pomoc" – mówię.
Teraz udaję się w długą drogę powrotną do domu z moją paczką.
