ഞാൻ മസാലകളുടെ ഭാഗത്ത് എത്തുന്നു.
എനിക്ക് കുരുമുളക് വേണം.
ഇവിടെ ഒരുപാട് മസാലകൾ ഉണ്ട്.
ഞാൻ ഷെൽഫുകൾ നോക്കുന്നു.
പക്ഷേ, ഞാൻ കുരുമുളക് കാണുന്നില്ല.
ഞാൻ അവിടെ ഒരു സഹായിയെ കാണുന്നു.
ഞാൻ അദ്ദേഹത്തോട് ചോദിക്കുന്നു.
"ക്ഷമിക്കണം, കുരുമുളക് എവിടെയാണ്?"
അദ്ദേഹം എന്നെ നോക്കി ചിരിക്കുന്നു.
"അത് ആ ഷെൽഫിൽ ഉണ്ട്," അദ്ദേഹം പറയുന്നു.
അദ്ദേഹം ഒരു പ്രത്യേക പാക്കറ്റ് കാണിക്കുന്നു.
"എനിക്ക് ഈ ബ്രാൻഡ് ഇഷ്ടമാണ്," അദ്ദേഹം പറയുന്നു.
"ഇത് വളരെ നല്ല കുരുമുളക് ആണ്."
"നന്ദി," ഞാൻ അദ്ദേഹത്തോട് പറയുന്നു.
ഞാൻ ആ പാക്കറ്റ് എടുക്കുന്നു.
ഞാൻ അത് കാർട്ടിൽ വെക്കുന്നു.
