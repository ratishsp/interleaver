ഞാൻ ഓഫീസിൽ നിന്ന് പുറത്തിറങ്ങുന്നു.
പുറത്ത് നല്ല ഇരുട്ടാണ്.
പെട്ടെന്ന് മഴ തുടങ്ങുന്നു.
വലിയ മഴത്തുള്ളികൾ താഴെ വീഴുന്നു.
വളരെ വേഗം മഴ ശക്തമാകുന്നു.
ഇപ്പോൾ നല്ല മഴ പെയ്യുന്നു.
ഞാൻ ബാഗിൽ നിന്ന് എൻ്റെ കുട എടുക്കുന്നു.
ഞാൻ വേഗം കുട തുറക്കുന്നു.
അപ്പോൾ വലിയ കാറ്റ് വീശുന്നു.
കാറ്റിൽ എൻ്റെ കുട അനങ്ങുന്നു.
മഴയും കാറ്റും വളരെ ശക്തമാണ്.
ഇപ്പോൾ വലിയ ഇടിയും ഉണ്ട്.
മുന്നോട്ട് നടക്കാൻ വളരെ ബുദ്ധിമുട്ടാണ്.
മഴവെള്ളം എൻ്റെ ദേഹത്ത് വീഴുന്നു.
എൻ്റെ വസ്ത്രങ്ങൾ നനയുന്നു.
ഞാൻ വളരെ പതുക്കെ നടക്കുന്നു.
മഴ ഇനിയും കൂടും.
ഇവിടെ ഈ കുട മതിയാകില്ല.
ഞാൻ ഒരു ഓട്ടോ വിളിക്കും.
