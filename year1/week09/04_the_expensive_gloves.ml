ഇന്ന് തണുത്ത കാറ്റാണ് വീശുന്നത്.
എൻ്റെ കൈകൾക്ക് നല്ല തണുപ്പുണ്ട്.
ചൂടുള്ള വസ്ത്രങ്ങളുള്ള ഒരു വലിയ സ്റ്റാൾ ഞാൻ കാണുന്നു.
ഞാൻ കച്ചവടക്കാരൻ്റെ അടുത്തേക്ക് നടക്കുന്നു.
അയാളുടെ മേശപ്പുറത്ത് ചൂടുള്ള നിരവധി സാധനങ്ങളുണ്ട്.
ഞാൻ കട്ടിയുള്ള ഒരു ജോടി കമ്പിളി കയ്യുറകൾ കയ്യിലെടുക്കുന്നു.
അവ വളരെ മൃദുവാണ്.
"ഈ കയ്യുറകൾക്ക് എത്രയാണ് വില?" ഞാൻ ചോദിക്കുന്നു.
"അവയ്ക്ക് ഇരുന്നൂറ് ക്രോണറാണ് വില," കച്ചവടക്കാരൻ മറുപടി പറയുന്നു.
ഞാൻ വീണ്ടും ആ കയ്യുറകളിലേക്ക് നോക്കുന്നു.
ഇരുന്നൂറ് ക്രോണർ എന്നത് ഉയർന്നൊരു വിലയാണ്.
എന്നെ സംബന്ധിച്ചിടത്തോളം ഇത് വളരെ വിലകൂടിയതാണ്.
ഞാൻ കയ്യുറകൾ തിരികെ മേശപ്പുറത്ത് വെക്കുന്നു.
"വേണ്ട, നന്ദി," ഞാൻ വളരെ മര്യാദയോടെ പറയുന്നു.
"നല്ലൊരു ദിവസം ആശംസിക്കുന്നു."
കച്ചവടക്കാരൻ തലകുലുക്കി ചിരിക്കുന്നു.
"നിങ്ങൾക്കും," അയാൾ പറയുന്നു.
ഞാൻ മാർക്കറ്റിലൂടെ നടത്തം തുടരുന്നു.
