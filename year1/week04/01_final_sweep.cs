V Kodani je leden.
Stojím ve svém dočasném pokoji.
Dnes se stěhuji do nového bytu.
Je ve stejné budově.
Můj velký kufr stojí na podlaze.
Zavírám ho.
Naposledy se rozhlížím po pokoji.
Dívám se pod malou postel.
Pod postelí leží kniha.
Je z Mexika.
Dávám knihu do své tašky.
Otevírám skříň.
Ve skříni stojí pár bot.
Beru ty boty.
Teď ve skříni nic není.
Jdu k psacímu stolu u okna.
Na stole leží kabel.
Beru ten kabel.
Dávám kabel do své tašky.
Beru své dvě tašky.
Zhasínám světlo a zavírám dveře.
