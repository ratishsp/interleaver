പല ഡാനിഷ്കാരും അവരുടെ ഒഴിവുസമയങ്ങളിൽ സന്നദ്ധപ്രവർത്തനം നടത്താറുണ്ടെന്ന് ഞാൻ കേട്ടിട്ടുണ്ട്.
എനിക്ക് ആ ആശയം ഇഷ്ടപ്പെട്ടു.
എനിക്ക് ഡാനിഷ് കുറച്ചുകൂടി നന്നായി സംസാരിക്കാൻ പഠിക്കണം, പുതിയ ആളുകളെ പരിചയപ്പെടുകയും വേണം.
ഒരു ദിവസം വൈകുന്നേരം, ഞാൻ എന്റെ കമ്പ്യൂട്ടറുമായി ഇരിക്കുകയാണ്.
സന്നദ്ധപ്രവർത്തനത്തിനുള്ള ഒരു വെബ്സൈറ്റ് ഞാൻ കണ്ടെത്തുന്നു.
ആ സൈറ്റിലെ ആദ്യത്തെ മൂന്ന് പരസ്യങ്ങൾ ഞാൻ വായിക്കുന്നു.
ആദ്യത്തെ പരസ്യം ഒരു സ്പോർട്സ് ക്ലബ്ബിൽ നിന്നാണ്.
എന്നാൽ അവർക്ക് വ്യാഴാഴ്ച വൈകുന്നേരങ്ങളിലാണ് സഹായം വേണ്ടത്, ആ സമയത്ത് ഞാൻ ബാഡ്മിന്റൺ കളിക്കാറുണ്ട്.
രണ്ടാമത്തെ പരസ്യം ഒരു മ്യൂസിയത്തിൽ നിന്നാണ്.
അവർക്ക് ബുധനാഴ്ച വൈകുന്നേരങ്ങളിലാണ് ഒരാളെ ആവശ്യമുള്ളത്, എന്നാൽ ആ സമയത്ത് ഞാൻ വ്യായാമം ചെയ്യാറുണ്ട്.
പിന്നെ ഞാൻ മൂന്നാമത്തെ പരസ്യം നോക്കുന്നു.
അത് എനിക്ക് നേരത്തെ അറിയാവുന്ന ചെറിയ കഫേയിൽ നിന്നാണ്.
അവർക്ക് ശനിയാഴ്ച രാവിലത്തേക്കാണ് ആളുകളെ വേണ്ടത്.
അത് എനിക്ക് തികച്ചും അനുയോജ്യമാണ്.
എന്റെ പേരും ഇമെയിൽ വിലാസവും നൽകി ഞാൻ ഒരു ചെറിയ ഫോം പൂരിപ്പിക്കുന്നു.
എന്റെ ഫോൺ നമ്പറും ഞാൻ എഴുതുന്നു: പന്ത്രണ്ട്, മുപ്പത്തിനാല്, അൻപത്തിയാറ്, എഴുപത്തിയെട്ട്.
അവസാനം, ഞാൻ സെൻഡ് അമർത്തുന്നു.
ഇതിനുമുമ്പ് ഞാൻ ഒരിക്കലും ഒരു കഫേയിൽ ജോലി ചെയ്തിട്ടില്ല, പക്ഷേ അത് പഠിക്കാൻ ഞാൻ തയ്യാറാണ്.
