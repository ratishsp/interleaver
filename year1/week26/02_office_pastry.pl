Siedzę przy moim biurku w biurze.
Przyszłam dzisiaj wcześnie do pracy.
Pracuję tu już od pół roku.
Nagle Peter i Eva podchodzą do mojego biurka.
Peter niesie małe ciasto z jedną świeczką.
„Wszystkiego najlepszego, Maya!” – mówią chórem.
Jestem naprawdę szczęśliwa i bardzo zaskoczona.
„Bardzo dziękuję” – mówię do nich.
Eva uśmiecha się szeroko.
„Kupiliśmy ciasto w piekarni dziś rano” – wyjaśnia.
„Tak, a ja zrobiłem dla nas kawę” – dodaje Peter.
Stawia duży kubek kawy na moim stole.
„Jesteście po prostu tacy kochani” – mówię.
„Kiedy pracowałam w Meksyku, rzadko dostawaliśmy rano ciasto.”
Peter i Eva przysuwają dwa krzesła do biurka.
Jemy razem ciasto i to fantastyczny początek mojego dnia.
