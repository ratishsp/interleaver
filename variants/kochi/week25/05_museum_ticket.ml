ഞാൻ മ്യൂസിയത്തിന്റെ അകത്തേക്ക് കയറുന്നു.
ഈ ലോബിയിൽ ഒട്ടും നനവില്ല.
ഞാൻ എന്റെ കുട അടച്ച് അതിലെ വെള്ളം കുടഞ്ഞുകളയുന്നു.
കുറച്ച് മിനിറ്റുകൾക്ക് മുമ്പ് ഞാൻ പുറത്ത് വലിയ മഴയിലായിരുന്നു.
ഞാൻ ടിക്കറ്റ് കൗണ്ടറിലേക്ക് നടക്കുന്നു.
അവിടെ ഒരു ക്ലാർക്ക് ഇരിക്കുന്നുണ്ട്.
അദ്ദേഹം എന്നെ നോക്കി സന്തോഷത്തോടെ ചിരിക്കുന്നു.
"ഒരു ടിക്കറ്റ് വേണോ?" അദ്ദേഹം ചോദിക്കുന്നു.
"അതെ, ഒരു ടിക്കറ്റ് വേണം," ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ അദ്ദേഹത്തിന് അമ്പത് രൂപ കൊടുക്കുന്നു.
അദ്ദേഹം എനിക്ക് ഒരു ടിക്കറ്റും ഒരു പുസ്തകവും തരുന്നു.
"അതെന്താണ്?" ഞാൻ ചോദിക്കുന്നു.
"അത് ഈ മ്യൂസിയത്തെക്കുറിച്ചുള്ള ഒരു ബ്രോഷറാണ്," അദ്ദേഹം പറയുന്നു.
"പ്രധാന എക്സിബിറ്റ് ഹാൾ എവിടെയാണ്?" ഞാൻ ചോദിക്കുന്നു.
"ആ ഹാൾ താഴത്തെ നിലയിലാണ്," അദ്ദേഹം മറുപടി പറയുന്നു.
ഞാൻ അദ്ദേഹത്തോട് നന്ദി പറയുന്നു.
എന്നിട്ട് ഞാൻ ആ ബ്രോഷർ തുറക്കുന്നു.
ഞാൻ താഴത്തെ നിലയിലുള്ള പ്രധാന ഹാളിലേക്ക് നടക്കുന്നു.
