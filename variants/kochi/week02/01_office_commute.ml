ഇന്ന് എന്റെ ആദ്യത്തെ ഓഫീസ് ദിവസമാണ്.
ഞാൻ അപ്പാർട്ട്മെന്റിൽ നിന്ന് പുറത്തേക്ക് ഇറങ്ങുന്നു.
കൊച്ചിയിൽ ഇത് ജനുവരി മാസമാണ്.
വളരെ നല്ല പ്രഭാതമാണ്.
ഞാൻ ഓഫീസിലേക്ക് പോകുന്നു.
ഞാൻ ഒരു ഓട്ടോറിക്ഷ വിളിക്കുന്നു.
ഓട്ടോറിക്ഷ വേഗം വരുന്നു.
ഞാൻ വണ്ടിയിൽ കയറുന്നു.
ഞങ്ങൾ ഇൻഫോപാർക്കിലേക്ക് പോകുന്നു.
കൊച്ചിയിലെ റോഡുകളിൽ വലിയ തിരക്കാണ്.
ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
ഞാൻ ഒരുപാട് കടകൾ കാണുന്നു.
എനിക്ക് കൊച്ചി നഗരം വളരെ ഇഷ്ടമാണ്.
എന്റെ ബാഗിൽ ലാപ്ടോപ്പ് ഉണ്ട്.
എനിക്ക് വലിയ സന്തോഷം ഉണ്ട്.
ഓട്ടോറിക്ഷ ഓഫീസിന്റെ മുന്നിൽ എത്തുന്നു.
ഞാൻ ഡ്രൈവർക്ക് എൺപത് രൂപ കൊടുക്കുന്നു.
ഞാൻ സോഫ്റ്റ്‌വെയർ കമ്പനിയിലേക്ക് നടക്കുന്നു.
