ഞാൻ സൈക്കിളിൽ വീട്ടിൽ എത്തി.
ഞാൻ വേഗം രാത്രി ഭക്ഷണം കഴിച്ചു.
ഇപ്പോൾ ഞാൻ മുറിയിലെ കസേരയിൽ ഇരിക്കുകയാണ്.
ഞാൻ എന്റെ ഫോൺ എടുത്തു.
ഞാൻ മെക്സിക്കോയിലേക്ക് ഒരു വീഡിയോ കോൾ ചെയ്തു.
അമ്മ ഫോൺ എടുത്തു.
അമ്മ എന്നെ നോക്കി സന്തോഷത്തോടെ ചിരിച്ചു.
"ഹലോ മായ, നിനക്ക് സുഖമാണോ?" അമ്മ ചോദിച്ചു.
"എനിക്ക് സുഖമാണ്, അമ്മേ."
"അമ്മ പ്രഭാതഭക്ഷണം കഴിച്ചോ?"
ഞാൻ ചോദിച്ചു.
"ഉവ്വ്, ഞാൻ ഒരു മണിക്കൂർ മുൻപ് കഴിച്ചു," അമ്മ പറഞ്ഞു.
അപ്പോൾ ഞാൻ സ്ക്രീനിൽ ഞങ്ങളുടെ നായയെ കണ്ടു.
ലോല പിന്നിലെ സോഫയിൽ ഉറങ്ങുകയാണ്.
"നോക്കൂ, ലോല നന്നായി ഉറങ്ങുകയാണല്ലോ," ഞാൻ ചിരിച്ചുകൊണ്ട് പറഞ്ഞു.
"അതെ, അവൾ ഇന്ന് രാവിലെ ഒരുപാട് നടന്നു," അമ്മ പറഞ്ഞു.
"അതുകൊണ്ട് അവൾക്ക് നല്ല ക്ഷീണമുണ്ട്."
"നിന്റെ ഇന്നത്തെ ദിവസം എങ്ങനെയുണ്ടായിരുന്നു?" അമ്മ ചോദിച്ചു.
"ഇന്ന് നല്ലൊരു ദിവസമായിരുന്നു."
"ഞാൻ വൈകുന്നേരം ബാഡ്മിന്റൺ കളിച്ചു."
"അവിടെ വെച്ച് എന്റെ കൂട്ടുകാരെ കണ്ടു."
"ഞങ്ങൾ ഒരുപാട് സംസാരിച്ചു."
"നിങ്ങൾ എന്തൊക്കെയാണ് സംസാരിച്ചത്?" അമ്മ ചോദിച്ചു.
"ജനുവരിയിൽ ഞാൻ കൊച്ചിയിൽ വന്ന കഥയാണ് ഞാൻ അവരോട് പറഞ്ഞത്," ഞാൻ മറുപടി നൽകി.
