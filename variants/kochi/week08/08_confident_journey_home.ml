വൈകുന്നേരം ആകുന്നു.
ഞാൻ ഫ്ലാറ്റിലേക്ക് മടങ്ങുന്നു.
ഞാൻ ബസ് സ്റ്റോപ്പിലേക്ക് നടക്കുന്നു.
വഴി എനിക്ക് ഇപ്പോൾ അറിയാം.
ആരോടും ഞാൻ വഴി ചോദിക്കുന്നില്ല.
"നേരെ പോകൂ, എന്നിട്ട് ഇടത്തോട്ട് തിരിയൂ."
ഞാൻ സ്വയം പറയുന്നു.
ഞാൻ വഴിയിലൂടെ നേരെ നടക്കുന്നു.
എന്നിട്ട് ഇടത്തോട്ട് തിരിയുന്നു.
അത് പ്രധാന റോഡ് ആണ്.
അവിടെ വലിയ ബസ് സ്റ്റോപ്പ് ഉണ്ട്.
എന്റെ ബസ് വരുന്നു.
ഞാൻ ബസ്സിൽ കയറുന്നു.
ഞാൻ ജാലകത്തിലൂടെ പുറത്തേക്ക് നോക്കുന്നു.
ബസ് കൊച്ചി നഗരത്തിലൂടെ പോകുന്നു.
ഞാൻ എന്റെ ഫ്ലാറ്റിനെക്കുറിച്ച് ചിന്തിക്കുന്നു.
നഗരത്തിൽ നിന്ന് ഫ്ലാറ്റിലേക്കുള്ള വഴി ഇപ്പോൾ വ്യക്തമാണ്.
എനിക്ക് വളരെ സന്തോഷം ഉണ്ട്.
