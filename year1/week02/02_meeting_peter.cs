Teď jsem uvnitř nové kanceláře.
Je to velká a světlá místnost.
U dveří stojí přátelský muž.
Usmívá se na mě.
„Vítej!“ říká.
„Jmenuji se Peter.“
Podávám mu ruku.
„Ahoj Petere, jmenuji se Maya,“ říkám.
Peter je kolega.
Procházíme společně kanceláří.
„Tady máš stůl,“ říká Peter.
Stůl má číslo šestnáct.
„A máš počítač,“ říká.
Dává mi nový notebook.
Dívám se na své nové místo.
Mám židli a velký monitor.
„Moc děkuji, Petere,“ říkám.
Jsem připravená na svůj první pracovní den.
