"Välkommen, Maya," säger han.
"Har du ditt pass?" frågar han.
"Ja, jag har mitt pass och mina papper," svarar jag.
"Varsågod," säger jag.
Han tittar på papperen.
Han skriver på sin dator.
Jag får ett danskt personnummer.
Numret är privat och mycket viktigt.
Han ger mig ett nytt kort.
"Varsågod, här är ditt kort," säger han.
"Nu är du registrerad i Danmark."
