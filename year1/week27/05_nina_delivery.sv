Jag lägger min telefon på bordet och slappnar av.
Plötsligt knackar det snabbt på min dörr.
Det avbryter mina tankar.
Jag reser mig från soffan och går ut i hallen.
När jag öppnar dörren står Nina ute i trapphuset.
Hon har en liten pappkartong i händerna.
"Hej Maya, jag har ett paket till dig", säger hon och ler.
Hon räcker mig kartongen.
"Den lämnades hos mig tidigare i eftermiddags", förklarar Nina.
"Brevbäraren råkade visst blanda ihop våra dörrar."
Jag tittar på kartongen och ser mitt namn på den.
"Åh!"
"Det är mina nya kaffebönor!"
"Jag brukar köpa dem på nätet", berättar jag för henne.
"Normalt lämnas ju paket nere i trappuppgången", säger Nina.
"Ja, de brukar läggas där", svarar jag.
Jag tar emot pappkartongen med ett stort leende.
Den doftar redan svagt av rostat kaffe.
"Tack så mycket för att du kom över med den", säger jag.
