Det är torsdag kväll, och jag är hemma.
Jag packar min sportväska.
Jag lägger mina skor och mina kläder i väskan.
Jag ser fram emot att spela i kväll.
Jag tar bussen till en stor sporthall.
Det är en kall vinterkväll.
Jag sitter på bussen och tittar ut.
Bussen stannar, och jag kliver av.
Jag går in i den stora sporthallen.
Den är mycket ljus.
Jag ser många människor i hallen.
De älskar att sporta.
Jag hör ett högt ljud.
Skorna gnisslar på de många träbanorna.
Folk springer snabbt och spelar tillsammans.
Det ser mycket roligt ut.
Jag är redo att spela.
Men först måste jag hyra en racket.
