Jdu do zkušební kabinky s novou košilí.
Chci si ji hned vyzkoušet.
Kabinka je malá, ale je tam dobré zrcadlo.
Sundávám si bundu a svetr.
Pak si oblékám modrou košili.
V zrcadle kontroluji, jak mi sedí.
Ta větší velikost je mnohem lepší.
Nesedí mi příliš těsně přes ramena.
Trochu hýbu rukama.
Ta košile je mnohem pohodlnější než ta druhá.
Ta menší košile ze soboty byla prostě příliš malá.
Tahle košile sedí perfektně.
Délka je také úplně akorát.
Barva je pořád stejně pěkná.
Spokojeně přikývnu.
Znovu si košili sundávám.
Poté si oblékám své vlastní oblečení.
Beru si novou košili s sebou ven ze zkušební kabinky.
Určitě si ji chci nechat.
Teď už si jen musím znovu promluvit s prodavačem.
