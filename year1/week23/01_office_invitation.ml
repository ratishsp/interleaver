ഒരു ബുധനാഴ്ച രാവിലെ ഞാൻ ഓഫീസിൽ എന്റെ ഡെസ്കിൽ ഇരിക്കുകയാണ്.
ഒരു കപ്പ് കാപ്പിയുമായി ഈവ എന്റെ ഡെസ്കിനടുത്തേക്ക് വരുന്നു.
"ഹായ് മായാ, വെള്ളിയാഴ്ച നിനക്ക് സമയമുണ്ടോ?" വലിയൊരു ചിരിയോടെ അവൾ ചോദിക്കുന്നു.
എനിക്ക് ശരിക്കും ആ വൈകുന്നേരം ഒഴിവുണ്ടെന്ന് ഞാൻ കരുതുന്നു.
"അതെ, എനിക്ക് ധാരാളം സമയമുണ്ട്," ഞാൻ അവൾക്ക് മറുപടി നൽകുന്നു.
"രാത്രി ഭക്ഷണത്തിനായി നിന്നെ വീട്ടിലേക്ക് ക്ഷണിക്കാൻ ഞാൻ ആഗ്രഹിക്കുന്നു," അവൾ പറയുന്നു.
ആ ക്ഷണത്തിൽ എനിക്ക് വലിയ സന്തോഷം തോന്നുന്നു.
"നന്ദി, വളരെ സന്തോഷത്തോടെ ഞാൻ വരാം," ഞാൻ പറയുന്നു.
"ഒരു വെജിറ്റേറിയൻ വിഭവം ഉണ്ടാക്കാനാണ് ഞാൻ ഉദ്ദേശിക്കുന്നത്," ഈവ വിശദീകരിക്കുന്നു.
"അത് തികച്ചും ഗംഭീരമാണെന്ന് തോന്നുന്നു," ഞാൻ പുഞ്ചിരിക്കുന്നു.
"ഞാൻ എത്ര മണിക്കാണ് അവിടെ എത്തേണ്ടത്?" ഞാൻ ചോദിക്കുന്നു.
"നീ ആറു മണിക്ക് വന്നാൽ മതി," അവൾ മറുപടി പറയുന്നു.
പുതിയ സുഹൃത്തുക്കളെ സന്ദർശിക്കുന്നത് എപ്പോഴും നല്ലൊരു കാര്യമാണെന്ന് ഞാൻ കരുതുന്നു.
"ഞാൻ തീർച്ചയായും അവിടെ എത്തും," ഞാൻ ഉറപ്പുനൽകുന്നു.
ഒരു ചെറിയ മഞ്ഞ കടലാസിൽ ഈവ അവളുടെ വിലാസം എഴുതുന്നു.
അവൾ ആ കടലാസ് എനിക്ക് നൽകുന്നു.
"വെള്ളിയാഴ്ചക്കായി ഞാൻ വളരെ ആകാംക്ഷയോടെ കാത്തിരിക്കും," ഞാൻ അവളോട് പറയുന്നു.
ഈവ വീണ്ടും പുഞ്ചിരിച്ചുകൊണ്ട് അവളുടെ കമ്പ്യൂട്ടറിനടുത്തേക്ക് തിരികെ പോകുന്നു.
