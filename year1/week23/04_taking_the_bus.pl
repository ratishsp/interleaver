Stoję na przystanku autobusowym z żółtymi kwiatami.
Jest wiele osób, które czekają.
Patrzę na ekran, żeby sprawdzić rozkład jazdy.
Autobus powinien tu być za pięć minut.
Myślę, że piątkowy ruch jest często bardzo powolny.
Ale dzisiaj ulice wyglądają na zupełnie puste.
Więc myślę, że autobus prawdopodobnie przyjedzie na czas.
Obok mnie stoi starszy mężczyzna.
Patrzy na swój zegarek i wzdycha.
„Wie pani, czy autobus jest spóźniony?” – pyta mnie.
Ponownie sprawdzam telefon.
„Nie, nie sądzę” – odpowiadam.
„Też jadę tym samym autobusem”.
„Myślę, że tak naprawdę jest tuż za rogiem”.
Uśmiecha się do mnie i kiwa głową.
Nagle widzimy duży czerwony autobus w głębi ulicy.
Szybko jedzie w naszą stronę.
„Miała pani rację” – mówi z ulgą mężczyzna.
Razem wsiadamy do autobusu.
Z pewnością będę u Evy na czas.
Nie mogę się doczekać, żeby zobaczyć jej mieszkanie.
