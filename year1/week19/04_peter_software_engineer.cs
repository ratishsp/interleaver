Sedám si k Peterovu stolu.
Díváme se na jeho velkou obrazovku.
Peter je také softwarový inženýr.
Je to dobrý kolega a píšeme spolu hodně kódu.
Dnes vypadá velmi unaveně.
„Co to děláš, Petere?“ ptám se.
„Mám velký problém,“ odpovídá.
„Na téhle chybě jsem pracoval tři hodiny.“
Usmívám se a pozorně se dívám na kód.
Při práci spolu často řešíme složité problémy.
Najednou na obrazovce vidím něco zvláštního.
Je to velmi malá chyba.
„Zkus se podívat sem,“ říkám a ukazuji na obrazovku.
„Tady jsi udělal malý překlep.“
Peter se dvě sekundy tiše dívá na obrazovku.
Pak se hlasitě zasměje.
„Máš naprostou pravdu,“ říká Peter.
„Pracoval jsem tři hodiny a nakonec je to jen jedna malá chyba!“
Také se směju, protože tuhle situaci znají všichni softwaroví inženýři.
Opravíme chybu a program konečně perfektně funguje.
