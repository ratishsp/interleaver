ഞാൻ എൻ്റെ പുതിയ വാതിലിനടുത്ത് നിൽക്കുന്നു.
ഒരു വാതിൽ തുറക്കുന്നു, ഒരു സ്ത്രീ പുറത്തേക്ക് വരുന്നു.
അവൾ എന്നെ നോക്കി ദയയോടെ പുഞ്ചിരിക്കുന്നു.
"ഹായ്," അവൾ പറയുന്നു.
"നിങ്ങൾ ഇവിടേക്ക് താമസം മാറുകയാണോ?"
"അതെ," ഞാൻ മറുപടി പറയുന്നു.
"എൻ്റെ പേര് നീന," ആ സ്ത്രീ പറയുന്നു.
"ഞാൻ നിങ്ങളുടെ അയൽക്കാരിയാണ്."
"നമസ്കാരം, എൻ്റെ പേര് മായ," ഞാൻ പറയുന്നു.
"മായ, നിങ്ങൾ എവിടെ നിന്നാണ് വരുന്നത്?" നീന ചോദിക്കുന്നു.
"ഞാൻ മെക്സിക്കോയിൽ നിന്നാണ് വരുന്നത്," ഞാൻ മറുപടി പറയുന്നു.
നീന വീണ്ടും പുഞ്ചിരിക്കുന്നു.
"മെക്സിക്കോയിൽ നിന്നോ, എത്ര ആവേശകരം."
"ഡെന്മാർക്കിലേക്ക് സ്വാഗതം!" അവൾ പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
നീന ഡെന്മാർക്കിൽ നിന്നാണ്, അവൾ വളരെ ദയയുള്ളവളാണ്.
ഇപ്പോൾ എനിക്ക് കോപ്പൻഹേഗനിൽ ഒരാളെ അറിയാം.
എനിക്ക് എൻ്റെ ആദ്യത്തെ സുഹൃത്തുണ്ട്.
