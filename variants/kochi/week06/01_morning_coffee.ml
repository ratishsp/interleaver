ഇന്ന് ഞാൻ നേരത്തെ ഉണരുന്നു.
ഇതൊരു നല്ല ഫെബ്രുവരി പ്രഭാതമാണ്.
കൊച്ചിയിലെ എൻ്റെ ഫ്ലാറ്റ് വളരെ ശാന്തമാണ്.
ഇപ്പോൾ സൂര്യൻ ഉദിക്കുകയാണ്.
ഞാൻ കട്ടിലിൽ നിന്ന് എഴുന്നേൽക്കുന്നു.
ഞാൻ ബാത്ത്റൂമിലേക്ക് പോകുന്നു.
ഞാൻ പല്ല് തേക്കുന്നു.
പിന്നെ ഞാൻ മുഖം കഴുകുന്നു.
അതിനുശേഷം ഞാൻ വസ്ത്രം ധരിക്കുന്നു.
ഞാൻ അടുക്കളയിലേക്ക് നടക്കുന്നു.
ഞാൻ ഇപ്പോൾ ഒരു കപ്പ് കാപ്പി ഉണ്ടാക്കുകയാണ്.
ഞാൻ വെള്ളം തിളപ്പിക്കുന്നു.
കാപ്പിക്ക് നല്ല മണമുണ്ട്.
ഞാൻ ചൂട് കാപ്പി കപ്പിലേക്ക് ഒഴിക്കുന്നു.
ഞാൻ ജനലിനടുത്ത് ഇരിക്കുന്നു.
ഞാൻ പതുക്കെ കാപ്പി കുടിക്കുകയാണ്.
ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
പക്ഷികൾ പറക്കുകയാണ്.
ഞാൻ ഇന്നത്തെ ദിവസത്തിനായി തയ്യാറെടുക്കുകയാണ്.
എനിക്ക് വളരെ സന്തോഷം തോന്നുന്നു.
