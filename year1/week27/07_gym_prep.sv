Jag stänger dörren efter Nina.
Jag är helt färdig med skärmar för ikväll.
Jag sätter min telefon i laddaren.
Den brukar ligga på soffan, men nu ska den laddas.
Imorgon är det onsdag.
Jag brukar träna på gymmet onsdag kväll.
Min egen lilla regel är att sportväskan packas kvällen innan.
Först hämtas väskan från garderoben i hallen.
Sedan läggs mina skor ner i den.
Jag hittar också min vattenflaska ute i köket.
Den läggs försiktigt bredvid skorna.
Jag brukar alltid ha med mig rena kläder.
Kläderna läggs också ner i väskan.
Jag kollar att jag har allt.
Till sist ställs väskan klar vid ytterdörren.
På så sätt glöms den inte bort imorgon bitti.
Nu är alla mina praktiska uppgifter avklarade för idag.
Jag ser bara fram emot en lugn kväll.
