ഞാൻ സ്വീകരണമുറിയിൽ ആണ്.
എന്റെ ബാഗുകൾ തറയിൽ കിടക്കുന്നു.
ഞാൻ ഒരു ബാഗ് തുറക്കുന്നു.
അതിൽ എന്റെ ലാപ്ടോപ്പ് ഉണ്ട്.
ഞാൻ ലാപ്ടോപ്പ് പുറത്ത് എടുക്കുന്നു.
മുറിയിൽ ഒരു ചെറിയ മേശ ഉണ്ട്.
ഞാൻ ലാപ്ടോപ്പ് ആ മേശയുടെ മുകളിൽ വെക്കുന്നു.
ഇപ്പോൾ ലാപ്ടോപ്പ് മേശയുടെ മുകളിൽ ഇരിക്കുന്നു.
ഞാൻ അടുത്ത ബാഗ് എടുക്കുന്നു.
അതിൽ എന്റെ പ്രിയപ്പെട്ട പുസ്തകങ്ങൾ ഉണ്ട്.
മേശയുടെ അടുത്ത് ഒരു കസേര ഉണ്ട്.
കസേരയുടെ അടുത്ത് ഒരു ചെറിയ ഷെൽഫ് ഉണ്ട്.
ഞാൻ ആ പുസ്തകങ്ങൾ ഷെൽഫിൽ വെക്കുന്നു.
പുസ്തകങ്ങൾ ഇപ്പോൾ ഷെൽഫിൽ ഭംഗിയായി ഇരിക്കുന്നു.
എന്റെ ജോലിസ്ഥലം ഇപ്പോൾ റെഡിയാണ്.
ഞാൻ എന്റെ പുതിയ കസേരയിൽ ഇരിക്കുന്നു.
