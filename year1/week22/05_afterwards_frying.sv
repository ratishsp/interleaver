Potatisarna kokar nu i grytan.
Det doftar redan härligt i köket.
Jag tar fram en stor stekpanna.
Jag läser nästa instruktioner i receptet.
Nästa del är viktig.
Det står: "Smält först en tjock bit smör i pannan."
Jag skär lite smör och lägger det i pannan.
Smöret fräser snabbt på den varma metallen.
Jag läser vidare: "Forma därefter köttet till runda bollar."
Jag använder en sked för att forma köttet.
Det är lite svårt, men de blir fina och runda.
Jag lägger dem försiktigt i den varma pannan.
Receptet fortsätter: "Stek dem sedan tills de är krispiga och bruna."
Jag sänker värmen lite.
De ska steka i cirka femton minuter.
Jag vänder dem ofta så att de inte bränns vid.
De doftar fantastiskt och får en bra färg.
Nu är köttbullarna och potatisarna nästan färdiga.
Jag ser fram emot att Kasper och Sara kommer.
Det är helt perfekt tajming.
