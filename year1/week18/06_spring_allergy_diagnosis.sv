Läkaren ber mig att öppna munnen.
"Säg ah", säger han med ett leende.
Han tittar noga i min hals.
Efteråt lyssnar han på min andning.
Han frågar om jag mår dåligt någon annanstans.
Jag berättar att mitt huvud också gör ont.
"Det är ingen förkylning", säger han.
"Du har en vanlig vårallergi", förklarar han.
Jag blir lite överraskad.
Jag har aldrig haft allergi förut.
Han berättar för mig att det är helt normalt.
Träden och blommorna här är nya för min kropp.
"Du borde köpa lite mild medicin på apoteket", säger läkaren.
Han lovar att det kommer att hjälpa snabbt.
"Då mår du bra igen", tillägger han.
Jag är mycket lättad.
Min hals gör ont, men det är lyckligtvis inte allvarligt.
