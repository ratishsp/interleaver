Jag kommer till det lilla bageriet på hörnet.
Jag går in i den varma butiken.
Det doftar ljuvligt av kaffe och kaka.
En bagare i vitt förkläde står bakom disken.
"God eftermiddag", säger bagaren.
"Hur kan jag hjälpa till?", frågar han.
Jag tittar på de många kakorna.
Jag köper en kaka till i kväll.
Jag pekar på en fin chokladkaka.
"Jag vill gärna ha chokladkakan, tack", säger jag.
"Självklart", svarar bagaren.
Han lägger kakan i en vit ask.
"Det blir sextiofem kronor", säger han.
Jag tar upp min plånbok ur väskan.
Jag betalar de sextiofem kronorna.
"Tack så mycket, och ha en trevlig kväll", säger bagaren.
"Tack, detsamma", svarar jag.
Jag tar den vita asken.
Jag går försiktigt ut ur butiken med kakan.
