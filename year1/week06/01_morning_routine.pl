Na zewnątrz wciąż jest ciemno.
Rano budzę się powoli.
Leżę przez chwilę w łóżku.
Dzisiaj jest zupełnie zwykły dzień powszedni.
Teraz wstaję z łóżka.
Podłoga jest trochę zimna pod moimi stopami.
Idę prosto do łazienki.
W łazience odkręcam wodę.
Woda jest ciepła i przyjemna.
Wchodzę do kabiny prysznicowej.
Biorę tutaj przyjemny, ciepły prysznic.
Najpierw myję włosy szamponem.
Potem myję się mydłem.
Mydło pachnie świeżo cytrusami.
Ciepła woda mnie rozbudza.
Na koniec zakręcam prysznic.
Biorę miękki ręcznik.
Teraz dokładnie się wycieram.
Jestem całkowicie rozbudzona i gotowa na dzisiejszy dzień.
