Kuchnia jest mała.
Ale kuchenka jest dobra.
Biorę pasternak i marchewkę.
Biorę też nóż.
Nóż jest ostry.
Kroję pasternak i marchewkę.
Otwieram puszkę.
Wkładam jedzenie do garnka.
Garnek stoi na kuchence.
Teraz jedzenie jest ciepłe.
Pachnie cudownie.
Biorę chleb żytni.
Odkrawam kromkę.
Talerz stoi na stole.
Wreszcie jem porządny posiłek w mieszkaniu.
Potem jem bułeczkę cynamonową.
Smakuje słodko.
