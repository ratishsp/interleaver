ഞങ്ങൾ ഭക്ഷണം കഴിച്ചു.
ഞങ്ങൾ റെസ്റ്റോറന്റിന്റെ പുറത്തേക്ക് ഇറങ്ങി.
ഇപ്പോൾ മഴ കുറഞ്ഞിട്ടുണ്ട്.
തെരുവുകളിൽ വെള്ളം നിറഞ്ഞിട്ടുണ്ട്.
പ്രകാശ് ഒരു ഓട്ടോ വിളിച്ചു.
ഞങ്ങൾ ഓട്ടോയ്ക്കായി കാത്തുനിന്നു.
അനിതയും ദീപയും സംസാരിച്ച് ചിരിച്ചു.
അവർ പെട്ടെന്ന് നല്ല സുഹൃത്തുക്കൾ ആയിട്ടുണ്ട്.
എന്റെ അയൽക്കാരിയും സഹപ്രവർത്തകരും ഒരുമിച്ച് നിന്നു.
അത് എനിക്ക് വളരെ സന്തോഷം തന്നു.
കുറച്ചു കഴിഞ്ഞപ്പോൾ, പ്രകാശിന്റെയും ദീപയുടെയും ഓട്ടോ വന്നു.
"ശുഭരാത്രി, മായ," ദീപ പറഞ്ഞു.
"ഒരിക്കൽ കൂടി ജന്മദിനാശംസകൾ," പ്രകാശും പറഞ്ഞു.
അവർ രണ്ടുപേരും അതിൽ കയറി പോയി.
എനിക്കും അനിതയ്ക്കും വേറെ ഒരു ഓട്ടോ കിട്ടി.
ഞങ്ങൾ ആ ഓട്ടോയിൽ വീട്ടിലേക്ക് തിരിച്ചു.
പുറത്ത് തണുത്ത കാറ്റ് വീശി.
എനിക്ക് ഇപ്പോൾ മുപ്പത്തിരണ്ട് വയസ്സായിട്ടുണ്ട്.
ഈ നഗരം ഇപ്പോൾ എന്റെ സ്വന്തം ഇടം ആയിട്ടുണ്ട്.
