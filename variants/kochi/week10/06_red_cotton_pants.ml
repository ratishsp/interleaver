ഞാൻ ഇപ്പോൾ പാന്റ്സ് സെക്ഷനിൽ ആണ്.
ഞാൻ അവിടെയുള്ള തുണികൾ നോക്കുന്നു.
അവിടെ ഞാൻ ഒരു കോട്ടൺ പാന്റ്സ് കാണുന്നു.
അതൊരു നല്ല ചുവന്ന പാന്റ്സ് ആണ്.
ഞാൻ അത് ഫിറ്റിംഗ് റൂമിലേക്ക് കൊണ്ടുപോകുന്നു.
ഞാൻ ആ പാന്റ്സ് ധരിക്കുന്നു.
ഇതൊരു വലിയ പാന്റ്സ് ആണ്.
ഇത് വളരെ കട്ടി കുറഞ്ഞ പാന്റ്സ് ആണ്.
ഈ ചൂടിന് ഇത് വളരെ നല്ലതാണ്.
ഞാൻ ഫിറ്റിംഗ് റൂമിൽ നിന്ന് പുറത്ത് വരുന്നു.
ഞാൻ സെയിൽസ്‌വുമണോട് വില ചോദിക്കുന്നു.
"ഈ പാന്റ്സിന്റെ വില എന്താണ്?" ഞാൻ ചോദിക്കുന്നു.
"ഇതിന് എണ്ണൂറ് രൂപയാണ്," അവർ പറയുന്നു.
എനിക്ക് ആ പാന്റ്സ് വളരെ ഇഷ്ടമാണ്.
അതിന്റെ ചുവപ്പ് നിറം വളരെ മനോഹരമാണ്.
"ഞാൻ ഇത് എടുക്കുന്നു," ഞാൻ അവരോട് പറയുന്നു.
ഞാൻ ആ ചുവന്ന പാന്റ്സ് എന്റെ കയ്യിൽ എടുക്കുന്നു.
കൊച്ചിയിലെ ചൂടിന് എനിക്ക് ഇത്തരം കോട്ടൺ തുണികൾ വേണം.
