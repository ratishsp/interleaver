Podchodzę do małego kiosku w hali sportowej.
Za ladą stoi młody mężczyzna.
Uśmiecha się i mówi cześć.
– Cześć, chcę dzisiaj zagrać w badmintona – mówię.
– Jesteś tu nowa w klubie? – pyta.
– Tak, chciałabym spróbować dołączyć – odpowiadam.
– Witamy – mówi mężczyzna.
– Potrzebujesz wypożyczyć rakietę? – pyta.
– Tak, poproszę, chcę wypożyczyć rakietę na dzisiejszy wieczór – mówię.
Znajduje dla mnie dobrą rakietę.
– To kosztuje czterdzieści koron – mówi.
Wyciągam moją kartę płatniczą.
Płacę te czterdzieści koron.
Podaje mi rakietę przez ladę.
– Uważam, że to fajny sport – mówię radośnie.
– Naprawdę udanej gry!
Dziękuję i podchodzę do kortów.
