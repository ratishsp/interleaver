എന്റെ പുതിയ ഫ്ലാറ്റിന്റെ വാതിൽ തുറന്നു കിടക്കുന്നു.
വാതിലിൽ ആരോ പതുക്കെ മുട്ടുന്നു.
ഞാൻ വാതിലിന്റെ അടുത്ത് പോകുന്നു.
അവിടെ അനിത നിൽക്കുന്നു.
അനിത എന്റെ അയൽക്കാരിയാണ്.
അവരുടെ കയ്യിൽ ഒരു ചെറിയ ചെടിയുണ്ട്.
ഞാൻ സന്തോഷത്തോടെ അവരെ നോക്കി ചിരിക്കുന്നു.
"ഹലോ മായ, അകത്തേക്ക് വരാമോ?" അനിത ചോദിക്കുന്നു.
"തീർച്ചയായും, അകത്തേക്ക് വരൂ," ഞാൻ പറയുന്നു.
അനിത സ്വീകരണമുറിയിൽ വരുന്നു.
അവർ ആ ചെടി എനിക്ക് തരുന്നു.
"ഇത് പുതിയ ഫ്ലാറ്റിലേക്കുള്ള ഒരു സമ്മാനമാണ്," അവർ പറയുന്നു.
"വളരെ നന്ദി അനിത," ഞാൻ പറയുന്നു.
ചെടി മനോഹരമായ ഒരു ചട്ടിയിലാണ്.
ഇപ്പോൾ അത് എന്റെ കയ്യിലാണ്.
അനിത മുറിയിൽ ചുറ്റും നോക്കുന്നു.
എന്റെ സാധനങ്ങളെല്ലാം ഇപ്പോൾ അവിടെ ഇരിക്കുന്നു.
"മുറി കാണാൻ വളരെ ഭംഗിയുണ്ട്," അനിത പറയുന്നു.
"സോഫയിൽ ഇരിക്കൂ," ഞാൻ അവരോട് പറയുന്നു.
അനിത സോഫയിൽ ഇരിക്കുന്നു.
