ഞാൻ മാർക്കറ്റിന് പുറത്തേക്ക് നടക്കുന്നു.
പെട്ടെന്ന്, എനിക്ക് നല്ലൊരു മണം കിട്ടുന്നു.
അത് പുതിയ മുല്ലപ്പൂവാണ്.
അവിടെ ഒരു സ്ത്രീ പായിൽ ഇരിക്കുന്നു.
അവർ മുല്ലപ്പൂമാല ഉണ്ടാക്കുന്നു.
ഞാൻ അവരുടെ അടുത്തേക്ക് പോകുന്നു.
"ചേച്ചീ, എനിക്ക് ഒരു ചെറിയ മുല്ലപ്പൂമാല തരൂ," ഞാൻ പറയുന്നു.
ആ സ്ത്രീ എന്നെ നോക്കി ചിരിക്കുന്നു.
അവർ ഒരു പൂമാല എനിക്ക് തരുന്നു.
പൂക്കൾക്ക് നല്ല ഭംഗിയുണ്ട്.
"ഇതിന് വില എത്ര?" ഞാൻ ചോദിക്കുന്നു.
"മുപ്പതു രൂപ," ആ സ്ത്രീ പറയുന്നു.
ഞാൻ എൻ്റെ ബാഗിൽ നിന്ന് പണം എടുക്കുന്നു.
ഞാൻ അവർക്ക് മുപ്പതു രൂപ കൊടുക്കുന്നു.
ആ സ്ത്രീ പണം വാങ്ങുന്നു.
"നന്ദി," അവർ പറയുന്നു.
ഞാൻ ആ മുല്ലപ്പൂ എൻ്റെ ബാഗിൽ വെക്കുന്നു.
