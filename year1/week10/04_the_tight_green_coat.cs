Potřebuji také zimní bundu.
Dívám se v obchodě na další oblečení.
Nacházím krásný zelený kabát.
Je to velmi krásný design.
Oblékám si ten zelený kabát.
Ale je příliš malý.
Je velmi těsný přes ramena.
"Máte ho v jiné velikosti?" ptám se.
Prodavačka se podívá.
"Ne, bohužel," odpovídá.
Takže ten zelený kabát věším zpátky.
Prodavačka pro mě najde jinou bundu.
Je to teplá, tmavě modrá zimní bunda.
Oblékám si tu tmavě modrou bundu.
Sedí perfektně.
Je pěkně velká a není těsná.
Dívám se do velkého zrcadla.
Líbí se mi.
"Vezmu si ji," říkám.
