Najdu si telefonní číslo své místní lékařské kliniky.
To číslo je třicet dva, čtyřicet pět, šedesát sedm, osmdesát devět.
Volám jim a čekám pár minut.
Telefon zvedne přátelská recepční.
„Lékařská klinika, mluvíte s Hannou,“ říká.
Vysvětluji, že jsem dnes opravdu onemocněla.
„Mám těžkou hlavu a svědí mě oči,“ říkám.
Také jí říkám, že mě bolí v krku.
Ptá se, jestli mám horečku.
Odpovídám, že si to nemyslím, ale jsem velmi unavená.
„Měla byste si dnes promluvit s lékařem,“ říká recepční.
Dívá se do kalendáře, aby našla volný termín.
„Můžete přijít v jednu hodinu?“ ptá se.
„Ano, to se mi perfektně hodí,“ odpovídám.
„Nezapomeňte si vzít svou žlutou zdravotní kartu,“ říká.
Děkuji jí a zavěšuji.
Teď si jen potřebuji trochu odpočinout, než tam půjdu.
