Stojím v kuchyni, když zazvoní zvonek u dveří.
Vyjdu do předsíně a otevřu dveře.
Je to Nina a na tváři má široký úsměv.
„Ahoj Mayo, moc děkuju za pozvání,“ říká.
Vejde dovnitř a směje se, zatímco si zouvá boty.
Vřele ji obejmu.
Nina drží v rukou krásnou zelenou pokojovou rostlinu.
„Tohle je pro tebe,“ říká a podává mi tu rostlinu.
„Perfektně se hodí do tvého obýváku.“
„Děkuju, je opravdu krásná,“ odpovídám vesele.
Postavím tu zelenou rostlinu na malý stolek vedle dveří.
Najednou se Nina zhluboka nadechne.
„Páni, voní to tu naprosto úžasně,“ říká.
„To je to mexické koření?“ ptá se zvědavě.
Přikývnu a vysvětlím, že jsem uvařila tradiční dušený pokrm.
„Z té kořeněné vůně mám úplně šílený hlad,“ směje se Nina.
„Jídlo je naštěstí úplně hotové,“ říkám s úsměvem.
Společně se posadíme ke stolu, abychom se najedly.
