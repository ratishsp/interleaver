Jest mi teraz bardzo zimno.
Moje ręce są zimne.
Rozglądam się po targu.
Widzę mały wózek z kawą.
Za wózkiem stoi młody mężczyzna.
Podchodzę do niego.
Mówię cześć bariście.
„Cześć, ile kosztuje czarna kawa?” – pytam.
Barista się uśmiecha.
„Gorąca, czarna kawa kosztuje trzydzieści koron” – odpowiada.
Mam monety w kieszeni płaszcza.
To moja reszta z jabłek.
Wyciągam monety.
Liczę je.
Mam dokładnie trzydzieści koron.
„Proszę, oto trzydzieści koron” – mówię.
Bierze pieniądze.
Daje mi gorącą kawę.
Kawa pachnie wspaniale.
Ogrzewam ręce o kubek.
