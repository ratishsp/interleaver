കഫേയിലെ എൻ്റെ മൂന്നാമത്തെ ഷിഫ്റ്റ് ഒടുവിൽ കഴിഞ്ഞു.
ഇത് വളരെ തിരക്കുള്ള ഒരു ശനിയാഴ്ചയായിരുന്നു.
ഞാൻ ആ വലിയ തടി കൗണ്ടർ കഴുകി വൃത്തിയാക്കി.
അതിനുശേഷം, ഞാൻ സ്റ്റാഫ് റൂമിലേക്ക് പോയി.
ഞാൻ എൻ്റെ ആപ്രോൺ ഊരിമാറ്റി.
ഭിത്തിയിലെ ആദ്യത്തെ കൊളുത്തിൽ ഞാൻ അത് തൂക്കിയിട്ടു.
എൻ്റെ ആദ്യത്തെ ഷിഫ്റ്റുകളിൽ നിന്ന് ഞാൻ ഒരുപാട് കാര്യങ്ങൾ പഠിച്ചു.
പാൽ ശരിയായി പതപ്പിക്കാൻ ഒടുവിൽ ഞാൻ പഠിച്ചു.
ഒരു സ്ഥിരം കസ്റ്റമറുടെ ഓർഡർ ഓർത്തുവെക്കാനും ഞാൻ പഠിച്ചു.
ഇത് രസകരമായിരുന്നു, പക്ഷേ ഞാൻ കുറച്ച് ക്ഷീണിച്ചിട്ടുമുണ്ടായിരുന്നു.
ഞാൻ മേശപ്പുറത്തുനിന്ന് എൻ്റെ ബാഗ് എടുത്തു.
പിന്നെ ഞാൻ മുൻവാതിലിനടുത്തേക്ക് നടന്നു.
ഉച്ചതിരിഞ്ഞുള്ള ഷിഫ്റ്റ് ഇപ്പോൾ ചുമതലയേറ്റു.
ഞാൻ തെരുവിലേക്ക് ഇറങ്ങി.
നഗരത്തിന് മുകളിൽ ഉച്ചതിരിഞ്ഞുള്ള സൂര്യൻ തിളങ്ങിനിൽക്കുന്നുണ്ടായിരുന്നു.
ബസ്സിലേക്കുള്ള വഴിയിൽ ഞാൻ എന്നോട് തന്നെ പുഞ്ചിരിച്ചു.
എൻ്റെ പുതിയ വോളണ്ടിയർ ജോലിയിൽ ഞാൻ വളരെ സന്തുഷ്ടയാണ്.
എൻ്റെ നാലാമത്തെ ഷിഫ്റ്റിനായി ഞാൻ ഇപ്പോൾ തന്നെ കാത്തിരിക്കുകയാണ്.
