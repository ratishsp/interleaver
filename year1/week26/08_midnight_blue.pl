Jest prawie dwunasta w nocy, ale niebo wciąż jest jasne.
Ma delikatny, niebieski kolor.
Idę ulicą z Evą i Peterem.
Niewiele rozmawiamy.
W nocy słychać tylko nasze kroki.
Patrzę na moich przyjaciół.
Eva się uśmiecha, a Peter wygląda na zmęczonego, ale szczęśliwego.
Kiedy tu przyjechałam, nikogo nie znałam.
Ale od tamtej pory wiele się zmieniło.
Mam teraz dobre codzienne życie i poznałam wielu ludzi.
Tak naprawdę znalazłam prawdziwych przyjaciół.
Peter był pierwszym kolegą z pracy, z którym rozmawiałam.
A Eva zaprosiła mnie niedawno do siebie.
Teraz idziemy tu razem pod jasnym, letnim niebem.
Właśnie skończyłam trzydzieści dwa lata.
Zbudowałam życie, które kocham.
Wreszcie czuję się w pełni jak w domu w moim nowym mieście.
