På min tredje lördag stod jag redo bakom disken.
Jag har äntligen lärt mig att slappna av lite på kaféet.
Genom fönstret såg jag en äldre man på gatan.
Han gick långsamt fram mot huvuddörren.
Han var också här på mitt första och mitt andra pass.
Han är en av kaféets fasta kunder.
Jag har lärt mig att komma ihåg hans beställning utantill.
Han köper alltid precis samma sak.
Han öppnade dörren och kom fram till kassan.
Jag tittade på honom och log.
"God morgon," sa jag.
"Ska jag göra din vanliga cortado?"
Mannen tittade förvånat på mig.
Sedan log han glatt.
"Ja tack, det vill jag mycket gärna," svarade han.
Jag gick fram till espressomaskinen.
Jag har gjort kaffe många gånger nu, så det gick snabbt.
Det var en bra känsla att känna våra gäster.
