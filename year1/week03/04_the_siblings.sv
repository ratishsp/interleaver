Nu är det två nya ansikten på min skärm.
Det är min lillasyster, Sofía, och min storebror, Diego.
De skrattar och knuffar lite på varandra.
"Hej lillasyster och storebror!" säger jag glatt.
"Hej Maya", säger Diego.
Min bror har ett stort leende.
"Är det kallt i Danmark?" frågar han.
"Är det en kall vinter?"
"Ja, det är en mycket kall vinter", skrattar jag.
"Men jag har ett varmt rum och en kopp te."
Nu lyfter Sofía upp en stor sak framför skärmen.
Det är en stor bok.
"Har du en ny bok där, Sofía?" frågar jag.
"Ja, det är min nya bok", säger min syster stolt.
"Det är en bok från mitt universitet."
"Det är en mycket tjock bok!"
Jag ler mot min bror och min syster.
Jag saknar min familj i Mexiko.
Men de är precis här på min lilla skärm.
