ഞാൻ വെയിറ്റിംഗ് റൂമിലെ ഒരു കസേരയിൽ ഇരിക്കുന്നു.
മുറി ഏതാണ്ട് പൂർണ്ണമായും നിശബ്ദമാണ്.
ഞാൻ ക്ഷമയോടെ കാത്തിരിക്കുന്നു.
എൻ്റെ തലയ്ക്ക് ഇപ്പോഴും നല്ല ഭാരമുണ്ട്.
എനിക്ക് എതിർവശത്തായി ഒരു അമ്മയും ചെറിയൊരു ആൺകുട്ടിയും ഇരിക്കുന്നുണ്ട്.
ആ കുട്ടിക്ക് ഒരുപക്ഷേ അഞ്ച് വയസ്സ് പ്രായം വരും.
അവൻ തൻ്റെ വലത് ചെവിയിൽ ഒരു കൈ വെച്ചിട്ടുണ്ട്.
"അയ്യോ, എൻ്റെ ചെവി വേദനിക്കുന്നു!" അവൻ ഉറക്കെ പറയുന്നു.
അവൻ്റെ അമ്മ അവനെ നോക്കുന്നു.
"എനിക്കറിയാം മോനേ," അവർ സൗമ്യമായി പറയുന്നു.
"പക്ഷേ വല്ലാതെ വേദനിക്കുന്നുണ്ട്!" ആ കുട്ടി പരാതിപ്പെടുന്നു.
"ഡോക്ടർ നമ്മളെ ഉടനെ വിളിക്കേണ്ടതാണ്," അമ്മ പറയുന്നു.
അവർ അവൻ്റെ തോളിലൂടെ ഒരു കൈ വെക്കുന്നു.
ആ കുട്ടി ഉറക്കെ നെടുവീർപ്പിടുന്നു.
അവൻ വളരെ ക്ഷീണിതനായി കാണപ്പെടുന്നു.
എനിക്ക് അവനെ നന്നായി മനസ്സിലാകുന്നുണ്ട്.
എൻ്റെ തൊണ്ടയ്ക്കും ശരിക്കും വേദനയുണ്ട്.
എനിക്ക് വീണ്ടും ഒന്ന് സുഖം പ്രാപിച്ചാൽ മാത്രം മതി.
