ഞാൻ ലാപ്ടോപ്പ് സ്ക്രീനിൽ നോക്കുന്നു.
സ്ക്രീനിൽ പുതിയ ഒരാൾ വരുന്നു.
"അച്ഛാ, അമ്മേ, നിങ്ങളുടെ കൂടെ ആരാണ്?" ഞാൻ ചോദിക്കുന്നു.
അത് എന്റെ ചേട്ടൻ ഡീഗോ ആണ്.
ഡീഗോ ക്യാമറ നോക്കി ചിരിക്കുന്നു.
അവന്റെ കയ്യിൽ ഒരു നായ ഉണ്ട്.
അത് ഞങ്ങളുടെ നായ ലോല ആണ്.
എനിക്ക് വളരെ സന്തോഷം തോന്നുന്നു.
"ലോലാ!"
"എന്റെ ലോലാ!" ഞാൻ ഉറക്കെ വിളിക്കുന്നു.
ലോല സ്ക്രീനിൽ നോക്കുന്നു.
അവളുടെ ചെവികൾ ഉയരുന്നു.
"മായേ, നിനക്ക് സുഖമാണോ?" ഡീഗോ ചോദിക്കുന്നു.
"എനിക്ക് സുഖമാണ്, ഡീഗോ ചേട്ടാ," ഞാൻ മറുപടി പറയുന്നു.
ലോല പെട്ടെന്ന് സന്തോഷത്തോടെ കുരയ്ക്കുന്നു.
അവൾക്ക് എന്റെ ശബ്ദം അറിയാം.
ഞാൻ അവളുടെ കണ്ണുകളിൽ നോക്കുന്നു.
എന്റെ പ്രഭാതം ഇപ്പോൾ വളരെ സുന്ദരമാണ്.
