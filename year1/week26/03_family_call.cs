Večer sedím na pohovce se svým počítačem.
Volám své rodině do Mexika.
Obrazovka ukazuje moje rodiče, mou sestru Sofíu a mého bratra Diega.
Je tam také náš pes, Lola.
„Všechno nejlepší k narozeninám!“ křičí všichni.
Sofía se ptá.
„Dostala jsi náš balíček?“
„Ano, přišel včera poštou,“ odpovídám.
„Už jsi ho otevřela?“ ptá se nadšeně.
Usmívám se a beru ze stolu barevný šátek.
„Otevřela jsem ho, když jsem přišla domů,“ říkám a zvedám šátek.
„Ty barvy opravdu miluju.“
Dávám si šátek kolem krku.
„Moc ti sluší,“ říká moje máma.
„Měla jsi dnes dobrý den?“ ptá se můj táta.
„Ano, kolegové mi už dřív koupili dort,“ vysvětluji.
Diego zvedá Lolu ke kameře.
„Lola taky snědla malý dortík,“ směje se.
Hlasitě se tomu malému psovi směju.
Jsou to moje první narozeniny daleko od domova, ale připadají mi velmi blízko.
