എൻ്റെ ഫോൺ സ്ക്രീനിൽ ഒരു പുതിയ സന്ദേശം തെളിയുന്നു.
എൻ്റെ ഐഡൻ്റിറ്റി സ്ഥിരീകരിക്കണം എന്നാണ് അതിൽ പറയുന്നത്.
"ഒരു വൺ-ടൈം കോഡ് എസ്.എം.എസ് വഴി അയക്കുന്നതായിരിക്കും," എന്ന് സിസ്റ്റം എഴുതിക്കാണിക്കുന്നു.
സ്ക്രീനിന്റെ താഴെയുള്ള നിർദ്ദേശങ്ങൾ ഞാൻ വായിക്കുന്നു.
"ദയവായി കാത്തിരിക്കുക."
"ഈ പേജ് ക്ലോസ് ചെയ്യരുത്."
ഞാൻ എൻ്റെ ഫോണിലേക്ക് നോക്കി കാത്തിരിക്കുന്നു.
സ്ക്രീൻ ശൂന്യമായിത്തന്നെ തുടരുന്നു, ഒന്നും സംഭവിക്കുന്നില്ല.
പത്ത് സെക്കൻഡുകൾ കടന്നുപോകുന്നു.
ഇരുപത് സെക്കൻഡുകൾ കടന്നുപോകുന്നു.
ഞാൻ പതുക്കെ ഒന്ന് നെടുവീർപ്പിടുന്നു.
എനിക്ക് കുറച്ച് അലോസരം തോന്നിത്തുടങ്ങുന്നു.
ഈ ഓട്ടോമാറ്റിക് കോഡുകൾ സാധാരണ പെട്ടെന്ന് തന്നെ വരാറുള്ളതാണ്.
സാധാരണ ഇതിന് ഒരു സെക്കൻഡ് മാത്രമേ എടുക്കാറുള്ളൂ.
പക്ഷേ എൻ്റെ ഇൻബോക്സ് ഇപ്പോഴും ശൂന്യമാണ്.
ഞാൻ ഫോണിലെ സമയം നോക്കുന്നു.
ഒരുപക്ഷേ ഇന്ന് വൈകുന്നേരം സിസ്റ്റം സ്ലോ ആയിരിക്കുമോ?
ഒരു മിനിറ്റ് കൂടി കാത്തിരിക്കാൻ ഞാൻ തീരുമാനിക്കുന്നു.
കോഡ് ഉടൻ അയച്ചില്ലെങ്കിൽ, എനിക്ക് വീണ്ടും ശ്രമിക്കേണ്ടി വരും.
