ഞാൻ ബില്ലിംഗ് കൗണ്ടറിലേക്ക് നടക്കുന്നു.
എന്റെ കയ്യിൽ മൂന്ന് പുതിയ തുണികൾ ഉണ്ട്.
ഞാൻ ഒരു നീല കുർത്തയും ചുവന്ന ടീ ഷർട്ടും വെള്ള സ്കാർഫും വാങ്ങുന്നു.
ഞാൻ ഈ തുണികൾ കൗണ്ടറിൽ വെക്കുന്നു.
അവിടെ ഒരു ക്യാഷിയർ ഉണ്ട്.
അയാൾ ബിൽ തയ്യാറാക്കുന്നു.
"ആകെ കൃത്യം ആയിരം രൂപയാണ്," അയാൾ പറയുന്നു.
ഞാൻ കാർഡ് ഉപയോഗിക്കുന്നില്ല.
ഞാൻ ബാഗിൽ നിന്ന് പണം എടുക്കുന്നു.
ഞാൻ ആയിരം രൂപ അയാൾക്ക് കൊടുക്കുന്നു.
അയാൾ എനിക്ക് ഒരു വലിയ ഷോപ്പിംഗ് ബാഗ് തരുന്നു.
ഈ ഷോപ്പിംഗ് ബാഗ് വളരെ വലുതാണ്.
എന്റെ പുതിയ തുണികൾ അതിൽ ഉണ്ട്.
ഞാൻ നാളെ പുതിയ നീല കുർത്ത ധരിക്കുന്നു.
ചുവന്ന ടീ ഷർട്ട് ഞാൻ ജിമ്മിൽ ഇടുന്നു.
ഈ തുണികൾ വളരെ നല്ലതാണ്.
ഞാൻ എന്റെ ഷോപ്പിംഗ് ബാഗ് എടുക്കുന്നു.
ഞാൻ കടയിൽ നിന്ന് പുറത്തേക്ക് നടക്കുന്നു.
