Teď jsem venku.
Můj kufr je velký a těžký.
Je tu taxík.
Zvedám svůj kufr do taxíku.
Řidič je přátelský muž.
"Jaká je adresa?" ptá se.
"Je to Parkvej číslo dvanáct," říkám.
Přikývne a jede.
"Jste turistka?" ptá se řidič.
"Ne, nejsem turistka," odpovídám.
"Odkud pocházíte?" ptá se.
"Pocházím z Mexika," říkám.
Dívám se z okna.
Jsem velmi hrdá.
"Jsem softwarová inženýrka," říkám.
"Moje nová práce je tady v Kodani."
Usmívá se.
"To je vzrušující."
"Hodně štěstí v Dánsku," říká.
"Mockrát děkuji," říkám.
