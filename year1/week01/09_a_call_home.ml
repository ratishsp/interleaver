ഞാൻ എൻ്റെ ഫോൺ എടുക്കുന്നു.
ഞാൻ മെക്സിക്കോയിലെ വീട്ടിലേക്ക് വിളിക്കുന്നു.
എൻ്റെ അമ്മ ഫോൺ എടുക്കുന്നു.
"ഹായ്, അമ്മേ," ഞാൻ പറയുന്നു.
അവരുടെ ശബ്ദം കേൾക്കുന്നത് വളരെ സന്തോഷകരമാണ്.
"നീ ഇപ്പോൾ ഡെന്മാർക്കിലാണോ?" അവർ ചോദിക്കുന്നു.
"അതെ, ഞാൻ കോപ്പൻഹേഗനിലാണ്," ഞാൻ പറയുന്നു.
"പിന്നെ, എനിക്ക് സുഖമാണ്."
ഞാൻ എൻ്റെ അച്ഛൻ്റെ ശബ്ദവും കേൾക്കുന്നു.
"ഹായ്, മായാ!" അദ്ദേഹം പറയുന്നു.
"എൻ്റെ പുതിയ ജോലി തിങ്കളാഴ്ച തുടങ്ങും," ഞാൻ പറയുന്നു.
"എത്ര സന്തോഷകരം," എൻ്റെ അമ്മ പറയുന്നു.
ഞാൻ വിടപറഞ്ഞ് പുഞ്ചിരിക്കുന്നു.
