എൻ്റെ കയ്യിൽ ഇപ്പോൾ വാടകയ്ക്ക് എടുത്ത ഒരു റാക്കറ്റ് ഉണ്ട്.
ഞാൻ അതുമായി കോർട്ടിലേക്ക് നടക്കുന്നു.
അവിടെ മൂന്ന് പേർ നിൽക്കുന്നുണ്ട്.
അവർ എന്നെ നോക്കി ചിരിക്കുന്നു.
അതിൽ ഒരു സ്ത്രീ എന്നെ നോക്കി കൈ വീശുന്നു.
ഞാൻ അവരുടെ അടുത്തേക്ക് പോകുന്നു.
"നമസ്കാരം, എൻ്റെ പേര് സാറ," അവർ പറയുന്നു.
"ഇത് കിരൺ, ഇത് വിഷ്ണു," സാറ അവരെ പരിചയപ്പെടുത്തുന്നു.
ഞാൻ സന്തോഷത്തോടെ എൻ്റെ പേര് പറയുന്നു.
"നമസ്കാരം, എൻ്റെ പേര് മായ," ഞാൻ പറയുന്നു.
"നിങ്ങൾ കളിക്കാൻ വരികയാണോ?" കിരൺ ചോദിക്കുന്നു.
"അതെ, എനിക്ക് ബാഡ്മിന്റൺ കളിക്കാൻ ഇഷ്ടമാണ്," ഞാൻ പറയുന്നു.
"ഞങ്ങൾ ഒരു ഡബിൾസ് ഗെയിം കളിക്കാൻ പോകുന്നു," സാറ പറയുന്നു.
"ഞങ്ങൾക്ക് ഒരാളെ കൂടെ വേണം," വിഷ്ണു പറയുന്നു.
"നിങ്ങൾക്ക് ഞങ്ങളുടെ കൂടെ കളിക്കാൻ കഴിയുമോ?" വിഷ്ണു ചോദിക്കുന്നു.
"തീർച്ചയായും, എനിക്ക് കളിക്കാൻ കഴിയും," ഞാൻ മറുപടി പറയുന്നു.
എനിക്ക് പുതിയ ആളുകളെ പരിചയപ്പെടാൻ വളരെ ഇഷ്ടമാണ്.
ഞാൻ അവരുടെ കൂടെ കളിക്കാൻ കോർട്ടിലേക്ക് പോകുന്നു.
