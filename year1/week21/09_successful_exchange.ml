ഞാൻ നീല ഷർട്ടുമായി ഫിറ്റിംഗ് റൂമിൽ നിന്ന് പുറത്തേക്ക് നടക്കുന്നു.
വലിയ സൈസ് കൃത്യമായി പാകമാണ്.
ക്ലാർക്ക് ഇപ്പോഴും രജിസ്റ്ററിന് അരികിൽ നിൽക്കുകയാണ്.
"ഇത് മെച്ചമാണോ?" ഒരു പുഞ്ചിരിയോടെ അവൾ ചോദിക്കുന്നു.
"അതെ, ഇത് വളരെ മെച്ചമാണ്," ഞാൻ മറുപടി നൽകുന്നു.
"ചെറിയ ഷർട്ട് വളരെ ഇറുകിയതായിരുന്നു," ഞാൻ വിശദീകരിക്കുന്നു.
"എനിക്ക് അതിനു പകരം ഇത് മാറ്റിയെടുക്കാൻ താല്പര്യമുണ്ട്."
"അതിന് യാതൊരു കുഴപ്പവുമില്ല," അവൾ പറയുന്നു.
"താങ്കളുടെ രസീത് ഒന്നുകൂടി കാണിക്കാമോ?" അവൾ ചോദിക്കുന്നു.
ഞാൻ അവൾക്ക് ആ ചെറിയ പേപ്പർ രസീത് നൽകുന്നു.
അവൾ ബാർകോഡ് സ്കാൻ ചെയ്യുന്നു.
"ദാ, ഇപ്പോൾ ഇത് മാറ്റിയെടുത്തു," അവൾ പറയുന്നു.
"ഇതിന് അധിക ചിലവില്ല."
"സഹായിച്ചതിന് വളരെ നന്ദി," ഞാൻ പറയുന്നു.
"സ്വാഗതം, നല്ലൊരു ദിനം ആശംസിക്കുന്നു," അവൾ മറുപടി നൽകുന്നു.
ഞാൻ ആ ഷർട്ട് എന്റെ ബാഗിലേക്ക് വയ്ക്കുന്നു.
ഇപ്പോൾ ഒടുവിൽ എനിക്ക് വസന്തകാലത്തേക്ക് നല്ല കുറച്ച് വസ്ത്രങ്ങളായി.
ഞാൻ കടയിൽ നിന്ന് പുറത്തേക്ക് നടക്കുന്നു.
വീട്ടിലേക്ക് നടക്കുമ്പോൾ ഞാൻ വളരെ സന്തുഷ്ടയാണ്.
