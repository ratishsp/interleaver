Odchodzę od targu i znajduję małe, lokalne muzeum.
Wchodzę do cichego budynku.
Podchodzę do lady, żeby kupić bilet wstępu.
Za kasą stoi młody mężczyzna.
– Dzień dobry, poproszę jeden bilet normalny – mówię.
– To będzie sto koron – mówi i drukuje go.
Płacę i patrzę na te kolorowe broszury na ladzie.
Reklamują specjalną wystawę o historii miasta.
– Czy ten bilet zapewnia również wstęp na wystawę na górze? – pytam.
– Tak, to muzeum oferuje tylko jeden łączony bilet – odpowiada.
– Wystawa znajduje się na górze, na pierwszym piętrze – mówi.
– Może tam pani spędzić tyle czasu, ile zechce.
– Jest tam wiele starych zdjęć miasta – wyjaśnia.
– Niektóre z nich mają ponad sto lat.
– To brzmi naprawdę ciekawie – mówię.
– Bardzo dziękuję – uśmiecham się.
Biorę mój bilet i spokojnie wchodzę po schodach.
