ഞാൻ ബസ്സിൽ ഓഫീസിലേക്ക് യാത്ര ചെയ്യുകയാണ്.
പുറത്ത് നല്ല മഴയാണ്.
ഞാൻ നനഞ്ഞ ജനലിലൂടെ പുറത്തേക്ക് നോക്കുന്നു.
റോഡുകളിൽ നിറയെ വെള്ളമാണ്.
വീട്ടിൽ നിന്ന് മാറിയുള്ള എൻ്റെ ആദ്യത്തെ ജന്മദിനമാണിത്.
ഞാൻ ജനുവരി മാസം ഓർക്കുന്നു.
ഞാൻ ജനുവരിയിൽ കൊച്ചിയിൽ വന്നു.
അന്ന് എനിക്ക് ഇവിടെ ആരെയും അറിയില്ലായിരുന്നു.
എനിക്ക് നല്ല പേടിയുണ്ടായിരുന്നു.
ഇപ്പോൾ ഒരുപാട് കാര്യങ്ങൾ മാറിയിട്ടുണ്ട്.
എനിക്ക് നല്ല സുഹൃത്തുക്കളെ കിട്ടിയിട്ടുണ്ട്.
ഈ നഗരത്തെക്കുറിച്ച് ഞാൻ പുതിയ കാര്യങ്ങൾ പഠിച്ചിട്ടുണ്ട്.
എൻ്റെ ആദ്യത്തെ ദിവസം ഞാൻ ഇതേ ബസ്സിൽ യാത്ര ചെയ്തു.
ഈ വഴി ഇപ്പോൾ എന്റെ സ്വന്തം വഴി പോലെ തോന്നുന്നു.
ബസ് ഇൻഫോപാർക്കിൽ എത്തുന്നു.
ഞാൻ എൻ്റെ കുട തുറന്ന് ഓഫീസിലേക്ക് നടക്കുന്നു.
