Det är söndag eftermiddag, och det knackar på dörren.
Ludwig springer ut i hallen och skäller glatt.
Jag öppnar dörren, och Nina står utanför med sin weekendväska.
"Hej Maya, tack så mycket för hjälpen", säger hon och ler.
Han viftar på svansen och hoppar upp mot henne.
"Ner, Ludwig", säger Nina och klappar honom.
"Han har varit en riktigt duktig hund", berättar jag för henne.
Nina skrattar och tar hans hundkoppel från det lilla bordet.
"Gick du en promenad med honom i hundskogen?" frågar hon.
"Ja, och han älskade det", svarar jag.
Jag ger henne resten av hundmaten.
"Varsågod, här är resten."
"Jag passar honom väldigt gärna igen någon gång."
"Självklart", säger Nina.
"Kom, Ludwig, vi ska hem", säger Nina till hunden.
Jag vinkar hejdå till dem båda två.
Lägenheten är plötsligt mycket tyst utan honom.
