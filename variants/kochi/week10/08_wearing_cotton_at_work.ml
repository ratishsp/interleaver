പിറ്റേ ദിവസം രാവിലെ ഞാൻ ഓഫീസിൽ പോകുന്നു.
കൊച്ചിയിൽ ഇപ്പോൾ വലിയ ചൂടാണ്.
ഞാൻ ഇന്ന് എൻ്റെ പുതിയ മഞ്ഞ കുർത്തി ധരിക്കുന്നു.
ഇത് ഒരു കോട്ടൺ കുർത്തിയാണ്.
ഞാൻ എൻ്റെ സോഫ്റ്റ്‌വെയർ ഓഫീസിൽ എത്തുന്നു.
എൻ്റെ സഹപ്രവർത്തകൻ പ്രകാശ് അവിടെ ഉണ്ട്.
പ്രകാശ് എൻ്റെ പുതിയ കുർത്തി കാണുന്നു.
അദ്ദേഹം എന്നോട് പറയുന്നു, "മായാ, ഇത് നല്ല ഒരു കുർത്തിയാണ്."
"മഞ്ഞ നല്ല ഒരു നിറമാണ്."
ഞാൻ ചെറിയ ഒരു ചിരിയോടെ പറയുന്നു, "നന്ദി, പ്രകാശ്."
"ഇത് കനം കുറഞ്ഞ കോട്ടൺ ആണ്."
"കൊച്ചിയിലെ ചൂടിന് കോട്ടൺ വളരെ നല്ലതാണ്."
പ്രകാശ് പറയുന്നു, "അതെ, ഓഫീസിന് പുറത്ത് വലിയ ചൂടാണ്."
"എന്നാൽ ഈ ഓഫീസിൽ നല്ല തണുപ്പാണ്."
ഞാൻ എൻ്റെ സീറ്റിൽ ഇരിക്കുന്നു.
ഈ പുതിയ വസ്ത്രം വളരെ നല്ലതാണ്.
എനിക്ക് വലിയ സന്തോഷം ഉണ്ട്.
ഞാൻ എൻ്റെ ജോലി തുടങ്ങുന്നു.
