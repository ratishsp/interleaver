മെക്സിക്കോയിൽ ഇപ്പോൾ രാത്രിയാണ്.
ഇവിടെ കൊച്ചിയിൽ രാവിലെയാണ്.
എന്റെ കുടുംബം എനിക്ക് ബൈ പറയുന്നു.
"ഗുഡ് നൈറ്റ്, മായാ!" എന്റെ അമ്മ പറയുന്നു.
എന്റെ അനിയത്തി സോഫിയ സന്തോഷത്തോടെ കൈ വീശുന്നു.
അവളുടെ കൂടെ നായ ലോലയുമുണ്ട്.
എന്റെ ചേട്ടൻ ഡീഗോ ഉറക്കെ ചിരിക്കുന്നു.
അവന്റെ ചിരി എനിക്ക് വളരെ ഇഷ്ടമാണ്.
ഞാൻ കോൾ അവസാനിപ്പിക്കുന്നു.
ഞാൻ ഫോൺ ഒരു മേശപ്പുറത്ത് വെക്കുന്നു.
ഇപ്പോൾ മുറിയിൽ വലിയ നിശ്ശബ്ദതയാണ്.
ഞാൻ ജനലിന് പുറത്തേക്ക് നോക്കുന്നു.
പുറത്ത് ആരാണ്?
അവിടെ ആരുമില്ല.
എനിക്ക് പെട്ടെന്ന് വലിയ സങ്കടം വരുന്നു.
ഫോണിൽ എന്റെ കുടുംബത്തിന്റെ ഒരു ഫോട്ടോ ഉണ്ട്.
ഞാൻ ആ ഫോട്ടോ നോക്കുന്നു.
"നിങ്ങളുടെ കൂടെ ഞാൻ എപ്പോഴും ഉണ്ട്," ഞാൻ പതുക്കെ പറയുന്നു.
എനിക്ക് എന്റെ വീട് വളരെ ഓർമ്മ വരുന്നു.
