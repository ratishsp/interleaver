ഞാൻ ഓഫീസിൽ എൻ്റെ ഡെസ്കിൽ ഇരിക്കുകയാണ്.
ഞാൻ ഇന്ന് നേരത്തെ എത്തി.
ഞാൻ ഇതിനകം അര വർഷമായി ഇവിടെ ജോലി ചെയ്യുന്നു.
പെട്ടെന്ന് പീറ്ററും ഈവയും എൻ്റെ ഡെസ്കിനടുത്തേക്ക് വരുന്നു.
പീറ്റർ ഒരു മെഴുകുതിരി വെച്ച ചെറിയൊരു കേക്ക് കയ്യിൽ പിടിച്ചിട്ടുണ്ട്.
"ജന്മദിനാശംസകൾ, മായാ!" അവർ ഒരുമിച്ച് പറയുന്നു.
എനിക്ക് വലിയ സന്തോഷവും അത്ഭുതവും തോന്നുന്നു.
"വളരെ നന്ദി," ഞാൻ അവരോട് പറയുന്നു.
ഈവ വിടർന്നു പുഞ്ചിരിക്കുന്നു.
"ഇന്ന് രാവിലെ ബേക്കറിയിൽ നിന്നാണ് ഞങ്ങൾ ഈ കേക്ക് വാങ്ങിയത്," അവൾ വിശദീകരിക്കുന്നു.
"അതെ, ഞാൻ നമുക്കുള്ള കോഫി ഉണ്ടാക്കിയിട്ടുണ്ട്," പീറ്റർ കൂട്ടിച്ചേർക്കുന്നു.
അവൻ എൻ്റെ മേശപ്പുറത്ത് ഒരു വലിയ കപ്പ് കോഫി വെക്കുന്നു.
"നിങ്ങൾ ശരിക്കും വളരെ സ്നേഹമുള്ളവരാണ്," ഞാൻ പറയുന്നു.
"ഞാൻ മെക്സിക്കോയിൽ ജോലി ചെയ്തിരുന്നപ്പോൾ, രാവിലെ ഞങ്ങൾക്ക് കേക്ക് ലഭിക്കുന്നത് വളരെ അപൂർവ്വമായിരുന്നു."
പീറ്ററും ഈവയും രണ്ട് കസേരകൾ ഡെസ്കിനടുത്തേക്ക് വലിച്ചിടുന്നു.
ഞങ്ങൾ ഒരുമിച്ച് കേക്ക് കഴിക്കുന്നു, ഇത് എൻ്റെ ദിവസത്തിന് ഒരു മികച്ച തുടക്കമാണ്.
