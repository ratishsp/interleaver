Wchodzę po schodach.
Mam w rękach dwie torby.
Wreszcie jestem pod moimi nowymi drzwiami.
W kieszeni mam klucz.
Stawiam torby na podłodze.
Wyciągam klucz.
Otwieram drzwi kluczem.
Popycham drzwi i wchodzę do środka.
Mieszkanie jest małe, ale jest idealne.
Ma ładne, jasne meble.
Zaglądam do salonu.
Przy oknie stoi sofa.
Pod sofą leży dywan.
Na sofie leży mała poduszka.
W rogu stoi lampa.
Zamykam za sobą drzwi.
Kładę swój klucz na stole.
