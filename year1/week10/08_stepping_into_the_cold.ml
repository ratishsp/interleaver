"ഒരു കവർ വേണോ?" കടയിലെ ജീവനക്കാരൻ ചോദിക്കുന്നു.
"വേണ്ട, നന്ദി," ഞാൻ പറയുന്നു.
എനിക്ക് ഒരു കവർ ആവശ്യമില്ല.
ഞാൻ ഉടനടി ആ പുതിയ വസ്ത്രങ്ങൾ ധരിക്കുന്നു.
ആദ്യം, ഞാൻ കട്ടിയുള്ള, ചുവന്ന സ്വെറ്റർ ധരിക്കുന്നു.
പിന്നെ, ഞാൻ കടും നീല വിന്റർ ജാക്കറ്റ് ധരിക്കുന്നു.
ഞാൻ ആ ചൂടുള്ള ജാക്കറ്റിന്റെ സിപ്പ് ഇടുന്നു.
അതിനുശേഷം, ഞാൻ ആ നീളമുള്ള, നീല സ്കാർഫ് എടുക്കുന്നു.
ഞാൻ അത് എന്റെ കഴുത്തിൽ ചുറ്റുന്നു.
ഒടുവിൽ, ഞാൻ ആ പുതിയ, കറുത്ത ഗ്ലൗസുകൾ ധരിക്കുന്നു.
ഇപ്പോൾ ഞാൻ എന്റെ ചൂടുള്ള വസ്ത്രങ്ങളെല്ലാം ധരിച്ചിട്ടുണ്ട്.
ഞാൻ പുഞ്ചിരിച്ചുകൊണ്ട് യാത്ര പറയുന്നു.
ഞാൻ കടയ്ക്ക് പുറത്തേക്ക് നടക്കുന്നു.
ഞാൻ വീണ്ടും ആ തണുത്ത തെരുവിൽ നിൽക്കുന്നു.
മരവിപ്പിക്കുന്ന തണുപ്പാണവിടെ.
കാറ്റ് ശക്തിയായി വീശുന്നു.
എന്നാൽ എനിക്ക് ഒട്ടും തണുക്കുന്നില്ല.
ഇപ്പോൾ ഞാൻ മഞ്ഞുകാലത്തിന് തയ്യാറാണ്.
