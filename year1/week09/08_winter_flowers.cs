Jdu k východu z trhu.
Vidím velký stánek s květinami.
Stánek má mnoho krásných květin.
Zastavuji se před stánkem.
Dívám se na svazek zimních tulipánů.
Jsou velmi barevné.
Ukazuji na tulipány.
„Kolik stojí ty tulipány?“ ptám se prodavače.
Prodavač zvedá tulipány.
„Stojí čtyřicet korun,“ odpovídá.
„Koupím si je,“ říkám.
Platím za květiny.
Prodavač mi dává tulipány.
Teď mám na trhu hotovo.
Jdu zpátky do svého bytu.
Držím ty barevné tulipány v ruce.
Piju svou horkou kávu.
Slunce svítí nad rušným trhem.
