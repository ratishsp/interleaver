„Tašku?“ ptá se prodavač.
„Ne, děkuji,“ říkám.
Nepotřebuji tašku.
Hned si oblékám to nové oblečení.
Nejdřív si oblékám ten silný červený svetr.
Pak si oblékám tmavě modrou zimní bundu.
Zapínám si tu teplou bundu na zip.
Potom si beru tu dlouhou modrou šálu.
Omotávám si ji kolem krku.
Nakonec si nasazuji ty nové černé rukavice.
Teď mám na sobě všechno své teplé oblečení.
Usmívám se a říkám na shledanou.
Vycházím z obchodu.
Zase stojím venku na studené ulici.
Je mrazivá zima.
Vítr silně fouká.
Ale mně vůbec není zima.
Teď jsem na zimu připravená.
