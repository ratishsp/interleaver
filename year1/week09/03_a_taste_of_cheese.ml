എന്റെ മുന്നിൽ ഒരു വലിയ ചീസ് സ്റ്റാൾ ഉണ്ട്.
ആ സ്റ്റാളിൽ ഒരുപാട് വലിയ ചീസുകളുണ്ട്.
സൗഹൃദഭാവമുള്ള ഒരു കച്ചവടക്കാരൻ എന്നെ നോക്കി ചിരിക്കുന്നു.
അദ്ദേഹത്തിന്റെ കയ്യിൽ ഒരു മരക്കമ്പിൽ ചെറിയൊരു ചീസ് കഷണമുണ്ട്.
"ഇതാ, ഒന്നു രുചിച്ചു നോക്കൂ," അദ്ദേഹം പറയുന്നു.
അദ്ദേഹം ആ മരക്കമ്പ് എനിക്ക് തരുന്നു.
ഞാൻ ആ മഞ്ഞ ചീസ് കഴിക്കുന്നു.
അതിന് വളരെ നല്ല രുചിയുണ്ട്.
ഞാൻ ചെറിയൊരു ചീസിലേക്ക് നോക്കുന്നു.
"ഈ ചീസിന് എത്രയാ വില?" ഞാൻ ചോദിക്കുന്നു.
"ഇതിന് അൻപത്തഞ്ച് ക്രോണറാണ്," കച്ചവടക്കാരൻ മറുപടി പറയുന്നു.
അതൊരു നല്ല വിലയാണ്.
ഞാൻ ആ ചെറിയ ചീസിലേക്ക് ചൂണ്ടിക്കാണിക്കുന്നു.
"ഞാൻ ഇത് വാങ്ങാം," ഞാൻ പറയുന്നു.
അദ്ദേഹം ആ ചീസ് കടലാസിൽ പൊതിയുന്നു.
ഞാൻ അദ്ദേഹത്തിന് പണം കൊടുക്കുന്നു.
"വളരെ നന്ദി," അദ്ദേഹം പറയുന്നു.
ആ ചീസിന് കടുപ്പമുള്ള നല്ല മണമുണ്ട്.
