Můj budík zvoní nahlas.
Je ráno, ale stále je tma.
Otevírám oči.
Dívám se směrem k oknu.
Venku je úplně černo.
Slunce ještě vůbec nevyšlo.
V Dánsku je stále zima.
Ráno je tu neuvěřitelná tma.
Rozednívá se velmi pozdě.
Pomalu si sedám v posteli.
Mimo peřinu je zima.
Rozsvěcím lampu na stole.
S trochou světla je hned příjemněji.
Za oknem je obloha stále úplně černá.
V Mexiku je teď často spousta slunečního světla.
Ale tady slunce spí.
Ve tmě je těžké se probouzet.
Dívám se na hodiny.
Vstávám z postele.
Den začíná teď.
