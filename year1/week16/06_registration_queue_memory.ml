ഞാൻ സ്‌ക്രീനിൽ എൻ്റെ അമ്മയെ നോക്കുന്നു.
ആ നീണ്ട ക്യൂവിനെക്കുറിച്ച് കൂടുതൽ കേൾക്കാൻ അവർ ആഗ്രഹിക്കുന്നു.
ആ നീണ്ട പ്രഭാതത്തെക്കുറിച്ച് ഞാൻ അവരോട് പറയുന്നു.
"ജനുവരിയിലെ തണുപ്പുള്ള ഒരു ചൊവ്വാഴ്ചയായിരുന്നു അത്," ഞാൻ പറയുന്നു.
ഞാൻ നഗരത്തിലെ സിറ്റിസൺ സെൻ്ററിലേക്ക് ബസ്സിലാണ് പോയത്.
ആ വലിയ മുറിയിൽ ശരിക്കും ഒത്തിരി ആളുകളുണ്ടായിരുന്നു.
ഒരു ചെറിയ മെഷീനിൽ നിന്ന് ഞാൻ ഒരു നമ്പർ എടുത്തു.
എൻ്റെ നമ്പർ അൻപത്തൊൻപത് ആയിരുന്നു.
എന്നാൽ ഭിത്തിയിലെ സ്‌ക്രീനിൽ ഇരുപത്തൊന്ന് മാത്രമേ കാണിച്ചിരുന്നുള്ളൂ.
ക്യൂ അവിശ്വസനീയമാംവിധം മന്ദഗതിയിലായിരുന്നു.
ഞാൻ ഒരു കട്ടിയുള്ള കസേരയിൽ ഇരുന്ന് രണ്ട് മണിക്കൂർ കാത്തിരുന്നു.
ഞാൻ ഇടയ്ക്കിടെ സ്‌ക്രീനിലേക്ക് നോക്കിയിരുന്നു.
ഒടുവിൽ, സൗഹൃദഭാവമുള്ള ഒരാൾ എൻ്റെ നമ്പർ വിളിച്ചു.
ഞാൻ എഴുന്നേറ്റ് അയാളുടെ ഡെസ്കിനടുത്തേക്ക് നടന്നു.
എൻ്റെ പാസ്‌പോർട്ടും സോഫ്റ്റ്‌വെയർ കമ്പനിയിൽ നിന്നുള്ള എൻ്റെ രേഖകളും ഞാൻ അയാൾക്ക് നൽകി.
അയാൾ ആ പേപ്പറുകൾ വായിക്കുകയും കമ്പ്യൂട്ടറിൽ ടൈപ്പ് ചെയ്യുകയും ചെയ്തു.
ഒടുവിൽ എനിക്ക് എൻ്റെ CPR നമ്പർ കിട്ടി.
ആ പ്രധാനപ്പെട്ട നമ്പർ വളരെ ശ്രദ്ധയോടെ സൂക്ഷിക്കാൻ അയാൾ എന്നോട് ആവശ്യപ്പെട്ടു.
"നിനക്ക് വളരെ ക്ഷമയുണ്ടായിരുന്നല്ലോ," അമ്മ പുഞ്ചിരിക്കുന്നു.
