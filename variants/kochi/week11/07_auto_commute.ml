പുറത്ത് നല്ല മഴ പെയ്യുന്നു.
നല്ല കാറ്റുമുണ്ട്.
എന്റെ കുട വളരെ ചെറുതാണ്.
അതുകൊണ്ട് ഞാൻ ഒരു ഓട്ടോ നോക്കുന്നു.
പെട്ടെന്ന് ഒരു ഓട്ടോ വരുന്നു.
ഞാൻ ഓട്ടോ വിളിക്കുന്നു.
ഡ്രൈവർ ഓട്ടോ നിർത്തുന്നു.
"പനമ്പിള്ളി നഗറിലേക്ക്," ഞാൻ പറയുന്നു.
"കയറിക്കോളൂ," ഡ്രൈവർ പറയുന്നു.
ഞാൻ വേഗം ഓട്ടോയിൽ കയറുന്നു.
ഇപ്പോൾ ഞാൻ സുരക്ഷിതയാണ്.
കൊച്ചിയിലെ കാലാവസ്ഥ വേഗം മാറുന്നു.
രാവിലെ നല്ല വെയിലാണ്.
ഉച്ചയ്ക്ക് നല്ല ചൂടാണ്.
എന്നാൽ ഇപ്പോൾ നല്ല മഴ പെയ്യുന്നു.
അപ്ലിക്കേഷൻ പറയുന്നു, രാത്രിയും മഴ പെയ്യും.
റോഡിൽ മുഴുവൻ ഇപ്പോൾ വെള്ളമാണ്.
ഓട്ടോ വെള്ളത്തിലൂടെ സാവധാനം പോകുന്നു.
ഞാൻ പുറത്തെ മഴ നോക്കി ഇരിക്കുന്നു.
