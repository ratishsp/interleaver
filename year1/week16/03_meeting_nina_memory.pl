Kasper chciał posłuchać o moim zupełnie pierwszym popołudniu.
To było zimne popołudnie w styczniu.
Weszłam po schodach do mojego nowego mieszkania.
Miałam jedną, bardzo ciężką walizkę.
Byłam bardzo zmęczona po długiej podróży.
Sama wniosłam moją walizkę na górę i do środka.
Chwilę później wyszłam na klatkę schodową.
Drzwi obok moich się otworzyły.
Wyszła młoda kobieta i uśmiechnęła się do mnie.
„Cześć, mam na imię Nina” – powiedziała.
„Też mieszkam tutaj w budynku”.
Odwzajemniłam uśmiech i podałam swoje imię.
Nina mieszkała tuż obok mnie.
Porozmawiałyśmy trochę na klatce schodowej.
Miło było od razu poznać sąsiadkę.
„Witaj w Danii” – powiedziała Nina.
To był mój pierwszy dzień tutaj.
Cieszyłam się, bo miałam już przyjaciółkę.
