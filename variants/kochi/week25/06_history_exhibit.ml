ഞാൻ മ്യൂസിയത്തിലൂടെ പതുക്കെ നടക്കുന്നു.
പുറത്ത്, മഴ മേൽക്കൂരയിൽ ശക്തിയായി വീഴുന്നു.
പക്ഷേ ഈ ഹാൾ വളരെ ശാന്തമാണ്.
ഇവിടെ പഴയ ഒരുപാട് സാധനങ്ങൾ ഉണ്ട്.
ഞാൻ ഒരു വലിയ ഗ്ലാസ്സ് പെട്ടി കാണുന്നു.
അത് എന്താണ്?
ഞാൻ ആ പെട്ടിക്ക് അടുത്തേക്ക് പോകുന്നു.
അതിൽ കുറച്ച് പഴയ നാണയങ്ങളും മരക്കഷണങ്ങളും ഉണ്ട്.
ഞാൻ അതിനടുത്തുള്ള ചെറിയ ബോർഡ് വായിക്കുന്നു.
അത് ഒരു പഴയ പോർച്ചുഗീസ് കപ്പലിനെക്കുറിച്ചാണ്.
ആ കപ്പൽ നൂറുകണക്കിന് വർഷങ്ങൾക്ക് മുമ്പ് കൊച്ചിയിൽ വന്നതാണ്.
പക്ഷേ അത് കടലിൽ മുങ്ങിപ്പോയി.
ഇത് ആ കപ്പലിന്റെ ഭാഗങ്ങളാണ്.
കൊച്ചിക്ക് വളരെ വലിയ ഒരു ചരിത്രം ഉണ്ട്.
വളരെക്കാലം മുമ്പ് പല രാജ്യങ്ങളിൽ നിന്നുള്ള ആളുകൾ ഇവിടെ വന്നു.
ഞാൻ എന്റെ യാത്രയെക്കുറിച്ചും ചിന്തിക്കുന്നു.
എനിക്ക് അത് ഒരുപാട് കാലം മുമ്പാണെന്ന് തോന്നുന്നു.
പക്ഷേ ഈ ചരിത്രത്തിന് മുന്നിൽ അത് ഒന്നുമല്ല.
ഞാൻ ആ മ്യൂസിയത്തിൽ സമാധാനത്തോടെ ഒരു മണിക്കൂർ ചെലവഴിക്കുന്നു.
