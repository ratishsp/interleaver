അത് രണ്ടു മൂന്നു തവണ റിംഗ് ചെയ്യുന്നു.
സ്ക്രീൻ പ്രകാശിക്കുന്നു.
ഞാൻ ഒരു സ്വീകരണമുറി കാണുന്നു.
അവിടെ വെയിലുണ്ട്, സ്വീകരണമുറിയിൽ നല്ല വെളിച്ചവുമുണ്ട്.
ഞാൻ രണ്ട് ആളുകളെ കാണുന്നു.
അത് എന്റെ അമ്മയും അച്ഛനുമാണ്.
അവർ ഒരുപാട് ചിരിക്കുകയും എന്നെ നോക്കി കൈ വീശുകയും ചെയ്യുന്നു.
"ഹലോ അമ്മേ, അച്ഛാ!" ഞാൻ ഉച്ചത്തിൽ പറയുന്നു.
"ഹലോ, മായ," എന്റെ അച്ഛൻ പറയുന്നു.
"എന്തൊക്കെയുണ്ട് വിശേഷം?"
"എല്ലാം നന്നായി പോകുന്നു," ഞാൻ സന്തോഷത്തോടെ മറുപടി നൽകുന്നു.
പെട്ടെന്ന് ഞാൻ ഒരു ശബ്ദം കേൾക്കുന്നു.
അതൊരു ചെറിയ കുരയാണ്.
"ഓ, ഞാൻ ഒരു നായയുടെ ശബ്ദം കേൾക്കുന്നു!" എന്ന് പറഞ്ഞ് ഞാൻ ചിരിക്കുന്നു.
ഒരു ചെറിയ നായ സോഫയിലേക്ക് ചാടിക്കയറുന്നു.
അത് ക്യാമറയിലേക്ക് നോക്കുന്നു.
"അതാ എന്റെ നായ!"
"ഹലോ, ലോല," ഞാൻ പറയുന്നു.
ലോല അവളുടെ വാലാട്ടുന്നു.
"അതെ, ഇത് നിന്റെ നായയാണ്," എന്റെ അമ്മ ചിരിച്ചുകൊണ്ട് പറയുന്നു.
ഞാൻ എന്റെ കുടുംബത്തെ സ്നേഹിക്കുന്നു.
അവരെയെല്ലാവരെയും കാണുന്നത് വളരെ സന്തോഷമുള്ള കാര്യമാണ്.
