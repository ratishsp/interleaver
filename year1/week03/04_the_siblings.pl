Teraz na moim ekranie są dwie nowe twarze.
To moja młodsza siostra, Sofía, i mój starszy brat, Diego.
Śmieją się i trochę się przepychają.
„Cześć, młodsza siostro i starszy bracie!” – mówię radośnie.
„Cześć, Maya” – mówi Diego.
Mój brat uśmiecha się szeroko.
„Czy w Danii jest zimno?” – pyta.
„Czy to mroźna zima?”
„Tak, to bardzo mroźna zima” – śmieję się.
„Ale mam ciepły pokój i kubek herbaty.”
Teraz Sofía podnosi dużą rzecz przed ekranem.
To duża książka.
„Masz tam nową książkę, Sofía?” – pytam.
„Tak, to moja nowa książka” – mówi z dumą moja siostra.
„To książka z mojego uniwersytetu.”
„To bardzo gruba książka!”
Uśmiecham się do mojego brata i mojej siostry.
Tęsknię za moją rodziną w Meksyku.
Ale są właśnie tutaj, na moim małym ekranie.
