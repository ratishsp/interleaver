Dorazila jsem do Odense krátce po deváté.
Odešla jsem z nádraží a šla přímo ke staré čtvrti.
Svítilo slunce a já si užívala svěží jarní vzduch.
Po krátké procházce se město změnilo.
Najednou jsem stála v úzké ulici s dlažebními kostkami.
Dlažební kostky byly ošlapané a staré.
Dívala jsem se na spoustu malých domů.
Stály těsně vedle sebe v řadě podél ulice.
Téměř všechny domy byly legrační a velmi křivé.
Každý dům ukazoval svou vlastní osobnost.
Mnoho z nich bylo natřeno krásnými, jasnými barvami.
Obzvlášť jsem si všimla žlutých a červených domů.
Barevné zdi zářily v jarním slunci.
Starou část města jsem prostě milovala.
Dlouho jsem stála a dívala se na ty křivé domy.
Každý dům měl svou vlastní veselou barvu.
Chtěla jsem si tuhle ulici zapamatovat navždy.
Potom jsem pomalu šla dál ulicí.
