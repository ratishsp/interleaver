ഇന്ന് വെള്ളിയാഴ്ച വൈകുന്നേരമാണ്.
ഞാൻ ഓഫീസിന്റെ ജനലിലൂടെ പുറത്തേക്ക് നോക്കുന്നു.
ആകാശത്ത് നിറയെ കറുത്ത മേഘങ്ങൾ ഉണ്ട്.
പെട്ടെന്ന് ശക്തമായ മഴ പെയ്യും എന്ന് ഞാൻ കരുതുന്നു.
എനിക്ക് ഇപ്പോൾ ദീപയുടെ വീട്ടിൽ പോകണം.
ഞാൻ ഫോണിൽ മാപ്പ് ആപ്പ് തുറക്കുന്നു.
ദീപയുടെ സ്ഥലത്തേക്കുള്ള വഴി ഞാൻ തിരയുന്നു.
മാപ്പിൽ വലിയ ട്രാഫിക് കാണിക്കുന്നു.
ഞാൻ സാധാരണയായി ഇൻഫോപാർക്കിൽ നിന്ന് ബസ്സിലാണ് പോകാറുള്ളത്.
പക്ഷേ, ഇന്ന് ബസ് യാത്രയ്ക്ക് ഒരുപാട് സമയം എടുക്കും.
ബസ്സിൽ വലിയ തിരക്ക് ഉണ്ടാകും എന്ന് എനിക്ക് തോന്നുന്നു.
മഴ കാരണം യാത്ര ബുദ്ധിമുട്ടാകും.
അതുകൊണ്ട്, ഞാൻ ഒരു ഓട്ടോ വിളിക്കാം എന്ന് തീരുമാനിക്കുന്നു.
ഓട്ടോയ്ക്ക് ചെറിയ വഴികളിലൂടെ പോകാൻ കഴിയും.
അങ്ങനെ പോയാൽ, ഞാൻ വേഗം ദീപയുടെ വീട്ടിൽ എത്തും.
ഞാൻ എന്റെ ബാഗും മധുരപലഹാരങ്ങളുടെ പെട്ടിയും എടുക്കുന്നു.
ഓഫീസ് ഗേറ്റിൽ നിന്ന് എനിക്ക് ഒരു ഓട്ടോ കിട്ടും.
ഞാൻ വേഗം താഴേക്ക് നടക്കുന്നു.
