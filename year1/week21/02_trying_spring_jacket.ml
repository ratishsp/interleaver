ഞാൻ ഒരു വലിയ തുണിക്കടയിലേക്ക് കയറുന്നു.
ഞാൻ പുതിയ വസന്തകാല വസ്ത്രങ്ങൾ നോക്കുന്നു.
ധാരാളം കനംകുറഞ്ഞ ജാക്കറ്റുകളും ഷർട്ടുകളും അവിടെ തൂക്കിയിട്ടിട്ടുണ്ട്.
ഞാൻ കടയ്ക്ക് ചുറ്റും പതുക്കെ നോക്കുന്നു.
എല്ലാം വളരെ പുതുമയുള്ളതും വസന്തകാലത്തിന്റേതുമായി കാണപ്പെടുന്നു.
പെട്ടെന്ന് ഞാൻ വളരെ മനോഹരമായ ഒരു ജാക്കറ്റ് കാണുന്നു.
അതിന് ഇളം പച്ച നിറമാണ്.
ഞാൻ അത് ഹാങ്ങറിൽ നിന്ന് താഴെയെടുക്കുന്നു.
എനിക്കിത് ഇട്ടുനോക്കണം.
നിലത്ത് ഒരു വലിയ കണ്ണാടി വെച്ചിട്ടുണ്ട്.
അതിനാൽ എനിക്ക് ഒരു ഫിറ്റിംഗ് റൂമിന്റെ ആവശ്യമില്ല.
ഞാൻ ആ ഇളം പച്ച ജാക്കറ്റ് ധരിക്കുന്നു.
ഞാൻ കണ്ണാടിയിൽ എന്നെത്തന്നെ നോക്കുന്നു.
ജാക്കറ്റ് എനിക്ക് നന്നായി പാകമാകുന്നുണ്ട്.
ഇത് വല്ലാതെ വലുതുമല്ല, വല്ലാതെ ചെറുതുമല്ല.
ശരിക്കും ഇത് കൃത്യം പാകമാണ്.
ഇതിന്റെ നിറവും എനിക്ക് നന്നായി ചേരുന്നുണ്ട്.
ഞാൻ കണ്ണാടി നോക്കി പുഞ്ചിരിക്കുന്നു.
ഞാൻ വീണ്ടും ആ ജാക്കറ്റ് ഊരി മാറ്റുന്നു.
അത് വാങ്ങാൻ ഞാൻ തീരുമാനിക്കുന്നു.
