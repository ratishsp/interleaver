Stojím u okna v obýváku.
Dívám se ven na město.
Obloha už není černá.
Pomalu šedne.
Slunce vychází pozdě.
Beru si telefon.
Čtu si předpověď počasí na dnešek.
Právě teď je velmi chladno.
Jsou jen dva stupně.
Ale venku je stále sucho.
Později bude velmi mokro.
Brzy bude pršet.
Bude také větrno.
Později během dne bude silně foukat.
Bude to opravdový zimní den.
Pokládám telefon na stůl.
Dívám se na oblohu ještě jednou.
