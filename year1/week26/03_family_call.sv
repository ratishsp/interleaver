På kvällen sitter jag i min soffa med min dator.
Jag ringer upp min familj i Mexiko.
Skärmen visar mina föräldrar, min syster Sofía och min bror Diego.
Vår hund, Lola, är också där.
"Grattis på födelsedagen!" ropar de allihop.
Sofía frågar.
"Har du fått vårt paket?"
"Ja, det kom med posten igår," svarar jag.
"Har du öppnat det?" frågar hon ivrigt.
Jag ler och tar en färgglad halsduk från bordet.
"Jag öppnade det när jag kom hem," säger jag och håller upp halsduken.
"Jag älskar verkligen färgerna."
Jag lägger halsduken runt halsen.
"Den klär dig bra," säger min mamma.
"Har du haft en bra dag idag?" frågar min pappa.
"Ja, mina kollegor köpte en tårta till mig tidigare," förklarar jag.
Diego lyfter upp Lola till kameran.
"Lola har också ätit en liten kaka," skrattar han.
Jag skrattar högt åt den lilla hunden.
Det är min första födelsedag borta hemifrån, men de känns väldigt nära.
