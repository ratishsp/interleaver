ഞാൻ മാർക്കറ്റിലൂടെ നടക്കുന്നു.
അവിടെ നല്ല തിരക്കുണ്ട്.
ഞാൻ വലിയ ഒരു പച്ചക്കറിക്കട കാണുന്നു.
അവിടെ നല്ല ചുവന്ന തക്കാളി ഉണ്ട്.
ഞാൻ ആ തക്കാളി ചൂണ്ടിക്കാണിക്കുന്നു.
"ചേട്ടാ, ഒരു കിലോ തക്കാളിക്ക് വില എത്ര?" ഞാൻ ചോദിക്കുന്നു.
"നാൽപ്പതു രൂപ," കച്ചവടക്കാരൻ പറയുന്നു.
ഞാൻ തലയാട്ടുന്നു.
ഞാൻ കുറച്ചു വലിയ തക്കാളി എടുക്കുന്നു.
ഞാൻ അത് അയാൾക്ക് കൊടുക്കുന്നു.
"ഇത് തൂക്കി തരൂ," ഞാൻ പറയുന്നു.
അയാൾ തക്കാളി ത്രാസിൽ വയ്ക്കുന്നു.
"അരക്കിലോ ഉണ്ട്," അയാൾ പറയുന്നു.
"ഇരുപതു രൂപ ആയി."
ഞാൻ ഇരുപതു രൂപ കൊടുക്കുന്നു.
അയാൾ തക്കാളി എന്റെ തുണിസഞ്ചിയിൽ വയ്ക്കുന്നു.
ഞാൻ നന്ദി പറയുന്നു.
ഞാൻ അടുത്ത കടയിലേക്ക് പോകുന്നു.
