Vejdu do velkého obchodu s oblečením.
Dívám se na nové jarní oblečení.
Visí tam mnoho lehkých bund a košil.
Pomalu se rozhlížím po obchodě.
Všechno vypadá svěže a jarně.
Najednou vidím velmi pěknou bundu.
Je světle zelená.
Sundám ji z ramínka.
Chtěla bych si ji vyzkoušet.
Na podlaze stojí velké zrcadlo.
Takže nepotřebuji zkušební kabinku.
Obléknu si tu světle zelenou bundu.
Dívám se na sebe do zrcadla.
Bunda mi sedí opravdu dobře.
Není příliš velká a není příliš malá.
Vlastně mi padne perfektně.
Ta barva mi také sluší.
Usměju se do zrcadla.
Zase si bundu svléknu.
Rozhodnu se ji koupit.
