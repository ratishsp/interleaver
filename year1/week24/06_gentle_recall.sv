Ludwig springer glatt runt i skogen.
Plötsligt ser han en stor fågel.
Han springer snabbt efter den.
Han springer ända bort mot träden.
"Stanna, Ludwig!" ropar jag högt.
"Kom hit!"
Jag tar upp en liten godbit ur fickan.
Jag sätter mig på huk i gräset.
"Ludwig, titta här," ropar jag mjukt.
Han stannar upp och tittar på mig.
Han vill väldigt gärna ha godbiten.
Han springer snabbt tillbaka till mig.
"Sitt," säger jag lugnt.
Han sätter sig ner, och jag ger den till honom.
"Duktig hund," säger jag och klappar honom.
Jag sätter fast kopplet på honom igen.
Nu ska vi hem och koppla av.
