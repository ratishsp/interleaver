ഞാൻ നാലരയ്ക്ക് ഹെയർഡ്രസ്സറുടെ അടുത്തെത്തുന്നു.
ഞാൻ എപ്പോഴും കൃത്യനിഷ്ഠ പാലിക്കാറുണ്ട്.
ഹെയർഡ്രസ്സർ എന്നെ അഭിവാദ്യം ചെയ്യുന്നു.
അവർ എന്റെ മുടി കഴുകി വെട്ടുന്നു.
ഇതിന് ഏകദേശം ഒരു മണിക്കൂർ സമയമെടുക്കുന്നു.
എന്റെ പുതിയ മുടി വളരെ മനോഹരമാണ്.
ഞാൻ ഹെയർഡ്രസ്സറോട് നന്ദി പറഞ്ഞ് സലൂണിൽ നിന്ന് ഇറങ്ങുന്നു.
എന്റെ സൈക്കിൾ പുറത്ത് മുന്നിലുണ്ട്.
ഞാൻ നഗരത്തിലൂടെ സൈക്കിൾ ചവിട്ടുന്നു.
ഇപ്പോൾ വ്യാഴാഴ്ച വൈകുന്നേരമാണ്.
ഞാൻ സൈക്കിൾ ചവിട്ടി മനോഹരമായ ഒരു കഫേയിലേക്ക് പോകുന്നു.
ഞാൻ എന്റെ സൈക്കിൾ പാർക്ക് ചെയ്ത് അകത്തേക്ക് കയറുന്നു.
നീന ഇതിനകം തന്നെ ഒരു മേശയ്ക്കരികിൽ ഇരിക്കുന്നുണ്ട്.
ഞാൻ എന്റെ വാച്ചിൽ നോക്കുന്നു.
സമയം കൃത്യം ആറുമണിയാണ്.
"ഹായ് മായ, നിന്റെ മുടി ശരിക്കും നന്നായിട്ടുണ്ട്," നീന പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
ഞങ്ങൾ രണ്ട് കപ്പ് കോഫി ഓർഡർ ചെയ്യുന്നു.
ഞങ്ങൾ കോഫി കുടിക്കുകയും പരസ്പരം സംസാരിക്കുകയും ചെയ്യുന്നു.
ഞാൻ എപ്പോഴും ഞങ്ങളുടെ കോഫി ഡേറ്റുകൾ ആസ്വദിക്കാറുണ്ട്.
