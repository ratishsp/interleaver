Piję moją wodę.
Woda jest zimna i przyjemna.
Zabieram moją torbę z podłogi.
Skończyłam moją przerwę.
Podchodzę do lady.
Miły barista nadal tam stoi.
Patrzy na mnie z uśmiechem.
„Czy chciałaby pani coś jeszcze?” – pyta.
„Nie, dziękuję” – odpowiadam.
„Chciałabym zapłacić.”
„Tak, oczywiście” – mówi.
Patrzy na swój mały ekran.
„Jedna czarna kawa i jedna bułeczka cynamonowa” – mówi.
„Tak, zgadza się” – mówię.
„Chce pani zapłacić kartą czy gotówką?” – pyta.
„Chciałabym zapłacić kartą” – odpowiadam.
„Dobrze.”
„To będzie osiemdziesiąt pięć koron” – mówi.
Wyciągam moją kartę płatniczą.
