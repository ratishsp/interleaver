എന്റെ അനിയത്തി സോഫിയ സ്ക്രീനിൽ വരുന്നു.
അവൾ എന്റെ അമ്മയുടെ അടുത്ത് ഇരിക്കുന്നു.
"ചേച്ചീ, ചേച്ചിയുടെ കയ്യിൽ എന്താണ്?" അവൾ ചോദിക്കുന്നു.
ഞാൻ ഒരു ചെറിയ പെട്ടി എടുക്കുന്നു.
അതൊരു ബേക്കറി പെട്ടിയാണ്.
ഞാൻ ആ പെട്ടി തുറക്കുന്നു.
അതിൽ ഒരു മധുരപലഹാരമുണ്ട്.
ഞാൻ അത് ക്യാമറയിൽ കാണിക്കുന്നു.
"ഇതിന്റെ പേര് ഹൽവ," ഞാൻ അവളോട് പറയുന്നു.
ഇതൊരു നല്ല പലഹാരമാണ്.
"ആരാണ് അത് ഉണ്ടാക്കുന്നത്?" സോഫിയ ചോദിക്കുന്നു.
"കൊച്ചിയിലെ ഒരു ബേക്കറി," ഞാൻ പറയുന്നു.
ഈ ഹൽവയ്ക്ക് നല്ല ചുവപ്പ് നിറമാണ്.
"അതിന് നല്ല മധുരമുണ്ടോ?" അവൾ ചോദിക്കുന്നു.
"അതെ, ഇതിന് നല്ല രുചിയുണ്ട്," ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ ഒരു ചെറിയ കഷ്ണം കഴിക്കുന്നു.
അവളുടെ മുഖത്ത് വളരെ സന്തോഷമുണ്ട്.
എനിക്കും ഈ മധുരം വളരെ ഇഷ്ടമാണ്.
