To była moja druga sobotnia zmiana w kawiarni.
Nauczyłam się już wykonywać dużą część pracy.
Tego przedpołudnia na zewnątrz było cudownie ciepło.
Pewna kobieta podeszła do lady.
„Poproszę o piwo imbirowe” – powiedziała.
„Oczywiście, chwileczkę” – odpowiedziałam.
Podeszłam do dużej, przeszklonej lodówki za ladą.
Spojrzałam na trzecią półkę.
Stały tam zimne butelki z piwem imbirowym.
Znalazłam butelkę i wyjęłam ją.
Imbir leżał jak gęsta chmura na samym dnie.
Nauczyłam się to mieszać, zanim otworzę butelkę.
Odwróciłam więc butelkę bardzo ostrożnie do góry dnem.
Przytrzymałam ją tak przez kilka sekund.
Imbir powoli wymieszał się z resztą płynu.
Teraz napój wyglądał idealnie.
Odwróciłam butelkę z powrotem i postawiłam ją na ladzie.
„Proszę bardzo, to będzie trzydzieści pięć koron” – powiedziałam do niej.
Zapłaciła i na pewno ze smakiem wypiła swój zimny napój.
