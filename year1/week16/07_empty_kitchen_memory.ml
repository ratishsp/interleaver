ആദ്യത്തെ ആ വൈകുന്നേരം എനിക്ക് കുഴപ്പമൊന്നും ഇല്ലായിരുന്നോ എന്ന് എൻ്റെ അമ്മ ചോദിക്കുന്നു.
അപ്പാർട്ട്മെന്റ് ഫർണിഷ് ചെയ്തതായിരുന്നു, എങ്കിലും എനിക്കത് പുതിയതായിരുന്നു.
അടുക്കളയിൽ അപ്പോൾ യാതൊരു ഭക്ഷണവും ഉണ്ടായിരുന്നില്ല.
വീട്ടിലേക്കുള്ള വഴിയിൽ ഞാൻ ലളിതമായ ഒരു അത്താഴം വാങ്ങി.
ഒരു കടയിൽ നിന്ന് വാങ്ങിയ സാൻഡ്‌വിച്ചായിരുന്നു അത്.
ഞാൻ ആ ചെറിയ സോഫയിൽ ഇരുന്നു.
അപ്പാർട്ട്മെന്റ് വളരെ നിശബ്ദമായിരുന്നു.
ഞാൻ വളരെ നിശബ്ദമായി എൻ്റെ അത്താഴം കഴിച്ചു.
എൻ്റെ അയൽക്കാരിയായ നീനയെ മാത്രമേ എനിക്ക് അപ്പോഴും പരിചയമുണ്ടായിരുന്നുള്ളൂ.
"അന്ന് വൈകുന്നേരം ഞാൻ നിങ്ങളെ എല്ലാവരെയും വല്ലാതെ മിസ്സ് ചെയ്തു," ഞാൻ അവരോട് പറയുന്നു.
എൻ്റെ സഹോദരി സോഫിയയെയും സഹോദരൻ ഡീഗോയെയും കുറിച്ച് ഞാൻ ഓർത്തു.
ഞങ്ങളുടെ നായ ലോലയെപ്പോലും ഞാൻ മിസ്സ് ചെയ്തു.
എന്നാൽ എൻ്റെ പുതിയ ജീവിതത്തിനായി ഞാൻ പ്രതീക്ഷയോടെ കാത്തിരിക്കുകയായിരുന്നു.
എൻ്റെ അമ്മ അവരുടെ നെഞ്ചിൽ കൈവയ്ക്കുന്നു.
"തുടക്കം എപ്പോഴും ബുദ്ധിമുട്ടായിരിക്കും," അവർ മറുപടി നൽകുന്നു.
ഞാൻ തലയാട്ടിക്കൊണ്ട് ആ ദിവസത്തെക്കുറിച്ച് ഓർക്കുന്നു.
അതൊരു ബുദ്ധിമുട്ടുള്ള വൈകുന്നേരമായിരുന്നു, എന്നാൽ പിറ്റേന്ന് രാവിലെ വളരെ മികച്ചതായിരുന്നു.
