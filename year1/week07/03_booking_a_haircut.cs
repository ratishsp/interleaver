Mám polední přestávku.
Sedím v kantýně v práci.
Včera jsem měla napilno.
Proto teď volám kadeřnici.
Beru si mobilní telefon.
Volám do kadeřnictví ve městě.
Telefon zvedá nějaká žena.
„Dobrý den, tady kadeřnictví,“ říká žena.
„Dobrý den, jmenuji se Maya,“ říkám.
„Chtěla bych se objednat na čtvrtek.“
„Okamžik,“ říká kadeřnice.
„Máte nějaký termín odpoledne?“ ptám se.
„Ano, máme volný termín v půl páté,“ říká.
„To mi velmi vyhovuje,“ říkám.
„Jaké je vaše telefonní číslo?“ ptá se kadeřnice.
„Moje číslo je dvanáct, třicet čtyři, padesát šest, sedmdesát osm,“ říkám.
„Moc děkuji, uvidíme se ve čtvrtek v půl páté,“ říká.
„Na viděnou,“ odpovídám.
Pokládám telefon na stůl.
Teď konečně jím své jídlo.
