"ടാക്സി എന്റെ കെട്ടിടത്തിന് മുന്നിൽ എത്തി," ഞാൻ സാറയോടും കിരണിനോടും പറഞ്ഞു.
"എന്റെ കൈയിൽ ഒരു വലിയ ബാഗ് ഉണ്ടായിരുന്നു."
"എന്റെ മുറി മുകളിലത്തെ നിലയിൽ ആയിരുന്നു."
"അതുകൊണ്ട് ഞാൻ ബാഗും എടുത്ത് പടികൾ കയറി."
"നിങ്ങൾ ഒറ്റയ്ക്കാണോ ആ ബാഗ് എടുത്തത്?"
കിരൺ പെട്ടെന്ന് ചോദിച്ചു.
"അതെ, ബാഗിന് നല്ല ഭാരം ഉണ്ടായിരുന്നു," ഞാൻ മറുപടി പറഞ്ഞു.
"ഞാൻ വളരെ പതുക്കെയാണ് നടന്നു കയറിയത്."
"അവസാനം ഞാൻ എന്റെ മുറിയുടെ വാതിലിന് മുന്നിൽ എത്തി."
"അന്ന് വൈകുന്നേരം ഞാൻ മുറിയിൽ നിന്ന് പുറത്തിറങ്ങി."
"പടികൾക്ക് അടുത്ത് വെച്ച് ഞാൻ എന്റെ അയൽക്കാരി അനിതയെ കണ്ടു."
"അവർ എന്നെ നോക്കി സന്തോഷത്തോടെ ചിരിച്ചു."
"ആദ്യത്തെ ദിവസം തന്നെ അവർ എന്നെ ഒരുപാട് സഹായിച്ചു."
സാറ ഇത് കേട്ട് ചിരിച്ചു.
"ആദ്യത്തെ ദിവസം തന്നെ നല്ലൊരു അയൽക്കാരിയെ കിട്ടിയത് വലിയ ഭാഗ്യമാണ്," സാറ പറഞ്ഞു.
ഞാൻ അത് പൂർണ്ണമായും സമ്മതിച്ചു.
"അതെ, അന്ന് എനിക്ക് വലിയ ആശ്വാസം തോന്നി," ഞാൻ പറഞ്ഞു.
