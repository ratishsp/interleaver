പെട്ടെന്ന്, ഞാൻ ഒരു വലിയ ശബ്ദം കേൾക്കുന്നു.
അത് വലിയ ഇടിയാണ്.
അപ്പോൾ തന്നെ ശക്തമായ മഴ പെയ്യുന്നു.
എന്റെ കൈയിൽ കുട ഇല്ല.
കുട വീട്ടിലാണ്.
ഞാൻ വേഗം ബസ് സ്റ്റോപ്പിലേക്ക് ഓടുന്നു.
ഞാൻ അവിടെ മേൽക്കൂരയ്ക്ക് താഴെ നിൽക്കുന്നു.
മഴ വളരെ ശക്തമാണ്.
ഇനിയും മഴ പെയ്യും.
ഞാൻ മഴ നോക്കി നിൽക്കുന്നു.
കാലാവസ്ഥ ഇപ്പോൾ തികച്ചും വ്യത്യസ്തമാണ്.
ഇപ്പോൾ വെയിലില്ല.
തീരെ ചൂടില്ല.
കാറ്റിന് നല്ല തണുപ്പാണ്.
ഞാൻ അവിടെ ബസ്സിനായി കാത്തുനിൽക്കുന്നു.
