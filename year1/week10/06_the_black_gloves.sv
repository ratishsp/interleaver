Jag har fortfarande min tunna jacka på mig.
Jag tänker på mina kalla händer från i morse.
Jag behöver tjocka handskar.
Jag tittar runt i den ljusa butiken.
Jag ser en stor korg.
Korgen är full av handskar.
Jag hittar ett par svarta vinterhandskar.
De är mycket tjocka och mjuka.
Jag tar på mig handskarna.
De passar mig perfekt.
Jag frågar den leende expediten.
"Vad kostar de svarta handskarna?" frågar jag.
"De kostar hundratjugo kronor," svarar hon.
Hundratjugo kronor är ett bra pris.
Mina händer är redan varma.
"Jag tar dem," säger jag glatt.
Jag tar av mig handskarna igen.
Jag lägger de svarta handskarna tillsammans med min röda tröja och min blå halsduk.
Nu är jag redo att betala.
