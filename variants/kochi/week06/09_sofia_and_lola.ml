ഞാൻ സോഫയിൽ സുഖമായി ഇരിക്കുകയാണ്.
എൻ്റെ വയറു നിറഞ്ഞു.
ഞാൻ എൻ്റെ ഫോൺ എടുക്കുകയാണ്.
ഞാൻ ഒരു വീഡിയോ കോൾ ചെയ്യുകയാണ്.
ഞാൻ എൻ്റെ സഹോദരി സോഫിയയെ വിളിക്കുകയാണ്.
സോഫിയ കോൾ എടുക്കുന്നു.
"ഹലോ മായാ, സുഖമാണോ?" സോഫിയ ചോദിക്കുന്നു.
"എനിക്ക് സുഖമാണ്," ഞാൻ പറയുന്നു.
ഞാൻ ഫോണിൻ്റെ സ്ക്രീനിൽ നോക്കുകയാണ്.
സ്ക്രീനിൽ ഞങ്ങളുടെ നായ ലോല ഉണ്ട്.
ലോല മെക്സിക്കോയിലെ വീട്ടിലാണ്.
അവൾ തറയിൽ കിടക്കുകയാണ്.
അവൾ നന്നായി ഉറങ്ങുകയാണ്.
"ലോല ഉറങ്ങുകയാണ്," സോഫിയ പറയുന്നു.
ഞാൻ ചിരിക്കുകയാണ്.
ഞങ്ങൾ ഒരുപാട് നേരം സംസാരിക്കുന്നു.
എനിക്ക് ഇപ്പോൾ വലിയ സന്തോഷമുണ്ട്.
