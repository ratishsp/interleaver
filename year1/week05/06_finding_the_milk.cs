Teď potřebuji mléko.
Jdu dlouhou uličkou.
Dívám se na regál.
Vidím vodu a džus.
Ale nemůžu najít mléko.
Dívám se všude.
Vidím muže.
Pracuje v supermarketu.
Zastavím zaměstnance a usměji se.
„Promiňte,“ říkám.
„Chtěla bych mléko.“
„Kde je mléko?“
Muž ukáže do zadní části obchodu.
„Oddělení mléčných výrobků je tamhle,“ říká.
„Moc děkuji,“ odpovídám.
Jdu tam.
Konečně nacházím lednici a mléko.
Vezmu krabici a vložím ji do košíku.
