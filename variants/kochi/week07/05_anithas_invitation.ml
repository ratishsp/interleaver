ഇന്ന് ചൊവ്വാഴ്ചയാണ്.
ഞാൻ അപ്പാർട്ട്മെന്റിൽ വെച്ച് അനിതയെ കാണുന്നു.
"മായ കൊച്ചിയിൽ വന്നിട്ട് ഇപ്പോൾ ഒരു മാസമായി," അനിത പറയുന്നു.
"നമുക്ക് നാളെ വൈകുന്നേരം കോഫി കുടിക്കാൻ പോകാം."
ഞാൻ ചോദിക്കുന്നു, "എത്ര മണിക്കാണ് നമ്മൾ പോകുന്നത്?"
"വൈകുന്നേരം അഞ്ചരയ്ക്ക് പോകാം," അവർ പറയുന്നു.
ഞാൻ എന്റെ ഫോണിൽ കലണ്ടർ നോക്കുന്നു.
എനിക്ക് നാളെ അഞ്ചരയ്ക്ക് സലൂണിൽ ഒരു അപ്പോയിന്റ്മെന്റ് ഉണ്ട്.
എനിക്ക് മുടി വെട്ടണം.
ഞാൻ അനിതയോട് പറയുന്നു, "എനിക്ക് നാളെ അഞ്ചരയ്ക്ക് സലൂണിൽ പോകണം."
"പക്ഷേ, ആ സമയം ഞാൻ മാറ്റാം."
"നമുക്ക് നാളെ അഞ്ചരയ്ക്ക് തന്നെ കഫേയിൽ പോകാം."
അനിത ചിരിക്കുന്നു.
ഞങ്ങൾ ബുധനാഴ്ച വൈകുന്നേരം കാണാൻ തീരുമാനിക്കുന്നു.
