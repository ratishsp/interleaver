ഞാൻ മീറ്റിംഗ് മുറിയിലേക്ക് പോകുന്നു.
അതൊരു ചെറിയ മുറിയാണ്.
എന്റെ സഹപ്രവർത്തകരും അവിടെയുണ്ട്.
ഞാൻ പ്രകാശിന്റെ അടുത്തായി ഇരിക്കുന്നു.
ഞങ്ങളുടെ ടീം ലീഡർ മുറിയിലേക്ക് വരുന്നു.
അദ്ദേഹം മീറ്റിംഗ് തുടങ്ങുന്നു.
ഞങ്ങൾ ഒരു പുതിയ സോഫ്റ്റ്‌വെയർ പ്രോജക്റ്റ് ചെയ്യുകയാണ്.
അദ്ദേഹം പുതിയ പ്ലാൻ വിശദീകരിക്കുകയാണ്.
ഞാൻ വളരെ ശ്രദ്ധിച്ച് കേൾക്കുകയാണ്.
പ്രകാശ് ചില കാര്യങ്ങൾ എഴുതിയെടുക്കുകയാണ്.
എന്റെ കയ്യിലും ഒരു നോട്ട്ബുക്ക് ഉണ്ട്.
ഞാൻ പ്രധാനപ്പെട്ട കാര്യങ്ങൾ എഴുതുന്നു.
അദ്ദേഹം എല്ലാവരോടും ചോദ്യങ്ങൾ ചോദിക്കുന്നു.
ഞങ്ങൾ മറുപടി പറയുന്നു.
മീറ്റിംഗ് പത്ത് മണിക്ക് തീരുന്നു.
ഞങ്ങൾ മുറിയിൽ നിന്ന് പുറത്തേക്ക് വരികയാണ്.
ഞാൻ വീണ്ടും ജോലി തുടങ്ങുകയാണ്.
