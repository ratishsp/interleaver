Sent på eftermiddagen gick jag ner till floden.
Vädret var fortfarande varmt och härligt.
Jag köpte en biljett till en liten träbåt.
Biljetten kostade sjuttio kronor.
Jag gick ombord och hittade en bra plats på däcket.
Båten åkte mycket långsamt nerför floden.
Det var inte många andra passagerare på båten.
En äldre dam satt mittemot mig.
Hon åt en matsäck tillsammans med sin man.
Hennes man log glatt mot henne.
Vi åkte under några stora, gröna träd.
Vattnet var blått och helt stilla.
Jag kopplade bara av och njöt av turen.
Himlen var fortfarande ljus, även om det var sent.
Det var en riktigt vacker dansk vårkväll.
Jag lutade mig tillbaka i den lilla båten.
Jag njöt av den gröna naturen längs floden.
Det var en perfekt avslutning på min dag i Odense.
