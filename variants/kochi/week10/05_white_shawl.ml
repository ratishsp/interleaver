പുറത്തെ നല്ല വെയിലിന് എനിക്ക് ഒരു ഷാൾ വേണം.
ഞാൻ സെയിൽസ് വുമണിനോട് ചോദിക്കുന്നു.
അവർ ഒരു വെള്ള കോട്ടൺ ഷാൾ കൊണ്ടുവരുന്നു.
ഞാൻ ആ ഷാൾ ധരിക്കുന്നു.
ഞാൻ അത് തോളിൽ ഇടുന്നു.
ഇത് വളരെ വലിയ ഷാൾ ആണ്.
ഈ വെള്ള ഷാൾ നല്ലതാണ്.
ഞാൻ വില ചോദിക്കുന്നു.
സെയിൽസ് വുമൺ പറയുന്നു.
"ഇതിന് ഇരുനൂറ് രൂപ ആണ്."
ഇരുനൂറ് രൂപ ഒരു ചെറിയ വില ആണ്.
എനിക്ക് ഈ ഷാൾ ഇഷ്ടമാണ്.
ഞാൻ ഈ ഷാൾ എടുക്കുന്നു.
ഞാൻ അത് മഞ്ഞ കുർത്തിയുടെ കൂടെ വെക്കുന്നു.
