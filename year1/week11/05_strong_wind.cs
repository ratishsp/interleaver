Vystupuji z autobusu nedaleko své práce.
Pevně si držím šálu.
Počasí je dnes velmi divoké.
Jdu po ulici.
Najednou je velmi větrno.
Silný vítr fouká proti mně.
V ruce mám rozevřený deštník.
Ale vítr je příliš silný.
Rychle se z toho stává problém.
Deštník létá ze strany na stranu.
Teď už je to nemožné.
Bojuji s ním.
Konečně deštník zavírám.
Bez něj je velmi chladno.
Déšť mi naráží do tváře.
Spěchám tím větrem.
Vchod do kanceláře je přímo přede mnou.
Vstupuji do budovy.
Tady uvnitř je naštěstí teplo a klid.
