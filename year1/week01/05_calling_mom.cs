Jsem teď v obýváku.
Je tu malá pohovka.
Volám své matce do Mexika.
„Ahoj mami,“ říkám.
„Ahoj Mayo,“ říká moje matka.
„Kde jsi?“ ptá se.
„Jsem v Kodani,“ odpovídám.
„Teď jsem v bytě.“
„To je moc dobře,“ říká moje matka.
„Je velký?“ ptá se.
„Ne, je malý,“ odpovídám.
„Ale je útulný a jsem šťastná.“
„Je tam zima?“ ptá se.
„Ano, venku je zima,“ říkám.
„Ale tady je teplo.“
„Jsem v bezpečí.“
„To je dobře,“ říká moje matka.
Usmívám se.
Dánsko je můj nový domov.
