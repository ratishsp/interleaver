Nadal mam na sobie moją cienką kurtkę.
Myślę o moich zimnych dłoniach z dzisiejszego rana.
Potrzebuję grubych rękawiczek.
Rozglądam się po jasnym sklepie.
Widzę duży kosz.
Kosz jest pełen rękawiczek.
Znajduję parę czarnych rękawiczek zimowych.
Są bardzo grube i miękkie.
Zakładam rękawiczki.
Pasują na mnie idealnie.
Pytam uśmiechniętą ekspedientkę.
„Ile kosztują te czarne rękawiczki?” – pytam.
„Kosztują sto dwadzieścia koron” – odpowiada.
Sto dwadzieścia koron to dobra cena.
Moje dłonie są już ciepłe.
„Wezmę je” – mówię radośnie.
Ponownie zdejmuję rękawiczki.
Kładę czarne rękawiczki razem z moim czerwonym swetrem i niebieskim szalikiem.
Teraz jestem gotowa zapłacić.
