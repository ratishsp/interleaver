പിന്നെ ഞാൻ ഒരു വാഴപ്പഴക്കട കാണുന്നു.
ഞാൻ വാഴപ്പഴം വിൽക്കുന്ന ഒരു വലിയ കട കാണുന്നു.
കടയിൽ വലിയ വാഴപ്പഴക്കുലകൾ ഉണ്ട്.
പലതരം വാഴപ്പഴങ്ങൾ അവിടെ ഉണ്ട്.
കടയ്ക്ക് മുന്നിൽ ഒരു ചെറിയ ബോർഡ് ഉണ്ട്.
അതിൽ വില വ്യക്തമായി എഴുതിയിട്ടുണ്ട്.
ഞാൻ ആ ബോർഡ് വായിക്കുന്നു.
ഒരു ചെറിയ കുലയ്ക്ക് അറുപതു രൂപ ആണ് വില.
വലിയ കുലയ്ക്ക് നൂറ്റിയിരുപതു രൂപ ആണ്.
എനിക്ക് ഒരു ചെറിയ കുല മതി.
ഞാൻ കടക്കാരനെ നോക്കുന്നു.
"എനിക്ക് ആ ചെറിയ കുല വേണം," ഞാൻ പറയുന്നു.
അദ്ദേഹം ആ ചെറിയ കുല എനിക്ക് തരുന്നു.
ഞാൻ അദ്ദേഹത്തോട് വില ചോദിക്കുന്നില്ല.
എന്റെ കയ്യിൽ പത്തു രൂപയുടെ ചെറിയ നോട്ടുകൾ ഉണ്ട്.
ഞാൻ കൃത്യം അറുപതു രൂപ അദ്ദേഹത്തിന് കൊടുക്കുന്നു.
അദ്ദേഹം ആ പണം വാങ്ങുന്നു.
ഞാൻ വാഴപ്പഴം എന്റെ സഞ്ചിയിൽ വെക്കുന്നു.
