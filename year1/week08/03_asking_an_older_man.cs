Přicházím na velké náměstí.
Je tam mnoho lidí.
Ale nevidím vodu.
Hledám přístav.
Vidím staršího muže na chodníku.
Zastavím ho.
„Promiňte,“ říkám.
„Kde je přístav?“
Starší muž přikývne.
Ukazuje dopředu.
„Jděte rovně přes náměstí,“ říká.
„Projděte kolem muzea.“
„A zahněte doprava.“
Dívám se přes náměstí.
Vidím velkou budovu.
Je to muzeum.
„Moc děkuji,“ říkám.
„Není zač,“ odpovídá.
Jdu dál.
