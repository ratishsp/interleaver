Wchodzę do sypialni.
Przynoszę walizkę z salonu.
Otwieram walizkę.
Wyjmuję swoje ubrania.
Składam ubrania.
Wkładam je do szafy.
Teraz moje swetry leżą w szafie.
W pokoju jest duże łóżko.
Na łóżku leży gruby koc.
Koc jest z Meksyku.
Znajduję też parę kapci.
Są bardzo miękkie.
Przy ścianie stoi małe krzesło.
Kładę moje kapcie na podłodze.
Teraz leżą pod krzesłem.
Teraz walizka jest pusta.
Zamykam ją i kładę pod łóżko.
