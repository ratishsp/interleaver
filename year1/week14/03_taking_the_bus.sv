Jag står vid busshållplatsen.
Snart åker jag med bussen.
Jag tittar nerför gatan.
Efter fem minuter kommer bussen.
Det är en lång och gul buss.
Bussen stannar precis framför mig.
Dörrarna öppnas.
Jag stiger på bussen.
Jag har mitt resekort i handen.
Jag skannar kortet vid dörren.
Det är många passagerare i dag.
Jag letar efter en ledig plats.
Jag hittar en bra plats vid fönstret.
Jag sätter mig ner.
Jag tittar ut på staden.
Nu tar jag bussen till metrostationen.
