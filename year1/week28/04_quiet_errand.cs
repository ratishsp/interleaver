V pátek odpoledne jdu na klidnou procházku na slunci.
Nesu si svou těžkou zimní bundu.
Už ji vůbec nepotřebuji.
Zastavím se před místní čistírnou.
Otevřu dveře a vejdu dovnitř.
V malém obchodě to voní po čistém oblečení a mýdle.
Za pultem stojí starší muž.
„Dobrý den, chtěla bych si nechat vyčistit tuhle bundu,“ říkám.
Podám tu velkou bundu přes pult.
„Samozřejmě,“ odpovídá muž a prohlíží si látku.
„Bude hotová ve středu,“ říká.
„Bude to dvě stě padesát korun.“
Vytáhnu z tašky platební kartu.
Zaplatím u pokladny a dostanu malou žlutou účtenku.
„Moc děkuji, přeji hezký víkend,“ říkám.
„Vám také,“ odpovídá s úsměvem.
Uložím si účtenku do tašky.
Pak vyjdu znovu na rušný chodník.
Užívám si procházku v teplém odpoledním slunci.
