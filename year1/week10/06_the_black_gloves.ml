ഞാൻ ഇപ്പോഴും എന്റെ കനംകുറഞ്ഞ ജാക്കറ്റാണ് ധരിച്ചിരിക്കുന്നത്.
ഇന്ന് രാവിലത്തെ എന്റെ തണുത്ത കൈകളെക്കുറിച്ച് ഞാൻ ചിന്തിക്കുന്നു.
എനിക്ക് കട്ടിയുള്ള ഗ്ലൗസുകൾ വേണം.
ഞാൻ പ്രകാശമുള്ള ആ കടയുടെ ചുറ്റും നോക്കുന്നു.
ഞാൻ വലിയൊരു കുട്ട കാണുന്നു.
ആ കുട്ട നിറയെ ഗ്ലൗസുകളാണ്.
ഞാൻ ഒരു ജോടി കറുത്ത വിന്റർ ഗ്ലൗസുകൾ കണ്ടെത്തുന്നു.
അവ വളരെ കട്ടിയുള്ളതും മൃദുവായതുമാണ്.
ഞാൻ ആ ഗ്ലൗസുകൾ ധരിക്കുന്നു.
അവ എനിക്ക് കൃത്യമായി പാകമാണ്.
പുഞ്ചിരിക്കുന്ന കട ജീവനക്കാരിയോട് ഞാൻ ചോദിക്കുന്നു.
"കറുത്ത ഗ്ലൗസുകൾക്ക് എന്താണ് വില?" ഞാൻ ചോദിക്കുന്നു.
"അവയ്ക്ക് നൂറ്റിയിരുപത് ക്രോണർ ആണ് വില," അവർ മറുപടി പറയുന്നു.
നൂറ്റിയിരുപത് ക്രോണർ എന്നത് ഒരു നല്ല വിലയാണ്.
എന്റെ കൈകൾ ഇതിനകം ചൂടായിക്കഴിഞ്ഞു.
"ഞാൻ അവ എടുക്കാം," സന്തോഷത്തോടെ ഞാൻ പറയുന്നു.
ഞാൻ വീണ്ടും ആ ഗ്ലൗസുകൾ അഴിച്ചുമാറ്റുന്നു.
ഞാൻ കറുത്ത ഗ്ലൗസുകൾ എന്റെ ചുവന്ന സ്വെറ്ററിനും നീല സ്കാർഫിനുമൊപ്പം വെക്കുന്നു.
ഇപ്പോൾ ഞാൻ പണം നൽകാൻ തയ്യാറാണ്.
