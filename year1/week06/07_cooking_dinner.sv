Jag är hemma i min lägenhet.
I köket lagar jag middag.
Jag sköljer färska grönsaker.
Jag hackar en lök på skärbrädan.
Jag skär också två röda tomater.
Jag tar en stekpanna.
På spisen värmer jag lite olja.
Jag lägger grönsakerna i stekpannan.
Jag steker maten.
Det doftar riktigt gott.
Jag har i salt och peppar i maten.
Maten är färdig.
Jag tar en tallrik.
Jag lägger maten på tallriken.
Jag hämtar ett glas vatten.
Jag sätter mig vid bordet.
Jag äter min middag.
Maten smakar underbart.
Jag njuter av en lugn måltid.
