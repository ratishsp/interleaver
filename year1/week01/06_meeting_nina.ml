ഞാൻ എന്റെ വാതിൽ തുറക്കുന്നു.
ഞാൻ ഗോവണിപ്പടിയിൽ നിൽക്കുകയാണ്.
അവിടെ നിശ്ശബ്ദമാണ്.
ഒരു വാതിൽ തുറക്കുന്നു.
ഒരു സ്ത്രീ എന്നെ നോക്കി പുഞ്ചിരിക്കുന്നു.
"ഹായ്," അവൾ പറയുന്നു.
"നിന്റെ പേരെന്താണ്?" അവൾ ചോദിക്കുന്നു.
"എന്റെ പേര് മായ," ഞാൻ മറുപടി നൽകുന്നു.
"നീ എവിടെ നിന്നാണ് വരുന്നത്?" അവൾ ചോദിക്കുന്നു.
"ഞാൻ മെക്സിക്കോയിൽ നിന്നാണ് വരുന്നത്," ഞാൻ പറയുന്നു.
"ഡെന്മാർക്കിലേക്ക് സ്വാഗതം," ആ സ്ത്രീ പറയുന്നു.
"എന്റെ പേര് നീന," അവൾ പറയുന്നു.
"ഞാൻ നിന്റെ അയൽക്കാരിയാണ്."
നീന വളരെ സൗഹാർദ്ദമുള്ളവളാണ്.
അവളുടെ മുഖത്ത് ഒരു പുഞ്ചിരിയുണ്ട്.
"ഇതാണ് എന്റെ വാതിൽ," അവൾ പറയുന്നു.
"സഹായിക്കുന്നതിൽ എനിക്ക് സന്തോഷമേയുള്ളൂ."
"നീ ഒന്ന് മുട്ടിയാൽ മതി," നീന പറയുന്നു.
"വളരെ നന്ദി, നീന," ഞാൻ മറുപടി നൽകുന്നു.
എനിക്ക് വളരെ സന്തോഷമുണ്ട്.
ഇപ്പോൾ എനിക്ക് കോപ്പൻഹേഗനിൽ ഒരു സുഹൃത്തുണ്ട്.
