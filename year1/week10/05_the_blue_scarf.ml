ഞാൻ കടയിലെ ഒരു മേശയ്ക്കടുത്തേക്ക് നടക്കുന്നു.
മേശപ്പുറത്ത് ഒരുപാട് സാധനങ്ങളുണ്ട്.
ഞാൻ ഇന്ന് സ്കാർഫ് ധരിച്ചിട്ടില്ല.
എനിക്ക് കഴുത്തിന് ചുറ്റും നല്ല തണുപ്പനുഭവപ്പെടുന്നു.
ഞാൻ ഒരു നീല സ്കാർഫ് കാണുന്നു.
അത് വളരെ നീളമുള്ള ഒരു സ്കാർഫാണ്.
അത് കമ്പിളി കൊണ്ടാണ് ഉണ്ടാക്കിയിരിക്കുന്നത്.
ഞാൻ ആ നീല സ്കാർഫ് എടുക്കുന്നു.
ഞാൻ അത് എന്റെ കഴുത്തിന് ചുറ്റും ഇടുന്നു.
അത് നല്ല സുഖമുള്ള ചൂടുള്ളതായി തോന്നുന്നു.
"അതൊരു നല്ല നിറമാണ്," കടയിലെ ജോലിക്കാരി പറയുന്നു.
"അതെ, ഇത് വളരെ മൃദുവുമാണ്," ഞാൻ പറയുന്നു.
ഞാൻ പ്രൈസ് ടാഗ് നോക്കുന്നു.
അതിന് നൂറ്റിയൻപത് ക്രോണറാണ് വില.
ചൂടുള്ള ഒരു സ്കാർഫിന് ഇതൊരു നല്ല വിലയാണ്.
ഞാൻ അത് വീണ്ടും അഴിച്ചുമാറ്റുന്നു.
"ഞാൻ ഇതും വാങ്ങുന്നു," ഞാൻ അവരോട് പറയുന്നു.
ഞാൻ ആ നീല സ്കാർഫ് ചുവന്ന സ്വെറ്ററിനൊപ്പം വെക്കുന്നു.
