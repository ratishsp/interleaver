Otwieram drzwi kluczem.
Wreszcie jestem w domu, w swoim mieszkaniu.
Na zewnątrz jest mokro i wietrznie.
Ale tu w środku jest ciepło.
Moja kurtka zimowa jest bardzo mokra.
Zdejmuję kurtkę.
Z mojego parasola też kapie woda.
Idę do łazienki.
Kładę parasol na podłodze.
Woda kapie na płytki.
Potem idę do salonu.
Jest tu zupełnie ciemno.
Prawie nic nie widzę.
W rogu stoi mała lampa.
Włączam lampę.
Światło jest żółte i miękkie.
W salonie od razu robi się jaśniej.
Teraz salon jest ciepły i jasny.
Miło jest teraz być w środku.
