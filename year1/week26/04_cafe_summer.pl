Jest sobotnie przedpołudnie i skończyłam pracę w kawiarni.
Właśnie przetarłam ostatni stolik.
Rozwiązuję fartuch i kładę go na krześle.
Dzisiaj miałam krótką zmianę.
W zeszłym tygodniu pracowałam do trzeciej.
Tego dnia mieliśmy dużo pracy przez cały dzień.
Ale dzisiaj mieliśmy tylko kilku gości.
Na zewnątrz świeci słońce i jest piękny, letni dzień.
Dziś wieczorem nad morzem jest wielkie ognisko.
Naprawdę nie mogę się doczekać, żeby je zobaczyć.
Biorę telefon i piszę wiadomość do Evy.
Pytam ją: „Nadal spotykamy się dziś wieczorem?”.
Piszę również, że skończyłam już pracę.
„Skończyłam dziś wcześniej, więc jestem gotowa” – piszę.
Eva odpowiada niemal natychmiast.
„Tak, oczywiście!” – odpowiada.
„Właśnie kupiłam świeże truskawki”.
„Do zobaczenia później na plaży” – pisze.
Uśmiecham się i biorę torbę.
Potem wychodzę na zewnątrz w ciepłą, letnią pogodę.
