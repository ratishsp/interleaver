Kuchyně je malá.
Ale sporák je dobrý.
Vezmu si pastinák a mrkev.
Vezmu si také nůž.
Nůž je ostrý.
Nakrájím pastinák a mrkev.
Otevřu plechovku.
Dám jídlo do hrnce.
Hrnec stojí na sporáku.
Teď je jídlo teplé.
Krásně voní.
Vezmu si žitný chléb.
Ukrojím si krajíc.
Talíř je na stole.
Konečně jím v bytě pořádné jídlo.
Potom sním skořicového šneka.
Chutná sladce.
