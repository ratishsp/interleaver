Je pozdní odpoledne.
Teď jdu domů do svého bytu.
Jdu snadnou cestou.
Prostě jdu po té dlouhé cestě.
Cesta je úplně rovná.
Jdu podél vody.
Nakonec odbočím pryč od vody.
Teď jdu zase do města.
Pak jdu kolem pekárny.
Stále to voní po kávě.
O chvíli později vidím park.
U parku odbočím doprava.
Nikoho se neptám na cestu.
Cestu najdu úplně sama.
O chvíli později vidím svou vlastní ulici.
Nakonec stojím u svých vchodových dveří.
Ode dveří se dívám zpátky dolů po ulici.
Teď znám svou cestu domů.
