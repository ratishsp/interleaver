Jdu k zeleninovému stánku.
Dnes vařím teplou polévku.
Dívám se na tu spoustu zeleniny na stole.
Ukazuji na nějaké velké zimní mrkve.
Potřebuji mrkve do polévky.
Za stolem stojí prodavač.
„Dobrý den,“ říká.
„Dobrý den,“ odpovídám.
„Kolik stojí ty mrkve?“ ptám se.
„Stojí patnáct korun za kilo,“ odpovídá prodavač.
Patnáct korun je dobrá cena.
„Vezmu si jedno kilo, prosím,“ říkám.
Prodavač váží mrkve.
Dává je do papírového sáčku.
Podává mi sáček.
Platím těch patnáct korun.
Dávám sáček do své velké tašky.
Těším se na tu teplou polévku.
