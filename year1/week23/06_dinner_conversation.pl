Siadamy przy pięknym stole.
Eva nakryła stół kolorowymi talerzami i zapalonymi świecami.
Przygotowała dla nas wspaniały wegetariański posiłek.
"Dziękuję, Evo, wygląda pysznie", mówię z uśmiechem.
"Pachnie absolutnie fantastycznie."
"Proszę bardzo", odpowiada i podaje mi miskę z sałatką.
Od razu próbuję jedzenia.
Uważam, że świeże składniki smakują naprawdę cudownie.
"To jest niesamowicie pyszne", mówię jej.
"Zamierzam wkrótce gotować jeszcze więcej lokalnych potraw", mówię.
"Bardzo chciałabym używać więcej duńskich warzyw."
"To brzmi jak naprawdę dobry pomysł", mówi radośnie Eva.
"Z pewnością musimy kiedyś coś razem ugotować."
"Wierzę, że pewnie będziemy się dobrze bawić w kuchni."
"Bardzo bym tego chciała", odpowiadam i biorę kolejny kęs.
Nalewamy trochę zimnej wody do szklanek.
Czuję, że ten wieczór już teraz jest wielkim sukcesem.
