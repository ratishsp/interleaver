ഞാൻ എന്റെ പുതിയ ജാക്കറ്റുമായി ക്യാഷ് രജിസ്റ്ററിനടുത്തേക്ക് നടക്കുന്നു.
പോകുന്ന വഴിക്ക്, ഞാൻ വളരെ മനോഹരമായ ഒരു ഷർട്ട് കാണുന്നു.
അത് ഇളം നീല നിറത്തിലുള്ളതും മൃദുവായ കോട്ടൺ കൊണ്ട് ഉണ്ടാക്കിയതുമാണ്.
ഓഫീസിൽ ഇടാൻ എനിക്കൊരു പുതിയ ഷർട്ട് ശരിക്കും ആവശ്യമുണ്ട്.
ഞാൻ ഹാങ്ങറിൽ നിന്ന് ആ ഷർട്ട് എടുക്കുന്നു.
ഞാൻ ഫിറ്റിംഗ് റൂമുകൾക്ക് നേരെ നോക്കുന്നു.
ഇന്ന് കടയിൽ ധാരാളം ആളുകളുണ്ട്.
ഫിറ്റിംഗ് റൂമുകൾക്ക് മുന്നിലെ വരി വളരെ നീളമുള്ളതാണ്.
ഒരുപാട് നേരം കാത്തുനിൽക്കാൻ എനിക്ക് താല്പര്യമില്ല.
അതുകൊണ്ട്, അത് ആദ്യം ഇട്ടുനോക്കേണ്ട എന്ന് ഞാൻ തീരുമാനിക്കുന്നു.
ഞാൻ സാധാരണയായി മീഡിയം സൈസാണ് ധരിക്കാറുള്ളത്.
ഞാൻ ഷർട്ടിന്റെ സൈസ് നോക്കുന്നു.
എങ്കിലും, കണ്ടിട്ട് അത് അല്പം ചെറുതാണെന്ന് എനിക്ക് തോന്നുന്നു.
എന്നാൽ ഇതിലും വലിയ സൈസ് ചിലപ്പോൾ വളരെ വലുതായിരിക്കും.
കൂടാതെ ചെറിയ സൈസ് തീർച്ചയായും വളരെ ഇറുക്കമുള്ളതായിരിക്കും.
അതുകൊണ്ട് ഞാൻ എന്റെ സാധാരണ സൈസ് തന്നെ എടുക്കുന്നു.
ഞാൻ ജാക്കറ്റിനൊപ്പം ഷർട്ടും എന്റെ കയ്യിൽ വെക്കുന്നു.
വീട്ടിലെത്തുമ്പോൾ ഷർട്ട് പാകമാകുമെന്ന് ഞാൻ പ്രതീക്ഷിക്കുന്നു.
