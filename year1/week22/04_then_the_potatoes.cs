Teď musím uvařit brambory.
Znovu se podívám na svůj recept.
Má nějaké velmi krátké instrukce.
Nejdřív se tam píše: „Vydrhněte malé brambory dočista.“
Dělám to malým kartáčkem pod studenou vodou.
Pak čtu další řádek.
Poté se tam píše: „Dejte brambory do hrnce s vodou.“
Vyndám ze skříňky svůj velký hrnec.
Vložím to celé kilo do hrnce.
Hrnec je téměř úplně plný.
Jaký je další krok?
Recept říká: „Přidejte do vody velkou lžíci hrubé soli.“
Vyndám si sůl a lžíci.
Nasypu sůl na lžíci.
Přidám tu velkou lžíci k bramborám.
Nakonec se tam píše: „Zapněte sporák.“
Postavím hrnec na sporák a zapnu ho.
Teď už se brambory musí vařit jen dvacet minut.
