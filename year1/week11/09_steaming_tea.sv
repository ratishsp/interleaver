Jag går ut i köket.
Jag vill gärna ha något varmt att dricka.
Jag kokar vatten till te.
Vattnet är mycket varmt.
Jag gör en stor kopp örtte.
Jag tar med mitt te in i vardagsrummet.
Jag sätter mig i soffan.
Det är en mörk vinterkväll.
Jag håller den varma koppen i mina händer.
Jag blir snabbt varm.
Jag lyssnar på vinden utanför.
Det blåser mycket.
Vädret är vilt i kväll.
Men det är mycket mysigt här inne.
Lampan lyser mjukt i hörnet.
Jag tar en klunk av mitt te.
Det smakar mynta.
Den långa dagen är slut.
Nu slappnar jag av.
