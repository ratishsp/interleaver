Jdu přes velké náměstí.
Najednou slyším hudbu.
Na rohu stojí pouliční muzikant.
Hraje na kytaru.
Poslouchám tu dobrou hudbu.
Dlouho se na něj dívám.
Pak jdu dál.
Zapomínám na muzeum.
Také zapomínám na svou trasu.
Místo toho jdu úzkou postranní ulicí.
Je tu velký klid.
Všude kolem vidím jen nějaké malé domy.
Pak se zastavím.
Kde je to muzeum?
Teď se rozhlížím kolem sebe.
Už ho nevidím.
Rychle se podívám zpátky do ulice.
Nevidím ani to náměstí.
Jsem úplně ztracená.
