അത്താഴത്തിന് ശേഷം ഞാൻ സ്വീകരണമുറിയിലേക്ക് പോകുന്നു.
അപ്പാർട്ട്മെൻ്റ് മനോഹരവും ഊഷ്മളവുമാണ്.
പുറത്ത് ഇരുട്ടും തണുപ്പുമാണ്.
ഞാൻ ഒരു ചെറിയ ലാമ്പ് ഓൺ ചെയ്യുന്നു.
ആ വെളിച്ചം ഊഷ്മളവും മൃദുവുമാണ്.
ഞാൻ ഒരു കപ്പ് ചൂട് ചായ ഉണ്ടാക്കുന്നു.
എന്നിട്ട് ഞാൻ സോഫയുടെ അടുത്തേക്ക് നടക്കുന്നു.
ഞാൻ മൃദുവായ കുഷ്യനുകളിൽ ഇരിക്കുന്നു.
മേശപ്പുറത്ത് ഒരു പുതിയ പുസ്തകം ഇരിപ്പുണ്ട്.
ഞാൻ ആ പുസ്തകമെടുത്ത് തുറക്കുന്നു.
അതൊരു ആവേശകരമായ കഥയാണ്.
ഞാൻ കുറച്ച് അധ്യായങ്ങൾ വായിക്കുന്നു.
എൻ്റെ ചായയ്ക്ക് നല്ല മണമുണ്ട്.
ഞാൻ ഒരിറക്ക് കുടിക്കുന്നു.
ഞാൻ പിന്നിലേക്ക് ചാരിയിരിക്കുന്നു.
ഇപ്പോൾ ഞാൻ പൂർണ്ണമായും വിശ്രമിക്കുന്നു.
അപ്പാർട്ട്മെൻ്റിൽ തികഞ്ഞ നിശ്ശബ്ദതയാണ്.
ഞാൻ എൻ്റെ തനിച്ചുള്ള സമയം ആസ്വദിക്കുന്നു.
