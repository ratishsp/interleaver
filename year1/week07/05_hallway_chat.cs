Jdu po schodech nahoru.
Jsem unavená po posilovně.
Ve druhém patře potkávám Ninu.
Usmívá se na mě.
„Ahoj Mayo,“ říká.
„Ahoj Nino, jak se máš?“ ptám se.
„Mám se moc dobře,“ odpovídá Nina.
„Vypadáš trochu unaveně.“
„Ano, ve středu vždycky cvičím,“ vysvětluji.
„V poslední době spolu málokdy pijeme kávu,“ říká Nina.
„Máš zítra čas?“ ptá se.
Přemýšlím o tom, co budu dělat ve čtvrtek.
„Ano, čtvrtek je opravdu dobrý den,“ říkám.
„V kolik hodin?“ ptám se.
„Možná v půl páté?“
„Půl pátá zní perfektně,“ odpovídám radostně.
„Uvidíme se zítra odpoledne,“ říká Nina.
Loučíme se venku na schodišti.
Jdu do svého bytu.
Těším se na naši schůzku u kávy.
