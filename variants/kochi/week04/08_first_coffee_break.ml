ഞാൻ അടുക്കളയിൽ പോകുന്നു.
അവിടെ ഒരു ചെറിയ ഗ്യാസ് അടുപ്പ് ഉണ്ട്.
ആ അടുപ്പിൽ ഞാൻ കാപ്പി ഉണ്ടാക്കുന്നു.
ഇത് എൻ്റെ നാട്ടിൽ നിന്നുള്ള കാപ്പിയാണ്.
രണ്ട് മഗ്ഗുകൾ കൗണ്ടറിന് മുകളിൽ ഇരിക്കുന്നു.
ഞാൻ മഗ്ഗുകളിൽ ചൂട് കാപ്പി ഒഴിക്കുന്നു.
അനിത ഇപ്പോൾ സ്വീകരണമുറിയിൽ ഉണ്ട്.
അവർ സോഫയിൽ ഇരിക്കുന്നു.
ഞാൻ അനിതയ്ക്ക് ഒരു മഗ്ഗ് കാപ്പി കൊടുക്കുന്നു.
ഞാൻ അവരുടെ അടുത്ത് ഇരിക്കുന്നു.
"മായ, ഈ കാപ്പി വളരെ നല്ലതാണ്," അനിത പറയുന്നു.
"ഇത് മെക്സിക്കോയിൽ നിന്നുള്ള കാപ്പിയാണ്," ഞാൻ പറയുന്നു.
ഞങ്ങൾ ഒരുമിച്ച് കാപ്പി കുടിക്കുന്നു.
ഫ്ലാറ്റിൽ വളരെ സമാധാനമുണ്ട്.
എനിക്ക് ഇപ്പോൾ വളരെ സന്തോഷമുണ്ട്.
