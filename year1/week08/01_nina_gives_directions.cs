Je sobota ráno.
Slunce svítí nad městem.
Jdu dolů na ulici.
Moje sousedka Nina stojí před naší budovou.
"Dobré ráno, Mayo," říká a usmívá se.
"Dobré ráno, Nino," odpovídám.
"Dnes mám volno," říkám jí.
"Vyrážím do města."
"Kam jdeš?" ptá se Nina.
"Jdu dolů k vodě," říkám.
"Ale neznám cestu."
Nina ukazuje dolů po ulici.
"Naštěstí je to velmi jednoduché," říká.
"Tady jdi rovně."
"A u parku zahni doleva."
"Tak dojdeš přímo dolů k přístavu."
"Moc děkuji za pomoc, Nino," říkám.
"Není zač a hezkou procházku," odpovídá.
Mávám na ni.
Začínám svou procházku směrem k vodě.
