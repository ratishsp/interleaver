Jag vaknade tidigt i morse.
Solen sken klart in i mitt sovrum.
Jag låg i sängen och tänkte på mitt hem i Mexiko.
Idag är det nämligen min födelsedag.
Jag fyller trettiotvå år idag.
Det är min första födelsedag borta från min familj.
Jag kände mig lite nostalgisk över det.
Men så tog jag min telefon från nattduksbordet.
Min familj har skickat många kärleksfulla meddelanden.
De skrev dem i natt medan jag sov.
Mina föräldrar har spelat in en rolig video med Lola, vår hund.
Min syster Sofía har skrivit en lång och fin text.
Och min bror Diego skickade en bild på min favorittårta.
Jag log stort när jag såg bilden.
De har inte alls glömt min stora dag.
Jag svarade på alla meddelanden direkt.
Jag skrev till dem att jag älskar och saknar dem.
Jag läser meddelandena om och om igen.
Det är en fantastisk start på min födelsedag.
