Det är måndag eftermiddag, och jag har slutat jobbet.
Jag tar bussen från mjukvaruföretaget.
Men jag åker inte direkt hem.
Jag kliver av bussen vid den stora gågatan.
Jag går bort till klädbutiken från i lördags.
I min väska har jag den blå bomullsskjortan.
Den är fortfarande helt ny och oanvänd.
Skjortan är för liten, så jag vill gärna prova en större.
Jag hoppas att de har den i en annan storlek.
Jag går in i den ljusa butiken.
Jag går direkt fram till kassan.
Jag öppnar min plånbok och hittar mitt kvitto.
Jag håller det redo i handen.
Sedan tar jag upp skjortan ur min väska.
En vänlig expedit står bakom disken.
Hon tittar upp och ler mot mig.
Jag ler tillbaka.
