Sedáme si k mému malému stolu.
Je tu trochu těsno, ale sedíme blízko sebe a pohodlně.
Nejprve dám na stůl misky s jídlem.
Potom si Kasper a Sara vezmou velkou porci.
Ochutnají karbanátky a brambory.
„Chutná to opravdu skvěle, Mayo!“ říká Sara.
„Ano, jsou opravdu dobré,“ říká Kasper.
Rychle si vezme další sousto.
Kasper také otevře studená piva.
Pak je nalije do našich sklenic.
„Na zdraví!“ řekneme všichni tři a napijeme se.
Kasper si z mísy vezme další karbanátky.
Sara si také vezme další porci brambor.
„Jsem moc ráda, že vám to chutná,“ říkám.
„Je toho dost pro všechny,“ usměju se.
Chválí tu autentickou chuť.
Povídáme si a smějeme se u stolu.
Dlouho jíme a povídáme si.
