Sedím u svého stolu v kanceláři.
Dnes jsem přišla brzy.
Pracuji tu už půl roku.
Najednou k mému stolu přijdou Peter a Eva.
Peter nese malý dort s jednou svíčkou.
„Všechno nejlepší k narozeninám, Mayo!“ řeknou sborově.
Mám opravdovou radost a jsem velmi překvapená.
„Moc vám děkuji,“ řeknu jim.
Eva se široce usměje.
„Ten dort jsme koupili dnes ráno v pekárně,“ vysvětluje.
„Ano, a já jsem nám udělal kávu,“ dodává Peter.
Postaví na můj stůl velký hrnek kávy.
„Jste prostě tak milí,“ řeknu.
„Když jsem pracovala v Mexiku, málokdy jsme ráno dostávali dort.“
Peter a Eva si ke stolu přitáhnou dvě židle.
Jíme dort společně a je to fantastický začátek mého dne.
