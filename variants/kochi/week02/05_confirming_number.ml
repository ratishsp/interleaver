ഞാൻ മൊബൈൽ കടയിൽ നിൽക്കുന്നു.
കടക്കാരൻ എനിക്ക് പുതിയ സിം കാർഡ് തരുന്നു.
അയാൾ കമ്പ്യൂട്ടറിൽ നോക്കുന്നു.
അയാൾ പറയുന്നു, "സിം ഇപ്പോൾ ആക്ടീവ് ആണ്."
ഞാൻ സിം കാർഡ് എന്റെ ഫോണിൽ ഇടുന്നു.
കടക്കാരൻ എനിക്ക് ഒരു കടലാസ് തരുന്നു.
ഞാൻ കടലാസിലെ പുതിയ നമ്പർ നോക്കുന്നു.
ഞാൻ നമ്പർ ഉറക്കെ വായിക്കുന്നു.
"തൊണ്ണൂറ്റിയെട്ട്, എഴുപത്തിയാറ്, അമ്പത്തിനാല്, മുപ്പത്തിരണ്ട്, പത്ത്."
കടക്കാരൻ ചിരിക്കുന്നു.
അയാൾ ചോദിക്കുന്നു, "ഇപ്പോൾ നെറ്റ്വർക്ക് സിഗ്നൽ ഉണ്ടോ?"
ഞാൻ ഫോണിൽ നോക്കുന്നു.
ഞാൻ പറയുന്നു, "അതെ, എനിക്ക് സിഗ്നൽ ഉണ്ട്."
ഞാൻ അയാൾക്ക് മുന്നൂറ് രൂപ കൊടുക്കുന്നു.
ഇപ്പോൾ എനിക്ക് ഒരു ഇന്ത്യൻ മൊബൈൽ നമ്പർ ഉണ്ട്.
