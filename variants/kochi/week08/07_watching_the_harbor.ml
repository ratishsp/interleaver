എനിക്ക് ചൂടുള്ള ചായയും ഒരു പഴംപൊരിയും കിട്ടുന്നു.
ഞാൻ തിരികെ ബെഞ്ചിലേക്ക് വരുന്നു.
ഞാൻ പഴംപൊരി കഴിക്കുന്നു.
അത് വളരെ രുചികരമാണ്.
ഞാൻ ചൂടുചായ കുടിക്കുന്നു.
രാവിലെ മെല്ലെ ഉച്ചയാകുന്നു.
എനിക്ക് തിടുക്കമില്ല.
