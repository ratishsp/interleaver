V kanceláři je pozdní odpoledne.
Dívám se na svou obrazovku.
Píšu poslední kód.
Úkol je teď hotový.
Usmívám se.
Zavírám svůj počítač.
Dávám ho do své tašky.
Potom si balím své věci.
Vstávám.
Můj kolega Peter sedí u svého stolu.
Jdu k němu.
„Na shledanou, Petere,“ říkám.
„Na shledanou, Mayo,“ říká Peter.
„Měj hezký večer,“ říká.
„Děkuji, nápodobně,“ odpovídám.
Vycházím z kanceláře.
Venku na chodbě jedu výtahem dolů.
Nakonec vycházím z budovy.
Teď jedu domů.
