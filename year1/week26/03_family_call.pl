Wieczorem siedzę na kanapie z moim komputerem.
Dzwonię do mojej rodziny w Meksyku.
Ekran pokazuje moich rodziców, moją siostrę Sofíę i mojego brata Diego.
Nasz pies, Lola, też tam jest.
"Wszystkiego najlepszego!" - krzyczą wszyscy.
Sofía pyta.
"Dostałaś naszą paczkę?"
"Tak, przyszła wczoraj pocztą" - odpowiadam.
"Otworzyłaś ją?" - pyta podekscytowana.
Uśmiecham się i biorę ze stołu kolorowy szalik.
"Otworzyłam ją, kiedy wróciłam do domu" - mówię i unoszę szalik.
"Naprawdę uwielbiam te kolory."
Zakładam szalik na szyję.
"Dobrze w nim wyglądasz" - mówi moja mama.
"Miałaś dziś dobry dzień?" - pyta mój tata.
"Tak, moi współpracownicy kupili mi wcześniej ciasto" - wyjaśniam.
Diego podnosi Lolę do kamery.
"Lola też zjadła małe ciastko" - śmieje się.
Śmieję się głośno z małego psa.
To moje pierwsze urodziny z dala od domu, ale czuję, jakby byli bardzo blisko.
