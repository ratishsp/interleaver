ഞാൻ വീണ്ടും മേശയ്ക്ക് അരികിൽ ഇരിക്കുന്നു.
ഞാൻ ഒരു ചെറിയ പെട്ടി എടുക്കുന്നു.
ഇത് എന്റെ ഇന്നത്തെ മധുരപലഹാരമാണ്.
"നോക്കൂ, ഇത് കോഴിക്കോടൻ ഹൽവയാണ്," ഞാൻ ക്യാമറയിൽ കാണിക്കുന്നു.
ഇതിന് നല്ല ഓറഞ്ച് നിറമാണ്.
അപ്പോൾ എന്റെ അനിയത്തി സോഫിയ ക്യാമറയ്ക്ക് മുന്നിൽ വരുന്നു.
അവളുടെ കയ്യിൽ ഒരു കടലാസ് ഉണ്ട്.
അതൊരു പുതിയ ചിത്രമാണ്.
നിറങ്ങളുള്ള ഒരു മനോഹരമായ ചിത്രം.
"സോഫിയാ, അത് ആരുടെ ചിത്രമാണ്?" ഞാൻ ചോദിക്കുന്നു.
"ഇത് എന്റെ ചിത്രമാണ്," സോഫിയ പറയുന്നു.
"ഇതൊരു നായയാണ്."
"അത് നമ്മുടെ ലോലയാണോ?" ഞാൻ ചോദിക്കുന്നു.
സോഫിയ ഉച്ചത്തിൽ ചിരിക്കുന്നു.
"അതെ, ഇത് നമ്മുടെ ലോലയാണ്," അവൾ പറയുന്നു.
അവളുടെ ചിത്രം വളരെ മനോഹരമാണ്.
ഞങ്ങൾ എല്ലാവരും വലിയ സന്തോഷത്തിലാണ്.
