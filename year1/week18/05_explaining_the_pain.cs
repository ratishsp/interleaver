Přátelský lékař otevírá dveře a volá moje jméno.
Vcházím do jeho světlé ordinace.
Sedáme si k jeho stolu.
„Jak se dnes cítíte?“ ptá se.
„Je mi opravdu špatně,“ odpovídám.
Lékař se na mě dívá.
„Kde vás to bolí?“ ptá se laskavě.
Ukazuji na krk.
„Moc mě bolí krk,“ vysvětluji.
„Je velmi suchý.“
Lékař přikyvuje a pozorně poslouchá.
„Moje hlava je také velmi těžká,“ pokračuji.
Dotýkám se svého obličeje.
„A moje oči jsou úplně červené.“
Pořád mě svědí.
„Rozhodně byste si měla odpočinout,“ říká.
Zapíná malou baterku.
„Dovolte, abych se na vás podíval zblízka,“ říká.
