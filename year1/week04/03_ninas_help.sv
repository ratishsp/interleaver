Jag går ut i trapphuset igen.
Min största resväska står på golvet.
Den är mycket tung.
Jag drar i resväskan.
Plötsligt hör jag steg i trappan.
Det är min danska granne, Nina.
Hon ler varmt mot mig.
"Flyttar du in i dag, Maya?" frågar hon.
"Ja, jag är äntligen i min nya lägenhet," säger jag.
"Jag hjälper dig," säger Nina vänligt.
Hon tar tag i resväskan.
Tillsammans bär vi in resväskan i vardagsrummet.
Nina ställer den försiktigt på golvet.
Nu står resväskan vid det stora fönstret.
Det ligger redan en väska under fönstret.
"Tack så mycket för hjälpen, Nina," säger jag glatt.
"Det var så lite," ler hon.
Nina går ut i trapphuset.
Jag stänger dörren och tittar på resväskan vid fönstret.
