Ludwig vesele pobíhá po lese.
Najednou uvidí velkého ptáka.
Rychle běží za ním.
Běží až tam směrem ke stromům.
„Stůj, Ludwigu!“ zakřičím nahlas.
„Pojď sem!“
Vytáhnu z kapsy malý pamlsek.
Dřepnu si do trávy.
„Ludwigu, podívej se sem,“ zavolám jemně.
Zastaví se a podívá se na mě.
Ten pamlsek opravdu chce.
Rychle běží zpátky ke mně.
„Sedni,“ řeknu klidně.
Sedne si a já mu ho dám.
„Hodný pes,“ řeknu a pohladím ho.
Znovu mu připnu vodítko.
Teď musíme jít domů a odpočinout si.
