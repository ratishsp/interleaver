കളി കഴിയുന്നു.
ഞങ്ങൾ ബാഗുകൾ എടുക്കുന്നു.
ഞാൻ ഫ്രണ്ട് ഡെസ്കിലേക്ക് നടക്കുന്നു.
വാടകയ്ക്ക് എടുത്ത റാക്കറ്റ് തിരികെ നൽകാൻ ഞാൻ പോകുന്നു.
ക്ലർക്ക് അവിടെ നിൽക്കുന്നുണ്ട്.
ഞാൻ ആ റാക്കറ്റ് അയാൾക്ക് കൊടുക്കുന്നു.
"നിങ്ങൾക്ക് കളി ഇഷ്ടമായോ?" അയാൾ എന്നോട് ചോദിക്കുന്നു.
"അതെ, എനിക്ക് വളരെ ഇഷ്ടമായി," ഞാൻ മറുപടി പറയുന്നു.
"ഇവിടുത്തെ കോർട്ടുകൾ വളരെ നല്ലതാണ്."
"എനിക്ക് എല്ലാ വ്യാഴാഴ്ചയും ഇവിടെ വരാൻ ഇഷ്ടമാണ്."
"നിങ്ങൾ നന്നായി കളിച്ചോ?" അയാൾ ചോദിക്കുന്നു.
"അതെ, ഞാൻ നന്നായി കളിച്ചു," ഞാൻ ചിരിച്ചുകൊണ്ട് പറയുന്നു.
"എനിക്ക് അടുത്ത വ്യാഴാഴ്ചയും വരാൻ കഴിയും."
"തീർച്ചയായും വരണം," അയാൾ സന്തോഷത്തോടെ പറയുന്നു.
ഞാൻ അയാളോട് നന്ദി പറയുന്നു.
എന്നിട്ട് ഞാൻ സുഹൃത്തുക്കളുടെ അടുത്തേക്ക് നടക്കുന്നു.
