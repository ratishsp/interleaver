Jag behöver också en vinterjacka.
Jag tittar på mer kläder i butiken.
Jag hittar en vacker, grön kappa.
Det är en väldigt vacker design.
Jag tar på mig den gröna kappan.
Men den är för liten.
Den är väldigt trång över axlarna.
"Har ni den i en annan storlek?" frågar jag.
Expediten tittar.
"Nej, tyvärr", svarar hon.
Så jag hänger tillbaka den gröna kappan.
Expediten hittar en annan jacka till mig.
Det är en varm, mörkblå vinterjacka.
Jag tar på mig den mörkblå jackan.
Den passar perfekt.
Den är härligt stor och inte trång.
Jag tittar i en stor spegel.
Jag tycker om den.
"Jag tar den", säger jag.
