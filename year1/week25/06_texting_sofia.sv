Jag sitter på museets kafé och tar en paus.
Jag dricker en kopp kaffe och slappnar av.
Jag tar upp de blå tallrikarna ur min väska.
De här tallrikarna passar perfekt i mitt kök.
Jag tar en bild på dem med min telefon.
Jag skickar bilden till min syster, Sofía.
"Titta bara på de här vackra tallrikarna", skriver jag.
"Jag hittade dem på en marknad för en timme sedan."
Sofía svarar mig nästan direkt.
Hon skickar tillbaka en gammal bild till mig.
Det här meddelandet gör mig mycket glad.
Bilden visar oss två på en stor loppmarknad i Mexiko.
"Kommer du ihåg den här marknaden?"
Sofía frågar i nästa meddelande.
"Vi var där för exakt två år sedan!" skriver hon.
Jag tittar på våra glada ansikten på bilden.
Det känns som väldigt länge sedan.
För två år sedan bodde jag fortfarande i Mexiko.
Jag ler och skriver ett glatt meddelande tillbaka.
