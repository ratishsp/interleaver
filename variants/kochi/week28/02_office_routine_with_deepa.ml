ഞാൻ ഓഫീസിൽ എന്റെ സീറ്റിൽ ഇരിക്കുകയാണ്.
ദീപ എന്റെ അടുത്ത് ഇരിക്കുന്നുണ്ട്.
ഞങ്ങൾ കമ്പ്യൂട്ടർ സ്ക്രീനിൽ പുതിയ യൂസർ ഇന്റർഫേസ് പരിശോധിക്കുകയാണ്.
ആദ്യത്തെ മീറ്റിംഗിന്റെ സമയത്ത് ഈ പ്രോജക്റ്റ് വളരെ ബുദ്ധിമുട്ടായി തോന്നിയിരുന്നു.
എന്നാൽ ഇപ്പോൾ ഇത് വളരെ എളുപ്പമുള്ള ഒരു സാധാരണ ജോലിയാണ്.
ദീപ സ്ക്രീനിലെ ഒരു ഭാഗത്തേക്ക് വിരൽ ചൂണ്ടി.
"മായ, ഈ ബട്ടണിന്റെ താഴെ കുറച്ചു കൂടി സ്ഥലം വേണം," അവർ പറഞ്ഞു.
"അക്ഷരങ്ങൾ ബോർഡറുമായി വളരെ അടുത്താണ്."
ഞാൻ ഡിസൈൻ സൂക്ഷിച്ചു നോക്കി.
അവർ പറഞ്ഞത് ശരിയാണ്.
ഞാൻ ഉടനെ തന്നെ കോഡിൽ ആ മാറ്റം വരുത്തി.
അതിന് ശേഷം ഞാൻ ഫയൽ സേവ് ചെയ്ത് സ്ക്രീൻ റിഫ്രഷ് ചെയ്തു.
"ഇപ്പോൾ എങ്ങനെയുണ്ട്?"
ഞാൻ ദീപയോട് ചോദിച്ചു.
"അതെ, ഇപ്പോൾ കാണാൻ ശരിയാണ്," അവർ ചിരിച്ചുകൊണ്ട് പറഞ്ഞു.
അതോടെ ഞങ്ങൾ ആ പേജിന്റെ ജോലി തീർത്തു.
"നമുക്ക് ചായ കുടിക്കാൻ പോയാലോ?"
ദീപ ചോദിച്ചു.
എനിക്കും ചെറിയ ക്ഷീണം ഉണ്ടായിരുന്നു.
"ശരി, നമുക്ക് ബ്രേക്ക് റൂമിലേക്ക് പോകാം," ഞാൻ മറുപടി നൽകി.
