Siedzę przy swoim biurku w biurze.
Eva podchodzi do mnie z kubkiem kawy.
W tym tygodniu ściśle ze sobą współpracujemy.
„Jesteś gotowa, żeby spojrzeć na nowy layout?” – pyta.
„Tak, muszę tylko otworzyć program” – odpowiadam.
Razem patrzymy na duży ekran.
Duży cyfrowy projekt wreszcie wygląda dobrze.
Ale nagle Eva widzi mały błąd w rogu.
Niebieski przycisk jest trochę za daleko w lewo.
„Spójrz tam, pozycja jest nieprawidłowa” – mówi.
„Masz rację, muszę przesunąć go w prawo” – mówię.
Szybko piszę kilka linijek kodu.
Przycisk przesuwa się na właściwe miejsce.
„Idealnie, dziękuję za pomoc” – mówi Eva i uśmiecha się ciepło.
Rozmawiamy o naszych planach na weekend i śmiejemy się razem.
Teraz dobrze już znam wszystkich w biurze.
