ഡോക്ടറെ കണ്ടതിന് ശേഷം വീട്ടിലേക്കുള്ള വഴിയിൽ, ഞാൻ അടുത്തുള്ള ഫാർമസിയിൽ കയറുന്നു.
ഞാൻ മെഷീനിൽ നിന്ന് ഒരു നമ്പർ എടുത്ത് അല്പനേരം കാത്തിരിക്കുന്നു.
സൗമ്യയായ ഒരു ഫാർമസിസ്റ്റ് മുപ്പത്തിയഞ്ച് എന്ന നമ്പർ വിളിക്കുന്നു.
ഞാൻ കൗണ്ടറിലേക്ക് നടന്നുചെന്ന് എൻ്റെ മഞ്ഞ ഹെൽത്ത് കാർഡ് കാണിക്കുന്നു.
അവൾ കമ്പ്യൂട്ടറിൽ എൻ്റെ കുറിപ്പടി കണ്ടെത്തുന്നു.
ഫാർമസിസ്റ്റ് എനിക്ക് അലർജിക്കുള്ള ഗുളികകളുടെ ഒരു ചെറിയ പെട്ടി തരുന്നു.
"നിങ്ങൾ എല്ലാ ദിവസവും രാവിലെ ഓരോ ഗുളിക വീതം കഴിക്കണം," അവൾ പറയുന്നു.
തൊണ്ടയ്ക്ക് എന്തെങ്കിലും ഉണ്ടോ എന്ന് ഞാൻ അവളോട് ചോദിക്കുന്നു.
"എൻ്റെ തൊണ്ടയ്ക്ക് ഇപ്പോഴും വേദനയുണ്ട്," ഞാൻ വ്യക്തമാക്കുന്നു.
അവൾ തലയാട്ടിയിട്ട്, മധുരമുള്ള ചില ത്രോട്ട് ഡ്രോപ്പുകൾ നിർദ്ദേശിക്കുന്നു.
"തൊണ്ടവേദന ഉള്ളപ്പോൾ ഇവ സഹായിക്കും," അവൾ പറയുന്നു.
"കൂടാതെ ഇന്ന് നിങ്ങൾ ധാരാളം വെള്ളം കുടിക്കുകയും വേണം."
ഞാൻ അവളോട് നന്ദി പറയുകയും ഗുളികകളും ഡ്രോപ്പുകളും വാങ്ങുകയും ചെയ്യുന്നു.
ഇതിന് ആകെ എൺപത്തിയഞ്ച് ക്രോണർ ആണ്.
എനിക്ക് ഇപ്പോഴും ക്ഷീണവും വേദനയുമുണ്ട്, എങ്കിലും മരുന്ന് കിട്ടിയതിൽ എനിക്ക് സന്തോഷമുണ്ട്.
ഇപ്പോൾ എനിക്ക് വീട്ടിൽ പോയി എൻ്റെ സ്വന്തം സോഫയിൽ ഇരുന്നാൽ മാത്രം മതി.
