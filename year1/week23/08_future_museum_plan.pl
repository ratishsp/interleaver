Wstaję i biorę swoją kurtkę.
Jest późno i muszę jechać autobusem do domu.
Eva odprowadza mnie do drzwi.
„Zrobimy coś w przyszłym miesiącu?” – pyta nagle.
„Zamierzam pójść do muzeum sztuki” – wyjaśnia.
„Chcesz może iść ze mną?”
Kiwam entuzjastycznie głową i biorę swoją torbę.
„Tak, bardzo chętnie” – odpowiadam.
Myślę, że na pewno będziemy się dobrze bawić.
Mówię jej również, że uwielbiam sztukę nowoczesną.
„I czuję, że zawsze tak dobrze nam się rozmawia” – dodaję.
Eva uśmiecha się szeroko i otwiera mi drzwi wejściowe.
„Na pewno wkrótce coś zaplanujemy” – obiecuje.
„Wyślę ci wiadomość w poniedziałek” – mówię.
Przytulam ją i wychodzę na klatkę schodową.
Już nie mogę się doczekać naszej wycieczki do muzeum.
