Stojím v klidné ulici.
Ztratila jsem se.
Před sebou vidím mladou ženu.
Venčí malého psa.
Ten pes vypadá jako pes mojí rodiny, Lola.
Jdu k té ženě.
„Promiňte,“ říkám.
„Hledám přístav.“
Žena se zastaví a poslouchá.
Ukáže zpět nahoru ulicí.
„Jděte rovně zpátky na náměstí,“ říká.
„A u muzea zahněte doprava.“
„Moc děkuji za pomoc,“ říkám.
„Není zač,“ odpovídá žena.
Podívám se dolů na toho malého psa.
Dívá se na mě.
Jdu zpátky směrem k náměstí.
Teď už vím, kde jsem.
