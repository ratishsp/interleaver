"ഇന്നലെ വൈകുന്നേരം പെട്ടെന്ന് മഴ പെയ്തു," സാറ പറയുന്നു.
അതെ, ഇന്നലെ നല്ല മഴയായിരുന്നു.
പിന്നെ ഞങ്ങൾ കഴിഞ്ഞ ആഴ്ചത്തെ കളിയെക്കുറിച്ച് സംസാരിക്കുന്നു.
കഴിഞ്ഞ ആഴ്ച കിരൺ കളി തോറ്റു.
സാറ അത് ഓർത്ത് ചിരിക്കുന്നു.
കിരണും അത് കേട്ട് ചിരിക്കുന്നു.
പെട്ടെന്ന് സാറ എന്നോട് ഒരു കാര്യം ചോദിക്കുന്നു.
"മായ, നിങ്ങൾ എപ്പോഴാണ് കൊച്ചിയിൽ വന്നത്?" അവർ ചോദിക്കുന്നു.
ഞാൻ സാറയെ നോക്കി ചിരിക്കുന്നു.
ഞാൻ ജനുവരിയിൽ ഇവിടെ വന്നു.
സമയം വളരെ വേഗം പോയി.
എന്റെ കൊച്ചിയിലെ ആദ്യത്തെ ദിവസങ്ങളെക്കുറിച്ച് ഞാൻ അവരോട് പറയുന്നു.
