വെള്ളിയാഴ്ച ജോലി കഴിഞ്ഞ് ഞാൻ അടുത്തുള്ള ചെറിയ പച്ചക്കറി മാർക്കറ്റിലേക്ക് നടക്കുന്നു.
മാർക്കറ്റിൽ അധികം ആളുകൾ ഇല്ല.
ഞാൻ സ്ഥിരമായി പോകുന്ന ഒരു കടയുണ്ട്.
ആ കടക്കാരന് ഇപ്പോൾ എന്നെ നന്നായി അറിയാം.
ഞാൻ എന്ത് പച്ചക്കറികളാണ് വാങ്ങുന്നത് എന്ന് അയാൾക്ക് അറിയാം.
ഞാൻ കടയിൽ എത്തുമ്പോൾ അയാൾ എന്നെ നോക്കി ചിരിക്കുന്നു.
"പതിവ് പോലെ തക്കാളിയും സവാളയും പച്ചമുളകും അല്ലേ?" അയാൾ ചോദിക്കുന്നു.
"അതെ, അതുതന്നെ മതി," ഞാൻ മറുപടി പറയുന്നു.
അയാൾ വേഗത്തിൽ ആ പച്ചക്കറികൾ എല്ലാം ഒരു സഞ്ചിയിൽ ആക്കുന്നു.
അതിനുശേഷം അയാൾ കുറച്ച് കറിവേപ്പില കൂടി ആ സഞ്ചിയിൽ ഇടുന്നു.
"ഇത് എന്റെ വകയാണ്."
"ഇതിന് പണം വേണ്ട," അയാൾ പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ സന്തോഷത്തോടെ പറയുന്നു.
ഞാൻ പച്ചക്കറികളുടെ പണം അയാൾക്ക് കൊടുക്കുന്നു.
എന്നിട്ട് പച്ചക്കറി സഞ്ചിയുമായി ഞാൻ വീട്ടിലേക്ക് മടങ്ങുന്നു.
