Zvoní zvonek.
S úsměvem otevírám dveře.
Kasper a Sara stojí venku.
Usmívají se a mávají na mě.
„Ahoj Mayo a moc děkujeme za pozvání!“ říká vesele Kasper.
„Ahoj!“
„Pojďte dál,“ odpovídám.
„Už teď to voní úžasně,“ říká Sara.
„Nejdřív si sundejte bundy,“ říkám jim.
Beru si jejich bundy a věším je v předsíni.
Poté mi Sara podává tašku.
„Přinesli jsme nějaká studená piva,“ vysvětluje.
„Je to místní dánské pivo,“ dodává Kasper.
Dívám se do tašky.
Je v ní šest lahví.
„Moc děkuju, to je naprosto perfektní,“ říkám.
„Jen je dám do lednice.“
„Dobrý nápad, a pak jsme připraveni k jídlu,“ směje se Kasper.
Jdu s lahvemi do kuchyně.
