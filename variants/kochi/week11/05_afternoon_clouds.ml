ഇപ്പോൾ സമയം നാലുമണിയാണ്.
ഞാൻ ഓഫീസിലാണ്.
ഞാൻ എന്റെ ഡെസ്കിൽ ഇരിക്കുന്നു.
ഞാൻ കോഡ് ടൈപ്പ് ചെയ്യുന്നു.
പെട്ടെന്ന് ഓഫീസിൽ ഇരുട്ടാകുന്നു.
ഞാൻ ജനാലയിലൂടെ പുറത്തേക്ക് നോക്കുന്നു.
ആകാശത്ത് സൂര്യൻ ഇല്ല.
ഇപ്പോൾ പുറത്ത് വെയിലില്ല.
കൊച്ചി നഗരത്തിന് മുകളിൽ കറുത്ത മേഘങ്ങൾ ഉണ്ട്.
പ്രകാശ് എന്റെ ഡെസ്കിനടുത്ത് വരുന്നു.
പ്രകാശും ജനാലയിലൂടെ നോക്കുന്നു.
പ്രകാശ് പറയുന്നു, 'മായ, വലിയ മഴ പെയ്യും.'
ഞാൻ പറയുന്നു, 'അതെ, ആകാശം കറുപ്പാണ്.'
ഇന്ന് വലിയ ചൂടാണ്.
പക്ഷേ ഇപ്പോൾ പുറത്ത് നല്ല കാറ്റ് വീശുന്നു.
ഇപ്പോൾ ഒട്ടും ചൂടില്ല.
ഞങ്ങൾ ജനാലയ്ക്കരികിൽ നിൽക്കുന്നു.
ഞങ്ങൾ കറുത്ത മേഘങ്ങളെ നോക്കുന്നു.
