V ložnici otevírám svou skříň.
Dívám se na své oblečení.
Vybírám si modrou košili a černé kalhoty.
Pak se oblékám.
Češu si vlasy před zrcadlem.
Teď jdu do kuchyně.
Mám hlad.
Najdu talíř a hrnek.
Dělám si rychlou snídani.
Dnes jím chleba se sýrem.
Nalévám kávu do hrnku.
Káva je černá a silná.
Sedám si ke stolu.
Tady jím své jídlo.
Chutná to dobře.
Piju svou kávu.
Nakonec si beru tašku a bundu.
Zamykám dveře a jdu ven.
