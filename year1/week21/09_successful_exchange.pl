Wychodzę z przymierzalni z niebieską koszulą.
Większy rozmiar pasuje idealnie.
Ekspedientka wciąż stoi przy kasie.
„Czy jest lepsza?” – pyta z uśmiechem.
„Tak, jest o wiele lepsza” – odpowiadam.
„Mniejsza koszula była za ciasna” – wyjaśniam.
„Chciałabym wymienić na tę”.
„Oczywiście, żaden problem” – mówi.
„Mogę jeszcze raz zobaczyć paragon?” – pyta.
Podaję jej mały papierowy paragon.
Skanuje kod kreskowy.
„Gotowe, wymienione” – mówi.
„Nie wymaga to żadnej dopłaty”.
„Bardzo dziękuję za pomoc” – mówię.
„Proszę bardzo i miłego dnia” – odpowiada.
Wkładam koszulę do torby.
Teraz w końcu mam dobre ubrania na wiosnę.
Wychodzę ze sklepu.
Jestem bardzo zadowolona, gdy wracam do domu.
