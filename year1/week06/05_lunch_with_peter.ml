ദിവസത്തിന്റെ മധ്യത്തിൽ, ഞാൻ താഴെയുള്ള കാന്റീനിലേക്ക് നടന്നുപോകുന്നു.
ആ മുറി നല്ല വെളിച്ചമുള്ളതും മനോഹരവുമാണ്.
ബുഫെയുടെ അടുത്തു ധാരാളം ആളുകൾ നിൽക്കുന്നുണ്ട്.
എന്റെ സഹപ്രവർത്തകനായ പീറ്ററിനെ ഞാൻ കാണുന്നു.
അവൻ ഭക്ഷണമുള്ള ഒരു പ്ലേറ്റ് എടുക്കുന്നു.
"ഹലോ മായാ," ഒരു പുഞ്ചിരിയോടെ അവൻ പറയുന്നു.
"ഹലോ പീറ്റർ," ഞാൻ മറുപടി നൽകുന്നു.
ഞങ്ങൾ കുറച്ച് ബ്രെഡും സലാഡും എടുക്കുന്നു.
ഞങ്ങൾ ഒരുമിച്ച് ജനലിനടുത്തുള്ള ഒൻപതാം നമ്പർ മേശ കണ്ടെത്തുന്നു.
ഞങ്ങൾ കസേരകളിൽ ഇരിക്കുന്നു.
ഭക്ഷണത്തിന് ശരിക്കും നല്ല രുചിയുണ്ട്.
പീറ്റർ തന്റെ പ്രോജക്ടിനെക്കുറിച്ച് സംസാരിക്കുന്നു.
അവൻ പുതിയ സോഫ്റ്റ്‌വെയറിലാണ് പ്രവർത്തിക്കുന്നത്.
ഞാൻ കേൾക്കുകയും തലയാട്ടുകയും ചെയ്യുന്നു.
അവസാനം ഞാൻ എന്റെ സ്വന്തം കോഡിനെക്കുറിച്ച് സംസാരിക്കുന്നു.
ഞങ്ങൾ ഒരു ഗ്ലാസ് വെള്ളം കുടിക്കുന്നു.
ഇടവേളയിൽ ഞാൻ നന്നായി ആസ്വദിക്കുന്നു.
വൈകാതെ ഞങ്ങൾ ഓഫീസിലേക്ക് തിരികെ നടക്കുന്നു.
