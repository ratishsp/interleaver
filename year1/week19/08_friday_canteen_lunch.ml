ഒടുവിൽ വെള്ളിയാഴ്ചയായി, തിരക്കേറിയ ഈ ആഴ്ച ഏകദേശം കഴിയാറായി.
നല്ല വെളിച്ചമുള്ള കാന്റീനിൽ ഞങ്ങൾ ഒരുമിച്ച് ഉച്ചഭക്ഷണം കഴിക്കുകയാണ്.
എന്റെ ടീമിനൊപ്പം ഒരു വലിയ മേശയ്ക്കു ചുറ്റുമാണ് ഞാൻ ഇരിക്കുന്നത്.
പീറ്റർ, ഞങ്ങളുടെ ഡിസൈനർ ഈവ, ഞങ്ങളുടെ ടെസ്റ്റർ മാഡ്‌സ് എന്നിവരും ഇവിടെയുണ്ട്.
ഞങ്ങൾക്കെല്ലാവർക്കും നല്ല ക്ഷീണമുണ്ട്, പക്ഷേ ഞങ്ങൾ വളരെ സന്തോഷത്തിലാണ്.
പുതിയ പ്രോജക്റ്റ് വളരെ ആവേശകരമായിരുന്നു.
"നമ്മൾ ശരിക്കും കഠിനാധ്വാനം ചെയ്തു," എന്ന് പറഞ്ഞ് പീറ്റർ പുഞ്ചിരിക്കുന്നു.
"അതെ, നമ്മൾ സങ്കീർണ്ണമായ ഒരുപാട് പ്രശ്നങ്ങൾ പരിഹരിച്ചു," ഞാൻ മറുപടി പറയുന്നു.
സോഫ്റ്റ്‌വെയർ എഞ്ചിനീയർമാർ എന്ന നിലയിൽ, ഈ ആഴ്ച നമ്മൾ ധാരാളം കോഡ് എഴുതിയിട്ടുണ്ട്.
"അതെല്ലാം ഞാൻ ടെസ്റ്റ് ചെയ്യുകയും ചെയ്തു," മാഡ്‌സ് ചിരിക്കുന്നു.
"ഭാഗ്യത്തിന്, നിനക്ക് ഒരുപാട് തെറ്റുകൾ കണ്ടുപിടിക്കാൻ കഴിഞ്ഞില്ലല്ലോ," പീറ്റർ കളിയാക്കുന്നു.
ഈവ തന്റെ ഫോണിൽ അവളുടെ മനോഹരമായ ഡിസൈൻ ഞങ്ങളെ കാണിക്കുന്നു.
അവൾ ഒരുപാട് വർഷങ്ങളായി ഡിസൈനറായി ജോലി ചെയ്തുവരുന്നു.
ഭക്ഷണം കഴിക്കുന്നതിനിടയിൽ ഞങ്ങൾ ഞങ്ങളുടെ വിവിധ ജോലികളെക്കുറിച്ച് സംസാരിക്കുന്നു.
എന്റെ സഹപ്രവർത്തകരെ കൂടുതൽ അടുത്തറിയാൻ കഴിയുന്നത് വളരെ സന്തോഷമുള്ള കാര്യമാണ്.
ഞങ്ങൾ ശരിക്കും നല്ലൊരു ടീമായി മാറിയിരിക്കുന്നു.
ഞാൻ എന്റെ ഭക്ഷണത്തിൽ നിന്ന് ഒരു കഷണം കഴിച്ച് അവരെ നോക്കുന്നു.
അവരോടൊപ്പം പ്രോജക്റ്റ് തുടരാൻ ഞാൻ ആകാംക്ഷയോടെ കാത്തിരിക്കുകയാണ്.
