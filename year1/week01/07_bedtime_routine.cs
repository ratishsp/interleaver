Teď je noc.
Je to moje první noc v Kodani.
Jsem v koupelně.
Je velmi malá.
Je tu umyvadlo.
Můj zubní kartáček je červený.
Dávám si zubní pastu na kartáček.
Čistím si zuby.
Voda je studená.
Myju si obličej.
Utírám si obličej.
Jdu k posteli.
Postel je úzká.
Ale je teplá a měkká.
Teď ležím pod peřinou.
Můj telefon leží na stole.
Nastavuji si budík.
Zazvoní zítra v osm hodin.
Jsem unavená, ale jsem připravená.
Dobrou noc, Kodani.
