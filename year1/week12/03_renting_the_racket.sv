Jag går fram till en liten kiosk i sporthallen.
En ung man står bakom disken.
Han ler och säger hej.
"Hej, jag vill spela badminton i dag," säger jag.
"Är du ny här i klubben?" frågar han.
"Ja, jag vill gärna prova att vara med," svarar jag.
"Välkommen," säger mannen.
"Behöver du hyra en racket?" frågar han.
"Ja tack, jag vill gärna hyra en racket till i kväll," säger jag.
Han tar fram en bra racket till mig.
"Det kostar fyrtio kronor," säger han.
Jag tar fram mitt betalkort.
Jag betalar de fyrtio kronorna.
Han ger mig racketen över disken.
"Jag tycker att det är en rolig sport," säger jag glatt.
"Ha en riktigt bra match!"
Jag säger tack och går över till banorna.
