ട്രെയിൻ പതുക്കെ നഗരം വിട്ടു.
ആദ്യം എവിടെയും വലിയ കെട്ടിടങ്ങൾ മാത്രമേ ഉണ്ടായിരുന്നുള്ളൂ.
പെട്ടെന്ന് തന്നെ നഗരത്തിലെ വലിയ ശബ്ദങ്ങൾ കുറഞ്ഞു.
പിന്നെ യാത്ര വളരെ ശാന്തമായിരുന്നു.
ഞാൻ എന്റെ സ്വന്തം സീറ്റിലിരുന്ന് പുറത്തേക്ക് നോക്കി.
കുറച്ചു കഴിഞ്ഞപ്പോൾ പുറത്തെ കാഴ്ചകൾ മാറി.
ട്രെയിൻ വളരെ നീളമുള്ള ഒരു പാലം കടന്നു.
പാലത്തിന് താഴെ ഞാൻ ഒരു വലിയ പുഴ കണ്ടു.
രാവിലത്തെ വെയിലിൽ ആ വെള്ളം നന്നായി തിളങ്ങി.
ട്രാക്കിന്റെ രണ്ടു വശത്തും പച്ച മരങ്ങൾ ഉണ്ടായിരുന്നു.
അവ വളരെ തിങ്ങിയ മരങ്ങൾ ആയിരുന്നു.
ആ മരങ്ങൾക്കിടയിലൂടെ വെള്ളം മിന്നിത്തിളങ്ങുന്നത് ഞാൻ കണ്ടു.
അത് വളരെ മനോഹരമായ ഒരു കാഴ്ചയായിരുന്നു.
ഞാൻ ബാഗിൽ നിന്ന് എന്റെ ക്യാമറ എടുത്തു.
ഞാൻ സ്വന്തം ക്യാമറയിൽ ആ ഭംഗി പകർത്തി.
എനിക്ക് വളരെ സന്തോഷം തോന്നി.
തെക്കോട്ടുള്ള ഈ ട്രെയിൻ യാത്ര നല്ലൊരു അനുഭവമായിരുന്നു.
