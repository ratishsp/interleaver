ഞാൻ എന്റെ ജോലിസ്ഥലത്ത് എത്തുന്നു.
ഞാൻ ഒരു സോഫ്റ്റ്‌വെയർ കമ്പനിയിലാണ് ജോലി ചെയ്യുന്നത്.
ഞാൻ ആ വലിയ മുറിയിലേക്ക് കടന്നുചെല്ലുന്നു.
എന്റെ ഡെസ്ക് ജനലിനരികിലാണ്.
ഇവിടെ ഞാൻ എന്റെ കസേരയിൽ ഇരിക്കുന്നു.
ഞാൻ എന്റെ കമ്പ്യൂട്ടർ ഓണാക്കുന്നു.
സ്ക്രീൻ തെളിയുന്നു.
ആദ്യം ഞാൻ എന്റെ സന്ദേശങ്ങൾ വായിക്കുന്നു.
എന്റെ മാനേജറിൽ നിന്ന് എനിക്കൊരു ഇമെയിൽ ഉണ്ട്.
ആ ഇമെയിൽ എന്റെ പുതിയ പ്രൊജക്റ്റിനെക്കുറിച്ചാണ്.
ഞാൻ ഒരു ചെറിയ മറുപടി എഴുതുന്നു.
അടുത്തതായി ഞാൻ എന്റെ വർക്ക് പ്രോഗ്രാം തുറക്കുന്നു.
ഇപ്പോൾ ഞാൻ പ്രൊജക്റ്റിനായുള്ള കോഡ് എഴുതുന്നു.
കോഡ് സ്ക്രീൻ മുഴുവൻ നിറയുന്നു.
ഞാൻ എന്റെ കീബോർഡിൽ വേഗത്തിൽ ടൈപ്പ് ചെയ്യുന്നു.
ഞാൻ കോഡിൽ നന്നായി ശ്രദ്ധ കേന്ദ്രീകരിക്കുന്നു.
ജോലി ആവേശകരമാണ്.
ഞാൻ എന്റെ കുപ്പിയിൽ നിന്ന് കുറച്ചു വെള്ളം കുടിക്കുന്നു.
കോപ്പൻഹേഗനിലെ പുതിയ ജോലിയിൽ ഞാൻ വളരെ സന്തുഷ്ടയാണ്.
