Jsem zpátky ve svém bytě.
Je neděle večer a je tu velký klid.
Stojím v kuchyni.
Myju své nové talíře ve dřezu.
Tyto talíře jsou opravdu krásné.
Jsou modré a trochu těžké.
Utírám je utěrkou.
Potom je dávám do skříně.
Jdu do obývacího pokoje a dívám se z okna.
Slunce pomalu zapadá nad střechami města.
Tento letní večer je krásný a světlý.
Tuto čtvrť mám opravdu ráda.
Bydlím tu už půl roku.
Od ledna se toho tolik stalo.
Tehdy jsem ve městě nikoho neznala.
Teď znám ulice a každodenní život mnohem lépe.
V tomto městě se cítím úplně jako doma.
Zítra je pondělí a jedu do práce autobusem.
Ale právě teď jenom odpočívám.
Jsem se svým životem tady naprosto spokojená.
