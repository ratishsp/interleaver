ഞാൻ എന്റെ ലാപ്ടോപ്പ് എടുക്കുന്നു.
ഞാൻ അവർക്ക് എന്റെ പുതിയ മുറി കാണിക്കുന്നു.
"ഇത് എന്റെ മുറിയാണ്," ഞാൻ പറയുന്നു.
"നിന്റെ മുറി വളരെ നല്ലതാണ്, മായ," അമ്മ പറയുന്നു.
സോഫിയ അവളുടെ അമ്മയുടെ അടുത്ത് നിൽക്കുന്നു.
"കട്ടിൽ എവിടെയാണ്?" അവൾ ചോദിക്കുന്നു.
"ഇതാണ് എന്റെ കട്ടിൽ," ഞാൻ പറയുന്നു.
"അവിടെ ഒരു മേശയും ഉണ്ട്."
ഡീഗോ സ്ക്രീനിൽ നോക്കുന്നു.
അവന്റെ കയ്യിൽ ലോലയുണ്ട്.
"നിന്റെ മുറിയിൽ വേറെ ആരുണ്ട്?" അവൻ ചോദിക്കുന്നു.
"ഇവിടെ വേറെ ആരും ഇല്ല, ചേട്ടാ," ഞാൻ പറയുന്നു.
ഞാൻ ലാപ്ടോപ്പ് ജനാലയുടെ അടുത്തേക്ക് തിരിക്കുന്നു.
ഞാൻ അവർക്ക് പുറത്തെ കാഴ്ച കാണിക്കുന്നു.
പുറത്ത് നല്ല വെയിലുണ്ട്.
"അവിടെ നല്ല വെയിലാണല്ലോ," അച്ഛൻ പറയുന്നു.
"അതെ, ഇത് കൊച്ചിയിലെ ഒരു മനോഹരമായ ദിവസമാണ്," ഞാൻ പറയുന്നു.
"പക്ഷേ നിങ്ങളുടെ അവിടെ ഇപ്പോൾ രാത്രിയാണ്."
അവരുടെ മുഖത്ത് വലിയ സന്തോഷമുണ്ട്.
