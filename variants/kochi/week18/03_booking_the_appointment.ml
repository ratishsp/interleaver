ഞാൻ ഫോണിൽ അടുത്തുള്ള ഒരു ക്ലിനിക്ക് നോക്കുന്നു.
ഞാൻ ഒരു ക്ലിനിക്ക് കണ്ടുപിടിക്കുന്നു.
ഞാൻ അവരുടെ റിസപ്ഷനിലേക്ക് വിളിക്കുന്നു.
ഒരു സ്ത്രീ ആണ് ഫോൺ എടുക്കുന്നത്.
"ഹലോ, എനിക്ക് ഡോക്ടറെ കാണണം," ഞാൻ പറയുന്നു.
"ശരി, എന്താണ് ബുദ്ധിമുട്ട്?" അവർ ചോദിക്കുന്നു.
"എനിക്ക് പനിയും തലവേദനയും ഉണ്ട്."
"എന്റെ തൊണ്ടയും നല്ലതുപോലെ വേദനിക്കുന്നു."
"ശരി, നിങ്ങളുടെ പേരെന്താണ്?" അവർ ചോദിക്കുന്നു.
"എന്റെ പേര് മായ."
"നിങ്ങൾ ആദ്യമായിട്ടാണോ ഇവിടെ വരുന്നത്?" അവർ ചോദിക്കുന്നു.
"അതെ," ഞാൻ പറയുന്നു.
"നിങ്ങളുടെ ഫോൺ നമ്പർ പറയൂ."
ഞാൻ എന്റെ മൊബൈൽ നമ്പർ പറയുന്നു.
"തൊണ്ണൂറ്റിയെട്ട്, എഴുപത്തിയാറ്, അമ്പത്തിനാല്, മുപ്പത്തിരണ്ട്, പത്ത്."
"ശരി, നിങ്ങൾ ഇന്ന് രാവിലെ പത്തരയ്ക്ക് വരണം," അവർ പറയുന്നു.
"ഞാൻ വരാം," ഞാൻ പറയുന്നു.
ഞാൻ ഫോൺ വെച്ചിട്ട് പോകാൻ തയ്യാറാകുന്നു.
