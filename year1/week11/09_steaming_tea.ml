ഞാൻ അടുക്കളയിലേക്ക് പോകുന്നു.
എനിക്ക് കുടിക്കാൻ ചൂടുള്ള എന്തെങ്കിലും വേണം.
ഞാൻ ചായയ്ക്കായി വെള്ളം തിളപ്പിക്കുന്നു.
വെള്ളത്തിന് നല്ല ചൂടുണ്ട്.
ഞാൻ ഒരു വലിയ കപ്പ് ഹെർബൽ ടീ ഉണ്ടാക്കുന്നു.
ഞാൻ എന്റെ ചായ സ്വീകരണമുറിയിലേക്ക് കൊണ്ടുപോകുന്നു.
ഞാൻ സോഫയിൽ ഇരിക്കുന്നു.
അതൊരു ഇരുണ്ട ശൈത്യകാല സായാഹ്നമാണ്.
ഞാൻ ആ ചൂടുള്ള കപ്പ് എന്റെ കൈകളിൽ പിടിക്കുന്നു.
എനിക്ക് പെട്ടെന്ന് ചൂട് ലഭിക്കുന്നു.
ഞാൻ പുറത്തെ കാറ്റ് ശ്രദ്ധിച്ചു കേൾക്കുന്നു.
കാറ്റ് ശക്തമായി വീശുന്നുണ്ട്.
ഇന്ന് രാത്രി കാലാവസ്ഥ വളരെ പ്രക്ഷുബ്ധമാണ്.
എന്നാൽ ഇതിനുള്ളിൽ വളരെ സുഖകരമാണ്.
മൂലയിൽ വിളക്ക് മൃദുവായി പ്രകാശിക്കുന്നു.
ഞാൻ എന്റെ ചായയിൽ നിന്ന് ഒരു കവിൾ കുടിക്കുന്നു.
അതിന് പുതിനയുടെ രുചിയാണ്.
ആ നീണ്ട ദിവസം അവസാനിച്ചു.
ഇപ്പോൾ ഞാൻ വിശ്രമിക്കുന്നു.
