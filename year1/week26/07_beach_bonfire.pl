Schodzę na plażę.
Wiele osób już dotarło na wieczorną imprezę.
Szukam Evy i Petera w tłumie.
Nagle widzę ich w dole, nad wodą, i spieszę tam.
– Miałaś udany tydzień urodzinowy? – pyta Peter z uśmiechem.
– Tak, był absolutnie fantastyczny – odpowiadam radośnie.
Eva otwiera mały koszyk.
– Kupiłam dziś rano świeże truskawki na targu – mówi.
– Próbowałaś kiedyś duńskich letnich truskawek?
– Nie, nigdy tego nie próbowałam – mówię i biorę jedną.
Smakuje niezwykle słodko i przypomina mi o lecie.
W tej samej chwili jakiś mężczyzna rozpala duże ognisko.
Płomienie szybko rosną i wznoszą się wysoko ku niebu.
Wcześniej było zimno, ale teraz ogień ogrzał powietrze.
Promieniujące ciepło szybko przegania chłód z wybrzeża.
Stoimy blisko siebie i długo wpatrujemy się w płomienie.
Myślę o tym, że mieszkam tu w mieście już od sześciu miesięcy.
Mój pierwszy miesiąc tutaj był ciemny, ale ten jasny letni wieczór jest idealny.
