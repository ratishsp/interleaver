Idę w stronę wyjścia z targu.
Widzę duże stoisko z kwiatami.
Na stoisku jest wiele pięknych kwiatów.
Zatrzymuję się przed stoiskiem.
Patrzę na pęczek zimowych tulipanów.
Są bardzo kolorowe.
Wskazuję na tulipany.
„Ile kosztują tulipany?” – pytam sprzedawcę.
Sprzedawca unosi tulipany.
„Kosztują czterdzieści koron” – odpowiada.
„Kupię je” – mówię.
Płacę za kwiaty.
Sprzedawca podaje mi tulipany.
Teraz skończyłam już na targu.
Wracam do swojego mieszkania.
Trzymam kolorowe tulipany w dłoni.
Piję swoją gorącą kawę.
Słońce świeci nad gwarnym targiem.
