Jag går ut ur provhytten med den blå skjortan.
Den större storleken passar perfekt.
Expediten står fortfarande vid kassan.
"Är den bättre?" frågar hon med ett leende.
"Ja, den är mycket bättre," svarar jag.
"Den mindre skjortan var för trång," förklarar jag.
"Jag vill gärna byta till den här."
"Det är helt okej," säger hon.
"Får jag se ditt kvitto igen?" frågar hon.
Jag ger henne det lilla papperskvittot.
Hon skannar streckkoden.
"Sådär, nu är den bytt," säger hon.
"Det kostar inget extra."
"Tack så mycket för hjälpen," säger jag.
"Tack själv, och ha en bra dag," svarar hon.
Jag lägger ner skjortan i min väska.
Nu har jag äntligen lite bra kläder till våren.
Jag går ut ur butiken.
Jag är mycket nöjd när jag går hem.
