Eva nalewa kawę do dwóch dużych kubków.
Siadamy na miękkiej sofie w salonie.
"Jak ci się teraz żyje w mieście?" – pyta Eva.
Biorę łyk ciepłej kawy.
Mówię jej, że czuję, iż moje nowe życie jest właściwie naprawdę wspaniałe.
"W końcu się tu zadomowiłam" – mówię z uśmiechem.
"Cieszę się, że to słyszę" – odpowiada.
"Pracujesz też bardzo ciężko nad naszym projektem w biurze."
"Tak, ale zamierzam teraz brać więcej wolnego" – mówię.
"W weekendy będę znacznie bardziej cieszyć się miastem."
"Dobrze to rozumiem" – mówi Eva.
Długo rozmawiamy o naszych pozostałych współpracownikach i o pracy.
Śmiejemy się i opowiadamy sobie wiele historii.
Uśmiecham się do niej znad kubka z kawą.
Mówię, że mam nadzieję, iż nadal będziemy się spotykać poza pracą.
"Na pewno będziemy" – odpowiada radośnie.
Myślę, że prawdopodobnie spędzimy razem wiele fajnych wieczorów.
