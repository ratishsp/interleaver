Sedáme si ke krásnému stolu.
Eva prostřela stůl barevnými talíři a zapálenými svíčkami.
Připravila pro nás skvělé vegetariánské jídlo.
„Děkuji, Evo, vypadá to výborně,“ říkám s úsměvem.
„Voní to naprosto fantasticky.“
„Rádo se stalo,“ odpovídá a podává mi misku se salátem.
Okamžitě jídlo ochutnávám.
Myslím, že ty čerstvé suroviny chutnají opravdu báječně.
„Tohle je neuvěřitelně lahodné,“ říkám jí.
„Mám v plánu brzy uvařit ještě více místních jídel,“ říkám.
„Moc ráda bych používala více dánské zeleniny.“
„To zní jako opravdu dobrý nápad,“ říká Eva radostně.
„Jednou určitě musíme vařit společně.“
„Věřím, že se v kuchyni asi budeme dobře bavit.“
„To bych moc ráda,“ odpovídám a beru si další sousto.
Naléváme trochu studené vody do sklenic.
Cítím, že tento večer je už teď velký úspěch.
