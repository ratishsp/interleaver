Jdu k pokladně se svými novými věcmi.
Prodavačka vzhlédne a pozdraví.
„Dobrý den,“ říká.
„Dobrý den,“ odpovídám.
Položím světle zelenou bundu a modrou košili na pult.
Naskenuje obě věci.
„Bude to šest set padesát korun,“ říká.
Platím kartou.
„Chcete účtenku?“ ptá se prodavačka.
„Ano, prosím,“ odpovídám rychle.
„Nezkoušela jsem si tu košili,“ vysvětluji.
„Doufám, že nebudu potřebovat větší.“
„Můžete ji kdykoli vyměnit,“ říká prodavačka laskavě.
Vytiskne účtenku a podá mi ji.
„Nezapomeňte si ji schovat,“ říká.
Vezmu si účtenku.
Složím ten malý kousek papíru.
Pak si ho bezpečně uložím do peněženky.
„Hezký víkend,“ říkám jí.
„Vám také,“ odpovídá.
