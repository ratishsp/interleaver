ഇന്ന് ചൊവ്വാഴ്ചയാണ്.
വൈകുന്നേരം ഞാൻ ഒരു ബ്യൂട്ടി പാർലറിലേക്ക് ഫോൺ വിളിക്കുന്നു.
ഒരു സ്ത്രീ ഫോൺ എടുക്കുന്നു.
അവർ വളരെ മാന്യമായി സംസാരിക്കുന്നു.
"ഹലോ, ബ്യൂട്ടി പാർലർ," അവർ പറയുന്നു.
"നമസ്കാരം, എനിക്ക് ഒരു ഹെയർകട്ട് വേണം," ഞാൻ പറയുന്നു.
"തീർച്ചയായും, ഏത് ദിവസമാണ് വരുന്നത്?" അവർ ചോദിക്കുന്നു.
"ഞാൻ വ്യാഴാഴ്ച വരാം," ഞാൻ പറയുന്നു.
"ശരി, വ്യാഴാഴ്ച എത്ര മണിക്ക്?" അവർ ചോദിക്കുന്നു.
ഞാൻ എന്റെ കലണ്ടർ നോക്കുന്നു.
ഞാൻ ചിലപ്പോൾ രാവിലെ തിരക്കിലാണ്.
പക്ഷേ ഞാൻ എല്ലാ ദിവസവും വൈകുന്നേരം ഫ്രീ ആണ്.
"വൈകുന്നേരം അഞ്ചരയ്ക്ക് വരാമോ?" ഞാൻ ചോദിക്കുന്നു.
"വ്യാഴാഴ്ച വൈകുന്നേരം അഞ്ചര മണിക്ക് വരാം," അവർ പറയുന്നു.
"നിങ്ങളുടെ പേര് എന്താണ്?" അവർ ചോദിക്കുന്നു.
"എന്റെ പേര് മായ," ഞാൻ പറയുന്നു.
"ശരി മായ, വ്യാഴാഴ്ച കാണാം," അവർ പറയുന്നു.
ഞാൻ ഫോൺ വെക്കുന്നു.
ഞാൻ എന്റെ കലണ്ടറിൽ പുതിയ സമയം എഴുതുന്നു.
