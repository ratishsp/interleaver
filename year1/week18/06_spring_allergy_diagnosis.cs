Lékař mě žádá, abych otevřela ústa.
„Řekněte á,“ říká s úsměvem.
Pečlivě se mi dívá do krku.
Potom poslouchá mé dýchání.
Ptá se, jestli mi není špatně i někde jinde.
Říkám mu, že mě bolí také hlava.
„Není to nachlazení,“ říká.
„Máte běžnou jarní alergii,“ vysvětluje.
Jsem trochu překvapená.
Nikdy předtím jsem alergii neměla.
Říká mi, že je to naprosto normální.
Zdejší stromy a květiny jsou pro mé tělo nové.
„Měla byste si v lékárně koupit nějaký slabší lék,“ říká lékař.
Slibuje, že to rychle pomůže.
„Pak vám bude zase dobře,“ dodává.
Velmi se mi ulevilo.
Bolí mě v krku, ale naštěstí to není vážné.
