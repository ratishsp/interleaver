പിന്നീട് ഉച്ചകഴിഞ്ഞ്, ഞാൻ എന്റെ അപ്പാർട്ട്മെന്റിൽ തിരിച്ചെത്തി.
ഷോപ്പിംഗിന് പോയതിന് ശേഷം എനിക്ക് അല്പം ക്ഷീണമുണ്ട്.
ഞാൻ കട്ടിലിൽ ഇരുന്ന് എന്റെ ബാഗുകളിലെ സാധനങ്ങൾ പുറത്തെടുക്കുന്നു.
ആദ്യം, ഞാൻ എന്റെ പുതിയ, ഇളം പച്ച നിറത്തിലുള്ള സ്പ്രിംഗ് ജാക്കറ്റ് പുറത്തെടുക്കുന്നു.
അതിനുശേഷം ഞാൻ ആ നീല കോട്ടൺ ഷർട്ട് പുറത്തെടുക്കുന്നു.
അത് ഇട്ടുനോക്കാൻ ഞാൻ വളരെ ആകാംക്ഷയിലാണ്.
ഞാൻ എന്റെ പഴയ സ്വെറ്റർ ഊരിമാറ്റി ആ ഷർട്ട് ധരിക്കുന്നു.
എന്നാൽ ഉടൻ തന്നെ എനിക്കൊരു പ്രശ്നം മനസ്സിലാകുന്നു.
ഷർട്ട് തീരെ ചെറുതാണ്.
ചുമലുകളുടെ ഭാഗത്ത് ഇത് വളരെ ഇറുകിയിരിക്കുകയാണ്.
ശരിക്കും പറഞ്ഞാൽ എനിക്ക് കൈകൾ ഉയർത്താൻ പോലും കഴിയുന്നില്ല.
കണ്ണാടിയിൽ നോക്കുമ്പോൾ ഷർട്ട് വളരെ ഇറുകിയതായി കാണുന്നു.
എനിക്ക് ഇതിലും വലിയൊരു സൈസ് ആവശ്യമാണെന്ന് വ്യക്തമാണ്.
എന്റെ സാധാരണ സൈസിനേക്കാൾ വളരെ ചെറുതാണ് ഈ മോഡൽ.
കടയിൽ വെച്ച് അതൊന്ന് ഇട്ടുനോക്കാതിരുന്നത് കഷ്ടമായിപ്പോയി.
എന്നാൽ ഫിറ്റിംഗ് റൂമുകൾക്ക് മുന്നിലെ ക്യൂ വളരെ നീളമുള്ളതായിരുന്നു.
ഞാൻ ആ ചെറിയ ഷർട്ട് വീണ്ടും ഊരിമാറ്റുന്നു.
ഞാനത് വൃത്തിയായി മടക്കി തിരികെ ബാഗിൽ വെക്കുന്നു.
ഭാഗ്യത്തിന്, എന്റെ പക്കൽ ഇപ്പോഴും രസീത് ഉണ്ട്.
തിങ്കളാഴ്ച ജോലി കഴിഞ്ഞിറങ്ങുമ്പോൾ എനിക്ക് ഈ ഷർട്ട് മാറ്റി വലിയതൊരെണ്ണം എടുക്കാം.
