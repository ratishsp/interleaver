Jag går över till Ninas dörr.
Jag knackar på dörren.
Nina öppnar och ler.
Jag visar henne chokladkakan.
"Hej Nina", säger jag.
"Jag har en kaka från bageriet."
"Hej Maya, vad härligt!" säger Nina.
Vi går in i hennes vardagsrum.
Vardagsrummet är mycket varmt och mysigt.
Vi sitter i den mjuka soffan.
Nina gör varmt te till oss.
Vi dricker te och äter den söta kakan.
Chokladkakan smakar verkligen gott.
Vi pratar om vår dag i stan.
Nina frågar om mitt arbete.
Jag berättar om kontoret och min kollega Peter.
Nina berättar också om sin dag.
Vi skrattar och pratar hela kvällen.
Det är en riktigt bra kväll.
Jag känner mig hemma här i min nya stad.
