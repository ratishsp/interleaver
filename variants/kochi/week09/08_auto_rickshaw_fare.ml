ഞാൻ മാർക്കറ്റിൽ നിന്ന് പുറത്ത് വരുന്നു.
എന്റെ കയ്യിൽ ഭാരമുള്ള തുണിസഞ്ചികൾ ഉണ്ട്.
രാവിലെ തന്നെ നല്ല ചൂടുണ്ട്.
എനിക്ക് വളരെ ക്ഷീണം തോന്നുന്നു.
ഞാൻ മെയിൻ റോഡിലേക്ക് നടക്കുന്നു.
റോഡിൽ ഒരുപാട് ഓട്ടോകൾ ഉണ്ട്.
ഞാൻ ഒരു ഓട്ടോയുടെ അടുത്തേക്ക് പോകുന്നു.
"എനിക്ക് കലൂരിൽ പോകണം," ഞാൻ ഡ്രൈവറോട് പറയുന്നു.
"കലൂരിലേക്ക് എത്ര രൂപ ആകും?"
ഞാൻ ചോദിക്കുന്നു.
"എൺപതു രൂപ ആകും," ഡ്രൈവർ മറുപടി പറയുന്നു.
ഞാൻ അത് സമ്മതിക്കുന്നു.
"ശരി, പോകാം," ഞാൻ പറയുന്നു.
ഞാൻ ആദ്യം സഞ്ചികൾ ഓട്ടോയിൽ വെക്കുന്നു.
എന്നിട്ട് ഞാൻ ഓട്ടോയിൽ കയറി ഇരിക്കുന്നു.
ഓട്ടോ എന്റെ ഫ്ലാറ്റിലേക്ക് യാത്ര തുടങ്ങുന്നു.
എനിക്ക് വളരെ ആശ്വാസം തോന്നുന്നു.
