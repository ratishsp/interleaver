ഞാൻ എഴുന്നേറ്റ് എൻ്റെ ജാക്കറ്റ് എടുക്കുന്നു.
സമയം വൈകി, എനിക്ക് വീട്ടിലേക്ക് ബസ്സിൽ പോകണം.
ഇവാ എൻ്റെ കൂടെ വാതിൽക്കൽ വരെ വരുന്നു.
"അടുത്ത മാസം നമുക്ക് എന്തെങ്കിലും ചെയ്യാമോ?" അവൾ പെട്ടെന്ന് ചോദിക്കുന്നു.
"ഞാൻ ഒരു ആർട്ട് മ്യൂസിയത്തിൽ പോകാൻ ഉദ്ദേശിക്കുന്നു," അവൾ വിശദീകരിക്കുന്നു.
"നിനക്കും ഒപ്പം വരാൻ താല്പര്യമുണ്ടോ?"
ഞാൻ ആവേശത്തോടെ തലയാട്ടി എൻ്റെ ബാഗ് എടുക്കുന്നു.
"അതെ, വരാൻ എനിക്ക് വലിയ സന്തോഷമാണ്," ഞാൻ മറുപടി പറയുന്നു.
നമുക്ക് തീർച്ചയായും നന്നായി ആസ്വദിക്കാൻ കഴിയുമെന്ന് ഞാൻ കരുതുന്നു.
എനിക്ക് മോഡേൺ ആർട്ട് വളരെ ഇഷ്ടമാണെന്നും ഞാൻ അവളോട് പറയുന്നു.
"പിന്നെ, നമ്മൾ എപ്പോഴും പരസ്പരം വളരെ നന്നായി സംസാരിക്കാറുണ്ടെന്നാണ് എനിക്ക് തോന്നുന്നത്," ഞാൻ കൂട്ടിച്ചേർക്കുന്നു.
ഇവാ നിറപുഞ്ചിരിയോടെ എനിക്കായി മുൻവാതിൽ തുറന്നുതരുന്നു.
"തീർച്ചയായും നമുക്ക് ഉടൻ തന്നെ അതിനായി ഒരു പ്ലാൻ ഉണ്ടാക്കാം," അവൾ ഉറപ്പുനൽകുന്നു.
"ഞാൻ തിങ്കളാഴ്ച നിനക്കൊരു മെസ്സേജ് അയക്കാം," ഞാൻ പറയുന്നു.
ഞാൻ അവളെ കെട്ടിപ്പിടിച്ചിട്ട് പുറത്തെ ഗോവണിയിലേക്ക് ഇറങ്ങുന്നു.
നമ്മുടെ മ്യൂസിയം യാത്രയ്ക്കായി ഞാൻ ഇപ്പോഴേ കാത്തിരിക്കുകയാണ്.
