Jdu zpátky po tiché ulici.
Jdu rovně.
Brzy znovu vidím velké náměstí.
Pak jdu přes náměstí.
Teď stojím u muzea.
Pamatuji si slova té ženy: „Zahněte doprava.“
U muzea zahýbám doprava.
Jdu dolů po široké ulici.
Dívám se před sebe.
Konečně vidím něco modrého.
To je voda!
Cestou jdu kolem malé kavárny.
Nakonec jdu až dolů k vodě.
Teď jsem v přístavu.
Přístav je velmi velký.
Vítr je studený a svěží.
Na vodě je mnoho lodí.
Tady se zastavuji.
Stojím a dívám se na lodě.
