ഇന്ന് ശനിയാഴ്ചയാണ്.
കഫേയിലെ എന്റെ രാവിലത്തെ ജോലി കഴിഞ്ഞു.
ഞാൻ പുറത്തേക്ക് ഇറങ്ങുന്നു.
പുറത്ത് നല്ല മഴ പെയ്യുന്നുണ്ട്.
കൊച്ചിയിൽ ഇപ്പോൾ മൺസൂൺ കാലമാണ്.
മൂന്ന് ആഴ്ചയായി ഇവിടെ മഴയാണ്.
എന്റെ ബാഗിൽ ഒരു കുടയുണ്ട്.
പക്ഷേ സൈക്കിൾ ഓടിക്കാൻ കുട മാത്രം പോരാ.
എനിക്ക് പുതിയ ഒരു റെയിൻകോട്ട് വേണം.
കൂടെ ഒരു പുതിയ ഷർട്ടും വാങ്ങണം.
ടൗണിൽ ഒരു നല്ല തുണിക്കടയുണ്ട്.
ആ കട വളരെ വലുതാണ്.
ഞാൻ അവിടേക്ക് പോകാൻ തീരുമാനിക്കുന്നു.
