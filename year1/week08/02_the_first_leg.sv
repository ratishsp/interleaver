Jag följer Ninas rutt.
Luften är frisk och kall.
Nu går jag nerför huvudgatan.
Först går jag bara rakt fram.
Det är mycket trafik på gatan.
På vägen ser jag tre gula cyklar.
Cyklarna kör snabbt förbi mig.
Därefter går jag längre fram.
Sedan kommer jag till en stor park.
Nu minns jag Ninas ord.
"Sväng vänster vid parken", säger hon.
Här svänger jag vänster.
Lite senare ser jag en öppen dörr.
Det är ett litet bageri.
Det är en härlig doft av färskt kaffe.
Jag älskar varmt bröd.
Idag är staden härlig.
Efteråt går jag vidare mot vattnet.
