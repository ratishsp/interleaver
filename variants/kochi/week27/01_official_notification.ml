ഞാൻ ഇൻഫോപാർക്കിലെ ഓഫീസിലാണ്.
ഇപ്പോൾ രാവിലത്തെ ചായ കുടിക്കുന്ന സമയമാണ്.
ഞാനും പ്രകാശും ഈ സമയത്ത് ഒരുമിച്ച് ചായ കുടിക്കാറുണ്ട്.
ഞങ്ങൾ കഫറ്റീരിയയിൽ സംസാരിച്ചിരിക്കുകയാണ്.
പെട്ടെന്ന് എന്റെ ഫോണിൽ ഒരു സന്ദേശം വരുന്നു.
ഞാൻ ഫോൺ എടുത്തു നോക്കുന്നു.
അതൊരു ഔദ്യോഗിക സന്ദേശമാണ്.
എന്റെ മൊബൈൽ സേവന ദാതാക്കളിൽ നിന്നാണ് അത് വന്നിരിക്കുന്നത്.
വളരെ ഔദ്യോഗികമായ ഭാഷയാണ് അതിൽ ഉപയോഗിച്ചിരിക്കുന്നത്.
"കണക്ഷൻ നിലനിർത്താൻ നിങ്ങളുടെ വിവരങ്ങൾ പുതുക്കപ്പെടേണ്ടതുണ്ട്."
അത് വായിച്ചപ്പോൾ എനിക്ക് ചെറിയ പേടി തോന്നുന്നു.
എന്റെ ഫോൺ കണക്ഷൻ അവർ റദ്ദാക്കുമോ?
ഞാൻ പ്രകാശിന് ഫോണിന്റെ സ്ക്രീൻ കാണിച്ചു കൊടുക്കുന്നു.
"പ്രകാശ്, ഇതൊന്ന് നോക്കൂ."
"എന്തെങ്കിലും പ്രശ്നമുണ്ടോ?" ഞാൻ ചോദിക്കുന്നു.
പ്രകാശ് ആ സന്ദേശം വായിക്കുന്നു.
എന്നിട്ട് അദ്ദേഹം ചിരിക്കുന്നു.
"ഇതൊരു സാധാരണ സന്ദേശമാണ് മായാ," പ്രകാശ് പറയുന്നു.
"കമ്പനികൾ ഉപഭോക്താക്കൾക്ക് ഇങ്ങനെ സന്ദേശങ്ങൾ അയക്കാറുണ്ട്."
"ഇതൊരു സാധാരണ പരിശോധന മാത്രമാണ്."
അതുകേട്ടപ്പോൾ എനിക്ക് വലിയ ആശ്വാസമാകുന്നു.
