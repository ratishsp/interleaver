ഞാൻ വീട്ടിലേക്ക് പോകാൻ ബസ്സിൽ കയറുന്നു.
പുറത്ത് നല്ല മഴ പെയ്യുന്നു.
ഇപ്പോൾ ശക്തമായ കാറ്റ് അടിക്കുന്നു.
മഴവെള്ളം ജനലിലൂടെ ബസ്സിനുള്ളിലേക്ക് വരുന്നു.
ഒരു യാത്രക്കാരൻ ഇരുമ്പ് ജനൽ താഴേക്ക് വലിച്ചിടുന്നു.
ഞാനും അയാളെ സഹായിക്കുന്നു.
ഞാൻ എന്റെ സീറ്റിനടുത്തുള്ള ജനലും അടയ്ക്കുന്നു.
മറ്റു യാത്രക്കാരും ജനലുകൾ വേഗത്തിൽ അടയ്ക്കുന്നു.
ഇപ്പോൾ മഴവെള്ളം ഉള്ളിലേക്ക് വരുന്നില്ല.
ബസ്സിനുള്ളിൽ നല്ല തണുപ്പാണ്.
കൊച്ചിയിൽ പൊതുവേ വളരെ ചൂടാണ്.
പകൽ സമയത്ത് നല്ല വെയിലാണ്.
പക്ഷേ ഇപ്പോൾ നല്ല മഴ പെയ്യുന്നു.
എനിക്ക് ഈ തണുപ്പ് വളരെ ഇഷ്ടമാണ്.
ബസ് യാത്ര തുടരുന്നു.
ഞാൻ സന്തോഷത്തോടെ ജനലിനടുത്ത് ഇരിക്കുന്നു.
