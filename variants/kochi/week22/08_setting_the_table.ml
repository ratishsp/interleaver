കിരണും സാറയും ഹാളിൽ ഇരിക്കുമ്പോൾ, ഞാൻ ഊണുമേശ ശരിയാക്കുന്നു.
ഞാൻ ആദ്യം മേശ തുടച്ച് വൃത്തിയാക്കുന്നു.
അതിനുശേഷം ഞാൻ മൂന്ന് പ്ലേറ്റുകൾ മേശപ്പുറത്ത് വെക്കുന്നു.
പിന്നെ മൂന്ന് ഗ്ലാസ്സുകളും ഒരു ജഗ്ഗ് വെള്ളവും കൊണ്ടുവരുന്നു.
ആ ജഗ്ഗ് ഞാൻ മേശയുടെ നടുവിൽ വെക്കുന്നു.
പ്ലേറ്റിനടുത്ത് മൂന്ന് സ്പൂണുകളും വെക്കുന്നു.
ഇപ്പോൾ അടുക്കളയിൽ നിന്ന് നല്ല മണം വരുന്നുണ്ട്.
ഞാൻ ഒരു വലിയ പാത്രത്തിൽ ചൂടുള്ള ചോറ് മേശപ്പുറത്ത് കൊണ്ടുവന്ന് വെക്കുന്നു.
അതിനുശേഷം കോഴിക്കറിയും മേശപ്പുറത്ത് വെക്കുന്നു.
"എല്ലാം തയ്യാറാണ്, നമുക്ക് കഴിക്കാം," ഞാൻ സന്തോഷത്തോടെ പറയുന്നു.
