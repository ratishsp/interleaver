ഇപ്പോൾ രാത്രിയാണ്.
ഇത് കോപ്പൻഹേഗനിലെ എന്റെ ആദ്യത്തെ രാത്രിയാണ്.
ഞാൻ ബാത്ത്റൂമിലാണ്.
അത് വളരെ ചെറുതാണ്.
അവിടെ ഒരു സിങ്ക് ഉണ്ട്.
എന്റെ ടൂത്ത് ബ്രഷ് ചുവപ്പാണ്.
ഞാൻ എന്റെ ടൂത്ത് ബ്രഷിൽ ടൂത്ത് പേസ്റ്റ് വെക്കുന്നു.
ഞാൻ പല്ല് തേക്കുന്നു.
വെള്ളം തണുത്തതാണ്.
ഞാൻ മുഖം കഴുകുന്നു.
അത് സുഖകരമാണ്.
ഞാൻ എന്റെ കിടക്കയിലേക്ക് പോകുന്നു.
കിടക്ക ചെറുതാണ്.
എന്നാൽ അത് ചൂടുള്ളതും മൃദുവായതുമാണ്.
ഞാൻ ഇപ്പോൾ പുതപ്പിനുള്ളിൽ കിടക്കുകയാണ്.
എന്റെ ഫോൺ മേശപ്പുറത്ത് ഇരിക്കുന്നു.
ഞാൻ എന്റെ അലാറം വെക്കുന്നു.
അത് നാളെ എട്ട് മണിക്ക് അടിക്കും.
എനിക്ക് ക്ഷീണമുണ്ട്, എങ്കിലും ഞാൻ തയ്യാറാണ്.
ശുഭരാത്രി, കോപ്പൻഹേഗൻ.
