Jag går fram till glasdisken.
Den är full av kakor och bröd.
Jag tittar på de många sakerna.
De ser mycket läckra ut.
Det finns små skyltar bredvid kakorna.
Skyltarna är handskrivna.
Jag läser namnen på skyltarna.
Det finns många slags bakverk.
Det är svårt att välja.
Det finns en stor chokladkaka.
Men jag tittar på ett annat bakverk.
Det är en stor kanelbulle.
Den har mycket socker på toppen.
Jag älskar smaken av kanel.
Det är perfekt till en kall vinterdag.
Jag vill mycket gärna ha kanelbullen.
Nu är jag redo att beställa.
