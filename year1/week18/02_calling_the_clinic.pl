Znajduję numer telefonu do mojej lokalnej przychodni lekarskiej.
Numer to trzydzieści dwa, czterdzieści pięć, sześćdziesiąt siedem, osiemdziesiąt dziewięć.
Dzwonię do nich i czekam kilka minut.
Przyjazna recepcjonistka odbiera telefon.
"Przychodnia lekarska, rozmawia pani z Hanną" – mówi.
Wyjaśniam, że dzisiaj bardzo się rozchorowałam.
"Mam ciężką głowę i swędzą mnie oczy" – mówię.
Mówię jej również, że boli mnie gardło.
Pyta, czy mam gorączkę.
Odpowiadam, że chyba nie, ale jestem bardzo zmęczona.
"Powinna pani porozmawiać dzisiaj z lekarzem" – mówi recepcjonistka.
Patrzy w kalendarz, żeby znaleźć termin.
"Czy może pani przyjść o pierwszej?" – pyta.
"Tak, to pasuje idealnie" – odpowiadam.
"Proszę pamiętać, aby zabrać swoją żółtą kartę zdrowia" – mówi.
Dziękuję jej i się rozłączam.
Teraz muszę tylko trochę odpocząć, zanim tam pójdę.
