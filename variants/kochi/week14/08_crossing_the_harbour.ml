ഞാൻ ജനലിലൂടെ പുറത്തേക്ക് നോക്കുന്നു.
കായലിലെ വെള്ളത്തിന് നല്ല നീല നിറമാണ്.
ഈ കായൽ വളരെ വലുതാണ്.
ഞാൻ ദൂരെ കര കാണുന്നു.
കരയിൽ മരം കൊണ്ടുള്ള വലിയ വലകൾ ഉണ്ട്.
അവ കൊച്ചിയിലെ പ്രശസ്തമായ ചീനവലകൾ ആണ്.
അവ കാണാൻ നല്ല ഭംഗിയുണ്ട്.
ബോട്ട് ഇപ്പോൾ ജെട്ടിയിലേക്ക് അടുക്കുന്നു.
എനിക്ക് ഫോർട്ട് കൊച്ചിയിൽ ഇറങ്ങണം.
എനിക്ക് അവിടെ ഒരു കടയിൽ പോകണം.
ഞാൻ എന്റെ ബാഗ് എടുക്കുന്നു.
ബോട്ട് ജെട്ടിയിൽ എത്തുന്നു.
വാതിൽ തുറക്കുന്നു.
