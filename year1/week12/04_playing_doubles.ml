ഞാൻ ഒരു ബാഡ്മിന്റൺ കോർട്ടിലേക്ക് നടന്നുപോകുന്നു.
കോർട്ടിൽ മൂന്ന് പേർ നിൽക്കുന്നുണ്ട്.
"ഹായ്, ഞാൻ കാസ്പർ," ഒരു പുരുഷൻ പറയുന്നു.
"പിന്നെ ഞാൻ സാറ," ഒരു സ്ത്രീ പറയുന്നു.
മൂന്നാമത്തെ കളിക്കാരന്റെ പേര് എമിൽ എന്നാണ്.
"ഞാൻ മായ," ഞാൻ പറയുന്നു.
"ഞങ്ങൾ സാധാരണയായി ഡബിൾസ് ആണ് കളിക്കാറുള്ളത്," കാസ്പർ പറയുന്നു.
"നിങ്ങൾക്ക് ഞങ്ങളുടെ കൂടെ കളിക്കണോ?" അവൻ ചോദിക്കുന്നു.
"അതെ, എനിക്കത് വലിയ സന്തോഷമാണ്," ഞാൻ മറുപടി നൽകുന്നു.
എനിക്ക് ബാഡ്മിന്റൺ കളിക്കാൻ വളരെ ഇഷ്ടമാണ്.
കാസ്പറും ഞാനും സാറയ്ക്കും എമിലിനും എതിരെ കളിക്കുന്നു.
ഞങ്ങൾ ഉടനടി കളിക്കാൻ തുടങ്ങുന്നു.
സാറ മത്സരം തുടങ്ങുന്നു.
ഷട്ടിൽകോക്ക് വേഗത്തിൽ അങ്ങോട്ടും ഇങ്ങോട്ടും പറക്കുന്നു.
എമിൽ ഷട്ടിൽകോക്ക് വായുവിലേക്ക് ഉയരെ അടിക്കുന്നു.
സ്മാഷ് ചെയ്യാൻ എനിക്ക് വളരെ ഇഷ്ടമാണ്.
ഞാൻ ചാടി നെറ്റിന് മുകളിലൂടെ അത് ശക്തിയായി സ്മാഷ് ചെയ്യുന്നു.
അത് കോർട്ടിന്റെ അവരുടെ ഭാഗത്ത് ചെന്ന് വീഴുന്നു.
"നല്ല ഷോട്ട്, മായാ!" കാസ്പർ വിളിച്ചുപറയുന്നു.
