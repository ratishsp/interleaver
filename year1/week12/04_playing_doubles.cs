Jdu k badmintonovému kurtu.
Na kurtu stojí tři lidé.
„Ahoj, já jsem Kasper,“ říká muž.
„A já jsem Sara,“ říká žena.
Třetí hráč se jmenuje Emil.
„Já jsem Maya,“ říkám.
„Většinou hrajeme čtyřhru,“ říká Kasper.
„Chceš hrát s námi?“ ptá se.
„Ano, moc ráda,“ odpovídám.
Moc ráda hraju badminton.
Kasper a já hrajeme proti Saře a Emilovi.
Hned začínáme hrát.
Sara zahajuje zápas.
Košíček rychle létá sem a tam.
Emil odpaluje košíček vysoko do vzduchu.
Miluju smečování.
Vyskočím a tvrdě ho zasmečuju přes síť.
Dopadne na jejich stranu kurtu.
„Dobrý úder, Mayo!“ křičí Kasper.
