ഞാൻ കോണിപ്പടികൾ കയറുന്നു.
എൻ്റെ കൈകളിൽ രണ്ട് ബാഗുകളുണ്ട്.
ഞാൻ ഒടുവിൽ എൻ്റെ പുതിയ വാതിലിനരികിൽ എത്തി.
എൻ്റെ പോക്കറ്റിൽ ഒരു താക്കോലുണ്ട്.
ഞാൻ ബാഗുകൾ താഴെ തറയിൽ വെക്കുന്നു.
ഞാൻ താക്കോൽ പുറത്തെടുക്കുന്നു.
ഞാൻ വാതിലിന്റെ പൂട്ട்துறക്കുന്നു.
ഞാൻ വാതിൽ തള്ളിത്തുറന്ന് അകത്തേക്ക് കയറുന്നു.
അപ്പാർട്ട്മെന്റ് ചെറുതാണ്, പക്ഷേ അത് വളരെ മികച്ചതാണ്.
അതിൽ മനോഹരവും ഇളം നിറത്തിലുള്ളതുമായ ഫർണിച്ചറുകളുണ്ട്.
ഞാൻ സ്വീകരണമുറിയിലേക്ക് നോക്കുന്നു.
ജനലിനരികിൽ ഒരു സോഫയുണ്ട്.
സോഫയുടെ അടിയിൽ ഒരു പരവതാനിയുണ്ട്.
സോഫയിൽ ഒരു ചെറിയ കുഷ്യനുണ്ട്.
മൂലയിൽ ഒരു ലാമ്പുണ്ട്.
ഞാൻ എൻ്റെ പിന്നിലെ വാതിലടക്കുന്നു.
ഞാൻ എൻ്റെ താക്കോൽ മേശപ്പുറത്ത് വെക്കുന്നു.
