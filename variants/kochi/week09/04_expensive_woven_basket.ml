ഞാൻ മാർക്കറ്റിലൂടെ വീണ്ടും നടക്കുന്നു.
അവിടെ വീട്ടുസാധനങ്ങളുടെ ഒരു കടയുണ്ട്.
ഞാൻ അവിടെ ഒരു ഭംഗിയുള്ള കുട്ട കാണുന്നു.
എനിക്ക് ആ കുട്ട വളരെ ഇഷ്ടമായി.
ഞാൻ കടക്കാരന്റെ അടുത്തേക്ക് പോകുന്നു.
"ചേട്ടാ, ഈ കുട്ടയ്ക്ക് വില എത്രയാണ്?" ഞാൻ ചോദിക്കുന്നു.
അയാൾ ആ കുട്ട നോക്കുന്നു.
"ഇത് നല്ല കുട്ടയാണ്," അയാൾ പറയുന്നു.
"ഇതിന് എണ്ണൂറ് രൂപയാണ്," അയാൾ പറയുന്നു.
എണ്ണൂറ് രൂപ!
അത് വലിയ വിലയാണ്.
ഞാൻ അയാളെ നോക്കി ചിരിക്കുന്നു.
"എനിക്ക് ഇത് ഇപ്പോൾ വേണ്ട, ചേട്ടാ," ഞാൻ പറയുന്നു.
"ഇതിന് വളരെ വില കൂടുതലാണ്."
ഞാൻ ആ കുട്ട തിരികെ വെക്കുന്നു.
ഞാൻ ആ കുട്ട വാങ്ങുന്നില്ല.
ഞാൻ അവിടെ നിന്നും മുന്നോട്ട് നടക്കുന്നു.
