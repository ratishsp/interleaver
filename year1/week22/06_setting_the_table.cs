Zatímco se maso dosmažuje, prostírám stůl v obývacím pokoji.
Můj jídelní kout je docela malý.
Ale je tam dost místa pro Kaspera, Saru a pro mě.
Vyndávám ze skříňky tři talíře.
Pokládám je na malý stůl.
Potom otevírám zásuvku s příbory.
Vyndávám vidličky a nože.
Ke každému talíři pokládám vidličku a nůž.
Budeme také potřebovat tři sklenice na vodu.
Jdu pro ně do kuchyně.
Nakonec beru z balíčku několik světle modrých papírových ubrousků.
Hezky je skládám.
Pak na každý talíř pokládám ubrousek.
Nyní je stůl prostřený a připravený pro hosty.
Vracím se ke sporáku.
Masové kuličky stále prskají na horké pánvi.
Sundávám pánev z ohně.
Jsem úplně připravená přivítat hosty.
