To mój pierwszy raz za ladą.
Kawiarnia nie jest jeszcze otwarta.
Jeden z doświadczonych wolontariuszy mnie woła.
Stoimy przed dużym ekspresem do kawy.
„Dzisiaj musisz nauczyć się robić kawę” – mówi.
Nigdy wcześniej nie robiłam kawy na takiej maszynie.
Pierwszym krokiem jest zmielenie ziaren kawy.
Naciska mały przycisk.
Maszyna miele brązowe ziarna z głośnym dźwiękiem.
Drugim krokiem jest spienienie mleka.
Nalewa zimne mleko do metalowego dzbanka.
Potem włącza gorącą parę.
W tym czasie uważnie przyglądam się jego dłoniom.
Mleko w dzbanku szybko staje się ciepłe i gęste.
Najwyraźniej robił już kawę wiele razy.
Kiedy przyszłam dziś rano, byłam bardzo zdenerwowana.
Ale dobrze to wytłumaczył, więc zrozumiałam już większość.
