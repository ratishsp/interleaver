മെട്രോ എത്തുന്നു, വാതിലുകൾ തുറക്കുന്നു.
ഞാൻ ട്രെയിനിലേക്ക് കയറുന്നു.
ട്രെയിൻ ഡ്രൈവറില്ലാതെയാണ് ഓടുന്നത്.
ഞാൻ ഏറ്റവും മുൻഭാഗത്തേക്ക് നടന്നുപോകുന്നു.
ഞാൻ ആ വലിയ ജനാലയ്ക്കരികിൽ നിൽക്കുന്നു.
ഞാൻ ഇരുട്ടിലൂടെ മെട്രോയിൽ യാത്ര ചെയ്യുന്നു.
ഞങ്ങൾ ഒരു നീളമുള്ള തുരങ്കത്തിലാണ്.
ഞങ്ങൾ വളരെ വേഗത്തിലാണ് പോകുന്നത്.
ജനാലയ്ക്കരികിലൂടെ വെളിച്ചം മിന്നിമറയുന്നു.
ഇത് കാണാൻ അതിമനോഹരമാണ്.
ഒരു ചെറിയ ആൺകുട്ടി എന്റെ അരികിൽ നിൽക്കുന്നുണ്ട്.
അവനും പുറത്തെ ഇരുട്ടിലേക്ക് നോക്കുന്നുണ്ട്.
ഞാൻ പലപ്പോഴും മെട്രോയിൽ യാത്ര ചെയ്യാറുണ്ട്.
ഇതൊരു വേഗതയേറിയതും എളുപ്പമുള്ളതുമായ യാത്രയാണ്.
ഇപ്പോൾ ഞങ്ങൾ എന്റെ സ്റ്റേഷനോട് അടുക്കുകയാണ്.
ഞാൻ തുറമുഖത്തേക്കാണ് പോകുന്നത്.
എന്റെ അടുത്ത യാത്ര ഹാർബർ ബസ്സിലാണ്.
വെള്ളം കാണാൻ ഞാൻ ആകാംക്ഷയോടെ കാത്തിരിക്കുകയാണ്.
