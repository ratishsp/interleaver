Jag går tillbaka längs den lugna gatan.
Jag går rakt fram.
Snart ser jag det stora torget igen.
Sedan går jag över torget.
Nu står jag vid museet.
Jag minns kvinnans ord: "Sväng höger."
Vid museet svänger jag höger.
Jag går nerför en bred gata.
Jag tittar framåt.
Äntligen ser jag något blått.
Det är vattnet!
På vägen går jag förbi ett litet café.
Till sist går jag ända ner till vattnet.
Nu är jag vid hamnen.
Hamnen är mycket stor.
Vinden är kall och frisk.
Det finns många båtar på vattnet.
Här stannar jag.
Jag står och tittar på båtarna.
