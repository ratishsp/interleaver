Niedługo potem nadeszło kolejne zamówienie.
Zrobiłam już dzisiaj moją pierwszą kawę.
Ale ten klient chciał tylko jedzenia.
Zamówił bułkę z serem.
Wzięłam z koszyka ciepłą bułkę na zakwasie.
Chleb na zakwasie często ma twardą skórkę.
Ale nauczyłam się szybko przekrawać chleb na pół.
Następnie położyłam na bułce gruby plaster sera.
Ładnie ułożyłam jedzenie na małym talerzu.
Teraz musiałam zanieść to klientowi.
Na środku kawiarni stało wielu ludzi.
Balansowałam talerzem i ostrożnie szłam naprzód.
Szłam powoli obok innych gości.
Na szczęście klient siedział w samym rogu.
Czekał przy czwartym stoliku.
Postawiłam talerz na stoliku przed nim.
"Proszę, ciepła bułka z serem" – powiedziałam.
"Bardzo dziękuję" – odpowiedział mężczyzna.
Miło jest widzieć zadowolonego gościa.
