Jag är hemma nu.
Här är mitt rum.
Det är ett litet rum.
Jag har en ny växt.
Den står på mitt skrivbord.
Det är kväll, och det är januari.
Mitt fönster är mycket mörkt.
Det är helt svart utanför.
Jag har en lampa och en kopp te.
Jag tänder min lampa.
Nu är mitt rum varmt och ljust.
Mitt te är också varmt.
Jag sitter vid mitt skrivbord.
Jag har min dator här.
Jag öppnar min dator.
Nu ringer jag till min familj i Mexiko.
Jag ser fram emot att se dem.
