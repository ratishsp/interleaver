ഞാൻ അവരുടെ അടുത്തേക്ക് നടക്കുന്നു.
ഞാൻ അവരോട് സംസാരിക്കുന്നു.
"നമസ്കാരം, എന്റെ പേര് മായ," ഞാൻ പറയുന്നു.
"ഞാൻ മെക്സിക്കോയിൽ നിന്നാണ് വരുന്നത്."
അവർ എന്നെ നോക്കി ചിരിക്കുന്നു.
അതിൽ ഒരു പെൺകുട്ടി എന്നോട് സംസാരിക്കുന്നു.
"എന്റെ പേര് സാറ," അവൾ പറയുന്നു.
"ഇത് കിരണും വിഷ്ണുവും ആണ്."
എനിക്ക് പുതിയ ആളുകളെ കാണാൻ ഇഷ്ടമാണ്.
സാറ എന്നോട് ഒരു ചോദ്യം ചോദിക്കുന്നു.
"നിങ്ങൾക്ക് ഡബിൾസ് കളിക്കാൻ ഇഷ്ടമാണോ?" സാറ ചോദിക്കുന്നു.
"നിങ്ങൾക്ക് ഡബിൾസ് കളിക്കാൻ കഴിയുമോ?"
ഞാൻ സന്തോഷത്തോടെ മറുപടി പറയുന്നു.
"അതെ, എനിക്ക് ഡബിൾസ് കളിക്കാൻ വളരെ ഇഷ്ടമാണ്."
"എനിക്ക് നന്നായി കളിക്കാൻ കഴിയും," ഞാൻ പറയുന്നു.
കിരൺ പറയുന്നു, "വളരെ നല്ലത്."
"ഞങ്ങൾക്ക് കളിക്കാൻ ഒരാളെ കൂടി വേണം."
"നമുക്ക് കളിക്കാൻ തുടങ്ങാം," വിഷ്ണു പറയുന്നു.
ഞാൻ അവർക്കൊപ്പം കളിക്കാൻ പോകുന്നു.
എനിക്ക് ഇപ്പോൾ വളരെ സന്തോഷമുണ്ട്.
