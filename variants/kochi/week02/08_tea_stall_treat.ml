ഞാൻ പുറത്തേക്ക് നടക്കുന്നു.
ജനുവരിയിലെ കാലാവസ്ഥ വളരെ നല്ലതാണ്.
വഴിയിൽ ഞാൻ ഒരു ചെറിയ തട്ടുകട കാണുന്നു.
ഞാൻ അവിടേക്ക് പോകുന്നു.
അവിടെ ഒരാൾ ചായ ഉണ്ടാക്കുന്നു.
എനിക്ക് നല്ല വിശപ്പുണ്ട്.
"എനിക്ക് ഒരു ചായ വേണം," ഞാൻ പറയുന്നു.
"ചൂട് പഴംപൊരി വേണോ?" അയാൾ ചോദിക്കുന്നു.
"വേണം," ഞാൻ പറയുന്നു.
അയാൾ എനിക്ക് ഒരു ഗ്ലാസ്സ് ചായ തരുന്നു.
കൂടെ ഒരു പഴംപൊരിയും തരുന്നു.
പഴംപൊരിക്ക് നല്ല മധുരമുണ്ട്.
ഞാൻ ചായ കുടിക്കുന്നു.
"എത്ര രൂപയാണ്?" ഞാൻ ചോദിക്കുന്നു.
"ഇരുപത്തിയഞ്ച് രൂപ," അയാൾ മറുപടി പറയുന്നു.
ഞാൻ ഇരുപത്തിയഞ്ച് രൂപ കൊടുക്കുന്നു.
