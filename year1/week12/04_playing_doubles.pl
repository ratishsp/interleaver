Podchodzę do kortu do badmintona.
Na korcie stoją trzy osoby.
„Cześć, jestem Kasper” – mówi mężczyzna.
„A ja jestem Sara” – mówi kobieta.
Trzeci gracz nazywa się Emil.
„Jestem Maya” – mówię.
„Zazwyczaj gramy w debla” – mówi Kasper.
„Chcesz z nami zagrać?” – pyta.
„Tak, bardzo chętnie” – odpowiadam.
Bardzo lubię grać w badmintona.
Kasper i ja gramy przeciwko Sarze i Emilowi.
Od razu zaczynamy grać.
Sara zaczyna mecz.
Lotka szybko lata w tę i z powrotem.
Emil odbija lotkę wysoko w powietrze.
Uwielbiam smeczować.
Podskakuję i mocno smeczuję ją przez siatkę.
Ląduje po ich stronie kortu.
„Dobre uderzenie, Maya!” – krzyczy Kasper.
