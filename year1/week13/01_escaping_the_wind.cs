V Kodani je zima.
Jdu po ulici.
Vítr je velmi studený.
Dnes silně fouká.
Opírám se do studeného větru.
Vytahuji si šálu nahoru.
Mrzne mi obličej.
Rozhlížím se.
Chtěla bych do tepla.
Vidím na rohu malou kavárnu.
Okna jsou zamlžená.
Vypadá to, že je tam teplo.
Jdu ke kavárně.
Otevírám těžké dveře.
Vstupuji dovnitř.
Voní to tu kávou.
Vzduch je příjemně teplý.
Zavírám za sebou dveře.
Studený vítr zůstává venku.
