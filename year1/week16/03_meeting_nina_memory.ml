എൻ്റെ ആദ്യത്തെ ഉച്ചകഴിഞ്ഞുള്ള സമയത്തെക്കുറിച്ച് അറിയാൻ കാസ്പറിന് ആഗ്രഹമുണ്ടായിരുന്നു.
അത് ജനുവരിയിലെ തണുപ്പുള്ള ഒരു ഉച്ചതിരിഞ്ഞ സമയമായിരുന്നു.
ഞാൻ പടികൾ കയറി എൻ്റെ പുതിയ അപ്പാർട്ട്മെൻ്റിലെത്തി.
എൻ്റെ കൈയിൽ വളരെ ഭാരമുള്ള ഒരു സ്യൂട്ട്കേസ് ഉണ്ടായിരുന്നു.
നീണ്ട യാത്രയ്ക്ക് ശേഷം ഞാൻ വളരെ ക്ഷീണിതയായിരുന്നു.
ഞാൻ എൻ്റെ സ്യൂട്ട്കേസ് സ്വന്തമായി എടുത്ത് മുകളിലേക്കും അകത്തേക്കും കൊണ്ടുപോയി.
കുറച്ചു കഴിഞ്ഞ് ഞാൻ പുറത്തിറങ്ങി കോണിപ്പടിക്കടുത്തേക്ക് ചെന്നു.
എൻ്റെ അടുത്തുണ്ടായിരുന്ന ഒരു വാതിൽ തുറന്നു.
ഒരു യുവതി പുറത്തുവന്ന് എന്നെ നോക്കി ചിരിച്ചു.
"ഹായ്, എൻ്റെ പേര് നീന," അവൾ പറഞ്ഞു.
"ഞാനും ഈ കെട്ടിടത്തിലാണ് താമസിക്കുന്നത്."
ഞാൻ തിരിച്ച് ചിരിക്കുകയും എൻ്റെ പേര് പറയുകയും ചെയ്തു.
നീന എൻ്റെ തൊട്ടടുത്താണ് താമസിച്ചിരുന്നത്.
ഞങ്ങൾ കോണിപ്പടിക്കടുത്ത് വെച്ച് കുറച്ചു നേരം സംസാരിച്ചു.
വന്നയുടനെ ഒരു അയൽവാസിയെ കണ്ടുമുട്ടിയത് സന്തോഷമുള്ള കാര്യമായിരുന്നു.
"ഡെൻമാർക്കിലേക്ക് സ്വാഗതം," നീന പറഞ്ഞു.
ഇവിടെ അത് എൻ്റെ ആദ്യത്തെ ദിവസമായിരുന്നു.
എനിക്ക് അപ്പോഴേക്കും ഒരു സുഹൃത്തിനെ കിട്ടിയതുകൊണ്ട് എനിക്ക് സന്തോഷം തോന്നി.
