ഞാൻ മേശയ്ക്കരികിൽ ഇരിക്കുകയാണ്.
ഒരു ജോലിക്കാരൻ എൻ്റെ അടുത്തേക്ക് വരുന്നു.
അയാളുടെ കയ്യിൽ ഒരു ചെറിയ ട്രേ ഉണ്ട്.
അയാൾ അത് മേശപ്പുറത്ത് വെക്കുന്നു.
അതിൽ എൻ്റെ ഐസ്ഡ് ടീയും ബനാന കേക്കും ഉണ്ട്.
"ഇതാ ചായയും കേക്കും," അയാൾ പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ സന്തോഷത്തോടെ പറയുന്നു.
അയാൾ തിരികെ പോകുന്നു.
ഞാൻ ഐസ്ഡ് ടീ എടുക്കുന്നു.
ഗ്ലാസിന് നല്ല തണുപ്പുണ്ട്.
ഞാൻ അത് പതുക്കെ കുടിക്കുന്നു.
ഈ ചൂടിൽ ഇത് വളരെ നല്ലതാണ്.
പിന്നെ ഞാൻ ബനാന കേക്ക് കഴിക്കുന്നു.
കേക്കിന് നല്ല മധുരമുണ്ട്.
ഞാൻ ജനലിലൂടെ പുറത്തേക്ക് നോക്കുന്നു.
പുറത്തെ റോഡിൽ നല്ല തിരക്കാണ്.
വാഹനങ്ങൾ വേഗത്തിൽ പോകുന്നു.
പക്ഷേ എനിക്ക് ഇവിടെ നല്ല സമാധാനമുണ്ട്.
