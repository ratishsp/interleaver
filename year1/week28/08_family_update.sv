På söndagseftermiddagen sitter jag i soffan i mitt vardagsrum.
Solen skiner in genom fönstret, och rummet är härligt ljust.
Jag har min dator på bordet framför mig för ett långt videosamtal.
Hela min familj i Mexiko är på skärmen.
Jag kan se mina föräldrar, min syster Sofía och min bror Diego.
Plötsligt skäller vår hund, Lola, väldigt högt.
Hon hoppar ivrigt runt framför kameran.
"Lola saknar dig", säger Sofía och skrattar.
"Jag saknar er alla också", säger jag och vinkar till dem.
Min pappa frågar om mitt jobb och min vardag här.
Jag berättar för dem om mitt arbete, min badminton och min snälla granne.
Vi pratar i över en timme.
Jag tittar runt i mitt ljusa vardagsrum.
Jag tittar på den fina gröna växten från igår.
Det har gått lång tid sedan januari.
"Trivs du med att bo där?" frågar min mamma.
Jag ler stort mot henne.
"Ja", svarar jag.
"Jag känner mig verkligen hemma i staden nu."
