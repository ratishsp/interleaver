Jsem zase venku na ulici.
Všechno je konečně na svém místě.
Je čas na malou oslavu.
Vidím malé pekařství na rohu.
Jdu dovnitř.
Krásně to tu voní.
Za pultem stojí pekař.
„Dobrý den,“ říká pekař.
„Dobrý den,“ odpovídám.
Ukazuji na sladké pečivo za sklem.
„Dala bych si skořicového šneka,“ říkám.
„Ano, samozřejmě,“ říká.
„Kolik to stojí?“ ptám se.
„Stojí dvacet pět korun,“ odpovídá pekař.
Peněženku mám v tašce.
Vytahuji platební kartu.
Platím za svého skořicového šneka.
Pekař mi dává malý sáček.
Teď mám skořicového šneka na svou malou oslavu.
