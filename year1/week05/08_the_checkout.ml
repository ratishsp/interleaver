ഞാൻ ചെക്കൗട്ടിന്റെ അടുത്തേക്ക് നടക്കുന്നു.
എന്റെ കയ്യിൽ ബാസ്കറ്റ് ഉണ്ട്.
ഞാൻ ഭക്ഷണം ബെൽറ്റിൽ വെക്കുന്നു.
ആദ്യം ഞാൻ ബാസ്കറ്റിൽ നിന്ന് റൈ ബ്രെഡ് എടുക്കുന്നു.
പിന്നെ ഞാൻ പാലും പാഴ്സ്നിപ്പും എടുക്കുന്നു.
ഞാൻ ക്യാരറ്റും കറുത്ത പയറും കൂടി എടുക്കുന്നു.
അവസാനം ഞാൻ പേസ്ട്രി ബെൽറ്റിൽ വെക്കുന്നു.
കാഷ്യർ ചെക്കൗട്ടിന് പിന്നിൽ ഇരിക്കുന്നു.
അയാൾ എന്നെ നോക്കി പുഞ്ചിരിക്കുന്നു.
"ഹലോ," അയാൾ പറയുന്നു.
"ഹലോ," ഞാൻ മറുപടി പറയുന്നു.
അയാൾ വേഗത്തിൽ ഭക്ഷണം സ്കാൻ ചെയ്യുന്നു.
ഞാൻ എന്റെ കാർഡ് പുറത്തെടുക്കുന്നു.
ഞാൻ കാർഡ് മെഷീന് മുകളിൽ പിടിക്കുന്നു.
മെഷീൻ ബീപ്പ് ചെയ്യുന്നു.
"നിങ്ങൾക്ക് രസീത് വേണോ?" അയാൾ ചോദിക്കുന്നു.
"അതെ, ദയവായി, എനിക്ക് രസീത് വേണം," ഞാൻ പറയുന്നു.
ഞാൻ എന്റെ ബാഗ് തുറക്കുന്നു.
ഞാൻ വേഗത്തിൽ ബാഗ് പാക്ക് ചെയ്യുന്നു.
"നല്ലൊരു ദിവസം ആശംസിക്കുന്നു," അയാൾ പറയുന്നു.
