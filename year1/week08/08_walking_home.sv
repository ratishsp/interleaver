Det är sent på eftermiddagen.
Nu går jag hem till min lägenhet.
Jag går en enkel väg.
Jag följer bara den långa vägen.
Vägen är helt rak.
Jag går längs vattnet.
Till sist svänger jag bort från vattnet.
Nu går jag in i staden igen.
Sedan går jag förbi bageriet.
Det doftar fortfarande kaffe.
Lite senare ser jag parken.
Vid parken svänger jag till höger.
Jag frågar inte någon om vägen.
Jag hittar vägen helt själv.
Lite senare ser jag min egen gata.
Till sist står jag vid min ytterdörr.
Från dörren tittar jag tillbaka ner längs gatan.
Nu kan jag min väg hem.
