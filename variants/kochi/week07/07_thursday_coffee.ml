ഇന്ന് വ്യാഴാഴ്ച ആണ്.
ഇപ്പോൾ വൈകുന്നേരം അഞ്ചര മണിയാണ്.
ഞാൻ പനമ്പിള്ളി നഗറിൽ ആണ്.
ഞാൻ ഇവിടെ ഒരു പ്രശസ്തമായ കഫേയിൽ അനിതയെ കാണുന്നു.
അനിത ചോദിക്കുന്നു, "ഹലോ മായ, സുഖമാണോ?"
ഞാൻ മറുപടി പറയുന്നു, "അതെ, എനിക്ക് സുഖമാണ്."
ഞങ്ങൾ രണ്ട് കോൾഡ് കോഫി ഓർഡർ ചെയ്യുന്നു.
ഞങ്ങൾ ഞങ്ങളുടെ ജോലിയെക്കുറിച്ച് സംസാരിക്കുന്നു.
എന്റെ ഓഫീസിൽ എപ്പോഴും ഒരുപാട് ജോലിയുണ്ട്.
അനിത പറയുന്നു, "എനിക്കും എല്ലാ ദിവസവും വളരെ തിരക്കാണ്."
അവർ എല്ലാ ദിവസവും ഓഫീസിൽ പോകുന്നു.
ഞങ്ങളുടെ കോൾഡ് കോഫി വരുന്നു.
ഞങ്ങൾ കോഫി കുടിക്കുന്നു.
കോഫിക്ക് നല്ല സ്വാദാണ്.
ഞങ്ങൾ ചിലപ്പോൾ ഒരുപാട് നേരം സംസാരിക്കുന്നു.
അനിത ഒരു നല്ല സുഹൃത്താണ്.
ഇന്ന് വളരെ നല്ല ഒരു ദിവസമാണ്.
