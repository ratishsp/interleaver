പുറത്ത് നല്ല മഴ പെയ്യുന്നുണ്ടായിരുന്നു.
കഫേയുടെ വാതിൽ തുറന്നു.
ഞാൻ കൗണ്ടറിന്റെ പിന്നിൽ നിന്നു.
എന്റെ ഒന്നാമത്തെ കസ്റ്റമർ അകത്തേക്ക് വന്നു.
എനിക്ക് ചെറിയ പേടിയുണ്ടായിരുന്നു.
ഞാൻ ചിരിച്ചുകൊണ്ട് അയാളെ സ്വാഗതം ചെയ്തു.
"നമസ്കാരം."
"എന്ത് വേണം?"
ഞാൻ ചോദിച്ചു.
"ഒരു കപ്പൂച്ചിനോ വേണം," അയാൾ പറഞ്ഞു.
ഞാൻ ശ്രദ്ധയോടെ ആ ഓർഡർ എടുത്തു.
കസ്റ്റമേഴ്സിനോട് നന്നായി സംസാരിക്കാൻ ഞാൻ പഠിക്കുകയാണ്.
ഞാൻ മെഷീനിൽ വേഗത്തിൽ കോഫി ഉണ്ടാക്കി.
ജെസ്സിയോടൊപ്പം ഞാൻ അത് പരിശീലിച്ചിട്ടുണ്ടായിരുന്നു.
അത് ഇന്നത്തെ എന്റെ രണ്ടാമത്തെ നല്ല കോഫിയായിരുന്നു.
ഞാൻ കോഫി ഒരു വലിയ കപ്പിലേക്ക് പകർന്നു.
ഞാൻ അയാളെ ഒട്ടും കാത്തുനിർത്തിയില്ല.
"ഇതാ നിങ്ങളുടെ കോഫി," എന്ന് പറഞ്ഞ് ഞാൻ കപ്പ് നൽകി.
അയാൾ എൺപത് രൂപ തന്നു.
"നന്ദി," അയാൾ ചിരിച്ചുകൊണ്ട് പറഞ്ഞു.
അയാൾ ഒരു മേശയുടെ അടുത്തേക്ക് പോയി.
എന്റെ കൈകൾ അപ്പോഴും ചെറുതായി വിറയ്ക്കുന്നുണ്ടായിരുന്നു.
