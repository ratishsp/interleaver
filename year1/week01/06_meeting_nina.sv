Jag öppnar min dörr.
Jag står i trappuppgången.
Det är tyst.
En dörr öppnas.
En kvinna ler mot mig.
"Hej," säger hon.
"Vad heter du?" frågar hon.
"Jag heter Maya," svarar jag.
"Var kommer du ifrån?" frågar hon.
"Jag kommer från Mexiko," säger jag.
"Välkommen till huset," säger kvinnan.
"Jag heter Nina," säger hon.
"Jag är din granne."
Nina är mycket vänlig.
Hon talar långsamt och tydligt.
"Här är min dörr," säger hon.
"Jag hjälper gärna till."
"Du knackar bara på," säger Nina.
"Tack så mycket, Nina," svarar jag.
Jag är mycket glad.
Nu har jag en vän i Köpenhamn.
