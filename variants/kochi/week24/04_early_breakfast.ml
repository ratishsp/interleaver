ഇന്ന് ശനിയാഴ്ചയാണ്.
ടോമിക്ക് വേണ്ടി ഞാൻ ഇന്ന് കഫേയിൽ നിന്ന് അവധി എടുത്തിട്ടുണ്ട്.
അതിനാൽ, ഞാൻ വളരെ നേരത്തെ എഴുന്നേൽക്കുന്നു.
ടോമിയും എന്റെ കൂടെ എഴുന്നേൽക്കുന്നു.
ഇപ്പോൾ അവന്റെ പ്രഭാതഭക്ഷണത്തിനുള്ള സമയമാണ്.
അനിത ഇന്നലെ അവന്റെ ഡ്രൈ ഫുഡ് കൊണ്ടുവന്നിട്ടുണ്ട്.
ഞാൻ ആ ഭക്ഷണം കൃത്യമായി അളക്കണം.
ഞാൻ അവന്റെ പാത്രത്തിൽ ഭക്ഷണം വെക്കുന്നു.
"ടോമീ, ഇങ്ങോട്ട് വരൂ!" ഞാൻ അവനെ വിളിക്കുന്നു.
അവൻ അത് വളരെ വേഗം കഴിക്കുന്നു.
പിന്നെ, ഞാൻ എന്റെ പ്രഭാതഭക്ഷണം കഴിക്കുന്നു.
ഞാൻ ഒരു ദോശ കഴിക്കുകയാണ്.
ടോമി എന്റെ പാത്രത്തിലേക്ക് നോക്കുന്നു.
അവൻ മെല്ലെ എന്റെ അടുത്തേക്ക് വരുന്നു.
എന്നാൽ ഞാൻ അനിതയുടെ നിയമം ഓർക്കുന്നു.
ഞാൻ അവന് എന്റെ പാത്രത്തിൽ നിന്ന് ഭക്ഷണം കൊടുക്കാൻ പാടില്ല.
"ഇല്ല ടോമി, മാറി നിൽക്കൂ," ഞാൻ അവനോട് കർശനമായി പറയുന്നു.
അവൻ അത് അനുസരിച്ച് അവന്റെ കിടക്കയിലേക്ക് പോകുന്നു.
ഇനി ഞങ്ങൾക്ക് രാവിലത്തെ നടത്തത്തിന് പോകണം.
