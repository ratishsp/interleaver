Jsem doma ve svém bytě.
V kuchyni připravuji večeři.
Myji čerstvou zeleninu.
Krájím cibuli na prkénku.
Také krájím dvě červená rajčata.
Beru si pánev.
Na sporáku rozehřívám trochu oleje.
Dávám zeleninu na pánev.
Opékám jídlo.
Voní to opravdu dobře.
Dávám do jídla sůl a pepř.
Jídlo je hotové.
Beru si talíř.
Dávám jídlo na talíř.
Jdu si pro sklenici vody.
Sedám si ke stolu.
Jím svou večeři.
Jídlo chutná skvěle.
Vychutnávám si klidné jídlo.
