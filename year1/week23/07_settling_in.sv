Eva häller upp kaffe i två stora koppar.
Vi sätter oss i den mjuka soffan i vardagsrummet.
"Hur går det för dig i staden nu?" frågar Eva.
Jag tar en klunk av det varma kaffet.
Jag berättar för henne att jag känner att mitt nya liv faktiskt är riktigt härligt.
"Jag har äntligen funnit mig väl tillrätta här," säger jag med ett leende.
"Det är jag glad att höra," svarar hon.
"Du arbetar också riktigt hårt med vårt projekt på kontoret."
"Ja, men jag har tänkt vara mer ledig nu," säger jag.
"Jag ska njuta av staden mycket mer på helgerna."
"Det förstår jag mycket väl," säger Eva.
Vi pratar länge om våra andra kollegor och arbetet.
Vi skrattar och delar många historier.
Jag ler mot henne över kaffekoppen.
Jag säger att jag hoppas att vi fortfarande kommer att ses utanför arbetet.
"Det ska vi helt säkert," svarar hon glatt.
Jag tänker att vi nog kommer att få många roliga kvällar tillsammans.
