Jag sitter nu vid mitt lilla bord.
Här är det härligt varmt.
Jag tittar på min kanelbulle.
Den doftar sött och gott.
Jag tar en liten tugga.
Bakverket är helt färskt och varmt.
Det smakar riktigt gott.
Jag dricker lite av mitt svarta kaffe.
Äntligen är mina fingrar varma igen.
Jag slappnar av i den mjuka stolen.
Kaféet är nästan fullt av människor.
Folk sitter i små grupper.
De pratar och skrattar tillsammans.
Jag lyssnar på de låga rösterna i rummet.
Ljudet är väldigt mysigt.
Jag tittar ut genom det stora fönstret.
Vädret utanför är grått och blåsigt.
Nu snöar det faktiskt igen.
Vita snöflingor faller långsamt ner på gatan.
Jag är bara glad över att vara inomhus.
