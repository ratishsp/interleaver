ഞാൻ കൗണ്ടറിനടുത്ത് കാത്തുനിൽക്കുന്നു.
അയാൾ എനിക്കുള്ള കോഫി ഉണ്ടാക്കുന്നു.
അയാൾ ഒരു മര ട്രേയിൽ ഒരു കപ്പ് ചൂട് കോഫി വെക്കുന്നു.
അയാൾ ആ ട്രേയിൽ ഒരു ചെറിയ പ്ലേറ്റും വെക്കുന്നു.
എന്റെ സിനമൺ റോൾ ആ പ്ലേറ്റിലുണ്ട്.
അതിന് നല്ല മണമുണ്ട്.
"ഇതാ, നിങ്ങളുടെ ഓർഡർ," അയാൾ പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ മറുപടി പറയുന്നു.
"നല്ല സേവനത്തിന് നന്ദി."
"സന്തോഷം," അയാൾ സ്നേഹത്തോടെ പറയുന്നു.
ഞാൻ രണ്ടു കൈകൊണ്ടും ട്രേ എടുക്കുന്നു.
ഞാൻ വളരെ സൂക്ഷിച്ച് തറയിലൂടെ നടക്കുന്നു.
ഞാൻ ജനാലയ്ക്കരികിലുള്ള എന്റെ ടേബിളിലേക്ക് തിരികെ നടക്കുന്നു.
ഞാൻ ട്രേ ടേബിളിൽ വെക്കുന്നു.
ഇപ്പോൾ എനിക്ക് ഇരിക്കണം.
ഞാൻ ഒരു നല്ല ഇടവേളയ്ക്ക് തയ്യാറാണ്.
