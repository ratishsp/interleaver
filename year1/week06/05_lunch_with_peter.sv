Mitt på dagen går jag ner till kantinen.
Rummet är ljust och trevligt.
Många människor står vid buffén.
Jag ser min kollega Peter.
Han tar en tallrik med mat.
"Hej Maya", säger han med ett leende.
"Hej Peter", svarar jag.
Vi tar lite bröd och sallad.
Tillsammans hittar vi bord nummer nio vid fönstret.
Vi sätter oss på stolarna.
Maten smakar riktigt gott.
Peter berättar om sitt projekt.
Han arbetar med ny mjukvara.
Jag lyssnar och nickar.
Till sist pratar jag om min egen kod.
Vi dricker ett glas vatten.
Jag har det väldigt trevligt under rasten.
Snart går vi tillbaka till kontoret.
