ഞാൻ പന്ത്രണ്ടാം നമ്പർ കെട്ടിടത്തിന് മുന്നിൽ നിൽക്കുകയാണ്.
ഞാൻ ഈവയുടെ പേര് കണ്ടുപിടിച്ച് ഡോർബെൽ അടിക്കുന്നു.
വാതിൽ തുറക്കുന്നു, ഞാൻ പടികൾ കയറി മുകളിലേക്ക് പോകുന്നു.
ഈവ വാതിൽക്കൽ നിന്നു വിശാലമായി ചിരിക്കുന്നു.
"ഹായ് മായ, സ്വാഗതം!" എന്ന് പറഞ്ഞുകൊണ്ട് അവൾ എന്നെ കെട്ടിപ്പിടിക്കുന്നു.
"ക്ഷണിച്ചതിന് നന്ദി," ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ അവളുടെ അപ്പാർട്ട്മെന്റിലേക്ക് കയറുന്നു.
അത് വളരെ സുഖപ്രദവും വർണ്ണാഭമായ കലാരൂപങ്ങൾ നിറഞ്ഞതുമാണ്.
ഞാൻ അവൾക്ക് ആ മഞ്ഞ ടുലിപ്സ് പൂക്കൾ നൽകുന്നു.
മേശപ്പുറത്ത് ഇതിനകം തന്നെ പൂക്കളുള്ള ഒരു പൂപ്പാത്രം ഉണ്ടാകില്ലെന്ന് ഞാൻ പ്രതീക്ഷിക്കുന്നു.
ഈവ ആ പൂക്കളിലേക്ക് നോക്കുന്നു, വളരെ സന്തോഷവതിയായി കാണപ്പെടുന്നു.
"ഇവയെന്തൊരു ഭംഗിയാണ്!" അവൾ ആശ്ചര്യത്തോടെ പറയുന്നു.
"എനിക്ക് മഞ്ഞപ്പൂക്കൾ വളരെ ഇഷ്ടമാണ്."
അവളുടെ സർഗ്ഗാത്മകമായ അഭിരുചി എനിക്ക് പലപ്പോഴും മനസ്സിലാകുന്നുണ്ടെന്ന് എനിക്ക് തോന്നുന്നു.
"ഞാൻ ഉടനെ ഇതിനൊരു പൂപ്പാത്രം കണ്ടുപിടിക്കാം," ഈവ പറയുന്നു.
"നീ ലിവിംഗ് റൂമിലേക്ക് പൊയ്ക്കോളൂ," അവൾ തുടർന്നു പറയുന്നു.
ഞാൻ എന്റെ ഷൂസ് അഴിച്ചുവെച്ച് അങ്ങോട്ട് പോകുന്നു.
ഡൈനിംഗ് ടേബിൾ ഭംഗിയുള്ള ഗ്ലാസുകൾ കൊണ്ട് മനോഹരമായി സജ്ജീകരിച്ചിരിക്കുന്നു.
ഞാൻ വിശ്രമിക്കാനും ഈ സായാഹ്നം ആസ്വദിക്കാനും ഉദ്ദേശിക്കുന്നു.
