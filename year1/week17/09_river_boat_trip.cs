Pozdě odpoledne jsem šla dolů k řece.
Počasí bylo stále teplé a příjemné.
Koupila jsem si lístek na malou dřevěnou loď.
Lístek stál sedmdesát korun.
Nalodila jsem se a našla si dobré místo na palubě.
Loď plula velmi pomalu po proudu řeky.
Na lodi nebylo mnoho dalších cestujících.
Naproti mně seděla starší paní.
Společně se svým manželem jedla přinesený oběd.
Její manžel se na ni šťastně usmíval.
Proplouvali jsme pod několika velkými zelenými stromy.
Voda byla modrá a naprosto klidná.
Jen jsem odpočívala a užívala si výlet.
Obloha byla stále světlá, i když už bylo pozdě.
Byl to opravdu krásný dánský jarní večer.
Opřela jsem se dozadu v té malé lodi.
Užívala jsem si zelenou přírodu podél řeky.
Byl to dokonalý závěr mého dne v Odense.
