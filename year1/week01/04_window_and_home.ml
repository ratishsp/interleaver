ഞാൻ ജനാലയ്ക്കരികിൽ നിൽക്കുകയാണ്.
ഗ്ലാസിന് തണുപ്പുണ്ട്.
ഇത് ജനുവരി മാസമാണ്.
ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
ഇന്ന് കോപ്പൻഹേഗൻ ചാരനിറത്തിലാണ്.
പുറത്ത് നല്ല തണുപ്പാണ്.
തെരുവിൽ ഐസുണ്ട്.
പക്ഷേ ഇവിടെ ചൂടുണ്ട്.
ഈ അപ്പാർട്ട്മെന്റ് നല്ലതാണ്.
ഞാൻ മെക്സിക്കോയെക്കുറിച്ച് ചിന്തിക്കുന്നു.
മെക്സിക്കോയിൽ നല്ല വെയിലുണ്ട്.
അവിടെ ചൂടുമുണ്ട്.
എനിക്ക് ആ വെയിൽ അല്പം മിസ്സ് ചെയ്യുന്നുണ്ട്.
പക്ഷേ ഞാൻ പുഞ്ചിരിക്കുന്നു.
ഇതൊരു പുതിയ നഗരമാണ്.
ഞാൻ ഇപ്പോൾ ഡെൻമാർക്കിലാണ്.
ഇതൊരു നല്ല തുടക്കമാണ്.
