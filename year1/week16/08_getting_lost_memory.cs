Teď se směju a vyprávím jim o zmatené sobotě.
Bylo to chladné sobotní ráno té první zimy.
Chtěla jsem jít dolů k přístavu.
Nina mi předem dala trasu.
Po cestě jsem uslyšela pouličního muzikanta.
Krásně hrál na kytaru.
Zastavila jsem se a dlouho poslouchala.
Pak jsem na Nininu trasu úplně zapomněla.
Zašla jsem do úzké postranní uličky.
Byly tam jen malé, tiché domy.
Najednou jsem se úplně ztratila.
Přede mnou šla mladá žena s malým psem.
Ten pes vypadal úplně jako naše Lola.
„Promiňte, hledám přístav,“ řekla jsem.
Laskavě mi ukázala zpátky směrem k náměstí.
Poděkovala jsem jí a našla správnou cestu.
Nakonec jsem došla k vodě.
Můj bratr Diego se na obrazovce hlasitě směje.
Byla to hloupá chyba, ale dobrá vzpomínka.
