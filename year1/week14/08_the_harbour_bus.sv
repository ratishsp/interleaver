En bred båt kommer över vattnet.
Det är hamnbussen.
Båten åker in till träbryggan.
Den stannar vid kanten.
Jag ska med hamnbussen nu.
Jag går ombord på fartyget.
Jag skannar mitt blå resekort igen.
Många passagerare sitter där inne.
Men jag går ut på det öppna däcket.
Jag står längst fram.
Vi åker med båten över det blå vattnet.
Staden ser vacker ut från vattnet.
Solen skiner ner på oss.
Jag tar ett djupt andetag.
Luften är mycket frisk och kall.
Jag njuter av den korta turen.
Vi är snart över på andra sidan.
