ഇപ്പോൾ ഞാൻ ചിരിച്ചുകൊണ്ട് ആശയക്കുഴപ്പമുണ്ടാക്കിയ ഒരു ശനിയാഴ്ചയെക്കുറിച്ച് അവരോട് പറയുന്നു.
ആദ്യത്തെ ശൈത്യകാലത്തെ തണുപ്പുള്ള ഒരു ശനിയാഴ്ച രാവിലെയായിരുന്നു അത്.
എനിക്ക് ഹാർബറിലേക്ക് നടന്നുപോകണമായിരുന്നു.
നീന നേരത്തെ തന്നെ എനിക്ക് പോകാനുള്ള വഴി പറഞ്ഞുതന്നിരുന്നു.
പോകുന്ന വഴിയിൽ ഞാൻ ഒരു തെരുവ് സംഗീതജ്ഞനെ കേട്ടു.
അയാൾ മനോഹരമായി ഗിറ്റാർ വായിച്ചിരുന്നു.
ഞാൻ അവിടെ നിന്നു, വളരെ നേരം അത് കേട്ടു.
പിന്നെ ഞാൻ നീനയുടെ വഴി പൂർണ്ണമായും മറന്നു.
ഞാൻ ഇടുങ്ങിയ ഒരു ഇടവഴിയിലേക്ക് നടന്നു.
അവിടെ ചെറിയ, ശാന്തമായ വീടുകൾ മാത്രമേ ഉണ്ടായിരുന്നുള്ളൂ.
പെട്ടെന്ന് എനിക്ക് വഴി പൂർണ്ണമായും തെറ്റി.
എനിക്ക് മുന്നിലായി ഒരു ചെറിയ നായയോടൊപ്പം ഒരു യുവതി നടക്കുന്നുണ്ടായിരുന്നു.
ആ നായയെ കണ്ടാൽ അസ്സൽ നമ്മുടെ ലോലയെപ്പോലെ ഉണ്ടായിരുന്നു.
"ക്ഷമിക്കണം, ഞാൻ ഹാർബറിലേക്കുള്ള വഴി അന്വേഷിക്കുകയാണ്," ഞാൻ പറഞ്ഞു.
അവർ ദയയോടെ തിരിച്ച് സ്ക്വയറിലേക്കുള്ള വഴി ചൂണ്ടിക്കാണിച്ചു തന്നു.
ഞാൻ അവരോട് നന്ദി പറയുകയും ശരിയായ വഴി കണ്ടെത്തുകയും ചെയ്തു.
അവസാനം ഞാൻ വെള്ളത്തിനരികിലെത്തി.
സ്ക്രീനിൽ എൻ്റെ സഹോദരൻ ഡീഗോ ഉച്ചത്തിൽ ചിരിക്കുന്നുണ്ട്.
അതൊരു മണ്ടത്തരമായ അബദ്ധമായിരുന്നു, എങ്കിലും നല്ലൊരു ഓർമ്മയാണ്.
