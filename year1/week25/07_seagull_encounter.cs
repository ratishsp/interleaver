Jdu domů přes velký park.
Před hodinou jsem byla v muzeu.
Teď si chci jen užít hezké počasí.
Zastavím se u malého stánku, abych si koupila zmrzlinu v kornoutku.
„Prosím, tady je vaše zmrzlina,“ říká muž ve stánku.
„Moc děkuji,“ odpovídám a beru si zmrzlinu.
Jdu pomalu podél jezera v parku.
Tahle zmrzlina v kornoutku vypadá opravdu dobře.
Najednou nad sebou slyším hlasitý zvuk.
Velký racek letí střemhlav přímo ke mně.
Chce mi ukrást zmrzlinu!
Rychle se skrčím a chráním si zmrzlinu rukou.
Ten pták mi moje jídlo neukradne.
Racek proletí kolem a přistane na trávě.
Žena na lavičce se směje.
„Dnes jsou velmi drzí,“ říká.
„Ano, to rozhodně jsou,“ směju se v odpověď.
Rychle dojídám zmrzlinu, zatímco jdu dál.
