ഞാൻ എന്റെ ഫ്ലാറ്റിന് അടുത്തുള്ള ഒരു ചെറിയ ബേക്കറിയിലേക്ക് നടക്കുന്നു.
ഇതൊരു നല്ല കടയാണ്.
കടയിൽ ഒരുപാട് മധുരപലഹാരങ്ങൾ ഉണ്ട്.
അവിടെ ഓറഞ്ച് നിറത്തിൽ ഒരു പലഹാരം ഉണ്ട്.
അത് പ്രശസ്തമായ കോഴിക്കോടൻ ഹൽവയാണ്.
ഞാൻ കടക്കാരനോട് ചോദിക്കുന്നു, "ഈ ഹൽവയ്ക്ക് എന്താണ് വില?"
അദ്ദേഹം പറയുന്നു, "ഒരു ബോക്സിന് അറുപത് രൂപയാണ്."
ഞാൻ അറുപത് രൂപ കൊടുക്കുന്നു.
അദ്ദേഹം എനിക്ക് ഒരു ബോക്സ് ഹൽവ തരുന്നു.
ഈ ഹൽവ എന്റെ കുടുംബത്തെ കാണിക്കാനാണ്.
അതിന് നല്ല ഭംഗിയുണ്ട്.
എന്റെ വീട്ടിൽ ആർക്കാണ് മധുരം കൂടുതൽ ഇഷ്ടം?
എന്റെ അനിയത്തി സോഫിയയ്ക്ക് മധുരം വളരെ ഇഷ്ടമാണ്.
അവൾക്ക് ഈ നിറവും വളരെ ഇഷ്ടമാണ്.
ഞാൻ ഹൽവ ബോക്സുമായി എന്റെ മുറിയിലേക്ക് മടങ്ങുന്നു.
