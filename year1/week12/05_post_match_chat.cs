Rychlý zápas skončil.
Společně odcházíme z kurtu.
Jsem velmi unavená.
Kasper a Sara jsou také unavení.
Pijeme trochu vody.
"Hraješ moc dobře," říká Sara.
"Moc děkuji," říkám.
"Přijde mi to strašně zábavné."
"Hraješ často?" ptá se Kasper.
"Ano, doma v Mexiku hraju hodně," odpovídám.
"Obvykle hraju se sestrou."
"Je to zábavný sport," říká Sara.
"Moc rádi hrajeme tady v klubu."
"Chci tady v Dánsku hrát víc," říkám.
"Rozhodně jsi rychlá," směje se Kasper.
"Díky, ale teď si chci sednout," říkám.
"Zajdeme do bufetu?" ptá se Kasper.
"Ano, to bych moc ráda," odpovídám.
