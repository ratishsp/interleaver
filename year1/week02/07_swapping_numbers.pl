Stoję przy moim mieszkaniu.
Mam torbę z bułeczką cynamonową.
Moja sąsiadka Nina jest przy drzwiach.
Uśmiecha się szeroko i mówi cześć.
"Cześć Maya, masz już duński numer?" pyta Nina.
"Tak, mam nowy numer telefonu," odpowiadam.
"To dobrze," mówi.
Mam mój telefon w ręce.
"Jaki jest twój numer?" pytam.
"Mój numer to osiemdziesiąt siedem, sześćdziesiąt pięć, czterdzieści trzy, dwadzieścia jeden," mówi Nina.
Wpisuję jej numer w moim telefonie.
"A mój numer to dwanaście, trzydzieści cztery, pięćdziesiąt sześć, siedemdziesiąt osiem," mówię.
Nina zapisuje mój numer w swoim telefonie.
Teraz jesteśmy w kontakcie.
Wchodzimy razem do środka.
Bardzo się cieszę z mojej nowej przyjaciółki.
