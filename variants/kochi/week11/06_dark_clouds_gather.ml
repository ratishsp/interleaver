സമയം അഞ്ച് മണിയാണ്.
ഞാൻ ഓഫീസിൽ നിന്ന് പുറത്തിറങ്ങുന്നു.
പുറത്ത് പെട്ടെന്ന് നല്ല ഇരുട്ടാകുന്നു.
ഞാൻ ആകാശം നോക്കുന്നു.
ആകാശത്ത് വലിയ കറുത്ത മേഘങ്ങൾ ഉണ്ട്.
രാവിലെ നല്ല വെയിലായിരുന്നു.
പക്ഷേ ഇപ്പോൾ ഒട്ടും വെയിലില്ല.
അതുപോലെ ഇപ്പോൾ ഒട്ടും ചൂടില്ല.
ക്യാമ്പസിൽ ശക്തമായ കാറ്റ് വീശുന്നു.
ഈ കാറ്റിന് നല്ല തണുപ്പാണ്.
എന്റെ മുടി കാറ്റിൽ പറക്കുന്നു.
ഞാൻ രാവിലത്തെ പ്രവചനം ഓർക്കുന്നു.
അതെ, ഇന്ന് തീർച്ചയായും മഴ പെയ്യും.
ഉടനെ വലിയ മഴ പെയ്യും.
അയ്യോ, എന്റെ കയ്യിൽ കുടയില്ല.
എനിക്ക് വേഗം വീട്ടിൽ പോകണം.
