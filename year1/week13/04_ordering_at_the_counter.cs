Jdu k pokladně.
Za pultem stojí mladý muž.
Je to barista v kavárně.
Usměju se na něj.
Vlídně přikývne.
„Dobrý den,“ říká.
„Co si dáte?“ ptá se.
„Dobrý den,“ odpovídám.
„Dala bych si černou kávu, prosím.“
„A mohu poprosit také o skořicového šneka?“
„Samozřejmě,“ říká.
„Černá káva a skořicový šnek.“
„Budete sedět tady?“ ptá se.
„Ano, prosím, posadím se tamhle,“ říkám.
„V pořádku,“ říká barista.
„Teď vám kávu připravím.“
„Moc děkuji,“ říkám.
