Później tej samej soboty znów mieliśmy duży ruch.
Młoda kobieta podeszła do lady i zamówiła duże cappuccino.
Moja pierwsza filiżanka nie była do końca idealna.
Ale tym razem byłam gotowa.
Wzięłam metalowy dzbanek i wlałam do niego zimne mleko.
Podstawiłam dzbanek pod ekspres i włączyłam gorącą parę.
Nie zwiększyłam ciśnienia od razu.
Tak naprawdę nauczyłam się słuchać ekspresu.
Głośny dźwięk pary był tym razem dokładnie taki, jak trzeba.
Mleko powoli robiło się ciepłe.
A piana na wierzchu stała się bardzo gęsta i puszysta.
To był duży krok naprzód.
Ostrożnie wlałam mleko do kawy w dużej filiżance.
Faktycznie wyglądało to jak prawdziwe, profesjonalne cappuccino.
„Proszę bardzo” – powiedziałam i postawiłam filiżankę na ladzie.
Kobieta uśmiechnęła się i wzięła swoją kawę.
Wreszcie nauczyłam się kontrolować ciśnienie.
