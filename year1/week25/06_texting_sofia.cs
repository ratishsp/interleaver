Sedím v kavárně muzea a dávám si přestávku.
Piju šálek kávy a odpočívám.
Vyndávám z tašky ty modré talíře.
Tyhle talíře se do mé kuchyně perfektně hodí.
Fotím si je telefonem.
Posílám tu fotku své sestře Sofíi.
„Jen se podívej na tyhle krásné talíře,“ píšu.
„Našla jsem je před hodinou na trhu.“
Sofía mi odpovídá téměř okamžitě.
Posílá mi zpátky starou fotku.
Tahle zpráva mi dělá velkou radost.
Ta fotka zachycuje nás dvě na velkém bleším trhu v Mexiku.
„Pamatuješ si tenhle trh?“
Sofía se ptá v další zprávě.
„Byly jsme tam přesně před dvěma lety!“ píše.
Dívám se na naše šťastné tváře na té fotce.
Připadá mi to jako velmi dávno.
Před dvěma lety jsem ještě žila v Mexiku.
Usmívám se a píšu zpátky radostnou zprávu.
