Ludwig radośnie biega po lesie.
Nagle widzi dużego ptaka.
Szybko za nim biegnie.
Biegnie aż w stronę drzew.
„Stój, Ludwig!” – krzyczę głośno.
„Chodź tutaj!”
Wyciągam z kieszeni mały smakołyk.
Kucam w trawie.
„Ludwig, spójrz tutaj” – wołam łagodnie.
Zatrzymuje się i patrzy na mnie.
Bardzo chce ten smakołyk.
Szybko biegnie z powrotem do mnie.
„Siad” – mówię spokojnie.
Siada, a ja mu go daję.
„Dobry pies” – mówię i go głaszczę.
Znowu przypinam mu smycz.
Teraz musimy iść do domu i odpocząć.
