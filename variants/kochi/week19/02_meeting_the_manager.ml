ഞാൻ ഓഫീസിലാണ്.
ഇന്ന് പുതിയ പ്രോജക്റ്റ് തുടങ്ങുന്നു.
ടീം മാനേജർ സുരേഷ് എന്നെ അദ്ദേഹത്തിന്റെ ക്യാബിനിലേക്ക് വിളിക്കുന്നു.
ഞാൻ അകത്ത് കയറി ഇരിക്കുന്നു.
"പുതിയ ടീമിലേക്ക് സ്വാഗതം, മായ," അദ്ദേഹം പറയുന്നു.
"നമ്മൾ ഒരു വലിയ പ്രോജക്റ്റ് തുടങ്ങുകയാണ്."
"മായ ഇതിനുമുമ്പ് ഇതുപോലുള്ള ജോലി ചെയ്തിട്ടുണ്ടോ?" അദ്ദേഹം ചോദിക്കുന്നു.
ഞാൻ ചിരിക്കുന്നു.
മെക്സിക്കോയിൽ ഞാൻ ഇത്തരത്തിലുള്ള ജോലി ചെയ്തിട്ടുണ്ട്.
"അതെ, ഞാൻ ഇതുപോലുള്ള രണ്ട് പ്രോജക്റ്റുകളിൽ പ്രവർത്തിച്ചിട്ടുണ്ട്," ഞാൻ മറുപടി പറയുന്നു.
"ഞാൻ കടകൾക്ക് വേണ്ടിയുള്ള സോഫ്റ്റ്‌വെയർ ഉണ്ടാക്കിയിട്ടുണ്ട്."
അദ്ദേഹം സന്തോഷത്തോടെ തലയാട്ടുന്നു.
"അത് വളരെ നല്ലതാണ്," സുരേഷ് പറയുന്നു.
"നിങ്ങളുടെ പരിചയം നമുക്ക് വളരെ ഉപകാരപ്പെടും."
അദ്ദേഹം എനിക്ക് ഒരു ഫയൽ തരുന്നു.
"ഈ വിവരങ്ങൾ വായിക്കുക."
"ശരി, ഞാൻ വായിക്കാം," ഞാൻ പറയുന്നു.
എനിക്ക് വളരെ സന്തോഷമുണ്ട്.
എന്റെ പഴയ പരിചയം ഈ പുതിയ ജോലിക്ക് പറ്റിയതാണ്.
