ഞാൻ ജനലിനരികിൽ നിൽക്കുകയാണ്.
ഗ്ലാസിന് തണുപ്പുണ്ട്.
ഇത് ജനുവരിയാണ്.
ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
കോപ്പൻഹേഗനിൽ ഇന്ന് മൂടിക്കെട്ടിയ അന്തരീക്ഷമാണ്.
പുറത്ത് തണുപ്പാണ്.
തെരുവിൽ മഞ്ഞുണ്ട്.
പക്ഷേ ഇവിടെ ചൂടുണ്ട്.
അപ്പാർട്ട്മെന്റ് നല്ലതാണ്.
ഞാൻ മെക്സിക്കോയെക്കുറിച്ച് ചിന്തിക്കുന്നു.
മെക്സിക്കോയിൽ വെയിലുണ്ട്.
അവിടെ ചൂടുമുണ്ട്.
ഞാൻ ആ വെയിൽ അല്പം മിസ്സ് ചെയ്യുന്നുണ്ട്.
എങ്കിലും ഞാൻ പുഞ്ചിരിക്കുന്നു.
ഇതൊരു പുതിയ നഗരമാണ്.
ഞാൻ ഇപ്പോൾ ഡെന്മാർക്കിലാണ്.
ഇതൊരു നല്ല തുടക്കമാണ്.
