ആ ചെറിയ കഫേയിലെ എൻ്റെ ആദ്യത്തെ ശനിയാഴ്ചത്തെ ഷിഫ്റ്റാണിത്.
ഞാൻ നേരത്തെ തന്നെ എത്തിയിട്ടുണ്ട്.
കോപ്പൻഹേഗനിലെ തെരുവിൽ സൂര്യൻ പ്രകാശിക്കുന്നുണ്ട്.
ഞാൻ അതിനായി കാത്തിരിക്കുകയാണ്, എങ്കിലും എനിക്ക് ചെറിയൊരു പരിഭ്രമവുമുണ്ട്.
ഒരു കഫേയിൽ ഞാൻ ജോലി ചെയ്യുന്നത് ഇത് ആദ്യമായാണ്.
തയ്യാറെടുക്കുന്നതിനായി ഞാൻ പിന്നിലെ മുറിയിലേക്ക് പോയി.
അവിടെ ഒരു മേശപ്പുറത്ത് എനിക്കായി ഒരു പുതിയ ഏപ്രണ്‍ വെച്ചിട്ടുണ്ടായിരുന്നു.
ഞാൻ അത് ധരിക്കുകയും പിന്നിലായി കെട്ടുകയും ചെയ്തു.
അത് ധരിക്കാൻ നല്ല സുഖമുണ്ടായിരുന്നു.
ഇപ്പോൾ ഞാൻ തുടങ്ങാൻ തയ്യാറാണ്.
കഫേ ശരിയായ രീതിയിൽ തുറക്കാൻ എനിക്ക് പഠിക്കണം.
ആദ്യം, മാനേജർ ഭാരമുള്ള മുൻവാതിലിന്റെ പൂട്ട് തുറന്നു.
അതിനുശേഷം, ഒരുക്കങ്ങൾ നടത്തുന്നതിനായി ഞാൻ പുറത്ത് നടപ്പാതയിലേക്ക് ഇറങ്ങി.
ഞാൻ നാല് കസേരകൾ പുറത്തേക്ക് കൊണ്ടുപോയി.
ഒരു ചെറിയ മേശയ്ക്ക് ചുറ്റുമായി ഞാൻ അവ വെച്ചു.
അൽപ്പസമയത്തിനുള്ളിൽ, മറ്റ് വോളന്റിയർമാരും എത്തും.
എൻ്റെ ആദ്യ ദിവസത്തെക്കുറിച്ച് ഓർത്ത് ഞാൻ വളരെ ആവേശത്തിലാണ്.
