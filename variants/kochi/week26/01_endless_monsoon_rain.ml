ഞാൻ രാവിലെ മഴയുടെ വലിയ ശബ്ദം കേട്ട് ഉണരുന്നു.
മേൽക്കൂരയിൽ മഴവെള്ളം വീഴുന്നു.
ഇപ്പോൾ ജൂലൈ മാസം ആണ്.
മഴക്കാലം അതിന്റെ ഏറ്റവും ശക്തമായ അവസ്ഥയിൽ എത്തിയിട്ടുണ്ട്.
കഴിഞ്ഞ കുറച്ചു ദിവസങ്ങളിൽ ഇവിടെ തുടർച്ചയായി മഴ പെയ്തു.
ഇന്നലെ രാത്രിയും ഒരുപാട് മഴ പെയ്തിട്ടുണ്ട്.
ഞാൻ അടുക്കളയിൽ പോകുന്നു.
ഞാൻ ഒരു കപ്പ് ചൂട് കാപ്പി ഉണ്ടാക്കുന്നു.
കാപ്പിയുമായി ഞാൻ ജനലിന്റെ അടുത്തേക്ക് വരുന്നു.
ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
മഴ നഗരത്തെ പൂർണ്ണമായും മാറ്റിയിട്ടുണ്ട്.
ചുറ്റുമുള്ള മരങ്ങളിൽ എല്ലാം പുതിയ ഇലകൾ വന്നു.
നഗരം മുഴുവൻ ഇപ്പോൾ പച്ച നിറം ആയിട്ടുണ്ട്.
ജനുവരിയിൽ ഞാൻ കൊച്ചിയിൽ വന്നപ്പോൾ ഇവിടെ കാലാവസ്ഥ വരണ്ടതും സുഖകരവുമായിരുന്നു.
പിന്നീട് വന്ന വേനൽച്ചൂട് ഇപ്പോൾ പോയി.
എനിക്ക് ഈ മഴക്കാലം വളരെ ഇഷ്ടമാണ്.
