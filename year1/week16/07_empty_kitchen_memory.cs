Moje matka se ptá, jestli jsem byla ten první večer v pořádku.
Byt byl zařízený, ale pro mě stále nový.
V kuchyni jsem ještě neměla žádné jídlo.
Cestou domů jsem si koupila jednoduchou večeři.
Byl to sendvič z obchodu.
Sedla jsem si na malou pohovku.
V bytě bylo velmi ticho.
Tiše jsem snědla svou večeři.
Zatím jsem znala jen svou sousedku Ninu.
„Ten večer jste mi všichni moc chyběli,“ říkám jí.
Myslela jsem na svou sestru Sofíi a svého bratra Diega.
Dokonce mi chyběl i náš pes Lola.
Ale těšila jsem se na svůj nový život.
Moje matka si položí ruku na srdce.
„Začátek je vždycky těžký,“ odpovídá.
Přikývnu a vzpomínám na ten den.
Byl to těžký večer, ale další ráno už bylo mnohem lepší.
