ശനിയാഴ്ച വൈകുന്നേരം അനിത എൻ്റെ ഫ്ലാറ്റിലേക്ക് വരുന്നു.
അവർ ടോമിയെയും കൂടെ കൊണ്ടുവരുന്നുണ്ട്.
വാതിൽ തുറന്ന ഉടനെ, ടോമി സന്തോഷത്തോടെ അകത്തേക്ക് ഓടുന്നു.
ഞാൻ അവന് ഒരു ചെറിയ കളിപ്പാട്ടം കൊടുക്കുന്നു.
ഞങ്ങൾ ഊണുമേശയ്ക്ക് അടുത്ത് ഇരിക്കുന്നു.
ഞാൻ ഉച്ചയ്ക്ക് ഉണ്ടാക്കിയ മെക്സിക്കൻ ഭക്ഷണം വിളമ്പുന്നു.
അനിത അത് രുചിച്ച് നോക്കിയിട്ട് ചിരിക്കുന്നു.
"ഇത് വളരെ രുചികരമാണ്, മായ!" അനിത പറയുന്നു.
"ഇതിന് കുറച്ച് എരിവുണ്ട്, അല്ലേ?" ഞാൻ ചോദിക്കുന്നു.
"അല്ല, ഇത് നമ്മൾ മലയാളികൾക്ക് പാകമാണ്," അവർ ചിരിച്ചുകൊണ്ട് പറയുന്നു.
ഞങ്ങൾ ഈ ആഴ്ചത്തെ വിശേഷങ്ങൾ സംസാരിക്കുന്നു.
ഓഫീസിലെ കാര്യങ്ങളും കഫേയിലെ വിശേഷങ്ങളും ഞാൻ പറയുന്നു.
പുറത്ത് മഴ പെയ്യുമ്പോഴും ഫ്ലാറ്റിനുള്ളിൽ നല്ല ചൂടും സന്തോഷവുമുണ്ട്.
ഭക്ഷണം കഴിഞ്ഞ ശേഷം ടോമി എൻ്റെ കാലിനടുത്ത് കിടന്നുറങ്ങുന്നു.
ജനുവരിയിൽ എനിക്ക് ഇവിടെ എല്ലാം പുതിയതായിരുന്നു.
ഇപ്പോൾ എനിക്ക് സുഹൃത്തുക്കളും നല്ലൊരു ദിനചര്യയുമുണ്ട്.
കൊച്ചി ഇപ്പോൾ എനിക്ക് വെറുമൊരു പുതിയ നഗരമല്ല.
ഇത് എൻ്റെ സ്വന്തം വീടാണ്.
