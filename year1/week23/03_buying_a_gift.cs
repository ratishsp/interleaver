Je pátek odpoledne a já mám po práci.
Jdu po ulici a zastavím se u květinářství.
Mám v úmyslu koupit dárek pro Evu.
Otevřu dveře a vejdu do malého obchodu.
„Dobrý den,“ říká prodavač s velkým úsměvem.
„Dobrý den,“ odpovídám.
Dívám se na spoustu krásných květin.
Myslím na to, že Eva má vždycky ráda barvy.
Je designérka, takže bude z něčeho barevného asi nadšená.
Najdu velkou kytici se žlutými tulipány.
„Ráda bych si koupila tuhle kytici,“ říkám a ukazuji na tulipány.
„To je opravdu dobrá volba,“ říká prodavač.
Zabalí květiny do pěkného papíru.
„Bude to sto padesát korun,“ říká.
Vytáhnu kartu a zaplatím za květiny.
„Dnes večer jdu na večeři,“ říkám mu.
„Tak to bude mít vaše kamarádka určitě radost,“ odpovídá.
Vezmu si kytici a vyjdu z obchodu.
Teď už jen musím najít svou zastávku autobusu.
