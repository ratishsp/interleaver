Dzwoni kilka razy.
Ekran się rozświetla.
Widzę salon.
Świeci słońce, a salon jest bardzo jasny.
Widzę dwie osoby.
To moja mama i mój tata.
Bardzo się uśmiechają i machają do mnie.
„Cześć mamo i tato!” – mówię głośno.
„Cześć, Maya” – mówi mój tata.
„Jak leci?”
„Wszystko dobrze” – odpowiadam radośnie.
Nagle słyszę jakiś dźwięk.
To krótkie szczeknięcie.
„O, słyszę psa!” – mówię i się śmieję.
Mały pies wskakuje na sofę.
Patrzy w kamerę.
„Tam jest mój pies!”
„Cześć, Lola” – mówię.
Lola merda ogonem.
„Tak, to twój pies” – mówi moja mama z uśmiechem.
Kocham moją rodzinę.
Wspaniale jest ich wszystkich widzieć.
