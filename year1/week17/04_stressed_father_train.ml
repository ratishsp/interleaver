ഞാൻ ട്രെയിനിലെ എന്റെ സീറ്റിലിരുന്ന് ചുറ്റും നോക്കി.
ഒരു അച്ഛൻ എനിക്ക് എതിർവശത്തായി ഇരുന്നിരുന്നു.
അദ്ദേഹം തന്റെ രണ്ട് കൊച്ചുകുട്ടികളെയും കൂടെ കൊണ്ടുവന്നിരുന്നു.
ആ അച്ഛന്റെ കൈയിൽ ഒരു വലിയ പുസ്തകം ഉണ്ടായിരുന്നു.
അദ്ദേഹത്തിന് തന്റെ പുസ്തകം വായിക്കാൻ വളരെ ആഗ്രഹമുണ്ടായിരുന്നു.
എന്നാൽ അദ്ദേഹത്തിന് വലിയ സമാധാനമൊന്നും കിട്ടിയില്ല.
അദ്ദേഹത്തിന്റെ മകളുടെ പക്കൽ ഒരു ചുവന്ന പന്ത് ഉണ്ടായിരുന്നു.
അദ്ദേഹത്തിന്റെ മകന്റെ പക്കൽ ഒരു പച്ച കളിപ്പാട്ട കാർ ഉണ്ടായിരുന്നു.
ആ കുട്ടികൾ ഒട്ടും അടങ്ങിയിരിക്കുന്നില്ലായിരുന്നു.
അവർ നിരന്തരം തങ്ങളുടെ കളിപ്പാട്ടങ്ങൾ തറയിലേക്ക് വലിച്ചെറിയുകയായിരുന്നു.
ആ അച്ഛൻ ഉറക്കെ നെടുവീർപ്പിടുകയും പുസ്തകം അടച്ചുവെക്കുകയും ചെയ്തു.
അദ്ദേഹം തറയിൽ നിന്ന് ആ സാധനങ്ങൾ പെറുക്കിയെടുത്തു.
അദ്ദേഹം ആ കളിപ്പാട്ടങ്ങൾ കുട്ടികൾക്ക് തിരികെ നൽകി.
"നിങ്ങൾ അടങ്ങിയിരിക്കണം," അദ്ദേഹം ക്ഷീണത്തോടെ പറഞ്ഞു.
അദ്ദേഹം വീണ്ടും തന്റെ പുസ്തകം തുറന്നു.
രണ്ട് മിനിറ്റിനുശേഷം, ആ പന്ത് തറയിൽ വീണു.
അത് ആ അച്ഛന്റെ ഇടത് ഷൂവിൽ കൊണ്ടു.
ആ മനുഷ്യൻ വീണ്ടും ആ പന്ത് പെറുക്കിയെടുത്തു.
ക്ഷീണിതനായ ആ അച്ഛനെ നോക്കി ഞാൻ പുഞ്ചിരിച്ചു.
അദ്ദേഹം വെറുതെ തല കുലുക്കിയിട്ട് താഴെ പുസ്തകത്തിലേക്ക് തന്നെ നോക്കി.
