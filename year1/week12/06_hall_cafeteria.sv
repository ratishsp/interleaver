Vi går in i den lilla cafeterian i hallen.
Vi hittar ett bord.
Jag är mycket törstig.
Vi dricker kallt vatten och pratar.
"Det här är en riktigt bra klubb", säger jag.
"Det är en bra sport att utöva", säger Kasper.
Kasper tittar på mig.
"Vill du vara med igen?" frågar han.
"Ja, mycket gärna", svarar jag.
"Jag vill spela här varje torsdag", förklarar jag.
"Det låter härligt", säger Sara.
"Vi spelar alltid här på torsdagar", säger Kasper.
"Då ses vi nästa vecka", säger jag glatt.
Vi dricker resten av vårt vatten.
Det är härligt att träffa nya människor.
