Szybki mecz się skończył.
Schodzimy razem z kortu.
Jestem bardzo zmęczona.
Kasper i Sara też są zmęczeni.
Pijemy trochę wody.
„Bardzo dobrze grasz” – mówi Sara.
„Bardzo dziękuję” – mówię.
„Uważam, że to świetna zabawa”.
„Często grasz?” – pyta Kasper.
„Tak, dużo gram u siebie w Meksyku” – odpowiadam.
„Zazwyczaj gram z moją siostrą”.
„To fajny sport” – mówi Sara.
„Uwielbiamy grać tutaj w klubie”.
„Chcę grać więcej tutaj, w Danii” – mówię.
„Zdecydowanie jesteś szybka” – śmieje się Kasper.
„Dzięki, ale teraz chcę usiąść” – mówię.
„Pójdziemy do kafeterii?” – pyta Kasper.
„Tak, bardzo bym chciała” – odpowiadam.
