Sedím u svého stolu v kanceláři.
Eva ke mně přichází s hrnkem kávy.
Tento týden spolu úzce spolupracujeme.
„Jsi připravená podívat se na ten nový layout?“ ptá se.
„Ano, jen musím otevřít ten program,“ odpovídám.
Společně se díváme na velkou obrazovku.
Ten velký digitální projekt vypadá konečně dobře.
Ale Eva najednou vidí v rohu malou chybu.
Jedno modré tlačítko je trochu moc daleko vlevo.
„Podívej tam, ta pozice je špatně,“ říká.
„Máš pravdu, musím ho posunout doprava,“ říkám.
Rychle napíšu pár řádků kódu.
Tlačítko se přesune na správné místo.
„Perfektní, děkuji za pomoc,“ říká Eva a vřele se usmívá.
Společně si povídáme a smějeme se našim plánům na víkend.
Teď už všechny v kanceláři dobře znám.
