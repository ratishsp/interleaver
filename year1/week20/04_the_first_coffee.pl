Dziś rano mieliśmy niesamowicie dużo pracy.
Właśnie zrobiłam moje pierwsze w życiu cappuccino.
Chwilę przed dziesiątą do lady podszedł pewien mężczyzna.
„Poproszę cappuccino” – powiedział.
Dopiero co nauczyłam się obsługiwać ekspres do kawy.
Więc od razu podeszłam do ekspresu.
Zaparzyłam kawę i zanurzyłam dyszę parową w mleku.
Ale trzymałam ją trochę za głęboko.
Pewnie byłam trochę za bardzo zdenerwowana.
Niestety, na mleku nie zrobiła się gęsta piana.
Ostrożnie zajrzałam do dzbanka.
Pianka nie była do końca idealna.
Ale wciąż wyglądała akceptowalnie.
Wlałam gorące mleko do kawy w filiżance.
Następnie podałam kawę mężczyźnie z uprzejmym uśmiechem.
„Proszę bardzo, to będzie pięćdziesiąt pięć koron” – powiedziałam.
Wziął filiżankę i usiadł przy pierwszym stoliku.
