ഇപ്പോൾ രാത്രിയാണ്.
ഇത് കോപ്പൻഹേഗനിലെ എന്റെ ആദ്യത്തെ രാത്രിയാണ്.
ഞാൻ കുളിമുറിയിലാണ്.
അത് വളരെ ചെറുതാണ്.
അവിടെ ഒരു വാഷ്ബേസിൻ ഉണ്ട്.
എന്റെ ടൂത്ത് ബ്രഷ് ചുവപ്പാണ്.
ഞാൻ എന്റെ ടൂത്ത് ബ്രഷിൽ ടൂത്ത് പേസ്റ്റ് വയ്ക്കുന്നു.
ഞാൻ എന്റെ പല്ല് തേക്കുന്നു.
വെള്ളം തണുത്തതാണ്.
ഞാൻ എന്റെ മുഖം കഴുകുന്നു.
അത് സുഖകരമാണ്.
ഞാൻ എന്റെ കിടക്കയ്ക്കരികിലേക്ക് പോകുന്നു.
കിടക്ക ചെറുതാണ്.
എന്നാൽ അത് ചൂടുള്ളതും മൃദുവായതുമാണ്.
ഞാൻ ഇപ്പോൾ പുതപ്പിനടിയിൽ കിടക്കുകയാണ്.
എന്റെ ഫോൺ മേശപ്പുറത്തുണ്ട്.
ഞാൻ എന്റെ അലാം വയ്ക്കുന്നു.
അത് നാളെ എട്ട് മണിക്ക് അടിക്കും.
ഞാൻ ക്ഷീണിതയാണ്, എങ്കിലും ഞാൻ തയ്യാറാണ്.
ശുഭരാത്രി, കോപ്പൻഹേഗൻ.
