Pokládám košili a účtenku na pult.
Prodavačka je připravena mi pomoci.
„Dobrý den, tuhle košili jsem si koupila v sobotu,“ říkám.
„Ale je bohužel moc malá.“
„Můžu ji vyměnit za větší velikost?“
„Ano, to samozřejmě můžete,“ odpovídá prodavačka.
„Jakou velikost potřebujete?“
„Potřebuji velikost L místo M,“ vysvětluji.
„Okamžik,“ říká prodavačka.
Jde k regálům s modrými košilemi.
Rychle najde správnou velikost a vrací se.
„Tady je velikost L,“ říká s úsměvem.
„Chcete si ji nejdřív vyzkoušet?“
„Ano, prosím,“ odpovídám radostně.
„Zkušební kabinky jsou hned tamhle vpravo,“ říká mi.
„Moc děkuji za pomoc,“ říkám a beru si novou košili.
Teď uvidím, jestli je ta větší košile lepší.
