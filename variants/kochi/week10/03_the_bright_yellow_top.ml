ഞാൻ ഡ്രെസ്സിങ് റൂമിന് പുറത്ത് നിൽക്കുന്നു.
അവിടെ ഒരു ചെറിയ റാക്ക് ഉണ്ട്.
അതിൽ നല്ല ഭംഗിയുള്ള ഒരു ടോപ്പ് ഉണ്ട്.
അതൊരു തിളക്കമുള്ള മഞ്ഞ ടോപ്പ് ആണ്.
എനിക്ക് ആ മഞ്ഞ ടോപ്പ് ഇഷ്ടമാകുന്നു.
ഞാൻ അത് എടുക്കുന്നു.
ഞാൻ അതും ഇട്ടു നോക്കുന്നു.
എനിക്ക് ആ ടോപ്പ് നന്നായി ചേരുന്നുണ്ട്.
അത് ഇടാൻ നല്ല സുഖമുണ്ട്.
ഞാൻ അതിന്റെ വില നോക്കുന്നു.
അവിടെ വില കാണുന്നില്ല.
ഞാൻ അടുത്തുള്ള ഒരു ജീവനക്കാരിയോട് ചോദിക്കുന്നു.
"ഈ ടോപ്പിന് എത്ര രൂപയാണ്?" ഞാൻ അവരോട് ചോദിക്കുന്നു.
"രണ്ടായിരം രൂപയാണ്, മേഡം," അവർ മറുപടി പറയുന്നു.
രണ്ടായിരം രൂപ!
അതൊരു വലിയ വിലയാണ്.
എനിക്ക് ഈ ടോപ്പ് വേണ്ട.
ഞാൻ അത് വാങ്ങുന്നില്ല.
ഞാൻ ആ മഞ്ഞ ടോപ്പ് തിരികെ റാക്കിൽ വെക്കുന്നു.
