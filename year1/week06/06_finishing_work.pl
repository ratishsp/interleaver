Jest późne popołudnie w biurze.
Patrzę na swój ekran.
Piszę ostatni kod.
Teraz zadanie jest skończone.
Uśmiecham się.
Zamykam komputer.
Wkładam go do torby.
Następnie pakuję swoje rzeczy.
Wstaję.
Mój kolega Peter siedzi przy swoim biurku.
Podchodzę do niego.
„Do widzenia, Peter” – mówię.
„Do widzenia, Maya” – mówi Peter.
„Miłego wieczoru” – mówi.
„Dziękuję, nawzajem” – odpowiadam.
Wychodzę z biura.
Na korytarzu zjeżdżam windą na dół.
W końcu wychodzę z budynku.
Teraz wracam do domu.
