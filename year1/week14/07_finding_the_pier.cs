Cesta metrem skončila.
Teď jdu nahoru na ulici.
Jedu eskalátorem.
Nahoře na ulici svítí slunce.
Teď jdu k vodě.
Pojedu přístavním autobusem.
Jdu dolů širokou ulicí.
Pak vidím kanál.
Voda je velmi modrá.
Hledám svou zastávku.
Kde ta loď zastavuje?
Jdu blíž k okraji.
Pak vidím malé dřevěné molo.
Je úplně dole u vody.
U mola je žlutá cedule.
Na ceduli je napsáno „Přístavní autobus“.
To je to správné místo.
Jdu na molo.
Teď už jen čekám na loď.
