Obrazovka ukazuje moje číslo.
To číslo je padesát devět.
Jdu k přepážce.
Za přepážkou sedí muž.
„Dobré ráno,“ říká.
„Dobré ráno,“ odpovídám.
„Jmenuji se Maya a je mi třicet jedna let,“ říkám.
„Vítejte, Mayo,“ říká.
„Máte svůj pas?“ ptá se.
„Ano, mám svůj pas a své papíry,“ odpovídám.
„Tady máte,“ říkám.
Dívá se na papíry.
Píše na svém počítači.
Dostávám dánské osobní identifikační číslo.
To číslo je soukromé a velmi důležité.
Dává mi novou kartu.
„Tady máte, tady je vaše karta,“ říká.
„Nyní jste zaregistrována v Dánsku.“
Usmívám se a beru si kartu.
Teď jsem součástí Dánska.
