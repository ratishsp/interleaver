Napsala jsem si do deníku o svém výletu do Odense.
Bylo krásné sobotní ráno.
Probudila jsem se brzy v sedm hodin.
Slunce svítilo a nebe bylo modré.
Sbalila jsem si svůj malý zelený batoh.
Dala jsem si do tašky zápisník a fotoaparát.
Vzala jsem si s sebou také silný svetr.
Jarní počasí v Dánsku může být trochu chladné.
Potom jsem jela autobusem na velké nádraží v Kodani.
Uvnitř bylo mnoho uspěchaných lidí.
Šla jsem k malému kiosku.
Koupila jsem si velkou teplou kávu na cestu.
Stála čtyřicet pět korun.
Podívala jsem se nahoru na velkou obrazovku.
Na obrazovce jsem rychle našla svůj vlak.
Jela jsem rychlým vlakem do Odense.
Vlak přijel na nástupiště přesně v osm hodin.
Nastoupila jsem do vlaku a našla své místo u velkého okna.
Pila jsem svou teplou kávu a těšila se na výlet.
