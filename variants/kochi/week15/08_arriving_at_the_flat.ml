എന്റെ അപ്പാർട്ട്മെന്റ് കെട്ടിടത്തിൽ എത്തി ഞാൻ പടികൾ കയറുന്നു.
ബാഗിൽ നിന്ന് താക്കോൽ എടുത്ത് വാതിൽ തുറക്കുന്നു.
അകത്തേക്ക് കയറി വാതിൽ അടയ്ക്കുന്നു.
ഞാൻ വാതിലിനടുത്ത് വെച്ച് ഷൂസ് ഊരുന്നു.
ഫ്ലാറ്റ് വളരെ ശാന്തമാണ്.
ഇപ്പോൾ പുറത്ത് നല്ല ചൂടാണ്.
അതുകൊണ്ട് ഞാൻ ലൈറ്റും ഫാനും ഇടുന്നു.
ലാപ്‌ടോപ്പ് ബാഗും പച്ചക്കറികളും മേശപ്പുറത്ത് വെക്കുന്നു.
ഞാൻ അടുക്കളയിലേക്ക് നടക്കുന്നു.
ഒരു ഗ്ലാസ് വെള്ളം എടുത്ത് കുടിക്കുന്നു.
അതിനുശേഷം ഞാൻ സോഫയിൽ ഇരിക്കുന്നു.
ഇന്നത്തെ ജോലി കഴിഞ്ഞു.
എനിക്ക് ഇപ്പോൾ നല്ല ക്ഷീണമുണ്ട്.
