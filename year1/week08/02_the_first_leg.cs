Sleduji Nininu trasu.
Vzduch je svěží a chladný.
Teď jdu po hlavní ulici.
Nejdřív jdu jen rovně.
Na ulici je velký provoz.
Cestou vidím tři žlutá kola.
Kola kolem mě rychle projíždějí.
Poté jdu dál dopředu.
Pak dojdu k velkému parku.
Teď si vzpomínám na Ninina slova.
„U parku zahni doleva,“ říká.
Tady zahýbám doleva.
O chvíli později vidím otevřené dveře.
Je to malé pekařství.
Je tu nádherná vůně čerstvé kávy.
Miluji teplý chléb.
Dnes je město krásné.
Potom jdu dál směrem k vodě.
