ഞാൻ വീണ്ടും പുറത്ത് പടിക്കെട്ടിലേക്ക് ഇറങ്ങുന്നു.
എന്റെ ഏറ്റവും വലിയ സ്യൂട്ട്കേസ് തറയിൽ ഇരിപ്പുണ്ട്.
അതിന് വളരെ ഭാരമുണ്ട്.
ഞാൻ സ്യൂട്ട്കേസ് വലിക്കുന്നു.
പെട്ടെന്ന് പടിക്കെട്ടിൽ കാലൊച്ചകൾ ഞാൻ കേൾക്കുന്നു.
അത് എന്റെ ഡാനിഷ് അയൽക്കാരി നീനയാണ്.
അവൾ എന്നെ നോക്കി സ്നേഹത്തോടെ പുഞ്ചിരിക്കുന്നു.
"മായാ, നീ ഇന്ന് ഇവിടേക്ക് മാറുകയാണോ?" അവൾ ചോദിക്കുന്നു.
"അതെ, ഞാൻ ഒടുവിൽ എന്റെ പുതിയ അപ്പാർട്ട്മെന്റിൽ എത്തി," ഞാൻ പറയുന്നു.
"ഞാൻ നിന്നെ സഹായിക്കാം," നീന സ്നേഹത്തോടെ പറയുന്നു.
അവൾ ആ സ്യൂട്ട്കേസിൽ പിടിക്കുന്നു.
ഞങ്ങൾ ഒരുമിച്ച് സ്യൂട്ട്കേസ് സ്വീകരണമുറിയിലേക്ക് കൊണ്ടുപോകുന്നു.
നീന അത് ശ്രദ്ധയോടെ തറയിൽ വെക്കുന്നു.
ഇപ്പോൾ ആ സ്യൂട്ട്കേസ് വലിയ ജനലിനരികിലിരിപ്പുണ്ട്.
ജനലിന് താഴെ നേരത്തെ തന്നെ ഒരു ബാഗ് വെച്ചിട്ടുണ്ട്.
"സഹായിച്ചതിന് ഒരുപാട് നന്ദി, നീന," ഞാൻ സന്തോഷത്തോടെ പറയുന്നു.
"അതിനെന്താ," അവൾ പുഞ്ചിരിക്കുന്നു.
നീന പുറത്ത് പടിക്കെട്ടിലേക്ക് നടക്കുന്നു.
ഞാൻ വാതിൽ അടച്ചിട്ട് ജനലിനരികിലുള്ള സ്യൂട്ട്കേസിലേക്ക് നോക്കുന്നു.
