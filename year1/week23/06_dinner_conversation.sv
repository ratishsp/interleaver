Vi sätter oss vid det vackra bordet.
Eva har dukat bordet med färgglada tallrikar och tända stearinljus.
Hon har lagat en härlig vegetarisk måltid till oss.
"Tack, Eva, det ser utsökt ut," säger jag med ett leende.
"Det doftar helt fantastiskt."
"Varsågod," svarar hon och räcker mig en skål med sallad.
Jag smakar genast på maten.
Jag tycker att de färska råvarorna verkligen smakar underbart.
"Det här är otroligt gott," säger jag till henne.
"Jag har tänkt mig att laga ännu fler lokala rätter snart," säger jag.
"Jag vill väldigt gärna använda fler danska grönsaker."
"Det låter som en riktigt bra idé," säger Eva glatt.
"Vi ska absolut laga mat tillsammans en dag."
"Jag tror att vi nog kommer att ha roligt i köket."
"Det vill jag väldigt gärna," svarar jag och tar en tugga till.
Vi häller upp lite kallt vatten i glasen.
Jag känner att kvällen redan är en stor succé.
