ഞാൻ എറണാകുളം മാർക്കറ്റിൽ എത്തുന്നു.
ഇപ്പോൾ രാവിലെ ആണ്.
പക്ഷേ നല്ല ചൂട് ഉണ്ട്.
മാർക്കറ്റിന്റെ മുന്നിൽ ഒരു ചെറിയ കട ഉണ്ട്.
ഞാൻ ആ കടയുടെ അടുത്തേക്ക് നടക്കുന്നു.
എനിക്ക് കുറച്ചു വെള്ളം വേണം.
കടക്കാരൻ അവിടെ നിൽക്കുന്നുണ്ട്.
"ഒരു കുപ്പി വെള്ളം തരൂ," ഞാൻ പറയുന്നു.
കടക്കാരൻ എനിക്ക് വെള്ളം തരുന്നു.
"എത്ര രൂപ ആയി?" ഞാൻ ചോദിക്കുന്നു.
"ഇരുപത് രൂപ," കടക്കാരൻ പറയുന്നു.
ഞാൻ എന്റെ ബാഗ് തുറക്കുന്നു.
ഞാൻ അതിൽ നിന്ന് കാശ് എടുക്കുന്നു.
ഞാൻ ഇരുപത് രൂപയുടെ നോട്ട് കൊടുക്കുന്നു.
അയാൾ കാശ് വാങ്ങുന്നു.
ഞാൻ അല്പം വെള്ളം കുടിക്കുന്നു.
ഇപ്പോൾ നല്ല ആശ്വാസം ഉണ്ട്.
പിന്നെ ഞാൻ മാർക്കറ്റിന്റെ ഉള്ളിലേക്ക് പോകുന്നു.
