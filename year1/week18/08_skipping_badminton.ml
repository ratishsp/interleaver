വ്യാഴാഴ്ച വൈകുന്നേരമാണ്, ഞാൻ സാധാരണയായി ബാഡ്മിന്റൺ കളിക്കാറുണ്ട്.
പക്ഷേ എനിക്ക് ഇപ്പോഴും അസുഖമാണ്, അതിനാൽ എനിക്കിത് റദ്ദാക്കേണ്ടതുണ്ട്.
ഞാൻ എന്റെ ബാഡ്മിന്റൺ പങ്കാളിക്ക് ഒരു സന്ദേശം എഴുതുന്നു.
എനിക്ക് അസുഖമാണെന്നും തലവേദനയുണ്ടെന്നും ഞാൻ വിശദീകരിക്കുന്നു.
എന്റെ തൊണ്ടയ്ക്കും ഇപ്പോഴും നല്ല വേദനയുണ്ട്.
ഇന്ന് രാത്രി ഞാൻ സോഫയിൽ വെറുതെ വിശ്രമിക്കുന്നതാണ് നല്ലത്.
ഞാൻ ചൂടുള്ള ഒരു പുതപ്പ് വലിച്ചു മൂടുന്നു.
ഞാൻ ഫാർമസിയിൽ നിന്നുള്ള എന്റെ പുതിയ മരുന്ന് കഴിക്കുന്നു.
അതിനുശേഷം, ഞാൻ ഒരു വലിയ കപ്പ് ചൂടുള്ള ചായ ഉണ്ടാക്കുന്നു.
ഞാൻ ചായയിൽ ഒരു വലിയ സ്പൂൺ തേൻ ചേർക്കുന്നു.
ഇത് എന്റെ വേദനയുള്ള തൊണ്ടയ്ക്ക് ശരിക്കും ആശ്വാസം നൽകുന്നു.
ഞാൻ ആ ചൂടുചായ വളരെ പതുക്കെ കുടിക്കുന്നു.
പെട്ടെന്നുതന്നെ എനിക്ക് അല്പം ഭേദം തോന്നുന്നു.
ഞാൻ കണ്ണുകളടച്ച് ശാന്തമായ സംഗീതം കേൾക്കുന്നു.
എനിക്ക് ഇതുവരെ പൂർണ്ണമായും സുഖം തോന്നിയിട്ടില്ല.
എങ്കിലും ഭാഗ്യവശാൽ എനിക്കിപ്പോൾ തന്നെ അല്പം ഭേദമുണ്ട്.
ഞാൻ നേരത്തെ പോയി കിടന്നുറങ്ങുന്നതാണ് നല്ലത്.
