Kładę koszulę i mój paragon na ladzie.
Ekspedientka jest gotowa mi pomóc.
„Cześć, kupiłam tę koszulę w sobotę” – mówię.
„Ale niestety jest za mała”.
„Czy mogę ją wymienić na większy rozmiar?”.
„Tak, oczywiście, że pani może” – odpowiada ekspedientka.
„Jakiego rozmiaru pani potrzebuje?”.
„Potrzebuję rozmiaru L zamiast M” – wyjaśniam.
„Chwileczkę” – mówi ekspedientka.
Podchodzi do półek z niebieskimi koszulami.
Szybko znajduje właściwy rozmiar i wraca.
„Oto rozmiar L” – mówi z uśmiechem.
„Czy chce ją pani najpierw przymierzyć?”.
„Tak, poproszę” – odpowiadam radośnie.
„Przymierzalnie są tam, po prawej” – mówi mi.
„Bardzo dziękuję za pomoc” – mówię i biorę nową koszulę.
Teraz mogę zobaczyć, czy większa koszula jest lepsza.
