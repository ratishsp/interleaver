എന്റെ അടുത്തുള്ള മെഡിക്കൽ ക്ലിനിക്കിന്റെ ഫോൺ നമ്പർ ഞാൻ കണ്ടെത്തുന്നു.
നമ്പർ മുപ്പത്തിരണ്ട്, നാൽപ്പത്തഞ്ച്, അറുപത്തേഴ്, എൺപത്തൊൻപത് ആണ്.
ഞാൻ അവരെ വിളിച്ച് കുറച്ച് മിനിറ്റ് കാത്തിരിക്കുന്നു.
സൗഹാർദ്ദമുള്ള ഒരു റിസപ്ഷനിസ്റ്റ് ഫോൺ എടുക്കുന്നു.
"മെഡിക്കൽ ക്ലിനിക്ക്, നിങ്ങൾ സംസാരിക്കുന്നത് ഹന്നയോടാണ്," അവൾ പറയുന്നു.
ഇന്ന് എനിക്ക് വല്ലാതെ സുഖമില്ലാതായി എന്ന് ഞാൻ വിശദീകരിക്കുന്നു.
"എന്റെ തലയ്ക്ക് നല്ല ഭാരമുണ്ട്, കണ്ണുകൾ ചൊറിയുന്നുമുണ്ട്," ഞാൻ പറയുന്നു.
എനിക്ക് തൊണ്ടവേദനയുണ്ടെന്നും ഞാൻ അവളോട് പറയുന്നു.
എനിക്ക് പനിയുണ്ടോ എന്ന് അവൾ ചോദിക്കുന്നു.
ഇല്ലെന്നാണ് എനിക്ക് തോന്നുന്നത്, പക്ഷേ ഞാൻ വളരെ ക്ഷീണിതയാണ് എന്ന് ഞാൻ മറുപടി പറയുന്നു.
"നിങ്ങൾ ഇന്ന് തന്നെ ഒരു ഡോക്ടറുമായി സംസാരിക്കണം," റിസപ്ഷനിസ്റ്റ് പറയുന്നു.
ഒരു അപ്പോയിന്റ്മെന്റ് കണ്ടെത്താൻ അവൾ കലണ്ടറിൽ നോക്കുന്നു.
"നിങ്ങൾക്ക് ഒരു മണിക്ക് വരാൻ കഴിയുമോ?" അവൾ ചോദിക്കുന്നു.
"അതെ, അത് തികച്ചും അനുയോജ്യമാണ്," ഞാൻ മറുപടി നൽകുന്നു.
"നിങ്ങളുടെ മഞ്ഞ ഹെൽത്ത് കാർഡ് കൊണ്ടുവരാൻ ഓർമ്മിക്കുക," അവൾ പറയുന്നു.
ഞാൻ അവളോട് നന്ദി പറഞ്ഞ് ഫോൺ വെക്കുന്നു.
അവിടേക്ക് നടന്നുപോകുന്നതിന് മുൻപ് എനിക്കിനി കുറച്ചൊന്ന് വിശ്രമിക്കണം.
