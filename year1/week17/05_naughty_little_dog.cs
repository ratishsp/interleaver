Rodina s sebou do vlaku vzala i malého psa.
Byl moc roztomilý, ale nebyl potichu.
Pes ležel ve svém malém košíku na podlaze.
Otec se znovu podíval dolů na svou knihu.
Chtěl si jen trochu číst.
Ale najednou pes vyskočil ze svého košíku.
Rychle přiběhl k otci.
Seděl s jednou nohou nahoře na tašce.
Pes popadl jeho levou botu.
Vzal si botu do tlamy.
Potom rychle utekl.
„Ne, vrať se s mojí botou!“ zakřičel otec.
Postavil se v ponožkách.
Běžel za psem uličkou.
Ty dvě děti na něj ukazovaly.
Podívaly se na sebe a hlasitě se smály.
Podívala jsem se na ně ze svého místa.
Také jsem se trochu zasmála za svou knihou.
Naštěstí svého psa nakonec chytil.
Dostal zpátky i svou botu.
