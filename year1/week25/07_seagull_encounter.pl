Idę do domu przez duży park.
Godzinę temu byłam w muzeum.
Teraz chcę po prostu cieszyć się dobrą pogodą.
Zatrzymuję się przy małym kiosku, żeby kupić lody w wafelku.
„Proszę, oto twoje lody” – mówi mężczyzna w kiosku.
„Bardzo dziękuję” – odpowiadam i biorę lody.
Idę powoli wzdłuż jeziora w parku.
Te lody w wafelku wyglądają naprawdę dobrze.
Nagle słyszę nad sobą głośny dźwięk.
Duża mewa pikuje prosto na mnie.
Chce ukraść moje lody!
Szybko się schylam i osłaniam lody ręką.
Ptak nie ukradnie mojego jedzenia.
Mewa przelatuje obok i ląduje na trawie.
Kobieta na ławce się śmieje.
„Są dzisiaj bardzo bezczelne” – mówi.
„Tak, zdecydowanie” – odpowiadam ze śmiechem.
Szybko kończę jeść lody, idąc dalej.
