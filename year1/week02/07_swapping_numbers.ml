ഞാൻ എന്റെ അപ്പാർട്ട്മെന്റിന്റെ അടുത്ത് നിൽക്കുകയാണ്.
എന്റെ കയ്യിൽ ഒരു സിനമൺ പേസ്ട്രിയുള്ള ഒരു കവറുണ്ട്.
എന്റെ അയൽക്കാരി നീന വാതിലിനരികിലുണ്ട്.
അവൾ വിശാലമായി പുഞ്ചിരിച്ചുകൊണ്ട് ഹലോ പറയുന്നു.
"ഹലോ മായാ, നിനക്കിപ്പോൾ ഒരു ഡാനിഷ് നമ്പർ ഉണ്ടോ?" നീന ചോദിക്കുന്നു.
"അതെ, എനിക്കൊരു പുതിയ ഫോൺ നമ്പറുണ്ട്," ഞാൻ മറുപടി പറയുന്നു.
"അത് നന്നായി," അവൾ പറയുന്നു.
എന്റെ ഫോൺ എന്റെ കയ്യിലുണ്ട്.
"നിന്റെ നമ്പർ എത്രയാണ്?" ഞാൻ ചോദിക്കുന്നു.
"എന്റെ നമ്പർ എൺപത്തിയേഴ്, അറുപത്തിയഞ്ച്, നാൽപ്പത്തിമൂന്ന്, ഇരുപത്തിയൊന്ന് എന്നാണ്," നീന പറയുന്നു.
ഞാൻ അവളുടെ നമ്പർ എന്റെ ഫോണിൽ എഴുതുന്നു.
"എന്റെ നമ്പർ പന്ത്രണ്ട്, മുപ്പത്തിനാല്, അൻപത്തിയാറ്, എഴുപത്തിയെട്ട് എന്നാണ്," ഞാൻ പറയുന്നു.
നീന എന്റെ നമ്പർ അവളുടെ ഫോണിൽ സേവ് ചെയ്യുന്നു.
ഇപ്പോൾ ഞങ്ങൾ സമ്പർക്കത്തിലാണ്.
ഞങ്ങൾ ഒരുമിച്ച് അകത്തേക്ക് പോകുന്നു.
എന്റെ പുതിയ സുഹൃത്തിനെ ഓർത്ത് ഞാൻ വളരെ സന്തോഷവതിയാണ്.
