Idę na spacer przez duży plac w mieście.
Co niedzielę jest tu duży pchli targ.
Świeci słońce, a między stołami przechadza się wielu ludzi.
Zatrzymuję się przy małym stoliku z wieloma różnymi rzeczami.
Za stolikiem stoi przyjazny sprzedawca.
Nagle widzę dwa niebieskie ceramiczne talerze.
Podnoszę je i uważnie im się przyglądam.
„Ile kosztują te talerze?” – pytam sprzedawcę.
Sprzedawca uśmiecha się do mnie.
„Kosztują tylko czterdzieści koron” – odpowiada.
To naprawdę dobra cena.
Miesiąc temu kupiłam mały stół do mojej kuchni.
Te talerze będą idealnie pasować do tego stołu.
„Bardzo chętnie je kupię” – mówię.
Daję sprzedawcy czterdzieści koron i ostrożnie wkładam talerze do mojej torby.
Zawsze miło jest znaleźć coś wyjątkowego w spokojną niedzielę.
