Cestou domů od doktora jdu do místní lékárny.
Vytáhnu si z automatu číslo a chvíli čekám.
Milá lékárnice vyvolá číslo pětatřicet.
Jdu k pultu a ukážu svou žlutou zdravotní kartu.
Najde můj recept v počítači.
Lékárnice mi dá malou krabičku s prášky na alergii.
„Měla byste brát jeden prášek každé ráno,“ říká.
Ptám se jí, jestli má něco na krk.
„Pořád mě bolí v krku,“ vysvětluji.
Přikývne a navrhne nějaké sladké pastilky na krk.
„Pomáhají, když vás bolí v krku,“ říká.
„A dnes byste také měla pít hodně vody.“
Poděkuji jí a koupím si ty prášky a pastilky.
Celkem to stojí pětaosmdesát korun.
Jsem stále unavená a rozbolavělá, ale jsem ráda, že mám léky.
Teď už chci jen domů na svou vlastní pohovku.
