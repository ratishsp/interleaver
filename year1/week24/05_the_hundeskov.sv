Ludwig går snabbt bredvid mig.
Vi är på väg till en lokal hundskog.
Solen skiner härligt den här eftermiddagen.
Han drar lite ivrigt i kopplet.
"Vänta", säger jag bestämt till honom.
"Kom, låt oss gå fint."
Vi kommer äntligen fram till den stora grinden.
Hundskogen är inhägnad och helt säker.
Vi går in, och jag stänger grinden bakom oss.
Jag sätter mig på huk och tittar på honom.
Jag knäpper långsamt loss kopplet från hans halsband.
"Nu får du springa fritt", säger jag med ett leende.
Han tittar glatt på mig och springer snabbt iväg.
Jag hittar en bra pinne på marken.
"Titta här, Ludwig!" ropar jag och visar honom den.
Jag kastar pinnen långt bort in bland träden.
"Hämta den!" säger jag högt.
Han springer bort till pinnen och tar den i munnen.
"Kom tillbaka", ropar jag och klappar i händerna.
Han är verkligen en duktig hund.
