Podróż metrem się skończyła.
Teraz idę na górę, na ulicę.
Jadę schodami ruchomymi.
Na górze, na ulicy świeci słońce.
Teraz idę nad wodę.
Popłynę autobusem wodnym.
Idę szeroką ulicą.
Potem widzę kanał.
Woda jest bardzo niebieska.
Szukam swojego przystanku.
Gdzie zatrzymuje się łódź?
Podchodzę bliżej krawędzi.
Wtedy widzę mały, drewniany pomost.
Znajduje się tuż przy wodzie.
Przy pomoście jest żółty znak.
Na znaku jest napisane „Autobus wodny”.
To właściwe miejsce.
Wchodzę na pomost.
Teraz tylko czekam na łódź.
