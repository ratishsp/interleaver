ഞാൻ നീനയുടെ വാതിലിനടുത്തേക്ക് നടക്കുന്നു.
ഞാൻ വാതിലിൽ മുട്ടുന്നു.
നീന വാതിൽ തുറന്ന് പുഞ്ചിരിക്കുന്നു.
ഞാൻ അവൾക്ക് ചോക്ലേറ്റ് കേക്ക് കാണിച്ചുകൊടുക്കുന്നു.
"ഹായ് നീന," ഞാൻ പറയുന്നു.
"എന്റെ കൈയിൽ ബേക്കറിയിൽ നിന്നുള്ള ഒരു കേക്കുണ്ട്."
"ഹായ് മായ, എത്ര മനോഹരം!" നീന പറയുന്നു.
ഞങ്ങൾ അവളുടെ സ്വീകരണമുറിയിലേക്ക് പോകുന്നു.
സ്വീകരണമുറി വളരെ ഊഷ്മളവും സുഖപ്രദവുമാണ്.
ഞങ്ങൾ മൃദുവായ സോഫയിൽ ഇരിക്കുന്നു.
നീന ഞങ്ങൾക്കായി ചൂടുള്ള ചായ ഉണ്ടാക്കുന്നു.
ഞങ്ങൾ ചായ കുടിക്കുകയും മധുരമുള്ള കേക്ക് കഴിക്കുകയും ചെയ്യുന്നു.
ചോക്ലേറ്റ് കേക്കിന് ശരിക്കും നല്ല രുചിയുണ്ട്.
നഗരത്തിലെ ഞങ്ങളുടെ ദിവസത്തെക്കുറിച്ച് ഞങ്ങൾ സംസാരിക്കുന്നു.
നീന എന്റെ ജോലിയെക്കുറിച്ച് ചോദിക്കുന്നു.
ഞാൻ ഓഫീസിനെക്കുറിച്ചും എന്റെ സഹപ്രവർത്തകനായ പീറ്ററിനെക്കുറിച്ചും പറയുന്നു.
നീനയും അവളുടെ ദിവസത്തെക്കുറിച്ച് പറയുന്നു.
വൈകുന്നേരം മുഴുവൻ ഞങ്ങൾ ചിരിക്കുകയും സംസാരിക്കുകയും ചെയ്യുന്നു.
അത് ശരിക്കും ഒരു നല്ല വൈകുന്നേരമാണ്.
ഇവിടെ എന്റെ പുതിയ നഗരത്തിൽ എനിക്ക് സ്വന്തം വീട്ടിലാണെന്ന് തോന്നുന്നു.
