ഇറച്ചി വറുത്തു തീരുന്നതിനിടയിൽ, ഞാൻ സ്വീകരണമുറിയിൽ മേശ ഒരുക്കുന്നു.
എന്റെ ഡൈനിംഗ് ഏരിയ വളരെ ചെറുതാണ്.
എന്നാൽ കാസ്പറിനും സാറയ്ക്കും എനിക്കും അവിടെ ആവശ്യത്തിന് സ്ഥലമുണ്ട്.
ഞാൻ അലമാരയിൽ നിന്ന് മൂന്ന് പ്ലേറ്റുകൾ എടുക്കുന്നു.
ഞാൻ അവ ആ ചെറിയ മേശപ്പുറത്ത് വെക്കുന്നു.
അതിനുശേഷം, ഞാൻ കട്ട്ലറി വെച്ചിരിക്കുന്ന ഡ്രോയർ തുറക്കുന്നു.
ഞാൻ ഫോർക്കുകളും കത്തികളും പുറത്തെടുക്കുന്നു.
ഓരോ പ്ലേറ്റിനരികിലും ഞാൻ ഒരു ഫോർക്കും ഒരു കത്തിയും വെക്കുന്നു.
വെള്ളത്തിനായി മൂന്ന് ഗ്ലാസുകൾ കൂടി ഞങ്ങൾക്ക് ആവശ്യമാണ്.
ഞാൻ അടുക്കളയിൽ നിന്ന് അവ എടുത്തുകൊണ്ടുവരുന്നു.
അവസാനം, ഞാൻ ഒരു പാക്കറ്റിൽ നിന്ന് ഇളം നീല നിറത്തിലുള്ള കുറച്ച് പേപ്പർ നാപ്കിനുകൾ എടുക്കുന്നു.
ഞാൻ അവ ഭംഗിയായി മടക്കുന്നു.
തുടർന്ന് ഓരോ പ്ലേറ്റിലും ഞാൻ ഓരോ നാപ്കിൻ വെക്കുന്നു.
ഇപ്പോൾ മേശ ഒരുങ്ങി, അതിഥികൾക്കായി തയ്യാറായിക്കഴിഞ്ഞു.
ഞാൻ തിരികെ അടുപ്പിനടുത്തേക്ക് നടക്കുന്നു.
ചൂടുള്ള പാനിൽ കിടന്ന് മീറ്റ്ബോളുകൾ ഇപ്പോഴും മൊരിയുന്നുണ്ട്.
ഞാൻ പാൻ അടുപ്പിൽ നിന്ന് മാറ്റുന്നു.
അതിഥികളെ സ്വീകരിക്കാൻ ഞാൻ പൂർണ്ണമായും തയ്യാറായിക്കഴിഞ്ഞു.
