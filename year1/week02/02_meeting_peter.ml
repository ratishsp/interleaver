ഞാൻ ഇപ്പോൾ പുതിയ ഓഫീസിനുള്ളിലാണ്.
അതൊരു വലുതും വെളിച്ചമുള്ളതുമായ മുറിയാണ്.
വാതിലിനരികിൽ സൗഹൃദമുള്ള ഒരാൾ നിൽക്കുന്നു.
അയാൾ എന്നെ നോക്കി ചിരിക്കുന്നു.
"സ്വാഗതം!" അയാൾ പറയുന്നു.
"എന്റെ പേര് പീറ്റർ."
ഞാൻ അയാൾക്ക് കൈകൊടുക്കുന്നു.
"ഹായ് പീറ്റർ, എന്റെ പേര് മായ," ഞാൻ പറയുന്നു.
പീറ്റർ ഒരു സഹപ്രവർത്തകനാണ്.
ഞങ്ങൾ ഒരുമിച്ച് ഓഫീസിലൂടെ നടക്കുന്നു.
"നിങ്ങൾക്ക് ഇവിടെയൊരു ഡെസ്ക് ഉണ്ട്," പീറ്റർ പറയുന്നു.
ഡെസ്കിന്റെ നമ്പർ പതിനാറാണ്.
"നിങ്ങൾക്കൊരു കമ്പ്യൂട്ടറും ഉണ്ട്," അയാൾ പറയുന്നു.
അയാൾ എനിക്കൊരു പുതിയ ലാപ്ടോപ്പ് തരുന്നു.
ഞാൻ എന്റെ പുതിയ സ്ഥലം നോക്കുന്നു.
എനിക്കൊരു കസേരയും വലിയൊരു മോണിറ്ററും ഉണ്ട്.
"വളരെ നന്ദി, പീറ്റർ," ഞാൻ പറയുന്നു.
എന്റെ ആദ്യത്തെ പ്രവൃത്തിദിവസത്തിനായി ഞാൻ തയ്യാറാണ്.
