Jsem za pultem poprvé.
Kavárna ještě není otevřená.
Jeden ze zkušených dobrovolníků na mě volá.
Stojíme před velkým kávovarem na espresso.
„Dnes se musíš naučit připravovat kávu,“ říká.
Nikdy předtím jsem na takovém přístroji kávu nepřipravovala.
Prvním krokem je namlít kávová zrna.
Stiskne malé tlačítko.
Přístroj s hlasitým zvukem mele hnědá zrna.
Druhým krokem je napařit mléko.
Nalije studené mléko do kovové konvičky.
Poté zapne horkou páru.
Mezitím se pozorně dívám na jeho ruce.
Mléko v konvičce rychle zteplá a zhoustne.
Očividně už kávu připravoval mnohokrát předtím.
Když jsem dnes ráno dorazila, byla jsem velmi nervózní.
Ale vysvětlil to dobře, takže už jsem většinu pochopila.
