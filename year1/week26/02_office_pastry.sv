Jag sitter vid mitt skrivbord på kontoret.
Jag kom in tidigt i dag.
Jag har redan jobbat här i ett halvår.
Plötsligt kommer Peter och Eva fram till min plats.
Peter bär en liten tårta med ett enda ljus.
"Grattis på födelsedagen, Maya!" säger de i kör.
Jag blir riktigt glad och mycket överraskad.
"Tusen tack," säger jag till dem.
Eva ler brett.
"Vi köpte tårtan på bageriet i morse," berättar hon.
"Ja, och jag har kokat kaffe till oss," tillägger Peter.
Han ställer en stor kopp kaffe på mitt bord.
"Ni är helt enkelt så gulliga," säger jag.
"När jag jobbade i Mexiko fick vi sällan tårta på morgonen."
Peter och Eva drar fram två stolar till skrivbordet.
Vi äter tårtan tillsammans, och det är en fantastisk start på min dag.
