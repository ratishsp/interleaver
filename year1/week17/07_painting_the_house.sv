Jag fortsatte nerför den smala gatan.
Jag stannade framför ett mycket gammalt hus.
Ett äldre par var ute i vårsolen.
Mannen stod i sin trädgård.
Han målade sitt gamla staket med en pensel.
Den nya färgen var ljusgul.
Hans fru satt på en träbänk i närheten.
Hon kopplade av och drack sitt varma te.
Mannen såg mig och stannade till ett ögonblick.
Han vinkade vänligt med sin pensel.
"God morgon!" sa han till mig.
"Er trädgård ser härlig ut," sa jag.
Hans fru log mot mig från sin bänk.
"Tack, vi njuter av våren," svarade hon.
Mannen målade lugnt vidare på sitt staket.
Fåglarna sjöng i deras trädgård.
Jag gick glatt vidare på min promenad.
