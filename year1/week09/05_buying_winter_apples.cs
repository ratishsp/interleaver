Dnes je na trhu hodně lidí.
Nacházím malý stánek s ovocem.
Ve stánku je mnoho košů.
Koše jsou plné tmavě červených zimních jablek.
Dívám se na malý sáček s jablky.
„Kolik stojí malý sáček?“ ptám se prodavače.
Podívá se do koše.
„Cena je dvacet korun,“ odpovídá.
Hledám v tašce peníze.
Dávám mu padesátikorunovou bankovku.
Prodavač mi podává sáček s jablky.
Pak mi vrací peníze.
Dostávám zpět přesně třicet korun v mincích.
Mince jsou tlusté a těžké.
Dávám těžké mince do kapsy kabátu.
Jablka voní velmi svěže.
Vkládám sáček do své velké nákupní tašky.
