വ്യാഴാഴ്ച വൈകുന്നേരം കൃത്യം അഞ്ചരയ്ക്ക് ഞാൻ സ്പോർട്സ് ക്ലബ്ബിൽ എത്തുന്നു.
റാക്കറ്റ് വാടകയ്ക്ക് എടുക്കാൻ ഞാൻ കൗണ്ടറിലേക്ക് പോകുന്നു.
അവിടുത്തെ ജീവനക്കാരന് ഇപ്പോൾ എന്റെ പേര് അറിയാം.
"മായ, ഇതാ റാക്കറ്റ്," അയാൾ ചിരിച്ചുകൊണ്ട് പറയുന്നു.
ഞാൻ അയാളോട് നന്ദി പറഞ്ഞിട്ട് കോർട്ടിലേക്ക് നടക്കുന്നു.
അവിടെ സാറ എനിക്കായി കാത്തിരിക്കുന്നുണ്ട്.
ഞങ്ങൾ ഉടനെ തന്നെ കളി തുടങ്ങുന്നു.
ഇന്നത്തെ കളി വളരെ കടുപ്പമുള്ളതാണ്.
ഷട്ടിൽ വളരെ വേഗത്തിൽ അങ്ങോട്ടും ഇങ്ങോട്ടും പറക്കുന്നു.
സാറ വളരെ നന്നായി കളിക്കുന്നു.
സാറയുടെ സ്മാഷുകൾ വളരെ ശക്തമാണ്.
കൂടുതൽ പോയിന്റുകളും സാറയ്ക്ക് തന്നെയാണ് കിട്ടുന്നത്.
എങ്കിലും ഞാൻ ഒട്ടും വിട്ടുകൊടുക്കുന്നില്ല.
കളി കഴിയുമ്പോൾ ഞങ്ങൾ രണ്ടുപേരും വല്ലാതെ ക്ഷീണിക്കുന്നു.
ഞങ്ങൾ നന്നായി വിയർക്കുന്നുണ്ട്.
എങ്കിലും ഞങ്ങൾ പരസ്പരം നോക്കി ചിരിക്കുന്നു.
ഞാൻ റാക്കറ്റ് കൗണ്ടറിൽ തിരികെ കൊടുക്കുന്നു.
എന്നിട്ട് സന്തോഷത്തോടെ ക്ലബ്ബിൽ നിന്ന് പുറത്തിറങ്ങുന്നു.
