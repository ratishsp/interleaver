ഞാൻ പതുക്കെ പുറത്തേക്ക് ഇറങ്ങുന്നു.
ഇന്ന് ഞായറാഴ്ചയാണ്.
ഈ തെരുവ് വളരെ ശാന്തമാണ്.
ഞാൻ മുന്നോട്ട് നടക്കുന്നു.
കൊച്ചിയിൽ ഒരു ചെറിയ കാറ്റ് വീശുന്നു.
വഴിയിൽ ഒരു നായ നിൽക്കുന്നു.
ഞാൻ എന്റെ നായ ലോലയെ ഓർക്കുന്നു.
എന്റെ കുടുംബം മെക്സിക്കോയിലാണ്.
അവരുടെ ശബ്ദം എന്റെ മനസ്സിലുണ്ട്.
ഞാൻ എന്റെ സഹോദരി സോഫിയയെ ഓർക്കുന്നു.
എന്റെ സഹോദരൻ ഡീഗോയെയും ഞാൻ ഓർക്കുന്നു.
എനിക്ക് ഇപ്പോൾ സങ്കടമില്ല.
ഞാൻ തിരികെ മുറിയിലേക്ക് നടക്കുന്നു.
