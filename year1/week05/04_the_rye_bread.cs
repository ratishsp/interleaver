Jdu k regálu s chlebem.
Hledám místní klasiku.
Chtěla bych dánský žitný chléb.
Dívám se na regál.
Nacházím žitný chléb.
Je v sáčku.
Dívám se na sáček.
Beru si ten žitný chléb.
Zvedám chléb.
Jsem překvapená.
Chléb je velmi těžký.
Připadá mi jako kámen!
Mám ráda světlý chléb.
Ale žitný chléb je tmavý a těžký.
Opatrně pokládám chléb do košíku.
Košík je teď také těžký.
