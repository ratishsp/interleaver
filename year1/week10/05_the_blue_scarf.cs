Jdu ke stolu v obchodě.
Na stole je spousta věcí.
Dnes na sobě nemám šálu.
Je mi velká zima na krk.
Vidím modrou šálu.
Je to velmi dlouhá šála.
Je z vlny.
Vezmu tu modrou šálu.
Dám si ji kolem krku.
Je úžasně teplá.
„To je pěkná barva,“ říká prodavačka.
„Ano, a je velmi hebká,“ říkám.
Podívám se na cenovku.
Stojí sto padesát korun.
To je dobrá cena za teplou šálu.
Zase si ji sundám.
„Taky si ji koupím,“ říkám jí.
Položím modrou šálu k červenému svetru.
