ഞാൻ വീണ്ടും സ്ക്രീനിൽ നോക്കുന്നു.
കോഡ് ഇപ്പോഴും കാണാനില്ല.
സാധാരണയായി എനിക്ക് സിസ്റ്റത്തിൽ പ്രശ്നങ്ങളൊന്നും ഉണ്ടാകാറില്ല.
ഞാൻ വെബ്സൈറ്റിലെ നിർദ്ദേശങ്ങൾ വായിക്കുന്നു.
അതിൽ ഇങ്ങനെ പറയുന്നു: "കോഡ് ലഭിച്ചില്ലെങ്കിൽ, പുതിയ കോഡിനായി അപേക്ഷിക്കാവുന്നതാണ്."
ഞാൻ പേജിന്റെ താഴെയുള്ള ലിങ്കിൽ അമർത്തുന്നു.
അവിടെ ഒരു ചെറിയ സന്ദേശമുണ്ട്: "ദയവായി കാത്തിരിക്കുക."
അൽപ്പസമയത്തിനുശേഷം, മേശപ്പുറത്തുള്ള എന്റെ ഫോൺ വൈബ്രേറ്റ് ചെയ്യുന്നു.
ഒടുവിൽ ഒരു പുതിയ സന്ദേശം അയയ്ക്കപ്പെട്ടിരിക്കുന്നു.
എന്റെ പുതിയ കോഡ് വായിക്കാൻ ഞാൻ ആ സന്ദേശം തുറക്കുന്നു.
അത് നാല്, ഒൻപത്, രണ്ട്, ഏഴ് ആണ്.
ഞാൻ പെട്ടെന്ന് ആ അക്കങ്ങൾ ഒഴിഞ്ഞ കള്ളിയിൽ ടൈപ്പ് ചെയ്യുന്നു.
അതിനുശേഷം, ഞാൻ "അംഗീകരിക്കുക" എന്ന ബട്ടണിൽ അമർത്തുന്നു.
പേജ് ഉടൻ തന്നെ അപ്‌ഡേറ്റ് ആകുന്നു.
സ്ക്രീനിൽ ഒരു വലിയ പച്ച ബാനർ കാണിക്കുന്നു.
അതിലെ വാചകം ഇങ്ങനെയാണ്: "നിങ്ങളുടെ പ്രൊഫൈൽ ഇപ്പോൾ അപ്‌ഡേറ്റ് ചെയ്തിരിക്കുന്നു."
ഞാൻ പുഞ്ചിരിച്ചുകൊണ്ട് വെബ്സൈറ്റ് ക്ലോസ് ചെയ്യുന്നു.
അത്തരത്തിലുള്ള പ്രായോഗിക കാര്യങ്ങൾ തീർപ്പാകുമ്പോൾ എപ്പോഴും ഒരു സന്തോഷമാണ്.
