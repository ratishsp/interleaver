ഒരു ചുവന്ന സിറ്റി ബസ് വരുന്നു.
ഞാൻ ബസ്സിൽ കയറുന്നു.
ബസ്സിൽ അധികം ആളുകൾ ഇല്ല.
വാതിലിന്റെ അടുത്ത് ഒരു സ്ത്രീ ഇരിക്കുന്നുണ്ട്.
അവർ ചിരിക്കുന്നു.
എനിക്ക് മെട്രോ സ്റ്റേഷനിലേക്ക് പോകണം.
ഞാൻ അവരോട് ചോദിക്കുന്നു.
"നമസ്കാരം, ഈ ബസ് മെട്രോ സ്റ്റേഷനിൽ പോകുമോ?"
"അതെ, ഇത് അവിടെ പോകും," അവർ പറയുന്നു.
"നന്ദി," ഞാൻ പറയുന്നു.
അവരുടെ അടുത്ത് ഒരു സീറ്റ് ഒഴിവുണ്ട്.
ഞാൻ ആ സീറ്റിൽ ഇരിക്കുന്നു.
ബസ്സ് മുന്നോട്ട് പോകുന്നു.
ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
എനിക്ക് മെട്രോ സ്റ്റേഷനിൽ ഇറങ്ങണം.
