"En påse?" frågar expediten.
"Nej tack," säger jag.
Jag behöver ingen påse.
Jag tar på mig de nya kläderna direkt.
Först tar jag på mig den tjocka, röda tröjan.
Sedan tar jag på mig den mörkblå vinterjackan.
Jag drar upp dragkedjan på den varma jackan.
Därefter tar jag den långa, blå halsduken.
Jag virar den runt halsen.
Till sist tar jag på mig de nya, svarta handskarna.
Nu har jag alla mina varma kläder på mig.
Jag ler och säger hejdå.
Jag går ut ur butiken.
Jag står ute på den kalla gatan igen.
Det är isande kallt.
Vinden blåser hårt.
Men jag fryser inte alls.
Nu är jag redo för vintern.
