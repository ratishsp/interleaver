Podchodzę do kasy z moimi nowymi ubraniami.
Ekspedientka uśmiecha się do mnie przyjaźnie.
– Czy to wszystko? – pyta.
– Tak, to wszystko – odpowiadam.
Skanuje wszystkie moje nowe rzeczy.
Jest tam sweter, kurtka, szalik i rękawiczki.
– Teraz pani nie zmarznie – mówi radośnie.
– To będzie tysiąc pięćset koron, proszę.
Ubrania są drogie, ale bardzo ciepłe.
Wyciągam kartę płatniczą.
– Płacę kartą – mówię.
– Może pani zapłacić tutaj – mówi.
Wskazuje na małe, czarne urządzenie.
Trzymam kartę nad urządzeniem.
Pika, a płatność zostaje zatwierdzona.
– Czy chce pani paragon? – pyta ekspedientka.
– Nie, dziękuję – odpowiadam.
Teraz mam dużo ładnych zimowych ubrań.
