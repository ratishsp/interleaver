ഞാൻ ഒരു വലിയ പാർക്കിലൂടെ വീട്ടിലേക്ക് നടക്കുന്നു.
ഒരു മണിക്കൂർ മുമ്പ് ഞാൻ ഒരു മ്യൂസിയത്തിലായിരുന്നു.
ഇപ്പോൾ എനിക്ക് ഈ നല്ല കാലാവസ്ഥ ഒന്ന് ആസ്വദിക്കണം.
ഒരു വാഫിൾ ഐസ്ക്രീം വാങ്ങാനായി ഞാൻ ഒരു ചെറിയ കിയോസ്കിനടുത്ത് നിൽക്കുന്നു.
"ഇതാ, നിങ്ങളുടെ ഐസ്ക്രീം," കിയോസ്കിലെ ആൾ പറയുന്നു.
"വളരെ നന്ദി," എന്ന് മറുപടി നൽകി ഞാൻ ഐസ്ക്രീം വാങ്ങുന്നു.
ഞാൻ പാർക്കിലെ തടാകത്തിന്റെ തീരത്തുകൂടി പതുക്കെ നടക്കുന്നു.
ഈ വാഫിൾ ഐസ്ക്രീം കണ്ടിട്ട് വളരെ നല്ലതാണെന്ന് തോന്നുന്നു.
പെട്ടെന്ന് എന്റെ മുകളിൽ നിന്ന് ഞാൻ ഒരു വലിയ ശബ്ദം കേൾക്കുന്നു.
ഒരു വലിയ കടൽക്കാക്ക എന്റെ നേരെ താഴേക്ക് കുതിച്ചുവരുന്നു.
അതിന് എന്റെ ഐസ്ക്രീം മോഷ്ടിക്കണം!
ഞാൻ വേഗത്തിൽ കുനിഞ്ഞ് കൈകൊണ്ട് എന്റെ ഐസ്ക്രീം മറയ്ക്കുന്നു.
ആ പക്ഷി എന്റെ ഭക്ഷണം മോഷ്ടിക്കാൻ പോകുന്നില്ല.
കടൽക്കാക്ക അരികിലൂടെ പറന്നുപോയി പുല്ലിൽ ഇറങ്ങുന്നു.
ഒരു ബെഞ്ചിലിരിക്കുന്ന സ്ത്രീ ചിരിക്കുന്നു.
"അവ ഇന്ന് വളരെ കുസൃതിക്കാരാണ്," അവർ പറയുന്നു.
"അതെ, തീർച്ചയായും അതെ," ഞാനും ചിരിച്ചുകൊണ്ട് പറയുന്നു.
മുന്നോട്ട് നടക്കുന്നതിനിടയിൽ ഞാൻ എന്റെ ഐസ്ക്രീം വേഗത്തിൽ കഴിച്ചുതീർക്കുന്നു.
