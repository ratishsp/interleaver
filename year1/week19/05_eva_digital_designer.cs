Později odpoledne jdu k Evině stolu.
Je digitální designérka týmu.
Do dneška jsem s ní nepracovala.
„Ahoj Mayo, pojď se podívat,“ říká.
Ukazuje na svou velkou obrazovku.
Vidím nějaké krásné skici našeho nového softwaru.
Barvy jsou klidné a design je velmi čistý.
„To vypadá opravdu dobře,“ říkám.
„Děkuji,“ odpovídá Eva s úsměvem.
Vysvětluje mi svou práci.
„Jako digitální designérka pracuji už od univerzity,“ říká.
„Vždy se zaměřuji na uživatelskou zkušenost.“
Ukazuje mi, jak se uživatel proklikává programem.
„Jeho používání musí být snadné a logické,“ vysvětluje.
Často se dívám jen na samotný kód.
Ale její design je pro projekt nesmírně důležitý.
Bavíme se ještě trochu o našich společných úkolech.
Těším se, až naprogramuji její krásný design.
