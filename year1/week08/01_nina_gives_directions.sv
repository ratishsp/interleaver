Det är lördag morgon.
Solen skiner över staden.
Jag går ner på gatan.
Min granne, Nina, står utanför vår byggnad.
"God morgon, Maya", säger hon och ler.
"God morgon, Nina", svarar jag.
"Jag är ledig i dag", berättar jag för henne.
"Jag ska ut på stan."
"Vart ska du gå?" frågar Nina.
"Jag går ner till vattnet", säger jag.
"Men jag kan inte vägen."
Nina pekar nerför gatan.
"Det är lyckligtvis mycket enkelt", säger hon.
"Gå rakt fram här."
"Och sväng vänster vid parken."
"Då kommer du rakt ner till hamnen."
"Tack så mycket för hjälpen, Nina", säger jag.
"Varsågod, och trevlig tur", svarar hon.
Jag vinkar till henne.
Jag börjar min promenad mot vattnet.
