ഇന്ന് വെള്ളിയാഴ്ച ഉച്ചതിരിഞ്ഞ സമയമാണ്, എനിക്ക് ജോലിയിൽ നിന്ന് അവധിയാണ്.
ഞാൻ തെരുവിലൂടെ നടന്ന് ഒരു പൂക്കടയുടെ മുന്നിൽ നിൽക്കുന്നു.
ഞാൻ ഈവയ്ക്ക് ഒരു സമ്മാനം വാങ്ങാൻ ഉദ്ദേശിക്കുന്നു.
ഞാൻ വാതിൽ തുറന്ന് ആ ചെറിയ കടയ്ക്കുള്ളിലേക്ക് കയറുന്നു.
"നമസ്കാരം," വലിയൊരു പുഞ്ചിരിയോടെ കടക്കാരൻ പറയുന്നു.
"നമസ്കാരം," ഞാൻ മറുപടി നൽകുന്നു.
ഞാൻ അവിടെയുള്ള മനോഹരമായ നിരവധി പൂക്കൾ നോക്കുന്നു.
ഈവയ്ക്ക് എപ്പോഴും നിറങ്ങൾ ഇഷ്ടമാണെന്ന് ഞാൻ കരുതുന്നു.
അവൾ ഒരു ഡിസൈനറാണ്, അതിനാൽ അവൾക്ക് നിറപ്പകിട്ടുള്ള എന്തെങ്കിലും മിക്കവാറും ഇഷ്ടപ്പെടും.
ഞാൻ മഞ്ഞ ട്യൂലിപ്പ് പൂക്കളുള്ള ഒരു വലിയ ബൊക്കെ കണ്ടെത്തുന്നു.
"എനിക്ക് ഈ ബൊക്കെ വാങ്ങണം," എന്ന് പറഞ്ഞ് ഞാൻ ആ ട്യൂലിപ്പുകൾ ചൂണ്ടിക്കാണിക്കുന്നു.
"അതൊരു വളരെ നല്ല തിരഞ്ഞെടുപ്പാണ്," കടക്കാരൻ പറയുന്നു.
അയാൾ ആ പൂക്കൾ ഭംഗിയുള്ള ഒരു പേപ്പറിൽ പൊതിയുന്നു.
"ഇതിന് നൂറ്റി അമ്പത് ക്രോണർ ആകും," അയാൾ പറയുന്നു.
ഞാൻ എന്റെ കാർഡ് എടുത്ത് പൂക്കൾക്കുള്ള പണം നൽകുന്നു.
"ഞാൻ ഇന്ന് രാത്രി ഒരു അത്താഴവിരുന്നിന് പോകുകയാണ്," ഞാൻ അയാളോട് പറയുന്നു.
"എങ്കിൽ നിങ്ങളുടെ സുഹൃത്തിന് തീർച്ചയായും സന്തോഷമാകും," അയാൾ മറുപടി പറയുന്നു.
ഞാൻ ആ ബൊക്കെയും വാങ്ങി കടയുടെ പുറത്തേക്ക് ഇറങ്ങുന്നു.
ഇനി എനിക്ക് എന്റെ ബസ് സ്റ്റോപ്പ് ഒന്ന് കണ്ടുപിടിക്കണം.
