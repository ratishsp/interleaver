ഞാൻ ബസ് സ്റ്റോപ്പിലേക്ക് നടക്കുന്നു.
സ്റ്റോപ്പിൽ കുറച്ചു ആളുകൾ ഉണ്ട്.
ഇൻഫോപാർക്കിലേക്കുള്ള ബസ് വരുന്നു.
ഞാൻ ആ ബസ്സിൽ കയറുന്നു.
കണ്ടക്ടർ എൻ്റെ അടുത്തേക്ക് വരുന്നു.
"എങ്ങോട്ടാണ്?" അയാൾ ചോദിക്കുന്നു.
"ഇൻഫോപാർക്കിലേക്ക്."
"ഒരു ടിക്കറ്റ്," ഞാൻ മറുപടി പറയുന്നു.
"ഇരുപതു രൂപ," അയാൾ പറയുന്നു.
ഞാൻ ഇരുപതു രൂപ അയാൾക്ക് കൊടുക്കുന്നു.
അയാൾ എനിക്ക് ടിക്കറ്റ് തരുന്നു.
എനിക്ക് ജനലിനടുത്ത് ഒരു സീറ്റ് കിട്ടുന്നു.
ഞാൻ ആ സീറ്റിൽ ഇരിക്കുന്നു.
ബസ് തിരക്കുള്ള നഗരത്തിലൂടെ പോകുന്നു.
ഞാൻ ജനലിലൂടെ പുറത്തേക്ക് നോക്കുന്നു.
കൊച്ചിയിലെ രാവിലെയുള്ള കാഴ്ചകൾ എനിക്ക് ഇഷ്ടമാണ്.
