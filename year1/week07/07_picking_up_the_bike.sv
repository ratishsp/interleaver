Det är torsdag eftermiddag.
Jag är ledig från jobbet.
Jag går till cykelmekanikern.
Klockan är kvart i fyra.
Mekanikern står i butiken.
"Hej," säger jag.
Han rullar ut cykeln till mig.
"Din cykel är klar," säger han.
"Tack så mycket," säger jag.
Cykeln ser riktigt fin ut.
Däcken är hårda nu.
Jag leder ut cykeln på gatan.
Solen skiner i dag.
Jag sätter mig på cykeln.
Jag cyklar ofta i Köpenhamn.
Det är väldigt enkelt.
Nu cyklar jag glad mot frisören.
Min tid är klockan halv fem.
Jag ser fram emot det.
