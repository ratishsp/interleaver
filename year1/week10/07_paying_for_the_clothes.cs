Jdu k pokladně se svým novým oblečením.
Prodavačka se na mě laskavě usměje.
„Je to všechno?“ ptá se.
„Ano, to je všechno,“ odpovídám.
Naskenuje všechny moje nové věci.
Je tam svetr, bunda, šála a rukavice.
„Teď už nezmrznete,“ říká vesele.
„Bude to tisíc pět set korun, prosím.“
Oblečení je drahé, ale je velmi teplé.
Vytahuji svou platební kartu.
„Platím kartou,“ říkám.
„Můžete zaplatit tady,“ říká.
Ukáže na malý černý přístroj.
Podržím svou kartu nad přístrojem.
Pípne to a platba je schválena.
„Chcete účtenku?“ ptá se prodavačka.
„Ne, děkuji,“ odpovídám.
Teď vlastním spoustu pěkného zimního oblečení.
