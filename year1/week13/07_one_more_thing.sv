Jag äter den sista biten av min kanelbulle.
Den smakar riktigt gott.
Men den är också väldigt söt.
Min kaffekopp är helt tom.
Jag är plötsligt väldigt törstig.
Jag vill gärna ha lite kallt vatten.
En ung man går förbi mitt bord.
Han jobbar här på caféet.
Han samlar in tomma koppar och tallrikar.
Jag fångar hans blick.
Han stannar vid mitt bord och ler.
"Ursäkta," säger jag artigt.
"Ja?" svarar den unge mannen.
"Får jag be om ett glas kranvatten?" frågar jag.
"Ja, självklart," säger han.
"Tack så mycket," säger jag.
Han tar min tomma tallrik och kopp.
Han går tillbaka till disken.
Lite senare kommer han med ett kallt glas vatten.
