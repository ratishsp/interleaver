Podchodzę do stołu w sklepie.
Na stole jest dużo rzeczy.
Nie mam dzisiaj na sobie szalika.
Jest mi bardzo zimno w szyję.
Widzę niebieski szalik.
To bardzo długi szalik.
Jest zrobiony z wełny.
Biorę niebieski szalik.
Owijam go wokół szyi.
Jest cudownie ciepły.
„To ładny kolor” – mówi ekspedientka.
„Tak, i jest bardzo miękki” – mówię.
Patrzę na metkę z ceną.
Kosztuje sto pięćdziesiąt koron.
To dobra cena za ciepły szalik.
Zdejmuję go ponownie.
„Też go kupuję” – mówię do niej.
Kładę niebieski szalik razem z czerwonym swetrem.
