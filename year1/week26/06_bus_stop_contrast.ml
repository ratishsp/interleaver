ഞാൻ ഒറ്റയ്ക്ക് കടൽത്തീരത്തേക്ക് നടന്നുപോകുന്നു.
ഇപ്പോൾത്തന്നെ വൈകുന്നേരമായി, എന്നാൽ ആകാശത്ത് ഇപ്പോഴും നല്ല വെളിച്ചമുണ്ട്.
സൂര്യൻ ഇതുവരെ അസ്തമിക്കാൻ തുടങ്ങിയിട്ടില്ല.
ഞാൻ മുകളിലേക്ക് നോക്കി ജനുവരിയെക്കുറിച്ച് ഓർക്കുന്നു.
അന്നൊക്കെ ജോലി കഴിഞ്ഞതിനുശേഷം ഞാൻ പലപ്പോഴും ബസ്സിനായി കാത്തുനിൽക്കാറുണ്ടായിരുന്നു.
സമയം ഉച്ചകഴിഞ്ഞ് നാലുമണി മാത്രമേ ആയിട്ടുണ്ടായിരുന്നുള്ളൂ.
പക്ഷേ അപ്പോഴേക്കും എല്ലായിടത്തും കൂരിരുട്ടായിരുന്നു.
ഞാൻ ബസ് സ്റ്റോപ്പിൽ തണുത്തുവിറച്ചു നിന്നു.
ഞാനിപ്പോൾ ഇവിടെ താമസം തുടങ്ങിയിട്ട് അര വർഷമായി.
എല്ലാം മാറിയിരിക്കുന്നു.
മെക്സിക്കോയിൽ, സൂര്യൻ എല്ലായ്പ്പോഴും ഏതാണ്ട് ഒരേ സമയത്താണ് അസ്തമിച്ചിരുന്നത്.
വർഷം മുഴുവനും അങ്ങനെത്തന്നെയായിരുന്നു.
ഇവിടെ, ഇതിനുമുമ്പ് ഇത്രയും നീണ്ട പകലുകൾ ഞാൻ അനുഭവിച്ചിട്ടില്ല.
വെളിച്ചം നഗരത്തിന് തികച്ചും പുതിയൊരു ജീവൻ നൽകിയിരിക്കുന്നു.
ഞാൻ എന്റെ ചൂടുള്ള സ്വെറ്റർ ഇടുന്നു.
ആകാശത്ത് വെളിച്ചമുണ്ടെങ്കിലും, കടലിൽ നിന്ന് വീശുന്ന കാറ്റിന് ചെറിയ തണുപ്പുണ്ട്.
തീക്കുണ്ഠം കാണാൻ ഞാൻ കാത്തിരിക്കുകയാണ്.
എന്റെ സുഹൃത്തുക്കൾക്കൊപ്പമുള്ള മനോഹരമായ ഒരു സായാഹ്നമായിരിക്കും അത്.
