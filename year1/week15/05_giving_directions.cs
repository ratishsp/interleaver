Mám po práci.
Vycházím na velké náměstí.
Ve městě je dnes hodně lidí.
Přichází ke mně nějaký muž.
Má velký fotoaparát.
Je to turista.
Usmívá se a říká ahoj.
„Kde je muzeum?“ ptá se turista.
To muzeum dobře znám.
Není to daleko.
Ukazuji dolů ulicí.
„Půjdete rovně,“ vysvětluji.
„Pak zahnete doleva.“
„Muzeum je na pravé straně.“
„Moc děkuji za pomoc,“ říká muž.
„Není zač,“ odpovídám vesele.
Jde dolů ulicí.
Jdu dál směrem k pekařství.
