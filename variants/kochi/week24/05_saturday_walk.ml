പ്രഭാതഭക്ഷണത്തിന് ശേഷം ഞാൻ ടോമിയെ നടക്കാൻ കൊണ്ടുപോകുന്നു.
പുറത്ത് ചെറിയ മഴ പെയ്യുന്നുണ്ട്.
ഞാൻ ടോമിയുടെ കഴുത്തിൽ ലീഷ് ഇടുന്നു.
തിരക്കുള്ള റോഡിനടുത്ത് അവൻ ഓടാൻ പാടില്ല.
അവൻ എപ്പോഴും ലീഷിൽ തന്നെ നടക്കണം.
പെട്ടെന്ന്, ഞങ്ങളുടെ മുന്നിൽ ഒരു തെരുവുപൂച്ച വരുന്നു.
അവൻ അതിനെ പിടിക്കാൻ ലീഷ് വേഗത്തിൽ വലിക്കുന്നു.
ഞാൻ അവനെ പുറകോട്ട് വലിക്കുന്നു.
"ടോമി, നിൽക്ക്!" ഞാൻ അവനോട് പറയുന്നു.
"നീ അതിനെ ഓടിക്കാൻ പാടില്ല."
"അവിടെ നിൽക്ക്, കാത്തിരിക്ക്."
അവൻ അവിടെ ഇരുന്ന് ശാന്തനാകുന്നു.
ഞങ്ങൾ വേഗം ഫ്ലാറ്റിലേക്ക് മടങ്ങുന്നു.
ടോമി അവന്റെ കിടക്കയിൽ സുഖമായി കിടക്കുന്നു.
അവൻ നല്ല കുട്ടിയാണ്.
ഞാൻ ഒരു ചൂട് ചായ ഉണ്ടാക്കി അവന്റെ കൂടെ മഴ നോക്കി ഇരിക്കുന്നു.
