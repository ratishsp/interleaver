റോഡിൽ നല്ല തിരക്കുണ്ട്.
അപ്പോൾ ഒരു ടൂറിസ്റ്റ് എന്റെ അടുത്തേക്ക് വരുന്നു.
അയാൾ ഫോണിൽ ഒരു മാപ്പ് നോക്കുന്നുണ്ട്.
അയാൾ ചോദിക്കുന്നു, "ക്ഷമിക്കണം, മെട്രോ സ്റ്റേഷൻ എവിടെയാണ്?"
"മെട്രോ സ്റ്റേഷൻ ഇവിടെ നിന്ന് കുറച്ച് ദൂരെയാണ്," ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ നേരെ മുന്നോട്ട് കൈ ചൂണ്ടുന്നു.
ഞാൻ പറയുന്നു, "നിങ്ങൾ ഈ റോഡിലൂടെ നേരെ പോകൂ."
"അവിടെ നിന്ന് ബസ് നേരെ മെട്രോ സ്റ്റേഷനിലേക്ക് പോകുന്നു."
"ബസ്സുകൾ ഇടയ്ക്കിടെ വരും."
അയാൾ ചോദിക്കുന്നു, "അത് ദൂരെയാണോ?"
"ബസ്സിൽ ആണെങ്കിൽ ദൂരം ഇല്ല," ഞാൻ പറയുന്നു.
"ഏകദേശം പത്ത് മിനിറ്റ് മതി."
അയാൾ ചിരിക്കുന്നു.
അയാൾ പറയുന്നു, "വളരെ നന്ദി."
ഞാൻ ചിരിച്ചുകൊണ്ട് പറയുന്നു, "സന്തോഷം."
അയാൾ മുന്നോട്ട് നടക്കുന്നു.
ഞാൻ എന്റെ വഴിക്ക് നടക്കുന്നു.
