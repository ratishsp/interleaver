ഞാൻ എന്റെ വാതിൽ തുറക്കുന്നു.
ഞാൻ പുറത്തേക്ക് വരുന്നു.
അടുത്ത വാതിൽ തുറക്കുന്നു.
അവിടെ ഒരു സ്ത്രീ ഉണ്ട്.
അവർ ചിരിക്കുന്നു.
"നമസ്കാരം, നിങ്ങൾ പുതിയ ആളാണോ?" അവർ ചോദിക്കുന്നു.
"അതെ, ഞാൻ ഇവിടെ പുതിയതാണ്," ഞാൻ പറയുന്നു.
"എന്റെ പേര് അനിത ആണ്," അവർ പറയുന്നു.
"നിങ്ങളുടെ പേര് എന്താണ്?"
"എന്റെ പേര് മായ ആണ്," ഞാൻ പറയുന്നു.
"നിങ്ങൾ എവിടെ നിന്നാണ്?" അനിത ചോദിക്കുന്നു.
"ഞാൻ മെക്സിക്കോയിൽ നിന്നാണ്."
"മെക്സിക്കോ!"
"അത് വളരെ ദൂരെയാണോ?"
"അതെ, അത് വളരെ ദൂരെയാണ്."
"നിങ്ങൾക്ക് ഇവിടെ ജോലി ഉണ്ടോ?" അനിത ചോദിക്കുന്നു.
"അതെ, ഞാൻ ഒരു സോഫ്റ്റ്‌വെയർ എഞ്ചിനീയറാണ്."
അനിതയ്ക്ക് വലിയ സന്തോഷം ഉണ്ട്.
"കൊച്ചിയിലേക്ക് സ്വാഗതം!" അവർ പറയുന്നു.
അനിത വളരെ നല്ല ഒരു സ്ത്രീയാണ്.
എനിക്ക് ഇപ്പോൾ ഇവിടെ ഒരു സുഹൃത്ത് ഉണ്ട്.
