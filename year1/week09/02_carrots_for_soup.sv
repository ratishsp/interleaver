Jag går över till ett grönsaksstånd.
Jag lagar en varm soppa i dag.
Jag tittar på de många grönsakerna på bordet.
Jag pekar på några stora vintermorötter.
Jag behöver morötter till min soppa.
Det står en försäljare bakom bordet.
"Hej," säger han.
"Hej," svarar jag.
"Hur mycket kostar morötterna?" frågar jag.
"De kostar femton kronor per kilo," svarar försäljaren.
Femton kronor är ett bra pris.
"Jag tar ett kilo, tack," säger jag.
Försäljaren väger morötterna.
Han lägger dem i en papperspåse.
Han ger mig påsen.
Jag betalar de femton kronorna.
Jag lägger ner påsen i min stora väska.
Jag ser fram emot den varma soppan.
