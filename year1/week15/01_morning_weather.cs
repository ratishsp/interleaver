Probouzím se brzy.
Je teprve šest hodin.
Je nový den.
Pomalu vstávám.
Jdu k oknu.
Dívám se ven na město.
Venku je stále tma a zima.
Zima je stále tady.
Jdu do koupelny.
Myji si obličej.
Čistím si zuby.
Pak se oblékám.
Oblékám si silný, teplý svetr.
Je perfektní na chladný den.
Jdu do kuchyně.
Připravuji si šálek teplé kávy.
Jím krajíc chleba se sýrem.
Teď jsem úplně vzhůru.
Jsem připravená na nový den.
