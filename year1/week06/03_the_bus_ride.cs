Venku na ulici čekám na svůj autobus.
Dnes je zima.
Na zastávce stojí mnoho lidí.
Přijíždí červený autobus.
Dveře se otevírají.
Nastupuji do autobusu.
Tady si skenuji cestovní kartu.
Řidič autobusu se na mě dívá.
„Dobré ráno,“ říká řidič.
„Dobré ráno,“ odpovídám.
Procházím autobusem.
Nacházím volné místo u okna.
Sedám si.
Autobus projíždí městem.
Za oknem vidím mnoho lidí.
Rychle jedou na kole po cyklostezce.
Projíždíme kolem krásného parku.
V parku se procházejí lidé.
Teď autobus zastavuje u mého pracoviště.
Vystupuji a jdu do kanceláře.
