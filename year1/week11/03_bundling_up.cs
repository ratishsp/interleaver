Dnes je chladno.
Je zima a ráno je tma.
Stojím ve svém pokoji a chystám se.
Nacházím své teplé zimní oblečení.
Nejdřív si oblékám silný svetr.
Přetahuji si ho přes hlavu.
Svetr je příjemně teplý a měkký.
Beru si také dlouhou šálu.
Pevně si ji omotávám kolem krku.
Poté jdu do své předsíně.
Ze schodiště táhne chladný průvan.
Beru si svou těžkou zimní bundu.
Zapínám si bundu úplně nahoru.
Zastavuje studený vzduch.
Dnes je důležité zůstat v teple.
Tak v tom chladu nezmrznu.
Beru si s sebou také svůj deštník.
Konečně jsem připravená vyrazit na svůj autobus.
Otevírám vchodové dveře a vycházím do zimy.
