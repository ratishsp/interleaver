Teraz potrzebuję mleka.
Idę długą alejką.
Patrzę na półkę.
Widzę wodę i sok.
Ale nie mogę znaleźć mleka.
Patrzę wszędzie.
Widzę mężczyznę.
On pracuje w supermarkecie.
Zatrzymuję pracownika i uśmiecham się.
"Przepraszam" – mówię.
"Chciałabym mleko."
"Gdzie jest mleko?"
Mężczyzna wskazuje na tył sklepu.
"Dział nabiałowy jest tam" – mówi.
"Bardzo dziękuję" – odpowiadam.
Idę tam.
W końcu znajduję lodówkę i mleko.
Biorę karton i wkładam go do koszyka.
