വ്യാഴാഴ്ച വൈകുന്നേരമാണ്, ഞാൻ സ്പോർട്സ് ഹാളിലാണ്.
എല്ലാ ആഴ്ചയും ഞാൻ ഇവിടെ ബാഡ്മിൻ്റൺ കളിക്കാറുണ്ട്.
ഞാൻ ക്ലബ്ബിലെ എൻ്റെ സുഹൃത്തായ സാറയ്ക്ക് എതിരെ ഒരു മത്സരം കളിക്കുകയാണ്.
മത്സരം വളരെ ആവേശകരവും ഇഞ്ചോടിഞ്ച് പോരാട്ടവുമാണ്.
ഞങ്ങൾ അവസാനത്തെ പോയിൻ്റിന് വേണ്ടിയാണ് കളിക്കുന്നത്.
അവൾ ഷട്ടിൽകോക്ക് ശക്തിയായി അടിക്കുന്നു.
അത് നെറ്റിന് മുകളിലൂടെ അതിവേഗം എൻ്റെ നേർക്ക് പറന്നു വരുന്നു.
അതിൽ എത്താൻ ഞാൻ കോർട്ടിലൂടെ ഒരു വലിയ ചുവടുവെക്കുന്നു.
എൻ്റെ സർവ്വ ശക്തിയുമെടുത്ത് ഞാൻ എൻ്റെ റാക്കറ്റ് വീശുന്നു.
ഞാൻ ഷട്ടിൽകോക്കിൽ കൃത്യമായി അടിക്കുന്നു.
അത് നേരെ ആ വെള്ള വരയിലാണ് വീഴുന്നത്.
ആ പോയിൻ്റ് എനിക്കുള്ളതാണ്, അങ്ങനെ ഞാൻ മത്സരത്തിൽ വിജയിക്കുന്നു.
നെറ്റിന് അപ്പുറത്ത് നിന്ന് സാറ പുഞ്ചിരിച്ചുകൊണ്ട് പറയുന്നു: "നല്ലൊരു മത്സരമായിരുന്നു!"
"വളരെ നന്ദി, അതൊരു ബുദ്ധിമുട്ടുള്ള പോയിൻ്റായിരുന്നു," ഞാൻ മറുപടി നൽകുന്നു.
ശ്വാസം നേരെയാക്കാൻ ഞാൻ കുറച്ചുനേരം നെറ്റിനടുത്ത് നിൽക്കുന്നു.
ഞാൻ വല്ലാതെ വിയർക്കുന്നുണ്ട്, എനിക്കൊരു ഇടവേള വേണം.
ബാഗിൽ നിന്ന് എൻ്റെ ചുവന്ന വാട്ടർ ബോട്ടിൽ ഞാൻ കണ്ടെത്തുന്നു.
ഞാൻ ധാരാളം തണുത്ത വെള്ളം കുടിക്കുന്നു.
ഓഫീസിലെ നീണ്ട ഒരു ദിവസത്തിന് ശേഷം ഇതുപോലെ ശരീരം അനങ്ങുന്നത് വളരെ നല്ലതാണ്.
