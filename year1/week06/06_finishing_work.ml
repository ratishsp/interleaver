ഓഫീസിൽ ഇപ്പോൾ വൈകുന്നേരമാണ്.
ഞാൻ എന്റെ സ്ക്രീനിലേക്ക് നോക്കുന്നു.
ഞാൻ അവസാനത്തെ കോഡ് എഴുതുന്നു.
ഇപ്പോൾ ടാസ്ക് പൂർത്തിയായി.
ഞാൻ പുഞ്ചിരിക്കുന്നു.
ഞാൻ എന്റെ കമ്പ്യൂട്ടർ അടയ്ക്കുന്നു.
ഞാൻ അത് എന്റെ ബാഗിൽ വെക്കുന്നു.
പിന്നെ ഞാൻ എന്റെ സാധനങ്ങൾ പാക്ക് ചെയ്യുന്നു.
ഞാൻ എഴുന്നേൽക്കുന്നു.
എന്റെ സഹപ്രവർത്തകൻ പീറ്റർ അവന്റെ ഡെസ്കിൽ ഇരിക്കുന്നു.
ഞാൻ അവന്റെ അടുത്തേക്ക് നടക്കുന്നു.
"ഗുഡ് ബൈ, പീറ്റർ," ഞാൻ പറയുന്നു.
"ഗുഡ് ബൈ, മായ," പീറ്റർ പറയുന്നു.
"നല്ലൊരു സായാഹ്നം ആശംസിക്കുന്നു," അവൻ പറയുന്നു.
"നന്ദി, നിനക്കും അങ്ങനെ തന്നെ," ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ ഓഫീസിൽ നിന്ന് പുറത്തേക്ക് നടക്കുന്നു.
പുറത്ത് ഇടനാഴിയിൽ നിന്ന് ഞാൻ എലിവേറ്ററിൽ താഴേക്ക് പോകുന്നു.
അവസാനം, ഞാൻ കെട്ടിടത്തിൽ നിന്ന് പുറത്തേക്ക് നടക്കുന്നു.
ഇപ്പോൾ ഞാൻ വീട്ടിലേക്ക് പോകുന്നു.
