സൗമ്യനായ ഒരു ഡോക്ടർ വാതിൽ തുറന്ന് എൻ്റെ പേര് വിളിക്കുന്നു.
ഞാൻ അദ്ദേഹത്തിൻ്റെ പ്രകാശമുള്ള ഓഫീസിലേക്ക് പോകുന്നു.
ഞങ്ങൾ അദ്ദേഹത്തിൻ്റെ ഡെസ്കിനരികിൽ ഇരിക്കുന്നു.
"ഇന്ന് നിങ്ങൾക്ക് എങ്ങനെയുണ്ട്?" അദ്ദേഹം ചോദിക്കുന്നു.
"എനിക്ക് ശരിക്കും സുഖമില്ല," ഞാൻ മറുപടി പറയുന്നു.
ഡോക്ടർ എന്നെ നോക്കുന്നു.
"എവിടെയാണ് വേദനിക്കുന്നത്?" അദ്ദേഹം സൗമ്യമായി ചോദിക്കുന്നു.
ഞാൻ എൻ്റെ തൊണ്ട ചൂണ്ടിക്കാണിക്കുന്നു.
"എൻ്റെ തൊണ്ടയ്ക്ക് നല്ല വേദനയുണ്ട്," ഞാൻ വിശദീകരിക്കുന്നു.
"അത് വല്ലാതെ വരണ്ടിരിക്കുന്നു."
ഡോക്ടർ തലയാട്ടുകയും ശ്രദ്ധയോടെ കേൾക്കുകയും ചെയ്യുന്നു.
"എൻ്റെ തലയ്ക്കും നല്ല ഭാരമുണ്ട്," ഞാൻ തുടരുന്നു.
ഞാൻ എൻ്റെ മുഖത്ത് തൊടുന്നു.
"കൂടാതെ എൻ്റെ കണ്ണുകൾ പൂർണ്ണമായും ചുവന്നിരിക്കുന്നു."
അവ എപ്പോഴും ചൊറിയുന്നുണ്ട്.
"നിങ്ങൾ തീർച്ചയായും വിശ്രമിക്കണം," അദ്ദേഹം പറയുന്നു.
അദ്ദേഹം ഒരു ചെറിയ ഫ്ലാഷ്‌ലൈറ്റ് തെളിക്കുന്നു.
"ഞാൻ നിങ്ങളെ ഒന്നുകൂടി അടുത്തു നോക്കട്ടെ," അദ്ദേഹം പറയുന്നു.
