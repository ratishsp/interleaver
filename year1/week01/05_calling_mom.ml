ഞാനിപ്പോൾ സ്വീകരണമുറിയിലാണ്.
അവിടെ ചെറിയൊരു സോഫയുണ്ട്.
ഞാൻ മെക്സിക്കോയിലുള്ള എൻ്റെ അമ്മയെ വിളിക്കുന്നു.
"ഹായ് അമ്മേ," ഞാൻ പറയുന്നു.
"ഹായ് മായ," എൻ്റെ അമ്മ പറയുന്നു.
"നീ എവിടെയാണ്?" അവർ ചോദിക്കുന്നു.
"ഞാൻ കോപ്പൻഹേഗനിലാണ്," ഞാൻ മറുപടി പറയുന്നു.
"ഞാനിപ്പോൾ അപ്പാർട്ട്മെൻ്റിലാണ്."
"അത് വളരെ നല്ലത്," എൻ്റെ അമ്മ പറയുന്നു.
"അത് വലുതാണോ?" അവർ ചോദിക്കുന്നു.
"അല്ല, അത് ചെറുതാണ്," ഞാൻ മറുപടി പറയുന്നു.
"പക്ഷേ അത് നല്ല സുഖപ്രദമാണ്, എനിക്ക് സന്തോഷവുമുണ്ട്."
"അവിടെ തണുപ്പാണോ?" അവർ ചോദിക്കുന്നു.
"അതെ, പുറത്ത് തണുപ്പാണ്," ഞാൻ പറയുന്നു.
"എന്നാൽ ഇവിടെ നല്ല ചൂടുണ്ട്."
"ഞാൻ സുരക്ഷിതയാണ്."
"അത് നന്നായി," എൻ്റെ അമ്മ പറയുന്നു.
ഞാൻ പുഞ്ചിരിക്കുന്നു.
ഞാൻ ഡെന്മാർക്കിനായി തയ്യാറാണ്.
