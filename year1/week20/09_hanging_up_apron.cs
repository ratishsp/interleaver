Moje třetí směna v kavárně konečně skončila.
Byla to velmi rušná sobota.
Umyla jsem velký dřevěný pult.
Potom jsem šla do místnosti pro zaměstnance.
Sundala jsem si zástěru.
Pověsila jsem ji na první háček na zdi.
Na svých prvních směnách jsem se toho naučila opravdu hodně.
Konečně jsem se naučila správně napěnit mléko.
Také jsem se naučila pamatovat si objednávku stálého zákazníka.
Byla to zábava, ale byla jsem také trochu unavená.
Vzala jsem si ze stolu svou tašku.
Pak jsem šla k hlavním dveřím.
Odpolední směna to teď převzala.
Vyšla jsem na ulici.
Odpolední slunce nad městem jasně svítilo.
Cestou k autobusu jsem se pro sebe usmívala.
Jsem se svou novou dobrovolnickou prací velmi spokojená.
Už teď se těším na svou čtvrtou směnu.
