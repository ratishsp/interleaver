Jdu se projít přes velké náměstí ve městě.
Každou neděli je tu velký bleší trh.
Slunce svítí a mnoho lidí se prochází mezi stoly.
Zastavím se u malého stolku s mnoha různými věcmi.
Za stolem stojí přátelský prodavač.
Najednou uvidím dva modré keramické talíře.
Vezmu je do ruky a pozorně si je prohlédnu.
„Kolik stojí tyto talíře?“ ptám se prodavače.
Prodavač se na mě usměje.
„Stojí jen čtyřicet korun,“ odpovídá.
To je opravdu dobrá cena.
Před měsícem jsem si koupila malý stůl do kuchyně.
Tyto talíře se k tomuto stolu budou perfektně hodit.
„Moc ráda bych si je koupila,“ říkám.
Dám prodavači čtyřicet korun a opatrně uložím talíře do tašky.
Je vždycky hezké najít v klidnou neděli něco speciálního.
