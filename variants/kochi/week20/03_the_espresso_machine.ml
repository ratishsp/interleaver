കഫേ ഇതുവരെ തുറന്നിട്ടില്ല.
ജെസ്സി എന്നെ എസ്‌പ്രെസ്സോ മെഷീൻ്റെ അടുത്തേക്ക് കൊണ്ടുപോകുന്നു.
അത് വളരെ വലുതും തിളക്കമുള്ളതുമാണ്.
"ഇതാണ് നമ്മുടെ എസ്‌പ്രെസ്സോ മെഷീൻ," ജെസ്സി പറയുന്നു.
ആദ്യം, അവർ എനിക്ക് അതിലെ ഡയലുകൾ കാണിച്ചുതരുന്നു.
പിന്നെ അവർ എനിക്ക് സ്റ്റീം വാൻഡ് കാണിച്ചുതരുന്നു.
"ഈ സ്റ്റീം വാൻഡ് പാലിനുള്ളതാണ്," അവർ വിശദീകരിക്കുന്നു.
ഞാൻ അവരെ ശ്രദ്ധയോടെ നോക്കുന്നു.
അവർ ഡയലുകൾ പതുക്കെ തിരിക്കുന്നു.
അപ്പോൾ മെഷീൻ വലിയ ശബ്ദം ഉണ്ടാക്കുന്നു.
"ഇത് ഉപയോഗിക്കാൻ പഠിക്കാൻ കുറച്ചു സമയം വേണം," ജെസ്സി പറയുന്നു.
"നല്ല ക്ഷമയും പരിശീലനവും ആവശ്യമാണ്."
ഞാൻ ഇതിനുമുമ്പ് എസ്‌പ്രെസ്സോ മെഷീൻ ഉപയോഗിച്ചിട്ടില്ല.
പക്ഷേ, എനിക്ക് കോഫി ഉണ്ടാക്കാൻ പഠിക്കാൻ വലിയ ആഗ്രഹമുണ്ട്.
"ഞാൻ പഠിക്കാൻ തയ്യാറാണ്," ഞാൻ അവരോട് പറയുന്നു.
ജെസ്സി തലയാട്ടുന്നു.
എൻ്റെ ഒന്നാമത്തെ കോഫി ഉണ്ടാക്കാൻ ഞാൻ കാത്തിരിക്കുകയാണ്.
