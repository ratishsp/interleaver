Konečně je pátek a rušný týden je skoro u konce.
Společně obědváme ve světlé jídelně.
Sedím u velkého stolu společně se svým týmem.
Peter, naše designérka Eva a náš tester Mads jsou tu také.
Všichni jsme unavení, ale jsme velmi šťastní.
Nový projekt byl velmi zajímavý.
„Pracovali jsme opravdu tvrdě,“ říká Peter a usmívá se.
„Ano, vyřešili jsme mnoho složitých problémů,“ odpovídám.
Jako softwaroví inženýři jsme tento týden napsali hodně kódu.
„A já jsem to všechno otestoval,“ směje se Mads.
„Naštěstí jsi nenašel moc chyb,“ škádlí ho Peter.
Eva nám na svém telefonu ukazuje svůj krásný návrh.
Pracuje jako designérka už mnoho let.
Zatímco jíme, bavíme se o našich různých úkolech.
Je milé lépe poznat své kolegy.
Stal se z nás opravdu dobrý tým.
Ukousnu si ze svého jídla a podívám se na ně.
Těším se, až s nimi budu na projektu pokračovat.
