Efter middagen går jag in i vardagsrummet.
Lägenheten är härligt varm.
Utanför är det mörkt och kallt.
Jag tänder en liten lampa.
Ljuset är varmt och mjukt.
Jag gör en varm kopp te.
Sedan går jag bort till soffan.
Jag sätter mig på de mjuka kuddarna.
På bordet ligger en ny bok.
Jag tar boken och öppnar den.
Det är en spännande historia.
Jag läser ett par kapitel.
Mitt te doftar gott.
Jag tar en klunk.
Jag lutar mig tillbaka.
Nu slappnar jag av helt.
Det är helt tyst i lägenheten.
Jag njuter av min tid ensam.
