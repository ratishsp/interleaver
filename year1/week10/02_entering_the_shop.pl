Skończyłam pracę.
Idę deptakiem.
Wiatr wciąż jest bardzo zimny.
Widzę duży sklep odzieżowy.
Sklep jest bardzo jasny.
Wchodzę do sklepu.
Jest tu cudownie ciepło.
Ekspedientka stoi za kasą.
Patrzy na mnie i się uśmiecha.
„Dzień dobry” – mówi.
„Dzień dobry” – odpowiadam.
„Bardzo marznę” – mówię.
„Mam na sobie tylko cienką kurtkę”.
„Chciałabym znaleźć jakieś ciepłe rzeczy”.
Ekspedientka znowu się uśmiecha.
„Dzisiaj też jest bardzo zimno” – mówi.
„Mamy wiele grubych swetrów”.
„Mamy również ciepłe ubrania zimowe”.
„Proszę się rozejrzeć” – mówi uprzejmie.
„Bardzo dziękuję” – odpowiadam.
