ഇന്ന് രാവിലെ ഞങ്ങൾക്ക് വല്ലാതെ തിരക്കായിരുന്നു.
ഞാൻ എന്റെ ഏറ്റവും ആദ്യത്തെ കാപ്പുച്ചിനോ ഇപ്പോൾ ഉണ്ടാക്കിയതേയുള്ളൂ.
പത്ത് മണിക്ക് അല്പം മുമ്പ് ഒരാൾ കൗണ്ടറിലേക്ക് വന്നു.
"ദയവായി ഒരു കാപ്പുച്ചിനോ," അയാൾ പറഞ്ഞു.
എസ്‌പ്രെസ്സോ മെഷീൻ ഉപയോഗിക്കാൻ ഞാൻ ഇപ്പോൾ പഠിച്ചതേയുള്ളൂ.
അതിനാൽ ഞാൻ ഉടൻ തന്നെ ആ മെഷീന്റെ അടുത്തേക്ക് പോയി.
ഞാൻ കോഫി തയ്യാറാക്കി, എന്നിട്ട് സ്റ്റീം വാണ്ട് പാലിലേക്ക് താഴ്ത്തി വെച്ചു.
പക്ഷേ ഞാൻ അത് അല്പം കൂടുതൽ ആഴത്തിലാണ് പിടിച്ചത്.
എനിക്ക് ഒരുപക്ഷേ അല്പം കൂടുതൽ പരിഭ്രമം ഉണ്ടായിരുന്നിരിക്കാം.
നിർഭാഗ്യവശാൽ, പാലിൽ കട്ടിയുള്ള പതയൊന്നും വന്നില്ല.
ഞാൻ ശ്രദ്ധയോടെ പിച്ചറിനുള്ളിലേക്ക് നോക്കി.
അതിലെ പത പൂർണ്ണമായും പെർഫെക്റ്റ് ആയിരുന്നില്ല.
എങ്കിലും കണ്ടിട്ട് അത് കുഴപ്പമില്ലെന്ന് തോന്നി.
ഞാൻ കപ്പിലെ കോഫിക്ക് മുകളിലേക്ക് ചൂടുപാൽ ഒഴിച്ചു.
അതിനുശേഷം, വിനയപൂർവ്വമുള്ള ഒരു പുഞ്ചിരിയോടെ ഞാൻ ആ കോഫി അയാൾക്ക് നൽകി.
"ഇതാ, അൻപത്തിയഞ്ച് ക്രോണർ ആയി," ഞാൻ പറഞ്ഞു.
അയാൾ ആ കപ്പ് വാങ്ങി ആദ്യത്തെ മേശയ്ക്കരികിൽ പോയി ഇരുന്നു.
