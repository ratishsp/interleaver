"നേരെ പോകൂ, പിന്നെ വലത്തോട്ട് തിരിയൂ," അദ്ദേഹം പറഞ്ഞു.
ഞാൻ പ്രധാന വഴിയിലൂടെ നേരെ നടക്കുന്നു.
ഞാൻ ഒരു ചെറിയ തിരിവ് കാണുന്നു.
ഇതാണ് വഴിയുടെ അവസാനം എന്ന് ഞാൻ കരുതുന്നു.
ഞാൻ നേരത്തെ വലത്തോട്ട് തിരിയുന്നു.
ഞാൻ ഒരു ചെറിയ തെരുവിലേക്ക് കയറുന്നു.
തെരുവ് നിറയെ കടകളാണ്.
അവിടെ തുണിക്കടകളും സുഗന്ധവ്യഞ്ജനങ്ങളുടെ കടകളും ഉണ്ട്.
ഒരു കടയുടെ മുന്നിൽ വലിയ ചാക്കുകൾ ഉണ്ട്.
ചാക്കുകളിൽ നിറയെ ഏലയ്ക്കയും കുരുമുളകുമാണ്.
ഞാൻ കുറച്ചു നേരം അവിടെ നിൽക്കുന്നു.
ഞാൻ ആ സുഗന്ധവ്യഞ്ജനങ്ങൾ നോക്കുന്നു.
പിന്നെ ഞാൻ ചുറ്റും നോക്കുന്നു.
ഒരുപാട് ആളുകൾ എന്റെ അടുത്തൂടെ നടക്കുന്നു.
എനിക്ക് ഈ സ്ഥലം അറിയില്ല.
ഈ തിരക്കിൽ എനിക്ക് വഴി തെറ്റി.
