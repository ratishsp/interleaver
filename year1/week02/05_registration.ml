ഒരു സ്ക്രീനിൽ എന്റെ നമ്പർ കാണിക്കുന്നു.
നമ്പർ അമ്പത്തൊമ്പത് ആണ്.
ഞാൻ കൗണ്ടറിനടുത്തേക്ക് നടക്കുന്നു.
കൗണ്ടറിന് പിന്നിൽ ഒരു പുരുഷൻ ഇരിക്കുന്നു.
"സുപ്രഭാതം," അയാൾ പറയുന്നു.
"സുപ്രഭാതം," ഞാൻ മറുപടി നൽകുന്നു.
"എന്റെ പേര് മായ, എനിക്ക് മുപ്പത്തിയൊന്ന് വയസ്സുണ്ട്," ഞാൻ പറയുന്നു.
"സ്വാഗതം, മായ," അയാൾ പറയുന്നു.
"നിങ്ങളുടെ പാസ്‌പോർട്ട് കയ്യിലുണ്ടോ?" അയാൾ ചോദിക്കുന്നു.
"അതെ, എന്റെ പാസ്‌പോർട്ടും പേപ്പറുകളും എന്റെ കയ്യിലുണ്ട്," ഞാൻ മറുപടി നൽകുന്നു.
"ഇതാ," ഞാൻ പറയുന്നു.
അയാൾ ആ പേപ്പറുകൾ നോക്കുന്നു.
അയാൾ തന്റെ കമ്പ്യൂട്ടറിൽ ടൈപ്പ് ചെയ്യുന്നു.
എനിക്ക് ഒരു ഡാനിഷ് വ്യക്തിഗത തിരിച്ചറിയൽ നമ്പർ ലഭിക്കുന്നു.
ആ നമ്പർ സ്വകാര്യവും വളരെ പ്രധാനപ്പെട്ടതുമാണ്.
അയാൾ എനിക്ക് ഒരു പുതിയ കാർഡ് നൽകുന്നു.
"ഇതാ, നിങ്ങളുടെ കാർഡ് ഇതാണ്," അയാൾ പറയുന്നു.
"ഇപ്പോൾ നിങ്ങൾ ഡെന്മാർക്കിൽ രജിസ്റ്റർ ചെയ്യപ്പെട്ടിരിക്കുന്നു."
ഞാൻ പുഞ്ചിരിച്ചുകൊണ്ട് ആ കാർഡ് വാങ്ങുന്നു.
ഇപ്പോൾ ഞാൻ ഡെന്മാർക്കിന്റെ ഭാഗമാണ്.
