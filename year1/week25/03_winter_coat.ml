ഞാൻ മാർക്കറ്റിന്റെ കുറച്ചുകൂടി ഉള്ളിലേക്ക് നടന്ന് തുണികൾ വിൽക്കുന്ന ഒരു സ്റ്റാളിന് മുന്നിൽ നിൽക്കുന്നു.
കമ്പിളി കൊണ്ടുണ്ടാക്കിയ ഭാരമുള്ള ഒരു വിന്റർ കോട്ട് ഞാൻ കാണുന്നു.
ഈ കോട്ട് കാണാൻ നല്ല ഭംഗിയുണ്ട്, പക്ഷേ ഇതിന് നല്ല കട്ടിയുമുണ്ട്.
എങ്കിലും ഞാൻ ആ കോട്ട് ഇട്ടുനോക്കുന്നു.
ഇതിന് ഭയങ്കര ചൂടാണ്.
ഉടൻ തന്നെ ഞാനത് ഊരിമാറ്റുന്നു.
ഇപ്പോൾ ജൂലൈ മാസമാണ്, ഇന്ന് നല്ല വെയിലുമുണ്ട്.
മേശയ്ക്ക് പിന്നിൽ നിൽക്കുന്ന സൗഹാർദ്ദമുള്ള ഒരു സ്ത്രീ ചിരിക്കുന്നു.
"ചൂട് കൂടുതലാണോ?" ആ സ്ത്രീ ചോദിക്കുന്നു.
"അതെ, വേനൽക്കാലത്തിന് ഇത് ഇത്തിരി ചൂട് കൂടുതലാണ്," ഞാൻ ചിരിച്ചുകൊണ്ട് മറുപടി പറയുന്നു.
ഞാൻ ആ കട്ടിയുള്ള തുണിയിൽ തൊട്ടുനോക്കുന്നു.
"പക്ഷേ, അഞ്ചുമാസം മുമ്പ് എനിക്ക് ഈ വിന്റർ കോട്ടിന്റെ ശരിക്കും ആവശ്യമുണ്ടായിരുന്നു!" ഞാൻ പറയുന്നു.
ആ സ്ത്രീ ഉച്ചത്തിൽ ചിരിക്കുന്നു.
"അതെ, ഫെബ്രുവരിയിൽ നല്ല തണുപ്പായിരുന്നു," അവർ പറയുന്നു.
കോപ്പൻഹേഗനിലെ എന്റെ ആദ്യത്തെ ആഴ്ചകൾ ഞാൻ ഓർക്കുന്നു.
അക്കാലത്ത് എനിക്ക് എപ്പോഴും വല്ലാതെ തണുക്കുന്നുണ്ടായിരുന്നു.
ഭാഗ്യത്തിന്, എനിക്കിപ്പോൾ ഇത്രയും ചൂടുള്ള വസ്ത്രങ്ങളുടെ ആവശ്യമില്ല.
ഞാൻ ആ കോട്ട് തിരികെ റാക്കിൽ തൂക്കിയിട്ട് യാത്ര പറയുന്നു.
