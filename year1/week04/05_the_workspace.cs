Jdu do obývacího pokoje.
U okna stojí malý psací stůl.
Stůl je pro mou práci.
Tady můžu v klidu pracovat.
Je to krásné malé místo.
Otevírám svou tašku.
Vyndávám svůj počítač.
Teď leží na stole.
Na stole stojí také lampa.
Lampa stojí hned u počítače.
Má teplé světlo.
Na stole leží také malá kniha.
Mám malou černou tašku s kabely.
Leží pod psacím stolem.
Takhle taška nepřekáží.
U psacího stolu je dobrá židle.
Sedím na židli a dívám se.
Otevírám počítač a začínám psát.
