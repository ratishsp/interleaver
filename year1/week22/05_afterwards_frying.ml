ഉരുളക്കിഴങ്ങ് ഇപ്പോൾ പാത്രത്തിൽ തിളയ്ക്കുകയാണ്.
അടുക്കളയിൽ ഇപ്പോൾത്തന്നെ നല്ല സുഗന്ധമുണ്ട്.
ഞാൻ ഒരു വലിയ ഫ്രൈയിംഗ് പാൻ പുറത്തെടുക്കുന്നു.
ഞാൻ പാചകക്കുറിപ്പിലെ അടുത്ത നിർദ്ദേശങ്ങൾ വായിക്കുന്നു.
അടുത്ത ഭാഗം പ്രധാനപ്പെട്ടതാണ്.
അതിൽ പറയുന്നു: "ആദ്യം പാനിൽ കട്ടിയുള്ള ഒരു കഷ്ണം വെണ്ണ ഉരുക്കുക."
ഞാൻ കുറച്ചു വെണ്ണ മുറിച്ച് പാനിലിടുന്നു.
ചൂടായ ലോഹത്തിൽ വെണ്ണ പെട്ടെന്ന് ശബ്ദത്തോടെ ഉരുകുന്നു.
ഞാൻ തുടർന്ന് വായിക്കുന്നു: "അതിനുശേഷം മാംസം ഉരുളകളാക്കി മാറ്റുക."
മാംസത്തിന് രൂപം നൽകാൻ ഞാൻ ഒരു സ്പൂൺ ഉപയോഗിക്കുന്നു.
ഇത് അല്പം ബുദ്ധിമുട്ടാണ്, എങ്കിലും അവ നല്ലതുപോലെ ഉരുണ്ട ആകൃതിയിലായി വരുന്നുണ്ട്.
ഞാൻ അവയെ ശ്രദ്ധയോടെ ചൂടുള്ള പാനിലേക്ക് വെക്കുന്നു.
പാചകക്കുറിപ്പിൽ തുടരുന്നു: "പിന്നീട് അവ മൊരിഞ്ഞ് തവിട്ടുനിറമാകുന്നത് വരെ വറുക്കുക."
ഞാൻ തീ അല്പം കുറയ്ക്കുന്നു.
അവ ഏകദേശം പതിനഞ്ച് മിനിറ്റ് വറുക്കേണ്ടതുണ്ട്.
അവ കരിഞ്ഞുപോകാതിരിക്കാൻ ഞാൻ ഇടയ്ക്കിടെ മറിച്ചിടുന്നു.
അവയ്ക്ക് ഗംഭീരമായ സുഗന്ധമുണ്ട്, അതുപോലെ നല്ല നിറവും ലഭിക്കുന്നുണ്ട്.
ഇപ്പോൾ മാംസ ഉരുളകളും ഉരുളക്കിഴങ്ങും ഏകദേശം തയ്യാറായി.
കാസ്പറും സാറയും എത്തുന്നതിനായി ഞാൻ കാത്തിരിക്കുകയാണ്.
ഇത് തികച്ചും കൃത്യമായ സമയമാണ്.
