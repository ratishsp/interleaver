Jestem teraz w nowym biurze.
To duże i jasne pomieszczenie.
Przy drzwiach stoi przyjazny mężczyzna.
Uśmiecha się do mnie.
„Witaj!” – mówi.
„Mam na imię Peter”.
Podaję mu rękę.
„Cześć Peter, mam na imię Maya” – mówię.
Peter to kolega z pracy.
Idziemy razem przez biuro.
„Tutaj masz biurko” – mówi Peter.
Biurko ma numer szesnaście.
„I masz komputer” – mówi.
Daje mi nowego laptopa.
Patrzę na moje nowe miejsce.
Mam krzesło i duży monitor.
„Bardzo dziękuję, Peter” – mówię.
Jestem gotowa na mój pierwszy dzień w pracy.
