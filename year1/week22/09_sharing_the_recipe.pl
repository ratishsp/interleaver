Wszyscy troje jesteśmy teraz bardzo najedzeni.
Na stole nie zostało już więcej jedzenia.
„To była fantastyczna kolacja, Mayo” – mówi radośnie Sara.
„Jak dokładnie robi się te klopsiki?” – pyta potem.
„Czy to bardzo trudne?”
„Nie, to właściwie całkiem proste” – odpowiadam.
„Najpierw sieka się cebulę, a potem miesza mięso” – wyjaśniam.
„Mam w telefonie naprawdę dobry przepis”.
„Wyślę ci dziś wieczorem link”.
„Dziękuję bardzo, chętnie spróbuję” – mówi Sara.
Wstajemy z małych krzeseł.
Kasper zaczyna zbierać puste talerze.
„Mamy teraz zanieść talerze do kuchni?” – pyta.
„Tak, poproszę”.
„Po prostu połóż je na blacie kuchennym” – mówię.
Szybko wspólnie sprzątamy ze stołu.
„Ale hej, następnym razem moja kolej” – mówi nagle Kasper.
„Tak”.
„Następnym razem to ty musisz nam ugotować!”
Sara się śmieje.
„Dokładnie”.
„I obiecuję, że będzie dobre” – mówi.
Śmiejemy się i zanosimy resztę rzeczy do kuchni.
