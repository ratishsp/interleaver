Det är onsdag kväll.
Klockan är sju.
Jag är på det lokala gymmet.
Jag gillar verkligen att träna.
Jag är alltid här på onsdagar.
Jag byter om.
Först lyfter jag vikter.
Vikterna är mycket tunga.
Jag tar en kort paus.
Efteråt springer jag på löpbandet.
Jag springer ofta snabbt.
Jag lyssnar alltid på musik.
Jag tränar i totalt en timme.
Nu är klockan åtta.
Jag är trött, men jag är glad.
Jag tar min väska.
Jag går hem.
