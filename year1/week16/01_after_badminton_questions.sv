Kasper, Sara, Emil och jag spelade badminton i nästan två timmar.
Nu var matchen slut, och vi var skönt trötta.
Vi gick bort till en bänk.
Vi satte oss ner tillsammans.
Jag öppnade min väska och hittade min vattenflaska.
Vi drack bara kallt vatten en lång stund.
"Det var en tuff match," sa Kasper.
Sara log och tittade på mig.
"Du kom till Danmark i januari, eller hur?" frågade hon.
"Jo, jag reste från Mexiko i januari," svarade jag.
Kasper lade sin racket på bänken.
"Hur var dina första dagar i landet?" frågade han.
Jag tänkte tillbaka på min första vecka.
Allting var nytt och mycket annorlunda då.
Jag kände inte alls till staden.
"Det var väldigt kallt," började jag.
Kasper och Sara skrattade högt.
"Den danska vintern är alltid kall," sa Sara.
Kasper frågade mig.
"Hur var din allra första dag?"
