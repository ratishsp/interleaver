Vejdeme do malého bufetu v hale.
Najdeme si stůl.
Mám velkou žízeň.
Pijeme studenou vodu a povídáme si.
„Tohle je opravdu dobrý klub,“ říkám.
„Je to dobrý sport,“ říká Kasper.
Kasper se na mě podívá.
„Chceš se zase přidat?“ ptá se.
„Ano, moc ráda,“ odpovídám.
„Chci tu hrát každý čtvrtek,“ vysvětluji.
„To zní skvěle,“ říká Sara.
„Hrajeme tu vždycky ve čtvrtek,“ říká Kasper.
„Tak se uvidíme příští týden,“ říkám vesele.
Dopijeme zbytek naší vody.
Je skvělé poznávat nové lidi.
