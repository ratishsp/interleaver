ഞാൻ എന്റെ അടുക്കളയിൽ നിൽക്കുമ്പോഴാണ് വാതിലിലെ ബെൽ മുഴങ്ങുന്നത്.
ഞാൻ ഇടനാഴിയിലേക്ക് നടന്ന് വാതിൽ തുറക്കുന്നു.
അത് നീനയാണ്, അവളുടെ മുഖത്ത് വലിയൊരു പുഞ്ചിരിയുണ്ട്.
"ഹലോ മായ, ക്ഷണിച്ചതിന് വലിയ നന്ദി," അവൾ പറയുന്നു.
അവൾ അകത്തേക്ക് കയറുകയും ഷൂ അഴിച്ചുമാറ്റുന്നതിനിടയിൽ ചിരിക്കുകയും ചെയ്യുന്നു.
ഞാൻ അവളെ സ്നേഹത്തോടെ കെട്ടിപ്പിടിക്കുന്നു.
മനോഹരമായ ഒരു പച്ച വീട്ടുചെടി നീന കൈകളിൽ പിടിച്ചിട്ടുണ്ട്.
"ഇത് നിനക്കുള്ളതാണ്," എന്ന് പറഞ്ഞുകൊണ്ട് അവൾ ആ ചെടി എനിക്ക് നേരെ നീട്ടുന്നു.
"നിന്റെ ലിവിംഗ് റൂമിന് ഇത് തികച്ചും അനുയോജ്യമാണ്."
"നന്ദി, ഇത് ശരിക്കും വളരെ ഭംഗിയുള്ളതാണ്," ഞാൻ സന്തോഷത്തോടെ മറുപടി നൽകുന്നു.
വാതിലിനടുത്തുള്ള ഒരു ചെറിയ മേശപ്പുറത്ത് ഞാൻ ആ പച്ചച്ചെടി വെക്കുന്നു.
പെട്ടെന്ന്, നീന ദീർഘമായി ശ്വാസമെടുക്കുന്നു.
"വൗ, ഇതിനുള്ളിൽ നല്ല ഗംഭീര മണമാണല്ലോ," അവൾ പറയുന്നു.
"അത് മെക്സിക്കൻ സുഗന്ധവ്യഞ്ജനങ്ങളാണോ?" അവൾ ആകാംക്ഷയോടെ ചോദിക്കുന്നു.
ഞാൻ തലകുലുക്കുകയും പരമ്പരാഗതമായ ഒരു സ്റ്റ്യൂ ആണ് ഉണ്ടാക്കിയതെന്ന് വിശദീകരിക്കുകയും ചെയ്യുന്നു.
"മസാലയുടെ ഈ സുഗന്ധം എന്നെ വല്ലാതെ വിശപ്പിക്കുന്നു," നീന ചിരിക്കുന്നു.
"ഭാഗ്യത്തിന്, ഭക്ഷണം പൂർണ്ണമായും തയ്യാറാണ്," ഞാൻ ഒരു പുഞ്ചിരിയോടെ പറയുന്നു.
ഭക്ഷണം കഴിക്കാനായി ഞങ്ങൾ ഒരുമിച്ച് മേശയ്ക്കരികിൽ ഇരിക്കുന്നു.
