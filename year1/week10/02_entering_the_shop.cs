Skončila jsem v práci.
Jdu po pěší zóně.
Vítr je stále velmi studený.
Vidím velký obchod s oblečením.
Obchod je velmi světlý.
Vcházím do obchodu.
Je tu krásně teplo.
Za pokladnou stojí prodavačka.
Dívá se na mě a usmívá se.
„Dobrý den,“ říká.
„Dobrý den,“ odpovídám.
„Je mi velká zima,“ říkám.
„Mám na sobě jen tenkou bundu.“
„Ráda bych našla nějaké teplé věci.“
Prodavačka se znovu usměje.
„Dnes je také velká zima,“ říká.
„Máme hodně silných svetrů.“
„Máme také teplé zimní oblečení.“
„Jen se klidně podívejte,“ říká vlídně.
„Moc děkuji,“ odpovídám.
