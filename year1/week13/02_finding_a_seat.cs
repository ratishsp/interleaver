Teď jsem uvnitř kavárny.
Je tu velmi teplo.
Sundávám si svou tlustou zimní bundu.
Je těžká.
Nacházím háček na zdi.
Věším svou bundu na háček.
Sundávám si také šálu a rukavice.
Kavárna je malá a útulná.
Hledám dobré místo.
U okna je malý stůl.
Stůl stojí vedle radiátoru.
Jdu ke stolu.
Sedám si na židli.
Moje ruce jsou stále studené.
Mnu si je o sebe.
Ruce se mi zahřívají.
Je to fantastické.
Teď už je mi skoro teplo.
Mám hlad a žízeň.
Chtěla bych si teď něco objednat.
