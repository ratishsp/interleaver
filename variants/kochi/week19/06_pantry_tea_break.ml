ഇപ്പോൾ വൈകുന്നേരം നാല് മണിയാണ്.
ഞങ്ങൾ ഓഫീസിലെ പാൻട്രിയിലാണ്.
സുരേഷും പ്രകാശും ദീപയും അരുണും എന്റെ കൂടെ ചായ കുടിക്കുന്നു.
ഞങ്ങൾ ഇപ്പോൾ ജോലിയെക്കുറിച്ച് സംസാരിക്കുന്നില്ല.
സുരേഷ് എന്നോട് ഒരു ചോദ്യം ചോദിക്കുന്നു.
"മായ, കേരളത്തിൽ ഏതൊക്കെ സ്ഥലങ്ങൾ സന്ദർശിച്ചിട്ടുണ്ട്?" അദ്ദേഹം ചോദിക്കുന്നു.
"ഞാൻ ഫോർട്ട് കൊച്ചിയും കായലുകളും സന്ദർശിച്ചിട്ടുണ്ട്," ഞാൻ മറുപടി പറയുന്നു.
ദീപ ചിരിച്ചുകൊണ്ട് എന്നെ നോക്കുന്നു.
"ഇവിടുത്തെ ബേക്കറികളിൽ നിന്ന് പലഹാരങ്ങൾ കഴിച്ചിട്ടുണ്ടോ?" ദീപ ചോദിക്കുന്നു.
ഞാൻ സന്തോഷത്തോടെ തലയാട്ടുന്നു.
"ഉവ്വ്, ഞാൻ പഴംപൊരിയും ഇറച്ചി പഫ്സും കഴിച്ചിട്ടുണ്ട്," ഞാൻ പറയുന്നു.
"ബനാന ചിപ്സ് കഴിച്ചിട്ടുണ്ടോ?" അരുൺ ചോദിക്കുന്നു.
"അനിത എനിക്ക് ബനാന ചിപ്സ് തന്നിട്ടുണ്ട്," ഞാൻ മറുപടി പറയുന്നു.
"അതിന് നല്ല രുചിയാണ്," ഞാൻ കൂട്ടിച്ചേർക്കുന്നു.
പ്രകാശ് ഒരു ബേക്കറിയെക്കുറിച്ച് രസകരമായ ഒരു കഥ പറയുന്നു.
ഞങ്ങൾ എല്ലാവരും ഉച്ചത്തിൽ ചിരിക്കുന്നു.
ചായ സമയം കഴിയുന്നു.
ഞങ്ങൾ തിരികെ ജോലിക്ക് പോകുന്നു.
