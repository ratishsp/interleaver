Wchodzę do salonu.
Przy oknie stoi małe biurko.
Stół jest do mojej pracy.
Tutaj mogę pracować w spokoju.
To urocze, małe miejsce.
Otwieram moją torbę.
Wyjmuję mój komputer.
Teraz stoi na stole.
Na stole stoi też lampa.
Lampa stoi tuż przy komputerze.
Ma ciepłe światło.
Na stole leży też mała książka.
Mam małą, czarną torbę z kablami.
Leży pod biurkiem.
W ten sposób torba nie przeszkadza.
Przy biurku stoi dobre krzesło.
Siedzę na krześle i patrzę.
Otwieram komputer i zaczynam pisać.
