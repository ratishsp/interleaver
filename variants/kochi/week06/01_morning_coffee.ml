ഞാൻ എഴുന്നേൽക്കുന്നു.
ഇപ്പോൾ രാവിലെയാണ്.
ഞാൻ അടുക്കളയിലേക്ക് നടക്കുന്നു.
ഞാൻ സ്റ്റൗ ഓൺ ചെയ്യുന്നു.
ഞാൻ പാത്രത്തിൽ വെള്ളം എടുക്കുന്നു.
വെള്ളം തിളക്കുകയാണ്.
ഞാൻ ഒരു കപ്പ് ചൂട് കാപ്പി ഉണ്ടാക്കുന്നു.
ഞാൻ സ്റ്റൗ ഓഫ് ചെയ്യുന്നു.
ഞാൻ കാപ്പിയുമായി ബാൽക്കണിയിലേക്ക് പോകുന്നു.
ഞാൻ ബാൽക്കണിയിൽ നിൽക്കുകയാണ്.
നല്ല കാറ്റ് വീശുകയാണ്.
പുറത്തെ കാലാവസ്ഥ വളരെ മനോഹരമാണ്.
ഞാൻ പതുക്കെ കാപ്പി കുടിക്കുകയാണ്.
ഞാൻ താഴെ റോഡിലേക്ക് നോക്കുന്നു.
കൊച്ചി നഗരം ഉണരുകയാണ്.
എനിക്ക് ഈ സമയം വളരെ ഇഷ്ടമാണ്.
ഒരു പുതിയ ദിവസം തുടങ്ങുന്നു.
