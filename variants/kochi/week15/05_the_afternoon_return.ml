അഞ്ചു മണിക്ക് എൻ്റെ ജോലി തീരുന്നു.
ഞാൻ ഓഫീസിൽ നിന്ന് പുറത്തിറങ്ങുന്നു.
ഞാൻ ഇൻഫോപാർക്ക് ബസ് സ്റ്റോപ്പിൽ കാത്തുനിൽക്കുന്നു.
സിറ്റി സെൻ്ററിലേക്കുള്ള ബസ് വരുന്നു.
ഞാൻ ബസ്സിൽ കയറുന്നു.
ഇന്ന് ബസ്സിൽ നല്ല തിരക്കാണ്.
ഞാൻ ഒരു ടിക്കറ്റ് വാങ്ങുന്നു.
എനിക്ക് സീറ്റ് കിട്ടുന്നില്ല.
കുറച്ചു കഴിയുമ്പോൾ ഞങ്ങൾ ഒരു വലിയ കവലയിൽ എത്തുന്നു.
ഇത് എൻ്റെ വീടിനടുത്താണ്.
ബസ് അവിടെ നിൽക്കുന്നു.
ഞാൻ ബസ്സിൽ നിന്ന് ഇറങ്ങുന്നു.
ഈ കവലയിൽ ധാരാളം കടകൾ ഉണ്ട്.
എനിക്ക് ചില സാധനങ്ങൾ വാങ്ങണം.
