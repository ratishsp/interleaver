Jag satt på min plats på tåget och tittade mig omkring.
En pappa satt mittemot mig.
Han hade sina två små barn med sig.
Pappan hade en stor bok.
Han ville väldigt gärna läsa sin bok.
Men han fick inte mycket ro.
Hans dotter hade en röd boll.
Hans son hade en grön leksaksbil.
Barnen satt inte alls stilla.
De kastade hela tiden sina leksaker på golvet.
Pappan suckade högt och stängde sin bok.
Han plockade upp sakerna från golvet.
Han gav barnen deras leksaker tillbaka.
"Ni måste sitta stilla," sa han trött.
Han öppnade sin bok igen.
Två minuter senare föll bollen på golvet.
Den träffade pappans vänstra sko.
Mannen plockade upp bollen igen.
Jag log mot den trötta pappan.
Han skakade bara på huvudet och tittade ner i sin bok.
