To moja przerwa na lunch.
Siedzę w kantynie w mojej pracy.
Wczoraj byłam zajęta.
Dlatego dzwonię teraz do fryzjera.
Biorę mój telefon komórkowy.
Dzwonię do salonu fryzjerskiego w mieście.
Kobieta odbiera telefon.
„Dzień dobry, tu salon fryzjerski” – mówi kobieta.
„Dzień dobry, nazywam się Maya” – mówię.
„Chciałabym umówić się na wizytę w czwartek”.
„Chwileczkę” – mówi fryzjerka.
„Czy macie wolny termin po południu?” – pytam.
„Tak, mamy wolny termin o wpół do piątej” – mówi.
„Bardzo mi to pasuje” – mówię.
„Jaki jest pani numer telefonu?” – pyta fryzjerka.
„Mój numer to dwanaście, trzydzieści cztery, pięćdziesiąt sześć, siedemdziesiąt osiem” – mówię.
„Bardzo dziękuję, do zobaczenia w czwartek o wpół do piątej” – mówi.
„Do zobaczenia” – odpowiadam.
Kładę telefon na stole.
Teraz w końcu jem moje jedzenie.
