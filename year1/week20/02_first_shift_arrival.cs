Je to moje první sobotní směna v té malé kavárně.
Dorazila jsem brzy.
Slunce svítí na ulici v Kodani.
Těším se, ale jsem také trochu nervózní.
Je to poprvé, co pracuji v kavárně.
Šla jsem do zadní místnosti, abych se připravila.
Na stole pro mě ležela nová zástěra.
Oblékla jsem si ji a zavázala na zádech.
Byl to dobrý pocit mít ji na sobě.
Teď jsem připravená začít.
Musím se naučit správně otevírat kavárnu.
Nejprve vedoucí odemkl těžké hlavní dveře.
Potom jsem šla ven na chodník, abych vše připravila.
Vynesla jsem ven čtyři židle.
Rozestavila jsem je kolem malého stolu.
Za chvíli dorazí ostatní dobrovolníci.
Jsem ze svého prvního dne velmi nadšená.
