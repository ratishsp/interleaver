Jdu po schodech nahoru.
V rukou mám dvě tašky.
Konečně jsem u svých nových dveří.
V kapse mám klíč.
Položím tašky na zem.
Vytáhnu klíč.
Odemknu dveře.
Otevřu dveře a vejdu dovnitř.
Byt je malý, ale je dokonalý.
Má pěkný, světlý nábytek.
Podívám se do obývacího pokoje.
U okna stojí pohovka.
Pod pohovkou je koberec.
Na pohovce leží malý polštář.
V rohu stojí lampa.
Zavřu za sebou dveře.
Položím svůj klíč na stůl.
