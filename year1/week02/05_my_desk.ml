ഞാൻ എന്റെ പുതിയ ഡെസ്കിൽ ഇരിക്കുന്നു.
ഡെസ്ക് ഒരു ജനാലയ്ക്കരികിലാണ്.
ഞാൻ കമ്പ്യൂട്ടർ ഓൺ ചെയ്യുന്നു.
ഒരു സഹപ്രവർത്തകൻ എന്റെ അടുത്തേക്ക് വരുന്നു.
അദ്ദേഹം പുഞ്ചിരിച്ചുകൊണ്ട് എന്റെ ആദ്യത്തെ ജോലി എനിക്ക് കാണിച്ചുതരുന്നു.
"ഇതാ നിങ്ങൾക്കുള്ള ഒരു ജോലി," അദ്ദേഹം പറയുന്നു.
തുടങ്ങാൻ അദ്ദേഹം എന്നെ സഹായിക്കുന്നു.
ഞങ്ങൾ ഒരു ചെറിയ ടീമാണ്.
ഞങ്ങൾ എട്ട് പേർ മാത്രമേയുള്ളൂ.
എല്ലാവരും വളരെ നല്ലവരാണ്.
ഇവിടെ കോപ്പൻഹേഗനിൽ എനിക്ക് നല്ലൊരു ജോലിയുണ്ട്.
