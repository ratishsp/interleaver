ഞാൻ ഓഫീസ് കെട്ടിടത്തിൽ കയറുന്നു.
കെട്ടിടത്തിൽ നല്ല വെളിച്ചമുണ്ട്.
ഇതൊരു മനോഹരമായ ജനുവരി പ്രഭാതമാണ്.
ഞാൻ എൻ്റെ പുതിയ സഹപ്രവർത്തകനെ കാണുന്നു.
അദ്ദേഹത്തിൻ്റെ പേര് പ്രകാശ് എന്നാണ്.
പ്രകാശ് എന്നെ നോക്കി ചിരിക്കുന്നു.
"നമസ്കാരം, മായാ," പ്രകാശ് പറയുന്നു.
"നമ്മുടെ ടീമിലേക്ക് സ്വാഗതം."
"നമസ്കാരം, പ്രകാശ്," ഞാൻ മറുപടി പറയുന്നു.
"വളരെ നന്ദി."
പ്രകാശ് എന്നോട് ഒരു ചോദ്യം ചോദിക്കുന്നു.
"നിങ്ങൾക്ക് എൻട്രി ബാഡ്ജ് ഉണ്ടോ?"
ഞാൻ മറുപടി പറയുന്നു.
"ഇല്ല, എനിക്ക് ബാഡ്ജ് ഇല്ല," ഞാൻ പറയുന്നു.
"എനിക്ക് ഇപ്പോൾ ഐഡി കാർഡ് ഇല്ല."
പ്രകാശ് വീണ്ടും ചിരിക്കുന്നു.
"കുഴപ്പമില്ല," അദ്ദേഹം പറയുന്നു.
ഞാൻ പ്രകാശിൻ്റെ കൂടെ അകത്തേക്ക് നടക്കുന്നു.
എനിക്ക് പുതിയ ഓഫീസിൽ വളരെ സന്തോഷമുണ്ട്.
