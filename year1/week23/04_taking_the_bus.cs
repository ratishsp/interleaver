Stojím na autobusové zastávce se žlutými květinami.
Je tu mnoho lidí, kteří čekají.
Dívám se na obrazovku, abych viděla jízdní řád.
Autobus tu má být za pět minut.
Myslím, že páteční doprava je často velmi pomalá.
Ale ulice dnes vypadají úplně prázdné.
Takže si myslím, že autobus asi přijede včas.
Vedle mě stojí starší muž.
Podívá se na hodinky a povzdechne si.
„Nevíte, jestli má autobus zpoždění?“ ptá se mě.
Znovu si kontroluji telefon.
„Ne, to si nemyslím,“ odpovídám.
„Taky jedu stejným autobusem.“
„Myslím, že je vlastně hned za rohem.“
Usměje se na mě a přikývne.
Najednou dole v ulici vidíme ten velký červený autobus.
Jede rychle směrem k nám.
„Měla jste pravdu,“ říká muž s úlevou.
Nastupujeme do autobusu společně.
U Evy budu určitě včas.
Těším se, až uvidím její byt.
