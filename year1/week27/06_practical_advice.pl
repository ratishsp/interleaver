Kładę pudełko na podłodze i znowu jej dziękuję.
„Nie ma za co” – odpowiada Nina.
Mówię jej, że portal działał dziś wieczorem trochę wolno.
„Tak, zazwyczaj jest bardzo wolny” – śmieje się Nina.
Pyta, czy moje potwierdzenie zostało zapisane.
„Zawsze pamiętaj, żeby pobrać swoje potwierdzenie” – radzi.
Pytam ją, dlaczego to jest ważne.
Nina wyjaśnia, że stare wiadomości są często usuwane na ich stronie internetowej.
System tak naprawdę usuwa je automatycznie po krótkim czasie.
Kiwam głową i ponownie otwieram portal na moim telefonie.
Znajduję plik i natychmiast zostaje on pobrany.
„Więc dokument jest bezpiecznie zapisany” – mówię z ulgą.
Nina uśmiecha się radośnie i życzy mi dobrego wieczoru.
Życzę jej tego samego.
Idzie korytarzem, a ja zamykam swoje drzwi.
To naprawdę miło mieć mądrą i pomocną sąsiadkę.
