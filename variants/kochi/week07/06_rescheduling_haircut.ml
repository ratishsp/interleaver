ഞാൻ വീണ്ടും സലൂണിലേക്ക് ഫോൺ ചെയ്യുന്നു.
റിസപ്ഷനിസ്റ്റ് ഫോൺ എടുക്കുന്നു.
"നമസ്കാരം, പനമ്പിള്ളി നഗർ സലൂൺ," അവർ പറയുന്നു.
"നമസ്കാരം, ഞാൻ മായ," ഞാൻ പറയുന്നു.
"എനിക്ക് ബുധനാഴ്ച വൈകുന്നേരം അഞ്ചരയ്ക്ക് ഒരു അപ്പോയിന്റ്മെന്റ് ഉണ്ട്."
"പക്ഷേ, എനിക്ക് ബുധനാഴ്ച വരാൻ സാധിക്കില്ല."
"മറ്റൊരു ദിവസം വരാമോ?" ഞാൻ ചോദിക്കുന്നു.
"തീർച്ചയായും, ഏത് ദിവസമാണ് വരുന്നത്?" അവർ ചോദിക്കുന്നു.
ഞാൻ എപ്പോഴും ചൊവ്വാഴ്ചയും വ്യാഴാഴ്ചയും ജിമ്മിൽ പോകുന്നു.
അതിനാൽ ആ ദിവസങ്ങളിൽ എനിക്ക് സമയം ഇല്ല.
"എനിക്ക് വെള്ളിയാഴ്ച വരാമോ?" ഞാൻ ചോദിക്കുന്നു.
"ശരി, വെള്ളിയാഴ്ച എത്ര മണിക്ക് വരുന്നു?" അവർ ചോദിക്കുന്നു.
"വൈകുന്നേരം ആറേ കാലിന് വരാമോ?" ഞാൻ ചോദിക്കുന്നു.
അവർ കമ്പ്യൂട്ടറിൽ നോക്കുന്നു.
"ആറേ കാൽ... ശരി, വരാം," അവർ പറയുന്നു.
"വെള്ളിയാഴ്ച വൈകുന്നേരം ആറേ കാലിന് കാണാം."
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
ഞാൻ സന്തോഷത്തോടെ ഫോൺ വെക്കുന്നു.
