Jestem teraz w salonie.
Jest tu mała sofa.
Dzwonię do mamy w Meksyku.
„Cześć, mamo” – mówię.
„Cześć, Maya” – mówi moja mama.
„Gdzie jesteś?” – pyta.
„Jestem w Kopenhadze” – odpowiadam.
„Jestem teraz w mieszkaniu”.
„To bardzo dobrze” – mówi moja mama.
„Czy jest duże?” – pyta.
„Nie, jest małe” – odpowiadam.
„Ale jest przytulne i jestem szczęśliwa”.
„Czy jest zimno?” – pyta.
„Tak, na zewnątrz jest zimno” – mówię.
„Ale tutaj jest ciepło”.
„Jestem bezpieczna”.
„To dobrze” – mówi moja mama.
Uśmiecham się.
Dania to mój nowy dom.
