കാസ്പർ ചോദിച്ചു:
"നിന്റെ ജോലിയുടെ കാര്യമോ?"
ഞാൻ ഒരു നിമിഷം ആലോചിച്ചു.
പിന്നെ സാറ സോഫ്റ്റ്‌വെയർ കമ്പനിയിലെ എന്റെ ആദ്യ ദിവസത്തെക്കുറിച്ച് ചോദിച്ചു.
അന്ന് രാവിലെ ഞാൻ വളരെ പരിഭ്രമിച്ചിരുന്നു.
ഞാൻ ബസ്സിലാണ് ജോലിക്ക് പോയത്.
ഞാൻ ജനാലയിലൂടെ പുറത്തേക്ക് നോക്കി എന്റെ പുതിയ സഹപ്രവർത്തകരെക്കുറിച്ച് ചിന്തിച്ചു.
ഞാൻ ആ വലിയ കെട്ടിടത്തിലേക്ക് നടന്നു കയറി.
ഞാൻ പുതിയ ഓഫീസിൽ നിന്ന് ഹലോ പറഞ്ഞു.
ഒരാൾ വേഗത്തിൽ എന്റെ അടുത്തേക്ക് വന്നു.
"ഡെൻമാർക്കിലേക്ക് സ്വാഗതം, എന്റെ പേര് പീറ്റർ," അദ്ദേഹം സ്നേഹത്തോടെ പറഞ്ഞു.
പീറ്റർ വലിയൊരു പുഞ്ചിരിയോടെ എന്റെ പുതിയ ഡെസ്ക് എനിക്ക് കാണിച്ചുതന്നു.
അദ്ദേഹം എന്റെ പുതിയ സഹപ്രവർത്തകനായിരുന്നു.
ഞങ്ങൾ ഒരുമിച്ച് ഒരു കപ്പ് കാപ്പി കുടിച്ചു.
മെക്സിക്കോയിൽ നിന്നുള്ള എന്റെ നീണ്ട യാത്രയെക്കുറിച്ച് അദ്ദേഹം ചോദിച്ചു.
അത് വളരെ സന്തോഷകരമായിരുന്നു, എനിക്ക് ആശ്വാസം തോന്നി.
സാറ തലയാട്ടി എന്നെ നോക്കി.
"നല്ല സഹപ്രവർത്തകർ അതീവ പ്രധാനമാണ്," അവൾ പറഞ്ഞു.
ഞാൻ അത് പൂർണ്ണമായും സമ്മതിച്ചു.
