Jag sitter på bussen.
Jag tittar ut genom fönstret.
Jag är inte helt säker på rutten.
En äldre kvinna sitter nära mig.
Jag tittar bort mot henne.
"Ursäkta," säger jag artigt.
"Går den här bussen till metrostationen?"
Kvinnan tittar på mig.
Hon nickar med ett vänligt leende.
"Ja, den går till metrostationen," svarar hon.
"Ska du med metron?" frågar kvinnan.
"Ja, jag ska med metron," säger jag.
"Jag åker ofta med den här bussen," säger kvinnan.
"Det är en enkel rutt," tillägger hon.
"Tack så mycket för hjälpen," säger jag.
"Det är min första tur på den här rutten."
Kvinnan nickar igen.
Jag slappnar av i sätet.
Vi åker vidare genom staden.
