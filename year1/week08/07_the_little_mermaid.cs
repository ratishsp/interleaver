Jdu rovně podél přístavu.
Jdu kolem malých lodí.
Najednou vidím mnoho lidí.
Stojí dole u vody.
Jdu tam.
Konečně ji vidím.
Malá mořská víla sedí na kameni ve vodě.
Je to velmi slavná socha v Kodani.
Ta postava vlastně není moc velká.
Ale ta bronzová socha je na slunci krásná.
Stojím mezi ostatními návštěvníky.
Mnoho turistů si sochu fotí.
Také vytahuji telefon.
Pořizuji krásnou fotku mořské víly.
Posílám fotku své rodině do Mexika.
Moje sestra Sofía rychle odpovídá.
„Je moc hezká,“ píše.
Znovu se dívám na vodu.
