ഞാൻ ആ ഇടുങ്ങിയ തെരുവിലൂടെ മുന്നോട്ട് പോയി.
ഞാൻ വളരെ പഴയ ഒരു വീടിനു മുന്നിൽ നിന്നു.
പ്രായമായ ഒരു ദമ്പതികൾ വസന്തകാലത്തെ വെയിലത്ത് പുറത്തുണ്ടായിരുന്നു.
ആ മനുഷ്യൻ തന്റെ പൂന്തോട്ടത്തിൽ നിൽക്കുകയായിരുന്നു.
അയാൾ ഒരു ബ്രഷ് ഉപയോഗിച്ച് തന്റെ പഴയ വേലിക്ക് പെയിന്റടിച്ചു.
പുതിയ നിറം ഇളം മഞ്ഞയായിരുന്നു.
അയാളുടെ ഭാര്യ അടുത്തുള്ള ഒരു മരബെഞ്ചിൽ ഇരിക്കുകയായിരുന്നു.
അവർ വിശ്രമിച്ചുകൊണ്ട് ചൂടുള്ള ചായ കുടിക്കുകയായിരുന്നു.
ആ മനുഷ്യൻ എന്നെ കണ്ട് ഒരു നിമിഷം നിർത്തി.
അയാൾ തന്റെ ബ്രഷ് കൊണ്ട് സ്നേഹപൂർവ്വം കൈവീശി.
"സുപ്രഭാതം!" അയാൾ എന്നോട് പറഞ്ഞു.
"നിങ്ങളുടെ പൂന്തോട്ടം കാണാൻ വളരെ മനോഹരമായിട്ടുണ്ട്," ഞാൻ പറഞ്ഞു.
അയാളുടെ ഭാര്യ തന്റെ ബെഞ്ചിൽ നിന്ന് എന്നെ നോക്കി പുഞ്ചിരിച്ചു.
"നന്ദി, ഞങ്ങൾ ഈ വസന്തകാലം ആസ്വദിക്കുകയാണ്," അവർ മറുപടി പറഞ്ഞു.
ആ മനുഷ്യൻ ശാന്തനായി വേലിയിൽ പെയിന്റടിക്കുന്നത് തുടർന്നു.
അവരുടെ പൂന്തോട്ടത്തിൽ പക്ഷികൾ പാടുന്നുണ്ടായിരുന്നു.
ഞാൻ സന്തോഷത്തോടെ എന്റെ നടത്തം തുടർന്നു.
