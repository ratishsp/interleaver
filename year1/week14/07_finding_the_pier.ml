മെട്രോയിലുള്ള യാത്ര കഴിഞ്ഞു.
ഇപ്പോൾ ഞാൻ മുകളിലെ തെരുവിലേക്ക് പോവുകയാണ്.
ഞാൻ എസ്‌കലേറ്റർ കയറുന്നു.
മുകളിലെ തെരുവിൽ സൂര്യൻ പ്രകാശിക്കുന്നുണ്ട്.
ഇപ്പോൾ ഞാൻ വെള്ളത്തിനടുത്തേക്ക് പോവുകയാണ്.
ഞാൻ ഹാർബർ ബസിലാണ് പോകുന്നത്.
ഞാൻ വിശാലമായ ഒരു തെരുവിലൂടെ നടക്കുന്നു.
അപ്പോൾ ഞാൻ ആ കനാൽ കാണുന്നു.
വെള്ളത്തിന് വളരെ നീല നിറമാണ്.
ഞാൻ എൻ്റെ സ്റ്റോപ്പിനായി തിരയുകയാണ്.
ബോട്ട് എവിടെയാണ് നിർത്തുക?
ഞാൻ അരികിലേക്ക് കുറച്ചുകൂടി അടുത്തു നടക്കുന്നു.
അപ്പോൾ ഞാൻ തടികൊണ്ടുള്ള ഒരു ചെറിയ ജെട്ടി കാണുന്നു.
അത് താഴെ വെള്ളത്തോട് ചേർന്നാണ് സ്ഥിതിചെയ്യുന്നത്.
ജെട്ടിക്ക് സമീപം ഒരു മഞ്ഞ സൈൻ ബോർഡുണ്ട്.
ആ സൈൻ ബോർഡിൽ "ഹാർബർ ബസ്" എന്ന് എഴുതിയിട്ടുണ്ട്.
ഇതാണ് ശരിയായ സ്ഥലം.
ഞാൻ ആ ജെട്ടിയിലേക്ക് നടക്കുന്നു.
ഇപ്പോൾ ഞാൻ ബോട്ടിനായി കാത്തിരിക്കുക മാത്രമാണ് ചെയ്യുന്നത്.
