ഉച്ചയ്ക്ക് ഞാനും പ്രകാശും കാന്റീനിൽ ഭക്ഷണം കഴിക്കാൻ ഇരിക്കുന്നു.
അപ്പോൾ ദീപ ഞങ്ങളുടെ മേശയുടെ അടുത്തേക്ക് വരുന്നു.
ദീപ ഞങ്ങളുടെ ടീമിലെ ഡിസൈനർ ആണ്.
എനിക്ക് അവരുടെ മുഖം മാത്രമേ പരിചയമുള്ളൂ.
അവർ എന്റെ അടുത്ത് വന്ന് ഇരിക്കുന്നു.
"മായ, ഞാൻ ദീപ," അവർ എന്നെ നോക്കി ചിരിക്കുന്നു.
അവർ ഒരു ടാബ്‌ലെറ്റിൽ ചില ചിത്രങ്ങൾ കാണിക്കുന്നു.
"പുതിയ പ്രോജക്റ്റിനായി ഞാൻ കുറച്ച് ഡിസൈനുകൾ ചെയ്തിട്ടുണ്ട്," ദീപ പറയുന്നു.
ആ ഡിസൈനുകൾ വളരെ മനോഹരമാണ്.
"നിങ്ങൾ എത്ര വർഷമായി ഡിസൈനർ ആയി ജോലി ചെയ്യുന്നു?" ഞാൻ ചോദിക്കുന്നു.
"ഞാൻ അഞ്ച് വർഷം ഡിസൈനർ ആയി ജോലി ചെയ്തിട്ടുണ്ട്," ദീപ മറുപടി പറയുന്നു.
പിന്നെ ഞങ്ങൾ ഭക്ഷണം കഴിക്കാൻ തുടങ്ങുന്നു.
ദീപ ഇന്ന് ചോറും മീൻകറിയും കൊണ്ടുവന്നിട്ടുണ്ട്.
ദീപ എന്നോട് എന്റെ നാടിനെക്കുറിച്ച് ചോദിക്കുന്നു.
ഞാൻ മെക്സിക്കോയെക്കുറിച്ച് അവരോട് സംസാരിക്കുന്നു.
ശേഷം ഞാൻ ദീപയോട് അവരുടെ നാടിനെക്കുറിച്ച് ചോദിക്കുന്നു.
"എന്റെ നാട് കണ്ണൂർ ആണ്," അവർ പറയുന്നു.
കണ്ണൂരിലെ നല്ല ഭക്ഷണത്തെക്കുറിച്ച് പ്രകാശ് ഞങ്ങളോട് സംസാരിക്കുന്നു.
ടീമിനൊപ്പമുള്ള ഇന്നത്തെ ഉച്ചഭക്ഷണം വളരെ രസകരമാണ്.
