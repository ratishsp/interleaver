എന്റെ ചേട്ടൻ ഡീഗോ കസേരയിൽ ഇരിക്കുന്നു.
അവന്റെ കൈകളിൽ ഞങ്ങളുടെ നായയുണ്ട്.
അവളുടെ പേര് ലോല എന്നാണ്.
അവൾ വളരെ കുസൃതിയുള്ള ഒരു നായയാണ്.
അവൾ സ്ക്രീനിൽ എന്നെ കാണുന്നു.
അവൾ ഉച്ചത്തിൽ കുരയ്ക്കുന്നു.
ഡീഗോ ലോലയോട് ചോദിക്കുന്നു, "ഇത് ആരാണ്?"
ഞാൻ ചിരിക്കുന്നു.
ഞാൻ ഫോണുമായി ജനലിന്റെ അടുത്തേക്ക് നടക്കുന്നു.
ഞാൻ എന്റെ നായയോട് സംസാരിക്കുന്നു.
ഞാൻ ജനലിലൂടെ പുറത്തെ കാഴ്ച കാണിക്കുന്നു.
ഇവിടെ കൊച്ചിയിൽ ഒരുപാട് പച്ച മരങ്ങൾ ഉണ്ട്.
ലോല ആ മരങ്ങൾ നോക്കുന്നു.
അവൾ വീണ്ടും കുരയ്ക്കുന്നു.
ഡീഗോ ചോദിക്കുന്നു, "അവിടെ പുറത്ത് ആരുണ്ട്?"
ഞാൻ പറയുന്നു, "ഇവിടെ വേറെ ആരുമില്ല."
ഞാൻ എന്റെ കുടുംബത്തോട് പറയുന്നു, "മെക്സിക്കോയിലെ നമ്മുടെ വീട് എപ്പോഴും ഇങ്ങനെയാണ്."
"നിങ്ങളുടെ ഈ ബഹളം എനിക്ക് വലിയ ഇഷ്ടമാണ്, ഞാൻ അത് മിസ്സ് ചെയ്യുന്നു."
എനിക്ക് വളരെ സന്തോഷം തോന്നുന്നു.
