എനിക്ക് ഇപ്പോൾ നല്ല ക്ഷീണം ഉണ്ട്.
മാർക്കറ്റിൽ വലിയ തിരക്കാണ്.
ഞാൻ അവിടെ ഒരു ചെറിയ ചായവണ്ടി കാണുന്നു.
അവിടെ ഒരു പ്രായമുള്ള ആൾ ഉണ്ട്.
ഞാൻ അദ്ദേഹത്തോട് ഒരു ചായ ചോദിക്കുന്നു.
"എനിക്ക് ഒരു കട്ടൻ ചായ തരൂ," ഞാൻ പറയുന്നു.
ഞാൻ അവിടെ ചൂട് പലഹാരങ്ങൾ കാണുന്നു.
"എനിക്ക് ഒരു പഴംപൊരിയും വേണം," ഞാൻ പറയുന്നു.
കടക്കാരൻ എനിക്ക് ചായയും പഴംപൊരിയും തരുന്നു.
പഴംപൊരിക്ക് നല്ല ചൂടുണ്ട്.
അത് നല്ല മൊരിഞ്ഞതാണ്.
അതിന് നല്ല മധുരവും ഉണ്ട്.
ഞാൻ ചൂട് കട്ടൻ ചായ കുടിക്കുന്നു.
ചായയും പലഹാരവും വളരെ രുചികരമാണ്.
"ആകെ എത്ര രൂപ ആയി?" ഞാൻ കടക്കാരനോട് ചോദിക്കുന്നു.
"ഇരുപത്തിയഞ്ച് രൂപ," കടക്കാരൻ പറയുന്നു.
ഞാൻ എന്റെ ബാഗിൽ നിന്ന് നാണയങ്ങൾ എടുക്കുന്നു.
ഞാൻ കൃത്യം ഇരുപത്തിയഞ്ച് രൂപ അദ്ദേഹത്തിന് കൊടുക്കുന്നു.
എനിക്ക് ഇപ്പോൾ നല്ല ഉന്മേഷം ഉണ്ട്.
