Jest styczeń w Kopenhadze.
Stoję w moim tymczasowym pokoju.
Dzisiaj przeprowadzam się do nowego mieszkania.
Jest w tym samym budynku.
Moja duża walizka stoi na podłodze.
Zamykam ją.
Rozglądam się po pokoju po raz ostatni.
Zaglądam pod małe łóżko.
Pod łóżkiem leży książka.
Jest z Meksyku.
Wkładam książkę do mojej torby.
Otwieram szafę.
W szafie stoi para butów.
Biorę buty.
Teraz w szafie nic nie ma.
Podchodzę do biurka przy oknie.
Na biurku leży kabel.
Biorę kabel.
Wkładam kabel do mojej torby.
Biorę moje dwie torby.
Gaszę światło i zamykam drzwi.
