ഞങ്ങൾ ക്ലബ്ബിന് പുറത്തേക്ക് വരുന്നു.
കിരൺ, സാറ, വിഷ്ണു എന്നിവർ എന്റെ കൂടെയുണ്ട്.
അവർ എന്നോട് സംസാരിക്കുന്നു.
സാറ എന്നെ നോക്കി ചിരിക്കുന്നു.
"മായ, അടുത്ത ആഴ്ച വീണ്ടും വരാൻ കഴിയുമോ?" സാറ ചോദിക്കുന്നു.
എനിക്ക് ഈ പുതിയ സുഹൃത്തുക്കളെ വളരെ ഇഷ്ടമാണ്.
"തീർച്ചയായും, എനിക്ക് വരാൻ കഴിയും," ഞാൻ മറുപടി പറയുന്നു.
"അത് വളരെ നല്ലതാണ്," വിഷ്ണു പറയുന്നു.
അവർക്ക് വളരെ സന്തോഷമാകുന്നു.
"അടുത്ത വ്യാഴാഴ്ച കാണാം," കിരൺ പറയുന്നു.
ഞങ്ങൾ യാത്ര ചോദിക്കുന്നു.
ഞാൻ സന്തോഷത്തോടെ വീട്ടിലേക്ക് പോകുന്നു.
വ്യാഴാഴ്ചകളിൽ വൈകുന്നേരം അഞ്ചരയ്ക്ക് ഞാൻ ജിമ്മിൽ പോകാറുണ്ട്.
എന്നാൽ ഇനി ഒരു മാറ്റമുണ്ട്.
ഞാൻ ഇനി വ്യാഴാഴ്ചകളിൽ ബാഡ്മിന്റൺ കളിക്കാൻ പോകുന്നു.
ഇത് എന്റെ പുതിയ ദിനചര്യയാണ്.
