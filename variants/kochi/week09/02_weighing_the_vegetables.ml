അവിടെ നല്ല ചുവന്ന തക്കാളി ഉണ്ട്.
എനിക്ക് കുറച്ചു തക്കാളി വേണം.
"ഒരു കിലോ തക്കാളിക്ക് വില എത്രയാ?" ഞാൻ ചോദിക്കുന്നു.
"അറുപതു രൂപ," അദ്ദേഹം മറുപടി പറയുന്നു.
വില കൂടുതലല്ല.
"ശരി, എനിക്ക് രണ്ടു കിലോ തക്കാളി തരൂ," ഞാൻ അദ്ദേഹത്തോട് പറയുന്നു.
കച്ചവടക്കാരൻ നല്ല തക്കാളികൾ എടുക്കുന്നു.
അദ്ദേഹം അത് ഒരു ഇരുമ്പുത്രാസിൽ വെക്കുന്നു.
അദ്ദേഹം തക്കാളി തൂക്കുന്നു.
"കൃത്യം രണ്ടു കിലോ ഉണ്ട്," അദ്ദേഹം പറയുന്നു.
"ആകെ എത്ര രൂപ ആയി?" ഞാൻ ചോദിക്കുന്നു.
"നൂറ്റിയിരുപതു രൂപ," കച്ചവടക്കാരൻ പറയുന്നു.
ഞാൻ ബാഗിൽ നിന്ന് പണം എടുക്കുന്നു.
ഞാൻ അദ്ദേഹത്തിന് നൂറ്റിയിരുപതു രൂപ കൊടുക്കുന്നു.
അദ്ദേഹം തക്കാളി എന്റെ തുണിസഞ്ചിയിൽ ഇടുന്നു.
