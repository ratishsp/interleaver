Na obrazovce mého telefonu se objeví nová zpráva.
Píše se tam, že moje totožnost musí být ověřena.
„Jednorázový kód bude zaslán přes SMS,“ píše systém.
Čtu si pokyny ve spodní části obrazovky.
„Čekejte prosím.“
„Nezavírejte stránku.“
Dívám se na telefon a čekám.
Obrazovka zůstává prázdná a nic se neděje.
Uplyne deset sekund.
Uplyne dvacet sekund.
Tiše si pro sebe povzdychnu.
Začínám být trochu podrážděná.
Tyto automatické kódy obvykle chodí okamžitě.
Normálně to trvá jen sekundu.
Ale moje schránka je stále prázdná.
Zkontroluji čas na telefonu.
Možná je systém dnes večer prostě pomalý?
Rozhodnu se počkat ještě minutu.
