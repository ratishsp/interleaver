Jag kom till Odense lite över nio.
Jag lämnade stationen och gick direkt mot det gamla kvarteret.
Solen sken och jag njöt av den friska vårluften.
Efter en kort promenad förändrades staden.
Plötsligt stod jag på en smal gata med kullerstenar.
Kullerstenarna var slitna och gamla.
Jag tittade på de många små husen.
De låg tätt ihop på rad längs gatan.
Nästan alla husen var roliga och mycket sneda.
Varje hus visade sin helt egna personlighet.
Många av dem var målade i vackra, ljusa färger.
Jag lade särskilt märke till de gula och röda husen.
De färgglada väggarna lyste upp i vårsolen.
Jag älskade helt enkelt den gamla stadsdelen.
Jag stod och tittade länge på de sneda husen.
Varje hus hade sin egen glada färg.
Jag ville minnas den här gatan för alltid.
Därefter gick jag långsamt vidare nerför gatan.
