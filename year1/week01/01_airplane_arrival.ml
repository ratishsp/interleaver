വിമാനം ഇപ്പോൾ കോപ്പൻഹേഗനിലാണ്.
ഇപ്പോൾ ജനുവരിയാണ്.
ഞാൻ വളരെ ആവേശത്തിലാണ്.
ഞാൻ എന്റെ പുസ്തകം ബാഗിലാക്കുന്നു.
എന്റെ അടുത്തായി ഒരു യാത്രികനുണ്ട്.
അയാൾ എന്നെ നോക്കി പുഞ്ചിരിക്കുന്നു.
"ഹലോ," അയാൾ പറയുന്നു.
"ഹലോ," ഞാൻ പറയുന്നു.
"നിങ്ങളുടെ പേരെന്താണ്?" അയാൾ ചോദിക്കുന്നു.
"എന്റെ പേര് മായ എന്നാണ്," ഞാൻ പറയുന്നു.
"മായ, നിങ്ങൾ എവിടെ നിന്നാണ് വരുന്നത്?" അയാൾ ചോദിക്കുന്നു.
ഞാൻ സന്തോഷത്തോടെ പുഞ്ചിരിക്കുന്നു.
"ഞാൻ മെക്സിക്കോയിൽ നിന്നാണ് വരുന്നത്," ഞാൻ മറുപടി പറയുന്നു.
"നിങ്ങൾ ഡെൻമാർക്കിൽ നിന്നാണോ?" ഞാൻ ചോദിക്കുന്നു.
"അതെ, ഞാൻ ഡെൻമാർക്കിൽ നിന്നാണ്," അയാൾ പറയുന്നു.
"ഡെൻമാർക്കിലേക്ക് സ്വാഗതം," അയാൾ പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
ഇപ്പോൾ നമ്മൾ ഇവിടെയാണ്.
ഞാൻ തയ്യാറാണ്.
