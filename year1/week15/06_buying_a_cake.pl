Docieram do małej piekarni na rogu.
Wchodzę do ciepłego sklepu.
Pięknie pachnie kawą i ciastem.
Piekarz w białym fartuchu stoi za ladą.
– Dzień dobry – mówi piekarz.
– W czym mogę pomóc? – pyta.
Przyglądam się wielu ciastom.
Kupuję ciasto na dzisiejszy wieczór.
Wskazuję na ładne ciasto czekoladowe.
– Poproszę ciasto czekoladowe – mówię.
– Oczywiście – odpowiada piekarz.
Wkłada ciasto do białego pudełka.
– To będzie sześćdziesiąt pięć koron – mówi.
Wyjmuję portfel z torebki.
Płacę sześćdziesiąt pięć koron.
– Bardzo dziękuję i życzę miłego wieczoru – mówi piekarz.
– Dziękuję, nawzajem – odpowiadam.
Biorę białe pudełko.
Ostrożnie wychodzę ze sklepu z ciastem.
