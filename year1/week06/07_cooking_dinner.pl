Jestem w domu w moim mieszkaniu.
W kuchni robię kolację.
Myję świeże warzywa.
Siekam cebulę na desce do krojenia.
Kroję też dwa czerwone pomidory.
Biorę patelnię.
Na kuchence rozgrzewam trochę oleju.
Wrzucam warzywa na patelnię.
Smażę jedzenie.
Pachnie naprawdę dobrze.
Dodaję sól i pieprz do jedzenia.
Jedzenie jest gotowe.
Biorę talerz.
Nakładam jedzenie na talerz.
Przynoszę szklankę wody.
Siadam do stołu.
Jem kolację.
Jedzenie smakuje wspaniale.
Delektuję się spokojnym posiłkiem.
