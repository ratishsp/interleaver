ഞാനും സാറയും ഒരുമിച്ച് കളിക്കുന്നു.
കിരണും വിഷ്ണുവും ഞങ്ങൾക്ക് എതിരെ കളിക്കുന്നു.
കളി തുടങ്ങാൻ പോകുന്നു.
എനിക്ക് ബാഡ്മിന്റൺ കളിക്കാൻ വളരെ ഇഷ്ടമാണ്.
വിഷ്ണു ഷട്ടിൽക്കോക്ക് അടിക്കുന്നു.
ഞാൻ കോർട്ടിലൂടെ വേഗത്തിൽ ഓടുന്നു.
ഞാൻ ഷട്ടിൽക്കോക്ക് ശക്തിയായി അടിക്കുന്നു.
സാറയും വളരെ നന്നായി കളിക്കുന്നു.
കിരൺ വീണ്ടും ഷട്ടിൽക്കോക്ക് അടിക്കാൻ പോകുന്നു.
ഞാൻ പെട്ടെന്ന് ചാടുന്നു.
ഞാൻ ഷട്ടിൽക്കോക്ക് തിരികെ അടിക്കുന്നു.
ഞങ്ങൾക്ക് ഒരു പോയിന്റ് കിട്ടുന്നു.
സാറ സന്തോഷത്തോടെ ചിരിക്കുന്നു.
എനിക്ക് വീണ്ടും ബാഡ്മിന്റൺ കളിക്കാൻ കഴിയും.
ഇത് എന്റെ ഏറ്റവും പ്രിയപ്പെട്ട കളിയാണ്.
എനിക്ക് ഇപ്പോൾ വളരെ സന്തോഷമുണ്ട്.
