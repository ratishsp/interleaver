നിന പോയതിന് ശേഷം ഞാൻ വാതിലടയ്ക്കുന്നു.
ഇന്നത്തെ രാത്രിയിലേക്ക് ഞാൻ സ്ക്രീനുകളുടെ ഉപയോഗം പൂർണ്ണമായും അവസാനിപ്പിച്ചു.
ഞാൻ എന്റെ ഫോൺ ചാർജറിലിടുന്നു.
സാധാരണയായി അത് സോഫയിലാണ് വെക്കാറുള്ളത്, എന്നാൽ ഇപ്പോൾ അത് ചാർജ് ചെയ്യേണ്ടതുണ്ട്.
നാളെ ബുധനാഴ്ചയാണ്.
ബുധനാഴ്ച വൈകുന്നേരങ്ങളിൽ ഞാൻ സാധാരണയായി ജിമ്മിൽ വ്യായാമം ചെയ്യാറുണ്ട്.
തലേദിവസം രാത്രി തന്നെ സ്പോർട്സ് ബാഗ് പാക്ക് ചെയ്തു വെക്കുക എന്നതാണ് എന്റെ ഒരു ചെറിയ നിയമം.
ആദ്യം, ഇടനാഴിയിലെ അലമാരയിൽ നിന്ന് ബാഗ് എടുത്തു വെക്കുന്നു.
പിന്നീട് അതിലേക്ക് എന്റെ ഷൂസുകൾ എടുത്തു വെക്കുന്നു.
അടുക്കളയിൽ നിന്ന് ഞാൻ എന്റെ വാട്ടർ ബോട്ടിലും എടുക്കുന്നു.
അത് ശ്രദ്ധാപൂർവ്വം ഷൂസിനരികിലായി വെക്കുന്നു.
ഞാൻ എപ്പോഴും വൃത്തിയുള്ള വസ്ത്രങ്ങളാണ് കൂടെ കൊണ്ടുപോകാറുള്ളത്.
ആ വസ്ത്രങ്ങളും ബാഗിലേക്ക് എടുത്തു വെക്കുന്നു.
വേണ്ടതെല്ലാം ഉണ്ടെന്ന് ഞാൻ പരിശോധിക്കുന്നു.
അവസാനമായി, ആ ബാഗ് മുൻവാതിലിനരികിൽ തയ്യാറാക്കി വെക്കുന്നു.
അങ്ങനെയാകുമ്പോൾ, നാളെ രാവിലെ അത് മറന്നുപോകില്ല.
അങ്ങനെ ഇന്നത്തെ എന്റെ പ്രായോഗികമായ ജോലികളെല്ലാം കഴിഞ്ഞു.
ശാന്തമായ ഒരു സായാഹ്നത്തിനായി മാത്രമാണ് ഞാൻ ഇനി കാത്തിരിക്കുന്നത്.
