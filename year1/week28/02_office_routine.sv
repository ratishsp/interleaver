Jag sitter vid mitt skrivbord på kontoret.
Eva kommer över till mig med en kopp kaffe.
Vi jobbar tätt tillsammans den här veckan.
"Är du redo att titta på den nya layouten?" frågar hon.
"Ja, jag ska bara öppna programmet," svarar jag.
Vi tittar på den stora skärmen tillsammans.
Det stora digitala projektet ser äntligen bra ut.
Men plötsligt ser Eva ett litet fel i hörnet.
En blå knapp är lite för långt till vänster.
"Titta där, positionen är fel," säger hon.
"Du har rätt, jag måste flytta den till höger," säger jag.
Jag skriver snabbt några få rader kod.
Knappen flyttar sig till rätt plats.
"Perfekt, tack för hjälpen," säger Eva och ler varmt.
Vi pratar och skrattar tillsammans om våra planer för helgen.
Nu känner jag alla på kontoret väl.
