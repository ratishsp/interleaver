ഞാൻ ഇപ്പോൾ പുതിയ ഓഫീസിനുള്ളിലാണ്.
ഇതൊരു വലുതും വെളിച്ചമുള്ളതുമായ മുറിയാണ്.
വാതിലിനരികിൽ സൗമ്യനായ ഒരു മനുഷ്യൻ നിൽക്കുന്നു.
അദ്ദേഹം എന്നെ നോക്കി ചിരിക്കുന്നു.
"സ്വാഗതം!" അദ്ദേഹം പറയുന്നു.
"എന്റെ പേര് പീറ്റർ."
ഞാൻ അദ്ദേഹത്തിന് കൈ കൊടുക്കുന്നു.
"ഹായ് പീറ്റർ, എന്റെ പേര് മായ," ഞാൻ പറയുന്നു.
പീറ്റർ ഒരു സഹപ്രവർത്തകനാണ്.
ഞങ്ങൾ ഒരുമിച്ച് ഓഫീസിലൂടെ നടക്കുന്നു.
"നിങ്ങൾക്ക് ഇവിടെ ഒരു ഡെസ്ക് ഉണ്ട്," പീറ്റർ പറയുന്നു.
ഡെസ്കിന്റെ നമ്പർ പതിനാറാണ്.
"പിന്നെ നിങ്ങൾക്ക് ഒരു കമ്പ്യൂട്ടറും ഉണ്ട്," അദ്ദേഹം പറയുന്നു.
അദ്ദേഹം എനിക്ക് ഒരു പുതിയ ലാപ്ടോപ്പ് നൽകുന്നു.
ഞാൻ എന്റെ പുതിയ ഇരിപ്പിടം നോക്കുന്നു.
എനിക്ക് ഒരു കസേരയും വലിയൊരു മോണിറ്ററും ഉണ്ട്.
"വളരെ നന്ദി, പീറ്റർ," ഞാൻ പറയുന്നു.
എന്റെ ആദ്യത്തെ പ്രവൃത്തിദിവസത്തിനായി ഞാൻ തയ്യാറാണ്.
