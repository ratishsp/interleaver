Stojím u svého bytu.
Mám sáček se skořicovým šnekem.
Moje sousedka Nina je u dveří.
Široce se usmívá a říká ahoj.
„Ahoj Mayo, máš už dánské číslo?“ ptá se Nina.
„Ano, mám nové telefonní číslo,“ odpovídám.
„To je dobře,“ říká.
Mám v ruce svůj telefon.
„Jaké je tvoje číslo?“ ptám se.
„Moje číslo je osmdesát sedm, šedesát pět, čtyřicet tři, dvacet jedna,“ říká Nina.
Zapisuji si její číslo do telefonu.
„A moje číslo je dvanáct, třicet čtyři, padesát šest, sedmdesát osm,“ říkám.
Nina si ukládá moje číslo do telefonu.
Teď jsme v kontaktu.
Jdeme společně dovnitř.
Mám ze své nové kamarádky velkou radost.
