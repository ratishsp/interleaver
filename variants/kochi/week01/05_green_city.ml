ഇപ്പോൾ രാവിലെ ആണ്.
ഞാൻ ജനലിന്റെ അടുത്താണ്.
ഞാൻ ജനൽ തുറക്കുന്നു.
ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
കൊച്ചി വളരെ മനോഹരമാണ്.
ഇത് ഒരു പച്ച നഗരം ആണ്.
പുറത്ത് ഒരുപാട് മരങ്ങൾ ഉണ്ട്.
ഈ മരങ്ങൾ വളരെ പച്ചയാണ്.
ഇപ്പോൾ ജനുവരി മാസം ആണ്.
ഇവിടെ നല്ല കാലാവസ്ഥ ആണ്.
ജനലിലൂടെ കാറ്റ് വരുന്നു.
അത് നല്ല കടൽക്കാറ്റ് ആണ്.
കാറ്റ് എന്റെ മുഖത്ത് തട്ടുന്നു.
ഒരു നിമിഷം ഞാൻ മെക്സിക്കോ ഓർക്കുന്നു.
മെക്സിക്കോ എന്റെ സ്വന്തം നാടാണ്.
അവിടുത്തെ തെരുവുകൾ ഞാൻ ഓർക്കുന്നു.
മേശപ്പുറത്ത് എന്റെ ഫോൺ ഉണ്ട്.
ഞാൻ വൈകുന്നേരം എന്റെ കുടുംബത്തെ വിളിക്കും.
ഇപ്പോൾ ഞാൻ ഈ നല്ല കാറ്റ് ആസ്വദിക്കുന്നു.
