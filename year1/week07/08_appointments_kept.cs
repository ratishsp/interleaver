Přicházím ke kadeřnici o půl páté.
Jsem vždycky přesná.
Kadeřnice mě zdraví.
Myje a stříhá mi vlasy.
Trvá to asi hodinu.
Můj nový účes je velmi pěkný.
Děkuji kadeřnici a odcházím ze salonu.
Moje kolo stojí venku před vchodem.
Jedu na kole městem.
Je čtvrtek večer.
Jedu na kole do útulné kavárny.
Zaparkuji kolo a jdu dovnitř.
Nina už sedí u stolu.
Podívám se na hodinky.
Je přesně šest hodin.
„Ahoj Mayo, tvoje vlasy jsou opravdu krásné,“ říká Nina.
„Moc děkuji,“ říkám.
Objednáváme si dva šálky kávy.
Pijeme kávu a povídáme si.
Vždycky si naše schůzky u kávy užívám.
