ഞാൻ ആ ഷർട്ടും രസീതും കൗണ്ടറിൽ വെക്കുന്നു.
അവിടുത്തെ ജീവനക്കാരി എന്നെ സഹായിക്കാൻ തയ്യാറാണ്.
"ഹായ്, ഞാൻ ഈ ഷർട്ട് ശനിയാഴ്ച വാങ്ങിയതാണ്," ഞാൻ പറയുന്നു.
"പക്ഷേ നിർഭാഗ്യവശാൽ, ഇത് വളരെ ചെറുതാണ്."
"ഇത് മാറ്റി കുറച്ചുകൂടി വലിയ സൈസ് എടുക്കാൻ എനിക്ക് കഴിയുമോ?"
"അതെ, തീർച്ചയായും സാധിക്കും," ആ ജീവനക്കാരി മറുപടി നൽകുന്നു.
"നിങ്ങൾക്ക് ഏത് സൈസ് ആണ് വേണ്ടത്?"
"എനിക്ക് മീഡിയത്തിന് പകരം ലാർജ് ആണ് വേണ്ടത്," ഞാൻ വ്യക്തമാക്കുന്നു.
"ഒരു നിമിഷം," ആ ജീവനക്കാരി പറയുന്നു.
നീല ഷർട്ടുകൾ വെച്ചിരിക്കുന്ന ഷെൽഫുകൾക്ക് അടുത്തേക്ക് അവർ നടക്കുന്നു.
അവർ വേഗത്തിൽ ശരിയായ സൈസ് കണ്ടുപിടിച്ച് തിരികെ വരുന്നു.
"ഇതാ ഒരു ലാർജ്," ചിരിച്ചുകൊണ്ട് അവർ പറയുന്നു.
"നിങ്ങൾക്ക് ആദ്യം ഇതൊന്ന് ഇട്ടു നോക്കണമെന്നുണ്ടോ?"
"അതെ," സന്തോഷത്തോടെ ഞാൻ മറുപടി നൽകുന്നു.
"ഫിറ്റിംഗ് റൂമുകൾ ദാ അവിടെ വലതുവശത്താണ് ഉള്ളത്," അവർ എന്നോട് പറയുന്നു.
"സഹായത്തിന് വളരെ നന്ദി," ഞാൻ പറയുന്നു, ഒപ്പം പുതിയ ഷർട്ട് എടുക്കുകയും ചെയ്യുന്നു.
വലിയ ഷർട്ട് എനിക്ക് കൂടുതൽ അനുയോജ്യമാണോ എന്ന് എനിക്കിനി നോക്കാം.
