ഇന്ന് എൻ്റെ ജന്മദിനമാണ്.
എനിക്ക് ഇന്ന് മുപ്പത്തിരണ്ട് വയസ്സായി.
ഞാൻ രാവിലെ നേരത്തെ എഴുന്നേൽക്കുന്നു.
ഞാൻ വാതിൽ തുറന്ന് വരാന്തയിലേക്ക് ഇറങ്ങുന്നു.
എൻ്റെ അയൽക്കാരി അനിതയും അവരുടെ നായ ടോമിയും അവിടെ നിൽക്കുന്നുണ്ട്.
ടോമി സന്തോഷത്തോടെ എൻ്റെ അടുത്തേക്ക് ഓടിവരുന്നു.
ഞാൻ അവനെ തലോടുന്നു.
അനിത ചിരിച്ചുകൊണ്ട് എൻ്റെ അടുത്തേക്ക് വരുന്നു.
"ജന്മദിനാശംസകൾ, മായാ," അവർ പറയുന്നു.
അവർ എനിക്ക് ഒരു ചെറിയ പാത്രം തരുന്നു.
"ഞാൻ നിനക്ക് വേണ്ടി പായസം ഉണ്ടാക്കിയിട്ടുണ്ട്," അനിത പറയുന്നു.
"ഞാൻ ഇത് രാവിലെ നേരത്തെ ഉണ്ടാക്കി," അവർ കൂട്ടിച്ചേർക്കുന്നു.
ഞാൻ സന്തോഷത്തോടെ പാത്രം വാങ്ങുന്നു.
ഞാൻ പാത്രം തുറക്കുന്നു.
ചൂടുള്ള മധുരപ്പായസത്തിന് നല്ല മണമുണ്ട്.
ടോമി പായസത്തിലേക്ക് നോക്കുന്നു.
അവനും കുറച്ചു പായസം വേണം.
അനിത ചിരിച്ചുകൊണ്ട് അവനെ പുറകോട്ട് മാറ്റുന്നു.
"വളരെ നന്ദി, അനിത," ഞാൻ പറയുന്നു.
എൻ്റെ ദിവസം വളരെ മനോഹരമായി തുടങ്ങുന്നു.
