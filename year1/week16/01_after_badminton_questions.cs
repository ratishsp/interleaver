Kasper, Sara, Emil a já jsme hráli badminton skoro dvě hodiny.
Zápas teď skončil a my jsme byli příjemně unavení.
Přešli jsme k lavičce.
Společně jsme se posadili.
Otevřela jsem tašku a našla svou láhev s vodou.
Dlouho jsme jen pili studenou vodu.
„To byl těžký zápas,“ řekl Kasper.
Sara se usmála a podívala se na mě.
„Přijela jsi do Dánska v lednu, že?“ zeptala se.
„Ano, z Mexika jsem odcestovala v lednu,“ odpověděla jsem.
Kasper položil svou raketu na lavičku.
„Jaké byly tvé první dny v této zemi?“ zeptal se.
Zavzpomínala jsem na svůj první týden.
Všechno tehdy bylo nové a velmi odlišné.
Vůbec jsem to město neznala.
„Byla velká zima,“ začala jsem.
Kasper a Sara se nahlas zasmáli.
„Dánská zima je vždycky studená,“ řekla Sara.
Kasper se mě zeptal.
