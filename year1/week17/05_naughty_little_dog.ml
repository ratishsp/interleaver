ആ കുടുംബം ഒരു ചെറിയ നായയെയും ട്രെയിനിൽ കൊണ്ടുവന്നിരുന്നു.
അത് വളരെ ഓമനത്വമുള്ളതായിരുന്നു, പക്ഷേ അത് നിശ്ശബ്ദമായിരുന്നില്ല.
നായ തറയിൽ അതിന്റെ ചെറിയ കുട്ടയിൽ കിടക്കുകയായിരുന്നു.
അച്ഛൻ വീണ്ടും താഴെ തന്റെ പുസ്തകത്തിലേക്ക് നോക്കി.
അദ്ദേഹത്തിന് കുറച്ചൊന്ന് വായിക്കണമെന്ന് മാത്രമേ ഉണ്ടായിരുന്നുള്ളൂ.
എന്നാൽ പെട്ടെന്ന് ആ നായ അതിന്റെ കുട്ടയിൽ നിന്ന് പുറത്തേക്ക് ചാടി.
അത് വേഗത്തിൽ അച്ഛന്റെ അടുത്തേക്ക് ഓടി.
അദ്ദേഹം ഒരു കാൽ ഒരു ബാഗിന് മുകളിൽ വെച്ചാണ് ഇരുന്നിരുന്നത്.
നായ അദ്ദേഹത്തിന്റെ ഇടത്തെ ഷൂ തട്ടിയെടുത്തു.
അത് ആ ഷൂ അതിന്റെ വായിലെടുത്തു.
എന്നിട്ട് അത് വേഗത്തിൽ ഓടിക്കളഞ്ഞു.
"വേണ്ട, എന്റെ ഷൂവും കൊണ്ട് തിരികെ വാ!" അച്ഛൻ ഉറക്കെ വിളിച്ചുപറഞ്ഞു.
അദ്ദേഹം സോക്സുകളോടെ തന്നെ എഴുന്നേറ്റുനിന്നു.
അദ്ദേഹം ഇടനാഴിയിലൂടെ നായയുടെ പിന്നാലെ ഓടി.
ആ രണ്ട് കുട്ടികളും അദ്ദേഹത്തിന് നേരെ വിരൽ ചൂണ്ടി.
അവർ പരസ്പരം നോക്കി ഉറക്കെ ചിരിച്ചു.
എന്റെ സീറ്റിലിരുന്ന് ഞാൻ അവരെ നോക്കി.
ഞാനും എന്റെ പുസ്തകത്തിന് പിന്നിൽ ചെറുതായി ചിരിച്ചു.
ഭാഗ്യവശാൽ, അവസാനം അദ്ദേഹം തന്റെ നായയെ പിടികൂടി.
അദ്ദേഹത്തിന് തന്റെ ഷൂവും തിരികെ ലഭിച്ചു.
