എന്റെ തുണിസഞ്ചികൾ ഇപ്പോൾ നിറഞ്ഞു.
അവയ്ക്ക് നല്ല ഭാരമുണ്ട്.
ഞാൻ എന്റെ വാച്ച് നോക്കുന്നു.
സമയം പത്ത് മണി.
ഞാൻ വളരെ സന്തോഷത്തിലാണ്.
ഞാൻ മാർക്കറ്റിലെ തിരക്കിൽ നിന്ന് പുറത്തേക്ക് നടക്കുന്നു.
അവിടെ കുറച്ച് ഓട്ടോകൾ കിടക്കുന്നുണ്ട്.
ഞാൻ ഒരു ഓട്ടോയുടെ അടുത്തേക്ക് പോകുന്നു.
"എന്റെ വീടിന്റെ അടുത്ത് വരെ വരാമോ?" ഞാൻ ഡ്രൈവറോട് ചോദിക്കുന്നു.
"വരാം," അയാൾ പറയുന്നു.
"അവിടേക്ക് എത്ര രൂപയാണ്?" ഞാൻ ചോദിക്കുന്നു.
"നൂറ്റിയമ്പത് രൂപ," അയാൾ മറുപടി പറയുന്നു.
ഞാൻ ശരി എന്ന് പറയുന്നു.
അയാൾ എന്റെ സഞ്ചികൾ ഓട്ടോയിൽ വെക്കാൻ സഹായിക്കുന്നു.
ഞാൻ ഓട്ടോയിൽ കയറുന്നു.
ഓട്ടോ മുന്നോട്ട് പോകുന്നു.
ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
ഇന്നത്തെ ഷോപ്പിംഗ് വളരെ നന്നായി.
