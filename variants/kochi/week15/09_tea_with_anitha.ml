വൈകുന്നേരം ഞാൻ അനിതയുടെ വാതിലിൽ മുട്ടുന്നു.
അനിത വാതിൽ തുറക്കുന്നു.
അവർ എന്നെ കണ്ട് സന്തോഷത്തോടെ ചിരിക്കുന്നു.
"അകത്തേക്ക് വരൂ, മായ," അനിത പറയുന്നു.
ഞാൻ അകത്തേക്ക് പോകുന്നു.
ഞങ്ങൾ സോഫയിൽ ഇരിക്കുന്നു.
അനിത എനിക്ക് ഒരു കപ്പ് ചൂട് ചായ തരുന്നു.
ചായയ്ക്ക് നല്ല രുചിയുണ്ട്.
ഞങ്ങൾ പതുക്കെ ചായ കുടിക്കുന്നു.
"ഇന്നത്തെ ദിവസം എങ്ങനെയുണ്ട്?" അവർ ചോദിക്കുന്നു.
ഞാൻ ഓഫീസിലെ കാര്യങ്ങൾ അവരോട് പറയുന്നു.
"ഇന്ന് ഓഫീസിലെ ജോലി വളരെ എളുപ്പമാണ്," ഞാൻ പറയുന്നു.
അനിത അവരുടെ ദിവസത്തെക്കുറിച്ച് സംസാരിക്കുന്നു.
"ഞാൻ ഇന്ന് വീട്ടിൽ ആണ്," അവർ പറയുന്നു.
"ഞാൻ ഒരു മലയാളം പുസ്തകം വായിക്കുന്നു."
ഞങ്ങൾ ഒരുപാട് നേരം സംസാരിക്കുന്നു.
അനിതയോട് സംസാരിക്കുന്നത് എനിക്ക് വലിയ ഇഷ്ടമാണ്.
അവരുടെ വീട് എപ്പോഴും വളരെ ശാന്തമാണ്.
ചായ കുടിച്ച ശേഷം ഞാൻ എൻ്റെ ഫ്ലാറ്റിലേക്ക് മടങ്ങുന്നു.
എനിക്ക് ഇപ്പോൾ വളരെ സന്തോഷമുണ്ട്.
