Jag står framför byggnad nummer tolv.
Jag hittar Evas namn och ringer på.
Dörren öppnas, och jag går uppför trappan.
Eva står i dörren och ler stort.
"Hej Maya, välkommen!" säger hon och ger mig en kram.
"Tack för inbjudan", svarar jag.
Jag stiger in i hennes lägenhet.
Den är väldigt mysig och full av färgglad konst.
Jag ger henne de gula tulpanerna.
Jag hoppas att hon inte redan har en vas med blommor på bordet.
Eva tittar på blommorna och ser mycket glad ut.
"Vad vackra de är!" utbrister hon.
"Jag älskar gula blommor."
Jag känner att jag ofta förstår hennes kreativa smak.
"Jag ska hitta en vas till dem med detsamma", säger Eva.
"Det är bara att gå in i vardagsrummet", fortsätter hon.
Jag tar av mig skorna och går in dit.
Matbordet är vackert dukat med fina glas.
Jag har tänkt mig att koppla av och njuta av kvällen.
