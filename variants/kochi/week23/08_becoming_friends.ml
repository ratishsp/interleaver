ഞങ്ങൾ ഭക്ഷണം കഴിച്ച് സ്വീകരണമുറിയിലേക്ക് പോകുന്നു.
ദീപ ചൂടുള്ള ജീരകവെള്ളം കൊണ്ടുവരുന്നു.
ഞാൻ ഹൽവയുടെ പെട്ടി തുറക്കുന്നു.
"നമുക്ക് ഇപ്പോൾ ഈ മധുരം കഴിക്കാം," ഞാൻ പറയുന്നു.
ദീപ ഒരു കഷണം ഹൽവ എടുക്കുന്നു.
"ഇതിന് നല്ല രുചിയുണ്ട്," ദീപ പറയുന്നു.
പുറത്ത് നല്ല മഴ പെയ്യുന്നുണ്ട്.
ഞങ്ങൾ ഞങ്ങളുടെ കുടുംബങ്ങളെക്കുറിച്ച് സംസാരിക്കുന്നു.
ദീപ മെക്സിക്കോയെക്കുറിച്ച് ചോദിക്കുന്നു.
"എന്റെ കുടുംബം മെക്സിക്കോയിലാണ്," ഞാൻ പറയുന്നു.
"ഞാൻ ഒരു ദിവസം മെക്സിക്കോയിൽ വരും," ദീപ പറയുന്നു.
"കൊച്ചി മനോഹരമായ ഒരു സ്ഥലമാണെന്ന് ഞാൻ കരുതുന്നു," ഞാൻ പറയുന്നു.
ദീപ സന്തോഷത്തോടെ ചിരിക്കുന്നു.
"തിങ്കളാഴ്ചയും മഴ പെയ്യും," ദീപ പറയുന്നു.
"നമുക്ക് ഒരുമിച്ച് ഓഫീസിൽ പോകാം," അവർ പറയുന്നു.
ഇപ്പോൾ, ഞങ്ങൾ വെറും സഹപ്രവർത്തകർ മാത്രമല്ല.
ഞങ്ങൾ നല്ല സുഹൃത്തുക്കളാണെന്ന് ഞാൻ കരുതുന്നു.
