ഇന്ന് ജോലി കഴിഞ്ഞു.
ഞാൻ എം ജി റോഡിലേക്ക് നടക്കുന്നു.
പുറത്ത് നല്ല ചൂട് ആണ്.
ഞാൻ ഒരു വലിയ തുണിക്കടയിൽ കയറുന്നു.
ഇത് ഒരു വലിയ കട ആണ്.
ഇവിടെ ഒരുപാട് തുണികൾ ഉണ്ട്.
ഒരു സെയിൽസ്‌വുമൺ എന്റെ അടുത്തേക്ക് വരുന്നു.
അവർ ചോദിക്കുന്നു.
"എന്താണ് വേണ്ടത്?"
ഞാൻ പറയുന്നു.
"എനിക്ക് കോട്ടൺ തുണികൾ വേണം."
എനിക്ക് ഓഫീസിൽ ധരിക്കാൻ നല്ല കോട്ടൺ തുണികൾ വേണം.
ചൂട് കാരണം കോട്ടൺ തുണികൾ ആണ് നല്ലത്.
സെയിൽസ്‌വുമൺ പറയുന്നു.
"ശരി, എന്റെ കൂടെ വരൂ."
ഞങ്ങൾ കോട്ടൺ സെക്ഷനിൽ പോകുന്നു.
ഞാൻ ചുറ്റും നോക്കുന്നു.
കോട്ടൺ സെക്ഷനിൽ നല്ല സെലക്ഷൻ ഉണ്ട്.
ഇവിടെ മുതിർന്നവർക്കും കുട്ടികൾക്കുമുള്ള വസ്ത്രങ്ങൾ ഉണ്ട്.
എനിക്ക് ഈ വലിയ കട ഇഷ്ടമാണ്.
