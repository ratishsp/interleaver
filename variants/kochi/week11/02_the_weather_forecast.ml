ഞാൻ കാപ്പി കുടിക്കുന്നു.
ഞാൻ എൻ്റെ മൊബൈൽ ഫോൺ എടുക്കുന്നു.
ഞാൻ ഫോണിൽ കാലാവസ്ഥാ ആപ്പ് തുറക്കുന്നു.
ഇന്നത്തെ കാലാവസ്ഥ എങ്ങനെയാണ്?
ആപ്പിൽ ഒരു സൂര്യൻ്റെ ചിത്രമുണ്ട്.
രാവിലെ നല്ല വെയിലാണ്.
പുറത്ത് നല്ല ചൂടാണ്.
ഇപ്പോൾ മഴ പെയ്യുന്നില്ല.
ഞാൻ വൈകുന്നേരത്തെ കാലാവസ്ഥ നോക്കുന്നു.
ആപ്പിൽ മഴയുടെ ഒരു ചിത്രമുണ്ട്.
വൈകുന്നേരം മഴ പെയ്യും.
ആകാശത്ത് ഇപ്പോൾ മേഘങ്ങൾ ഇല്ല.
ഞാൻ ബാക്കി കാപ്പി കുടിക്കുന്നു.
ഞാൻ കപ്പ് മേശപ്പുറത്ത് വെക്കുന്നു.
