Jag är ledig från jobbet.
Jag går ut på ett stort torg.
Det är många människor i staden i dag.
En man går fram till mig.
Han har en stor kamera.
Han är turist.
Han ler och säger hej.
"Var ligger museet?" frågar turisten.
Jag känner väl till museet.
Det är inte långt borta.
Jag pekar nerför gatan.
"Du går rakt fram," förklarar jag.
"Sedan svänger du till vänster."
"Museet ligger på höger sida."
"Tack så mycket för hjälpen," säger mannen.
"Varsågod," svarar jag glatt.
Han går nerför gatan.
Jag går vidare mot bageriet.
