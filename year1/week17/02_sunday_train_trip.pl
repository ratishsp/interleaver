Napisałam w pamiętniku o mojej wycieczce do Odense.
To był piękny sobotni poranek.
Obudziłam się wcześnie o siódmej.
Słońce świeciło, a niebo było niebieskie.
Spakowałam mój mały, zielony plecak.
Włożyłam notatnik i aparat do torby.
Wzięłam też ze sobą gruby sweter.
Wiosenna pogoda w Danii może być trochę chłodna.
Potem pojechałam autobusem na duży dworzec w Kopenhadze.
W środku było wielu zabieganych ludzi.
Podeszłam do małego kiosku.
Kupiłam dużą, ciepłą kawę na podróż.
Kosztowała czterdzieści pięć koron.
Spojrzałam w górę na duży ekran.
Szybko znalazłam mój pociąg na ekranie.
Jechałam szybkim pociągiem do Odense.
Pociąg przyjechał na peron dokładnie o ósmej.
Weszłam do pociągu i znalazłam swoje miejsce przy dużym oknie.
Piłam moją ciepłą kawę i cieszyłam się na wycieczkę.
