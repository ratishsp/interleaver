കൊച്ചിയിൽ ഇപ്പോൾ വൈകുന്നേരം ആണ്.
എന്റെ മുറിയിൽ ഒരു കട്ടിൽ ഉണ്ട്.
ഞാൻ കട്ടിലിൽ ഇരിക്കുന്നു.
ഞാൻ എന്റെ അമ്മയെ വിളിക്കുന്നു.
അമ്മ മെക്സിക്കോയിൽ ആണ്.
"ഹലോ മായാ," അമ്മ പറയുന്നു.
"അമ്മേ, ഞാൻ കൊച്ചിയിൽ ആണ്," ഞാൻ പറയുന്നു.
"നീ ഫ്ലാറ്റിൽ ആണോ?" അമ്മ ചോദിക്കുന്നു.
"അതെ അമ്മേ, ഞാൻ എന്റെ ഫ്ലാറ്റിൽ ആണ്," ഞാൻ പറയുന്നു.
"അവിടെ എല്ലാം സുരക്ഷിതം ആണോ?" അമ്മ ചോദിക്കുന്നു.
"അതെ, ഞാൻ ഇവിടെ സുരക്ഷിത ആണ്," ഞാൻ പറയുന്നു.
"നിനക്ക് അവിടെ നല്ല ജോലി ഉണ്ടോ?" അമ്മ ചോദിക്കുന്നു.
"ഉണ്ട് അമ്മേ, എനിക്ക് ഇവിടെ നല്ല ജോലി ഉണ്ട്," ഞാൻ പറയുന്നു.
"സോഫിയയും ഡീഗോയും എവിടെ ആണ്?" ഞാൻ ചോദിക്കുന്നു.
"അവർ ഇവിടെ ഉണ്ട്," അമ്മ പറയുന്നു.
"നമ്മുടെ നായ ലോലയും ഇവിടെ ഉണ്ട്," അമ്മ പറയുന്നു.
ഞാൻ സന്തോഷത്തോടെ ചിരിക്കുന്നു.
ഞാൻ ഫോൺ വെക്കുന്നു.
