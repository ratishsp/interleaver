Jag går fram till kassan med mina nya saker.
Expediten tittar upp och säger hej.
"Hej", säger hon.
"Hej", svarar jag.
Jag lägger den ljusgröna jackan och den blå skjortan på disken.
Hon skannar in båda sakerna.
"Det blir sexhundrafemtio kronor", säger hon.
Jag betalar med mitt kort.
"Vill du ha kvittot?" frågar expediten.
"Ja tack", svarar jag snabbt.
"Jag har inte provat skjortan", förklarar jag.
"Jag hoppas att jag inte behöver en större."
"Du kan alltid byta den", säger expediten vänligt.
Hon skriver ut kvittot och ger mig det.
"Kom ihåg att spara det", säger hon.
Jag tar emot kvittot.
Jag viker det lilla papperet.
Sedan lägger jag ner det säkert i min plånbok.
"Ha en trevlig helg", säger jag till henne.
"Detsamma", svarar hon.
