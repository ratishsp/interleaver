Spojrzałam na Kaspera i Sarę i uśmiechnęłam się.
"Mój pierwszy dzień był wielką przygodą" - powiedziałam.
Przypomniałam sobie zimne powietrze na lotnisku.
Kasper zapytał:
"Jaka była pogoda?"
"Niebo było całkowicie szare" - odpowiedziałam.
Stałam przed lotniskiem z moją dużą walizką.
Wiał wiatr, ale cieszyłam się, że tu jestem.
Sara napiła się trochę wody i pokiwała głową.
"To brzmi jak duża zmiana w porównaniu z Meksykiem" - powiedziała.
Znalazłam taksówkę przed budynkiem.
Taksówkarz był miły i mi pomógł.
Zapytał o mój nowy adres.
Powiedziałam mój adres na głos.
"Dobrze znam tę ulicę" - powiedział kierowca.
Pojechaliśmy w stronę miasta.
Podczas jazdy patrzyłam przez okno.
Wszyscy ludzie mieli na sobie ciepłe płaszcze i szaliki.
Sara zapytała:
"Byłaś zdenerwowana?"
"Tak, trochę" - odpowiedziałam.
Ale nie mogłam się też doczekać mojego nowego mieszkania.
