ഞാൻ ഫോർട്ട് കൊച്ചിയിൽ വാട്ടർ മെട്രോയിൽ നിന്ന് ഇറങ്ങുന്നു.
പുറത്ത് നല്ല ചൂടുണ്ട്.
ഇവിടെ അടുത്തായി ഒരു ചെറിയ മസാലക്കടയുണ്ട്.
എനിക്ക് ആ കടയിലേക്ക് പോകണം.
ഞാൻ നേരെ കടയിലേക്ക് നടക്കുന്നു.
ഞാൻ കടയുടെ ഉള്ളിലേക്ക് കയറുന്നു.
അവിടെ ഒരാൾ നിൽക്കുന്നുണ്ട്.
ഞാൻ അയാളോട് ചിരിക്കുന്നു.
"നമസ്കാരം, എന്താണ് വേണ്ടത്?" അയാൾ ചോദിക്കുന്നു.
"നമസ്കാരം," ഞാൻ പറയുന്നു.
"എനിക്ക് ഒരു പാക്കറ്റ് കുരുമുളക് വേണം."
"ഇത് എന്റെ കുടുംബത്തിന് വേണ്ടിയാണ്."
"അവർ മെക്സിക്കോയിലാണ്."
"പുതിയ കുരുമുളക് ഉണ്ടോ?"
അയാൾ സന്തോഷത്തോടെ തലയാട്ടുന്നു.
അയാൾ എനിക്ക് ഒരു പാക്കറ്റ് തരുന്നു.
"ഇത് പുതിയതാണ്, വളരെ നല്ല കുരുമുളകാണ്," അയാൾ പറയുന്നു.
ഞാൻ പണം കൊടുക്കുന്നു.
കൊച്ചിയിലെ കുരുമുളക് എന്റെ കുടുംബത്തിന് തീർച്ചയായും ഇഷ്ടമാകും.
