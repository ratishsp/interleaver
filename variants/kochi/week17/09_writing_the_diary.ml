ഇപ്പോൾ ഞാൻ എന്റെ അപ്പാർട്ട്മെന്റിൽ തിരിച്ചെത്തി.
രാത്രിയായി.
മുറിയിൽ നല്ല സുഖമുണ്ട്.
ഞാൻ എന്റെ യാത്രാ ഡയറിയുമായി മേശയ്ക്കരികിൽ ഇരിക്കുന്നു.
ഞാൻ സ്വന്തം ഡയറിയിൽ ഇന്നത്തെ ഓർമ്മകൾ എഴുതുന്നു.
ഇന്ന് വളരെ മനോഹരമായ ഒരു ദിവസമായിരുന്നു.
രാവിലെ ഞാൻ ട്രെയിനിൽ പോയി.
പകൽ പന്ത്രണ്ട് മണിക്ക് ഞാൻ ഒരു ബോട്ടിൽ കയറി.
ഞാൻ ഒരുപാട് മനോഹരമായ സ്ഥലങ്ങൾ കണ്ടു.
ഞാൻ സ്വന്തം ക്യാമറയിൽ എടുത്ത ഫോട്ടോകളും നോക്കുന്നു.
ഇന്ന് എന്റെ അനിയത്തി സോഫിയ അവളുടെ ഫോട്ടോകൾ എനിക്ക് അയച്ചുതന്നു.
അവൾ അവളുടെ സുഹൃത്തുക്കൾക്കൊപ്പം ആയിരുന്നു.
പക്ഷേ, കൊച്ചിക്ക് പുറത്തേക്കുള്ള എന്റെ ആദ്യത്തെ ഒറ്റയ്ക്കുള്ള യാത്രയായിരുന്നു ഇത്.
യാത്ര വളരെ നന്നായി നടന്നു.
ഞാൻ ഡയറി അടയ്ക്കുന്നു.
നാളെ തിങ്കളാഴ്ചയാണ്, എനിക്ക് ഓഫീസിൽ പോകണം.
അതുകൊണ്ട് ഞാൻ ഉറങ്ങാൻ പോകുന്നു.
