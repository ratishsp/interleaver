I förmiddag har vi haft otroligt mycket att göra.
Jag har precis gjort min allra första cappuccino.
Strax före tio kom en man fram till disken.
"En cappuccino, tack," sa han.
Jag har precis lärt mig att använda espressomaskinen.
Så jag gick fram till maskinen direkt.
Jag bryggde kaffet och satte ner ångröret i mjölken.
Men jag höll det lite för djupt ner.
Jag har nog varit lite för nervös.
Tyvärr blev det inget tjockt skum på mjölken.
Jag tittade försiktigt ner i kannan.
Skummet var inte helt perfekt.
Men det såg ändå acceptabelt ut.
Jag hällde den varma mjölken över kaffet i koppen.
Därefter gav jag kaffet till mannen med ett artigt leende.
"Varsågod, det blir femtiofem kronor," sa jag.
Han tog koppen och satte sig vid det första bordet.
