Jag går vidare på marknaden och stannar vid ett klädstånd.
Jag ser en tung vinterkappa av ull.
Den här kappan är vacker, men väldigt tjock.
Jag provar kappan ändå.
Den är otroligt varm.
Jag tar av mig den igen direkt.
Det är juli, och solen skiner i dag.
En vänlig kvinna står bakom bordet och ler.
"Är den för varm?" frågar kvinnan.
"Ja, den är lite för varm för sommaren", svarar jag och skrattar.
Jag rör vid det tjocka tyget.
"Men jag behövde verkligen den här vinterkappan för fem månader sedan!" säger jag.
Kvinnan skrattar högt.
"Ja, februari var mycket kall", säger hon.
Jag minns mina första veckor i Köpenhamn.
Jag frös konstant då.
Lyckligtvis behöver jag inte så varma kläder just nu.
Jag hänger tillbaka kappan på klädställningen och säger hejdå.
