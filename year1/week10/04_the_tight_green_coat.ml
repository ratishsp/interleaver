എനിക്ക് ഒരു വിന്റർ ജാക്കറ്റ് കൂടി ആവശ്യമുണ്ട്.
ഞാൻ കടയിൽ കൂടുതൽ വസ്ത്രങ്ങൾ നോക്കുന്നു.
ഞാൻ മനോഹരമായ ഒരു പച്ച കോട്ട് കണ്ടെത്തുന്നു.
അതൊരു വളരെ മനോഹരമായ ഡിസൈൻ ആണ്.
ഞാൻ ആ പച്ച കോട്ട് ധരിക്കുന്നു.
എന്നാൽ അത് വളരെ ചെറുതാണ്.
ചുമലുകളുടെ ഭാഗത്ത് അത് വളരെ ഇറുകിയതാണ്.
"നിങ്ങളുടെ പക്കൽ ഇതിന്റെ മറ്റൊരു സൈസ് ഉണ്ടോ?" ഞാൻ ചോദിക്കുന്നു.
കടയിലെ സഹായി നോക്കുന്നു.
"ഇല്ല, നിർഭാഗ്യവശാൽ," അവൾ മറുപടി നൽകുന്നു.
അതിനാൽ ഞാൻ ആ പച്ച കോട്ട് തിരികെ തൂക്കിയിടുന്നു.
കടയിലെ സഹായി എനിക്കായി മറ്റൊരു ജാക്കറ്റ് കണ്ടെത്തുന്നു.
അത് ചൂടുനൽകുന്ന, കടും നീല നിറത്തിലുള്ള ഒരു വിന്റർ ജാക്കറ്റാണ്.
ഞാൻ ആ കടും നീല ജാക്കറ്റ് ധരിക്കുന്നു.
അത് കൃത്യമായി പാകമാണ്.
അത് നല്ല വലുപ്പമുള്ളതും ഒട്ടും ഇറുകിയതല്ലാത്തതുമാണ്.
ഞാൻ ഒരു വലിയ കണ്ണാടിയിൽ നോക്കുന്നു.
എനിക്കിത് ഇഷ്ടമായി.
"ഞാൻ ഇതെടുക്കാം," ഞാൻ പറയുന്നു.
