കടക്കാരൻ ഹൽവ ഒരു ചെറിയ പെട്ടിയിൽ വെക്കുന്നു.
അത് നല്ല ചുവന്ന ഹൽവയാണ്.
"ഇതിന് എന്താണ് വില?" ഞാൻ ചോദിക്കുന്നു.
"അമ്പതു രൂപ," കടക്കാരൻ പറയുന്നു.
ഞാൻ എന്റെ ബാഗ് തുറക്കുന്നു.
ഞാൻ കൃത്യം അമ്പതു രൂപ കൊടുക്കുന്നു.
"ഇത് ആര് ഉണ്ടാക്കുന്നു?" ഞാൻ ചോദിക്കുന്നു.
"എന്റെ ചേട്ടൻ ഉണ്ടാക്കുന്നു," അദ്ദേഹം പറയുന്നു.
"നിങ്ങളുടെ കട വളരെ നല്ലതാണ്," ഞാൻ പറയുന്നു.
അദ്ദേഹം സന്തോഷത്തോടെ ചിരിക്കുന്നു.
ഞാൻ പെട്ടി വാങ്ങുന്നു.
ഞാൻ അദ്ദേഹത്തോട് നന്ദി പറയുന്നു.
ഞാൻ കടയിൽ നിന്ന് പുറത്തിറങ്ങുന്നു.
ഞാൻ എന്റെ അപ്പാർട്ട്മെന്റിലേക്ക് നടക്കുന്നു.
