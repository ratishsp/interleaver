ഞങ്ങൾ മൂന്നുപേരും മേശയ്ക്ക് ചുറ്റും ഇരിക്കുന്നു.
ആദ്യം ഞാൻ അവർക്ക് ചോറ് വിളമ്പുന്നു.
അതിനുശേഷം ഞാൻ ചിക്കൻ കറി എടുക്കുന്നു.
കിരൺ ചോദിക്കുന്നു, "മായ, ഞാൻ കുറച്ച് കറി എടുക്കട്ടെ?"
ഞാൻ പറയുന്നു, "തീർച്ചയായും, ആദ്യം രണ്ട് സ്പൂൺ കറി ഒഴിക്കൂ."
പിന്നെ സാറയും കറി എടുക്കുന്നു.
ഞങ്ങൾ ഒരുമിച്ച് ഭക്ഷണം കഴിക്കാൻ തുടങ്ങുന്നു.
സാറ കുറച്ച് കറി കഴിക്കുന്നു.
അവൾ സന്തോഷത്തോടെ പറയുന്നു, "മായ, ഇത് വളരെ രുചികരമാണ്!"
കിരണും സമ്മതിക്കുന്നു.
അവൻ പറയുന്നു, "അതെ, ഇതിന് നല്ല തനി കേരള കറിയുടെ രുചിയാണ്."
ഞാൻ അവരോട് നന്ദി പറയുന്നു.
എനിക്ക് വളരെ സന്തോഷം തോന്നുന്നു.
അവർ കൂടുതൽ ചോറും കറിയും കഴിക്കുന്നു.
ഞങ്ങൾ ബാഡ്മിന്റൺ കളിയെക്കുറിച്ച് സംസാരിക്കുന്നു.
പുറത്ത് ഇപ്പോഴും മഴയുടെ ശബ്ദം കേൾക്കാം.
ഈ ഞായറാഴ്ച ഉച്ചഭക്ഷണം വളരെ നല്ലൊരു അനുഭവമാണ്.
