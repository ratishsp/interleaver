ഇന്ന് ഞായറാഴ്ചയാണ്.
വളരെ ചൂടുള്ള ഒരു പ്രഭാതം ആയിരുന്നു അത്.
നഗരത്തിലെ ചൂട് എനിക്ക് സഹിക്കാൻ കഴിഞ്ഞില്ല.
ഈ ചൂടിൽ നിന്ന് രക്ഷപ്പെടാൻ ഞാൻ തീരുമാനിച്ചു.
എനിക്ക് തെക്കുള്ള ഒരു തീരദേശ നഗരത്തിലേക്ക് പോകണമായിരുന്നു.
ഞാൻ വേഗം എന്റെ സ്വന്തം ബാഗ് എടുത്തു.
പിന്നെ ഞാൻ പുറത്തിറങ്ങി ഒരു ഓട്ടോറിക്ഷ വിളിച്ചു.
ഓട്ടോ ഡ്രൈവർ വളരെ നല്ലൊരു ആളായിരുന്നു.
"എങ്ങോട്ടാണ് പോകേണ്ടത്?" അയാൾ ചോദിച്ചു.
"എറണാകുളം റെയിൽവേ സ്റ്റേഷനിലേക്ക്," ഞാൻ മറുപടി പറഞ്ഞു.
ഞങ്ങൾ ഒൻപത് മണിക്ക് സ്റ്റേഷനിൽ എത്തി.
ഞാൻ ടിക്കറ്റ് കൗണ്ടറിൽ പോയി.
ഞാൻ ആലപ്പുഴയ്ക്ക് ഒരു ടിക്കറ്റ് വാങ്ങി.
ടിക്കറ്റിന് അൻപത് രൂപ ആയിരുന്നു.
അതിനുശേഷം ഞാൻ പ്ലാറ്റ്‌ഫോമിലേക്ക് നടന്നു.
പ്ലാറ്റ്‌ഫോം മുഴുവൻ ആളുകളെക്കൊണ്ട് നിറഞ്ഞിരുന്നു.
ഞാൻ എന്റെ ട്രെയിൻ വരാൻ അവിടെ കാത്തുനിന്നു.
നഗരത്തിന് പുറത്തേക്കുള്ള എന്റെ ആദ്യത്തെ യാത്രയായിരുന്നു അത്.
