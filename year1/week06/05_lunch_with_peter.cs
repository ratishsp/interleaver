Uprostřed dne jdu dolů do jídelny.
Místnost je světlá a příjemná.
U bufetu stojí mnoho lidí.
Vidím svého kolegu Petera.
Bere si talíř s jídlem.
„Ahoj Mayo,“ říká s úsměvem.
„Ahoj Petere,“ odpovídám.
Bereme si trochu chleba a salát.
Společně nacházíme stůl číslo devět u okna.
Sedáme si na židle.
Jídlo chutná opravdu dobře.
Peter vypráví o svém projektu.
Pracuje s novým softwarem.
Poslouchám a přikyvuji.
Nakonec mluvím o svém vlastním kódu.
Pijeme sklenici vody.
Během přestávky si to moc užívám.
Brzy jdeme zpátky do kanceláře.
