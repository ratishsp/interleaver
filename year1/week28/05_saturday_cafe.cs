Je sobotní ráno a já jsem v místní kavárně.
Pracuji tu jako dobrovolnice každý víkend.
Kavárna je už plná lidí.
Stojím za velkým dřevěným pultem.
Otírám pult čistým hadříkem.
K pultu přistoupí mladý muž.
„Dobré ráno, chtěl bych velkou kávu,“ říká.
„A dva kousky teplého sladkého pečiva, prosím,“ dodává.
„Samozřejmě, hned to bude,“ odpovídám s úsměvem.
Přejdu k velkému kávovaru.
Ten přístroj už teď znám velmi dobře.
Rychle připravím šálek horké kouřící kávy.
Vůně čerstvé kávy naplní malou místnost.
Potom dám oba kousky teplého sladkého pečiva do papírového sáčku.
Podám mu kávu a sáček přes pult.
„Bude to padesát pět korun,“ říkám.
Zaplatí kartou a vezme si kávu.
„Mějte hezký víkend,“ říká radostně.
„Děkuji, vám také,“ odpovídám.
Mávnu na dalšího zákazníka ve frontě, ať přistoupí.
