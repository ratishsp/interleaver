Je skoro dvanáct hodin v noci, ale obloha je stále světlá.
Má jemnou, modrou barvu.
Jdu po ulici s Evou a Peterem.
Moc nemluvíme.
Nocí se ozývají jen naše kroky.
Dívám se na své přátele.
Eva se usmívá a Peter vypadá unavený, ale šťastný.
Když jsem sem přijela, nikoho jsem neznala.
Ale od té doby se toho hodně změnilo.
Mám teď dobrý každodenní život a poznala jsem spoustu lidí.
Vlastně jsem si našla opravdové přátele.
Peter byl první kolega, se kterým jsem mluvila.
A Eva mě nedávno pozvala k sobě domů.
Teď tu jdeme společně pod jasnou letní oblohou.
Právě mi bylo dvaatřicet let.
Vybudovala jsem si život, který miluji.
Ve svém novém městě se konečně cítím úplně jako doma.
