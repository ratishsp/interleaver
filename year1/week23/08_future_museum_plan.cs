Zvednu se a vezmu si bundu.
Je pozdě a musím jet autobusem domů.
Eva mě vyprovází ke dveřím.
„Podnikneme něco příští měsíc?“ zeptá se najednou.
„Mám v plánu jít do muzea umění,“ vysvětluje.
„Nechceš jít třeba taky?“
Nadšeně přikývnu a vezmu si tašku.
„Ano, to bych moc ráda,“ odpovím.
Myslím, že si to určitě užijeme.
Také jí řeknu, že miluju moderní umění.
„A mám pocit, že se nám spolu vždycky tak dobře povídá,“ dodám.
Eva se široce usměje a otevře mi vchodové dveře.
„Určitě brzy něco naplánujeme,“ slibuje.
„V pondělí ti pošlu zprávu,“ řeknu.
Obejmu ji a vyjdu na schodiště.
Už teď se těším na náš výlet do muzea.
