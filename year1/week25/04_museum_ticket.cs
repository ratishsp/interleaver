Odcházím z trhu a nacházím malé místní muzeum.
Vcházím do tiché budovy.
Jdu k pultu, abych si koupila vstupenku.
Za pokladnou stojí mladý muž.
„Dobrý den, jednu vstupenku pro dospělé, prosím,“ říkám.
„Bude to sto korun,“ říká a tiskne ji.
Platím a dívám se na tyhle barevné brožury na pultu.
Propagují speciální výstavu o historii města.
„Umožňuje tato vstupenka i přístup na výstavu nahoře?“ ptám se.
„Ano, toto muzeum má jen jednu společnou vstupenku,“ odpovídá.
„Výstava je nahoře v prvním patře,“ říká.
„Klidně si tam dejte na čas.“
„Je tam spousta starých fotografií města,“ vysvětluje.
„Některé z nich jsou více než sto let staré.“
„To zní opravdu zajímavě,“ říkám.
„Moc děkuji,“ usmívám se.
Beru si vstupenku a v klidu jdu po schodech nahoru.
