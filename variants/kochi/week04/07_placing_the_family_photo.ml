എൻ്റെ ബാഗ് കസേരയുടെ അടുത്ത് ഇരിക്കുന്നു.
ഞാൻ ബാഗ് തുറക്കുന്നു.
ബാഗിൽ ഒരു ഫോട്ടോ ഉണ്ട്.
ഞാൻ ആ ഫോട്ടോ എടുക്കുന്നു.
ഞാൻ അത് അനിതയെ കാണിക്കുന്നു.
"ഇത് ആരാണ്?" അനിത ചോദിക്കുന്നു.
"ഇത് എൻ്റെ കുടുംബമാണ്," ഞാൻ പറയുന്നു.
"എൻ്റെ അച്ഛൻ, അമ്മ, സഹോദരി സോഫിയ, പിന്നെ സഹോദരൻ ഡീഗോ."
"ഫോട്ടോയിൽ എൻ്റെ നായ ലോലയും ഉണ്ട്."
"അവർ മെക്സിക്കോയിൽ ആണ്."
ഞാൻ ഷെൽഫിൻ്റെ അടുത്ത് പോകുന്നു.
ഷെൽഫിൽ കുറെ പുസ്തകങ്ങൾ ഉണ്ട്.
ഞാൻ ഫോട്ടോ ഷെൽഫിൻ്റെ മുകളിൽ വെക്കുന്നു.
ഇപ്പോൾ ഫോട്ടോ പുസ്തകങ്ങളുടെ മുകളിൽ ഇരിക്കുന്നു.
പുസ്തകങ്ങൾ ഫോട്ടോയുടെ അടിയിൽ ഇരിക്കുന്നു.
"ഇപ്പോൾ ഈ മുറി വളരെ ഭംഗിയുണ്ട്," അനിത പറയുന്നു.
ഞാൻ ഫോട്ടോയിൽ നോക്കുന്നു.
ഈ പുതിയ വീട്ടിൽ എൻ്റെ കുടുംബം എൻ്റെ അടുത്ത് ഉണ്ട്.
