ഇനി എനിക്ക് പാൽ വേണം.
ഞാൻ നീളമുള്ള ഒരു ഇടനാഴിയിലൂടെ നടക്കുന്നു.
ഞാൻ ഷെൽഫിലേക്ക് നോക്കുന്നു.
എനിക്ക് വെള്ളവും ജ്യൂസും കാണാൻ കഴിയുന്നുണ്ട്.
പക്ഷേ എനിക്ക് പാൽ കണ്ടെത്താൻ കഴിയുന്നില്ല.
ഞാൻ എല്ലായിടത്തും നോക്കുന്നു.
ഞാൻ ഒരാളെ കാണുന്നു.
അയാൾ സൂപ്പർമാർക്കറ്റിൽ ജോലി ചെയ്യുന്നു.
ഞാൻ ആ ജീവനക്കാരനെ തടഞ്ഞുനിർത്തി പുഞ്ചിരിക്കുന്നു.
"ക്ഷമിക്കണം," ഞാൻ പറയുന്നു.
"എനിക്ക് പാൽ വേണമായിരുന്നു."
"പാൽ എവിടെയാണ്?"
അയാൾ കടയുടെ പിന്നിലേക്ക് ചൂണ്ടിക്കാണിക്കുന്നു.
"ഡയറി വിഭാഗം അവിടെ താഴെയാണ്," അയാൾ പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ മറുപടി നൽകുന്നു.
ഞാൻ അവിടേക്ക് നടക്കുന്നു.
ഒടുവിൽ ഞാൻ ഫ്രിഡ്ജും പാലും കണ്ടെത്തുന്നു.
ഞാൻ ഒരു കാർട്ടൺ എടുത്ത് ബാസ്കറ്റിൽ വെക്കുന്നു.
