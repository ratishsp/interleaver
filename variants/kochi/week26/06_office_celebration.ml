വൈകുന്നേരത്തെ ചായ സമയമാണ്.
ഞാൻ കമ്പ്യൂട്ടറിൽ ജോലി ചെയ്യുകയാണ്.
അപ്പോൾ പ്രകാശ് എന്റെ അടുത്തേക്ക് വരുന്നു.
"മായ, വേഗം മീറ്റിംഗ് റൂമിലേക്ക് വരൂ," പ്രകാശ് പറയുന്നു.
ഞാൻ പെട്ടെന്ന് മീറ്റിംഗ് റൂമിലേക്ക് പോകുന്നു.
അവിടെ ദീപയും മറ്റ് ടീം അംഗങ്ങളും നിൽക്കുന്നുണ്ട്.
മേശപ്പുറത്ത് മനോഹരമായ ഒരു ചെറിയ കേക്ക് വെച്ചിട്ടുണ്ട്.
"ഹാപ്പി ബർത്ത്ഡേ, മായ!" അവർ എല്ലാവരും ഒരുമിച്ച് പറയുന്നു.
ഞാൻ ഈ സർപ്രൈസ് ഒട്ടും പ്രതീക്ഷിച്ചില്ല.
അവർ എനിക്കായി ഈ മനോഹരമായ കേക്ക് വാങ്ങിയിട്ടുണ്ട്.
ദീപ കേക്കിലെ മെഴുകുതിരി കത്തിക്കുന്നു.
എല്ലാവരും സന്തോഷത്തോടെ ജന്മദിന ഗാനം പാടുന്നു.
ഞാൻ എല്ലാവർക്കും നന്ദി പറയുന്നു.
അതിനുശേഷം ഞാൻ കേക്ക് മുറിക്കുന്നു.
ഞങ്ങൾ എല്ലാവരും സംസാരിക്കുന്നു, കൂടെ കേക്കും ചായയും കഴിക്കുന്നു.
കുറച്ചു സമയത്തിനുശേഷം, എല്ലാവരും വീണ്ടും ജോലിയിലേക്ക് മടങ്ങുന്നു.
