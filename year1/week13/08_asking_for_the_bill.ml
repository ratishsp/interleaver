ഞാൻ എൻ്റെ വെള്ളം കുടിക്കുന്നു.
വെള്ളം തണുത്തതും നല്ലതുമാണ്.
ഞാൻ തറയിൽ നിന്ന് എൻ്റെ ബാഗ് എടുക്കുന്നു.
എൻ്റെ ഇടവേള കഴിഞ്ഞു.
ഞാൻ കൗണ്ടറിന് അടുത്തേക്ക് നടക്കുന്നു.
സൗഹൃദമുള്ള ആ ബാരിസ്റ്റ ഇപ്പോഴും അവിടെ നിൽപ്പുണ്ട്.
അയാൾ ഒരു പുഞ്ചിരിയോടെ എന്നെ നോക്കുന്നു.
"നിങ്ങൾക്ക് വേറെ എന്തെങ്കിലും വേണമെന്നുണ്ടോ?" അയാൾ ചോദിക്കുന്നു.
"വേണ്ട, നന്ദി," ഞാൻ മറുപടി പറയുന്നു.
"എനിക്ക് പണമടയ്ക്കണം."
"അതെ, തീർച്ചയായും," അയാൾ പറയുന്നു.
അയാൾ തൻ്റെ ചെറിയ സ്ക്രീനിലേക്ക് നോക്കുന്നു.
"ഒരു ബ്ലാക്ക് കോഫിയും ഒരു സിനമൺ റോളും," അയാൾ പറയുന്നു.
"അതെ, അത് ശരിയാണ്," ഞാൻ പറയുന്നു.
"നിങ്ങൾ കാർഡ് വഴിയാണോ അതോ പണമായിട്ടാണോ അടയ്ക്കുന്നത്?" അയാൾ ചോദിക്കുന്നു.
"എനിക്ക് കാർഡ് ഉപയോഗിച്ച് അടയ്ക്കണം," ഞാൻ മറുപടി പറയുന്നു.
"ശരി."
"അതിന് എൺപത്തിയഞ്ച് ക്രോണർ ആകും," അയാൾ പറയുന്നു.
ഞാൻ എൻ്റെ പേയ്‌മെൻ്റ് കാർഡ് പുറത്തെടുക്കുന്നു.
