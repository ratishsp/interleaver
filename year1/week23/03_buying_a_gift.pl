Jest piątkowe popołudnie, a ja skończyłam już pracę.
Idę ulicą i zatrzymuję się przed kwiaciarnią.
Zamierzam kupić prezent dla Evy.
Otwieram drzwi i wchodzę do małego sklepu.
„Dzień dobry” – mówi sprzedawca z szerokim uśmiechem.
„Dzień dobry” – odpowiadam.
Patrzę na wiele pięknych kwiatów.
Myślę, że Eva zawsze lubi kolory.
Jest projektantką, więc pewnie spodoba jej się coś kolorowego.
Znajduję duży bukiet żółtych tulipanów.
„Chciałabym kupić ten bukiet” – mówię i wskazuję na tulipany.
„To naprawdę dobry wybór” – mówi sprzedawca.
Zawija kwiaty w ładny papier.
„To będzie sto pięćdziesiąt koron” – mówi.
Wyciągam kartę i płacę za kwiaty.
„Idę dziś wieczorem na kolację” – mówię mu.
„W takim razie pani przyjaciółka na pewno się ucieszy” – odpowiada.
Biorę bukiet i wychodzę ze sklepu.
Teraz muszę tylko znaleźć mój przystanek autobusowy.
