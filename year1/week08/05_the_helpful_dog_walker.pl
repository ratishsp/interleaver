Stoję na cichej ulicy.
Zgubiłam się.
Przede mną widzę młodą kobietę.
Wyprowadza małego psa.
Pies przypomina psa mojej rodziny, Lolę.
Podchodzę do kobiety.
"Przepraszam" – mówię.
"Szukam portu."
Kobieta zatrzymuje się i słucha.
Wskazuje z powrotem w górę ulicy.
"Proszę iść prosto, z powrotem na plac" – mówi.
"I skręcić w prawo przy muzeum."
"Bardzo dziękuję za pomoc" – mówię.
"Proszę bardzo" – odpowiada kobieta.
Spoglądam w dół na małego psa.
Patrzy na mnie.
Idę z powrotem w stronę placu.
Teraz wiem, gdzie jestem.
