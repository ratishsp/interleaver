Svou třetí sobotu jsem stála připravená za pultem.
Konečně jsem se naučila v kavárně trochu uvolnit.
Oknem jsem na ulici uviděla staršího muže.
Pomalu šel směrem k hlavním dveřím.
Byl tady i na mé první a druhé směně.
Je jedním ze stálých zákazníků kavárny.
Naučila jsem se jeho objednávku nazpaměť.
Vždycky si kupuje přesně to samé.
Otevřel dveře a přišel k pokladně.
Podívala jsem se na něj a usmála se.
„Dobré ráno,“ řekla jsem.
„Mám vám připravit vaše obvyklé cortado?“
Muž se na mě překvapeně podíval.
Pak se radostně usmál.
„Ano, prosím, to bych moc rád,“ odpověděl.
Šla jsem k přístroji na espresso.
Kávu jsem teď dělala už mnohokrát, takže to šlo rychle.
Byl to dobrý pocit znát naše hosty.
