Efter morgonmötet sitter jag vid mitt skrivbord.
Jag tittar på mina anteckningar från presentationen.
Min chef, Thomas, kommer fram till mig.
Han är vår projektledare.
Han har arbetat här i många år.
"God morgon, Maya", säger han med ett leende.
"Det var en riktigt bra presentation."
"Tack, Thomas", svarar jag.
"Vi är mycket glada över att ha dig i teamet", fortsätter Thomas.
"Hela teamet har sett fram emot att arbeta tillsammans med dig."
"Jag har också sett fram emot det", säger jag glatt.
"Det är ett spännande projekt."
Thomas ler igen och går tillbaka till sitt kontor.
Jag tittar på min datorskärm.
Jag känner mig riktigt välkommen i teamet.
