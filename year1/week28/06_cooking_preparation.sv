Senare på eftermiddagen går jag ner till den lokala mataffären.
Jag ska handla till i kväll.
Jag hittar några färska, röda tomater och en påse bönor.
Jag behöver också några starka kryddor.
Jag betalar i kassan och går hem igen.
Mitt kök är litet, men det är väldigt mysigt.
Jag ställer mina påsar på bordet och tvättar händerna.
Jag ska göra en stor portion traditionell mexikansk gryta.
Det är ett av min mammas gamla recept.
Jag tar fram min skärbräda i trä och en vass kniv.
Jag tillbringar en avkopplande timme i köket.
Det är härligt att stå och hacka grönsaker.
Jag skär tomaterna och lökarna i små bitar.
Dofterna påminner mig om mitt hem i Mexiko.
Men nu är det också mitt hem här i Köpenhamn.
Jag lägger alltihop i en stor gryta på spisen.
Grytan ska stå och puttra långsamt.
Jag rör om och smakar på såsen med en sked.
Den smakar helt perfekt.
Jag ser verkligen fram emot att äta middag med Nina.
