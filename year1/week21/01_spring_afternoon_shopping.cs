Je dvanáct hodin a v kavárně mám hotovo.
Moje dobrovolnická směna v sobotu dopoledne je vždycky rušná, ale příjemná.
Teď mám volno.
Počasí je dnes krásné.
Udělalo se opravdu příjemně a krásně.
Svítí slunce a je mnohem tepleji než minulý týden.
Mám chuť se trochu rozmazlovat.
Jdu po velké pěší zóně.
Ve městě je dnes spousta lidí.
Lidé se usmívají a užívají si pěkného počasí.
Chtěla bych si koupit nějaké nové oblečení.
Hledám nějaké lehčí jarní oblečení.
Možná nějakou hezkou novou jarní bundu a košili.
Dívám se do výlohy velkého obchodu s oblečením.
Mají tam oblečení v mnoha krásných jarních barvách.
Rozhodnu se jít dovnitř.
Těším se, až si některé z těch věcí vyzkouším.
