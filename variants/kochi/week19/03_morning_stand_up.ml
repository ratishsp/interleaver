ഞങ്ങൾ എല്ലാവരും രാവിലത്തെ മീറ്റിംഗിനായി മീറ്റിംഗ് റൂമിൽ കൂടുന്നു.
ഇതൊരു ചെറിയ മീറ്റിംഗ് ആണ്.
പ്രകാശ് എൻ്റെ അടുത്താണ് നിൽക്കുന്നത്.
സുരേഷ് എല്ലാവരോടും അവരുടെ ജോലിയെക്കുറിച്ച് ചോദിക്കുന്നു.
എല്ലാവരും ഓരോരുത്തരായി സംസാരിക്കുന്നു.
എനിക്ക് ചെറിയ പേടി തോന്നുന്നു.
ഇപ്പോൾ എൻ്റെ ഊഴമാണ്.
സുരേഷ് എന്നെ നോക്കി ചോദിക്കുന്നു.
"മായ, ഇന്നത്തെ പ്ലാൻ എന്താണ്?"
ഞാൻ ദീർഘമായി ശ്വാസമെടുക്കുന്നു.
"ഞാൻ പുതിയ പ്രൊജക്റ്റിൻ്റെ രേഖകൾ വായിച്ചിട്ടുണ്ട്," ഞാൻ പറയുന്നു.
"ഒരു സോഫ്റ്റ്‌വെയർ എൻജിനീയർ എന്ന നിലയിൽ, ഞാൻ അതിൻ്റെ കോഡിംഗ് ഭാഗം പരിശോധിച്ചിട്ടുണ്ട്."
"എൻ്റെ ജോലിക്കായി ഞാൻ ഒരു പ്ലാൻ തയ്യാറാക്കിയിട്ടുണ്ട്."
ഞാൻ ആ പ്ലാൻ എല്ലാവർക്കും വിശദീകരിക്കുന്നു.
എല്ലാവരും തലയാട്ടുന്നു.
പ്രകാശ് എന്നെ നോക്കി ചിരിക്കുന്നു.
"അതൊരു നല്ല പ്ലാൻ ആണ്, മായ," സുരേഷ് പറയുന്നു.
എൻ്റെ പേടി മാറുന്നു.
ഇപ്പോൾ എനിക്ക് ആത്മവിശ്വാസത്തോടെ എൻ്റെ ജോലി തുടങ്ങാൻ കഴിയും.
