Sedím u okna v autobuse.
Ranní slunce je dnes krásně teplé.
V Kodani je léto a město vypadá krásně.
Dívám se ven na známé ulice.
Projíždíme kolem velkého parku se zelenými stromy.
Lidé už jezdí na kolech po cyklostezkách.
Tímto autobusem jezdím do práce každé ráno.
Trasa je přesně stejná jako v lednu.
Ale všechno je teď úplně jiné.
Vzpomínám si na svůj první týden tady ve městě.
Byla mrazivá zima a velká tma.
Tehdy jsem tu čtvrť vůbec neznala.
Byla jsem také velmi nervózní ze své nové práce v softwarové firmě.
Teď přesně vím, kde jsme.
Poznávám místní pekařství a náměstí.
Autobus zastavuje a nastupují další lidé.
Usmívám se a opírám se do sedadla.
Jsem připravená na dobrý den v kanceláři.
