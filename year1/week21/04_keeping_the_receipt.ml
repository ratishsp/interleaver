എന്റെ പുതിയ സാധനങ്ങളുമായി ഞാൻ ക്യാഷ് കൗണ്ടറിലേക്ക് നടക്കുന്നു.
ക്ലാർക്ക് മുകളിലേക്ക് നോക്കി ഹായ് പറയുന്നു.
"ഹായ്," അവൾ പറയുന്നു.
"ഹായ്," ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ ഇളം പച്ച ജാക്കറ്റും നീല ഷർട്ടും കൗണ്ടറിൽ വെക്കുന്നു.
അവൾ രണ്ട് സാധനങ്ങളും സ്കാൻ ചെയ്യുന്നു.
"അതിന് അറുനൂറ്റി അൻപത് ക്രോണർ ആകും," അവൾ പറയുന്നു.
ഞാൻ എന്റെ കാർഡ് ഉപയോഗിച്ച് പണം നൽകുന്നു.
"നിങ്ങൾക്ക് രസീത് വേണമോ?" ക്ലാർക്ക് ചോദിക്കുന്നു.
"അതെ, വേണം," ഞാൻ വേഗത്തിൽ മറുപടി പറയുന്നു.
"ഞാൻ ഷർട്ട് ഇട്ടുനോക്കിയിട്ടില്ല," ഞാൻ വിശദീകരിക്കുന്നു.
"എനിക്ക് ഇതിലും വലുത് വേണ്ടിവരില്ലെന്ന് പ്രതീക്ഷിക്കുന്നു."
"നിങ്ങൾക്ക് എപ്പോൾ വേണമെങ്കിലും ഇത് മാറ്റിയെടുക്കാം," ക്ലാർക്ക് സ്നേഹത്തോടെ പറയുന്നു.
അവൾ രസീത് പ്രിൻ്റ് ചെയ്ത് എനിക്ക് തരുന്നു.
"ഇത് സൂക്ഷിച്ച് വെക്കാൻ ഓർക്കുക," അവൾ പറയുന്നു.
ഞാൻ ആ രസീത് വാങ്ങുന്നു.
ഞാൻ ആ ചെറിയ കടലാസ് കഷണം മടക്കുന്നു.
ശേഷം ഞാൻ അത് എന്റെ പേഴ്സിൽ ഭദ്രമായി വെക്കുന്നു.
"നല്ലൊരു വാരാന്ത്യം ആശംസിക്കുന്നു," ഞാൻ അവളോട് പറയുന്നു.
"നിങ്ങൾക്കും അങ്ങനെ തന്നെ," അവൾ മറുപടി നൽകുന്നു.
