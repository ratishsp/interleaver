എൻ്റെ പുതിയ വസ്ത്രങ്ങളുമായി ഞാൻ കൗണ്ടറിൻ്റെ അടുത്തേക്ക് നടക്കുന്നു.
കടയിലെ സഹായി എന്നെ നോക്കി സ്നേഹത്തോടെ ചിരിക്കുന്നു.
"ഇത്രയേ ഉള്ളോ?" അവൾ ചോദിക്കുന്നു.
"അതെ, ഇത്രയേ ഉള്ളൂ," ഞാൻ മറുപടി നൽകുന്നു.
അവൾ എൻ്റെ പുതിയ സാധനങ്ങളെല്ലാം സ്കാൻ ചെയ്യുന്നു.
അതിൽ ഒരു സ്വെറ്റർ, ഒരു ജാക്കറ്റ്, ഒരു സ്കാർഫ്, കയ്യുറകൾ എന്നിവയുണ്ട്.
"ഇനി നിങ്ങൾക്ക് തണുക്കില്ല," അവൾ സന്തോഷത്തോടെ പറയുന്നു.
"അതിന് ആയിരത്തി അഞ്ഞൂറ് ക്രോണർ ആകും."
വസ്ത്രങ്ങൾക്ക് വില കൂടുതലാണ്, എന്നാൽ അവ നല്ല ചൂട് നൽകുന്നവയാണ്.
ഞാൻ എൻ്റെ പേയ്‌മെൻ്റ് കാർഡ് പുറത്തെടുക്കുന്നു.
"ഞാൻ കാർഡ് വഴിയാണ് പണമടയ്ക്കുന്നത്," ഞാൻ പറയുന്നു.
"നിങ്ങൾക്ക് ഇവിടെത്തന്നെ പണമടയ്ക്കാം," അവൾ പറയുന്നു.
അവൾ ഒരു ചെറിയ കറുത്ത മെഷീനിലേക്ക് ചൂണ്ടിക്കാണിക്കുന്നു.
ഞാൻ എൻ്റെ കാർഡ് മെഷീന് മുകളിൽ പിടിക്കുന്നു.
അത് ബീപ്പ് ചെയ്യുന്നു, പേയ്‌മെന്റ് അംഗീകരിച്ചു.
"നിങ്ങൾക്ക് രസീത് വേണമോ?" കടയിലെ സഹായി ചോദിക്കുന്നു.
"വേണ്ട, നന്ദി," ഞാൻ മറുപടി പറയുന്നു.
ഇപ്പോൾ എൻ്റെ പക്കൽ നല്ലൊരു കൂട്ടം ശൈത്യകാല വസ്ത്രങ്ങളുണ്ട്.
