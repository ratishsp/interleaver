Jag går över det stora torget.
Plötsligt hör jag musik.
På hörnet står en gatumusikant.
Han spelar gitarr.
Jag lyssnar på den bra musiken.
Jag tittar länge på honom.
Sedan går jag vidare.
Jag glömmer museet.
Jag glömmer också min rutt.
Istället går jag nerför en smal sidogata.
Här är det mycket tyst.
Runt omkring ser jag bara några små hus.
Sedan stannar jag.
Var är museet?
Nu tittar jag mig omkring.
Jag kan inte se det längre.
Jag tittar snabbt tillbaka uppför gatan.
Jag kan inte heller se torget.
Jag är helt vilse.
