Jdu dolů na pláž.
Mnoho lidí už dorazilo na večerní oslavu.
Hledám v davu Evu a Petera.
Najednou je vidím dole u vody a spěchám tam.
„Měla jsi hezký narozeninový týden?“ ptá se Peter s úsměvem.
„Ano, byl naprosto fantastický,“ odpovídám radostně.
Eva otevírá malý košík.
„Dnes ráno jsem na trhu koupila čerstvé jahody,“ říká.
„Ochutnala jsi někdy dánské letní jahody?“
„Ne, to jsem ještě nikdy nezkusila,“ říkám a beru si jahodu.
Chutná neuvěřitelně sladce a připomíná mi léto.
Přesně v tu chvíli nějaký muž zapaluje velký oheň.
Plameny rychle rostou a šlehají vysoko k nebi.
Předtím byla zima, ale teď oheň ohřál vzduch.
Žhnoucí teplo rychle zahání chlad z pobřeží.
Stojíme blízko u sebe a dlouho se díváme do plamenů.
Myslím na to, že tu ve městě žiji už šest měsíců.
Můj první měsíc tady byl temný, ale tento světlý letní večer je dokonalý.
