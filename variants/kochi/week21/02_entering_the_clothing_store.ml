ഞാൻ ടൗണിലെ വലിയ തുണിക്കടയിൽ എത്തുന്നു.
ഞാൻ പതുക്കെ കടയുടെ ഉള്ളിലേക്ക് കയറുന്നു.
കടയുടെ ഉള്ളിൽ നല്ല തണുപ്പാണ്.
എനിക്ക് വലിയ ആശ്വാസം തോന്നുന്നു.
മഴ കാരണം പുറത്ത് നല്ല ഈർപ്പമാണ്.
പുറത്തെ ഈർപ്പത്തെക്കാൾ നല്ലതാണ് ഈ തണുപ്പ്.
കടയിൽ ഒരുപാട് സാധനങ്ങൾ ഉണ്ട്.
ഞാൻ ചുറ്റും നോക്കുന്നു.
എനിക്ക് ആദ്യം ഒരു റെയിൻകോട്ട് ആണ് വേണ്ടത്.
ഞാൻ സ്ത്രീകളുടെ തുണികളുടെ ഭാഗത്തൂടെ നടക്കുന്നു.
അവിടെ റെയിൻകോട്ടുകൾ ഒന്നും കാണുന്നില്ല.
ഞാൻ അവിടെയുള്ള ഒരു ജോലിക്കാരനെ കാണുന്നു.
ഞാൻ അയാളോട് ചോദിക്കുന്നു.
"റെയിൻകോട്ട് സെക്ഷൻ എവിടെയാണ്?"
അയാൾ വലതുവശത്തേക്ക് ചൂണ്ടിക്കാണിക്കുന്നു.
ഞാൻ അങ്ങോട്ട് നടക്കുന്നു.
