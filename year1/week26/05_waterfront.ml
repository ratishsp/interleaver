ഞാൻ വീട്ടിൽ എന്റെ അപ്പാർട്ട്മെന്റിലാണ്.
ഇന്ന് ശനിയാഴ്ച വൈകുന്നേരമാണ്, എങ്കിലും സൂര്യൻ ഇപ്പോഴും പ്രകാശിക്കുന്നുണ്ട്.
കടൽത്തീരത്തെ തീക്കുണ്ടത്തിനായി ഞാൻ തയ്യാറെടുക്കുകയാണ്.
ഞാൻ എന്റെ ബാഗ് പാക്ക് ചെയ്തിട്ടുണ്ട്.
ഞാൻ ബാഗിൽ ചൂടുള്ള ഒരു സ്വെറ്റർ വെച്ചു.
ഞാൻ ആ സ്വെറ്റർ ഫെബ്രുവരിയിൽ വാങ്ങിയതാണ്.
ഇപ്പോൾ വൈകുന്നേരങ്ങളിൽ നല്ല വെളിച്ചമുണ്ട്, എങ്കിലും പിന്നീട് പലപ്പോഴും തണുപ്പാകും.
ഞാൻ കുറച്ച് സ്നാക്സും ഉണ്ടാക്കിയിട്ടുണ്ട്.
കഫേയിലെ എന്റെ ഷിഫ്റ്റിന് പോകുന്നതിന് മുമ്പ് ഇന്ന് രാവിലെ ഞാൻ സാധനങ്ങൾ വാങ്ങിയിരുന്നു.
എന്റെ ഫോൺ അടിക്കുന്നു, ഞാൻ അതെടുക്കുന്നു.
അത് ഈവയാണ്.
"നീ തയ്യാറാണോ, മായാ?" അവൾ ചോദിക്കുന്നു.
"അതെ, ഞാൻ ഏകദേശം തയ്യാറായി," ഞാൻ മറുപടി പറയുന്നു.
"എനിക്ക് എന്റെ സൺഗ്ലാസ്സ് ഇപ്പോൾ കിട്ടിയതേയുള്ളൂ," ഞാൻ പറയുന്നു.
"ഞാൻ ഇരുപത് മിനിറ്റോളം അത് തിരയുകയായിരുന്നു," ഞാൻ ചിരിക്കുന്നു.
"പെർഫെക്റ്റ്, അര മണിക്കൂറിനുള്ളിൽ നമുക്ക് വെള്ളത്തിനടുത്ത് കാണാം," ഈവ പറയുന്നു.
ഞാൻ എന്റെ ഷൂസ് ധരിച്ച് ബാഗ് തോളിലിടുന്നു.
ഞാൻ വാതിൽ പൂട്ടി പടികൾ ഇറങ്ങുന്നു.
എന്റെ ആദ്യത്തെ ഡാനിഷ് വേനൽക്കാല സായാഹ്നത്തിനായി ഞാൻ ശരിക്കും കാത്തിരിക്കുകയാണ്.
