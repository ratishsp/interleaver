ഞാൻ ആ ചെറിയ ടൗണിലെ റെയിൽവേ സ്റ്റേഷനിൽ ഇറങ്ങി.
ഉച്ചയ്ക്ക് നല്ല ചൂട് ഉണ്ടായിരുന്നു.
ഞാൻ സ്റ്റേഷനിൽ നിന്ന് ബോട്ട് ജെട്ടി അന്വേഷിച്ച് നടന്നു.
എനിക്ക് വല്ലാതെ ദാഹിച്ചു.
റോഡിന് അരികിൽ ഞാൻ ഒരു ചെറിയ കട കണ്ടു.
ഒരു കച്ചവടക്കാരൻ കടയിൽ ഇരിക്കുന്നുണ്ടായിരുന്നു.
ഞാൻ ആ കടയുടെ അടുത്തേക്ക് പോയി.
"എനിക്ക് ഒരു കുപ്പി തണുത്ത വെള്ളം വേണം," ഞാൻ അയാളോട് പറഞ്ഞു.
അയാൾ ഒരു കുപ്പി തണുത്ത വെള്ളം എടുത്തു തന്നു.
അതിന് ഇരുപത് രൂപ ആയിരുന്നു.
ഞാൻ അയാൾക്ക് പണം കൊടുത്തു.
എന്നിട്ട് ഞാൻ അയാളോട് വഴി ചോദിച്ചു.
"ബോട്ട് ജെട്ടി എവിടെയാണ്?"
അയാൾ വലതുവശത്തേക്ക് കൈ ചൂണ്ടി.
"നേരെ പോകൂ, അവിടെയാണ് ബോട്ട്," അയാൾ പറഞ്ഞു.
ഞാൻ അയാളോട് നന്ദി പറഞ്ഞു.
ഞാൻ ആ കുപ്പിയിൽ നിന്ന് കുറച്ചു തണുത്ത വെള്ളം കുടിച്ചു.
പിന്നെ ഞാൻ ജെട്ടിയിലേക്ക് നടന്നു.
