Vycházím ze zkušební kabinky s modrou košilí.
Ta větší velikost padne perfektně.
Prodavačka stále stojí u pokladny.
„Je lepší?“ ptá se s úsměvem.
„Ano, je mnohem lepší,“ odpovídám.
„Ta menší košile byla moc těsná,“ vysvětluji.
„Ráda bych ji vyměnila za tuhle.“
„To je naprosto v pořádku,“ říká.
„Mohu ještě jednou vidět vaši účtenku?“ ptá se.
Dávám jí malou papírovou účtenku.
Skenuje čárový kód.
„Tak, teď je to vyměněné,“ říká.
„Nestojí to nic navíc.“
„Moc děkuji za pomoc,“ říkám.
„Není zač a hezký den,“ odpovídá.
Dávám košili do tašky.
Teď mám konečně nějaké dobré oblečení na jaro.
Vycházím z obchodu.
Jsem velmi spokojená, když jdu domů.
