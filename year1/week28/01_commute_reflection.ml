ഞാൻ ബസ്സിൽ ജനാലയ്ക്കരികിൽ ഇരിക്കുന്നു.
ഇന്നത്തെ പ്രഭാതസൂര്യൻ മനോഹരവും ഇളംചൂടുള്ളതുമാണ്.
കോപ്പൻഹേഗനിൽ ഇപ്പോൾ വേനൽക്കാലമാണ്, നഗരം കാണാൻ വളരെ മനോഹരമായിരിക്കുന്നു.
പരിചിതമായ തെരുവുകളിലേക്ക് ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
പച്ച മരങ്ങളുള്ള ഒരു വലിയ പാർക്കിന് മുന്നിലൂടെ ഞങ്ങൾ കടന്നുപോകുന്നു.
ആളുകൾ നേരത്തെ തന്നെ സൈക്കിൾ പാതകളിലൂടെ സൈക്കിൾ ചവിട്ടുന്നുണ്ട്.
എല്ലാ ദിവസവും രാവിലെ ജോലിക്ക് പോകാൻ ഞാൻ ഈ ബസ്സിലാണ് കയറുന്നത്.
ഈ റൂട്ട് കൃത്യമായി ജനുവരിയിലേത് പോലെ തന്നെയാണ്.
എന്നാൽ ഇപ്പോൾ എല്ലാം തികച്ചും വ്യത്യസ്തമാണ്.
ഈ നഗരത്തിലെ എൻ്റെ ആദ്യത്തെ ആഴ്ച ഞാൻ ഓർക്കുന്നു.
അന്ന് നല്ല കൊടുംതണുപ്പും ഇരുട്ടുമായിരുന്നു.
അന്ന് എനിക്ക് ഈ പ്രദേശത്തെക്കുറിച്ച് യാതൊരു പരിചയവുമില്ലായിരുന്നു.
സോഫ്റ്റ്‌വെയർ കമ്പനിയിലെ എൻ്റെ പുതിയ ജോലിയെക്കുറിച്ചോർത്ത് എനിക്ക് വളരെ ആശങ്കയുമുണ്ടായിരുന്നു.
ഇപ്പോൾ നമ്മൾ എവിടെയാണെന്ന് എനിക്ക് കൃത്യമായി അറിയാം.
ഇവിടുത്തെ ബേക്കറിയും സ്ക്വയറും ഞാൻ തിരിച്ചറിയുന്നു.
ബസ് നിൽക്കുന്നു, കൂടുതൽ ആളുകൾ കയറുന്നു.
ഞാൻ പുഞ്ചിരിച്ചുകൊണ്ട് എൻ്റെ സീറ്റിലേക്ക് ചാരിയിരിക്കുന്നു.
ഓഫീസിലെ ഒരു നല്ല ദിവസത്തിനായി ഞാൻ തയ്യാറാണ്.
