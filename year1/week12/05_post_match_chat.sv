Den snabba matchen är över.
Vi går av banan tillsammans.
Jag är mycket trött.
Kasper och Sara är också trötta.
Vi dricker lite vatten.
"Du spelar mycket bra," säger Sara.
"Tack så mycket," säger jag.
"Jag tycker det är så roligt."
"Spelar du ofta?" frågar Kasper.
"Ja, jag spelar mycket hemma i Mexiko," svarar jag.
"Jag brukar spela med min syster."
"Det är en rolig sport," säger Sara.
"Vi älskar att spela här i klubben."
"Jag vill gärna spela mer här i Danmark," säger jag.
"Du är definitivt snabb," skrattar Kasper.
"Tack, men nu vill jag gärna sitta ner," säger jag.
"Ska vi gå in i cafeterian?" frågar Kasper.
"Ja, det vill jag mycket gärna," svarar jag.
