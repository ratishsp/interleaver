ഇൻഫോപാർക്ക് ഓഫീസിൽ ചൊവ്വാഴ്ച രാവിലെയാണ്.
ഞാൻ എന്റെ ഡെസ്കിൽ ജോലി ചെയ്യുകയാണ്.
ദീപ എന്റെ ഡെസ്കിന്റെ അടുത്തേക്ക് വരുന്നു.
"മായ, വെള്ളിയാഴ്ച വൈകുന്നേരം തിരക്കാണോ?" ദീപ ചോദിക്കുന്നു.
ഞാൻ എന്റെ കലണ്ടർ നോക്കുന്നു.
വ്യാഴാഴ്ച വൈകുന്നേരങ്ങളിൽ ഞാൻ ബാഡ്മിന്റൺ കളിക്കാറുണ്ട്.
അതുകൊണ്ട് വെള്ളിയാഴ്ച ഞാൻ ഫ്രീയാണെന്ന് ഞാൻ കരുതുന്നു.
"വെള്ളിയാഴ്ച എനിക്ക് മറ്റ് പരിപാടികൾ ഒന്നുമില്ല," ഞാൻ മറുപടി പറയുന്നു.
"എങ്കിൽ ഡിന്നറിന് എന്റെ വീട്ടിലേക്ക് വരണം," ദീപ പറയുന്നു.
എനിക്ക് വലിയ സന്തോഷം തോന്നുന്നു.
"ഞാൻ ഒരു പ്രത്യേക കേരള ഭക്ഷണം ഉണ്ടാക്കാം," അവർ പറയുന്നു.
"വലിയ സന്തോഷം, ദീപ."
"ഞാൻ തീർച്ചയായും വരും," ഞാൻ പറയുന്നു.
"ഞാൻ ലൊക്കേഷൻ ഫോണിലേക്ക് അയക്കാം," അവർ പറയുന്നു.
"ശരി, നമുക്ക് വെള്ളിയാഴ്ച കാണാം," ഞാൻ പറയുന്നു.
ദീപ ചിരിച്ചുകൊണ്ട് തിരികെ പോകുന്നു.
