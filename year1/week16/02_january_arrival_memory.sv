Jag tittade på Kasper och Sara och log.
"Min första dag var ett stort äventyr", sa jag.
Jag mindes den kalla luften på flygplatsen.
Kasper frågade:
"Hur var vädret?"
"Himlen var helt grå", svarade jag.
Jag stod utanför flygplatsen med min stora resväska.
Vinden blåste, men jag såg fram emot att vara här.
Sara drack lite vatten och nickade.
"Det låter som en stor förändring från Mexiko", sa hon.
Jag hittade en taxi framför byggnaden.
Taxichauffören var vänlig och hjälpte mig.
Han frågade om min nya adress.
Jag sa min adress högt.
"Jag känner väl till gatan", sa chauffören.
Vi körde in mot staden.
Jag tittade ut genom fönstret under resan.
Alla människor hade varma rockar och halsdukar på sig.
Sara frågade:
"Var du nervös?"
"Ja, lite", svarade jag.
Men jag såg också fram emot min nya lägenhet.
