Det är fredag eftermiddag, och jag är ledig från jobbet.
Jag går nerför gatan och stannar vid en blomsterhandel.
Jag har tänkt köpa en present till Eva.
Jag öppnar dörren och går in i den lilla butiken.
"Goddag," säger expediten med ett stort leende.
"Goddag," svarar jag.
Jag tittar på de många vackra blommorna.
Jag tror att Eva alltid gillar färger.
Hon är designer, så hon kommer nog att älska något färgglatt.
Jag hittar en stor bukett med gula tulpaner.
"Jag vill gärna köpa den här buketten," säger jag och pekar på tulpanerna.
"Det är ett riktigt bra val," säger expediten.
Han slår in blommorna i lite fint papper.
"Det blir etthundrafemtio kronor," säger han.
Jag tar fram mitt kort och betalar för blommorna.
"Jag ska på en middag i kväll," berättar jag för honom.
"Då kommer din väninna helt säkert att bli glad," svarar han.
Jag tar buketten och går ut ur butiken.
Nu ska jag bara hitta min busshållplats.
