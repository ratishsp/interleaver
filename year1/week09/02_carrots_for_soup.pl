Podchodzę do stoiska z warzywami.
Robię dziś gorącą zupę.
Patrzę na mnóstwo warzyw na stole.
Wskazuję na kilka dużych, zimowych marchewek.
Potrzebuję marchewek do mojej zupy.
Za stołem stoi sprzedawca.
„Dzień dobry” – mówi.
„Dzień dobry” – odpowiadam.
„Ile kosztują marchewki?” – pytam.
„Kosztują piętnaście koron za kilogram” – odpowiada sprzedawca.
Piętnaście koron to dobra cena.
„Wezmę jeden kilogram, poproszę” – mówię.
Sprzedawca waży marchewki.
Wkłada je do papierowej torebki.
Podaje mi torebkę.
Płacę te piętnaście koron.
Wkładam torebkę do mojej dużej torby.
Nie mogę się doczekać gorącej zupy.
