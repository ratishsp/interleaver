Jag går förbi ett litet stånd.
Det doftar färskt bröd.
Jag går fram till ståndet.
Bagaren står bakom ett stort bord.
Bordet är fyllt med bakverk.
Jag ser ett mörkt rågbröd.
Det ser mycket färskt ut.
Jag pekar på rågbrödet.
"Hur mycket kostar det mörka rågbrödet?" frågar jag.
Bagaren torkar sina händer.
"Det kostar trettiofem kronor," svarar han.
"Jag köper det," säger jag.
Jag tar fram mitt betalkort.
Jag betalar med kortet.
Bagaren ger mig brödet i en papperspåse.
Jag rör vid påsen.
Brödet är fortfarande varmt.
Jag ser fram emot att äta det.
