വൈകുന്നേരം ഞാൻ ഫ്ലാറ്റിൽ എത്തുന്നു.
പുറത്ത് നല്ല മഴയാണ്.
ഞാൻ പടികൾ കയറുന്നു.
അപ്പോൾ അനിത താഴേക്ക് വരുന്നുണ്ട്.
അവർ എന്നെ നോക്കി ചിരിക്കുന്നു.
"മായേ, ഇന്നത്തെ ദിവസം എങ്ങനെ ഉണ്ടായിരുന്നു?" അനിത ചോദിക്കുന്നു.
"എല്ലാം വളരെ നന്നായി നടന്നു," ഞാൻ പറയുന്നു.
എനിക്ക് ഇപ്പോൾ നല്ല ക്ഷീണം ഉണ്ട്.
പക്ഷേ എനിക്ക് വലിയ സന്തോഷവുമുണ്ട്.
"പുതിയ ടീമിലുള്ളവർ നല്ലവരാണോ?" അവർ ചോദിക്കുന്നു.
"അതെ, എല്ലാവരും വളരെ നല്ലവരാണ്," ഞാൻ മറുപടി പറയുന്നു.
"ഞാൻ ഇന്ന് എല്ലാവരോടും സംസാരിച്ചിട്ടുണ്ട്."
"എൻ്റെ ജോലിയും എനിക്ക് നന്നായി മനസ്സിലായിട്ടുണ്ട്."
"അത് വലിയൊരു കാര്യമാണ്," അനിത സന്തോഷത്തോടെ പറയുന്നു.
"മായ എന്തെങ്കിലും കഴിച്ചിട്ടുണ്ടോ?" അവർ ചോദിക്കുന്നു.
"ഇല്ല, ഞാൻ ഇനി ഭക്ഷണം ഉണ്ടാക്കണം," ഞാൻ പറയുന്നു.
"ശരി, പോയി നന്നായി വിശ്രമിക്കൂ," അനിത പറയുന്നു.
ഞാൻ ശുഭരാത്രി പറഞ്ഞ് ഫ്ലാറ്റിലേക്ക് നടക്കുന്നു.
ഇപ്പോൾ ഈ പുതിയ പ്രോജക്റ്റ് എൻ്റേതാണെന്ന് എനിക്ക് തോന്നുന്നു.
ക്ഷീണത്തോടെ, പക്ഷേ വലിയ സന്തോഷത്തോടെ ഞാൻ എൻ്റെ വാതിൽ തുറക്കുന്നു.
