Je pondělní odpoledne a já mám po práci.
Jedu autobusem ze softwarové firmy.
Ale nejedu přímo domů.
Vystupuji z autobusu u velké pěší zóny.
Jdu k tomu obchodu s oblečením ze soboty.
V tašce mám tu modrou bavlněnou košili.
Je stále úplně nová a nenošená.
Košile je moc malá, takže bych si ráda vyzkoušela větší.
Doufám, že ji mají v jiné velikosti.
Vcházím do světlého obchodu.
Jdu přímo k pokladně.
Otevřu peněženku a najdu účtenku.
Držím ji připravenou v ruce.
Pak vyndám košili z tašky.
Za pultem stojí milá prodavačka.
Vzhlédne a usměje se na mě.
Oplatím jí úsměv.
