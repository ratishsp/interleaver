Barista se na mě usmívá.
Držím svou kartu nad terminálem.
Přístroj pípne.
„Chcete účtenku?“ ptá se.
„Ne, děkuji,“ odpovídám.
Jdu ke zdi.
Sundávám z háčku svou silnou zimní bundu.
Oblékám si bundu.
Nasazuji si také šálu.
Navlékám si také rukavice.
Teď jsem připravená na zimu.
Znovu se podívám na baristu.
„Moc děkuji za kávu,“ říkám.
„Rádo se stalo,“ říká s úsměvem.
„Mějte hezký den.“
„Nápodobně,“ říkám.
Jdu k hlavním dveřím.
Zatlačím do těžkých dveří a otevírám je.
Vítr je studený, ale cítím se dobře.
