Je páteční večer a Nina klepe na mé dveře.
Má s sebou svého psa, Ludwiga.
Zůstane u mě na víkend.
Nina se usmívá a dává mi vodítko.
„Moc děkuji za pomoc, Mayo,“ říká.
„To je naprosto v pořádku,“ odpovídám vesele.
Vysvětluje mi o něm pár věcí.
„Dávej mu jídlo v sedm ráno a v šest večer,“ říká Nina.
„A pamatuj, nesmí dostávat lidské jídlo.“
Směju se a dívám se dolů na malého psa.
„Ne, Ludwigu, moje večeře není pro tebe,“ říkám mu.
Nina se také směje a ukazuje na dveře.
„Vždy ho měj na vodítku, když půjdete blízko té velké silnice,“ říká.
„V parku může běhat volně.“
Přikyvuji.
„Neboj, dobře se o něj postarám.“
Nina mě objímá a loučí se s námi.
Zavírá dveře a já stojím sama s Ludwigem.
Vzhlíží ke mně a vrtí ocasem.
Už teď ho mám moc ráda.
