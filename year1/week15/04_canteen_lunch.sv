Klockan är tolv.
Det är lunchtid.
Peter och jag går ner till kantinen.
Kantinen är stor och ljus.
Vi är väldigt hungriga.
Vi tittar på den goda maten.
Det finns många alternativ i dag.
Jag väljer ett klassiskt smörrebröd.
Det är med fisk och citron.
Peter tar en stor sallad.
Vi går fram till kassan.
En vänlig man står vid kassan.
"Det blir fyrtio kronor," säger han till mig.
Jag betalar med mitt kort.
"Varsågod," säger jag.
"Tack, och smaklig måltid," svarar han.
Vi hittar ett ledigt bord i hörnet.
Vi sätter oss ner.
Maten smakar verkligen gott.
Vi pratar om vår dag.
