Stojím v supermarketu po práci.
Dnes je v obchodě hodně lidí.
V ruce mám svůj nákupní seznam.
Na zítřejší večeři potřebuji přesná množství.
Nejprve jdu k zelenině.
Najdu nějaké malé, dobré brambory.
Dám je do sáčku a zvážím je.
Váha ukazuje přesně jedno kilo.
To je to správné množství do receptu.
Pak vezmu dvě velké žluté cibule.
Potom přejdu k masu.
Na karbanátky potřebuji mleté vepřové.
Dívám se na různé balíčky v chladicím pultu.
Vybírám balíček s pěti sty gramy.
Nakonec svůj seznam ještě jednou zkontroluji.
Vezmu také balíček másla a trochu mléka.
Dám všechny věci do svého košíku.
Teď jsem připravená vařit pro Kaspera a Saru.
