Jag låser upp dörren.
Jag är äntligen hemma i min lägenhet.
Det är blött och blåsigt ute.
Men det är varmt här inne.
Min vinterjacka är mycket blöt.
Jag tar av mig jackan.
Mitt paraply droppar också vatten.
Jag går ut i badrummet.
Jag lägger paraplyet på golvet.
Vattnet droppar ner på golvplattorna.
Sedan går jag in i vardagsrummet.
Det är helt mörkt här inne.
Jag kan knappt se något.
Det står en liten lampa i hörnet.
Jag tänder lampan.
Ljuset är gult och mjukt.
Det blir genast ljusare i vardagsrummet.
Nu är vardagsrummet varmt och ljust.
Det är skönt att vara inomhus nu.
