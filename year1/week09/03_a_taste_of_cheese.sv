Framför mig finns det ett stort oststånd.
Ståndet har många stora ostar.
En vänlig försäljare ler mot mig.
Han har en liten bit ost på en träpinne.
"Varsågod, ett litet smakprov", säger han.
Han ger pinnen till mig.
Jag äter den gula osten.
Den smakar riktigt gott.
Jag tittar på en liten ost.
"Hur mycket kostar den här osten?" frågar jag.
"Den kostar femtiofem kronor", svarar försäljaren.
Det är ett bra pris.
Jag pekar på den lilla osten.
"Jag köper den", säger jag.
Han slår in osten i papper.
Jag ger honom pengarna.
"Tack så mycket", säger han.
Osten doftar starkt och gott.
