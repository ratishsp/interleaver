വ്യാഴാഴ്ച ഉച്ചതിരിഞ്ഞ് ഞാൻ ഓഫീസിലാണ്.
ഞാനും എന്റെ സഹപ്രവർത്തകൻ പ്രകാശും ചായ കുടിക്കുന്നു.
അദ്ദേഹം എന്നോട് വൈകുന്നേരത്തെ കാര്യങ്ങൾ ചോദിക്കുന്നു.
"മായ, ഇന്ന് ജിമ്മിൽ പോകുന്നുണ്ടോ?" പ്രകാശ് ചോദിക്കുന്നു.
"ഇല്ല," ഞാൻ മറുപടി പറയുന്നു.
"ഇനി ഞാൻ വ്യാഴാഴ്ചകളിൽ ബാഡ്മിന്റൺ കളിക്കാൻ പോകുന്നു."
"ചൊവ്വാഴ്ചകളിൽ മാത്രം ഞാൻ ജിമ്മിൽ പോകും."
"ഏത് സമയത്താണ് കളിക്കാൻ പോകുന്നത്?" പ്രകാശ് ചോദിക്കുന്നു.
"വൈകുന്നേരം അഞ്ചരയ്ക്ക്," ഞാൻ പറയുന്നു.
"എന്റെ നാടായ മെക്സിക്കോയിൽ ഈ കളി കളിക്കാൻ എനിക്ക് വലിയ ഇഷ്ടമാണ്," ഞാൻ വിശദീകരിക്കുന്നു.
"നിങ്ങൾക്ക് നന്നായി കളിക്കാൻ കഴിയുമോ?" പ്രകാശ് ചോദിക്കുന്നു.
"അതെ, എനിക്ക് നന്നായി കളിക്കാൻ കഴിയും," ഞാൻ ചിരിച്ചുകൊണ്ട് പറയുന്നു.
"പുതിയ ആളുകളെ കാണാനും എനിക്ക് ഇഷ്ടമാണ്."
"അത് വളരെ നല്ലതാണ്," പ്രകാശ് പറയുന്നു.
ഞങ്ങൾ ചായ കുടിച്ച് തീർക്കുന്നു.
അതിനുശേഷം ഞങ്ങൾ വീണ്ടും ജോലി ചെയ്യാൻ പോകുന്നു.
