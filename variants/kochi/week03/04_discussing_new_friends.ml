എന്റെ അച്ഛൻ സ്ക്രീനിൽ വരുന്നു.
ഞാൻ ചോദിക്കുന്നു, "അച്ഛാ, നിങ്ങളുടെ ചായ എവിടെ?"
അച്ഛൻ ചിരിക്കുന്നു.
"മായാ, കൊച്ചിയിൽ ആരാണ് നിന്റെ പുതിയ കൂട്ടുകാരി?" അച്ഛൻ ചോദിക്കുന്നു.
ഞാൻ എന്റെ ചൂട് ചായ എടുക്കുന്നു.
ഞാൻ മേശയുടെ അടുത്തേക്ക് നടക്കുന്നു.
ഞാൻ ഫോൺ മേശപ്പുറത്ത് വെക്കുന്നു.
"എന്റെ കൂട്ടുകാരി അനിത ആണ്," ഞാൻ പറയുന്നു.
"അവൾ വളരെ നല്ല ഒരു കൂട്ടുകാരി ആണ്."
"അവൾ എന്റെ അയൽക്കാരി ആണ്."
"അവളുടെ വീട് ഈ കെട്ടിടത്തിൽ ആണ്."
"അവൾ എനിക്ക് ഒരു നല്ല വഴികാട്ടി ആണ്."
"ഈ പുതിയ നഗരത്തിൽ അവൾ എന്നെ സഹായിക്കുന്നു."
അച്ഛൻ വീണ്ടും ചിരിക്കുന്നു.
"അവൾ കൊച്ചിയിൽ നിന്നാണോ?" അദ്ദേഹം ചോദിക്കുന്നു.
"അതെ, അവൾ കൊച്ചിക്കാരി ആണ്," ഞാൻ പറയുന്നു.
എന്റെ അച്ഛന് ഇപ്പോൾ വലിയ സന്തോഷം ഉണ്ട്.
