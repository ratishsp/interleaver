അതിനുശേഷം, ഞാൻ നഗരത്തിലെ വലിയ മ്യൂസിയത്തിലേക്ക് നടന്നു.
അത് പ്രശസ്ത എഴുത്തുകാരനായ ഹാൻസ് ക്രിസ്റ്റ്യൻ ആൻഡേഴ്സനെ കുറിച്ചുള്ളതായിരുന്നു.
ഞാൻ എന്റെ ടിക്കറ്റ് വാങ്ങി ആ മനോഹരമായ കെട്ടിടത്തിനുള്ളിലേക്ക് കയറി.
ആ പ്രദർശനം അദ്ദേഹത്തിന്റെ ജീവിതത്തെക്കുറിച്ചും നീണ്ട യാത്രകളെക്കുറിച്ചും പറയുന്നതായിരുന്നു.
ഒരു വലിയ ചില്ലുകൂട്ടിൽ വെച്ചിരുന്ന അദ്ദേഹത്തിന്റെ പഴയ സാധനങ്ങൾ ഞാൻ നോക്കിക്കണ്ടു.
അദ്ദേഹം തന്റെ നീളൻ തൊപ്പി എല്ലായിടത്തും കൂടെ കൊണ്ടുപോയിരുന്നു.
കറുത്ത നിറമുള്ള ആ നീളൻ തൊപ്പി എന്റെ തൊട്ടുമുന്നിൽത്തന്നെ ഉണ്ടായിരുന്നു.
അദ്ദേഹത്തിന്റെ കടലാസും പഴയ പേനയും അവിടെ ഉണ്ടായിരുന്നു.
തന്റെ അത്ഭുതകരമായ യക്ഷിക്കഥകൾ എഴുതുമ്പോൾ അദ്ദേഹം അവ ഉപയോഗിച്ചിരുന്നു.
ഒരു വെള്ള ഭിത്തിയിലുണ്ടായിരുന്ന നീളമുള്ള ഒരു കുറിപ്പ് ഞാൻ വായിച്ചു.
എനിക്കേറ്റവും പ്രിയപ്പെട്ട യക്ഷിക്കഥയ്ക്ക് പിന്നിലുള്ള ആളെക്കുറിച്ചായിരുന്നു അത്.
യഥാർത്ഥത്തിൽ അദ്ദേഹമാണ് ആ ചെറിയ മത്സ്യകന്യകയെ സൃഷ്ടിച്ചത്.
കഴിഞ്ഞ ഫെബ്രുവരിയിൽ കോപ്പൻഹേഗനിൽ വെച്ച് ഒരു പ്രതിമയായി ഞാൻ അവളെ കണ്ടിരുന്നു.
ഇപ്പോൾ ആ എഴുത്തുകാരന്റെ സ്വന്തം സാധനങ്ങൾ കാണുന്നത് വളരെ രസകരമായിരുന്നു.
അദ്ദേഹത്തിന്റെ വലിയ യാത്രാ ബാഗിന്റെ കുറച്ചു ചിത്രങ്ങൾ ഞാൻ എടുത്തു.
പുതിയ രാജ്യങ്ങൾ സന്ദർശിക്കാൻ അദ്ദേഹം ഒരുപാട് ഇഷ്ടപ്പെട്ടിരുന്നു എന്ന് തോന്നുന്നു.
അവസാനം മ്യൂസിയത്തിലെ കടയിൽ നിന്ന് ഞാൻ ഒരു ചെറിയ പുസ്തകം വാങ്ങി.
അദ്ദേഹത്തിന്റെ ഏറ്റവും മികച്ച കഥകളെല്ലാം അതിൽ ഉണ്ടായിരുന്നു.
ഡാനിഷ് സംസ്കാരത്തെക്കുറിച്ച് ഇപ്പോൾ എനിക്ക് കുറച്ചുകൂടി നന്നായി അറിയാമെന്ന് തോന്നുന്നു.
