ഇന്ന് ബുധനാഴ്ച ആണ്.
ഞാൻ ഓഫീസിൽ ആണ്.
ഞാൻ എന്റെ ഡെസ്കിൽ ജോലി ചെയ്യുന്നു.
ഇപ്പോൾ സമയം ഉച്ചയ്ക്ക് മൂന്ന് മണി ആണ്.
ഓഫീസിൽ എപ്പോഴും ഒരുപാട് ജോലിയുണ്ട്.
പ്രകാശ് അടുത്ത ഡെസ്കിൽ ജോലി ചെയ്യുന്നു.
അപ്പോൾ എന്റെ ഫോണിൽ ഒരു മെസ്സേജ് വരുന്നു.
അത് എന്റെ അയൽക്കാരി അനിതയാണ്.
അനിത ചിലപ്പോൾ ഉച്ചയ്ക്ക് മെസ്സേജ് അയക്കും.
"മായാ, നാളെ ഫ്രീ ആണോ?" അനിത ചോദിക്കുന്നു.
നാളെ വ്യാഴാഴ്ച ആണ്.
"നമുക്ക് വൈകുന്നേരം കാപ്പി കുടിക്കാൻ പോകാം," മെസ്സേജിൽ പറയുന്നു.
"വൈകുന്നേരം അഞ്ചരയ്ക്ക് പോകാമോ?"
ഞാൻ എല്ലാ ദിവസവും കാപ്പി കുടിക്കും.
ഞാൻ വേഗം ഒരു മറുപടി ടൈപ്പ് ചെയ്യുന്നു.
"ശരി, നമുക്ക് അഞ്ചരയ്ക്ക് കാണാം."
ഞാൻ ഫോൺ ഡെസ്കിൽ വെക്കുന്നു.
ഞാൻ വീണ്ടും ജോലി തുടങ്ങുന്നു.
