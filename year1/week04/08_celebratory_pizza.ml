ഫ്ലാറ്റ് ഒടുവിൽ തയ്യാറായി.
ഇപ്പോൾ ഇതൊരു യഥാർത്ഥ വീടാണ്.
നീന വാതിലിൽ മുട്ടുന്നു.
അവൾ ചൂടുള്ള ഭക്ഷണവുമായി വാതിൽക്കൽ നിൽക്കുന്നു.
"എൻ്റെ പക്കൽ രണ്ട് പിസ്സകളുണ്ട്," അവൾ പറയുന്നു.
ഞങ്ങൾ സ്വീകരണമുറിയിലേക്ക് പോകുന്നു.
ജനലിനരികിൽ ഒരു ചെറിയ സോഫയുണ്ട്.
ഞങ്ങൾ ഒരുമിച്ച് സോഫയിൽ ഇരിക്കുന്നു.
കോഫി ടേബിളിൽ രണ്ട് പിസ്സ ബോക്സുകളുണ്ട്.
ആ ബോക്സുകൾ ഞങ്ങൾക്കിടയിലാണ്.
മേശപ്പുറത്ത് രണ്ട് ഗ്ലാസുകൾ കൂടിയുണ്ട്.
ഞങ്ങൾ ആ ചൂടുള്ള പിസ്സകൾ കഴിക്കുന്നു.
"നിൻ്റെ പുതിയ ഫ്ലാറ്റിലേക്ക് സ്വാഗതം," നീന പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ മറുപടി നൽകുന്നു.
ഞങ്ങൾ ഒരുപാട് നേരം ഒരുമിച്ച് സംസാരിക്കുന്നു.
എൻ്റെ പുതിയ ചെടി ജനൽപ്പടിയിലുണ്ട്.
എൻ്റെ വീട്ടുചെരുപ്പുകൾ കസേരയ്ക്കടിയിലാണ്.
എല്ലാം അതിൻ്റെ സ്ഥാനത്താണ്.
എൻ്റെ പുതിയ വീട്ടിൽ ഞാൻ വളരെ സന്തോഷവതിയാണ്.
