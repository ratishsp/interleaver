സെയിൽസ് വുമൺ എനിക്ക് ഒരു കുർത്തി കാണിക്കുന്നു.
അത് ഒരു മഞ്ഞ കുർത്തി ആണ്.
അത് നല്ല കോട്ടൺ ആണ്.
ഞാൻ തുണി തൊടുന്നു.
തുണി വളരെ മൃദു ആണ്.
ഞാൻ വില ചോദിക്കുന്നു.
"ഈ കുർത്തിയുടെ വില എന്താണ്?" ഞാൻ ചോദിക്കുന്നു.
"അറുനൂറ് രൂപ ആണ് വില," സെയിൽസ് വുമൺ പറയുന്നു.
ഞാൻ ആ മഞ്ഞ കുർത്തി എടുക്കുന്നു.
ഞാൻ ഫിറ്റിംഗ് റൂമിലേക്ക് നടക്കുന്നു.
ഞാൻ കുർത്തി ധരിക്കുന്നു.
ഞാൻ കണ്ണാടിയിൽ നോക്കുന്നു.
ഇത് നല്ല പാകം ആണ്.
ഇത് വലിയ കുർത്തി അല്ല.
ഇത് ചെറിയ കുർത്തി അല്ല.
കുർത്തി വളരെ മനോഹരം ആണ്.
എനിക്ക് ഈ മഞ്ഞ കുർത്തി ഇഷ്ടമാണ്.
ഞാൻ സെയിൽസ് വുമണിന്റെ അടുത്തേക്ക് തിരിച്ചു പോകുന്നു.
"ഞാൻ ഇത് വാങ്ങുന്നു," ഞാൻ പറയുന്നു.
