ഇന്ന് ശനിയാഴ്ച ആണ്.
കൊച്ചിയിൽ രാവിലെ നല്ല കാലാവസ്ഥ ആണ്.
ഞാൻ ഫ്ലാറ്റിന് പുറത്ത് വരുന്നു.
അനിത അവിടെ ഉണ്ട്.
"ഗുഡ് മോർണിംഗ് മായാ," അനിത പറയുന്നു.
"പുറത്ത് പോവുകയാണോ?" അവൾ ചോദിക്കുന്നു.
ഞാൻ പറയുന്നു, "അതെ, ഞാൻ സിറ്റിയിലേക്ക് പോവുകയാണ്."
അനിത ചിരിക്കുന്നു.
"മറൈൻ ഡ്രൈവിലേക്ക് പോകൂ," അവൾ പറയുന്നു.
"അതൊരു നല്ല സ്ഥലമാണ്."
"ഞാൻ അവിടെ എങ്ങനെ പോകും?"
ഞാൻ ചോദിക്കുന്നു.
അനിത എനിക്ക് വഴി പറയുന്നു.
"ആദ്യം, ഇവിടെ നിന്ന് നേരെ നടക്കൂ."
"എന്നിട്ട്, വലത്തോട്ട് തിരിയൂ."
"അവിടെ ഒരു ബസ് സ്റ്റോപ്പ് ഉണ്ട്."
"അവിടെ നിന്ന് സിറ്റിയിലേക്ക് ബസ്സിൽ പോകൂ."
"ശരി, വളരെ നന്ദി," ഞാൻ പറയുന്നു.
ഞാൻ സന്തോഷത്തോടെ താഴേക്ക് നടക്കുന്നു.
