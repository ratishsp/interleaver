Dveře jsou otevřené.
Práh je vysoký.
Kufr je velmi těžký!
Ale teď je kufr v předsíni.
Je tu úplná tma.
Kde je vypínač?
Stěna je studená.
Je vypínač tady?
Ano, tam je vypínač!
Teď je tu světlo.
Jsem v bytě.
Je malý, ale je hezký.
Tady je obývací pokoj.
Je tam pohovka a stůl.
Je to zařízený domov.
Kufr je na podlaze.
Jsem velmi unavená.
Ale jsem také šťastná.
Jsem v Kodani!
