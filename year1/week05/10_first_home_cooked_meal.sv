Köket är litet.
Men spisen är bra.
Jag tar palsternackan och en morot.
Jag tar också en kniv.
Kniven är vass.
Jag skär palsternackan och moroten.
Jag öppnar burken.
Jag lägger maten i en gryta.
Grytan står på spisen.
Nu är maten varm.
Den doftar ljuvligt.
Jag tar rågbrödet.
Jag skär en skiva.
Tallriken står på bordet.
Äntligen äter jag en riktig måltid i lägenheten.
Efteråt äter jag kanelbullen.
Den smakar sött.
