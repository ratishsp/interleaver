ഇന്ന് ഞായറാഴ്ചയാണ്.
കൊച്ചിയിൽ ഇപ്പോൾ നല്ല കാലാവസ്ഥയാണ്.
ഇന്ന് രാവിലെ വളരെ ശാന്തമാണ്.
ഞാൻ എന്റെ കലണ്ടർ നോക്കുന്നു.
ഞാൻ ഈ ആഴ്ചയിലെ കാര്യങ്ങൾ പ്ലാൻ ചെയ്യുന്നു.
തിങ്കളാഴ്ച മുതൽ വെള്ളിയാഴ്ച വരെ ഞാൻ ഓഫീസിൽ പോകുന്നു.
എല്ലാ ദിവസവും രാവിലെ എട്ടു മണിക്ക് ഞാൻ ഓഫീസിൽ പോകുന്നു.
അതിനാൽ, വൈകുന്നേരങ്ങളിൽ മാത്രമാണ് എനിക്ക് സമയമുള്ളത്.
വൈകുന്നേരം ഞാൻ എന്റെ സ്വന്തം കാര്യങ്ങൾ ചെയ്യുന്നു.
ചൊവ്വാഴ്ചയും വ്യാഴാഴ്ചയും ഞാൻ ജിമ്മിൽ പോകുന്നു.
ഞാൻ എപ്പോഴും കൃത്യസമയത്ത് അവിടെ പോകുന്നു.
ഈ ആഴ്ച എനിക്ക് മുടി വെട്ടണം.
മുടി വെട്ടാൻ എത്ര മണിക്ക് പോകണം?
അത് ഞാൻ നാളെ തീരുമാനിക്കും.
എനിക്ക് എന്റെ സൈക്കിളും നന്നാക്കണം.
വൈകുന്നേരം ചിലപ്പോൾ ഞാൻ സൈക്കിൾ ഓടിക്കുന്നു.
ഞാൻ ഈ കാര്യങ്ങൾ എല്ലാം കലണ്ടറിൽ എഴുതുന്നു.
വരുന്ന ആഴ്ച വളരെ തിരക്കുള്ളതാണ്.
പക്ഷേ ഇന്ന് ഞാൻ വീട്ടിൽ വിശ്രമിക്കുന്നു.
