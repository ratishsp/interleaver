കൗണ്ടറിന് പിന്നിൽ ഇത് എന്റെ ആദ്യത്തെ തവണയാണ്.
കഫേ ഇതുവരെ തുറന്നിട്ടില്ല.
പരിചയസമ്പന്നരായ വോളന്റിയർമാരിൽ ഒരാൾ എന്നെ വിളിക്കുന്നു.
ഞങ്ങൾ വലിയ എസ്‌പ്രെസ്സോ മെഷീനു മുന്നിൽ നിൽക്കുന്നു.
"ഇന്ന് നീ കാപ്പി ഉണ്ടാക്കാൻ പഠിക്കണം," അദ്ദേഹം പറയുന്നു.
ഇതിനുമുമ്പ് ഞാൻ ഇങ്ങനെയൊരു മെഷീനിൽ കാപ്പി ഉണ്ടാക്കിയിട്ടില്ല.
കാപ്പിക്കുരു പൊടിക്കുക എന്നതാണ് ആദ്യത്തെ പടി.
അദ്ദേഹം ഒരു ചെറിയ ബട്ടൺ അമർത്തുന്നു.
വലിയ ശബ്ദത്തോടെ മെഷീൻ ആ തവിട്ടുനിറത്തിലുള്ള കുരുക്കൾ പൊടിക്കുന്നു.
പാൽ സ്റ്റീം ചെയ്യുക എന്നതാണ് രണ്ടാമത്തെ പടി.
അദ്ദേഹം ഒരു മെറ്റൽ ജഗ്ഗിലേക്ക് തണുത്ത പാൽ ഒഴിക്കുന്നു.
അതിനുശേഷം അദ്ദേഹം ചൂടുള്ള ആവി തുറന്നുവിടുന്നു.
ആ സമയത്ത് ഞാൻ അദ്ദേഹത്തിന്റെ കൈകൾ ശ്രദ്ധിച്ചു നോക്കുന്നു.
ജഗ്ഗിലെ പാൽ പെട്ടെന്ന് ചൂടുള്ളതും കട്ടിയുള്ളതുമായി മാറുന്നു.
അദ്ദേഹം ഇതിനുമുമ്പ് പലതവണ കാപ്പി ഉണ്ടാക്കിയിട്ടുണ്ടെന്ന് വ്യക്തമാണ്.
ഇന്ന് രാവിലെ ഞാൻ എത്തിയപ്പോൾ എനിക്ക് നല്ല പരിഭ്രമമുണ്ടായിരുന്നു.
പക്ഷേ അദ്ദേഹം അത് നന്നായി വിശദീകരിച്ചു, അതിനാൽ എനിക്ക് ഇതിനകം തന്നെ മിക്കവാറും കാര്യങ്ങൾ മനസ്സിലായി.
