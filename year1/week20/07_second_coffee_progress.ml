അതേ ശനിയാഴ്ച പിന്നീട്, ഞങ്ങൾക്ക് വീണ്ടും നല്ല തിരക്കായി.
ഒരു യുവതി കൗണ്ടറിനടുത്ത് വന്ന് ഒരു വലിയ കപ്പുച്ചിനോ ഓർഡർ ചെയ്തു.
എൻ്റെ ആദ്യത്തെ കപ്പ് അത്ര പൂർണ്ണമായിരുന്നില്ല.
എന്നാൽ ഇത്തവണ ഞാൻ തയ്യാറായിരുന്നു.
ഞാൻ മെറ്റൽ ജഗ്ഗ് എടുത്ത് അതിൽ തണുത്ത പാൽ ഒഴിച്ചു.
ഞാൻ ആ ജഗ്ഗ് മെഷീന്റെ അടിയിൽ വെച്ച് ചൂടുള്ള ആവി ഓൺ ആക്കി.
ഞാൻ പെട്ടെന്ന് തന്നെ മർദ്ദം കൂട്ടിയില്ല.
ഞാൻ യഥാർത്ഥത്തിൽ മെഷീന്റെ ശബ്ദം ശ്രദ്ധിക്കാൻ പഠിച്ചിട്ടുണ്ട്.
ആവിയിൽ നിന്നുള്ള വലിയ ശബ്ദം ഇത്തവണ തികച്ചും ശരിയായിരുന്നു.
പാൽ പതുക്കെ ചൂടായി.
കൂടാതെ മുകളിലെ പത വളരെ കട്ടിയുള്ളതും മൃദുവായതുമായി മാറി.
അതൊരു വലിയ ചുവടുവെപ്പായിരുന്നു.
ഞാൻ വളരെ ശ്രദ്ധയോടെ ഒരു വലിയ കപ്പിലെ കോഫിക്ക് മുകളിൽ പാൽ ഒഴിച്ചു.
അത് കണ്ടാൽ ശരിക്കും ഒരു പ്രൊഫഷണൽ കപ്പുച്ചിനോ പോലെ ഉണ്ടായിരുന്നു.
"ഇതാ," ഞാൻ പറഞ്ഞുകൊണ്ട് ആ കപ്പ് കൗണ്ടറിൽ വെച്ചു.
ആ സ്ത്രീ പുഞ്ചിരിച്ചുകൊണ്ട് അവരുടെ കോഫി എടുത്തു.
മർദ്ദം നിയന്ത്രിക്കാൻ ഞാൻ ഒടുവിൽ പഠിച്ചു കഴിഞ്ഞു.
