Po večeři jdu do obývacího pokoje.
V bytě je krásně teplo.
Venku je tma a zima.
Rozsvítím malou lampu.
Světlo je teplé a měkké.
Připravím si šálek teplého čaje.
Pak jdu k pohovce.
Sednu si na měkké polštáře.
Na stole leží nová kniha.
Vezmu knihu a otevřu ji.
Je to napínavý příběh.
Přečtu si pár kapitol.
Můj čaj hezky voní.
Dám si doušek.
Opřu se.
Teď se úplně uvolním.
V bytě je úplné ticho.
Užívám si čas o samotě.
