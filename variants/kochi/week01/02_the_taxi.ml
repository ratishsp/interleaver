അവിടെ ഒരു ടാക്സി ഉണ്ട്.
ഞാൻ എന്റെ വലിയ ബാഗ് ടാക്സിയിൽ വെക്കുന്നു.
ഞാൻ ടാക്സിയിൽ കയറുന്നു.
ഡ്രൈവർ എന്നെ നോക്കുന്നു.
"മാഡം, സ്ഥലം എവിടെ ആണ്?" അദ്ദേഹം ചോദിക്കുന്നു.
ഞാൻ എന്റെ പുതിയ വിലാസം അദ്ദേഹത്തിന് കൊടുക്കുന്നു.
"സ്ഥലം നഗരത്തിന് അടുത്താണോ?" അദ്ദേഹം ചോദിക്കുന്നു.
"അതെ, ഫ്ലാറ്റ് എന്റെ ഓഫീസിന് അടുത്താണ്," ഞാൻ പറയുന്നു.
ടാക്സി മുന്നോട്ട് പോകുന്നു.
"നിങ്ങൾ എവിടെ നിന്ന് ആണ്?" അദ്ദേഹം ചോദിക്കുന്നു.
"ഞാൻ മെക്സിക്കോയിൽ നിന്ന് ആണ്," ഞാൻ പറയുന്നു.
"മെക്സിക്കോ, വളരെ നല്ലത് മാഡം," അദ്ദേഹം പറയുന്നു.
ടാക്സി എന്റെ പുതിയ ഫ്ലാറ്റിലേക്ക് പോകുന്നു.
