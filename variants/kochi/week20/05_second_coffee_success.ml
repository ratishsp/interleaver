ഞാൻ ദീർഘമായി ഒന്ന് ശ്വാസമെടുക്കുന്നു.
ഞാൻ എന്റെ രണ്ടാമത്തെ കോഫി ഉണ്ടാക്കാൻ തുടങ്ങുന്നു.
ഒന്നാമത്തെ കോഫിയിൽ എനിക്ക് തെറ്റുകൾ പറ്റിയിരുന്നു.
ഇത്തവണ ഞാൻ സ്റ്റീം വാൻഡിൽ കൂടുതൽ ശ്രദ്ധിക്കുന്നു.
ഞാൻ പാൽപാത്രം ശരിയായി പിടിക്കുന്നു.
പാൽ നന്നായി പതപ്പിക്കാൻ ഞാൻ പഠിക്കുകയാണ്.
ഞാൻ സ്റ്റീം വാൻഡ് ഓൺ ചെയ്യുന്നു.
ഇപ്പോൾ പാൽ നന്നായി പതഞ്ഞു വന്നിട്ടുണ്ട്.
ഞാൻ ആ പാൽ ശ്രദ്ധയോടെ കപ്പിലേക്ക് ഒഴിക്കുന്നു.
ജെസ്സി ആ കോഫി നോക്കുന്നു.
അവർക്ക് അത് ഇഷ്ടമായിട്ടുണ്ട്.
"ഇത് വളരെ നന്നായിട്ടുണ്ട്, മായ," ജെസ്സി പറയുന്നു.
എനിക്ക് വളരെ സന്തോഷം തോന്നുന്നു.
ഞാൻ നല്ലൊരു കോഫി ഉണ്ടാക്കിയിട്ടുണ്ട്!
ഈ മെഷീൻ ഉപയോഗിക്കാൻ ഞാൻ പതുക്കെ പഠിക്കുകയാണ്.
ഇന്ന് എനിക്ക് വലിയ അഭിമാനം തോന്നുന്നു.
