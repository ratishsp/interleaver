ഞാൻ സ്റ്റൗ കത്തിച്ച് ഒരു പാൻ ചൂടാക്കുന്നു.
ഞാൻ പാനിലേക്ക് കുറച്ച് വെളിച്ചെണ്ണ ഒഴിക്കുന്നു.
ആദ്യം, ഞാൻ അരിഞ്ഞ ഉള്ളി ചൂടായ എണ്ണയിലേക്ക് ഇടുന്നു.
ഞാൻ ഉള്ളി നന്നായി വഴറ്റുന്നു.
അത് പതുക്കെ സ്വർണ്ണ നിറമാകുന്നു.
പിന്നെ, ഞാൻ അരിഞ്ഞ തക്കാളി ചേർക്കുന്നു.
"തക്കാളി മൃദുവാകുന്നതുവരെ ഇളക്കുക," എന്ന് പാചകക്കുറിപ്പിൽ പറയുന്നു.
ഞാൻ അഞ്ച് മിനിറ്റ് ഇത് നന്നായി ഇളക്കുന്നു.
അതിനുശേഷം, മസാലകൾ ചേർക്കാനുള്ള സമയമാണ്.
ഞാൻ കൃത്യം രണ്ട് സ്പൂൺ മസാലപ്പൊടി ചേർക്കുന്നു.
അടുക്കളയിൽ നല്ലൊരു മണം നിറയുന്നു.
അവസാനം, ഞാൻ ചിക്കൻ കഷണങ്ങൾ അതിലേക്ക് ഇടുന്നു.
"ഇറച്ചി മസാലയുമായി നന്നായി യോജിപ്പിക്കുക," പാചകക്കുറിപ്പിൽ പറയുന്നു.
ഞാൻ എല്ലാം കൂടി ശ്രദ്ധയോടെ ഇളക്കുന്നു.
അടുത്തതായി, ഞാൻ അര കപ്പ് വെള്ളം ഒഴിക്കുന്നു.
"ആവശ്യത്തിന് ഉപ്പ് ചേർത്ത് പാൻ അടച്ചുവെക്കുക," ഞാൻ ഉറക്കെ വായിക്കുന്നു.
ഞാൻ ഉപ്പ് ചേർത്ത് പാൻ അടച്ചുവെക്കുന്നു.
ഇനി കറി ഇരുപത് മിനിറ്റ് വേവണം.
