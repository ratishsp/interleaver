ഞാൻ വരാന്തയിൽ നിൽക്കുന്നു.
എന്റെ കയ്യിൽ ഒരു താക്കോൽ ഉണ്ട്.
ഇത് എന്റെ പുതിയ ഫ്ലാറ്റിന്റെ താക്കോൽ ആണ്.
ഞാൻ വാതിൽ തുറക്കുന്നു.
ഞാൻ മെല്ലെ ഉള്ളിലേക്ക് നടക്കുന്നു.
ഇത് എന്റെ സ്വന്തം വീടാണ്.
ഞാൻ സ്വീകരണമുറിയിൽ ചുറ്റും നോക്കുന്നു.
ഇവിടെ നല്ല നിശബ്ദതയാണ്.
ഈ മുറിയിൽ ഫർണിച്ചറുകൾ ഉണ്ട്.
വാതിലിന്റെ അടുത്ത് ഒരു ചെറിയ മേശ ഇരിക്കുന്നു.
മേശയ്ക്ക് മുകളിൽ ഒരു വിളക്ക് ഉണ്ട്.
മുറിയുടെ നടുവിൽ ഒരു വലിയ സോഫ ഇരിക്കുന്നു.
സോഫയുടെ അടിയിൽ ഒരു പരവതാനി കിടക്കുന്നു.
ജനലിന്റെ അടുത്ത് ഒരു കസേരയും ഇരിക്കുന്നു.
ജനലിലൂടെ നല്ല വെളിച്ചം വരുന്നുണ്ട്.
കൊച്ചിയിൽ ഇപ്പോൾ ജനുവരിയിലെ നല്ല കാലാവസ്ഥയാണ്.
ഞാൻ ദീർഘമായി ശ്വാസം എടുക്കുന്നു.
എനിക്ക് ഈ പുതിയ ഫ്ലാറ്റ് വളരെ ഇഷ്ടമാണ്.
