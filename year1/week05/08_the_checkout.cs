Jdu k pokladně.
Mám v ruce košík.
Pokládám jídlo na pás.
Nejdřív beru z košíku žitný chleba.
Pak beru mléko a pastinák.
Beru také mrkev a černé fazole.
Nakonec pokládám na pás sladké pečivo.
Pokladní sedí za pokladnou.
Usmívá se na mě.
„Dobrý den,“ říká.
„Dobrý den,“ odpovídám.
Rychle skenuje jídlo.
Vytahuji svou kartu.
Držím kartu nad terminálem.
Terminál pípne.
„Přejete si účtenku?“ ptá se.
„Ano, prosím, ráda bych účtenku,“ říkám.
Otevírám svou tašku.
Rychle skládám věci do tašky.
„Mějte hezký den,“ říká.
