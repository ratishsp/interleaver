Přicházím k malému pekařství na rohu.
Vcházím do teplého obchodu.
Krásně to tu voní kávou a dorty.
Za pultem stojí pekař v bílé zástěře.
„Dobré odpoledne,“ říká pekař.
„S čím vám mohu pomoci?“ ptá se.
Dívám se na tu spoustu dortů.
Kupuji dort na dnešní večer.
Ukazuji na pěkný čokoládový dort.
„Prosila bych ten čokoládový dort,“ říkám.
„Samozřejmě,“ odpovídá pekař.
Dává dort do bílé krabice.
„Bude to šedesát pět korun,“ říká.
Vytahuji z tašky peněženku.
Platím těch šedesát pět korun.
„Moc děkuji a přeji hezký večer,“ říká pekař.
„Děkuji, nápodobně,“ odpovídám.
Beru si bílou krabici.
Opatrně s dortem vycházím z obchodu.
