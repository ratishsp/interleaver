ഞാൻ ഡോക്ടറുടെ മുറിയിലേക്ക് കയറുന്നു.
ഡോക്ടർ അവിടെ ഇരിക്കുന്നുണ്ട്.
അദ്ദേഹം എന്നോട് കസേരയിൽ ഇരിക്കാൻ പറയുന്നു.
"എന്താണ് ബുദ്ധിമുട്ട്?" ഡോക്ടർ ചോദിക്കുന്നു.
"എനിക്ക് തീരെ സുഖമില്ല," ഞാൻ മറുപടി പറയുന്നു.
"എനിക്ക് പനിയും തലവേദനയും ഉണ്ട്."
"വേറെ എന്തൊക്കെ പ്രശ്നങ്ങൾ ഉണ്ട്?" അദ്ദേഹം ചോദിക്കുന്നു.
"എനിക്ക് നല്ല തൊണ്ടവേദന ഉണ്ട്," ഞാൻ പറയുന്നു.
"വെള്ളം കുടിക്കുമ്പോൾ തൊണ്ട നന്നായി വേദനിക്കുന്നു."
"പിന്നെ, നല്ല ചുമയും ഉണ്ട്."
"ശരീരവേദന ഉണ്ടോ?" ഡോക്ടർ വീണ്ടും ചോദിക്കുന്നു.
"അതെ, ശരീരം മുഴുവൻ വേദനിക്കുന്നു," ഞാൻ പറയുന്നു.
"രാത്രി ഉറങ്ങാൻ കഴിഞ്ഞോ?" അദ്ദേഹം ചോദിക്കുന്നു.
"ഇല്ല, ചുമ കാരണം ഞാൻ ഉറങ്ങിയില്ല," ഞാൻ മറുപടി പറയുന്നു.
ഡോക്ടർ ഒരു ചെറിയ ടോർച്ച് എടുക്കുന്നു.
"വായ തുറക്കൂ," അദ്ദേഹം എന്നോട് പറയുന്നു.
"ഞാൻ തൊണ്ട ഒന്ന് നോക്കട്ടെ."
ഞാൻ വായ തുറക്കുന്നു.
അദ്ദേഹം എന്റെ തൊണ്ട പരിശോധിക്കുന്നു.
