ഇപ്പോൾ രാത്രിയാണ്.
കോപ്പൻഹേഗനിലെ എന്റെ ആദ്യത്തെ രാത്രിയാണിത്.
ഞാൻ ബാത്ത്റൂമിലാണ്.
ഇത് വളരെ ചെറുതാണ്.
അവിടെ ഒരു സിങ്ക് ഉണ്ട്.
എന്റെ ടൂത്ത് ബ്രഷ് ചുവപ്പാണ്.
ഞാൻ എന്റെ ടൂത്ത് ബ്രഷിൽ ടൂത്ത് പേസ്റ്റ് വെക്കുന്നു.
ഞാൻ പല്ല് തേക്കുന്നു.
വെള്ളം തണുത്തതാണ്.
ഞാൻ മുഖം കഴുകുന്നു.
ഞാൻ മുഖം തുടയ്ക്കുന്നു.
ഞാൻ എന്റെ കിടക്കയിലേക്ക് പോകുന്നു.
കിടക്ക ഇടുങ്ങിയതാണ്.
പക്ഷേ അത് ചൂടുള്ളതും മൃദുവായതുമാണ്.
ഞാൻ ഇപ്പോൾ പുതപ്പിനടിയിൽ കിടക്കുകയാണ്.
എന്റെ ഫോൺ മേശപ്പുറത്തുണ്ട്.
ഞാൻ അലാറം വെക്കുന്നു.
നാളെ എട്ട് മണിക്ക് അത് അടിക്കും.
ഞാൻ ക്ഷീണിതയാണ്, എങ്കിലും ഞാൻ തയ്യാറാണ്.
ശുഭരാത്രി, കോപ്പൻഹേഗൻ.
