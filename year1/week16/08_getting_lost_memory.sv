Nu skrattar jag och berättar om en förvirrande lördag.
Det var en kall lördagsmorgon den första vintern.
Jag ville gå ner till hamnen.
Nina gav mig rutten i förväg.
På vägen hörde jag en gatumusiker.
Han spelade vackert på sin gitarr.
Jag stannade och lyssnade länge.
Då glömde jag helt bort Ninas rutt.
Jag gick in på en smal sidogata.
Där fanns bara små, tysta hus.
Plötsligt gick jag helt vilse.
Framför mig gick en ung kvinna med en liten hund.
Hunden såg exakt ut som vår Lola.
"Ursäkta, jag letar efter hamnen", sa jag.
Hon pekade vänligt tillbaka mot torget.
Jag tackade henne och hittade rätt väg.
Till slut nådde jag ner till vattnet.
Min bror Diego skrattar högt på skärmen.
Det var ett fånigt misstag, men ett fint minne.
