ഞാൻ പീറ്ററിന്റെ ഡെസ്കിനടുത്ത് ഇരിക്കുന്നു.
ഞങ്ങൾ അവന്റെ വലിയ സ്ക്രീനിലേക്ക് നോക്കുന്നു.
പീറ്ററും ഒരു സോഫ്റ്റ്‌വെയർ എഞ്ചിനീയറാണ്.
അവനൊരു നല്ല സഹപ്രവർത്തകനാണ്, ഞങ്ങൾ ഒരുമിച്ച് ഒരുപാട് കോഡ് എഴുതാറുണ്ട്.
ഇന്ന് അവന് വളരെ ക്ഷീണമുള്ളതായി തോന്നുന്നു.
"നീ എന്താണ് ചെയ്യുന്നത്, പീറ്റർ?" ഞാൻ ചോദിക്കുന്നു.
"എനിക്കൊരു വലിയ പ്രശ്നമുണ്ട്," അവൻ മറുപടി പറയുന്നു.
"കഴിഞ്ഞ മൂന്ന് മണിക്കൂറായി ഞാൻ ഈ എററിന്മേൽ ജോലി ചെയ്യുകയാണ്."
ഞാൻ പുഞ്ചിരിച്ചുകൊണ്ട് കോഡ് സൂക്ഷ്മമായി നോക്കുന്നു.
ഞങ്ങളുടെ ജോലിയിൽ ഞങ്ങൾ പലപ്പോഴും സങ്കീർണ്ണമായ പ്രശ്നങ്ങൾ ഒരുമിച്ച് പരിഹരിക്കാറുണ്ട്.
പെട്ടെന്ന് ഞാൻ സ്ക്രീനിൽ വിചിത്രമായ എന്തോ ഒന്ന് കാണുന്നു.
അതൊരു വളരെ ചെറിയ തെറ്റാണ്.
"ഇവിടെ ഒന്നു നോക്കൂ," സ്ക്രീനിലേക്ക് ചൂണ്ടിക്കൊണ്ട് ഞാൻ പറയുന്നു.
"നീ ഇവിടെ ഒരു ചെറിയ ടൈപ്പിംഗ് തെറ്റ് വരുത്തിയിട്ടുണ്ട്."
പീറ്റർ രണ്ട് സെക്കൻഡ് നിശബ്ദനായി സ്ക്രീനിലേക്ക് നോക്കുന്നു.
പിന്നെ അവൻ ഉറക്കെ ചിരിക്കുന്നു.
"നീ പറഞ്ഞത് തികച്ചും ശരിയാണ്," പീറ്റർ പറയുന്നു.
"ഞാൻ മൂന്ന് മണിക്കൂറായി ജോലി ചെയ്യുകയായിരുന്നു, എന്നിട്ട് വെറുമൊരു ചെറിയ തെറ്റ് മാത്രം!"
ഞാനും ചിരിക്കുന്നു, കാരണം എല്ലാ സോഫ്റ്റ്‌വെയർ എഞ്ചിനീയർമാർക്കും ആ സാഹചര്യം അറിയാം.
ഞങ്ങൾ ആ തെറ്റ് തിരുത്തുന്നു, ഒടുവിൽ പ്രോഗ്രാം കൃത്യമായി പ്രവർത്തിക്കുന്നു.
