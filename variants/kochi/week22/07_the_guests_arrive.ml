അടുക്കളയിൽ നിന്ന് മസാലയുടെ നല്ല മണം വരുന്നു.
കറി അടുപ്പിൽ തിളക്കുന്നു.
അപ്പോൾ ഞാൻ വാതിലിൽ ഒരു ശബ്ദം കേൾക്കുന്നു.
ഞാൻ വാതിൽ തുറക്കുന്നു.
കിരണും സാറയും വാതിൽക്കൽ നിൽക്കുന്നു.
അവരുടെ കയ്യിൽ നനഞ്ഞ കുടകൾ ഉണ്ട്.
ആദ്യം, അവർ കുടകൾ അടയ്ക്കുന്നു.
"കുടകൾ അവിടെ വെക്കൂ," ഞാൻ പറയുന്നു.
അവർ കുടയിലെ വെള്ളം തട്ടിക്കളയുന്നു.
അതിനുശേഷം, "മായേ, എന്ത് നല്ല മണം!" സാറ സന്തോഷത്തോടെ പറയുന്നു.
"ചിക്കൻ കറിയുടെ മണമാണ്," കിരൺ പറയുന്നു.
"അതെ, ഞാൻ ചിക്കൻ കറി ഉണ്ടാക്കുകയാണ്," ഞാൻ പറയുന്നു.
കറി തയ്യാറാകാൻ അഞ്ച് മിനിറ്റ് കൂടി വേണം.
പിന്നെ, ഞാൻ അവരെ അകത്തേക്ക് വിളിക്കുന്നു.
