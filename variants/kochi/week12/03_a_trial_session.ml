ഞാൻ ക്ലബ്ബിന്റെ ഫ്രണ്ട് ഡെസ്കിലേക്ക് പോകുന്നു.
അവിടെ ഒരാൾ ഇരിക്കുന്നു.
ഞാൻ അയാളെ നോക്കി ചിരിക്കുന്നു.
"നിങ്ങൾ ഇവിടെ മെമ്പർ ആണോ?" അയാൾ ചോദിക്കുന്നു.
"അല്ല, ഞാൻ മെമ്പർ അല്ല," ഞാൻ മറുപടി പറയുന്നു.
"എനിക്ക് ഒരു ദിവസം കളിക്കാൻ കഴിയുമോ?" ഞാൻ ചോദിക്കുന്നു.
"അതെ, നിങ്ങൾക്ക് കളിക്കാൻ കഴിയും," അയാൾ പറയുന്നു.
"ഗസ്റ്റ് ഫീസ് ഇരുന്നൂറ് രൂപയാണ്."
ഞാൻ അയാൾക്ക് ഇരുന്നൂറ് രൂപ കൊടുക്കുന്നു.
പക്ഷേ, എന്റെ കയ്യിൽ റാക്കറ്റ് ഇല്ല.
"എനിക്ക് ഒരു റാക്കറ്റ് വാടകയ്ക്ക് എടുക്കാൻ കഴിയുമോ?" ഞാൻ ചോദിക്കുന്നു.
"അതെ, കഴിയും," അയാൾ മറുപടി പറയുന്നു.
"റാക്കറ്റിന്റെ വാടക അൻപത് രൂപയാണ്."
ഞാൻ അൻപത് രൂപ കൂടി കൊടുക്കുന്നു.
അയാൾ എനിക്ക് ഒരു നല്ല റാക്കറ്റ് തരുന്നു.
"നന്ദി," ഞാൻ അയാളോട് പറയുന്നു.
ഇപ്പോൾ ഞാൻ കളിക്കാൻ പോകുന്നു.
