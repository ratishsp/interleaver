എനിക്ക് ഇന്ന് ഒരു പാക്കേജ് എടുക്കേണ്ടതുണ്ട്.
അത് നഗരത്തിന്റെ മറുവശത്താണ്.
ഞാൻ എന്റെ ഫോണിൽ നോക്കുന്നു.
ഞാൻ ഒരു പബ്ലിക് ട്രാൻസ്പോർട്ട് ആപ്പ് തുറക്കുന്നു.
ഞാൻ എന്റെ റൂട്ട് പ്ലാൻ ചെയ്യുന്നു.
ആ റൂട്ട് നീളമുള്ളതാണ്.
അതിന് മൂന്ന് ഭാഗങ്ങളുണ്ട്.
ആദ്യം, എനിക്ക് ഒരു ബസ്സിൽ പോകണം.
ബസ്സ് മെട്രോയിലേക്കാണ് പോകുന്നത്.
പിന്നെ എനിക്ക് മെട്രോയിൽ യാത്ര ചെയ്യണം.
ഒടുവിൽ, എനിക്ക് തുറമുഖത്തേക്ക് പോകണം.
ഇവിടെ, എനിക്ക് ഹാർബർ ബസ്സിൽ പോകണം.
ഹാർബർ ബസ്സ് ഒരു വലിയ ബോട്ടാണ്.
അത് വെള്ളത്തിലൂടെയാണ് സഞ്ചരിക്കുന്നത്.
പാക്കേജ് ഒരു ചെറിയ കടയിലാണ്.
ആ കട വെള്ളത്തിന് സമീപമാണ്.
അതൊരു നല്ല പ്ലാനാണ്.
ഞാൻ എന്റെ നീല ട്രാവൽ കാർഡ് എടുക്കുന്നു.
ഞാൻ യാത്രയ്ക്ക് തയ്യാറാണ്.
