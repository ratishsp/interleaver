Jag står vid busshållplatsen med de gula blommorna.
Det är många människor som väntar.
Jag tittar på skärmen för att se tidtabellen.
Bussen ska vara här om fem minuter.
Jag tycker att fredagstrafiken ofta är mycket långsam.
Men gatorna ser helt tomma ut i dag.
Så jag tror att bussen nog kommer i tid.
En äldre man står bredvid mig.
Han tittar på sin klocka och suckar.
"Vet du om bussen är försenad?" frågar han mig.
Jag kollar min telefon igen.
"Nej, jag tror inte det," svarar jag.
"Jag ska också med samma buss."
"Jag tror att den faktiskt är precis runt hörnet."
Han ler mot mig och nickar.
Plötsligt ser vi den stora röda bussen nere på gatan.
Den kör snabbt mot oss.
"Du hade rätt," säger mannen lättad.
Vi stiger på bussen tillsammans.
Jag kommer helt säkert att vara hos Eva i tid.
Jag är spänd på att se hennes lägenhet.
