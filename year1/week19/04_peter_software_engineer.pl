Siadam przy biurku Petera.
Patrzymy na jego duży ekran.
Peter też jest inżynierem oprogramowania.
Jest dobrym kolegą i piszemy razem dużo kodu.
Dziś wygląda na bardzo zmęczonego.
"Co robisz, Peter?" – pytam.
"Mam duży problem" – odpowiada.
"Pracuję nad tym błędem od trzech godzin."
Uśmiecham się i patrzę uważnie na kod.
W naszej pracy często razem rozwiązujemy skomplikowane problemy.
Nagle widzę na ekranie coś dziwnego.
To bardzo mały błąd.
"Spójrz tutaj" – mówię i wskazuję na ekran.
"Zrobiłeś tu małą literówkę."
Peter przez dwie sekundy patrzy w milczeniu na ekran.
Potem głośno się śmieje.
"Masz całkowitą rację" – mówi Peter.
"Pracowałem przez trzy godziny, a to tylko jeden mały błąd!"
Ja też się śmieję, bo wszyscy inżynierowie oprogramowania znają tę sytuację.
Poprawiamy błąd i program wreszcie działa idealnie.
