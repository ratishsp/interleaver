Jag sätter mig på en stol i väntrummet.
Rummet är nästan helt tyst.
Jag väntar tålmodigt.
Mitt huvud är fortfarande mycket tungt.
En mamma och en liten pojke sitter mittemot mig.
Pojken är kanske fem år gammal.
Han håller en hand på sitt högra öra.
"Aj, mitt öra gör ont!" säger han högt.
Hans mamma tittar på honom.
"Jag vet, älskling," säger hon milt.
"Men det gör mycket ont!" klagar pojken.
"Läkaren borde snart ropa på oss," säger mamman.
Hon lägger en arm om hans axlar.
Pojken suckar högt.
Han ser mycket trött ut.
Jag förstår honom mycket väl.
Min egen hals gör också riktigt ont.
Jag vill bara må bra igen.
