ഇന്ന് ഞാൻ കാപ്പി ഉണ്ടാക്കാൻ പഠിക്കുകയാണ്.
ജെസ്സി എന്റെ അടുത്ത് നിൽക്കുന്നുണ്ട്.
ഞാൻ എന്റെ ഒന്നാമത്തെ കാപ്പി ഉണ്ടാക്കാൻ ശ്രമിക്കുന്നു.
ആദ്യം, ഞാൻ പാലിന്റെ ജഗ് എടുക്കുന്നു.
പക്ഷേ, എനിക്ക് അത് ശരിയായി പിടിക്കാൻ അറിയില്ല.
ഞാൻ അത് ഒരുപാട് ചരിക്കുന്നു.
സ്റ്റീം വേഗത്തിൽ പുറത്തേക്ക് വരുന്നു.
പാൽ പതപ്പിക്കാൻ ഞാൻ ബുദ്ധിമുട്ടുന്നു.
പാൽ ഒരുപാട് ചൂടായി.
അതിൽ പത തീരെ വന്നില്ല.
എന്റെ ഒന്നാമത്തെ കാപ്പി ഉണ്ടാക്കിയത് പൂർണ്ണമായും പാളിപ്പോയി!
ഞാൻ പരിഭ്രമത്തോടെ ചിരിക്കുന്നു.
"ക്ഷമിക്കണം ജെസ്സി, ഇത് ശരിയായില്ല," ഞാൻ പറയുന്നു.
ജെസ്സി എന്നെ നോക്കി ചിരിക്കുന്നു.
"കുഴപ്പമില്ല മായ," അവർ പറയുന്നു.
"എല്ലാവരുടെയും ഒന്നാമത്തെ കാപ്പി ഇങ്ങനെയാണ്."
