Przyjazny lekarz otwiera drzwi i wywołuje moje imię.
Wchodzę do jego jasnego gabinetu.
Siadamy przy jego biurku.
"Jak się dzisiaj czujesz?" - pyta.
"Czuję się naprawdę źle" - odpowiadam.
Lekarz patrzy na mnie.
"Gdzie boli?" - pyta życzliwie.
Wskazuję na swoje gardło.
"Bardzo boli mnie gardło" - wyjaśniam.
"Jest bardzo suche."
Lekarz kiwa głową i słucha uważnie.
"Moja głowa też jest bardzo ciężka" - kontynuuję.
Dotykam swojej twarzy.
"A moje oczy są całkowicie czerwone."
Swędzą cały czas.
"Zdecydowanie powinnaś odpocząć" - mówi.
Włącza małą latarkę.
"Pozwól, że przyjrzę ci się bliżej" - mówi.
