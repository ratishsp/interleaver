മഞ്ഞപ്പൂക്കളുമായി ഞാൻ ബസ് സ്റ്റോപ്പിൽ നിൽക്കുകയാണ്.
അവിടെ കാത്തുനിൽക്കുന്ന ധാരാളം ആളുകളുണ്ട്.
സമയവിവരപ്പട്ടിക കാണാനായി ഞാൻ സ്ക്രീനിലേക്ക് നോക്കുന്നു.
അഞ്ച് മിനിറ്റിനുള്ളിൽ ബസ് ഇവിടെ എത്തേണ്ടതാണ്.
വെള്ളിയാഴ്ചകളിലെ ട്രാഫിക് പലപ്പോഴും വളരെ സാവധാനത്തിലാണെന്ന് എനിക്ക് തോന്നുന്നു.
എന്നാൽ ഇന്ന് തെരുവുകൾ തികച്ചും ശൂന്യമായി കാണപ്പെടുന്നു.
അതിനാൽ ബസ് കൃത്യസമയത്ത് തന്നെ എത്തുമെന്ന് ഞാൻ കരുതുന്നു.
പ്രായമായ ഒരു മനുഷ്യൻ എന്റെ അടുത്തായി നിൽക്കുന്നുണ്ട്.
അദ്ദേഹം തന്റെ വാച്ചിൽ നോക്കി നെടുവീർപ്പിടുന്നു.
"ബസ് വൈകുമോ എന്ന് നിങ്ങൾക്കറിയാമോ?" അദ്ദേഹം എന്നോട് ചോദിക്കുന്നു.
ഞാൻ വീണ്ടും ഫോൺ പരിശോധിക്കുന്നു.
"ഇല്ല, അങ്ങനെ തോന്നുന്നില്ല," ഞാൻ മറുപടി നൽകുന്നു.
"ഞാനും അതേ ബസ്സിലാണ് പോകുന്നത്."
"അത് ശരിക്കും തൊട്ടടുത്ത് തന്നെ എത്തിയിട്ടുണ്ടെന്ന് ഞാൻ കരുതുന്നു."
അദ്ദേഹം എന്നെ നോക്കി പുഞ്ചിരിക്കുകയും തലയാട്ടുകയും ചെയ്യുന്നു.
പെട്ടെന്ന് ആ വലിയ ചുവന്ന ബസ് തെരുവിലൂടെ വരുന്നത് ഞങ്ങൾ കാണുന്നു.
അത് ഞങ്ങൾക്ക് നേരെ വേഗത്തിൽ വരുന്നു.
"നിങ്ങൾ പറഞ്ഞത് ശരിയായിരുന്നു," ആശ്വാസത്തോടെ ആ മനുഷ്യൻ പറയുന്നു.
ഞങ്ങൾ ഒരുമിച്ച് ബസ്സിൽ കയറുന്നു.
ഞാൻ എന്തായാലും കൃത്യസമയത്ത് ഈവയുടെ വീട്ടിൽ എത്തും.
അവളുടെ അപ്പാർട്ട്മെന്റ് കാണാൻ എനിക്ക് അതിയായ ആവേശമുണ്ട്.
