Pociąg jechał szybko przez krajobraz.
Siedziałam spokojnie na swoim miejscu.
Miałam naprawdę dobre miejsce przy oknie.
Po krótkim czasie w końcu dotarliśmy do wybrzeża.
Pociąg wjechał na bardzo długi most nad morzem.
Nagle dookoła nas była tylko woda.
Most znajdował się wysoko nad wodą.
Wyjrzałam przez duże okno.
Woda pod nami była bardzo niebieska.
Podziwiałam piękny, rozległy widok.
Daleko w dole zobaczyłam kilka małych statków.
Wyglądały prawie jak zabawki.
Niebo było jasnoniebieskie i całkowicie bez chmur.
To było prawie jak lot nad morzem.
Wyjęłam aparat z torby.
Zrobiłam parę zdjęć małym statkom.
Nigdy nie widziałam czegoś podobnego.
Potem schowałam aparat i po prostu cieszyłam się podróżą.
