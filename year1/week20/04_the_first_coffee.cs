Dnes dopoledne jsme měli neuvěřitelně napilno.
Zrovna jsem udělala své úplně první cappuccino.
Chvíli před desátou přišel k pultu nějaký muž.
„Jedno cappuccino, prosím,“ řekl.
Právě jsem se naučila používat kávovar na espresso.
Takže jsem šla hned k přístroji.
Uvařila jsem kávu a ponořila parní trysku do mléka.
Ale držela jsem ji trochu moc hluboko.
Asi jsem byla trochu moc nervózní.
Na mléce se bohužel neudělala žádná hustá pěna.
Opatrně jsem se podívala dolů do konvičky.
Pěna nebyla úplně dokonalá.
Ale pořád to vypadalo přijatelně.
Nalila jsem horké mléko na kávu v šálku.
Pak jsem kávu se zdvořilým úsměvem podala tomu muži.
„Tady máte, bude to padesát pět korun,“ řekla jsem.
Vzal si šálek a posadil se k prvnímu stolu.
