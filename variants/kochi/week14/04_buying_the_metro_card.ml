അവിടെ കൗണ്ടറിൽ ഒരു ഉദ്യോഗസ്ഥൻ ഉണ്ട്.
ഞാൻ അയാളോട് സംസാരിക്കുന്നു.
"നമസ്കാരം, എനിക്ക് ഫോർട്ട് കൊച്ചിയിലേക്ക് പോകണം," ഞാൻ പറയുന്നു.
"എനിക്ക് ഒരു പുതിയ കാർഡ് വേണം."
"മെട്രോയ്ക്കും വാട്ടർ മെട്രോയ്ക്കും ഒരേ കാർഡ് ഉപയോഗിക്കാമോ?"
അയാൾ പറയുന്നു, "അതെ, ഉപയോഗിക്കാം."
"നിങ്ങളുടെ ഐഡി കാർഡ് തരൂ."
ഞാൻ എൻ്റെ ഐഡി കാർഡ് അയാൾക്ക് കാണിക്കുന്നു.
അതിൽ എൻ്റെ വിവരങ്ങൾ ഉണ്ട്.
അയാൾ കാർഡ് നോക്കുന്നു.
അയാൾ പറയുന്നു, "പുതിയ കാർഡിന് ഇരുന്നൂറ് രൂപയാണ്."
ഞാൻ ഇരുന്നൂറ് രൂപ അയാൾക്ക് കൊടുക്കുന്നു.
അയാൾ ഒരു പുതിയ കാർഡ് എനിക്ക് തരുന്നു.
"നന്ദി," ഞാൻ പറയുന്നു.
"ഞാൻ എവിടെ ട്രെയിനിൽ കയറണം?"
അയാൾ പറയുന്നു, "അവിടെ മുകളിൽ പോയി ട്രെയിനിൽ കയറുക."
ഞാൻ പുതിയ കാർഡ് എടുക്കുന്നു.
ഞാൻ ഗേറ്റിലേക്ക് നടക്കുന്നു.
