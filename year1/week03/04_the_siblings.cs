Teď jsou na mé obrazovce dvě nové tváře.
Je to moje mladší sestra Sofía a můj starší bratr Diego.
Smějí se a trochu do sebe strkají.
„Ahoj sestřičko a bráško!“ říkám vesele.
„Ahoj Mayo,“ říká Diego.
Můj bratr má velký úsměv.
„Je v Dánsku zima?“ ptá se.
„Je to studená zima?“
„Ano, je to velmi studená zima,“ směju se.
„Ale mám teplý pokoj a šálek čaje.“
Teď Sofía zvedá před obrazovku velkou věc.
Je to velká kniha.
„Máš tam novou knihu, Sofío?“ ptám se.
„Ano, to je moje nová kniha,“ říká moje sestra hrdě.
„Je to kniha z mé univerzity.“
„Je to velmi tlustá kniha!“
Usmívám se na svého bratra a svou sestru.
Chybí mi moje rodina v Mexiku.
Ale jsou přímo tady na mé malé obrazovce.
