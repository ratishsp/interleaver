ഞായറാഴ്ച ഉച്ചകഴിഞ്ഞ് ഞാൻ ടോമിയെ കുറെ ദൂരം നടക്കാനായി കൊണ്ടുപോകുന്നു.
എന്റെ കയ്യിൽ അവന്റെ ചെറിയ റബ്ബർ പന്തും ഉണ്ട്.
ഞങ്ങൾ ശാന്തമായ ഒരു പുൽമൈതാനത്ത് എത്തുന്നു.
ഞാൻ പന്ത് കുറച്ചകലെ എറിയുന്നു.
ഞാൻ അവനോട് പറയുന്നു: "ടോമി, പോയി പന്ത് പിടിക്കൂ!"
അവൻ വലിയ സന്തോഷത്തോടെ ഓടി പന്ത് പിടിക്കുന്നു.
ഞാൻ വിളിച്ചുപറയുന്നു: "ഇനി അത് ഇങ്ങോട്ട് കൊണ്ടുവരൂ!"
ടോമി എന്റെ അടുത്തേക്ക് ഓടി വരുന്നു, ഞാൻ അവനെ തലോടുന്നു.
ഈ കളി അവന് വളരെ ഇഷ്ടമാണ്.
വഴിയിൽ മുന്നിലായി വലിയ ഒരു ചെളിക്കുഴി ഉണ്ട്.
അവൻ പതുക്കെ അതിന്റെ അടുത്തേക്ക് നടക്കുന്നു.
അവൻ ആ വെള്ളത്തിൽ ഇറങ്ങാൻ പാടില്ല.
ഞാൻ ഉറക്കെ വിളിക്കുന്നു: "ടോമി, നിൽക്കൂ!"
"അങ്ങോട്ട് പോകരുത്, പെട്ടെന്ന് ഇങ്ങോട്ട് വരൂ!"
ടോമി നിന്നിട്ട് എന്നെ നോക്കുന്നു.
ഞാൻ കർശനമായി പറയുന്നു: "നീ ആ വെള്ളത്തിൽ ഇറങ്ങാൻ പാടില്ല."
"നീ എന്റെ കൂടെ നിൽക്കുക തന്നെ വേണം."
അവൻ ചെളിയിൽ പോകാതെ എന്റെ അടുത്തേക്ക് തിരികെ വരുന്നു.
ഞാൻ അവനെ വീണ്ടും തലോടുന്നു, എന്നിട്ട് ഞങ്ങൾ നടത്തം തുടരുന്നു.
