ഞങ്ങൾ ഊണുമേശയ്ക്ക് ചുറ്റും ഇരിക്കുന്നു.
ദീപ ചൂടുള്ള അപ്പവും വെജിറ്റബിൾ സ്റ്റ്യൂവും കൊണ്ടുവരുന്നു.
ആ കറിക്ക് നല്ല മണമുണ്ട്.
"മായ, കഴിക്കൂ."
"ഞാൻ വിളമ്പാം," ദീപ പറയുന്നു.
അവർ എന്റെ പ്ലേറ്റിൽ അപ്പവും സ്റ്റ്യൂവും വിളമ്പുന്നു.
"നിനക്ക് ഇത് ഇഷ്ടമാകും എന്ന് ഞാൻ കരുതുന്നു," അവർ പറയുന്നു.
ഞാൻ വളരെ താല്പര്യത്തോടെ ഭക്ഷണം രുചിച്ചു നോക്കുന്നു.
അപ്പം വളരെ മൃദുവാണ്.
സ്റ്റ്യൂവും വളരെ രുചികരമാണ്.
"ദീപ, ഇത് ഗംഭീരമാണ്!" ഞാൻ പറയുന്നു.
"കൊച്ചിയിൽ വന്നതിന് ശേഷം ഞാൻ കഴിച്ച ഏറ്റവും നല്ല സ്റ്റ്യൂ ഇതാണ് എന്ന് ഞാൻ കരുതുന്നു!"
ദീപ സന്തോഷത്തോടെ ചിരിക്കുന്നു.
"നിനക്ക് ഇഷ്ടമായി എന്ന് അറിയുന്നതിൽ എനിക്ക് സന്തോഷമുണ്ട്," ദീപ പറയുന്നു.
"ഞാൻ നിനക്കായി ഇത് വീണ്ടും ഉണ്ടാക്കാം."
"ഞാൻ തീർച്ചയായും വീണ്ടും വരും!" ഞാൻ ചിരിച്ചുകൊണ്ട് പറയുന്നു.
ഞങ്ങൾ സംസാരിച്ചുകൊണ്ട് ഭക്ഷണം കഴിക്കുന്നു.
ഇതൊരു മികച്ച അത്താഴമാണ്.
