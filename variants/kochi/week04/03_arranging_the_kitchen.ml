ഞാൻ അടുക്കളയിലേക്ക് പോകുന്നു.
ഒരു ചെറിയ പെട്ടി താഴെ ഇരിക്കുന്നു.
ഞാൻ ആ പെട്ടി തുറക്കുന്നു.
പെട്ടിയിൽ പാത്രങ്ങളും ഭക്ഷണസാധനങ്ങളും ഉണ്ട്.
ഞാൻ പാത്രങ്ങൾ എടുക്കുന്നു.
ഞാൻ പാത്രങ്ങൾ അലമാരയിൽ വെക്കുന്നു.
ഇപ്പോൾ പാത്രങ്ങൾ അലമാരയിൽ ഇരിക്കുന്നു.
പെട്ടിയിൽ വലിയ ഭരണികൾ ഉണ്ട്.
ഈ ഭരണികൾക്ക് വലിയ ഭാരമുണ്ട്.
ഞാൻ ഭരണികൾ കൗണ്ടറിന് അടിയിൽ വെക്കുന്നു.
അവ കൗണ്ടറിന് അടിയിൽ ഇരിക്കുന്നു.
ഞാൻ എന്റെ ടീ ടിൻ എടുക്കുന്നു.
അത് എന്റെ പ്രിയപ്പെട്ട ചായയാണ്.
ഞാൻ ടീ ടിൻ ഷെൽഫിന് മുകളിൽ വെക്കുന്നു.
ഇപ്പോൾ ടീ ടിൻ ഷെൽഫിന് മുകളിൽ ഇരിക്കുന്നു.
എല്ലാ രാവിലെയും ഞാൻ അത് അവിടെ കാണുന്നു.
എന്റെ പുതിയ അടുക്കള ഇപ്പോൾ റെഡിയാണ്.
