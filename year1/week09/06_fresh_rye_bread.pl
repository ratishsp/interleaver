Przechodzę obok małego stoiska.
Pachnie świeżym chlebem.
Podchodzę do stoiska.
Piekarz stoi za dużym stołem.
Stół jest pełen wypieków.
Widzę ciemny chleb żytni.
Wygląda na bardzo świeży.
Wskazuję na chleb żytni.
„Ile kosztuje ciemny chleb żytni?” – pytam.
Piekarz wyciera ręce.
„Kosztuje trzydzieści pięć koron” – odpowiada.
„Kupuję go” – mówię.
Wyciągam kartę płatniczą.
Płacę kartą.
Piekarz podaje mi chleb w papierowej torbie.
Dotykam torby.
Chleb jest jeszcze ciepły.
Nie mogę się doczekać, żeby go zjeść.
