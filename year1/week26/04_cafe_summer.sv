Det är lördag förmiddag, och jag är klar på kaféet.
Jag har precis torkat av det sista bordet.
Jag knyter upp mitt förkläde och lägger det på en stol.
Idag har jag haft ett kort pass.
Förra veckan jobbade jag till klockan tre.
Den dagen hade vi mycket att göra hela dagen.
Men idag har vi bara haft några få gäster.
Solen skiner ute, och det är en vacker sommardag.
I kväll är det en stor brasa nere vid havet.
Jag ser verkligen fram emot att se den.
Jag tar min telefon och skriver ett meddelande till Eva.
Jag frågar henne: "Ska vi fortfarande ses i kväll?"
Jag skriver också att jag redan har slutat.
"Jag slutade tidigt i dag, så jag är redo," skriver jag.
Eva svarar nästan direkt.
"Ja, självklart!" svarar hon.
"Jag har precis köpt färska jordgubbar."
"Vi ses vid stranden senare," skriver hon.
Jag ler och tar min väska.
Sedan går jag ut i det varma sommarvädret.
