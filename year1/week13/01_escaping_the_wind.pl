Jest zima w Kopenhadze.
Idę ulicą.
Wiatr jest bardzo zimny.
Dzisiaj mocno wieje.
Pochylam się pod naporem zimnego wiatru.
Podciągam szalik wyżej.
Marznie mi twarz.
Rozglądam się.
Chciałabym wejść do ciepła.
Widzę małą kawiarnię na rogu.
Okna są zaparowane.
Wygląda na to, że w środku jest ciepło.
Podchodzę do kawiarni.
Otwieram ciężkie drzwi.
Wchodzę do środka.
Pachnie tu kawą.
Powietrze jest przyjemnie ciepłe.
Zamykam za sobą drzwi.
Zimny wiatr zostaje na zewnątrz.
