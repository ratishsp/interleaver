ഞാൻ ഫ്ലാറ്റിലാണ്.
ഞാൻ എന്റെ കലണ്ടർ നോക്കുന്നു.
ഞാൻ കലണ്ടറിൽ അനിതയുടെ പേര് എഴുതുന്നു.
വ്യാഴാഴ്ച വൈകുന്നേരം അഞ്ചരയ്ക്കാണ് കാപ്പി.
അപ്പോൾ ഞാൻ ഒരു പ്രശ്നം കാണുന്നു.
വ്യാഴാഴ്ച വൈകുന്നേരം അഞ്ചരയ്ക്ക് എനിക്ക് ഹെയർകട്ട് ഉണ്ട്!
ഞാൻ വേഗം എന്റെ ഫോൺ എടുക്കുന്നു.
ഞാൻ വീണ്ടും ബ്യൂട്ടി പാർലറിലേക്ക് വിളിക്കുന്നു.
പാർലറിലെ സ്ത്രീ ഫോൺ എടുക്കുന്നു.
"ഹലോ," അവർ പറയുന്നു.
"ക്ഷമിക്കണം, വ്യാഴാഴ്ച എനിക്ക് മറ്റൊരു കാര്യമുണ്ട്," ഞാൻ പറയുന്നു.
"എനിക്ക് വെള്ളിയാഴ്ച വരാമോ?" ഞാൻ ചോദിക്കുന്നു.
"വരാം, വെള്ളിയാഴ്ച എത്ര മണിക്ക് വരും?" അവർ ചോദിക്കുന്നു.
"വൈകുന്നേരം ആറേ മുക്കാലിന് വരാമോ?" ഞാൻ ചോദിക്കുന്നു.
"ശരി, വെള്ളിയാഴ്ച വൈകുന്നേരം ആറേ മുക്കാലിന് വരിക," അവർ പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
ഞാൻ കലണ്ടറിൽ പുതിയ സമയം എഴുതുന്നു.
ഇപ്പോൾ എല്ലാ ദിവസവും എനിക്ക് ഓരോ പരിപാടിയുണ്ട്.
അതിനാൽ ഞാൻ എപ്പോഴും എന്റെ കലണ്ടർ നോക്കുന്നു.
