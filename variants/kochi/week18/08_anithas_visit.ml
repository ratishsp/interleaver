ഞാൻ ക്ലിനിക്കിൽ നിന്ന് അപ്പാർട്ട്മെന്റിൽ തിരിച്ചെത്തുന്നു.
എനിക്ക് നല്ല ക്ഷീണം ഉണ്ട്.
ഞാൻ പതുക്കെ ഇടനാഴിയിലൂടെ നടക്കുന്നു.
അപ്പോൾ എന്റെ അയൽക്കാരി അനിത അവരുടെ വാതിൽ തുറക്കുന്നു.
അവർ എന്റെ മുഖത്തേക്ക് നോക്കുന്നു.
"മായ, നിനക്ക് സുഖമില്ലേ?" അനിത ചോദിക്കുന്നു.
"അതെ, എനിക്ക് തീരെ വയ്യ," ഞാൻ പറയുന്നു.
"എനിക്ക് നല്ല പനിയും ജലദോഷവും ഉണ്ട്."
"എന്റെ തലയും തൊണ്ടയും വേദനിക്കുന്നു."
അനിതക്ക് വിഷമം തോന്നുന്നു.
"നീ ഇപ്പോൾ റൂമിൽ പോയി കിടക്കണം," അവർ പറയുന്നു.
"നീ നന്നായി വിശ്രമിക്കണം."
ഞാൻ തലയാട്ടുന്നു.
"ഉച്ചയ്ക്ക് ഞാൻ നിനക്ക് കുറച്ചു ചൂട് കഞ്ഞി കൊണ്ടുവരാം," അനിത പറയുന്നു.
എനിക്ക് വലിയ ആശ്വാസം തോന്നുന്നു.
"വളരെ നന്ദി, അനിത," ഞാൻ പറയുന്നു.
ഞാൻ എന്റെ ഫ്ലാറ്റിന്റെ വാതിൽ തുറക്കുന്നു.
ഞാൻ വേഗം കിടപ്പുമുറിയിലേക്ക് പോകുന്നു.
