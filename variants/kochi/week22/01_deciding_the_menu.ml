ഇന്ന് ഞായറാഴ്ച രാവിലെയാണ്.
ഞാൻ ഇന്ന് നേരത്തെ എഴുന്നേൽക്കുന്നു.
ഇന്ന് ഉച്ചഭക്ഷണത്തിന് എന്റെ വീട്ടിൽ അതിഥികൾ വരുന്നുണ്ട്.
കിരണും സാറയുമാണ് വരുന്നത്.
കഴിഞ്ഞ വ്യാഴാഴ്ച ബാഡ്മിന്റൺ കഴിഞ്ഞതിന് ശേഷം ഞാൻ അവരെ ക്ഷണിച്ചതാണ്.
എനിക്ക് അവർക്ക് നല്ലൊരു ഭക്ഷണം കൊടുക്കണം.
ഞാൻ എന്താണ് ഉണ്ടാക്കേണ്ടത്?
ഞാൻ എന്റെ ഫോൺ എടുത്ത് ഇന്റർനെറ്റിൽ തിരയുന്നു.
ആദ്യം, ഞാൻ ഒരു ചിക്കൻ കറിയുടെ റെസിപ്പി നോക്കുന്നു.
ഇന്റർനെറ്റിൽ ഒരുപാട് റെസിപ്പികൾ ഉണ്ട്.
ഞാൻ വളരെ എളുപ്പമുള്ള ഒരു റെസിപ്പി കണ്ടുപിടിക്കുന്നു.
പിന്നെ, ഞാൻ അത് ഉണ്ടാക്കാനുള്ള വഴികൾ വായിക്കുന്നു.
ഇതൊരു തനി നാടൻ കേരള ചിക്കൻ കറിയാണ്.
ചോറിന്റെ കൂടെ ഈ കറി ഉണ്ടാക്കാൻ ഞാൻ തീരുമാനിക്കുന്നു.
നല്ലൊരു ഉച്ചഭക്ഷണം ആയിരിക്കും ഇത്.
അതിനുശേഷം, എനിക്ക് ആവശ്യമായ സാധനങ്ങൾ എന്തെല്ലാമാണെന്ന് നോക്കണം.
