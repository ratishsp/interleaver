Det är nästa dag på kontoret.
Jag sitter bredvid Mads, vår mjukvarutestare.
Han tittar på de nya skärmarna.
Han klickar väldigt snabbt med musen.
Plötsligt stannar han upp.
Han har redan hittat ett litet fel.
Han tittar på mig och skrattar lite.
"Mitt jobb är att förstöra saker", säger han.
"Jag måste hitta felen före våra användare."
Han har arbetat som testare i fem år.
Han har testat många olika projekt.
Det är därför han hittar problemen så snabbt.
Jag tittar på felet på min dator.
Det är lyckligtvis bara ett litet problem.
Jag fixar koden direkt.
Han testar programmet en gång till.
Nu fungerar allt helt perfekt.
Jag är mycket glad för hans hjälp.
