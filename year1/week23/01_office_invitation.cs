Sedím u svého stolu v kanceláři ve středu ráno.
Eva přichází k mému stolu s šálkem kávy.
„Ahoj Mayo, máš v pátek čas?“ ptá se se širokým úsměvem.
Myslím, že mám vlastně volný večer.
„Ano, mám spoustu času,“ odpovídám jí.
„Moc ráda bych tě pozvala k sobě domů na večeři,“ říká.
Z toho pozvání mám velkou radost.
„Děkuji, moc ráda přijdu,“ říkám.
„Mám v plánu připravit vegetariánské jídlo,“ vysvětluje Eva.
„To zní naprosto perfektně,“ usmívám se.
„V kolik hodin tam mám být?“ ptám se.
„Můžeš přijít klidně v šest,“ odpovídá.
Myslím si, že je vždycky příjemné navštívit nové přátele.
„Určitě tam budu,“ potvrzuji.
Eva píše svou adresu na malý žlutý papírek.
Podává mi ten papírek.
„Budu se na pátek moc těšit,“ říkám jí.
Eva se znovu usměje a jde zpátky ke svému počítači.
