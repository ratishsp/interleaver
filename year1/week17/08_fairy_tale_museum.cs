Potom jsem šla do velkého městského muzea.
Bylo o slavném spisovateli Hansi Christianu Andersenovi.
Koupila jsem si vstupenku a vešla do té krásné budovy.
Výstava vyprávěla o jeho životě a jeho dlouhých cestách.
Prohlížela jsem si jeho staré věci ve velké skleněné vitríně.
Svůj cylindr si bral všude s sebou.
Ten vysoký černý klobouk teď ležel přímo přede mnou.
Ležel tam také jeho papír a jeho staré pero.
Používal je, když psal své fantastické pohádky.
Přečetla jsem si dlouhý text na bílé zdi.
Byl o muži, který stál za mou oblíbenou pohádkou.
Byl to totiž on, kdo stvořil malou mořskou vílu.
Setkala jsem se s ní jako se sochou v Kodani už v únoru.
Bylo zábavné vidět teď autorovy vlastní věci.
Pořídila jsem pár fotek jeho velké cestovní tašky.
Očividně velmi rád navštěvoval nové země.
Nakonec jsem si v muzejním obchodě koupila malou knížku.
Obsahovala všechny jeho nejlepší příběhy.
Teď mám pocit, že dánskou kulturu znám o něco lépe.
