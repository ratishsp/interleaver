ഞാൻ എന്റെ പഴയ മുറിയിലേക്ക് പോകുന്നു.
എന്റെ സാധനങ്ങൾ അവിടെ ഉണ്ട്.
പുതിയ ഫ്ലാറ്റ് വളരെ അടുത്ത് ആണ്.
ഞാൻ ആദ്യം രണ്ട് ചെറിയ ബാഗുകൾ എടുക്കുന്നു.
ഞാൻ പുതിയ ഫ്ലാറ്റിലേക്ക് നടക്കുന്നു.
ഞാൻ അവ സ്വീകരണമുറിയിൽ വെക്കുന്നു.
അവ ഇപ്പോൾ താഴെ ഉണ്ട്.
ബാഗുകൾ സോഫയുടെ അടുത്ത് കിടക്കുന്നു.
ഞാൻ വീണ്ടും പഴയ മുറിയിലേക്ക് പോകുന്നു.
അവിടെ വലിയ ഒരു സ്യൂട്ട്കേസ് ഉണ്ട്.
അതിന് നല്ല ഭാരം ഉണ്ട്.
ഞാൻ സ്യൂട്ട്കേസ് പതുക്കെ പുതിയ ഫ്ലാറ്റിലേക്ക് വലിക്കുന്നു.
ഞാൻ അത് കിടപ്പുമുറിയിൽ വെക്കുന്നു.
വലിയ സ്യൂട്ട്കേസ് കട്ടിലിന്റെ അടുത്ത് ഇരിക്കുന്നു.
എന്റെ എല്ലാ സാധനങ്ങളും ഇപ്പോൾ പുതിയ ഫ്ലാറ്റിൽ ഉണ്ട്.
