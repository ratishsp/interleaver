Jag ställer lådan på golvet och tackar henne igen.
"Det var så lite", svarar Nina.
Jag berättar för henne att portalen var lite långsam i kväll.
"Ja, den brukar vara väldigt långsam", skrattar Nina.
Hon frågar om min bekräftelse har sparats.
"Kom alltid ihåg att ladda ner din bekräftelse", råder hon.
Jag frågar henne varför det är viktigt.
Nina förklarar att gamla meddelanden ofta raderas på deras hemsida.
Systemet raderar dem nämligen automatiskt efter en kort tid.
Jag nickar och öppnar portalen på min telefon igen.
Jag hittar filen, och den laddas genast ner.
"Då är dokumentet säkert sparat", säger jag lättad.
Nina ler glatt och önskar mig en trevlig kväll.
Jag önskar henne detsamma.
Hon går nerför korridoren, och jag stänger min dörr.
Det är verkligen härligt att ha en klok och hjälpsam granne.
