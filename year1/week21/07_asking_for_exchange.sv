Jag lägger skjortan och kvittot på disken.
Expediten är redo att hjälpa mig.
"Hej, jag köpte den här skjortan i lördags," säger jag.
"Men den är tyvärr för liten."
"Kan jag byta den till en större storlek?"
"Ja, självklart kan du det," svarar expediten.
"Vilken storlek behöver du?"
"Jag behöver en large istället för en medium," förklarar jag.
"Ett ögonblick," säger expediten.
Hon går bort till hyllorna med de blå skjortorna.
Hon hittar snabbt rätt storlek och kommer tillbaka.
"Här är en large," säger hon med ett leende.
"Vill du prova den först?"
"Ja tack," svarar jag glatt.
"Provhytterna är precis där borta till höger," berättar hon.
"Tack så mycket för hjälpen," säger jag och tar den nya skjortan.
Nu kan jag se om den större skjortan är bättre.
