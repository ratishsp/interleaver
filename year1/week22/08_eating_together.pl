Siadamy przy moim małym stole.
Jest trochę ciasno, ale siedzimy blisko i wygodnie.
Najpierw stawiam na stole miski z jedzeniem.
Następnie Kasper i Sara biorą dużą porcję.
Próbują klopsików i ziemniaków.
„To smakuje naprawdę wyśmienicie, Maya!” – mówi Sara.
„Tak, są naprawdę dobre” – mówi Kasper.
Szybko bierze kolejny kęs.
Kasper otwiera też zimne piwa.
Potem nalewa je do naszych szklanek.
„Na zdrowie!” – mówimy we troje i pijemy.
Kasper bierze więcej klopsików z półmiska.
Sara też bierze dodatkową porcję ziemniaków.
„Bardzo się cieszę, że wam smakuje” – mówię.
„Dla wszystkich wystarczy” – uśmiecham się.
Chwalą autentyczny smak.
Rozmawiamy i śmiejemy się przy stole.
Jemy i rozmawiamy przez długi czas.
