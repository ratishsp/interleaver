ഞാൻ ഇൻഫോപാർക്കിലെ ഓഫീസിലാണ്.
ഓഫീസിൽ എസിയുടെ നല്ല തണുപ്പുണ്ട്.
ഞാൻ എന്റെ ഡെസ്കിൽ ഇരിക്കുന്നു.
ഞാൻ കമ്പ്യൂട്ടറിൽ പുതിയ സോഫ്റ്റ്‌വെയർ ടൈപ്പ് ചെയ്യുന്നു.
അപ്പോൾ പ്രകാശ് എന്റെ അടുത്തേക്ക് വരുന്നു.
അദ്ദേഹം എന്റെ സഹപ്രവർത്തകനാണ്.
പ്രകാശ് എന്റെ ഡെസ്കിന്റെ അരികിൽ നിൽക്കുന്നു.
ഞങ്ങൾ ഒരുമിച്ച് കമ്പ്യൂട്ടർ സ്ക്രീനിൽ നോക്കുന്നു.
"മായ, ഇത് പുതിയ പ്രോജക്റ്റിന് വേണ്ടിയാണോ?" പ്രകാശ് ചോദിക്കുന്നു.
"അതെ, ഞാൻ എന്റെ ഭാഗം തയ്യാറാക്കുകയാണ്," ഞാൻ പറയുന്നു.
അദ്ദേഹം സ്ക്രീനിൽ വിരൽ ചൂണ്ടുന്നു.
"ഈ ഭാഗം വളരെ നല്ലതാണ്," അദ്ദേഹം പറയുന്നു.
"നന്ദി പ്രകാശ്," ഞാൻ പറയുന്നു.
ഞങ്ങൾ വരാനിരിക്കുന്ന പ്രോജക്റ്റിനെക്കുറിച്ച് സംസാരിക്കുന്നു.
പ്രകാശ് ചില പുതിയ കാര്യങ്ങൾ പറയുന്നു.
അദ്ദേഹം എന്നെ ഒരുപാട് സഹായിക്കുന്നു.
ഞാൻ വീണ്ടും കമ്പ്യൂട്ടറിൽ ടൈപ്പ് ചെയ്യുന്നു.
ഇന്ന് ഒരുപാട് ജോലിയുണ്ട്.
