ശനിയാഴ്ച രാവിലെയാണ്, ഞാൻ ഇവിടുത്തെ ലോക്കൽ കഫേയിലാണ്.
എല്ലാ വാരാന്ത്യത്തിലും ഞാൻ ഇവിടെ വോളന്റിയറായി ജോലി ചെയ്യാറുണ്ട്.
കഫേ ഇപ്പോൾത്തന്നെ ആളുകളെക്കൊണ്ട് നിറഞ്ഞിരിക്കുകയാണ്.
ഞാൻ മരം കൊണ്ടുള്ള വലിയ കൗണ്ടറിന് പിന്നിൽ നിൽക്കുന്നു.
വൃത്തിയുള്ള ഒരു തുണികൊണ്ട് ഞാൻ ആ കൗണ്ടർ തുടച്ചു വൃത്തിയാക്കുന്നു.
ഒരു ചെറുപ്പക്കാരൻ കൗണ്ടറിന് അടുത്തേക്ക് നടന്നു വരുന്നു.
"ഗുഡ് മോർണിംഗ്, എനിക്കൊരു ലാർജ് കോഫി വേണം," അയാൾ പറയുന്നു.
"പിന്നെ ചൂടുള്ള രണ്ട് പേസ്ട്രികളും വേണം," അയാൾ കൂട്ടിച്ചേർക്കുന്നു.
"തീർച്ചയായും, ഉടനെ തരാം," ഒരു പുഞ്ചിരിയോടെ ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ ആ വലിയ എസ്പ്രസ്സോ മെഷീന്റെ അടുത്തേക്ക് നടക്കുന്നു.
എനിക്കിപ്പോൾ ഈ മെഷീൻ നന്നായി ഉപയോഗിക്കാൻ അറിയാം.
ഞാൻ പെട്ടെന്നുതന്നെ ആവി പറക്കുന്ന ഒരു കപ്പ് ചൂട് കോഫി ഉണ്ടാക്കുന്നു.
ഫ്രഷ് കോഫിയുടെ മണം ആ ചെറിയ മുറിയിലാകെ നിറയുന്നു.
അതിനുശേഷം, ഞാൻ ചൂടുള്ള രണ്ട് പേസ്ട്രികൾ ഒരു പേപ്പർ ബാഗിലാക്കുന്നു.
ഞാൻ കൗണ്ടറിന് മുകളിലൂടെ കോഫിയും ബാഗും അയാൾക്ക് നേരെ നീട്ടുന്നു.
"അമ്പത്തഞ്ച് ക്രോണർ ആയി," ഞാൻ പറയുന്നു.
അയാൾ കാർഡ് ഉപയോഗിച്ച് പണം നൽകുകയും കോഫി വാങ്ങുകയും ചെയ്യുന്നു.
"നല്ലൊരു വാരാന്ത്യം ആശംസിക്കുന്നു," അയാൾ സന്തോഷത്തോടെ പറയുന്നു.
"നന്ദി, നിങ്ങൾക്കും അങ്ങനെത്തന്നെയാവട്ടെ," ഞാൻ മറുപടി നൽകുന്നു.
വരിയിൽ നിൽക്കുന്ന അടുത്ത ഉപഭോക്താവിനോട് മുന്നോട്ട് വരാൻ ഞാൻ കൈകാണിക്കുന്നു.
