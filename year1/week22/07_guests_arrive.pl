Dzwoni dzwonek do drzwi.
Otwieram drzwi z uśmiechem.
Kasper i Sara stoją na zewnątrz.
Uśmiechają się i machają do mnie.
„Cześć Maya i bardzo dziękujemy za zaproszenie!” – mówi radośnie Kasper.
„Cześć!”
„Wejdźcie do środka” – odpowiadam.
„Już pachnie niesamowicie” – mówi Sara.
„Najpierw zdejmijcie kurtki” – mówię do nich.
Biorę ich kurtki i wieszam je w przedpokoju.
Następnie Sara daje mi torbę.
„Przynieśliśmy kilka zimnych piw” – wyjaśnia.
„To lokalne duńskie piwo” – dodaje Kasper.
Zaglądam do torby.
W środku jest sześć butelek.
„Bardzo dziękuję, to po prostu idealnie” – mówię.
„Zaraz włożę je do lodówki”.
„Dobry pomysł, a potem będziemy gotowi do jedzenia” – śmieje się Kasper.
Idę do kuchni z butelkami.
