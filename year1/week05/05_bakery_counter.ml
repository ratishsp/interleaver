ഞാൻ ബേക്കറി കൗണ്ടറിനടുത്തേക്ക് നടക്കുന്നു.
മണം വളരെ നല്ലതാണ്.
എനിക്ക് കേക്കുകൾ ഇഷ്ടമാണ്.
കൂടാതെ എനിക്ക് കറുവാപ്പട്ട പേസ്ട്രികൾ വളരെ ഇഷ്ടമാണ്.
ഒരു ബേക്കർ കൗണ്ടറിന് പിന്നിൽ നിൽക്കുന്നു.
ബേക്കർ എന്നെ നോക്കുന്നു.
അദ്ദേഹം ചിരിക്കുന്നു.
"നിങ്ങൾക്ക് എന്താണ് വേണ്ടത്?" ബേക്കർ ചോദിക്കുന്നു.
ഞാൻ ഒരു കറുവാപ്പട്ട പേസ്ട്രി ചൂണ്ടിക്കാണിക്കുന്നു.
പേസ്ട്രി കാണാൻ നല്ല രുചിയുള്ളതായി തോന്നുന്നു.
"ദയവായി, എനിക്ക് ഒരു കറുവാപ്പട്ട പേസ്ട്രി വേണം," ഞാൻ പറയുന്നു.
"അതെ, തീർച്ചയായും," ബേക്കർ പറയുന്നു.
അദ്ദേഹം ആ പേസ്ട്രി എടുക്കുന്നു.
അദ്ദേഹം പേസ്ട്രി ഒരു ബാഗിൽ ഇടുന്നു.
അദ്ദേഹം ആ ബാഗ് കൗണ്ടറിന് മുകളിലൂടെ കൈമാറുന്നു.
"ഇതാ," അദ്ദേഹം പറയുന്നു.
ഞാൻ ആ ബാഗ് എടുക്കുന്നു.
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
ഞാൻ ആ ബാഗ് കൂടയിൽ വെക്കുന്നു.
