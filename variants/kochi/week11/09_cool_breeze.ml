ഞാൻ ജനലിനടുത്ത് നിൽക്കുന്നു.
ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
കാലാവസ്ഥ വളരെ മനോഹരമാണ്.
എനിക്ക് വളരെ സന്തോഷമുണ്ട്.
