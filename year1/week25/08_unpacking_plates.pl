Jestem z powrotem w moim mieszkaniu.
Jest niedzielny wieczór i jest tu bardzo cicho.
Stoję w kuchni.
Myję moje nowe talerze w zlewie.
Te talerze są naprawdę piękne.
Są niebieskie i trochę ciężkie.
Wycieram je ściereczką do naczyń.
Potem wstawiam je do szafki.
Idę do salonu i wyglądam przez okno.
Słońce powoli zachodzi nad dachami miasta.
Ten letni wieczór jest piękny i jasny.
Naprawdę lubię tę okolicę.
Mieszkam tu już od pół roku.
Tak wiele wydarzyło się od stycznia.
Wtedy nie znałam w mieście nikogo.
Teraz o wiele lepiej znam ulice i codzienne życie.
Czuję się w tym mieście zupełnie jak u siebie.
Jutro jest poniedziałek i jadę autobusem do pracy.
Ale teraz po prostu odpoczywam.
Jestem całkowicie zadowolona z mojego życia tutaj.
