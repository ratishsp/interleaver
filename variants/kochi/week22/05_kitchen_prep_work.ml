ഞാൻ മാർക്കറ്റിൽ നിന്ന് വീട്ടിൽ തിരിച്ചെത്തുന്നു.
ഞാൻ ഉച്ചഭക്ഷണം ഉണ്ടാക്കാൻ അടുക്കളയിലേക്ക് പോകുന്നു.
ഞാൻ പച്ചക്കറികളും കോഴിയിറച്ചിയും മേശപ്പുറത്ത് വെക്കുന്നു.
ഞാൻ എന്റെ ഫോണിൽ പാചകക്കുറിപ്പ് തുറക്കുന്നു.
ഞാൻ അത് ഉറക്കെ വായിക്കുന്നു.
"ആദ്യം, കോഴിയിറച്ചി നന്നായി കഴുകുക," ഞാൻ വായിക്കുന്നു.
ഞാൻ ആ അര കിലോ കോഴിയിറച്ചി എടുത്ത് വെള്ളത്തിൽ കഴുകുന്നു.
ഞാൻ അത് ഒരു പാത്രത്തിൽ മാറ്റിവെക്കുന്നു.
പാചകക്കുറിപ്പിലെ അടുത്ത വരി ഞാൻ നോക്കുന്നു.
"പിന്നെ, ഉള്ളിയും തക്കാളിയും ചെറുതായി അരിയുക."
ഞാൻ രണ്ട് വലിയ ഉള്ളി എടുക്കുന്നു.
ഞാൻ അത് ചെറിയ കഷ്ണങ്ങളായി അരിയുന്നു.
അതിനുശേഷം, ഞാൻ മൂന്ന് തക്കാളിയും അങ്ങനെ തന്നെ അരിയുന്നു.
"അതിനുശേഷം, ഇഞ്ചിയും പച്ചമുളകും ചതച്ചെടുക്കുക," ഞാൻ വീണ്ടും വായിക്കുന്നു.
ഞാൻ അതും ചെയ്യുന്നു.
ഞാൻ രണ്ട് സ്പൂൺ മസാലപ്പൊടിയും എടുത്തുവെക്കുന്നു.
ഇപ്പോൾ കറി ഉണ്ടാക്കാനുള്ള എല്ലാം തയ്യാറാണ്.
ഇനി എനിക്ക് പാചകം തുടങ്ങാം.
