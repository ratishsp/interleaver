Pokládám krabici na podlahu a znovu jí děkuji.
„Není zač,“ odpovídá Nina.
Říkám jí, že ten portál byl dnes večer trochu pomalý.
„Ano, většinou bývá velmi pomalý,“ směje se Nina.
Ptá se, jestli se moje potvrzení uložilo.
„Vždy si nezapomeň své potvrzení stáhnout,“ radí.
Ptám se jí, proč je to důležité.
Nina vysvětluje, že staré zprávy se na jejich webových stránkách často mažou.
Systém je totiž po krátké době automaticky maže.
Přikyvuji a znovu otevírám portál na svém telefonu.
Najdu ten soubor a okamžitě se stáhne.
„Takže je dokument bezpečně uložený,“ říkám s úlevou.
Nina se vesele usmívá a přeje mi hezký večer.
Přeji jí to samé.
Jde po chodbě a já zavírám dveře.
Je opravdu skvělé mít chytrou a ochotnou sousedku.
