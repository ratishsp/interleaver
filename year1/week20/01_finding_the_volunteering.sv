Jag har hört att många danskar arbetar ideellt på sin fritid.
Jag gillar idén.
Jag vill gärna lära mig att prata bättre danska och träffa nya människor.
En kväll sitter jag med min dator.
Jag hittar en hemsida för volontärarbete.
Jag läser de första tre annonserna på sidan.
Den första annonsen är från en sportklubb.
Men de behöver hjälp torsdag kväll, och då spelar jag badminton.
Den andra annonsen är från ett museum.
De behöver en person onsdag kväll, men då tränar jag.
Sedan tittar jag på den tredje annonsen.
Den är från det lilla caféet som jag redan känner till.
De behöver folk till lördag förmiddag.
Det passar mig helt perfekt.
Jag fyller i ett kort formulär med mitt namn och min e-postadress.
Jag skriver också mitt telefonnummer: tolv, trettiofyra, femtiosex, sjuttioåtta.
Till sist trycker jag på skicka.
Jag har aldrig arbetat på ett café förut, men jag är redo att lära mig det.
