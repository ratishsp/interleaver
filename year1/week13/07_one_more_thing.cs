Jím poslední kousek svého skořicového šneka.
Chutná opravdu dobře.
Ale je také velmi sladký.
Můj šálek na kávu je úplně prázdný.
Najednou mám velkou žízeň.
Dala bych si trochu studené vody.
Mladý muž prochází kolem mého stolu.
Pracuje tady v kavárně.
Sbírá prázdné šálky a talíře.
Zachytím jeho pohled.
Zastaví se u mého stolu a usměje se.
„Promiňte,“ říkám zdvořile.
„Ano?“ odpovídá mladý muž.
„Mohu poprosit o sklenici vody z kohoutku?“ ptám se.
„Ano, samozřejmě,“ říká.
„Moc děkuji,“ říkám.
Vezme můj prázdný talíř a šálek.
Jde zpátky k pultu.
O chvíli později přichází se sklenicí studené vody.
