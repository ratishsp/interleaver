ലുഡ്‌വിഗ് എൻ്റെ അരികിലൂടെ വേഗത്തിൽ നടക്കുന്നു.
ഞങ്ങൾ ഒരു ലോക്കൽ ഡോഗ് ഫോറസ്റ്റിലേക്കുള്ള വഴിയിലാണ്.
ഇന്ന് ഉച്ചകഴിഞ്ഞ് സൂര്യൻ നന്നായി പ്രകാശിക്കുന്നുണ്ട്.
അവൻ അല്പം ആകാംക്ഷയോടെ ലീഷ് വലിക്കുന്നുണ്ട്.
"നിൽക്കൂ," ഞാൻ അവനോട് കർശനമായി പറയുന്നു.
"വരൂ, നമുക്ക് മര്യാദയ്ക്ക് നടക്കാം."
ഒടുവിൽ ഞങ്ങൾ ആ വലിയ ഗേറ്റിന് മുന്നിലെത്തുന്നു.
ഈ ഡോഗ് ഫോറസ്റ്റിന് ചുറ്റും വേലി കെട്ടിയിട്ടുണ്ട്, ഇത് തികച്ചും സുരക്ഷിതമാണ്.
ഞങ്ങൾ അകത്തേക്ക് കയറുന്നു, ഞാൻ ഞങ്ങൾക്ക് പിന്നിലായി ഗേറ്റ് അടയ്ക്കുന്നു.
ഞാൻ കുത്തിയിരുന്ന് അവനെ നോക്കുന്നു.
ഞാൻ പതുക്കെ അവൻ്റെ കോളറിൽ നിന്ന് ലീഷ് അഴിച്ചുമാറ്റുന്നു.
"ഇനി നിനക്ക് സ്വതന്ത്രമായി ഓടാം," ഞാൻ പുഞ്ചിരിയോടെ പറയുന്നു.
അവൻ സന്തോഷത്തോടെ എന്നെ നോക്കി വേഗത്തിൽ ഓടിപ്പോകുന്നു.
ഞാൻ നിലത്ത് നിന്ന് നല്ലൊരു വടി കണ്ടെത്തുന്നു.
"ഇങ്ങോട്ട് നോക്കൂ, ലുഡ്‌വിഗ്!" ഞാൻ ഉറക്കെ വിളിച്ച് അവന് അത് കാണിച്ചുകൊടുക്കുന്നു.
ഞാൻ ആ വടി മരങ്ങൾക്കിടയിലേക്ക് ദൂരേക്ക് എറിയുന്നു.
"അതെടുത്തുകൊണ്ടു വരൂ!" ഞാൻ ഉറക്കെ പറയുന്നു.
അവൻ വടിയുടെ അടുത്തേക്ക് ഓടിച്ചെന്ന് അത് വായിലെടുക്കുന്നു.
"തിരികെ വരൂ," ഞാൻ വിളിച്ചുകൊണ്ട് കൈയടിക്കുന്നു.
അവൻ ശരിക്കും നല്ലൊരു നായയാണ്.
