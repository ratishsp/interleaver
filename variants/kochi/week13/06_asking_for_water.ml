ഞാൻ കേക്ക് മുഴുവൻ കഴിക്കുന്നു.
എനിക്ക് ഇപ്പോൾ നന്നായി ദാഹിക്കുന്നു.
എനിക്ക് കുറച്ചു പച്ച വെള്ളം വേണം.
ഞാൻ കൗണ്ടറിലേക്ക് നോക്കുന്നു.
ഒരു വെയിറ്റർ ആ വഴി വരുന്നു.
ഞാൻ അയാളെ നോക്കുന്നു.
"ചേട്ടാ," ഞാൻ വിളിക്കുന്നു.
അയാൾ എന്റെ മേശയുടെ അടുത്തേക്ക് വരുന്നു.
"ഒരു ഗ്ലാസ്സ് വെള്ളം തരുമോ?" ഞാൻ ചോദിക്കുന്നു.
"സാധാരണ വെള്ളം വേണോ?" അയാൾ ചോദിക്കുന്നു.
"അല്ല, കുറച്ചു തണുത്ത വെള്ളം കിട്ടുമോ?" ഞാൻ ചോദിക്കുന്നു.
"ശരി, ഇപ്പോൾ കൊണ്ടുവരാം," അയാൾ പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
അയാൾ അവിടെ നിന്ന് പോകുന്നു.
