Ziemniaki gotują się teraz w garnku.
W kuchni już pięknie pachnie.
Wyjmuję dużą patelnię.
Czytam następne instrukcje w przepisie.
Następna część jest ważna.
Jest napisane: „Najpierw rozpuść gruby kawałek masła na patelni”.
Kroję trochę masła i kładę je na patelnię.
Masło szybko skwierczy na gorącym metalu.
Czytam dalej: „Następnie uformuj z mięsa okrągłe kulki”.
Używam łyżki, żeby uformować mięso.
To trochę trudne, ale wychodzą ładne i okrągłe.
Ostrożnie kładę je na gorącą patelnię.
Przepis mówi dalej: „Następnie smaż je, aż będą chrupiące i brązowe”.
Trochę zmniejszam ogień.
Muszą się smażyć przez około piętnaście minut.
Często je przewracam, żeby się nie przypaliły.
Pachną fantastycznie i nabierają ładnego koloru.
Teraz klopsiki i ziemniaki są prawie gotowe.
Nie mogę się doczekać, aż przyjdą Kasper i Sara.
To absolutnie idealne wyczucie czasu.
