Czekam przy ladzie.
On robi moją kawę.
Stawia gorącą filiżankę kawy na drewnianej tacy.
Stawia również mały talerzyk na tacy.
Moja bułeczka cynamonowa leży na talerzyku.
Pachnie cudownie.
„Proszę, twoje zamówienie” – mówi.
„Bardzo dziękuję” – odpowiadam.
„Dziękuję za dobrą obsługę”.
„Proszę bardzo” – mówi uprzejmie.
Biorę tacę obiema rękami.
Idę bardzo ostrożnie po podłodze.
Wracam do mojego stolika przy oknie.
Stawiam tacę na stoliku.
Teraz chciałabym usiąść.
Jestem gotowa na dobrą przerwę.
