ഞാൻ ഫ്ലാറ്റിൽ തിരിച്ചെത്തുന്നു.
ഞാൻ എൻ്റെ ലാപ്ടോപ്പ് തുറക്കുന്നു.
ഞാൻ മെക്സിക്കോയിലേക്ക് ഒരു വീഡിയോ കോൾ ചെയ്യുന്നു.
എൻ്റെ സഹോദരൻ ഡിയേഗോ കോൾ എടുക്കുന്നു.
"ഹലോ മായാ, നിനക്ക് സുഖമാണോ?" ഡിയേഗോ ചോദിക്കുന്നു.
"എനിക്ക് സുഖമാണ്, ഡിയേഗോ," ഞാൻ പറയുന്നു.
"ഓഫീസിൽ എനിക്ക് വളരെ നല്ല ഒരു പുതിയ ഡെസ്ക് ഉണ്ട്."
ഞാൻ ഇത് അവനോട് അഭിമാനത്തോടെ പറയുന്നു.
"നിനക്ക് ഇപ്പോൾ ഇന്ത്യൻ ഫോൺ നമ്പർ ഉണ്ടോ?" അവൻ ചോദിക്കുന്നു.
"അതെ, എനിക്ക് ഇപ്പോൾ ഒരു ഇന്ത്യൻ നമ്പർ ഉണ്ട്," ഞാൻ പറയുന്നു.
"അത് നന്നായി പ്രവർത്തിക്കുന്നു."
"കൊച്ചിയിൽ ഇപ്പോൾ ചൂട് ഉണ്ടോ?" അവൻ ചോദിക്കുന്നു.
"ഇല്ല, ഇവിടെ ഇപ്പോൾ ചൂട് ഇല്ല," ഞാൻ പറയുന്നു.
"ജനുവരിയിലെ കാലാവസ്ഥ വളരെ നല്ലതാണ്."
"ലോലയ്ക്ക് സുഖമാണോ?" ഞാൻ വീണ്ടും ചോദിക്കുന്നു.
"അതെ, ലോലയ്ക്ക് സുഖമാണ്," ഡിയേഗോ പറയുന്നു.
എനിക്ക് ഇപ്പോൾ വളരെ സന്തോഷം ഉണ്ട്.
കുറച്ച് കഴിഞ്ഞ് ഞാൻ കോൾ അവസാനിപ്പിക്കുന്നു.
