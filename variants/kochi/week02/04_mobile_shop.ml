ഇപ്പോൾ ഉച്ചസമയമാണ്.
ഞാൻ ഓഫീസിൽ നിന്ന് പുറത്തേക്ക് നടക്കുന്നു.
എനിക്ക് ഒരു ഇന്ത്യൻ സിം കാർഡ് വേണം.
ഞാൻ അടുത്തുള്ള ഒരു മൊബൈൽ കടയിലേക്ക് പോകുന്നു.
കടയിൽ വലിയ തിരക്കില്ല.
ഞാൻ കടക്കാരനോട് സംസാരിക്കുന്നു.
"നമസ്കാരം, എനിക്ക് ഒരു പുതിയ സിം കാർഡ് വേണം," ഞാൻ പറയുന്നു.
കടക്കാരൻ എനിക്ക് ഒരു ഫോം തരുന്നു.
ഞാൻ ഫോമിൽ എന്റെ പേര് എഴുതുന്നു.
"മേഡത്തിന് ഐഡി കാർഡ് ഉണ്ടോ?" കടക്കാരൻ ചോദിക്കുന്നു.
"അതെ, എനിക്ക് പാസ്പോർട്ട് ഉണ്ട്," ഞാൻ മറുപടി പറയുന്നു.
"മേഡത്തിന് എത്ര വയസ്സാണ്?" അയാൾ ചോദിക്കുന്നു.
"എനിക്ക് മുപ്പത്തിയൊന്ന് വയസ്സാണ്," ഞാൻ പറയുന്നു.
ഞാൻ അത് ഫോമിൽ എഴുതുന്നു.
അയാൾ എന്റെ പാസ്പോർട്ട് നോക്കുന്നു.
പുതിയ സിം കാർഡിന് മുന്നൂറ് രൂപയാണ്.
ഞാൻ പണം കൊടുക്കുന്നു.
