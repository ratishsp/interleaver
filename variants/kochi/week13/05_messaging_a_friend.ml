ഞാൻ എന്റെ ഫോൺ എടുക്കുന്നു.
ഞാൻ അനിതയ്ക്ക് ഒരു മെസ്സേജ് എഴുതുന്നു.
"ഹായ് അനിത, ഞാൻ ഒരു പുതിയ കഫേയിലാണ്."
"ഇവിടം വളരെ മനോഹരമാണ്."
"ഇവിടുത്തെ ബനാന കേക്ക് വളരെ രുചികരമാണ്."
"നിങ്ങൾക്ക് ഒരു ബനാന കേക്ക് വേണോ?"
"അടുത്ത തവണ ഞാൻ വാങ്ങിത്തരാം."
ഞാൻ ആ മെസ്സേജ് അയക്കുന്നു.
അനിതയുടെ മറുപടി ഉടനെ വരുന്നു.
"എനിക്കും ഒരു കേക്ക് കിട്ടുമോ?"
ഞാൻ "തീർച്ചയായും" എന്ന് മറുപടി കൊടുക്കുന്നു.
അനിത വീണ്ടും എഴുതുന്നു, "എനിക്ക് ആ കേക്ക് വേണം!"
ഞാൻ സന്തോഷത്തോടെ ചിരിക്കുന്നു.
ഞാൻ ഫോൺ മേശപ്പുറത്ത് വെക്കുന്നു.
ഞാൻ വീണ്ടും എന്റെ ഐസ് ടീ കുടിക്കുന്നു.
