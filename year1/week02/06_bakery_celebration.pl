Znowu jestem na ulicy.
Wszystko jest wreszcie na swoim miejscu.
Czas na małe świętowanie.
Widzę małą piekarnię na rogu.
Wchodzę do środka.
Pięknie pachnie.
Piekarz stoi za ladą.
„Dzień dobry” – mówi piekarz.
„Dzień dobry” – odpowiadam.
Wskazuję na ciastko za szybą.
„Chciałabym cynamonkę” – mówię.
„Tak, oczywiście” – mówi.
„Ile to kosztuje?” – pytam.
„Kosztuje dwadzieścia pięć koron” – odpowiada piekarz.
Mam portfel w torbie.
Wyciągam kartę płatniczą.
Płacę za moją cynamonkę.
Piekarz daje mi małą torebkę.
Teraz mam cynamonkę na moje małe świętowanie.
