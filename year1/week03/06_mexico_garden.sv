Jag tittar på min dator.
Jag saknar mitt hem i Mexiko lite.
"Pappa, hur är din trädgård?" säger jag.
Min pappa ler mot mig.
Han går ut med telefonen.
Det finns en stor trädgård.
Solen skiner mycket där.
"Titta, Maya," säger min pappa.
"Här är trädgården och ett träd."
Det är ett mycket stort träd.
Det är ett vackert träd.
Jag ler mot min skärm.
Det känns bra och varmt inombords.
Min mamma, min syster och min bror kommer också ut.
Min hund springer under trädet.
Hela min familj vinkar till mig.
"Hej då, allihopa!" säger jag.
"Hej då, Maya," säger de.
Jag stänger min dator.
