ഞാൻ ഓഫീസിൽ എത്തി.
ഞാൻ വാതിൽ തുറന്നു.
ഓഫീസിൽ എസി ഉണ്ട്.
ഇവിടെ നല്ല തണുപ്പാണ്.
പ്രകാശ് അവിടെ ഉണ്ട്.
"ഗുഡ് മോർണിംഗ്, പ്രകാശ്," ഞാൻ പറഞ്ഞു.
"ഗുഡ് മോർണിംഗ്, മായ," പ്രകാശ് പറഞ്ഞു.
"ഇന്ന് പുറത്ത് ഭയങ്കര ചൂടാണ്," പ്രകാശ് പറഞ്ഞു.
"അതെ, ഇന്ന് നല്ല വെയിലാണ്," ഞാൻ പറഞ്ഞു.
"പക്ഷേ ഇന്ന് മഴ പെയ്യും," ഞാൻ പ്രകാശിനോട് പറഞ്ഞു.
"മഴ പെയ്യുമോ?"
പ്രകാശ് ചോദിച്ചു.
"സത്യമാണോ?"
"അതെ, ആപ്പിൽ അങ്ങനെ കാണിക്കുന്നു," ഞാൻ പറഞ്ഞു.
"വൈകുന്നേരം മഴ പെയ്യും."
"അത് വലിയ ആശ്വാസമാണ്," പ്രകാശ് പറഞ്ഞു.
ഞങ്ങൾ ജോലി തുടങ്ങി.
