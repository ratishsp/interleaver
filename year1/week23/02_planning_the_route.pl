Robię sobie małą przerwę od pracy.
Wyciągam telefon, żeby spojrzeć na mapę.
Chcę znaleźć adres Evy.
Mieszka zupełnie po drugiej stronie miasta.
Uważnie przyglądam się trasie na ekranie.
To właściwie dość daleko.
Peter wchodzi do pokoju socjalnego po kubek kawy.
Zagląda mi przez ramię i pyta, co robię.
„W piątek odwiedzam Evę” – wyjaśniam.
„Pojedziesz tam rowerem?” – pyta.
Zastanawiam się nad tym przez chwilę.
Myślę, że chyba pojadę autobusem.
Czuję, że to po prostu za daleko na rower.
„Nie, zamierzam pojechać autobusem” – odpowiadam mu.
„Wtedy będziesz mogła też odpocząć w drodze” – mówi Peter z uśmiechem.
Ma całkowitą rację.
Zamykam aplikację i wkładam telefon z powrotem do kieszeni.
Teraz moja trasa jest zaplanowana.
Nie mogę się doczekać miłego wieczoru.
