Senare samma lördag fick vi mycket att göra igen.
En ung kvinna kom fram till disken och beställde en stor cappuccino.
Min första kopp var inte helt perfekt.
Men den här gången var jag redo.
Jag tog metallkannan och hällde kall mjölk i den.
Jag ställde kannan under maskinen och slog på den varma ångan.
Jag vred inte upp trycket direkt.
Jag har faktiskt lärt mig att lyssna på maskinen.
Det höga ljudet från ångan var helt rätt den här gången.
Mjölken blev långsamt varm.
Och skummet på toppen blev mycket tjockt och mjukt.
Det var ett stort framsteg.
Jag hällde försiktigt mjölken över kaffet i en stor kopp.
Det såg faktiskt ut som en riktig professionell cappuccino.
"Varsågod," sa jag och ställde koppen på disken.
Kvinnan log och tog sitt kaffe.
Jag har äntligen lärt mig att kontrollera trycket.
