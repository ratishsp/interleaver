ഞാൻ എന്റെ പുതിയ ഫ്ലാറ്റിന്റെ വാതിൽ തുറക്കുന്നു.
ഞാൻ അകത്തേക്ക് പോകുന്നു.
ഇത് ചെറുതാണ്, പക്ഷേ വളരെ മനോഹരമാണ്.
ഒരു ചെറിയ അടുക്കളയുണ്ട്.
ഒരു മേശയും രണ്ട് കസേരകളുമുണ്ട്.
കൂടാതെ ഒരു വലിയ ജനാലയുമുണ്ട്.
ഞാൻ എന്റെ ചുവന്ന സ്യൂട്ട്കേസ് തറയിൽ വെക്കുന്നു.
ഒടുവിൽ ഞാൻ കോപ്പൻഹേഗനിലാണ്.
ഇത് ഡെൻമാർക്കിലെ ഒരു നല്ല തുടക്കമാണ്.
