Docieram do fryzjera o wpół do piątej.
Zawsze jestem punktualna.
Fryzjerka mnie wita.
Myje i obcina mi włosy.
Zajmuje to około godziny.
Moja nowa fryzura jest bardzo ładna.
Dziękuję fryzjerce i wychodzę z salonu.
Mój rower stoi przed wejściem.
Jadę rowerem przez miasto.
Jest czwartkowy wieczór.
Jadę rowerem do przytulnej kawiarni.
Parkuję rower i wchodzę do środka.
Nina siedzi już przy stoliku.
Spoglądam na zegarek.
Jest dokładnie szósta.
„Cześć Maya, twoje włosy wyglądają naprawdę ładnie” – mówi Nina.
„Bardzo dziękuję” – mówię.
Zamawiamy dwie filiżanki kawy.
Pijemy kawę i rozmawiamy.
Zawsze bardzo lubię nasze spotkania przy kawie.
