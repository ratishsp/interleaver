വാതിൽ തുറന്നിരിക്കുകയാണ്.
വാതിൽപ്പടിക്ക് നല്ല ഉയരമുണ്ട്.
സ്യൂട്ട്കേസിന് നല്ല ഭാരമുണ്ട്!
പക്ഷേ ഇപ്പോൾ സ്യൂട്ട്കേസ് ഇടനാഴിയിലാണ്.
ഇവിടെ പൂർണ്ണമായും ഇരുട്ടാണ്.
സ്വിച്ച് എവിടെയാണ്?
ഭിത്തിക്ക് തണുപ്പുണ്ട്.
സ്വിച്ച് ഇവിടെയാണോ?
അതെ, അവിടെയുണ്ട് സ്വിച്ച്!
ഇപ്പോൾ വെളിച്ചമുണ്ട്.
ഞാൻ അപ്പാർട്ട്മെന്റിലാണ്.
ഇത് ചെറുതാണ്, പക്ഷേ മനോഹരമാണ്.
ഇവിടെ ഒരു സ്വീകരണമുറിയുണ്ട്.
അവിടെ ഒരു സോഫയും ഒരു മേശയും ഉണ്ട്.
ഇതൊരു ഫർണിഷ് ചെയ്ത വീടാണ്.
സ്യൂട്ട്കേസ് തറയിലാണ്.
ഞാൻ വളരെ ക്ഷീണിതയാണ്.
പക്ഷേ ഞാൻ സന്തോഷവതിയുമാണ്.
ഞാൻ കോപ്പൻഹേഗനിലാണ്!
