„Reklamówkę?” – pyta sprzedawca.
„Nie, dziękuję” – mówię.
Nie potrzebuję reklamówki.
Od razu zakładam nowe ubrania.
Najpierw zakładam gruby, czerwony sweter.
Potem zakładam ciemnoniebieską kurtkę zimową.
Zapinam ciepłą kurtkę.
Następnie biorę długi, niebieski szalik.
Owijam go wokół szyi.
Na koniec zakładam nowe, czarne rękawiczki.
Teraz mam na sobie wszystkie moje ciepłe ubrania.
Uśmiecham się i mówię do widzenia.
Wychodzę ze sklepu.
Znowu stoję na zewnątrz na zimnej ulicy.
Jest lodowato.
Wiatr mocno wieje.
Ale w ogóle nie marznę.
Teraz jestem gotowa na zimę.
