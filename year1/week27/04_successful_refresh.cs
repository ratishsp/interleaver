Znovu se podívám na obrazovku.
Kód stále chybí.
Obvykle se systémem nemám problémy.
Čtu si pokyny na webové stránce.
Píše se tam: „Pokud kód neobdržíte, lze zažádat o nový kód.“
Kliknu na odkaz dole na stránce.
Je tam krátká zpráva: „Čekejte prosím.“
O chvíli později mi na stole zavibruje telefon.
Nová zpráva byla konečně odeslána.
Otevřu zprávu, abych si přečetla svůj nový kód.
Je to čtyři, devět, dva, sedm.
Rychle napíšu čísla do prázdného políčka.
Poté stisknu tlačítko „Schválit“.
Stránka se okamžitě aktualizuje.
Na obrazovce se zobrazí velký zelený banner.
V textu stojí: „Váš profil je nyní aktualizován.“
Usměju se a zavřu webovou stránku.
Je vždycky fajn, když jsou takové praktické věci vyřízené.
