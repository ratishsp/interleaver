കാസ്പറും സാറയും എമിലും ഞാനും കൂടി ഏകദേശം രണ്ട് മണിക്കൂറോളം ബാഡ്മിൻ്റൺ കളിച്ചു.
ഇപ്പോൾ മത്സരം കഴിഞ്ഞിരുന്നു, നന്നായി കളിച്ചതിൻ്റെ ഒരു നല്ല ക്ഷീണം ഞങ്ങൾക്കുണ്ടായിരുന്നു.
ഞങ്ങൾ നടന്ന് ഒരു ബെഞ്ചിനടുത്തേക്ക് പോയി.
ഞങ്ങൾ ഒരുമിച്ച് അവിടെ ഇരുന്നു.
ഞാൻ എൻ്റെ ബാഗ് തുറന്ന് വാട്ടർ ബോട്ടിൽ എടുത്തു.
ഞങ്ങൾ കുറേ നേരം തണുത്ത വെള്ളം കുടിച്ചുകൊണ്ടിരുന്നു.
"അതൊരു കടുത്ത മത്സരമായിരുന്നു," കാസ്പർ പറഞ്ഞു.
സാറ പുഞ്ചിരിച്ചുകൊണ്ട് എന്നെ നോക്കി.
"നീ ജനുവരിയിലല്ലേ ഡെന്മാർക്കിലേക്ക് വന്നത്?" അവൾ ചോദിച്ചു.
"അതെ, ഞാൻ ജനുവരിയിലാണ് മെക്സിക്കോയിൽ നിന്ന് യാത്ര തിരിച്ചത്," ഞാൻ മറുപടി പറഞ്ഞു.
കാസ്പർ അവൻ്റെ റാക്കറ്റ് ബെഞ്ചിൽ വെച്ചു.
"ഈ രാജ്യത്തെ നിൻ്റെ ആദ്യത്തെ കുറച്ചു ദിവസങ്ങൾ എങ്ങനെയുണ്ടായിരുന്നു?" അവൻ ചോദിച്ചു.
ഞാൻ എൻ്റെ ആദ്യത്തെ ആഴ്ചയെക്കുറിച്ച് ഓർത്തു.
അന്ന് എല്ലാം പുതിയതും വളരെ വ്യത്യസ്തവുമായിരുന്നു.
എനിക്ക് ഈ നഗരം തീരെ പരിചയമില്ലായിരുന്നു.
"നല്ല തണുപ്പായിരുന്നു," ഞാൻ പറഞ്ഞു തുടങ്ങി.
കാസ്പറും സാറയും ഉച്ചത്തിൽ ചിരിച്ചു.
"ഡാനിഷ് ശൈത്യകാലം എപ്പോഴും തണുപ്പുള്ളതാണ്," സാറ പറഞ്ഞു.
കാസ്പർ എന്നോട് ചോദിച്ചു.
"നിൻ്റെ ഏറ്റവും ആദ്യത്തെ ദിവസം എങ്ങനെയുണ്ടായിരുന്നു?"
