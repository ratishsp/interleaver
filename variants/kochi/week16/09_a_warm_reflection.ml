"ആ ജനുവരി മാസം വളരെ തിരക്കായിരുന്നു," അമ്മ പറഞ്ഞു.
ഞാൻ അത് സമ്മതിച്ചു.
"എല്ലാം വളരെ വേഗത്തിൽ മാറി," ഞാൻ അമ്മയോട് പറഞ്ഞു.
ജനുവരിയിൽ എല്ലാം പുതിയതായിരുന്നു.
തുടക്കത്തിൽ എനിക്ക് ചെറിയ പേടി തോന്നി.
പക്ഷേ, ഈ നഗരം എനിക്ക് വേഗത്തിൽ പരിചിതമായി.
എനിക്ക് ഇവിടെ നല്ല സുഹൃത്തുക്കളെ കിട്ടി.
കഴിഞ്ഞ ആഴ്ച എനിക്ക് ആ പഴയ പേടി തോന്നിയില്ല.
ഇന്നലെ മുറിയിൽ ഇരുന്നപ്പോൾ എനിക്ക് വലിയ സമാധാനം തോന്നി.
ഇതെല്ലാം കാരണം കൊച്ചി ഇപ്പോൾ എന്റെ സ്വന്തം വീടുപോലെയാണ്.
"നീ അവിടെ സന്തോഷവതിയാണ്," അമ്മ ചിരിച്ചുകൊണ്ട് പറഞ്ഞു.
"അതെ, ഞാൻ ഇവിടെ വളരെ സന്തോഷവതിയാണ്," ഞാൻ മറുപടി നൽകി.
സ്ക്രീനിൽ ലോല പതിയെ അനങ്ങി.
അവൾ നല്ല ഉറക്കത്തിലായിരുന്നു.
ഞങ്ങൾ കുറച്ചു സമയം കൂടി സംസാരിച്ചു.
കോൾ കഴിഞ്ഞ ശേഷം ഞാൻ എന്റെ മുറിയിലേക്ക് നോക്കി.
കൊച്ചിയിലെ എന്റെ ജീവിതം എനിക്ക് ഇഷ്ടമായി.
ആ ചിന്ത എനിക്ക് വലിയ സന്തോഷം നൽകി.
