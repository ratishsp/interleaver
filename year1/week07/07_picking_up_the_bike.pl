Jest czwartkowe popołudnie.
Skończyłam pracę.
Idę do mechanika rowerowego.
Jest za kwadrans czwarta.
Mechanik stoi w sklepie.
– Hej – mówię.
Wyprowadza do mnie rower.
– Twój rower jest gotowy – mówi.
– Bardzo dziękuję – mówię.
Rower wygląda naprawdę dobrze.
Opony są teraz twarde.
Wyprowadzam rower na ulicę.
Dzisiaj świeci słońce.
Wsiadam na rower.
Często jeżdżę na rowerze po Kopenhadze.
To bardzo łatwe.
Teraz zadowolona jadę rowerem w stronę fryzjera.
Mam wizytę o wpół do piątej.
Nie mogę się doczekać.
