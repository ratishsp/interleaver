Slyšela jsem, že mnoho Dánů ve svém volném čase pracuje jako dobrovolníci.
Ten nápad se mi líbí.
Chci se naučit mluvit lépe dánsky a poznat nové lidi.
Jednoho večera sedím u počítače.
Najdu webovou stránku pro dobrovolnickou práci.
Přečtu si první tři inzeráty na stránce.
První inzerát je ze sportovního klubu.
Ale potřebují pomoct ve čtvrtek večer, a to já hraju badminton.
Druhý inzerát je z muzea.
Potřebují někoho na středu večer, ale to já cvičím.
Pak se podívám na třetí inzerát.
Je z té malé kavárny, kterou už znám.
Potřebují lidi na sobotní dopoledne.
To mi naprosto dokonale vyhovuje.
Vyplním krátký formulář se svým jménem a e-mailovou adresou.
Napíšu také své telefonní číslo: dvanáct, třicet čtyři, padesát šest, sedmdesát osm.
Nakonec stisknu odeslat.
Nikdy předtím jsem v kavárně nepracovala, ale jsem připravená se to naučit.
