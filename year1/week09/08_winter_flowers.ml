ഞാൻ മാർക്കറ്റിന്റെ പുറത്തേക്കുള്ള വഴിയിലേക്ക് നടക്കുന്നു.
ഞാൻ ഒരു വലിയ പൂക്കട കാണുന്നു.
ആ കടയിൽ ഒരുപാട് മനോഹരമായ പൂക്കളുണ്ട്.
ഞാൻ ആ കടയ്ക്ക് മുന്നിൽ നിൽക്കുന്നു.
ഞാൻ ഒരു കെട്ട് വിന്റർ ടുലിപ്‌സ് നോക്കുന്നു.
അവ വളരെ വർണ്ണാഭമാണ്.
ഞാൻ ആ ടുലിപ്‌സിന് നേരെ വിരൽ ചൂണ്ടുന്നു.
"ഈ ടുലിപ്‌സിന് എത്രയാണ് വില?" ഞാൻ വിൽപ്പനക്കാരനോട് ചോദിക്കുന്നു.
വിൽപ്പനക്കാരൻ ടുലിപ്‌സ് ഉയർത്തിപ്പിടിക്കുന്നു.
"ഇതിന് നാൽപ്പത് ക്രോണർ ആണ്," അയാൾ മറുപടി പറയുന്നു.
"ഞാൻ ഇത് വാങ്ങാം," ഞാൻ പറയുന്നു.
ഞാൻ പൂക്കൾക്കുള്ള പണം നൽകുന്നു.
വിൽപ്പനക്കാരൻ എനിക്ക് ആ ടുലിപ്‌സ് നൽകുന്നു.
ഇപ്പോൾ മാർക്കറ്റിലെ എന്റെ കാര്യങ്ങൾ കഴിഞ്ഞു.
ഞാൻ എന്റെ അപ്പാർട്ട്മെന്റിലേക്ക് തിരികെ നടക്കുന്നു.
ഞാൻ ആ വർണ്ണാഭമായ ടുലിപ്‌സ് എന്റെ കയ്യിൽ പിടിക്കുന്നു.
ഞാൻ എന്റെ ചൂട് കാപ്പി കുടിക്കുന്നു.
തിരക്കേറിയ മാർക്കറ്റിന് മുകളിൽ സൂര്യൻ പ്രകാശിക്കുന്നു.
