Det är sen eftermiddag på kontoret.
Jag tittar på min skärm.
Jag skriver den sista koden.
Nu är uppgiften färdig.
Jag ler.
Jag stänger min dator.
Jag lägger den i min väska.
Därefter packar jag mina saker.
Jag reser mig upp.
Min kollega Peter sitter vid sitt skrivbord.
Jag går fram till honom.
"Hejdå, Peter," säger jag.
"Hejdå, Maya," säger Peter.
"Ha en trevlig kväll," säger han.
"Tack, detsamma," svarar jag.
Jag går ut från kontoret.
Ute i korridoren tar jag hissen ner.
Till sist går jag ut ur byggnaden.
Nu åker jag hem.
