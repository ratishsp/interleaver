വെള്ളിയാഴ്ച ഉച്ചഭക്ഷണത്തിന്റെ സമയമാണ്.
ഞാൻ പ്രകാശ് പറഞ്ഞ ബേക്കറിയിൽ പോകുന്നു.
കടയിൽ നല്ല തിരക്കുണ്ട്.
അവിടെ ഗ്ലാസ്സ് അലമാരയിൽ ഒരുപാട് മധുരപലഹാരങ്ങൾ ഉണ്ട്.
ദീപയ്ക്ക് ഇത് ഇഷ്ടമാകും എന്ന് ഞാൻ കരുതുന്നു.
ഞാൻ പല നിറത്തിലുള്ള ഹൽവകൾ കാണുന്നു.
ചുവപ്പ്, കറുപ്പ്, മഞ്ഞ നിറങ്ങളിൽ അവിടെ ഹൽവ ഉണ്ട്.
ഞാൻ ഒരു മിക്സഡ് ഹൽവ ബോക്സ് വാങ്ങാം.
"ചേട്ടാ, എനിക്ക് ഒരു മിക്സഡ് ഹൽവ ബോക്സ് വേണം," ഞാൻ കടക്കാരനോട് പറയുന്നു.
"തീർച്ചയായും, എത്ര കിലോ വേണം?" അയാൾ ചോദിക്കുന്നു.
"അര കിലോ മതി," ഞാൻ മറുപടി പറയുന്നു.
അയാൾ പല നിറത്തിലുള്ള ഹൽവകൾ ഒരു പെട്ടിയിലാക്കുന്നു.
"ഇതിന് ഇരുന്നൂറ് രൂപയാണ്," അയാൾ പറയുന്നു.
ഞാൻ അയാൾക്ക് പണം കൊടുക്കുന്നു.
ഇന്ന് രാത്രി ദീപയുടെ വീട്ടിൽ പോകുമ്പോൾ ഞാൻ ഇത് കൊണ്ടുപോകും.
ഇത് നല്ലൊരു സമ്മാനമാണ് എന്ന് എനിക്ക് ഉറപ്പുണ്ട്.
