Později tu samou sobotu jsme měli zase velmi napilno.
Mladá žena přišla k pultu a objednala si velké cappuccino.
Můj první šálek nebyl úplně perfektní.
Ale tentokrát jsem byla připravená.
Vzala jsem kovovou konvičku a nalila do ní studené mléko.
Dala jsem konvičku pod přístroj a zapnula horkou páru.
Nezvýšila jsem tlak okamžitě.
Naučila jsem se totiž ten přístroj poslouchat.
Hlasitý zvuk páry byl tentokrát naprosto správný.
Mléko se pomalu ohřívalo.
A pěna nahoře byla velmi hustá a jemná.
Byl to velký krok kupředu.
Opatrně jsem nalila mléko na kávu ve velkém šálku.
Vlastně to vypadalo jako opravdové profesionální cappuccino.
„Prosím,“ řekla jsem a postavila šálek na pult.
Žena se usmála a vzala si svou kávu.
Konečně jsem se naučila kontrolovat tlak.
