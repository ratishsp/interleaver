ഞാൻ ഒരു പച്ചക്കറി കടയുടെ അടുത്തേക്ക് നടക്കുന്നു.
ഞാൻ ഇന്ന് ചൂടുള്ള ഒരു സൂപ്പ് ഉണ്ടാക്കുകയാണ്.
മേശപ്പുറത്തുള്ള നിരവധി പച്ചക്കറികളിലേക്ക് ഞാൻ നോക്കുന്നു.
ഞാൻ കുറച്ച് വലിയ വിന്റർ ക്യാരറ്റുകൾക്ക് നേരെ വിരൽ ചൂണ്ടുന്നു.
എൻ്റെ സൂപ്പിലേക്ക് എനിക്ക് ക്യാരറ്റ് ആവശ്യമാണ്.
മേശയ്ക്ക് പിന്നിലായി ഒരു കച്ചവടക്കാരൻ നിൽക്കുന്നുണ്ട്.
"ഹലോ," അയാൾ പറയുന്നു.
"ഹലോ," ഞാൻ മറുപടി പറയുന്നു.
"ക്യാരറ്റിന് എത്രയാണ് വില?" ഞാൻ ചോദിക്കുന്നു.
"കിലോയ്ക്ക് പതിനഞ്ച് ക്രോണർ ആണ്," കച്ചവടക്കാരൻ മറുപടി നൽകുന്നു.
പതിനഞ്ച് ക്രോണർ എന്നത് നല്ലൊരു വിലയാണ്.
"ഞാൻ ഒരു കിലോ എടുക്കാം," ഞാൻ പറയുന്നു.
കച്ചവടക്കാരൻ ക്യാരറ്റ് തൂക്കി നോക്കുന്നു.
അയാൾ അത് ഒരു പേപ്പർ ബാഗിൽ ഇടുന്നു.
അയാൾ എനിക്ക് ആ ബാഗ് തരുന്നു.
ഞാൻ ആ പതിനഞ്ച് ക്രോണർ കൊടുക്കുന്നു.
ഞാൻ ആ ബാഗ് എൻ്റെ വലിയ ബാഗിനുള്ളിലേക്ക് വയ്ക്കുന്നു.
ആ ചൂടുള്ള സൂപ്പിനായി ഞാൻ കാത്തിരിക്കുകയാണ്.
