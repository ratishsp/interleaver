Siedzę w autobusie.
Wyglądam przez okno.
Nie jestem do końca pewna trasy.
Blisko mnie siedzi starsza kobieta.
Spoglądam na nią.
„Przepraszam” – mówię grzecznie.
„Czy ten autobus jedzie na stację metra?”
Kobieta patrzy na mnie.
Kiwa głową z przyjaznym uśmiechem.
„Tak, jedzie na stację metra” – odpowiada.
„Jedzie pani metrem?” – pyta kobieta.
„Tak, jadę metrem” – mówię.
„Często jeżdżę tym autobusem” – mówi kobieta.
„To prosta trasa” – dodaje.
„Bardzo dziękuję za pomoc” – mówię.
„To moja pierwsza podróż tą trasą”.
Kobieta znów kiwa głową.
Odprężam się na siedzeniu.
Jedziemy dalej przez miasto.
