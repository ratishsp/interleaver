Vycházím znovu na chodbu.
Můj největší kufr stojí na podlaze.
Je velmi těžký.
Zatáhnu za kufr.
Najednou slyším na schodech kroky.
Je to moje dánská sousedka, Nina.
Vřele se na mě usmívá.
„Dnes se stěhuješ, Mayo?“ ptá se.
„Ano, konečně jsem ve svém novém bytě,“ říkám.
„Pomůžu ti,“ říká Nina laskavě.
Chytne kufr.
Společně neseme kufr do obýváku.
Nina ho opatrně postaví na podlahu.
Teď kufr stojí u velkého okna.
Pod oknem už leží taška.
„Moc děkuji za pomoc, Nino,“ říkám radostně.
„Není zač,“ usmívá se.
Nina odchází na chodbu.
Zavírám dveře a dívám se na kufr u okna.
