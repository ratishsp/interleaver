Samolot jest teraz w Kopenhadze.
Jest styczeń.
Jestem bardzo podekscytowana.
Pakuję książkę do torby.
Obok mnie jest pasażer.
Patrzy na mnie i się uśmiecha.
„Cześć” – mówi.
„Cześć” – mówię.
„Jak masz na imię?” – pyta.
„Mam na imię Maya” – mówię.
„Skąd pochodzisz, Maya?” – pyta.
Uśmiecham się radośnie.
„Pochodzę z Meksyku” – odpowiadam.
„Czy jesteś z Danii?” – pytam.
„Tak, jestem z Danii” – mówi.
„Witamy w Danii” – mówi.
„Bardzo dziękuję” – mówię.
Teraz jesteśmy na miejscu.
Jestem gotowa.
