Po śniadaniu mam dużo czasu.
Zazwyczaj w soboty pracuję jako wolontariuszka w kawiarni.
Ale Ludwig nie powinien być sam.
Na szczęście mam dzisiaj wolne w kawiarni.
Ustaliłam to z nimi w zeszłym tygodniu.
Teraz Ludwig i ja mamy cały poranek razem.
Wychodzimy na podwórko za moim budynkiem.
Wyciągam jego małą piłkę.
"Spójrz na piłkę, Ludwig!" - mówię do niego.
Rzucam ją na trawę.
"Przynieś!" - krzyczę.
Biegnie szybko i łapie piłkę.
"Chodź tutaj!" - wołam.
Radośnie biegnie z powrotem do mnie.
"Daj mi ją" - mówię łagodnie.
Puszcza piłkę, a ja go głaszczę.
"Jesteś dobrym psem" - mówię i uśmiecham się.
Rzucam ją znowu, a on ją przynosi.
Muszę się nim dobrze opiekować przez cały weekend.
Bardzo się cieszę, że zostałam z nim w domu.
