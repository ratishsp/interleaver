W moją trzecią sobotę stałam gotowa za ladą.
W końcu nauczyłam się trochę relaksować w kawiarni.
Przez okno zobaczyłam starszego mężczyznę na ulicy.
Szedł powoli w stronę drzwi wejściowych.
Był tu też na mojej pierwszej i drugiej zmianie.
Jest jednym ze stałych klientów kawiarni.
Nauczyłam się jego zamówienia na pamięć.
Zawsze kupuje dokładnie to samo.
Otworzył drzwi i podszedł do kasy.
Spojrzałam na niego i uśmiechnęłam się.
„Dzień dobry” – powiedziałam.
„Zrobić panu to, co zwykle, czyli cortado?”
Mężczyzna spojrzał na mnie zaskoczony.
Potem uśmiechnął się radośnie.
„Tak, poproszę, bardzo chętnie” – odpowiedział.
Podeszłam do ekspresu do kawy.
Robiłam kawę już wiele razy, więc poszło szybko.
To było miłe uczucie znać naszych gości.
