വെള്ളിയാഴ്ച വൈകുന്നേരം വളരെ വൈകിയ സമയമാണിത്.
ഉറങ്ങാൻ പോകുന്നതിനുമുമ്പ്, ഞാൻ ലുഡ്‌വിഗിനെയും കൂട്ടി പുറത്തേക്ക് പോകുന്നു.
ഞങ്ങൾ അയൽപക്കത്ത് ഒരു ചെറിയ നടത്തത്തിന് പോകുന്നു.
തെരുവുകൾ ഇപ്പോൾ വളരെ ശാന്തമാണ്.
ലുഡ്‌വിഗ് എൻ്റെ അരികിലൂടെ നല്ല രീതിയിൽ നടക്കുന്നു.
പെട്ടെന്ന് അവൻ നിൽക്കുന്നു.
ഫുട്പാത്തിലുള്ള എന്തോ ഒന്ന് അവൻ ആവേശത്തോടെ മണത്തുനോക്കുന്നു.
അത് ഭക്ഷണ അവശിഷ്ടങ്ങളുള്ള ഒരു അഴുക്കുപിടിച്ച കവറാണ്.
അതെടുക്കാൻ അവൻ വായ തുറക്കുന്നു.
"വേണ്ട, അത് താഴെയിടു!" ഞാൻ അവനോട് കർശനമായി പറയുന്നു.
ഞാൻ അവനെ ആ കവറിൽ നിന്ന് പതുക്കെ വലിച്ചുമാറ്റുന്നു.
"ചവറ് ഭക്ഷണമല്ല, ലുഡ്‌വിഗ്," ഞാൻ വിശദീകരിക്കുന്നു.
"ഇങ്ങോട്ട് വാ, ലുഡ്‌വിഗ്," ഞാൻ അവനെ വിളിക്കുന്നു.
അവൻ കവർ താഴെയിട്ടിട്ട് എൻ്റെ മുഖത്തേക്ക് നോക്കുന്നു.
അവൻ വേഗത്തിൽ വാലാട്ടാൻ തുടങ്ങുന്നു.
"നല്ല കുട്ടി," എന്ന് പറഞ്ഞുകൊണ്ട് ഞാൻ അവനെ തലോടുന്നു.
ഞങ്ങൾ തെരുവിലൂടെ ഞങ്ങളുടെ നടത്തം തുടരുന്നു.
ഇനി ഞങ്ങൾക്ക് വീട്ടിൽ പോയി ഉറങ്ങുകയേ വേണ്ടൂ.
