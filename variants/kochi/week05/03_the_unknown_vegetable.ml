ഞാൻ പച്ചക്കറിക്കടക്കാരനെ നോക്കുന്നു.
അവിടെ ഒരു ചെറിയ കുട്ട ഉണ്ട്.
ആ കുട്ടയിൽ ഒരു പച്ച പച്ചക്കറി ഉണ്ട്.
അതിന് നല്ല നീളമുണ്ട്.
എനിക്ക് ഈ പച്ചക്കറി അറിയില്ല.
ഞാൻ അതിലേക്ക് വിരൽ ചൂണ്ടുന്നു.
"ഇതെന്താണ്?" ഞാൻ അദ്ദേഹത്തോട് ചോദിക്കുന്നു.
"അത് പാവയ്ക്ക ആണ്," കടക്കാരൻ പറയുന്നു.
"നിങ്ങൾക്ക് പാവയ്ക്ക വേണമോ?" അദ്ദേഹം ചോദിക്കുന്നു.
എനിക്ക് പുതിയ പച്ചക്കറികൾ ഇഷ്ടമാണ്.
"അതെ, എനിക്ക് ഒന്ന് വേണം," ഞാൻ പറയുന്നു.
"എനിക്ക് ഒരു പാവയ്ക്ക മാത്രം വേണം," ഞാൻ വീണ്ടും പറയുന്നു.
കടക്കാരൻ ഒരു പാവയ്ക്ക എടുക്കുന്നു.
അദ്ദേഹം ചിരിക്കുന്നു.
"ഇതിന് കയ്പ്പാണ്," അദ്ദേഹം പറയുന്നു.
ഞാൻ തിരിച്ച് ചിരിക്കുന്നു.
എനിക്ക് കയ്പ്പുള്ള ഭക്ഷണവും ഇഷ്ടമാണ്.
അദ്ദേഹം അത് എന്റെ സഞ്ചിയിൽ വെക്കുന്നു.
