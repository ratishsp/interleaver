ഞങ്ങൾ എൻ്റെ ചെറിയ മേശയ്ക്കരികിൽ ഇരിക്കുന്നു.
അവിടെ അല്പം സ്ഥലപരിമിതി ഉണ്ട്, എങ്കിലും ഞങ്ങൾ അടുത്തടുത്ത് സുഖമായി ഇരിക്കുന്നു.
ആദ്യം, ഞാൻ ഭക്ഷണമുള്ള പാത്രങ്ങൾ മേശപ്പുറത്ത് വെക്കുന്നു.
അതിനുശേഷം, കാസ്പറും സാറയും വലിയൊരു പങ്ക് എടുക്കുന്നു.
അവർ മീറ്റ്ബോളുകളും ഉരുളക്കിഴങ്ങും രുചിച്ച് നോക്കുന്നു.
"ഇത് ശരിക്കും വളരെ രുചികരമാണ്, മായാ!" സാറ പറയുന്നു.
"അതെ, അവ ശരിക്കും നല്ലതാണ്," കാസ്പർ പറയുന്നു.
അവൻ വേഗത്തിൽ ഒരു കടി കൂടി എടുക്കുന്നു.
കാസ്പർ തണുത്ത ബിയറുകളും തുറക്കുന്നു.
തുറന്ന് അവൻ അത് ഞങ്ങളുടെ ഗ്ലാസുകളിലേക്ക് ഒഴിക്കുന്നു.
"ചിയേഴ്സ്!" ഞങ്ങൾ മൂന്നുപേരും പറയുകയും കുടിക്കുകയും ചെയ്യുന്നു.
കാസ്പർ പാത്രത്തിൽ നിന്ന് കൂടുതൽ മീറ്റ്ബോളുകൾ എടുക്കുന്നു.
സാറയും ഉരുളക്കിഴങ്ങിന്റെ ഒരു അധിക പങ്ക് എടുക്കുന്നു.
"നിങ്ങൾക്ക് ഇത് ഇഷ്ടപ്പെട്ടതിൽ എനിക്ക് വളരെ സന്തോഷമുണ്ട്," ഞാൻ പറയുന്നു.
"എല്ലാവർക്കും വേണ്ടുവോളമുണ്ട്," ഞാൻ പുഞ്ചിരിക്കുന്നു.
അവർ അതിൻ്റെ തനതായ രുചിയെ പ്രശംസിക്കുന്നു.
ഞങ്ങൾ മേശയ്ക്ക് ചുറ്റുമിരുന്ന് സംസാരിക്കുകയും ചിരിക്കുകയും ചെയ്യുന്നു.
ഞങ്ങൾ വളരെ നേരം ഭക്ഷണം കഴിക്കുകയും സംസാരിക്കുകയും ചെയ്യുന്നു.
