Vinden blåser kallt i dag.
Mina händer är mycket kalla.
Jag ser ett stort stånd med varma kläder.
Jag går fram till försäljaren.
Han har många varma saker på bordet.
Jag tar upp ett par tjocka ullhandskar.
De är mycket mjuka.
"Hur mycket kostar handskarna?" frågar jag.
"De kostar tvåhundra kronor," svarar försäljaren.
Jag tittar på handskarna igen.
Tvåhundra kronor är ett högt pris.
Det är för dyrt för mig.
Jag lägger tillbaka handskarna på bordet.
"Nej tack," säger jag artigt.
"Ha en bra dag."
Försäljaren nickar och ler.
"Detsamma," säger han.
Jag går vidare runt på marknaden.
