Nu ska jag koka potatisarna.
Jag tittar på mitt recept igen.
Det har några mycket korta instruktioner.
Först står det: "Skrubba de små potatisarna rena."
Det gör jag med en liten borste under kallt vatten.
Sedan läser jag nästa rad.
Därefter står det: "Lägg potatisarna i en gryta med vatten."
Jag tar fram min stora gryta ur skåpet.
Jag lägger ner hela kilot i grytan.
Grytan är nästan helt full.
Vad är nästa steg?
Receptet säger: "Tillsätt en stor skedfull grovt salt i vattnet."
Jag tar fram saltet och en sked.
Jag häller upp saltet på skeden.
Jag häller ner den stora skedfullen till potatisarna.
Till sist står det: "Sätt på spisen."
Jag ställer grytan på spisen och sätter på den.
Nu ska potatisarna bara koka i tjugo minuter.
