Vidím zvláštní zeleninu.
Ta zelenina je dlouhý kořen.
Ten kořen je velmi světlý.
Vypadá jako bílá mrkev.
Podívám se dolů na cedulku.
Na cedulce je napsáno „pastiňák“.
Tu zeleninu neznám.
Je to dánská zelenina?
Mám ráda zeleninu.
Mám ráda mrkev.
Možná ten pastiňák chutná dobře.
Vezmu pastiňák do ruky.
Ten kořen je docela velký.
Chtěla bych ho.
Podívám se na košík.
Dám ten kořen do košíku.
Chtěla bych zkusit něco nového.
