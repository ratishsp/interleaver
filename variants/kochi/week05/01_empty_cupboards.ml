ഞാൻ അടുക്കളയിൽ പോകുന്നു.
ഞാൻ അലമാരകൾ തുറക്കുന്നു.
അലമാരകൾ മിക്കവാറും ഒഴിഞ്ഞതാണ്.
അവിടെ വീട്ടിൽ നിന്ന് കൊണ്ടുവന്ന എന്റെ കാപ്പി മാത്രമേ ഉള്ളൂ.
ഞാൻ ഫ്രിഡ്ജ് തുറക്കുന്നു.
ഫ്രിഡ്ജും കാലിയാണ്.
എനിക്ക് വിശക്കുന്നു.
എനിക്ക് ഭക്ഷണം വേണം.
ഈ ആഴ്ച എനിക്ക് പുതിയ സാധനങ്ങൾ വേണം.
എനിക്ക് പുതിയ പച്ചക്കറികൾ വേണം.
ഞാൻ എന്റെ മേശയുടെ അടുത്തേക്ക് നടക്കുന്നു.
ഞാൻ ഒരു പേപ്പറും പേനയും എടുക്കുന്നു.
ഞാൻ ഒരു ലിസ്റ്റ് എഴുതുന്നു.
എനിക്ക് അരി വേണം.
എനിക്ക് പാൽ വേണം.
എനിക്ക് ചായപ്പൊടിയും വേണം.
ഇപ്പോൾ എന്റെ ലിസ്റ്റ് തയ്യാറാണ്.
