ഞാൻ ഓട്ടോയിൽ വീട്ടിലേക്ക് പോവുകയാണ്.
രാവിലത്തെ കാലാവസ്ഥ വളരെ നല്ലതാണ്.
ഓട്ടോ എൻ്റെ ഫ്ലാറ്റിനടുത്ത് നിർത്തുന്നു.
ഫ്ലാറ്റിനടുത്ത് ഒരു ചെറിയ പച്ചക്കറിക്കടയുണ്ട്.
ഞാൻ ആ കടയിലേക്ക് പോകുന്നു.
എനിക്ക് പുതിയ പച്ചക്കറികൾ വേണം.
കടയിൽ ധാരാളം പച്ചക്കറികൾ ഉണ്ട്.
അവിടെ ഞാൻ തക്കാളിയും ക്യാരറ്റും ഉള്ളിയും കാണുന്നു.
എനിക്ക് തക്കാളി വളരെ ഇഷ്ടമാണ്.
ഞാൻ ചുവന്ന തക്കാളി ചൂണ്ടിക്കാണിക്കുന്നു.
ഞാൻ കടക്കാരനോട് സംസാരിക്കുന്നു.
"എനിക്ക് തക്കാളി വേണം," ഞാൻ പറയുന്നു.
അദ്ദേഹം ചിരിച്ചുകൊണ്ട് ഒരു കൊട്ട എടുക്കുന്നു.
പിന്നെ ഞാൻ ക്യാരറ്റ് ചൂണ്ടിക്കാണിക്കുന്നു.
"എനിക്ക് ക്യാരറ്റും ഉള്ളിയും വേണം," ഞാൻ അദ്ദേഹത്തോട് പറയുന്നു.
അദ്ദേഹം എല്ലാം കൊട്ടയിൽ വെക്കുന്നു.
ഇവ വളരെ നല്ല പച്ചക്കറികളാണ്.
എനിക്ക് സന്തോഷമുണ്ട്.
