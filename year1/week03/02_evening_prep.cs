Teď jsem doma.
Tady je můj pokoj.
Je to malý pokoj.
Mám novou rostlinu.
Stojí na mém psacím stole.
Je večer a je leden.
Moje okno je velmi tmavé.
Venku je úplně černo.
Mám lampu a šálek čaje.
Rozsvěcím svou lampu.
Teď je můj pokoj teplý a světlý.
Můj čaj je také teplý.
Sedím u svého psacího stolu.
Mám tady svůj počítač.
Otevírám svůj počítač.
Teď volám své rodině do Mexika.
Těším se, až je uvidím.
