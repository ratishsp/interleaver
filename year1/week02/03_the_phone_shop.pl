To moja przerwa na lunch.
Jestem w sklepie z telefonami.
Mam telefon z Meksyku.
Sprzedawcą jest młody mężczyzna.
„Czy ma pan duńską kartę SIM?” – pytam.
„Tak, oczywiście” – odpowiada.
Daję mu mój telefon.
Wkłada kartę SIM do telefonu.
Telefon jest już gotowy.
„Pani nowy numer to dwanaście, trzydzieści cztery, pięćdziesiąt sześć, siedemdziesiąt osiem” – mówi.
Mam w torbie notatnik.
Zapisuję numer.
„Dwanaście, trzydzieści cztery, pięćdziesiąt sześć, siedemdziesiąt osiem” – powtarzam.
„Tak, dokładnie” – mówi sprzedawca.
„Dziękuję za pomoc” – mówię.
Mam teraz duński numer!
Wkładam telefon do kieszeni.
