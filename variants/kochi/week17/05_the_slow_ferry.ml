ഞാൻ സ്വന്തം ടിക്കറ്റ് വാങ്ങി ബോട്ടിൽ കയറി.
അത് ഒരു പഴയ ബോട്ടായിരുന്നു.
എങ്കിലും അത് വളരെ മനോഹരമായിരുന്നു.
ഞാൻ ജനലിനടുത്ത് ഇരുന്നു.
പതുക്കെ, ബോട്ട് ജെട്ടിയിൽ നിന്ന് നീങ്ങിത്തുടങ്ങി.
അത് വളരെ പതുക്കെ പോകുന്ന ഒരു ഫെറിയായിരുന്നു.
കായലിന്റെ ഇരുവശത്തും വലിയ തെങ്ങുകൾ ഉണ്ടായിരുന്നു.
ഇടതൂർന്ന മരങ്ങൾക്കിടയിലൂടെ ബോട്ട് സുഗമമായി നീങ്ങി.
അവിടെ വളരെ നിശ്ശബ്ദമായിരുന്നു.
വെള്ളത്തിന്റെ ശബ്ദം കേൾക്കാൻ നല്ല രസമായിരുന്നു.
ഉച്ചയ്ക്ക് മുൻപ്, വേനൽക്കാലത്തെ ചൂട് ഭയങ്കരമായിരുന്നു.
എന്നാൽ അവിടെ വെള്ളത്തിൽ നിന്ന് ഒരു നല്ല കാറ്റ് വന്നു.
ആ തണുത്ത കാറ്റ് ഒടുവിൽ കനത്ത ചൂട് മാറ്റി.
ഞാൻ കണ്ണുകൾ അടച്ച് ആ കാറ്റ് ആസ്വദിച്ചു.
ഞാൻ ബഹളമുള്ള നഗരത്തെക്കുറിച്ച് പൂർണ്ണമായി മറന്നു.
ഈ ബോട്ട് യാത്ര വളരെ ശാന്തമായിരുന്നു.
