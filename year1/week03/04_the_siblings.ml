ഇപ്പോൾ എന്റെ സ്ക്രീനിൽ രണ്ട് പുതിയ മുഖങ്ങളുണ്ട്.
അതെന്റെ അനിയത്തി സോഫിയയും ചേട്ടൻ ഡീഗോയുമാണ്.
അവർ ചിരിക്കുകയും പരസ്പരം ചെറുതായി തള്ളുകയും ചെയ്യുന്നു.
"ഹലോ അനിയത്തീ, ചേട്ടാ!" ഞാൻ സന്തോഷത്തോടെ പറയുന്നു.
"ഹായ് മായ," ഡീഗോ പറയുന്നു.
എന്റെ ചേട്ടന്റെ മുഖത്ത് വലിയൊരു ചിരിയുണ്ട്.
"ഡെന്മാർക്കിൽ തണുപ്പുണ്ടോ?" അവൻ ചോദിക്കുന്നു.
"ഇതൊരു തണുപ്പുള്ള മഞ്ഞുകാലമാണോ?"
"അതെ, നല്ല തണുപ്പുള്ള മഞ്ഞുകാലമാണ്," ഞാൻ ചിരിക്കുന്നു.
"പക്ഷേ, എനിക്ക് ചൂടുള്ള ഒരു മുറിയും ഒരു കപ്പ് ചായയുമുണ്ട്."
ഇപ്പോൾ സോഫിയ സ്ക്രീനിന് മുന്നിലേക്ക് വലിയൊരു സാധനം ഉയർത്തിക്കാണിക്കുന്നു.
അതൊരു വലിയ പുസ്തകമാണ്.
"സോഫിയാ, നിന്റെ കയ്യിലുള്ളത് പുതിയ പുസ്തകമാണോ?" ഞാൻ ചോദിക്കുന്നു.
"അതെ, ഇതെന്റെ പുതിയ പുസ്തകമാണ്," എന്റെ അനിയത്തി അഭിമാനത്തോടെ പറയുന്നു.
"ഇത് എന്റെ യൂണിവേഴ്സിറ്റിയിലെ പുസ്തകമാണ്."
"ഇത് നല്ല കട്ടിയുള്ള ഒരു പുസ്തകമാണ്!"
ഞാൻ എന്റെ ചേട്ടനെയും അനിയത്തിയെയും നോക്കി ചിരിക്കുന്നു.
മെക്സിക്കോയിലുള്ള എന്റെ കുടുംബത്തെ ഞാൻ മിസ്സ് ചെയ്യുന്നു.
പക്ഷേ, അവർ ഇതാ എന്റെ ചെറിയ സ്ക്രീനിലുണ്ട്.
