Wysiadam z autobusu w pobliżu mojej pracy.
Trzymam mocno mój szalik.
Pogoda jest dzisiaj bardzo gwałtowna.
Idę ulicą.
Nagle robi się bardzo wietrznie.
Silny wiatr wieje prosto na mnie.
Mam w ręku otwarty parasol.
Ale wiatr jest zbyt silny.
Szybko staje się to problemem.
Parasol lata z boku na bok.
Teraz to niemożliwe.
Siłuję się z nim.
W końcu zamykam parasol.
Bez niego jest bardzo zimno.
Deszcz uderza mnie w twarz.
Śpieszę się, przedzierając się przez wiatr.
Wejście do biura jest tuż przede mną.
Wchodzę do budynku.
Na szczęście w środku jest ciepło i cicho.
