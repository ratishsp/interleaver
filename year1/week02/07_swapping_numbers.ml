ഞാൻ എന്റെ അപ്പാർട്ട്മെന്റിന് സമീപം നിൽക്കുകയാണ്.
ഒരു കറുവപ്പട്ട പേസ്ട്രിയുള്ള ഒരു ബാഗ് എന്റെ കയ്യിലുണ്ട്.
എന്റെ അയൽവാസി നീന വാതിൽക്കൽ ഉണ്ട്.
അവൾ നിറപുഞ്ചിരിയോടെ ഹലോ പറയുന്നു.
"ഹലോ മായാ, നിനക്കിപ്പോൾ ഒരു ഡാനിഷ് നമ്പർ ഉണ്ടോ?" നീന ചോദിക്കുന്നു.
"അതെ, എനിക്കൊരു പുതിയ ഫോൺ നമ്പർ ഉണ്ട്," ഞാൻ മറുപടി നൽകുന്നു.
"അത് നന്നായി," അവൾ പറയുന്നു.
എന്റെ ഫോൺ എന്റെ കയ്യിലുണ്ട്.
"നിന്റെ നമ്പർ എന്താണ്?" ഞാൻ ചോദിക്കുന്നു.
"എന്റെ നമ്പർ എൺപത്തിഏഴ്, അറുപത്തിയഞ്ച്, നാൽപ്പത്തിമൂന്ന്, ഇരുപത്തിയൊന്ന് ആണ്," നീന പറയുന്നു.
ഞാൻ അവളുടെ നമ്പർ എന്റെ ഫോണിൽ കുറിച്ച് വെക്കുന്നു.
"പിന്നെ എന്റെ നമ്പർ പന്ത്രണ്ട്, മുപ്പത്തിനാല്, അമ്പത്തിയാറ്, എഴുപത്തിയെട്ട് ആണ്," ഞാൻ പറയുന്നു.
നീന എന്റെ നമ്പർ അവളുടെ ഫോണിൽ സേവ് ചെയ്യുന്നു.
ഇപ്പോൾ ഞങ്ങൾ തമ്മിൽ കോൺടാക്റ്റ് ഉണ്ട്.
ഞങ്ങൾ ഒരുമിച്ച് അകത്തേക്ക് പോകുന്നു.
എന്റെ പുതിയ സുഹൃത്തിനെ ഓർത്ത് ഞാൻ വളരെ സന്തോഷവതിയാണ്.
