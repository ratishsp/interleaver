Jsem doma ve své kuchyni.
Obléknu si zástěru.
Čtu si recept na telefonu.
Recept je velmi srozumitelný.
Píše se tam: Nejprve nakrájejte cibule velmi najemno.
Potom dejte maso do velké mísy.
Následně přidejte vejce, trochu mouky a mléka.
Nakonec vše důkladně promíchejte.
Najdu si prkénko a ostrý nůž.
Nakrájím ty dvě žluté cibule na malé kousky.
Trochu mi slzí oči.
Otevřu balíček s pěti sty gramy mletého vepřového masa.
Dám maso do své velké modré mísy.
Potom přidám cibule k masu.
Rozklepnu vejce do mísy.
Následně přidám trochu mouky a mléka.
Vezmu velkou lžíci a vše promíchám.
Masová směs vypadá opravdu dobře.
První krok byl velmi snadný.
