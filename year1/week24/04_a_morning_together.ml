പ്രഭാതഭക്ഷണത്തിന് ശേഷം എനിക്ക് ധാരാളം സമയമുണ്ട്.
ഞാൻ സാധാരണയായി ശനിയാഴ്ചകളിൽ ഒരു കഫേയിൽ വോളണ്ടിയറായി ജോലി ചെയ്യാറുണ്ട്.
എന്നാൽ ലുഡ്‌വിഗ് തനിച്ചാകാൻ പാടില്ല.
ഭാഗ്യവശാൽ ഇന്ന് എനിക്ക് കഫേയിൽ നിന്ന് അവധിയാണ്.
ഞാൻ കഴിഞ്ഞ ആഴ്ച അവരുമായി അത് ക്രമീകരിച്ചിരുന്നു.
ഇപ്പോൾ ലുഡ്‌വിഗിനും എനിക്കും ഈ പ്രഭാതം മുഴുവൻ ഒരുമിച്ചുണ്ട്.
ഞങ്ങൾ എന്റെ കെട്ടിടത്തിന് പിന്നിലെ മുറ്റത്തേക്ക് പോകുന്നു.
ഞാൻ അവന്റെ ചെറിയ പന്ത് പുറത്തെടുക്കുന്നു.
"പന്തിലേക്ക് നോക്കൂ, ലുഡ്‌വിഗ്!" ഞാൻ അവനോട് പറയുന്നു.
ഞാൻ അത് പുല്ലിന് മുകളിലൂടെ എറിയുന്നു.
"അതെടുത്തുകൊണ്ട് വാ!" ഞാൻ വിളിച്ചുപറയുന്നു.
അവൻ വേഗത്തിൽ ഓടിപ്പോയി പന്ത് പിടിക്കുന്നു.
"ഇങ്ങോട്ട് വാ!" ഞാൻ വിളിക്കുന്നു.
അവൻ സന്തോഷത്തോടെ എന്റെ അടുത്തേക്ക് ഓടിവരുന്നു.
"അതെനിക്ക് തരൂ," ഞാൻ മൃദുവായി പറയുന്നു.
അവൻ പന്ത് താഴെയിടുന്നു, ഞാൻ അവനെ തലോടുന്നു.
"നീ ഒരു നല്ല നായയാണ്," എന്ന് പറഞ്ഞ് ഞാൻ പുഞ്ചിരിക്കുന്നു.
ഞാൻ അത് വീണ്ടും എറിയുന്നു, അവൻ അത് എടുത്തുകൊണ്ടുവരുന്നു.
ഈ വാരാന്ത്യം മുഴുവൻ ഞാൻ അവനെ നന്നായി നോക്കണം.
അവനോടൊപ്പം വീട്ടിൽ തങ്ങിയതിൽ എനിക്ക് വലിയ സന്തോഷമുണ്ട്.
