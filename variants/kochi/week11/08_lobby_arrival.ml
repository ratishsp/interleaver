ഞാൻ അപ്പാർട്ട്മെന്റിൽ എത്തുന്നു.
പുറത്ത് ഇപ്പോഴും നല്ല മഴ പെയ്യുന്നു.
ഞാൻ വേഗം ലോബിയിലേക്ക് കയറുന്നു.
അവിടെ മഴയില്ല.
എന്റെ അയൽക്കാരി അനിത അവിടെ നിൽക്കുന്നുണ്ട്.
അനിത എന്നെ നോക്കി ചിരിക്കുന്നു.
"മായേ, നല്ല മഴ പെയ്യുന്നു," അനിത പറയുന്നു.
ഞാൻ എന്റെ നനഞ്ഞ കുട മടക്കുന്നു.
"അതെ, കൊച്ചിയിൽ ഇത് എന്റെ ആദ്യത്തെ മഴയാണ്," ഞാൻ പറയുന്നു.
"നഗരത്തിൽ ഇപ്പോൾ വലിയ ചൂടാണ്," അനിത പറയുന്നു.
"ഈ മഴ വലിയൊരു ആശ്വാസമാണ്."
"പകൽ വലിയ വെയിലാണ്," ഞാൻ പറയുന്നു.
"അതുകൊണ്ട് ഈ മഴ നല്ലതാണ്."
"നാളെയും മഴ പെയ്യുമോ?" ഞാൻ ചോദിക്കുന്നു.
"അതെ, നാളെയും മഴ പെയ്യും," അനിത പറയുന്നു.
"ഇനി നഗരത്തിൽ ചൂട് കുറയും."
ലോബിയിലേക്ക് നല്ല തണുത്ത കാറ്റ് വരുന്നു.
ഞങ്ങൾ കുറച്ചുനേരം മഴയും കാറ്റും ആസ്വദിക്കുന്നു.
