Jest niedzielne popołudnie i ktoś puka do drzwi.
Ludwig wybiega na korytarz i szczeka radośnie.
Otwieram drzwi, a na zewnątrz stoi Nina ze swoją torbą weekendową.
„Cześć Maya, bardzo dziękuję za pomoc” – mówi i uśmiecha się.
Merda ogonem i skacze na nią.
„Zejdź, Ludwig” – mówi Nina i głaszcze go.
„Był naprawdę grzecznym psem” – mówię jej.
Nina śmieje się i bierze jego smycz z małego stolika.
„Poszłaś z nim na spacer do psiego lasu?” – pyta.
„Tak, i bardzo mu się podobało” – odpowiadam.
Daję jej resztę karmy dla psa.
„Proszę, oto reszta”.
„Bardzo chętnie zaopiekuję się nim znowu innym razem”.
„Jasne” – mówi Nina.
„Chodź, Ludwig, musimy wracać do domu” – mówi Nina do psa.
Macham im obojgu na pożegnanie.
W mieszkaniu jest nagle bardzo cicho bez niego.
