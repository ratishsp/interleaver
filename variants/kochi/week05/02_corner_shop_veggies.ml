ഞാൻ ചെറിയ പച്ചക്കറിക്കടയിലേക്ക് നടക്കുന്നു.
ഈ കട എന്റെ ഫ്ലാറ്റിന് അടുത്താണ്.
ഞാൻ കടക്കാരനെ കാണുന്നു.
അദ്ദേഹം വളരെ നല്ല ഒരു മനുഷ്യനാണ്.
ഞാൻ അദ്ദേഹത്തെ നോക്കി കൈ വീശുന്നു.
അദ്ദേഹം എന്നെ നോക്കി ചിരിക്കുന്നു.
"നമസ്കാരം," കടക്കാരൻ പറയുന്നു.
"നമസ്കാരം," ഞാൻ മറുപടി പറയുന്നു.
കടയിൽ ധാരാളം പച്ചക്കറികൾ ഉണ്ട്.
എനിക്ക് തക്കാളിയും സവാളയും വേണം.
എന്റെ സോസിന് എനിക്ക് ഇത് വേണം.
എനിക്ക് തക്കാളി വളരെ ഇഷ്ടമാണ്.
ഞാൻ അഞ്ച് തക്കാളികൾ എടുക്കുന്നു.
അവ നല്ല ചുവന്ന തക്കാളികളാണ്.
എനിക്ക് വലിയ സവാളയും വേണം.
എനിക്ക് സവാളയുടെ രുചി ഇഷ്ടമാണ്.
ഞാൻ ആ പച്ചക്കറികൾ ഒരു കുട്ടയിൽ വയ്ക്കുന്നു.
