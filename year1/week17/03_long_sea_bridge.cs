Vlak jel rychle krajinou.
Seděla jsem tiše na svém místě.
Měla jsem opravdu dobré místo u okna.
Po chvíli jsme konečně dojeli k pobřeží.
Vlak vjel na velmi dlouhý most přes moře.
Najednou byla všude kolem nás jen voda.
Most byl vysoko nad vodou.
Dívala jsem se ven velkým oknem.
Voda pod námi byla velmi modrá.
Obdivovala jsem ten krásný, otevřený výhled.
Hluboko dole jsem viděla několik malých lodí.
Vypadaly skoro jako hračky.
Nebe bylo světle modré a úplně bez mraků.
Bylo to skoro jako letět nad mořem.
Vyndala jsem z tašky fotoaparát.
Udělala jsem pár fotek těch malých lodí.
Nikdy jsem nic podobného neviděla.
Potom jsem fotoaparát schovala a jen si užívala cestu.
