Podchodzę do lady w piekarni.
Zapach jest bardzo przyjemny.
Lubię ciastka.
A naprawdę lubię bułeczki cynamonowe.
Za ladą stoi piekarz.
Piekarz patrzy na mnie.
Uśmiecha się.
„Co podać?” pyta piekarz.
Wskazuję na bułeczkę cynamonową.
Ciastko wygląda pysznie.
„Poproszę bułeczkę cynamonową,” mówię.
„Tak, oczywiście,” mówi piekarz.
Bierze ciastko.
Wkłada ciastko do torebki.
Podaje torebkę przez ladę.
„Proszę bardzo,” mówi.
Biorę torebkę.
„Bardzo dziękuję,” mówię.
Wkładam torebkę do koszyka.
