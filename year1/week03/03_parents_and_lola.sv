Det ringer ett par gånger.
Skärmen lyser upp.
Jag ser ett vardagsrum.
Det är sol, och vardagsrummet är mycket ljust.
Jag ser två personer.
Det är min mamma och min pappa.
De ler mycket och vinkar till mig.
"Hej mamma och pappa!" säger jag högt.
"Hej, Maya," säger min pappa.
"Hur går det?"
"Det går bra," svarar jag glatt.
Plötsligt hör jag ett ljud.
Det är ett litet skall.
"Åh, jag hör en hund!" säger jag och skrattar.
En liten hund hoppar upp på en soffa.
Den tittar in i kameran.
"Där är min hund!"
"Hej, Lola," säger jag.
Lola viftar på svansen.
"Ja, det är din hund," säger min mamma med ett leende.
Jag älskar min familj.
Det är härligt att se dem alla.
