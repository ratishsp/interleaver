ഞാൻ കടയുടെ മുൻവശത്തേക്ക് നടക്കുന്നു.
അവിടെ ഒരുപാട് സാധനങ്ങൾ ഉണ്ട്.
ഞാൻ വലിയ ഒരു വെള്ള കോട്ടൺ സ്കാർഫ് കാണുന്നു.
അത് വളരെ മനോഹരമായ ഒരു സ്കാർഫ് ആണ്.
ആ കോട്ടൺ സ്കാർഫ് വളരെ മൃദു ആണ്.
ഞാൻ ആ സ്കാർഫ് കയ്യിൽ എടുക്കുന്നു.
ഒരു ജീവനക്കാരൻ അവിടെ നിൽക്കുന്നുണ്ട്.
ഞാൻ അയാളെ നോക്കുന്നു.
"ഈ സ്കാർഫിന്റെ വില എന്താണ്?" ഞാൻ ചോദിക്കുന്നു.
"ഇതിന് നൂറ് രൂപ ആണ്, മാഡം," അയാൾ പറയുന്നു.
നൂറ് രൂപ ഒരു ചെറിയ വില ആണ്.
കൊച്ചിയിൽ ഇപ്പോൾ നല്ല വെയിൽ ആണ്.
ഞാൻ ബസ്സിലാണ് ഓഫീസിലേക്ക് പോകുന്നത്.
ഓഫീസിൽ പോകുമ്പോൾ എനിക്ക് ഈ സ്കാർഫ് ധരിക്കാം.
ഈ വലിയ സ്കാർഫ് വെയിൽ തടയാൻ നല്ലതാണ്.
"ഞാൻ ഇത് വാങ്ങുന്നു," ഞാൻ അയാളോട് പറയുന്നു.
അയാൾ സന്തോഷത്തോടെ തലയാട്ടുന്നു.
