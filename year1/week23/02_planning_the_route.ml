ഞാൻ ജോലിയിൽ നിന്ന് ഒരു ചെറിയ ഇടവേള എടുക്കുകയാണ്.
മാപ്പ് നോക്കാൻ ഞാൻ എന്റെ ഫോൺ പുറത്തെടുക്കുന്നു.
എനിക്ക് ഈവയുടെ വിലാസം കണ്ടുപിടിക്കണം.
അവൾ താമസിക്കുന്നത് നഗരത്തിന്റെ തീർത്തും മറ്റേ അറ്റത്താണ്.
സ്ക്രീനിലെ റൂട്ട് ഞാൻ ശ്രദ്ധയോടെ നോക്കുന്നു.
ഇത് ശരിക്കും വളരെ ദൂരെയാണ്.
ഒരു കപ്പ് കാപ്പി എടുക്കാൻ പീറ്റർ ബ്രേക്ക് റൂമിലേക്ക് വരുന്നു.
അവൻ എന്റെ തോളിലൂടെ നോക്കി ഞാൻ എന്താണ് ചെയ്യുന്നതെന്ന് ചോദിക്കുന്നു.
"വെള്ളിയാഴ്ച ഞാൻ ഈവയെ സന്ദർശിക്കാൻ പോവുകയാണ്," ഞാൻ വിശദീകരിക്കുന്നു.
"നീ സൈക്കിളിലാണോ അങ്ങോട്ട് പോകുന്നത്?" അവൻ ചോദിക്കുന്നു.
ഞാൻ ഒരു നിമിഷം അതിനെക്കുറിച്ച് ചിന്തിക്കുന്നു.
ഞാൻ മിക്കവാറും ബസ്സിൽ പോകുമെന്നാണ് തോന്നുന്നത്.
സൈക്കിളിൽ പോകാൻ ഇത് വളരെ ദൂരമാണെന്ന് എനിക്ക് തോന്നുന്നു.
"ഇല്ല, ഞാൻ ബസ്സിൽ പോകാനാണ് ഉദ്ദേശിക്കുന്നത്," ഞാൻ അവന് മറുപടി നൽകുന്നു.
"എങ്കിൽ യാത്രയിൽ നിനക്ക് വിശ്രമിക്കുകയും ചെയ്യാമല്ലോ," ഒരു പുഞ്ചിരിയോടെ പീറ്റർ പറയുന്നു.
അവൻ പറഞ്ഞത് തികച്ചും ശരിയാണ്.
ഞാൻ ആപ്പ് ക്ലോസ് ചെയ്ത് ഫോൺ തിരികെ എന്റെ പോക്കറ്റിൽ വയ്ക്കുന്നു.
ഇപ്പോൾ എന്റെ റൂട്ട് പ്ലാൻ ചെയ്തു കഴിഞ്ഞു.
സന്തോഷകരമായ ഒരു സായാഹ്നത്തിനായി ഞാൻ കാത്തിരിക്കുകയാണ്.
