വൈകുന്നേരം ഞാൻ എന്റെ ഫ്ലാറ്റിൽ എത്തുന്നു.
ഞാൻ എന്റെ അനിയത്തി സോഫിയയെ വീഡിയോ കോൾ ചെയ്യുന്നു.
അവൾ മെക്സിക്കോയിൽ വീട്ടിലാണ്.
"ചേച്ചീ, കഫേയിലെ ജോലി എങ്ങനെ ഉണ്ടായിരുന്നു?" സോഫിയ ചോദിക്കുന്നു.
"വളരെ നല്ലൊരു ദിവസമായിരുന്നു, സോഫിയ," ഞാൻ പറയുന്നു.
ഞാൻ എന്റെ ആദ്യത്തെ ഷിഫ്റ്റിനെക്കുറിച്ച് അവളോട് പറയുന്നു.
"ഞാൻ ഇന്ന് കോഫി ഉണ്ടാക്കാൻ പഠിച്ചു."
സോഫിയ ചിരിച്ചുകൊണ്ട് ചോദിക്കുന്നു, "ചേച്ചി തെറ്റുകൾ വരുത്തിയോ?"
"അതെ, ഞാൻ ഇന്ന് ചില തെറ്റുകൾ വരുത്തിയിട്ടുണ്ട്," ഞാൻ മറുപടി നൽകുന്നു.
"പക്ഷേ, ആ തെറ്റുകളിൽ നിന്ന് പുതിയ കാര്യങ്ങൾ ചെയ്യാൻ ഞാൻ പഠിച്ചു."
"രാവിലെ കഫേയിൽ നല്ല തിരക്കായിരുന്നു."
"എന്റെ ഒന്നാമത്തെ കസ്റ്റമർ ഒരു നല്ല മനുഷ്യനായിരുന്നു."
"അദ്ദേഹം എന്നോട് ഒരു കാപ്പുച്ചീനോ ഓർഡർ ചെയ്തു."
സോഫിയ കൈയടിക്കുന്നു.
"പിന്നെ വേറെ എന്തൊക്കെ ചെയ്തു?" അവൾ ചോദിക്കുന്നു.
"കസ്റ്റമേഴ്സിന്റെ ഓർഡറുകൾ എടുക്കാനും ഞാൻ പഠിച്ചു."
"അതൊരു നല്ല അനുഭവമായിരുന്നു."
"എന്റെ രണ്ടാമത്തെ ഷിഫ്റ്റിനായി അടുത്ത ശനിയാഴ്ചയും അവിടെ പോകാൻ ഞാൻ തീരുമാനിച്ചിട്ടുണ്ട്," ഞാൻ പറയുന്നു.
