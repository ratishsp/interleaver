Eva nalévá kávu do dvou velkých šálků.
Sedáme si na měkkou pohovku v obýváku.
„Jak se ti teď ve městě daří?“ ptá se Eva.
Dám si doušek teplé kávy.
Říkám jí, že mám pocit, že můj nový život je vlastně opravdu krásný.
„Konečně jsem se tu dobře zabydlela,“ říkám s úsměvem.
„To ráda slyším,“ odpovídá.
„Taky v kanceláři opravdu tvrdě pracuješ na našem projektu.“
„Ano, ale hodlám si teď brát víc volna,“ říkám.
„Budu si město o víkendech mnohem víc užívat.“
„To moc dobře chápu,“ říká Eva.
Dlouho si povídáme o našich dalších kolezích a o práci.
Smějeme se a vyprávíme si spoustu historek.
Usmívám se na ni přes šálek kávy.
Říkám, že doufám, že se budeme i dál vídat mimo práci.
„To rozhodně budeme,“ odpovídá radostně.
Myslím, že spolu asi zažijeme spoustu zábavných večerů.
