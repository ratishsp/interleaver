ഞാൻ ഇടനാഴിയിൽ നിൽക്കുകയാണ്.
അവിടെ നിശബ്ദമാണ്.
ഒരു വാതിൽ തുറക്കുന്നു.
ഒരു സ്ത്രീ എന്നെ നോക്കി പുഞ്ചിരിക്കുന്നു.
"ഹായ്," അവൾ പറയുന്നു.
"നിങ്ങളുടെ പേരെന്താണ്?" അവൾ ചോദിക്കുന്നു.
"എന്റെ പേര് മായ എന്നാണ്," ഞാൻ മറുപടി പറയുന്നു.
"നിങ്ങൾ എവിടെ നിന്നാണ് വരുന്നത്?" അവൾ ചോദിക്കുന്നു.
"ഞാൻ മെക്സിക്കോയിൽ നിന്നാണ് വരുന്നത്," ഞാൻ പറയുന്നു.
"ഡെന്മാർക്കിലേക്ക് സ്വാഗതം," ആ സ്ത്രീ പറയുന്നു.
"എന്റെ പേര് നീന എന്നാണ്," അവൾ പറയുന്നു.
"ഞാൻ നിങ്ങളുടെ അയൽക്കാരിയാണ്."
നീന വളരെ സൗഹാർദ്ദമുള്ളവളാണ്.
അവളുടെ മുഖത്ത് ഒരു പുഞ്ചിരിയുണ്ട്.
"ഇതാണ് എന്റെ വാതിൽ," അവൾ പറയുന്നു.
"സഹായിക്കുന്നതിൽ എനിക്ക് സന്തോഷമേയുള്ളൂ."
"നിങ്ങൾ ഒന്ന് മുട്ടിയാൽ മതി," നീന പറയുന്നു.
"വളരെ നന്ദി, നീന," ഞാൻ മറുപടി പറയുന്നു.
എനിക്ക് വളരെ സന്തോഷമുണ്ട്.
ഇപ്പോൾ കോപ്പൻഹേഗനിൽ എനിക്കൊരു സുഹൃത്തുണ്ട്.
