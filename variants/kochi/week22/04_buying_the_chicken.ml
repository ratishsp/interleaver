പച്ചക്കറി വാങ്ങിയ ശേഷം ഞാൻ അടുത്തുള്ള ഇറച്ചിക്കടയിലേക്ക് പോകുന്നു.
ഞായറാഴ്ച രാവിലെ അവിടെ നല്ല തിരക്കാണ്.
എന്നാലും കടയിൽ ആവശ്യത്തിന് കോഴിയിറച്ചി ഉണ്ട്.
ഞാൻ കടക്കാരനോട് കോഴിയിറച്ചി ചോദിക്കുന്നു.
"ചേട്ടാ, എനിക്ക് അര കിലോ കോഴിയിറച്ചി വേണം," ഞാൻ പറയുന്നു.
അയാൾ അര കിലോ ഇറച്ചി എടുക്കുന്നു.
"ഇത് കറി വെക്കാനാണോ?" അയാൾ എന്നോട് ചോദിക്കുന്നു.
"അതെ, കറി വെക്കാനാണ്," ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ അയാളോട് പറയുന്നു, "ആദ്യം ഇത് നന്നായി വൃത്തിയാക്കണം."
"അതിനുശേഷം കറിക്ക് വേണ്ടി ചെറിയ കഷണങ്ങളായി മുറിക്കണം."
കറിക്ക് ചെറിയ കഷണങ്ങളാണ് എപ്പോഴും നല്ലത്.
അയാൾ തലകുലുക്കുന്നു.
അയാൾ വേഗത്തിൽ ഇറച്ചി വെട്ടി ചെറിയ കഷണങ്ങളാക്കുന്നു.
പിന്നെ അയാൾ അത് ഒരു കവറിലാക്കി എനിക്ക് തരുന്നു.
ഞാൻ അയാൾക്ക് നൂറ്റി അറുപത് രൂപ കൊടുക്കുന്നു.
ഞാൻ കോഴിയിറച്ചി എന്റെ സഞ്ചിയിൽ വെക്കുന്നു.
പുറത്ത് ഇപ്പോഴും നല്ല മഴയുണ്ട്.
ഞാൻ കുട നിവർത്തി വേഗം വീട്ടിലേക്ക് നടക്കുന്നു.
ഇനി എനിക്ക് കറി ഉണ്ടാക്കാൻ തുടങ്ങണം.
