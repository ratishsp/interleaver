ആ സ്ത്രീ എന്നെ നോക്കി ചിരിക്കുന്നു.
എനിക്ക് വഴി തെറ്റി എന്ന് അവർക്ക് മനസ്സിലാകുന്നു.
അവർ എന്റെ കൂടെ നടക്കുന്നു.
ഞങ്ങൾ ആ മാർക്കറ്റിന്റെ അവസാനം എത്തുന്നു.
ദൂരെ ഒരു വലിയ കെട്ടിടം ഉണ്ട്.
അവർ ആ കെട്ടിടത്തിലേക്ക് വിരൽ ചൂണ്ടുന്നു.
എന്നിട്ട് അവർ എന്നോട് പറയുന്നു.
"ആ വലിയ കെട്ടിടം കാണുന്നുണ്ടോ?"
"ആ കെട്ടിടത്തിലേക്ക് നേരെ പോകൂ."
"വഴിയിൽ ഇടത്തോട്ട് തിരിയരുത്."
"നേരെ തന്നെ നടക്കൂ."
"അവിടെ നിന്ന് വലത്തോട്ട് തിരിയൂ."
"മറൈൻ ഡ്രൈവ് അവിടെയാണ്."
എനിക്ക് വലിയ ആശ്വാസമാകുന്നു.
ഞാൻ അവരോട് നന്ദി പറയുന്നു.
അവർ തിരികെ മാർക്കറ്റിലേക്ക് നടക്കുന്നു.
ഞാൻ ആ വലിയ കെട്ടിടത്തിലേക്ക് നേരെ നടക്കുന്നു.
