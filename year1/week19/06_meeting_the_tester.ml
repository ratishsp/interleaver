ഓഫീസിലെ അടുത്ത ദിവസമാണിത്.
ഞങ്ങളുടെ സോഫ്റ്റ്‌വെയർ ടെസ്റ്ററായ മാഡ്‌സിന്റെ അടുത്താണ് ഞാൻ ഇരിക്കുന്നത്.
അദ്ദേഹം പുതിയ സ്ക്രീനുകളിലേക്ക് നോക്കുന്നു.
അദ്ദേഹം മൗസ് ഉപയോഗിച്ച് വളരെ വേഗത്തിൽ ക്ലിക്ക് ചെയ്യുന്നു.
പെട്ടെന്ന് അദ്ദേഹം നിർത്തുന്നു.
അദ്ദേഹം ഇതിനകം ഒരു ചെറിയ തെറ്റ് കണ്ടുപിടിച്ചു കഴിഞ്ഞു.
അദ്ദേഹം എന്നെ നോക്കി ചെറുതായി ചിരിക്കുന്നു.
"കാര്യങ്ങൾ തകർക്കുക എന്നതാണ് എന്റെ ജോലി," അദ്ദേഹം പറയുന്നു.
"നമ്മുടെ ഉപയോക്താക്കൾക്ക് മുമ്പ് ഞാൻ തെറ്റുകൾ കണ്ടെത്തണം."
അദ്ദേഹം അഞ്ച് വർഷമായി ഒരു ടെസ്റ്ററായി ജോലി ചെയ്യുന്നു.
അദ്ദേഹം പലവിധത്തിലുള്ള നിരവധി പ്രോജക്റ്റുകൾ ടെസ്റ്റ് ചെയ്തിട്ടുണ്ട്.
അതുകൊണ്ടാണ് അദ്ദേഹം ഇത്ര വേഗത്തിൽ പ്രശ്നങ്ങൾ കണ്ടെത്തുന്നത്.
ഞാൻ എന്റെ കമ്പ്യൂട്ടറിലെ ആ തെറ്റ് നോക്കുന്നു.
ഭാഗ്യവശാൽ, അതൊരു ചെറിയ പ്രശ്നം മാത്രമാണ്.
ഞാൻ ഉടൻ തന്നെ കോഡ് ശരിയാക്കുന്നു.
അദ്ദേഹം പ്രോഗ്രാം ഒരിക്കൽ കൂടി ടെസ്റ്റ് ചെയ്യുന്നു.
ഇപ്പോൾ എല്ലാം തികച്ചും കൃത്യമായി പ്രവർത്തിക്കുന്നു.
അദ്ദേഹത്തിന്റെ സഹായത്തിൽ എനിക്ക് വളരെ സന്തോഷമുണ്ട്.
