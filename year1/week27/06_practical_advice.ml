ഞാൻ ആ പെട്ടി തറയിൽ വെച്ചിട്ട് അവളോട് വീണ്ടും നന്ദി പറയുന്നു.
"അത് സാരമില്ല," നീന മറുപടി പറയുന്നു.
ഇന്ന് രാത്രി പോർട്ടൽ കുറച്ചു പതുക്കെയായിരുന്നു എന്ന് ഞാൻ അവളോട് പറയുന്നു.
"അതെ, ഇത് സാധാരണയായി വളരെ പതുക്കെയാണ്," നീന ചിരിച്ചുകൊണ്ട് പറയുന്നു.
എന്റെ സ്ഥിരീകരണം സേവ് ചെയ്തിട്ടുണ്ടോ എന്ന് അവൾ ചോദിക്കുന്നു.
"നിങ്ങളുടെ സ്ഥിരീകരണം എപ്പോഴും ഡൗൺലോഡ് ചെയ്യാൻ ഓർക്കണം," അവൾ ഉപദേശിക്കുന്നു.
അതെന്തുകൊണ്ടാണ് പ്രധാനമായിരിക്കുന്നതെന്ന് ഞാൻ അവളോട് ചോദിക്കുന്നു.
അവരുടെ വെബ്സൈറ്റിലെ പഴയ സന്ദേശങ്ങൾ പലപ്പോഴും ഡിലീറ്റ് ചെയ്യപ്പെടാറുണ്ടെന്ന് നീന വിശദീകരിക്കുന്നു.
കുറച്ചു സമയത്തിനുശേഷം സിസ്റ്റം യാന്ത്രികമായി അവ ഡിലീറ്റ് ചെയ്യുന്നു.
ഞാൻ തലയാട്ടി വീണ്ടും എന്റെ ഫോണിൽ പോർട്ടൽ തുറക്കുന്നു.
ഞാൻ ആ ഫയൽ കണ്ടെത്തുന്നു, അത് ഉടൻ തന്നെ ഡൗൺലോഡ് ആകുന്നു.
"അപ്പോൾ ഡോക്യുമെന്റ് സുരക്ഷിതമായി സേവ് ചെയ്തു," ഞാൻ ആശ്വാസത്തോടെ പറയുന്നു.
നീന സന്തോഷത്തോടെ ചിരിക്കുകയും എനിക്ക് ഒരു ശുഭസായാഹ്നം നേരുകയും ചെയ്യുന്നു.
ഞാനും അവൾക്ക് അതുതന്നെ നേരുന്നു.
അവൾ ഇടനാഴിയിലൂടെ നടന്നുപോകുന്നു, ഞാൻ എന്റെ വാതിൽ അടയ്ക്കുന്നു.
മിടുക്കിയും സഹായിക്കാൻ മനസ്സുമുള്ള ഒരു അയൽക്കാരിയെ ലഭിക്കുന്നത് ശരിക്കും വളരെ നല്ല കാര്യമാണ്.
