ട്രെയിൻ സ്റ്റേഷനിൽ എത്തി.
ഞാൻ വേഗം ട്രെയിനിൽ കയറി.
എനിക്ക് ഒരു വിൻഡോ സീറ്റ് കിട്ടി.
ഞാൻ ആ സീറ്റിൽ ഇരുന്നു.
കുറച്ചുകഴിഞ്ഞ്, ഒരു കുടുംബം എന്റെ എതിർവശത്ത് വന്നിരുന്നു.
ഒരു അച്ഛനും അമ്മയും ഒരു ചെറിയ കുട്ടിയും ആയിരുന്നു അത്.
ആ കുട്ടിയുടെ കയ്യിൽ ഒരു വലിയ ബാഗ് ഉണ്ടായിരുന്നു.
ബാഗിന് നല്ല ഭാരമുണ്ടായിരുന്നു.
അവന്റെ അമ്മ അവനെ സഹായിക്കാൻ നോക്കി.
അവർ അവന്റെ ബാഗ് വാങ്ങാൻ ശ്രമിച്ചു.
പക്ഷേ അവൻ ആ ബാഗ് അവർക്ക് കൊടുത്തില്ല.
"ഇത് എന്റെ സ്വന്തം ബാഗാണ്," അവൻ പറഞ്ഞു.
അവൻ സ്വന്തം ബാഗ് ഒറ്റയ്ക്ക് എടുത്തു.
അവൻ വളരെ കഷ്ടപ്പെട്ട് അത് സീറ്റിൽ വെച്ചു.
അവന്റെ അമ്മ അത് കണ്ട് ചിരിച്ചു.
ഞാനും ആ കുട്ടിയെ നോക്കി ചിരിച്ചു.
അല്പസമയത്തിനുശേഷം ട്രെയിൻ മുന്നോട്ട് നീങ്ങി.
