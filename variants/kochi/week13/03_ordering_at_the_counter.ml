ഞാൻ കൗണ്ടറിലേക്ക് നടക്കുന്നു.
അവിടെ ഒരു വലിയ മെനു ഉണ്ട്.
ഞാൻ മെനു നോക്കുന്നു.
കൗണ്ടറിൽ ഒരു ജീവനക്കാരൻ നിൽക്കുന്നു.
അയാൾ എന്നെ നോക്കി ചിരിക്കുന്നു.
"നമസ്കാരം," അയാൾ പറയുന്നു.
"എന്ത് വേണം?" അയാൾ ചോദിക്കുന്നു.
"നമസ്കാരം," ഞാൻ പറയുന്നു.
എനിക്ക് നല്ല ദാഹം ഉണ്ട്.
എനിക്ക് ഒരു തണുത്ത പാനീയം വേണം.
"ഒരു വലിയ ഗ്ലാസ് ഐസ് ടീ കിട്ടുമോ?" ഞാൻ ചോദിക്കുന്നു.
"അതെ, കിട്ടും," അയാൾ പറയുന്നു.
എനിക്ക് ചെറിയ വിശപ്പും ഉണ്ട്.
ഞാൻ മെനു വീണ്ടും നോക്കുന്നു.
"ഒരു കഷ്ണം ബനാന കേക്ക് തരുമോ?" ഞാൻ ചോദിക്കുന്നു.
"തീർച്ചയായും തരാം," അയാൾ പറയുന്നു.
"വേറെ എന്തെങ്കിലും വേണമോ?" അയാൾ ചോദിക്കുന്നു.
"ഇല്ല, ഇത് മാത്രം മതി," ഞാൻ പറയുന്നു.
"വളരെ നന്ദി."
ഞാൻ എന്റെ ടേബിളിലേക്ക് തിരിച്ചു പോകുന്നു.
