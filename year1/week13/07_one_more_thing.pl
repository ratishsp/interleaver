Jem ostatni kawałek mojej bułeczki cynamonowej.
Smakuje naprawdę dobrze.
Ale jest też bardzo słodka.
Moja filiżanka po kawie jest zupełnie pusta.
Nagle jestem bardzo spragniona.
Chciałabym trochę zimnej wody.
Młody mężczyzna przechodzi obok mojego stolika.
Pracuje tu w kawiarni.
Zbiera puste filiżanki i talerze.
Łapię jego spojrzenie.
Zatrzymuje się przy moim stoliku i uśmiecha się.
„Przepraszam” – mówię grzecznie.
„Tak?” – odpowiada młody mężczyzna.
„Czy mogę prosić o szklankę wody z kranu?” – pytam.
„Tak, oczywiście” – mówi.
„Bardzo dziękuję” – mówię.
Zabiera mój pusty talerz i filiżankę.
Wraca do lady.
Chwilę później przychodzi ze szklanką zimnej wody.
