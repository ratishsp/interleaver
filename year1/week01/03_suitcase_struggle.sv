Dörren är öppen.
Tröskeln är hög.
Resväskan är mycket tung!
Men nu är resväskan i hallen.
Det är helt mörkt här.
Var är strömbrytaren?
Väggen är kall.
Är strömbrytaren här?
Ja, där är strömbrytaren!
Nu är det ljust.
Jag är i lägenheten.
Den är liten, men den är fin.
Här är ett vardagsrum.
Det finns en soffa och ett bord.
Det är ett möblerat hem.
Resväskan är på golvet.
Jag är mycket trött.
Men jag är också glad.
Jag är i Köpenhamn!
