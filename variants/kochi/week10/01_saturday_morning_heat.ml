ഇന്ന് ശനിയാഴ്ച രാവിലെ ആണ്.
മാർച്ച് മാസം നല്ല ചൂടാണ്.
ഞാൻ ഫ്ലാറ്റിന് പുറത്ത് നിൽക്കുന്നു.
അനിത അവിടെ വരുന്നു.
"സുപ്രഭാതം, മായ," അനിത പറയുന്നു.
"സുപ്രഭാതം, അനിത," ഞാൻ പറയുന്നു.
"ഇന്ന് നല്ല ചൂടാണ്," ഞാൻ പറയുന്നു.
ഞാൻ കട്ടിയുള്ള വസ്ത്രങ്ങൾ ആണ് ധരിക്കുന്നത്.
"എന്റെ വസ്ത്രങ്ങൾ നല്ല കട്ടിയാണ്," ഞാൻ അനിതയോട് പറയുന്നു.
"ഈ ചൂടിൽ എനിക്ക് കോട്ടൺ വസ്ത്രങ്ങൾ വേണം."
"നേർത്ത കോട്ടൺ വസ്ത്രങ്ങൾ ഇടുക," അനിത പറയുന്നു.
"നഗരത്തിൽ ഒരു വലിയ തുണിക്കട ഉണ്ട്."
"അതൊരു നല്ല കടയാണ്," അവർ പറയുന്നു.
"അവിടെ നല്ല കോട്ടൺ വസ്ത്രങ്ങൾ കിട്ടും."
"അത് കൊള്ളാം," ഞാൻ പറയുന്നു.
"ഞാൻ ഇന്ന് ആ വലിയ കടയിൽ പോകുന്നു."
