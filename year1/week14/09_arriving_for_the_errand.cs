Loď připlouvá na druhý břeh.
Přístavní autobus zastavuje u malého mola.
Vystupuji z lodi.
Cesta lodí je teď u konce.
Kontroluji mapu v telefonu.
Jdu do malého kiosku.
Kiosek se nachází támhle na rohu.
Jdu ulicí nahoru.
Vidím obchod na konci ulice.
Otevírám dveře a vcházím dovnitř.
Za pokladnou stojí mladý muž.
„Ahoj,“ říká mile.
„Ahoj, jdu si vyzvednout balíček,“ říkám.
Muž přikyvuje a usmívá se.
Ptá se na mé jméno.
„Moje jméno je Maya,“ odpovídám.
Na polici nachází velkou krabici.
Dává mi balíček.
„Moc děkuji za pomoc,“ říkám.
Teď se se svým balíčkem vydávám na dlouhou cestu zpátky domů.
