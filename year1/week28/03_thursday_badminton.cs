Je čtvrtek večer a já jsem ve sportovní hale.
Každý týden tu hraju badminton.
Hraju zápas proti své kamarádce Saře z klubu.
Zápas je velmi napínavý a vyrovnaný.
Hrajeme o úplně poslední bod.
Tvrdě udeří do košíčku.
Rychle letí přes síť směrem ke mně.
Udělám velký krok přes kurt, abych na něj dosáhla.
Švihnu raketou vší silou.
Dokonale trefím košíček.
Dopadne přímo na bílou čáru.
Bod je můj a já vyhrávám zápas.
Sara se přes síť usměje a řekne: „Dobrý zápas!“
„Moc děkuju, to byl těžký bod,“ odpovím.
Chvíli stojím u sítě, abych popadla dech.
Hodně se potím a potřebuju přestávku.
V tašce najdu svou červenou láhev s vodou.
Piju spoustu studené vody.
Je skvělé protáhnout si tělo po dlouhém dni v kanceláři.
