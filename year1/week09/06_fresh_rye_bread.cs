Jdu kolem malého stánku.
Voní to čerstvým chlebem.
Jdu ke stánku.
Pekař stojí za velkým stolem.
Stůl je plný pečiva.
Vidím tmavý žitný chléb.
Vypadá velmi čerstvý.
Ukazuji na ten žitný chléb.
„Kolik stojí ten tmavý žitný chléb?“ ptám se.
Pekař si utírá ruce.
„Stojí třicet pět korun,“ odpovídá.
„Koupím si ho,“ říkám.
Vytahuji svou platební kartu.
Platím kartou.
Pekař mi dává chléb v papírovém sáčku.
Dotýkám se sáčku.
Chléb je ještě teplý.
Těším se, až ho sním.
