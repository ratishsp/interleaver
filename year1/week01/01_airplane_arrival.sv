Flygplanet är i Köpenhamn nu.
Det är januari.
Jag är mycket förväntansfull.
Jag packar ner min bok i min väska.
Det sitter en passagerare bredvid mig.
Han tittar på mig och ler.
"Hej", säger han.
"Hej", säger jag.
"Vad heter du?" frågar han.
"Jag heter Maya", säger jag.
"Var kommer du ifrån, Maya?" frågar han.
Jag ler glatt.
"Jag kommer från Mexiko", svarar jag.
"Är du från Danmark?" frågar jag.
"Ja, jag är från Danmark", säger han.
"Välkommen till Danmark", säger han.
"Tack så mycket", säger jag.
Nu är vi här.
Jag är redo.
