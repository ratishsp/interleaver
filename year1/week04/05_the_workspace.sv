Jag går in i vardagsrummet.
Det står ett litet skrivbord vid fönstret.
Bordet är till mitt arbete.
Här kan jag arbeta i ro.
Det är en härlig liten plats.
Jag öppnar min väska.
Jag tar ut min dator.
Den står nu på bordet.
Det står också en lampa på bordet.
Lampan står precis vid datorn.
Den har ett varmt ljus.
Det ligger också en liten bok på bordet.
Jag har en liten svart väska med kablar.
Den ligger under skrivbordet.
Så är väskan inte i vägen.
Det står en bra stol vid skrivbordet.
Jag sitter i stolen och tittar.
Jag öppnar datorn och börjar skriva.
