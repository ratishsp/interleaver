എന്റെ ജോലി കഴിയുന്നു.
ഞാൻ ഓഫീസിൽ നിന്ന് ഇറങ്ങുകയാണ്.
ഞാൻ ബസ് സ്റ്റോപ്പിലേക്ക് നടക്കുന്നു.
അവിടെ ആളുകൾ ബസ് കാത്തുനിൽക്കുകയാണ്.
ഞാനും അവർക്കൊപ്പം നിൽക്കുന്നു.
ഇപ്പോൾ സൂര്യൻ അസ്തമിക്കുകയാണ്.
വൈകുന്നേരത്തെ ആകാശം വളരെ മനോഹരമാണ്.
കുറച്ചു കഴിഞ്ഞ് എന്റെ ബസ് വരുന്നു.
ഞാൻ ബസ്സിൽ കയറുകയാണ്.
ഞാൻ കണ്ടക്ടറിൽ നിന്ന് ടിക്കറ്റ് വാങ്ങുകയാണ്.
ബസ് മുന്നോട്ട് പോകുന്നു.
ഞാൻ ജനലിലൂടെ പുറത്തേക്ക് നോക്കുകയാണ്.
കൊച്ചിയിലെ തെരുവുകളിൽ ഇപ്പോൾ നല്ല തിരക്കാണ്.
കടകളിൽ ലൈറ്റുകൾ കത്തുകയാണ്.
എനിക്ക് ഈ സായാഹ്നയാത്ര വളരെ ഇഷ്ടമാണ്.
