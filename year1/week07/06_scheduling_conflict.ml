ഞാൻ എന്റെ ഫോൺ എടുക്കുന്നു.
ഞാൻ എന്റെ കലണ്ടർ തുറക്കുന്നു.
ഞാൻ വ്യാഴാഴ്ചത്തെ കാര്യങ്ങൾ നോക്കുന്നു.
പെട്ടെന്ന് ഞാൻ ഒരു പ്രശ്നം കാണുന്നു.
എനിക്ക് നാലരയ്ക്ക് ഹെയർഡ്രെസ്സറുടെ അടുത്ത് ഒരു അപ്പോയിന്റ്മെന്റ് ഉണ്ട്.
നിനയ്ക്കൊപ്പമുള്ള എന്റെ കോഫിയും നാലരയ്ക്കാണ്!
ഞാൻ ഉടനെ നിനയ്ക്ക് ഒരു ടെക്സ്റ്റ് മെസ്സേജ് അയക്കുന്നു.
ഞാൻ എഴുതുന്നു: "ഹായ് നിന, ക്ഷമിക്കണം."
"എനിക്ക് വ്യാഴാഴ്ച നാലരയ്ക്ക് ഹെയർഡ്രെസ്സറുടെ അടുത്ത് ഒരു അപ്പോയിന്റ്മെന്റ് ഉണ്ട്."
"പകരം നിനക്ക് ആറ് മണിക്ക് സമയമുണ്ടോ?"
നിന വളരെ വേഗം മറുപടി നൽകുന്നു.
അവൾ എഴുതുന്നു: "ഒരു പ്രശ്നവുമില്ല!"
"ആറ് മണിക്ക് കാണാം."
ഞാൻ പുഞ്ചിരിച്ചുകൊണ്ട് കലണ്ടറിലെ സമയം മാറ്റുന്നു.
ഇപ്പോൾ എന്റെ വ്യാഴാഴ്ച കൃത്യമായി പൊരുത്തപ്പെടുന്നുണ്ട്.
