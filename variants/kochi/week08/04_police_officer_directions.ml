ഞാൻ ബസ്സിൽ നിന്ന് ഇറങ്ങുന്നു.
ഇത് നഗരത്തിന്റെ കേന്ദ്രമാണ്.
ഇവിടെ വലിയ ട്രാഫിക് ഉണ്ട്.
ഇവിടെ പല റോഡുകൾ ഉണ്ട്.
എനിക്ക് വഴി മനസ്സിലാകുന്നില്ല.
ഞാൻ ഒരു ട്രാഫിക് പോലീസുകാരനെ കാണുന്നു.
ഞാൻ അദ്ദേഹത്തിന്റെ അടുത്തേക്ക് നടക്കുന്നു.
"നമസ്കാരം സാർ," ഞാൻ പറയുന്നു.
"മറൈൻ ഡ്രൈവ് നടപ്പാതയിലേക്ക് ഏതാണ് വഴി?" ഞാൻ ചോദിക്കുന്നു.
അദ്ദേഹം ഒരു വലിയ റോഡിലേക്ക് ചൂണ്ടിക്കാണിക്കുന്നു.
"ഈ റോഡിലൂടെ നേരെ പോകൂ," അദ്ദേഹം പറയുന്നു.
"എന്നിട്ട് ഇടത്തോട്ട് തിരിയൂ," അദ്ദേഹം പറയുന്നു.
"നടപ്പാത അവിടെയാണ്," അദ്ദേഹം പറയുന്നു.
"നന്ദി സാർ," ഞാൻ പറയുന്നു.
ഞാൻ ആ വലിയ റോഡിലേക്ക് നടക്കുന്നു.
ഞാൻ നേരെ നടക്കുന്നു.
ഞാൻ ഇടത്തേക്കുള്ള വഴി നോക്കുന്നു.
