Je úterý ráno.
Je čtvrt na devět.
Vedu své kolo.
Je rozbité.
Jdu dovnitř k opraváři kol.
Často pracuje brzy.
Dílna je plná kol.
Opravář kol vzhlédne.
„Dobré ráno,“ říká.
„Dobré ráno,“ říkám.
„Moje kolo je rozbité.“
Bere si moje kolo.
„Dnes ho opravím,“ říká.
„Moc děkuji,“ říkám.
Vycházím z dílny.
Teď jdu k autobusové zastávce.
Normálně jezdím do práce autobusem.
Na kole jezdím většinou o víkendu.
Brzy přijede můj autobus.
Je krásné únorové ráno.
Jsem v práci ve tři čtvrtě na devět.
