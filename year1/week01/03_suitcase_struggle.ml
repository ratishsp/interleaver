വാതിൽ തുറന്നിരിക്കുകയാണ്.
വാതിൽപ്പടിക്ക് ഉയരമുണ്ട്.
സ്യൂട്ട്കേസിന് വളരെ ഭാരമുണ്ട്!
എന്നാൽ ഇപ്പോൾ സ്യൂട്ട്കേസ് ഇടനാഴിയിലാണ്.
ഇവിടെ ആകെ ഇരുട്ടാണ്.
സ്വിച്ച് എവിടെയാണ്?
ഭിത്തിക്ക് തണുപ്പുണ്ട്.
സ്വിച്ച് ഇവിടെയാണോ?
അതെ, അതാ സ്വിച്ച്!
ഇപ്പോൾ വെളിച്ചമുണ്ട്.
ഞാൻ അപ്പാർട്ട്മെൻ്റിലാണ്.
ഇത് ചെറുതാണ്, പക്ഷേ നല്ലതാണ്.
ഇവിടെ ഒരു സ്വീകരണമുറിയുണ്ട്.
അവിടെ ഒരു സോഫയും ഒരു മേശയുമുണ്ട്.
ഇതൊരു ഫർണിഷ് ചെയ്ത വീടാണ്.
സ്യൂട്ട്കേസ് തറയിലാണ്.
ഞാൻ വളരെ ക്ഷീണിതയാണ്.
പക്ഷേ എനിക്ക് സന്തോഷവുമുണ്ട്.
ഞാൻ കോപ്പൻഹേഗനിലാണ്!
