Jag sätter mig vid Peters skrivbord.
Vi tittar på hans stora skärm.
Peter är också mjukvaruingenjör.
Han är en bra kollega, och vi skriver mycket kod tillsammans.
I dag ser han mycket trött ut.
"Vad gör du, Peter?" frågar jag.
"Jag har ett stort problem," svarar han.
"Jag har arbetat med det här felet i tre timmar."
Jag ler och tittar noga på koden.
Vi löser ofta komplexa problem tillsammans i vårt arbete.
Plötsligt ser jag något konstigt på skärmen.
Det är ett mycket litet fel.
"Prova att titta här," säger jag och pekar på skärmen.
"Du har gjort ett litet skrivfel här."
Peter tittar tyst på skärmen i två sekunder.
Sedan skrattar han högt.
"Du har helt rätt," säger Peter.
"Jag har arbetat i tre timmar, och så är det bara ett litet fel!"
Jag skrattar också, för alla mjukvaruingenjörer känner igen den situationen.
Vi rättar felet, och programmet fungerar äntligen perfekt.
