Siedziałam na swoim miejscu w pociągu i rozglądałam się dookoła.
Naprzeciwko mnie siedział ojciec.
Miał ze sobą dwoje małych dzieci.
Ojciec miał dużą książkę.
Bardzo chciał poczytać swoją książkę.
Ale nie miał zbyt wiele spokoju.
Jego córka miała czerwoną piłkę.
Jego syn miał zielony samochodzik.
Dzieci w ogóle nie siedziały spokojnie.
Ciągle rzucały swoje zabawki na podłogę.
Ojciec westchnął głośno i zamknął książkę.
Podniósł rzeczy z podłogi.
Oddał dzieciom ich zabawki.
„Musicie siedzieć spokojnie” – powiedział zmęczony.
Znowu otworzył swoją książkę.
Dwie minuty później piłka spadła na podłogę.
Trafiła w lewy but ojca.
Mężczyzna znowu podniósł piłkę.
Uśmiechnęłam się do zmęczonego ojca.
Tylko pokręcił głową i spojrzał w dół na swoją książkę.
