V sobotu večer leží Ludwig vedle mě na gauči a spí.
Po naší procházce v lese je velmi unavený.
Otevřu počítač a zavolám přes video domů své rodině do Mexika.
Moje sestra Sofía a můj bratr Diego sedí připraveni před obrazovkou.
„Prostě musíte vidět mého malého hosta,“ říkám jim.
Vezmu počítač a namířím kameru dolů na psa.
Sofía se radostně usmívá.
„Jen se na něj podívejte!“
„Ten je ale roztomilý,“ říká Diego.
Ludwig otevře jedno oko, ale zůstane dál ležet.
„Podívejte se na něj.“
„Je stejně klidný jako náš pes Lola u nás doma,“ říkám.
Diego se mě ptá, jestli je to nenáročný pes na hlídání.
„Ano, moc ráda ho hlídám,“ odpovídám.
„Venku na ulici musí chodit jenom na vodítku.“
„A rozhodně nesmí dostat lidské jídlo.“
„Takže mu dávám jen jeho vlastní pamlsky.“
Najednou slyšíme, jak Lola v pozadí videa hlasitě štěká.
Ludwig zvedne hlavu a velmi zmateně se podívá na obrazovku.
„Jen si zase lehni, kamaráde,“ říkám něžně a hladím ho.
Popřeji rodině dobrou noc, aby měl klid.
Zavře oči a rychle znovu usne.
