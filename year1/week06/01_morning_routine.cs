Venku je ještě tma.
Ráno se probouzím pomalu.
Chvíli ležím v posteli.
Dnes je úplně obyčejný všední den.
Teď vstávám z postele.
Podlaha je pod mýma nohama trochu studená.
Jdu rovnou do koupelny.
V koupelně pouštím vodu.
Voda je teplá a příjemná.
Vstupuji do sprchového koutu.
Tady si dávám příjemnou teplou sprchu.
Nejdřív si myju vlasy šamponem.
Potom se myju mýdlem.
Mýdlo svěže voní po citrusech.
Teplá voda mě probouzí.
Nakonec sprchu vypínám.
Beru si měkký ručník.
Teď se důkladně utírám.
Jsem úplně vzhůru a připravená na dnešní den.
