Jdu k malému kiosku ve sportovní hale.
Za pultem stojí mladý muž.
Usmívá se a říká ahoj.
„Ahoj, dnes bych si chtěla zahrát badminton,“ říkám.
„Jsi tady v klubu nová?“ ptá se.
„Ano, ráda bych se zkusila přidat,“ odpovídám.
„Vítej,“ říká muž.
„Potřebuješ si půjčit raketu?“ ptá se.
„Ano, prosím, chtěla bych si půjčit raketu na dnešní večer,“ říkám.
Najde mi dobrou raketu.
„Stojí to čtyřicet korun,“ říká.
Vytahuji svou platební kartu.
Platím těch čtyřicet korun.
Podává mi raketu přes pult.
„Myslím, že je to zábavný sport,“ říkám vesele.
„Přeji opravdu dobrou hru.“
Poděkuji a jdu ke kurtům.
