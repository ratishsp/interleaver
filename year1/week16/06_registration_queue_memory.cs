Dívám se na mámu na obrazovce.
Chce slyšet víc o té dlouhé frontě.
Vyprávím jí o dlouhém dopoledni.
„Bylo to chladné úterý v lednu,“ říkám.
Jela jsem autobusem do městského centra služeb pro občany.
Ve velké místnosti bylo opravdu hodně lidí.
Vytáhla jsem si číslo z malého automatu.
Moje číslo bylo padesát devět.
Ale obrazovka na zdi ukazovala jen dvacet jedna.
Fronta byla neuvěřitelně pomalá.
Seděla jsem na tvrdé židli a čekala dvě hodiny.
Často jsem vzhlížela k obrazovce.
Konečně jeden milý muž vyvolal moje číslo.
Vstala jsem a šla k jeho stolu.
Dala jsem mu svůj pas a dokumenty ze softwarové firmy.
Přečetl si papíry a psal na počítači.
Konečně jsem dostala své CPR číslo.
Požádal mě, abych na to důležité číslo dávala opravdu dobrý pozor.
„Byla jsi velmi trpělivá,“ usmívá se moje máma.
