ഞാൻ ഓഫീസിൽ എത്തുന്നു.
ഇതൊരു വലിയ സോഫ്റ്റ്‌വെയർ കമ്പനിയാണ്.
ഞാൻ അകത്തേക്ക് നടക്കുന്നു.
എന്റെ സഹപ്രവർത്തകൻ പീറ്റർ അപ്പോഴേക്കും അവിടെയുണ്ട്.
അദ്ദേഹം വളരെ സൗഹാർദ്ദമുള്ളയാളാണ്.
"ശുഭപ്രഭാതം, മായ," പീറ്റർ പറയുന്നു.
"ശുഭപ്രഭാതം, പീറ്റർ," ഞാൻ പറയുന്നു.
ഞാൻ എന്റെ സീറ്റിലേക്ക് നടക്കുന്നു.
ഞാൻ എന്റെ ഡെസ്കിൽ ഇരിക്കുന്നു.
ഞാൻ എന്റെ കമ്പ്യൂട്ടർ ഓൺ ചെയ്യുന്നു.
എന്റെ കയ്യിൽ ഒരു കപ്പ് കാപ്പിയുണ്ട്.
അത് കറുത്തതും ചൂടുള്ളതുമാണ്.
ഞാൻ കാപ്പി കുടിക്കുന്നു.
ഞാൻ ഒരു സോഫ്റ്റ്‌വെയർ എഞ്ചിനീയറായാണ് ജോലി ചെയ്യുന്നത്.
ഞാൻ സ്ക്രീനിലേക്ക് നോക്കുന്നു.
ഞാൻ എന്റെ കമ്പ്യൂട്ടറിൽ കോഡ് ടൈപ്പ് ചെയ്യുന്നു.
ജോലി വളരെ ആവേശകരമാണ്.
എന്റെ ജോലിയിൽ ഞാൻ സന്തുഷ്ടയാണ്.
