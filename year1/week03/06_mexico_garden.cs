Dívám se na svůj počítač.
Trochu se mi stýská po domově v Mexiku.
„Tati, jaká je tvoje zahrada?“ říkám.
Můj táta se na mě usmívá.
Jde s telefonem ven.
Je tam velká zahrada.
Hodně tam svítí slunce.
„Podívej, Mayo,“ říká můj táta.
„Tady je zahrada a strom.“
Je to velmi velký strom.
Je to krásný strom.
Usmívám se na obrazovku.
Uvnitř se cítím dobře a je mi teplo.
Moje máma, moje sestra a můj bratr jdou také ven.
Můj pes běhá pod stromem.
Celá moje rodina na mě mává.
„Tak ahoj, všichni!“ říkám.
„Ahoj, Mayo,“ říkají.
Zavírám svůj počítač.
