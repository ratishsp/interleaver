Senare på eftermiddagen går jag över till Evas skrivbord.
Hon är teamets digitala designer.
Jag har inte arbetat med henne före i dag.
"Hej Maya, kom och titta", säger hon.
Hon pekar på sin stora skärm.
Jag ser några vackra skisser av vår nya mjukvara.
Färgerna är lugna och designen är mycket ren.
"Det ser riktigt bra ut", säger jag.
"Tack", svarar Eva med ett leende.
Hon förklarar sitt arbete för mig.
"Jag har arbetat som digital designer sedan universitetet", säger hon.
"Jag fokuserar alltid på användarens upplevelse."
Hon visar mig hur användaren klickar runt i programmet.
"Det måste vara enkelt och logiskt att använda", förklarar hon.
Jag tittar ofta bara på själva koden.
Men hennes design är otroligt viktig för projektet.
Vi pratar lite mer om våra gemensamma uppgifter.
Jag ser fram emot att programmera hennes vackra design.
