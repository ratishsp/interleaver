ഞാൻ കോണിലുള്ള ചെറിയ ബേക്കറിയിൽ എത്തിച്ചേരുന്നു.
ഞാൻ ആ ചൂടുള്ള കടയിലേക്ക് കയറുന്നു.
അവിടെ കാപ്പിയുടെയും കേക്കിന്റെയും നല്ല ഗന്ധമുണ്ട്.
വെളുത്ത ഏപ്രണണിഞ്ഞ ഒരു ബേക്കർ കൗണ്ടറിന് പിന്നിൽ നിൽക്കുന്നുണ്ട്.
"ഗുഡ് ആഫ്റ്റർനൂൺ," ബേക്കർ പറയുന്നു.
"ഞാൻ നിങ്ങളെ എങ്ങനെയാണ് സഹായിക്കേണ്ടത്?" അദ്ദേഹം ചോദിക്കുന്നു.
ഞാൻ അവിടെയുള്ള നിരവധി കേക്കുകളിലേക്ക് നോക്കുന്നു.
ഞാൻ ഇന്ന് രാത്രിക്ക് വേണ്ടി ഒരു കേക്ക് വാങ്ങുകയാണ്.
ഞാൻ മനോഹരമായ ഒരു ചോക്ലേറ്റ് കേക്കിന് നേരെ വിരൽ ചൂണ്ടുന്നു.
"ദയവായി എനിക്ക് ആ ചോക്ലേറ്റ് കേക്ക് തരൂ," ഞാൻ പറയുന്നു.
"തീർച്ചയായും," ബേക്കർ മറുപടി പറയുന്നു.
അദ്ദേഹം ആ കേക്ക് ഒരു വെള്ള പെട്ടിയിൽ വെക്കുന്നു.
"അറുപത്തിയഞ്ച് ക്രോണർ ആയി," അദ്ദേഹം പറയുന്നു.
ഞാൻ എന്റെ ബാഗിൽ നിന്നും പഴ്സ് എടുക്കുന്നു.
ഞാൻ ആ അറുപത്തിയഞ്ച് ക്രോണർ നൽകുന്നു.
"വളരെ നന്ദി, നല്ലൊരു സായാഹ്നം ആശംസിക്കുന്നു," ബേക്കർ പറയുന്നു.
"നന്ദി, താങ്കൾക്കും അങ്ങനെ തന്നെ," ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ ആ വെള്ള പെട്ടി എടുക്കുന്നു.
ഞാൻ കേക്കുമായി കടയിൽ നിന്ന് വളരെ ശ്രദ്ധയോടെ പുറത്തേക്ക് നടക്കുന്നു.
