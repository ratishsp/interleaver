ഇപ്പോൾ മാർച്ച് മാസം ആണ്.
കൊച്ചിയിൽ ഇപ്പോൾ നല്ല ചൂട് ആണ്.
ഞാൻ എൻ്റെ സോഫ്റ്റ്‌വെയർ ഓഫീസിലേക്ക് നടക്കുകയാണ്.
രാവിലത്തെ വെയിലിന് നല്ല ചൂട് ആണ്.
ഞാൻ ഇന്ന് കട്ടിയുള്ള വസ്ത്രങ്ങൾ ആണ് ധരിക്കുന്നത്.
ഈ വസ്ത്രങ്ങൾ എനിക്ക് വലിയ ബുദ്ധിമുട്ട് ആണ്.
ചൂടുകാലത്ത് കട്ടിയുള്ള വസ്ത്രങ്ങൾ നല്ലതല്ല.
എനിക്ക് കോട്ടൺ വസ്ത്രങ്ങൾ വേണം.
കോട്ടൺ വസ്ത്രങ്ങൾ നല്ലതാണ്.
ഞാൻ ജോലിക്ക് ശേഷം ഒരു തുണിക്കടയിൽ പോകും.
എം.ജി റോഡിൽ ഒരു വലിയ തുണിക്കട ഉണ്ട്.
അതൊരു നല്ല കട ആണ്.
ഞാൻ അവിടെ നിന്ന് കനം കുറഞ്ഞ കോട്ടൺ വസ്ത്രങ്ങൾ വാങ്ങും.
ഓഫീസിൽ കോട്ടൺ വസ്ത്രങ്ങൾ ഇടുന്നത് നല്ലതാണ്.
നാളെ ഞാൻ ഒരു പുതിയ കോട്ടൺ വസ്ത്രം ധരിക്കും.
