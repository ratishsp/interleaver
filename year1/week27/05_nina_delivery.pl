Kładę telefon na stole i się relaksuję.
Nagle rozlega się szybkie pukanie do moich drzwi.
To przerywa moje myśli.
Wstaję z sofy i wychodzę do przedpokoju.
Kiedy otwieram drzwi, na korytarzu stoi Nina.
Ma w rękach małe kartonowe pudełko.
„Cześć Maya, mam dla ciebie paczkę” – mówi i uśmiecha się.
Wręcza mi pudełko.
„Została dostarczona do mnie wcześniej po południu” – wyjaśnia Nina.
„Listonosz musiał przypadkowo pomylić nasze drzwi”.
Patrzę na pudełko i widzę na nim swoje imię.
„Och!”
„To moje nowe ziarna kawy!”
„Zazwyczaj kupuję je przez internet” – mówię jej.
„Zwykle paczki zostawia się na dole na klatce schodowej” – mówi Nina.
„Tak, zazwyczaj się je tam zostawia” – odpowiadam.
Przyjmuję kartonowe pudełko z szerokim uśmiechem.
Już lekko pachnie paloną kawą.
„Bardzo dziękuję, że ją przyniosłaś” – mówię.
