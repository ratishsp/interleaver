ഞങ്ങൾ പനമ്പിള്ളി നഗറിലെ ഒരു റെസ്റ്റോറന്റിലാണ്.
പുറത്ത് നല്ല മഴ പെയ്യുന്നുണ്ട്.
എന്റെ ജന്മദിനത്തിന് ഞാൻ അനിതയെയും പ്രകാശിനെയും ദീപയെയും ക്ഷണിച്ചിട്ടുണ്ട്.
ഞങ്ങൾ ഉള്ളിൽ ഒരു നല്ല മേശയ്ക്ക് ചുറ്റും ഇരുന്നു.
റെസ്റ്റോറന്റ് വളരെ മനോഹരവും വെളിച്ചമുള്ളതുമാണ്.
ഞങ്ങൾ മെനു നോക്കി.
"ഞാൻ കുറച്ച് എരിവുള്ള ഭക്ഷണം ഓർഡർ ചെയ്തിട്ടുണ്ട്," ഞാൻ അവരോട് പറയുന്നു.
"ഈ തണുപ്പിന് അത് വളരെ നല്ലതാണ്," പ്രകാശ് പറയുന്നു.
പെട്ടെന്ന് വെയ്റ്റർ ഭക്ഷണം കൊണ്ടുവന്നു.
ഞങ്ങൾക്ക് ചൂടുള്ള പൊറോട്ടയും ബീഫ് റോസ്റ്റും ചിക്കൻ കറിയും കിട്ടി.
ഞങ്ങൾ എല്ലാം പങ്കുവെച്ച് കഴിച്ചു.
"ഭക്ഷണം വളരെ രുചികരമാണ്," ദീപ പറയുന്നു.
"മായ ഈ ചിക്കൻ കറി കഴിച്ചിട്ടുണ്ടോ?" അനിത ചോദിക്കുന്നു.
"ഉവ്വ്, ഞാൻ കുറച്ച് കഴിച്ചു," ഞാൻ മറുപടി പറയുന്നു.
പുറത്ത് വലിയ മഴയുടെ ശബ്ദം ഞങ്ങൾക്ക് കേൾക്കാം.
എന്നാൽ ഉള്ളിൽ നല്ല ചൂടുണ്ട്.
ഇവിടുത്തെ എന്റെ ആദ്യത്തെ പിറന്നാൾ വിരുന്ന് വളരെ മനോഹരമായി.
