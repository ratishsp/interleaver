അനിത സ്വന്തം ഫ്ലാറ്റിലേക്ക് പോകുന്നു.
ഞാൻ ഇപ്പോൾ എന്റെ ഫ്ലാറ്റിൽ തനിച്ചാണ്.
മുറികളെല്ലാം വളരെ ശാന്തമാണ്.
ഞാൻ സ്വീകരണമുറിയിൽ നടക്കുന്നു.
എന്റെ മേശ ജനലിനടുത്ത് ഇരിക്കുന്നു.
ജനൽപ്പടിയിൽ ചെറിയ ചെടിയുണ്ട്.
ഞാൻ അടുക്കളയിൽ നോക്കുന്നു.
അലമാരയിൽ പുതിയ പാത്രങ്ങൾ ഉണ്ട്.
എല്ലാം നല്ല ഭംഗിയായി ഇരിക്കുന്നു.
ഫോട്ടോ ഷെൽഫിന് മുകളിൽ ഇരിക്കുന്നു.
ഞാൻ എന്റെ കുടുംബത്തിന്റെ ഫോട്ടോ നോക്കുന്നു.
പിന്നെ ഞാൻ കിടപ്പുമുറിയിലേക്ക് പോകുന്നു.
കൊച്ചിയിലെ നല്ല കാറ്റ് ജനലിലൂടെ വരുന്നുണ്ട്.
എന്റെ വലിയ ബാഗ് കട്ടിലിനടിയിൽ ഇരിക്കുന്നു.
എന്റെ വസ്ത്രങ്ങൾ അലമാരയിൽ ഉണ്ട്.
കട്ടിലിന് മുകളിൽ പുതിയ വിരിയുണ്ട്.
ഞാൻ കട്ടിലിൽ കിടക്കുന്നു.
എനിക്ക് ഇപ്പോൾ വലിയ സന്തോഷം തോന്നുന്നു.
ഈ ഫ്ലാറ്റ് ശരിക്കും എന്റെ സ്വന്തം വീടാണ്.
