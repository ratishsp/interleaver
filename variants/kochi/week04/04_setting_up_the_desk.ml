ഞാൻ ഇപ്പോൾ സ്വീകരണമുറിയിൽ ആണ്.
മുറിയുടെ മൂലയിൽ ഒരു ചെറിയ മര മേശ ഉണ്ട്.
ഇത് എന്റെ പുതിയ ഓഫീസ് മേശ ആണ്.
മേശ ജനലിന്റെ അടുത്ത് ആണ്.
ഞാൻ ജനൽ തുറക്കുന്നു.
പുറത്തുനിന്ന് നല്ല കാറ്റ് വരുന്നു.
കൊച്ചിയിൽ ജനുവരി നല്ലൊരു മാസമാണ്.
ഞാൻ ബാഗിൽ നിന്ന് ലാപ്ടോപ്പ് എടുക്കുന്നു.
ഞാൻ ലാപ്ടോപ്പ് മേശയുടെ മുകളിൽ വെക്കുന്നു.
ഇപ്പോൾ ലാപ്ടോപ്പ് മേശയിൽ സുരക്ഷിതമായി ഇരിക്കുന്നു.
ഞാൻ നോട്ട്ബുക്ക് ലാപ്ടോപ്പിന്റെ അടുത്ത് വെക്കുന്നു.
എന്റെ പേന നോട്ട്ബുക്കിന്റെ മുകളിൽ കിടക്കുന്നു.
ഒഴിഞ്ഞ ബാഗ് മേശയുടെ അടിയിൽ കിടക്കുന്നു.
ഞാൻ ഒരു കസേര മേശയുടെ അടുത്ത് ഇടുന്നു.
ഞാൻ കസേരയിൽ ഇരിക്കുന്നു.
ജനലിലൂടെ വരുന്ന കാറ്റ് എനിക്ക് ഇഷ്ടമാണ്.
എനിക്ക് ഈ പുതിയ സ്ഥലം വളരെ ഇഷ്ടമാണ്.
ഇവിടെ ഇരുന്ന് ജോലി ചെയ്യാൻ ഞാൻ തയ്യാറാണ്.
