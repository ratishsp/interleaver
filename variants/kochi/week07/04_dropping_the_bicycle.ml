ഇന്ന് തിങ്കളാഴ്ചയാണ്.
ഇപ്പോൾ വൈകുന്നേരമാണ്.
എല്ലാ ദിവസവും അഞ്ച് മണിക്ക് എന്റെ ജോലി തീരുന്നു.
ഞാൻ എന്റെ സൈക്കിളുമായി പുറത്ത് പോകുന്നു.
ഞാൻ ഒരു ചെറിയ റിപ്പയർ കടയിലേക്ക് നടക്കുന്നു.
ഈ കട എന്റെ അപ്പാർട്ട്മെന്റിന് അടുത്താണ്.
അവിടെ ഒരു മെക്കാനിക്ക് ഉണ്ട്.
ഞാൻ അദ്ദേഹത്തോട് നമസ്കാരം പറയുന്നു.
"നമസ്കാരം," അദ്ദേഹം മറുപടി പറയുന്നു.
"ഈ സൈക്കിൾ ഒന്ന് സർവീസ് ചെയ്യണം," ഞാൻ പറയുന്നു.
അദ്ദേഹം സൈക്കിൾ നോക്കുന്നു.
"ശരി, ഞാൻ ചെയ്യാം," മെക്കാനിക്ക് പറയുന്നു.
"എത്ര മണിക്ക് വരും?" അദ്ദേഹം ചോദിക്കുന്നു.
"ഞാൻ ബുധനാഴ്ച വരാം," ഞാൻ പറയുന്നു.
"ബുധനാഴ്ച എത്ര മണിക്ക്?" അദ്ദേഹം ചോദിക്കുന്നു.
"വൈകുന്നേരം ഏഴ് മണിക്ക് വരാം," ഞാൻ പറയുന്നു.
"ശരി, ഏഴ് മണിക്ക് വരൂ," അദ്ദേഹം പറയുന്നു.
ഞാൻ സൈക്കിൾ കടയിൽ വെക്കുന്നു.
അതിനുശേഷം ഞാൻ തിരിച്ച് വീട്ടിലേക്ക് നടക്കുന്നു.
