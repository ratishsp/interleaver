ഞാൻ ബസ് സ്റ്റോപ്പിൽ നിൽക്കുന്നു.
അവിടെ ധാരാളം ആളുകൾ ഉണ്ട്.
ഒരു ചുവന്ന സിറ്റി ബസ് വരുന്നു.
ഞാൻ ബസ്സിൽ കയറുന്നു.
ബസ്സിൽ നല്ല തിരക്കാണ്.
കണ്ടക്ടർ എന്റെ അടുത്ത് നിൽക്കുന്നു.
ഞാൻ അദ്ദേഹത്തോട് ചോദിക്കുന്നു.
"ഈ ബസ് എറണാകുളത്തേക്ക് പോകുമോ?"
"മറൈൻ ഡ്രൈവിലേക്ക് പോകുമോ?"
കണ്ടക്ടർ തലയാട്ടുന്നു.
"അതെ, പോകും," അദ്ദേഹം പറയുന്നു.
"നിങ്ങൾ ഉള്ളിലേക്ക് പോകൂ," അദ്ദേഹം പറയുന്നു.
"നേരെ നടക്കൂ."
"ഒരു സീറ്റിൽ ഇരിക്കൂ," അദ്ദേഹം എന്നോട് പറയുന്നു.
ഞാൻ നേരെ നടക്കുന്നു.
ഞാൻ ഒരു ഒഴിഞ്ഞ സീറ്റ് കാണുന്നു.
ഞാൻ ആ സീറ്റിൽ ഇരിക്കുന്നു.
ബസ് മുന്നോട്ട് പോകുന്നു.
