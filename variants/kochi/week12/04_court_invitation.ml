ഞാൻ മരത്തിന്റെ കോർട്ടിലേക്ക് നടക്കുന്നു.
അവിടെ നല്ല വെളിച്ചമുണ്ട്.
കിരൺ, സാറ, വിഷ്ണു എന്നിവർ അവിടെ കളിക്കുന്നുണ്ട്.
എനിക്ക് അവരുടെ കളി കാണാൻ ഇഷ്ടമാണ്.
ഞാൻ അത് കാണാൻ അവിടെ നിൽക്കുന്നു.
അവർ വളരെ നന്നായി കളിക്കുന്നു.
അപ്പോൾ സാറ എന്നെ കാണുന്നു.
അവൾ എന്നെ നോക്കി ചിരിക്കുന്നു.
കിരണും വിഷ്ണുവും കളി നിർത്തുന്നു.
അവരും എന്നെ നോക്കുന്നു.
സാറ എനിക്ക് നേരെ കൈ വീശുന്നു.
"നിങ്ങൾക്ക് കളിക്കാൻ ഇഷ്ടമാണോ?" സാറ ചോദിക്കുന്നു.
"ഞങ്ങളുടെ കൂടെ കളിക്കാൻ വരുന്നുണ്ടോ?" അവൾ ചോദിക്കുന്നു.
"നിങ്ങൾക്ക് ബാഡ്മിന്റൺ കളിക്കാൻ കഴിയുമോ?" കിരൺ ചോദിക്കുന്നു.
ഞാൻ സന്തോഷത്തോടെ അവരുടെ അടുത്തേക്ക് നടക്കുന്നു.
"അതെ, എനിക്ക് കളിക്കാൻ കഴിയും," ഞാൻ മറുപടി പറയുന്നു.
"എനിക്ക് കളിക്കാൻ വളരെ ഇഷ്ടമാണ്," ഞാൻ പറയുന്നു.
അവർ സന്തോഷത്തോടെ എന്നെ കോർട്ടിലേക്ക് വിളിക്കുന്നു.
ഞാൻ അവരുടെ കൂടെ കളിക്കാൻ പോകുന്നു.
