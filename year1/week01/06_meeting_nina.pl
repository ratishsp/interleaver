Otwieram swoje drzwi.
Stoję na klatce schodowej.
Jest cicho.
Otwierają się drzwi.
Jakaś kobieta uśmiecha się do mnie.
„Cześć” – mówi.
„Jak masz na imię?” – pyta.
„Mam na imię Maya” – odpowiadam.
„Skąd pochodzisz?” – pyta.
„Pochodzę z Meksyku” – mówię.
„Witaj w naszym budynku” – mówi kobieta.
„Mam na imię Nina” – mówi.
„Jestem twoją sąsiadką”.
Nina jest bardzo miła.
Mówi powoli i wyraźnie.
„Tutaj są moje drzwi” – mówi.
„Chętnie pomogę”.
„Wystarczy, że zapukasz” – mówi Nina.
„Bardzo dziękuję, Nino” – odpowiadam.
Jestem bardzo szczęśliwa.
Teraz mam przyjaciółkę w Kopenhadze.
