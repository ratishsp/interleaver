W niedzielne popołudnie siedzę na kanapie w moim salonie.
Słońce świeci przez okno, a pokój jest cudownie jasny.
Mam na stole przed sobą komputer do długiej rozmowy wideo.
Cała moja rodzina w Meksyku jest na ekranie.
Widzę moich rodziców, moją siostrę Sofíę i mojego brata Diego.
Nagle nasz pies, Lola, szczeka bardzo głośno.
Skacze podekscytowana przed kamerą.
„Lola tęskni za tobą” – mówi Sofía i się śmieje.
„Też za wami wszystkimi tęsknię” – mówię i macham do nich.
Mój tata pyta o moją pracę i moje codzienne życie tutaj.
Opowiadam im o mojej pracy, badmintonie i mojej miłej sąsiadce.
Rozmawiamy razem przez ponad godzinę.
Rozglądam się po moim jasnym salonie.
Patrzę na ładną zieloną roślinę z wczoraj.
Od stycznia minęło dużo czasu.
„Dobrze ci się tam mieszka?” – pyta moja mama.
Uśmiecham się do niej szeroko.
„Tak” – odpowiadam.
„Teraz naprawdę czuję się w tym mieście jak w domu.”
