Efteråt gick jag bort till stadens stora museum.
Det handlade om den berömda författaren Hans Christian Andersen.
Jag köpte min biljett och gick in i den vackra byggnaden.
Utställningen berättade om hans liv och hans långa resor.
Jag tittade på hans gamla saker i en stor glasmonter.
Han tog med sig sin höga hatt överallt.
Den höga, svarta hatten låg precis där framför mig.
Där låg också hans papper och hans gamla penna.
Han använde dem när han skrev sina fantastiska sagor.
Jag läste en lång text på en vit vägg.
Den handlade om mannen bakom min favoritsaga.
Det var faktiskt han som skapade den lilla sjöjungfrun.
Jag träffade henne som staty i Köpenhamn redan i februari.
Det var roligt att se författarens egna saker nu.
Jag tog ett par bilder på hans stora resväska.
Han älskade tydligen att besöka nya länder.
Jag köpte en liten bok i museets butik till sist.
Den innehöll alla hans bästa historier.
Nu känner jag att jag känner till den danska kulturen lite bättre.
