Jag går fram till kassan.
En ung man står bakom disken.
Han är barista på kaféet.
Jag ler mot honom.
Han nickar vänligt.
"Hej," säger han.
"Vad skulle du vilja ha?" frågar han.
"Hej," svarar jag.
"Jag skulle vilja ha en svart kaffe, tack."
"Och får jag också be om en kanelbulle?"
"Självklart," säger han.
"En svart kaffe och en kanelbulle."
"Vill du sitta här?" frågar han.
"Ja tack, jag sätter mig där borta," säger jag.
"Det går bra," säger baristan.
"Jag gör din kaffe nu."
"Tack så mycket," säger jag.
