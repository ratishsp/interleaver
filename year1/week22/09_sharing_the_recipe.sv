Vi är alla tre väldigt mätta nu.
Det finns ingen mer mat kvar på bordet.
"Det var en fantastisk middag, Maya", säger Sara glatt.
"Hur gör man exakt de här köttbullarna?" frågar hon sedan.
"Är det väldigt svårt?"
"Nej, det är faktiskt ganska lätt", svarar jag.
"Först hackar man lök, och därefter blandar man köttet", förklarar jag.
"Jag har ett riktigt bra recept på min telefon."
"Jag skickar en länk till dig i kväll."
"Tusen tack, det vill jag gärna prova", säger Sara.
Vi reser oss upp från de små stolarna.
Kasper börjar samla ihop de tomma tallrikarna.
"Ska vi ta ut tallrikarna i köket nu?" frågar han.
"Ja tack."
"Ställ dem bara på köksbänken", säger jag.
Vi dukar snabbt av bordet tillsammans.
"Men hej, nästa gång är det min tur", säger Kasper plötsligt.
"Ja."
"Nästa gång ska du laga mat till oss!"
Sara skrattar.
"Precis."
"Och jag lovar att det blir bra", säger han.
Vi skrattar och bär ut resten av sakerna i köket.
