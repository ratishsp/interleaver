Ludwig idzie szybko obok mnie.
Jesteśmy w drodze na lokalny wybieg dla psów.
Słońce pięknie świeci tego popołudnia.
Trochę niecierpliwie ciągnie za smycz.
"Czekaj", mówię do niego stanowczo.
"Chodź, idźmy grzecznie."
W końcu docieramy do dużej furtki.
Wybieg dla psów jest ogrodzony i całkowicie bezpieczny.
Wchodzimy do środka, a ja zamykam za nami furtkę.
Kucam i patrzę na niego.
Powoli odpinam smycz od jego obroży.
"Teraz możesz biegać swobodnie", mówię z uśmiechem.
Patrzy na mnie radośnie i szybko odbiega.
Znajduję na ziemi dobry patyk.
"Spójrz tutaj, Ludwig!" krzyczę i pokazuję mu go.
Rzucam patyk daleko między drzewa.
"Przynieś!" mówię głośno.
Biegnie do patyka i bierze go do pyska.
"Wracaj", wołam i klaszczę w dłonie.
To naprawdę dobry pies.
