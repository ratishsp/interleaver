Párkrát to zazvoní.
Obrazovka se rozsvítí.
Vidím obývací pokoj.
Svítí tam slunce a obývací pokoj je velmi světlý.
Vidím dva lidi.
Je to moje máma a můj táta.
Hodně se usmívají a mávají na mě.
„Ahoj mami a tati!“ říkám nahlas.
„Ahoj Mayo,“ říká můj táta.
„Jak to jde?“
„Jde to dobře,“ odpovídám vesele.
Najednou slyším zvuk.
Je to malé štěknutí.
„Jé, slyším psa!“ říkám a směju se.
Malý pes vyskočí na pohovku.
Dívá se do kamery.
„Tam je můj pes!“
„Ahoj Lolo,“ říkám.
Lola vrtí ocasem.
„Ano, je to tvůj pes,“ říká moje máma s úsměvem.
Miluju svou rodinu.
Je krásné je všechny vidět.
