ഇന്ന് തിങ്കളാഴ്ച രാവിലെയാണ്.
പുറത്ത് ശക്തമായ മഴ പെയ്യുന്നുണ്ട്.
ഞാൻ ഇൻഫോപാർക്ക് ഓഫീസിലേക്കുള്ള ബസ്സിൽ ഇരിക്കുകയാണ്.
ജനാലയിലൂടെ ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
റോഡുകളിൽ നിറയെ വെള്ളമാണ്.
ബസ്സ് വെള്ളത്തിലൂടെ പതുക്കെ പോകുന്നു.
ഇവിടുത്തെ എന്റെ ആദ്യത്തെ ആഴ്ചകൾ ഞാൻ ഓർക്കുകയാണ്.
അന്ന് കൊച്ചിയിൽ നല്ല വെയിലായിരുന്നു.
ഈ ബസ്സ് യാത്ര എനിക്ക് അന്ന് വളരെ പുതിയതായിരുന്നു.
ബസ്സ് എവിടെ നിൽക്കും എന്ന് പോലും എനിക്ക് അറിയില്ലായിരുന്നു.
എന്നാൽ ഇപ്പോൾ അങ്ങനെയല്ല.
എനിക്ക് ഈ വഴികളെല്ലാം കൃത്യമായി അറിയാം.
ബസ്സ് ഓഫീസിന് അടുത്തുള്ള സ്റ്റോപ്പിൽ എത്തുന്നു.
ഞാൻ കുടയെടുത്ത് ബസ്സിൽ നിന്ന് താഴേക്ക് ഇറങ്ങുന്നു.
റോഡിൽ എന്റെ മുന്നിൽ ഒരു വലിയ വെള്ളക്കെട്ട് ഉണ്ട്.
പക്ഷേ, എവിടെ ചവിട്ടണം എന്ന് ഇപ്പോൾ എനിക്ക് നന്നായി അറിയാം.
ഞാൻ ആ വെള്ളക്കെട്ട് ഒഴിവാക്കി മുന്നോട്ട് നടക്കുന്നു.
ഈ മഴയും ഈ യാത്രയും ഇപ്പോൾ എന്റെ ജീവിതത്തിന്റെ ഭാഗമാണ്.
