Jag går iväg från marknaden och hittar ett litet, lokalt museum.
Jag går in i den tysta byggnaden.
Jag går fram till disken för att köpa en entrébiljett.
Det står en ung man bakom kassan.
"Hej, en vuxenbiljett, tack," säger jag.
"Det blir ett hundra kronor," säger han och skriver ut den.
Jag betalar och tittar på de här färgglada broschyrerna på disken.
De gör reklam för en särskild utställning om stadens historia.
"Ger den här biljetten också tillträde till utställningen en trappa upp?" frågar jag.
"Ja, det här museet har bara en kombinerad biljett," svarar han.
"Utställningen ligger en trappa upp, på första våningen," säger han.
"Du kan lugnt ta god tid på dig däruppe."
"Den har många gamla fotografier av staden," förklarar han.
"Några av dem är över hundra år gamla."
"Det låter riktigt spännande," säger jag.
"Tack så mycket," ler jag.
Jag tar min biljett och går lugnt uppför trappan.
