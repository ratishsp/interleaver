Piju svou vodu.
Voda je studená a příjemná.
Beru svou tašku z podlahy.
Moje přestávka skončila.
Jdu k pultu.
Ten milý barista tam stále stojí.
Dívá se na mě s úsměvem.
"Dáte si ještě něco?" ptá se.
"Ne, děkuji," odpovídám.
"Chtěla bych zaplatit."
"Ano, samozřejmě," říká.
Dívá se na svůj malý displej.
"Jedna černá káva a jeden skořicový šnek," říká.
"Ano, to souhlasí," říkám.
"Chcete platit kartou, nebo hotově?" ptá se.
"Chtěla bych platit kartou," odpovídám.
"Dobře."
"Bude to osmdesát pět korun," říká.
Vytahuji svou platební kartu.
