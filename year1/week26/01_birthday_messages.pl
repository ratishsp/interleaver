Obudziłam się dziś wcześnie rano.
Słońce jasno świeciło do mojej sypialni.
Leżałam w łóżku i myślałam o moim domu w Meksyku.
Tak naprawdę dzisiaj są moje urodziny.
Kończę dzisiaj trzydzieści dwa lata.
To moje pierwsze urodziny z dala od rodziny.
Czułam z tego powodu lekką nostalgię.
Ale potem wzięłam telefon z szafki nocnej.
Moja rodzina przysłała wiele czułych wiadomości.
Napisali je w nocy, kiedy spałam.
Moi rodzice nagrali zabawne wideo z Lolą, naszym psem.
Moja siostra Sofía napisała długą i uroczą wiadomość.
A mój brat Diego wysłał zdjęcie mojego ulubionego ciasta.
Uśmiechnęłam się szeroko, kiedy zobaczyłam to zdjęcie.
Wcale nie zapomnieli o moim wielkim dniu.
Od razu odpowiedziałam na wszystkie wiadomości.
Napisałam im, że ich kocham i za nimi tęsknię.
Czytam te wiadomości raz za razem.
To fantastyczny początek moich urodzin.
