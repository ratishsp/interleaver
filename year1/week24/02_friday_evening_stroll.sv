Det är sent fredag kväll.
Innan vi går och lägger oss tar jag med Ludwig ut.
Vi går en kort promenad i kvarteret.
Gatorna är mycket tysta nu.
Ludwig går fint bredvid mig.
Plötsligt stannar han.
Han nosar ivrigt på något på trottoaren.
Det är en smutsig påse med matrester.
Han öppnar munnen för att ta den.
"Nej, släpp den!" säger jag bestämt till honom.
Jag drar honom försiktigt bort från påsen.
"Skräpet är inte mat, Ludwig", förklarar jag.
"Kom hit, Ludwig", ropar jag på honom.
Han släpper påsen och tittar upp på mig.
Han börjar snabbt vifta på svansen.
"Duktig hund", säger jag och klappar honom.
Vi fortsätter vår promenad nerför gatan.
Nu ska vi bara hem och sova.
