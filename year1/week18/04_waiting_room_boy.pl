Siadam na krześle w poczekalni.
W pomieszczeniu jest prawie zupełnie cicho.
Czekam cierpliwie.
Moja głowa jest wciąż bardzo ciężka.
Matka i mały chłopiec siedzą naprzeciwko mnie.
Chłopiec ma może pięć lat.
Trzyma dłoń na prawym uchu.
„Aua, boli mnie ucho!” – mówi głośno.
Jego matka patrzy na niego.
„Wiem, kochanie” – mówi łagodnie.
„Ale to bardzo boli!” – narzeka chłopiec.
„Lekarz powinien nas wkrótce wezwać” – mówi matka.
Obejmuje go ramieniem.
Chłopiec wzdycha głośno.
Wygląda na bardzo zmęczonego.
Dobrze go rozumiem.
Moje własne gardło też bardzo boli.
Chcę tylko znów poczuć się dobrze.
