Jag står i mataffären efter jobbet.
Det är många människor i butiken i dag.
Jag har min inköpslista i handen.
Jag behöver exakta mängder till min middag i morgon.
Först går jag bort till grönsakerna.
Jag hittar några små, fina potatisar.
Jag lägger dem i en påse och väger dem.
Vågen visar precis ett kilo.
Det är den rätta mängden till receptet.
Sedan tar jag två stora, gula lökar.
Därefter går jag över till köttet.
Jag behöver fläskfärs till köttbullarna.
Jag tittar på de olika paketen i kyldisken.
Jag väljer ett paket med femhundra gram.
Till sist kollar jag min lista en extra gång.
Jag tar också ett paket smör och lite mjölk.
Jag lägger ner alla sakerna i min korg.
Nu är jag redo att laga mat till Kasper och Sara.
