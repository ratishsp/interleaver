Jag går fram till kassan.
Jag har korgen i handen.
Jag lägger maten på bandet.
Först tar jag rågbrödet ur korgen.
Sedan tar jag mjölken och palsternackan.
Jag tar också morötter och svarta bönor.
Till sist lägger jag kakan på bandet.
Kassören sitter bakom kassan.
Han ler mot mig.
"Hej", säger han.
"Hej", svarar jag.
Han skannar maten snabbt.
Jag tar fram mitt kort.
Jag håller kortet över maskinen.
Maskinen piper.
"Vill du ha kvittot?" frågar han.
"Ja tack, jag vill gärna ha kvittot", säger jag.
Jag öppnar min påse.
Jag packar påsen snabbt.
"Ha en bra dag", säger han.
