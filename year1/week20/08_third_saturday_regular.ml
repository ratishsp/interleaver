എൻ്റെ മൂന്നാമത്തെ ശനിയാഴ്ച, കൗണ്ടറിനു പിന്നിൽ ഞാൻ തയ്യാറായി നിന്നു.
കഫേയിൽ അല്പം സ്വസ്ഥമായിരിക്കാൻ ഞാൻ ഒടുവിൽ പഠിച്ചിരിക്കുന്നു.
ജനാലയിലൂടെ ഞാൻ തെരുവിൽ ഒരു പ്രായമുള്ള മനുഷ്യനെ കണ്ടു.
അദ്ദേഹം സാവധാനം മുൻവാതിലിനടുത്തേക്ക് നടന്നു.
എൻ്റെ ഒന്നാമത്തെയും രണ്ടാമത്തെയും ഷിഫ്റ്റിലും അദ്ദേഹം ഇവിടെ ഉണ്ടായിരുന്നു.
കഫേയിലെ സ്ഥിരം ഉപഭോക്താക്കളിൽ ഒരാളാണ് അദ്ദേഹം.
അദ്ദേഹത്തിൻ്റെ ഓർഡർ മനഃപാഠമാക്കാൻ ഞാൻ പഠിച്ചിട്ടുണ്ട്.
അദ്ദേഹം എപ്പോഴും കൃത്യമായി ഒരേ സാധനം തന്നെയാണ് വാങ്ങാറുള്ളത്.
വാതിൽ തുറന്ന് അദ്ദേഹം ക്യാഷ് രജിസ്റ്ററിനടുത്തേക്ക് വന്നു.
ഞാൻ അദ്ദേഹത്തെ നോക്കി പുഞ്ചിരിച്ചു.
"ഗുഡ് മോർണിംഗ്," ഞാൻ പറഞ്ഞു.
"നിങ്ങളുടെ സ്ഥിരം കോർട്ടാഡോ ഞാൻ ഉണ്ടാക്കട്ടെ?"
ആ മനുഷ്യൻ അത്ഭുതത്തോടെ എന്നെ നോക്കി.
പിന്നെ അദ്ദേഹം സന്തോഷത്തോടെ പുഞ്ചിരിച്ചു.
"അതെ, അത് വളരെ നന്നായിരിക്കും," അദ്ദേഹം മറുപടി പറഞ്ഞു.
ഞാൻ എസ്പ്രസ്സോ മെഷീനടുത്തേക്ക് പോയി.
ഞാൻ ഇപ്പോൾ ഒരുപാട് തവണ കാപ്പി ഉണ്ടാക്കിയിട്ടുണ്ട്, അതിനാൽ അത് വേഗത്തിൽ കഴിഞ്ഞു.
ഞങ്ങളുടെ അതിഥികളെ അറിയുന്നത് ഒരു നല്ല അനുഭവമായിരുന്നു.
