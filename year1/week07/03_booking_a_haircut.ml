ഇത് എന്റെ ഉച്ചഭക്ഷണ ഇടവേളയാണ്.
ഞാൻ ജോലിസ്ഥലത്തെ കാന്റീനിൽ ഇരിക്കുകയാണ്.
ഇന്നലെ എനിക്ക് തിരക്കായിരുന്നു.
അതുകൊണ്ട് ഞാൻ ഇപ്പോൾ ഹെയർഡ്രെസ്സറെ വിളിക്കുകയാണ്.
ഞാൻ എന്റെ മൊബൈൽ ഫോൺ എടുക്കുന്നു.
ഞാൻ നഗരത്തിലെ ഒരു ഹെയർ സലൂണിലേക്ക് വിളിക്കുന്നു.
ഒരു സ്ത്രീ ഫോണെടുക്കുന്നു.
"ഹലോ, ഇത് ഹെയർ സലൂൺ ആണ്," ആ സ്ത്രീ പറയുന്നു.
"ഹലോ, എന്റെ പേര് മായ എന്നാണ്," ഞാൻ പറയുന്നു.
"എനിക്ക് വ്യാഴാഴ്ച ഒരു അപ്പോയിന്റ്മെന്റ് ബുക്ക് ചെയ്യണം."
"ഒരു നിമിഷം," ഹെയർഡ്രെസ്സർ പറയുന്നു.
"നിങ്ങൾക്ക് ഉച്ചകഴിഞ്ഞ് ഒരു അപ്പോയിന്റ്മെന്റ് ഉണ്ടോ?" ഞാൻ ചോദിക്കുന്നു.
"അതെ, ഞങ്ങൾക്ക് നാലരയ്ക്ക് ഒരു അപ്പോയിന്റ്മെന്റ് ലഭ്യമാണ്," അവർ പറയുന്നു.
"അത് എനിക്ക് വളരെ അനുയോജ്യമാണ്," ഞാൻ പറയുന്നു.
"നിങ്ങളുടെ ഫോൺ നമ്പർ എന്താണ്?" ഹെയർഡ്രെസ്സർ ചോദിക്കുന്നു.
"എന്റെ നമ്പർ പന്ത്രണ്ട്, മുപ്പത്തിനാല്, അൻപത്തിയാറ്, എഴുപത്തിയെട്ട് ആണ്," ഞാൻ പറയുന്നു.
"വളരെ നന്ദി, വ്യാഴാഴ്ച നാലരയ്ക്ക് കാണാം," അവർ പറയുന്നു.
"കാണാം," ഞാൻ മറുപടി നൽകുന്നു.
ഞാൻ ഫോൺ മേശപ്പുറത്ത് വെക്കുന്നു.
ഇപ്പോൾ ഞാൻ ഒടുവിൽ എന്റെ ഭക്ഷണം കഴിക്കുകയാണ്.
