Jdu dál po trhu a zastavím se u stánku s oblečením.
Vidím těžký zimní kabát z vlny.
Tento kabát je krásný, ale velmi silný.
Přesto si kabát zkusím.
Je neuvěřitelně teplý.
Hned si ho zase sundám.
Je červenec a dnes svítí slunce.
Za stolem stojí přátelská žena a usmívá se.
„Je příliš teplý?“ ptá se žena.
„Ano, na léto je trochu moc teplý,“ odpovím a zasměju se.
Dotknu se silné látky.
„Ale tenhle zimní kabát jsem opravdu potřebovala před pěti měsíci!“ řeknu.
Žena se hlasitě zasměje.
„Ano, únor byl velmi studený,“ říká.
Vzpomenu si na své první týdny v Kodani.
Tehdy jsem neustále mrzla.
Naštěstí teď tak teplé oblečení nepotřebuji.
Pověsím kabát zpět na stojan a rozloučím se.
