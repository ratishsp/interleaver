Podchodzę do kasy.
Za ladą stoi młody mężczyzna.
Jest baristą w kawiarni.
Uśmiecham się do niego.
Przyjaźnie kiwa głową.
– Cześć – mówi.
– Co podać? – pyta.
– Cześć – odpowiadam.
– Poproszę czarną kawę.
– I czy mogę również prosić o cynamonkę?
– Oczywiście – mówi.
– Czarna kawa i cynamonka.
– Chcesz usiąść tutaj? – pyta.
– Tak, dziękuję, usiądę tam – mówię.
– W porządku – mówi barista.
– Już robię twoją kawę.
– Bardzo dziękuję – mówię.
