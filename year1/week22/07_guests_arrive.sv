Dörrklockan ringer.
Jag öppnar dörren med ett leende.
Kasper och Sara står utanför.
De ler och vinkar till mig.
"Hej Maya, och tack så mycket för inbjudan!" säger Kasper glatt.
"Hej!"
"Kom in," svarar jag.
"Det doftar redan fantastiskt," säger Sara.
"Ta av er jackorna först," säger jag till dem.
Jag tar deras jackor och hänger upp dem i hallen.
Därefter ger Sara mig en påse.
"Vi har tagit med några kalla öl," förklarar hon.
"Det är en lokal dansk öl," tillägger Kasper.
Jag tittar i påsen.
Det ligger sex flaskor i den.
"Tusen tack, det är helt perfekt," säger jag.
"Jag ställer bara in dem i kylskåpet."
"Bra idé, och sedan är vi redo att äta," skrattar Kasper.
Jag går ut i köket med flaskorna.
