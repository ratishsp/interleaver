ഇപ്പോൾ മാർച്ച് മാസമാണ്.
ഉച്ചകഴിഞ്ഞുള്ള സമയമാണ്.
കൊച്ചിയിൽ ഇപ്പോൾ വല്ലാത്ത ചൂടുണ്ട്.
നല്ല വെയിലുണ്ട്.
ഞാൻ ഒരു തിരക്കുള്ള റോഡിലൂടെ നടക്കുന്നു.
എനിക്ക് വല്ലാതെ ചൂടെടുക്കുന്നു.
ഞാൻ നന്നായി വിയർക്കുന്നു.
ഞാൻ വളരെ ക്ഷീണിതയാണ്.
എനിക്ക് കുറച്ച് തണുത്ത വെള്ളം വേണം.
എനിക്ക് അല്പം വിശ്രമവും വേണം.
ഞാൻ ചുറ്റും നോക്കുന്നു.
റോഡിന്റെ വശത്ത് ഞാൻ ഒരു ചെറിയ കഫേ കാണുന്നു.
പുറത്തെ ചൂടിൽ നിന്ന് എനിക്കൊരു മാറ്റം വേണം.
ഞാൻ വേഗത്തിൽ ആ കഫേയിലേക്ക് നടക്കുന്നു.
ഞാൻ വാതിൽ തുറന്ന് ഉള്ളിലേക്ക് കയറുന്നു.
കഫേയുടെ ഉള്ളിൽ നല്ല തണുപ്പുണ്ട്.
എനിക്ക് വലിയ ആശ്വാസം തോന്നുന്നു.
