ഞായറാഴ്ച ഉച്ചതിരിഞ്ഞ് ഞാൻ എന്റെ സ്വീകരണമുറിയിലെ സോഫയിൽ ഇരിക്കുന്നു.
ജനലിലൂടെ സൂര്യപ്രകാശം ഉള്ളിലേക്ക് അടിക്കുന്നുണ്ട്, മുറി നല്ല പ്രകാശപൂരിതമാണ്.
ഒരു നീണ്ട വീഡിയോ കോളിനായി ഞാൻ എന്റെ കമ്പ്യൂട്ടർ എന്റെ മുന്നിലുള്ള മേശപ്പുറത്ത് വെച്ചിട്ടുണ്ട്.
മെക്സിക്കോയിലുള്ള എന്റെ കുടുംബം മുഴുവൻ സ്ക്രീനിലുണ്ട്.
എന്റെ മാതാപിതാക്കളെയും സഹോദരി സോഫിയയെയും സഹോദരൻ ഡീഗോയെയും എനിക്ക് കാണാം.
പെട്ടെന്ന് ഞങ്ങളുടെ നായ ലോല വളരെ ഉച്ചത്തിൽ കുരയ്ക്കുന്നു.
അവൾ ആവേശത്തോടെ ക്യാമറയ്ക്ക് മുന്നിൽ ചാടിക്കളിക്കുന്നു.
"ലോലയ്ക്ക് നിന്നെ മിസ്സ് ചെയ്യുന്നുണ്ട്," സോഫിയ ചിരിച്ചുകൊണ്ട് പറയുന്നു.
"എനിക്കും നിങ്ങളെയെല്ലാവരെയും മിസ്സ് ചെയ്യുന്നുണ്ട്," ഞാൻ അവർക്ക് നേരെ കൈവീശിക്കൊണ്ട് പറയുന്നു.
എന്റെ അച്ഛൻ ഇവിടുത്തെ എന്റെ ജോലിയെക്കുറിച്ചും ദൈനംദിന ജീവിതത്തെക്കുറിച്ചും ചോദിക്കുന്നു.
എന്റെ ജോലിയെക്കുറിച്ചും എന്റെ ബാഡ്മിന്റൺ കളിയെക്കുറിച്ചും പ്രിയപ്പെട്ട അയൽക്കാരിയെക്കുറിച്ചും ഞാൻ അവരോട് പറയുന്നു.
ഞങ്ങൾ ഒരു മണിക്കൂറിലധികം നേരം സംസാരിക്കുന്നു.
ഞാൻ എന്റെ പ്രകാശപൂരിതമായ സ്വീകരണമുറിക്ക് ചുറ്റും നോക്കുന്നു.
ഇന്നലത്തെ ആ മനോഹരമായ പച്ചച്ചെടിയിലേക്ക് ഞാൻ നോക്കുന്നു.
ജനുവരിക്ക് ശേഷം ഒരുപാട് സമയം കടന്നുപോയി.
"അവിടെ താമസിക്കുന്നതിൽ നിനക്ക് സന്തോഷമുണ്ടോ?" എന്റെ അമ്മ ചോദിക്കുന്നു.
ഞാൻ അവരെ നോക്കി വിടർന്നു പുഞ്ചിരിക്കുന്നു.
"അതെ," ഞാൻ മറുപടി പറയുന്നു.
"എനിക്കിപ്പോൾ ഈ നഗരം ശരിക്കും എന്റെ സ്വന്തം വീടുപോലെ തോന്നുന്നു."
