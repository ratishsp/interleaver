Jest styczeń i jest bardzo zimno.
Idę do domu z przystanku autobusowego w Kopenhadze.
Widzę kwiaciarnię na ulicy.
W środku jest jasno i ciepło.
Wchodzę do ciepłego sklepu.
Patrzę na małą, zieloną roślinę.
Sprzedawca uśmiecha się do mnie.
– Dzień dobry – mówi.
– Dzień dobry – mówię.
– Szukam rośliny.
– Czy to na prezent? – pyta.
– Nie, to do mojego pokoju – odpowiadam.
– To naprawdę dobra roślina – mówi.
– Ile kosztuje? – pytam.
– Kosztuje pięćdziesiąt pięć koron – odpowiada.
Płacę za moją nową roślinę.
Wkłada roślinę do papierowej torby.
– Proszę, oto pani torba – mówi.
– Bardzo dziękuję – mówię radośnie.
Wychodzę w zimny wieczór.
Moja mała roślina bardzo mnie cieszy.
