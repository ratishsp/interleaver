Je čtvrtek odpoledne.
Mám po práci.
Jdu k opraváři kol.
Je tři čtvrtě na čtyři.
Mechanik stojí v obchodě.
„Ahoj,“ říkám.
Vyveze mi kolo.
„Vaše kolo je připravené,“ říká.
„Moc děkuji,“ říkám.
Kolo vypadá opravdu hezky.
Pneumatiky jsou teď tvrdé.
Vytlačím kolo ven na ulici.
Dnes svítí slunce.
Nasedám na kolo.
Často jezdím v Kodani na kole.
Je to velmi snadné.
Teď s radostí jedu na kole ke kadeřníkovi.
Jsem objednaná na půl pátou.
Těším se.
