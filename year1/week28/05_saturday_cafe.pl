Jest sobotni poranek, a ja jestem w lokalnej kawiarni.
W każdy weekend pracuję tu jako wolontariuszka.
Kawiarnia jest już pełna ludzi.
Stoję za dużą, drewnianą ladą.
Przecieram ladę czystą ściereczką.
Do lady podchodzi młody mężczyzna.
„Dzień dobry, poproszę dużą kawę” – mówi.
„I dwa ciepłe ciastka, poproszę” – dodaje.
„Oczywiście, już się robi” – odpowiadam z uśmiechem.
Podchodzę do dużego ekspresu do kawy.
Znam już tę maszynę bardzo dobrze.
Szybko przygotowuję parującą, gorącą filiżankę kawy.
Zapach świeżej kawy wypełnia małe pomieszczenie.
Następnie wkładam dwa ciepłe ciastka do papierowej torebki.
Podaję mu przez ladę kawę i torebkę.
„To będzie pięćdziesiąt pięć koron” – mówię.
Płaci kartą i odbiera kawę.
„Miłego weekendu” – mówi radośnie.
„Dziękuję, nawzajem” – odpowiadam.
Przywołuję gestem następnego klienta w kolejce.
