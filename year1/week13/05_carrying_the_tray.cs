Čekám u pultu.
Připravuje moji kávu.
Pokládá horký šálek kávy na dřevěný tác.
Na tác pokládá také malý talířek.
Můj skořicový šnek leží na talířku.
Krásně voní.
"Prosím, vaše objednávka," říká.
"Moc děkuji," odpovídám.
"Děkuji za dobrou obsluhu."
"Rádo se stalo," říká mile.
Beru tác oběma rukama.
Jdu velmi opatrně po podlaze.
Jdu zpátky ke svému stolu u okna.
Pokládám tác na stůl.
Teď bych si ráda sedla.
Jsem připravená na dobrou pauzu.
