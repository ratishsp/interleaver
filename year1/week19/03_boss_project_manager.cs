Po ranní schůzce sedím u svého stolu.
Dívám se na své poznámky z prezentace.
Můj šéf, Thomas, přichází ke mně.
Je to náš projektový manažer.
Pracuje tu už mnoho let.
„Dobré ráno, Mayo,“ říká s úsměvem.
„To byla opravdu dobrá prezentace.“
„Děkuji, Thomasi,“ odpovídám.
„Jsme moc rádi, že tě máme v týmu,“ pokračuje Thomas.
„Celý tým se těšil na spolupráci s tebou.“
„Také jsem se těšila,“ říkám radostně.
„Je to zajímavý projekt.“
Thomas se znovu usměje a jde zpátky do své kanceláře.
Dívám se na obrazovku svého počítače.
Cítím se v týmu opravdu vítaná.
