V neděli odpoledne sedím na pohovce ve svém obývacím pokoji.
Slunce svítí oknem dovnitř a pokoj je krásně světlý.
Na stole před sebou mám počítač na dlouhý videohovor.
Celá moje rodina v Mexiku je na obrazovce.
Vidím své rodiče, sestru Sofíi a bratra Diega.
Najednou náš pes, Lola, velmi hlasitě štěká.
Nadšeně poskakuje před kamerou.
„Lole chybíš,“ říká Sofía a směje se.
„Taky mi všichni chybíte,“ říkám a mávám jim.
Můj otec se ptá na mou práci a můj každodenní život tady.
Vyprávím jim o své práci, o badmintonu a o své milé sousedce.
Povídáme si spolu přes hodinu.
Rozhlížím se po svém světlém obývacím pokoji.
Dívám se na tu pěknou zelenou rostlinu ze včerejška.
Od ledna uplynulo hodně času.
„Bydlíš tam ráda?“ ptá se moje matka.
Široce se na ni usmívám.
„Ano,“ odpovídám.
„Opravdu se teď ve městě cítím jako doma.“
