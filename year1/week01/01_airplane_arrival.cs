Letadlo je teď v Kodani.
Je leden.
Jsem velmi nadšená.
Dávám si knihu do tašky.
Vedle mě je cestující.
Dívá se na mě a usmívá se.
„Ahoj,“ říká.
„Ahoj,“ říkám.
„Jak se jmenuješ?“ ptá se.
„Jmenuji se Maya,“ říkám.
„Odkud jsi, Mayo?“ ptá se.
Radostně se usmívám.
„Jsem z Mexika,“ odpovídám.
„Jsi z Dánska?“ ptám se.
„Ano, jsem z Dánska,“ říká.
„Vítej v Dánsku,“ říká.
„Moc děkuji,“ říkám.
Teď jsme tady.
Jsem připravená.
