Siedzę przy biurku w biurze w środę rano.
Eva podchodzi do mojego biurka z kubkiem kawy.
"Cześć Maya, masz czas w piątek?" – pyta z szerokim uśmiechem.
Myślę, że właściwie mam wolny wieczór.
"Tak, mam dużo czasu" – odpowiadam jej.
"Bardzo chciałabym zaprosić cię do siebie na kolację" – mówi.
Bardzo się cieszę z tego zaproszenia.
"Dziękuję, bardzo chętnie przyjdę" – mówię.
"Zamierzam przygotować wegetariańskie danie" – wyjaśnia Eva.
"To brzmi absolutnie idealnie" – uśmiecham się.
"O której powinnam tam być?" – pytam.
"Możesz po prostu przyjść o osiemnastej" – odpowiada.
Myślę, że zawsze miło jest odwiedzać nowych przyjaciół.
"Na pewno tam będę" – potwierdzam.
Eva zapisuje swój adres na małej żółtej karteczce.
Podaje mi tę karteczkę.
"Nie mogę się doczekać piątku" – mówię do niej.
Eva znów się uśmiecha i wraca do swojego komputera.
