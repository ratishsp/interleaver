ശനിയാഴ്ച വൈകുന്നേരം, ലുഡ്‌വിഗ് സോഫയിൽ എന്റെ അരികിലായി കിടന്നുറങ്ങുകയാണ്.
കാട്ടിലൂടെയുള്ള ഞങ്ങളുടെ നടത്തത്തിന് ശേഷം അവൻ വളരെ ക്ഷീണിതനാണ്.
ഞാൻ എന്റെ കമ്പ്യൂട്ടർ തുറന്ന് മെക്സിക്കോയിലുള്ള എന്റെ കുടുംബത്തിലേക്ക് വീഡിയോ കോൾ ചെയ്യുന്നു.
എന്റെ സഹോദരി സോഫിയയും എന്റെ സഹോദരൻ ഡീഗോയും സ്ക്രീനിന് മുന്നിൽ തയ്യാറായി ഇരിക്കുന്നുണ്ട്.
"നിങ്ങൾ തീർച്ചയായും എന്റെ ചെറിയ അതിഥിയെ കാണണം," ഞാൻ അവരോട് പറയുന്നു.
ഞാൻ കമ്പ്യൂട്ടർ എടുത്ത് ക്യാമറ താഴെ നായയ്ക്ക് നേരെ തിരിക്കുന്നു.
സന്തോഷത്തോടെ സോഫിയ പുഞ്ചിരിക്കുന്നു.
"അവനെ ഒന്ന് നോക്കൂ!"
"അവൻ ശരിക്കും ക്യൂട്ട് ആണ്," ഡീഗോ പറയുന്നു.
ലുഡ്‌വിഗ് ഒരു കണ്ണ് തുറക്കുന്നു, പക്ഷേ അവൻ എഴുന്നേൽക്കാതെ അവിടെത്തന്നെ കിടക്കുന്നു.
"അവനെ നോക്കൂ."
"നാട്ടിലെ നമ്മുടെ നായയായ ലോലയെപ്പോലെ തന്നെ അവനും വളരെ ശാന്തനാണ്," ഞാൻ പറയുന്നു.
അവനെ നോക്കാൻ എളുപ്പമാണോ എന്ന് ഡീഗോ എന്നോട് ചോദിക്കുന്നു.
"അതെ, അവനെ നോക്കാൻ എനിക്ക് വളരെ ഇഷ്ടമാണ്," ഞാൻ മറുപടി നൽകുന്നു.
"പുറത്ത് തെരുവിൽ നടക്കുമ്പോൾ അവനെ ലീഷ് ഇട്ട് നടത്തണം എന്ന് മാത്രമേയുള്ളൂ."
"പിന്നെ അവന് തീർച്ചയായും മനുഷ്യർ കഴിക്കുന്ന ഭക്ഷണം നൽകരുത്."
"അതുകൊണ്ട് ഞാൻ അവനുള്ള ട്രീറ്റുകൾ മാത്രമേ അവന് നൽകാറുള്ളൂ."
പെട്ടെന്ന് വീഡിയോയുടെ പശ്ചാത്തലത്തിൽ ലോല ഉച്ചത്തിൽ കുരയ്ക്കുന്നത് ഞങ്ങൾ കേൾക്കുന്നു.
ലുഡ്‌വിഗ് തലയുയർത്തി വളരെ ആശയക്കുഴപ്പത്തോടെ സ്ക്രീനിലേക്ക് നോക്കുന്നു.
"വീണ്ടും കിടന്നോളൂ, എന്റെ സുഹൃത്തേ," എന്ന് ഞാൻ സൗമ്യമായി പറഞ്ഞുകൊണ്ട് അവനെ തലോടുന്നു.
അവന് കുറച്ച് സ്വസ്ഥത കിട്ടാൻ വേണ്ടി ഞാൻ എന്റെ കുടുംബത്തോട് ശുഭരാത്രി പറയുന്നു.
അവൻ കണ്ണുകൾ അടച്ച് പെട്ടെന്ന് തന്നെ വീണ്ടും ഉറങ്ങുന്നു.
