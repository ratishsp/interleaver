Všichni tři jsme teď velmi sytí.
Na stole už nezbylo žádné jídlo.
„Byla to fantastická večeře, Mayo,“ říká Sara vesele.
„Jak přesně se dělají tyhle karbanátky?“ ptá se potom.
„Je to hodně těžké?“
„Ne, vlastně je to docela snadné,“ odpovídám.
„Nejdřív nakrájíš cibuli a potom smícháš maso,“ vysvětluji.
„Mám v telefonu opravdu dobrý recept.“
„Dnes večer ti pošlu odkaz.“
„Moc děkuji, to bych ráda zkusila,“ říká Sara.
Vstáváme z malých židlí.
Kasper začíná sbírat prázdné talíře.
„Máme teď odnést talíře do kuchyně?“ ptá se.
„Ano, prosím.“
„Jen je položte na kuchyňskou linku,“ říkám.
Rychle společně sklízíme stůl.
„Ale hele, příště jsem na řadě já,“ říká Kasper najednou.
„Ano.“
„Příště nám musíš uvařit ty!“
Sara se směje.
„Přesně tak.“
„A slibuju, že to bude dobré,“ říká.
Smějeme se a odnášíme zbytek věcí do kuchyně.
