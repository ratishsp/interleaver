ഞാൻ രാവിലെ എഴുന്നേൽക്കുന്നു.
ഞാൻ ജനൽ തുറക്കുന്നു.
പുറത്ത് നല്ല വെയിലാണ്.
കൊച്ചിയിൽ ഇപ്പോൾ നല്ല ചൂടാണ്.
ഞാൻ എന്റെ ഫോൺ എടുക്കുന്നു.
ഞാൻ ഫോണിൽ കാലാവസ്ഥ നോക്കുന്നു.
ആപ്പിൽ ഇന്നത്തെ കാലാവസ്ഥ കാണിക്കുന്നു.
രാവിലെ നല്ല ചൂടാണ്.
ഉച്ചയ്ക്കും വലിയ ചൂടാണ്.
പക്ഷേ, വൈകുന്നേരം മഴ പെയ്യും.
എനിക്ക് ഓഫീസിൽ പോകണം.
ഞാൻ അലമാര തുറക്കുന്നു.
ഞാൻ ഒരു കോട്ടൺ വസ്ത്രം എടുക്കുന്നു.
ഈ ചൂടിന് കോട്ടൺ വസ്ത്രമാണ് നല്ലത്.
ഞാൻ അത് ധരിക്കുന്നു.
ഞാൻ എന്റെ ബാഗ് എടുക്കുന്നു.
ഞാൻ ബാഗിൽ ഒരു കുട വെക്കുന്നു.
ഇന്ന് മഴ പെയ്യും.
അതുകൊണ്ട് കുട ആവശ്യമാണ്.
ഞാൻ പുറത്തേക്ക് പോകാൻ തയ്യാറാകുന്നു.
