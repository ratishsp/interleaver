ഞാൻ കൊച്ചിയിലെ ഒരു വലിയ സൂപ്പർമാർക്കറ്റിലേക്ക് നടക്കുന്നു.
ഇന്ന് നല്ല കാലാവസ്ഥയാണ്.
ഞാൻ സൂപ്പർമാർക്കറ്റിൽ കയറുന്നു.
ഞാൻ അവിടെനിന്ന് ഒരു കാർട്ട് എടുക്കുന്നു.
എനിക്ക് എന്റെ അടുക്കളയിലേക്ക് കുറച്ചു സാധനങ്ങൾ വേണം.
എനിക്ക് പ്രധാനമായും അരിയും പരിപ്പും വേണം.
ഞാൻ അരിയുടെ ഭാഗത്തേക്ക് നടക്കുന്നു.
ഇവിടെ പലതരം അരികൾ ഉണ്ട്.
എനിക്ക് കേരളത്തിലെ അരി വേണം.
ഞാൻ അഞ്ച് കിലോയുടെ ഒരു വലിയ പാക്കറ്റ് എടുക്കുന്നു.
അതിന് നല്ല ഭാരമുണ്ട്.
ഞാൻ അത് എന്റെ കാർട്ടിൽ വെക്കുന്നു.
പിന്നെ, ഞാൻ പരിപ്പ് തിരയുന്നു.
ഞാൻ മഞ്ഞ പരിപ്പിന്റെ ഒരു പാക്കറ്റ് കാണുന്നു.
എനിക്ക് അതും വേണം.
ഞാൻ ആ പരിപ്പും കാർട്ടിൽ വെക്കുന്നു.
ഇപ്പോൾ എന്റെ കാർട്ടിൽ പ്രധാനപ്പെട്ട സാധനങ്ങൾ ഉണ്ട്.
