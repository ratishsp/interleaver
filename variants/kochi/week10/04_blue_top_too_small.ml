ഞാൻ തിരികെ വസ്ത്രങ്ങളുടെ അടുത്തേക്ക് പോകുന്നു.
ഞാൻ ഒരു നീല ടോപ്പ് കാണുന്നു.
അതൊരു കോട്ടൺ ടോപ്പ് ആണ്.
അത് നല്ലൊരു ടോപ്പ് ആണ്.
ഞാൻ ആ ടോപ്പ് എടുക്കുന്നു.
ഞാൻ ഫിറ്റിംഗ് റൂമിലേക്ക് പോകുന്നു.
ഞാൻ ആ നീല ടോപ്പ് ഇടുന്നു.
ഞാൻ കണ്ണാടിയിൽ നോക്കുന്നു.
ഈ ടോപ്പ് വളരെ ചെറുതാണ്.
ഇതൊരു ചെറിയ ടോപ്പ് ആണ്.
ഞാൻ ആ ടോപ്പ് മാറ്റുന്നു.
ഞാൻ പുറത്തേക്ക് വരുന്നു.
സെയിൽസ്‌വുമൺ എന്നെ നോക്കുന്നു.
അവർ ചോദിക്കുന്നു, "ടോപ്പ് നല്ലതാണോ?"
ഞാൻ പറയുന്നു, "അല്ല, ഇതൊരു ചെറിയ ടോപ്പ് ആണ്."
"ഈ നീല ടോപ്പ് എനിക്ക് വളരെ ചെറുതാണ്."
"എനിക്ക് ഒരു വലിയ ടോപ്പ് വേണം."
ഞാൻ ആ നീല ടോപ്പ് തിരികെ കൊടുക്കുന്നു.
ഞാൻ വേറെ വസ്ത്രങ്ങൾ നോക്കുന്നു.
