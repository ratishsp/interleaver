ഓഫീസിലെ ജോലി കഴിയുന്നു.
ഞാൻ ബസ് സ്റ്റോപ്പിലേക്ക് നടക്കുകയാണ്.
ഒരു പച്ച ബസ് വരികയാണ്.
ഞാൻ ബസ്സിൽ കയറുന്നു.
ഞാൻ ജനലിന്റെ അടുത്ത് ഇരിക്കുന്നു.
ബസ് മുന്നോട്ട് പോവുകയാണ്.
ഞാൻ പുറത്തേക്ക് നോക്കുന്നു.
കൊച്ചി നഗരത്തിൽ സൂര്യൻ അസ്തമിക്കുകയാണ്.
ആകാശം വളരെ മനോഹരമാണ്.
ഞാൻ പുറത്തെ കടകൾ കാണുകയാണ്.
ആ കടകൾക്ക് പല നിറങ്ങളുണ്ട്.
റോഡിൽ വളരെ തിരക്കാണ്.
ബസ് പതുക്കെ പോവുകയാണ്.
ജനലിലൂടെ നല്ല കാറ്റ് വരികയാണ്.
എന്റെ ക്ഷീണം മാറുന്നു.
ഞാൻ നല്ലപോലെ വിശ്രമിക്കുകയാണ്.
എനിക്ക് വളരെ സമാധാനം തോന്നുന്നു.
