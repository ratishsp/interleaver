ഇന്ന് ശനിയാഴ്ച രാവിലെയാണ്.
ഞാൻ കഫേയിൽ സഹായിക്കാൻ നിൽക്കുകയാണ്.
ഇന്ന് കഫേയിൽ ധാരാളം ആളുകൾ ഉണ്ട്.
ഞാനും ജെസ്സിയും വേഗത്തിൽ ജോലി ചെയ്യുന്നു.
ഞങ്ങൾക്ക് അധികം സംസാരിക്കേണ്ട ആവശ്യമില്ല.
എന്താണ് ചെയ്യേണ്ടതെന്ന് ഞങ്ങൾക്ക് ഇപ്പോൾ നന്നായി അറിയാം.
"നാലാമത്തെ ടേബിളിലേക്ക് രണ്ട് കോഫി," ജെസ്സി വിളിച്ചു പറയുന്നു.
"ഞാൻ ഉണ്ടാക്കാം," ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ പാൽ ചൂടാക്കി നല്ല രണ്ട് കോഫി ഉണ്ടാക്കുന്നു.
ജെസ്സി അവ വേഗം മേശയിലേക്ക് കൊണ്ടുപോകുന്നു.
ആളുകൾ ചൂട് ചായ കുടിച്ചുകൊണ്ട് മഴ നോക്കി ഇരിക്കുകയാണ്.
കഫേയ്ക്കുള്ളിൽ നല്ല ചൂടും തിരക്കുമുണ്ട്.
ഇപ്പോൾ ഞാൻ കോഫികൾ തയ്യാറാക്കുന്നു, ജെസ്സി അവ കൊടുക്കുന്നു.
ഞങ്ങൾ ഒരു നല്ല ടീമായി ജോലി ചെയ്യുകയാണ്.
ഇവിടുത്തെ എന്റെ ആദ്യത്തെ കോഫി പൂർണ്ണമായും തെറ്റായിപ്പോയിരുന്നു.
ഇപ്പോൾ എല്ലാ കോഫിയും നന്നായി വരുന്നു.
