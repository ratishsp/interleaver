മെക്സിക്കോയിൽ ഇപ്പോൾ രാത്രിയാണ്.
"ഇപ്പോൾ സമയം വൈകി," അമ്മ പറയുന്നു.
"ഉറങ്ങാൻ സമയമായി," അച്ഛൻ പറയുന്നു.
ഞാൻ എന്റെ കുടുംബത്തെ നോക്കുന്നു.
"ഡീഗോ ചേട്ടാ, ശുഭരാത്രി," ഞാൻ പറയുന്നു.
ഡീഗോ ചേട്ടൻ കൈ വീശുന്നു.
"സോഫിയാ, ശുഭരാത്രി," ഞാൻ പറയുന്നു.
അവൾക്കും ഉറക്കം വരുന്നുണ്ട്.
"ലോലയ്ക്ക് ഒരു ഉമ്മ," ഞാൻ പറയുന്നു.
"ശുഭരാത്രി മായാ," അമ്മയും അച്ഛനും പറയുന്നു.
എല്ലാവരുടെയും മുഖത്ത് ഒരു നല്ല പുഞ്ചിരിയുണ്ട്.
ഞാൻ അവർക്ക് സന്തോഷത്തോടെ കൈ വീശുന്നു.
ഞാൻ കോൾ അവസാനിപ്പിക്കുന്നു.
ഞാൻ മെല്ലെ എന്റെ ലാപ്ടോപ്പ് അടയ്ക്കുന്നു.
ഇപ്പോൾ എന്റെ മുറിയിൽ വലിയ നിശബ്ദതയാണ്.
എനിക്ക് ഒരു ചെറിയ സങ്കടം തോന്നുന്നു.
ഞാൻ എന്റെ കുടുംബത്തെ ഓർക്കുന്നു.
