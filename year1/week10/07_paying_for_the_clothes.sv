Jag går fram till kassan med mina nya kläder.
Expediten ler vänligt mot mig.
"Är det allt?" frågar hon.
"Ja, det är allt," svarar jag.
Hon skannar alla mina nya saker.
Det är en tröja, en jacka, en halsduk och handskar.
"Nu kommer du inte att frysa," säger hon glatt.
"Det blir ettusen femhundra kronor, tack."
Kläderna är dyra, men de är väldigt varma.
Jag tar fram mitt betalkort.
"Jag betalar med kort," säger jag.
"Du kan bara betala här," säger hon.
Hon pekar på en liten, svart maskin.
Jag håller mitt kort över maskinen.
Den piper, och betalningen är godkänd.
"Vill du ha kvittot?" frågar expediten.
"Nej tack," svarar jag.
Nu äger jag en massa fina vinterkläder.
