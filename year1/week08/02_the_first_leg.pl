Podążam trasą Niny.
Powietrze jest rześkie i zimne.
Teraz idę główną ulicą.
Najpierw po prostu idę prosto.
Na ulicy jest duży ruch.
Po drodze widzę trzy żółte rowery.
Rowery szybko mnie mijają.
Następnie idę dalej przed siebie.
Potem dochodzę do dużego parku.
Teraz przypominam sobie słowa Niny.
„Skręć w lewo przy parku” – mówi.
Tutaj skręcam w lewo.
Chwilę później widzę otwarte drzwi.
To mała piekarnia.
Czuć cudowny zapach świeżej kawy.
Uwielbiam ciepły chleb.
Dzisiaj miasto jest piękne.
Potem idę dalej w stronę wody.
