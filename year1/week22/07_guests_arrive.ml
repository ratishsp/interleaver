ഡോർബെൽ മുഴങ്ങുന്നു.
ഞാൻ ഒരു പുഞ്ചിരിയോടെ വാതിൽ തുറക്കുന്നു.
കാസ്പറും സാറയും പുറത്തു നിൽക്കുന്നു.
അവർ എന്നെ നോക്കി ചിരിക്കുകയും കൈവീശുകയും ചെയ്യുന്നു.
"ഹായ് മായാ, ക്ഷണിച്ചതിന് വളരെ നന്ദി!" സന്തോഷത്തോടെ കാസ്പർ പറയുന്നു.
"ഹായ്!"
"അകത്തേക്ക് വരൂ," ഞാൻ മറുപടി നൽകുന്നു.
"ഇപ്പോൾത്തന്നെ ഗംഭീരമായ മണം വരുന്നുണ്ട്," സാറ പറയുന്നു.
"ആദ്യം നിങ്ങളുടെ ജാക്കറ്റുകൾ ഊരിവെക്കൂ," ഞാൻ അവരോട് പറയുന്നു.
ഞാൻ അവരുടെ ജാക്കറ്റുകൾ വാങ്ങി ഇടനാഴിയിൽ തൂക്കിയിടുന്നു.
അതിനുശേഷം, സാറ എനിക്കൊരു ബാഗ് തരുന്നു.
"ഞങ്ങൾ കുറച്ചു തണുത്ത ബിയർ കൊണ്ടുവന്നിട്ടുണ്ട്," അവൾ വിശദീകരിക്കുന്നു.
"ഇതൊരു പ്രാദേശിക ഡാനിഷ് ബിയറാണ്," കാസ്പർ കൂട്ടിച്ചേർക്കുന്നു.
ഞാൻ ആ ബാഗിനുള്ളിലേക്ക് നോക്കുന്നു.
അതിൽ ആറ് കുപ്പികളുണ്ട്.
"വളരെ നന്ദി, ഇത് തികച്ചും മികച്ചതാണ്," ഞാൻ പറയുന്നു.
"ഞാൻ ഇതെടുത്ത് ഫ്രിഡ്ജിൽ വെക്കാം."
"നല്ല ആശയം, അപ്പോൾ നമ്മൾ കഴിക്കാൻ തയ്യാറാണ്," കാസ്പർ ചിരിക്കുന്നു.
ഞാൻ ആ കുപ്പികളുമായി അടുക്കളയിലേക്ക് നടക്കുന്നു.
