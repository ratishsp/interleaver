ഈവ രണ്ട് വലിയ കപ്പുകളിലേക്ക് കാപ്പി പകരുന്നു.
ഞങ്ങൾ സ്വീകരണമുറിയിലെ മൃദുവായ സോഫയിൽ ഇരിക്കുന്നു.
"ഇപ്പോൾ നഗരത്തിൽ നിനക്ക് എങ്ങനെയുണ്ട്?" ഈവ ചോദിക്കുന്നു.
ഞാൻ ചൂടുള്ള കാപ്പി ഒരിറക്ക് കുടിക്കുന്നു.
എന്റെ പുതിയ ജീവിതം ശരിക്കും വളരെ മനോഹരമാണെന്ന് എനിക്ക് തോന്നുന്നതായി ഞാൻ അവളോട് പറയുന്നു.
"ഞാൻ ഒടുവിൽ ഇവിടെ നന്നായി പൊരുത്തപ്പെട്ടു," ഒരു പുഞ്ചിരിയോടെ ഞാൻ പറയുന്നു.
"അത് കേൾക്കുന്നതിൽ എനിക്ക് സന്തോഷമുണ്ട്," അവൾ മറുപടി പറയുന്നു.
"ഓഫീസിലെ നമ്മുടെ പ്രോജക്റ്റിനുവേണ്ടി നീയും വളരെ കഠിനമായി അധ്വാനിക്കുന്നുണ്ട്."
"അതെ, പക്ഷേ ഇപ്പോൾ കൂടുതൽ സമയം ഒഴിവെടുക്കാനാണ് ഞാൻ ഉദ്ദേശിക്കുന്നത്," ഞാൻ പറയുന്നു.
"വാരാന്ത്യങ്ങളിൽ ഞാൻ നഗരം കൂടുതൽ ആസ്വദിക്കും."
"അതെനിക്ക് നന്നായി മനസ്സിലാകും," ഈവ പറയുന്നു.
ഞങ്ങൾ ഞങ്ങളുടെ മറ്റ് സഹപ്രവർത്തകരെക്കുറിച്ചും ജോലിയെക്കുറിച്ചും വളരെ നേരം സംസാരിക്കുന്നു.
ഞങ്ങൾ ചിരിക്കുകയും നിരവധി കഥകൾ പങ്കിടുകയും ചെയ്യുന്നു.
ഞാൻ കാപ്പിക്കപ്പിന് മുകളിലൂടെ അവളെ നോക്കി പുഞ്ചിരിക്കുന്നു.
ജോലിക്ക് പുറത്തും നമ്മൾ ഇനിയും തമ്മിൽ കാണുമെന്ന് ഞാൻ പ്രതീക്ഷിക്കുന്നു എന്ന് ഞാൻ പറയുന്നു.
"തീർച്ചയായും കാണാം," അവൾ സന്തോഷത്തോടെ മറുപടി പറയുന്നു.
നമുക്ക് ഒരുമിച്ച് രസകരമായ നിരവധി സായാഹ്നങ്ങൾ ഉണ്ടാകുമെന്ന് ഞാൻ കരുതുന്നു.
