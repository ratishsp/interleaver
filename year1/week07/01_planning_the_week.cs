Je pondělí ráno.
Dělám si šálek horkého čaje.
Sedím u stolu v kuchyni.
Otevírám svůj kalendář.
Vždycky si tady plánuji svůj týden.
Teď je únor.
Měsíc je už velmi plný.
Zítra je úterý.
Moje kolo je bohužel rozbité.
Zítra ráno jdu k opraváři kol.
Otevírá v osm hodin.
Píšu si to do kalendáře.
Dnes také volám kadeřníkovi.
Moje vlasy jsou až příliš dlouhé.
Ve středu jdu do posilovny.
Ve středu často cvičím.
Obvykle je to v sedm hodin večer.
Znovu se dívám na svůj plán.
Piju svůj čaj.
Teď jsem připravená na nový týden.
