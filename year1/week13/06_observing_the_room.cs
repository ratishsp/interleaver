Teď sedím u svého malého stolku.
Je tu krásně teplo.
Dívám se na svého skořicového šneka.
Voní sladce a dobře.
Vezmu si malé sousto.
Pečivo je úplně čerstvé a teplé.
Chutná opravdu dobře.
Odpiju si trochu své černé kávy.
Konečně mám prsty zase v teple.
Odpočívám v měkkém křesle.
Kavárna je téměř plná lidí.
Lidé sedí v malých skupinkách.
Povídají si a společně se smějí.
Poslouchám tiché hlasy v místnosti.
Ten zvuk je velmi příjemný.
Dívám se ven z velkého okna.
Počasí venku je šedé a větrné.
Teď vlastně zase sněží.
Bílé sněhové vločky pomalu padají dolů na ulici.
Jsem prostě ráda, že jsem uvnitř.
