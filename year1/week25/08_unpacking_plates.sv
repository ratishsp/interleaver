Jag är tillbaka i min lägenhet.
Det är söndag kväll, och det är väldigt tyst här.
Jag står ute i köket.
Jag diskar mina nya tallrikar i diskhon.
De här tallrikarna är verkligen vackra.
De är blå och lite tunga.
Jag torkar dem med en kökshandduk.
Efteråt ställer jag in dem i skåpet.
Jag går in i vardagsrummet och tittar ut genom fönstret.
Solen går långsamt ner över stadens tak.
Den här sommarkvällen är vacker och ljus.
Jag tycker verkligen om det här kvarteret.
Jag har bott här i ett halvår nu.
Det har hänt så mycket sedan januari.
Då kände jag ingen i staden.
Nu känner jag gatorna och vardagen mycket bättre.
Jag känner mig helt hemma i den här staden.
I morgon är det måndag, och jag tar bussen till jobbet.
Men just nu kopplar jag bara av.
Jag är helt nöjd med mitt liv här.
