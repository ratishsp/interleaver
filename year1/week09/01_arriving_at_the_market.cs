Je sobotní ráno.
V Dánsku je zima.
Počasí je dnes velmi chladné.
Stojím na velkém náměstí ve městě.
Je tu venkovní trh.
Dívám se na spoustu stánků.
Všechny vypadají lákavě.
Na náměstí je hodně lidí.
Lidé mají na sobě teplé zimní oblečení.
Mám na sobě jen tenkou bundu.
Mám s sebou velkou tašku.
Taška je právě teď úplně prázdná.
Hledám čerstvé jídlo na víkend.
Trh nabízí spoustu čerstvého zboží.
Vidím zeleninu, ovoce a chléb.
Přemýšlím o cenách.
Kolik tady věci stojí?
Jdu k prvnímu stánku.
