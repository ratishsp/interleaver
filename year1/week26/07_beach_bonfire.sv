Jag går ner till stranden.
Många människor har redan anlänt till kvällens fest.
Jag letar efter Eva och Peter i mängden.
Plötsligt ser jag dem nere vid vattnet, och jag skyndar mig dit.
"Har du haft en bra födelsedagsvecka?" frågar Peter med ett leende.
"Ja, den har varit helt fantastisk," svarar jag glatt.
Eva öppnar en liten korg.
"Jag köpte färska jordgubbar på marknaden i morse," säger hon.
"Har du någonsin smakat danska sommarjordgubbar?"
"Nej, det har jag aldrig provat," säger jag och tar ett bär.
Det smakar otroligt sött och påminner mig om sommar.
Just i det ögonblicket tänder en man det stora bålet.
Lågorna växer snabbt och sträcker sig högt upp mot himlen.
Det var kallt tidigare, men nu har elden värmt upp luften.
Den glödande värmen jagar snabbt bort kylan från kusten.
Vi står tätt tillsammans och tittar länge in i lågorna.
Jag tänker på att jag nu har bott här i staden i sex månader.
Min första månad här var mörk, men den här ljusa sommarkvällen är perfekt.
