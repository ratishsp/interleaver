ഇന്ന് ശനിയാഴ്ചയാണ്.
നല്ല വെയിലുള്ള ഒരു പ്രഭാതം.
എനിക്ക് നഗരം കാണണം.
ഞാൻ എന്റെ അപ്പാർട്ട്മെന്റിൽ നിന്ന് പുറത്തിറങ്ങുന്നു.
ഇടനാഴിയിൽ വെച്ച് ഞാൻ അനിതയെ കാണുന്നു.
"സുപ്രഭാതം, മായ," അവർ പറയുന്നു.
"സുപ്രഭാതം അനിത," ഞാൻ പറയുന്നു.
"നഗരത്തിൽ നടക്കാൻ നല്ലൊരു സ്ഥലം ഉണ്ടോ?" ഞാൻ ചോദിക്കുന്നു.
"ഉണ്ട്, കായൽ തീരത്തെ വാക്ക് വേയിലേക്ക് പോകാം," അനിത പറയുന്നു.
"അവിടേക്ക് എങ്ങനെ പോകും?" ഞാൻ ചോദിക്കുന്നു.
"ഈ കെട്ടിടത്തിൽ നിന്ന് നേരെ പുറത്തേക്ക് നടക്കൂ," അവർ പറയുന്നു.
"എന്നിട്ട് ഇടത്തോട്ട് തിരിയൂ."
"മെയിൻ ബസ് സ്റ്റോപ്പിലേക്ക് നേരെ നടക്കൂ," അനിത പറയുന്നു.
"അവിടെ നിന്ന് നഗരത്തിലേക്ക് ഒരു ബസ്സ് കയറൂ."
"നഗരത്തിൽ എത്തിയിട്ട് കായൽ തീരത്തേക്കുള്ള വഴി ആരോടെങ്കിലും ചോദിക്കൂ," അവർ പറയുന്നു.
ഞാൻ ചിരിച്ചുകൊണ്ട് അവരോട് നന്ദി പറയുന്നു.
ഞാൻ ഗേറ്റിലേക്ക് നേരെ നടക്കുന്നു.
എന്നിട്ട് ഇടത്തോട്ട് തിരിയുന്നു.
കൊച്ചി നഗരം കാണുന്നതിൽ എനിക്ക് വളരെ സന്തോഷമുണ്ട്.
