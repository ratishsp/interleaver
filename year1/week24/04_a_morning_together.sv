Efter frukosten har jag gott om tid.
Jag arbetar normalt som volontär på ett kafé på lördagarna.
Men Ludwig ska inte vara ensam.
Lyckligtvis är jag ledig från kaféet i dag.
Jag bestämde det med dem förra veckan.
Nu har Ludwig och jag hela morgonen tillsammans.
Vi går ut på gården bakom min byggnad.
Jag tar fram hans lilla boll.
"Titta på bollen, Ludwig!" säger jag till honom.
Jag kastar den över gräset.
"Hämta den!" ropar jag.
Han springer snabbt och fångar bollen.
"Kom hit!" ropar jag.
Han springer glatt tillbaka till mig.
"Ge mig den", säger jag mjukt.
Han släpper bollen, och jag klappar honom.
"Du är en duktig hund", säger jag och ler.
Jag kastar den igen, och han hämtar den.
Jag måste ta väl hand om honom hela helgen.
Jag är mycket glad över att jag stannade hemma med honom.
