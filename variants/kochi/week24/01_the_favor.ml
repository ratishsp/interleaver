വ്യാഴാഴ്ച വൈകുന്നേരം വളരെ വൈകി ഞാൻ എന്റെ ഫ്ലാറ്റിൽ തിരിച്ചെത്തുന്നു.
എല്ലാ വ്യാഴാഴ്ചയും അഞ്ചരയ്ക്ക് ഞാൻ ബാഡ്മിന്റൺ കളിക്കാൻ പോകാറുണ്ട്.
ക്ലബ്ബിലെ റാക്കറ്റ് തിരികെ കൊടുത്തിട്ടാണ് ഞാൻ വരുന്നത്.
അപ്പോൾ വാതിലിൽ ഒരു മുട്ട് കേൾക്കുന്നു.
ഞാൻ വാതിൽ തുറക്കുന്നു.
എന്റെ അയൽക്കാരി അനിതയാണ് പുറത്ത് നിൽക്കുന്നത്.
"മായേ, എനിക്ക് ഈ വാരാന്ത്യത്തിൽ ഒന്ന് യാത്ര ചെയ്യണം," അനിത പറയുന്നു.
"എനിക്ക് നിന്നോട് ഒരു ചെറിയ സഹായം ചോദിക്കാൻ ഉണ്ട്."
"എന്താണ് അനിത?" ഞാൻ ചോദിക്കുന്നു.
"എന്റെ നായ ടോമിയെ ഈ വാരാന്ത്യത്തിൽ ഒന്ന് നോക്കാമോ?" അവർ ചോദിക്കുന്നു.
"അവനെ ദിവസം മുഴുവൻ ഒറ്റയ്ക്ക് ആക്കാൻ പാടില്ല," അവർ പറയുന്നു.
ഞാൻ വളരെ സന്തോഷത്തോടെ ആ സഹായം ചെയ്യാൻ സമ്മതിക്കുന്നു.
"തീർച്ചയായും നോക്കാം, എനിക്ക് നായ്ക്കളെ വളരെ ഇഷ്ടമാണ്," ഞാൻ പറയുന്നു.
"മെക്സിക്കോയിലെ എന്റെ വീട്ടിലും ഒരു നായ ഉണ്ട്."
"അവനെ ഞാൻ നോക്കാം, അനിത വിഷമിക്കേണ്ട," ഞാൻ പറയുന്നു.
"വളരെ നന്ദി മായേ, ഞാൻ നാളെ വൈകുന്നേരം അവനെ കൊണ്ടുവരാം," അനിത ചിരിച്ചുകൊണ്ട് പറയുന്നു.
ഈ വാരാന്ത്യത്തിൽ ടോമിയോടൊപ്പം സമയം ചിലവഴിക്കാൻ ഞാൻ കാത്തിരിക്കുകയാണ്.
