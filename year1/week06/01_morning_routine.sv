Det är fortfarande mörkt ute.
På morgonen vaknar jag långsamt.
Jag ligger en liten stund i sängen.
Idag är en helt vanlig vardag.
Nu stiger jag ur sängen.
Golvet är lite kallt under mina fötter.
Jag går direkt ut till badrummet.
I badrummet sätter jag på vattnet.
Vattnet är varmt och skönt.
Jag kliver in i duschkabinen.
Här tar jag en härlig varm dusch.
Först tvättar jag håret med schampo.
Efteråt tvättar jag mig med tvål.
Tvålen doftar fräscht av citrus.
Det varma vattnet väcker mig.
Till sist stänger jag av duschen.
Jag tar en mjuk handduk.
Nu torkar jag mig noggrant.
Jag är helt vaken och redo för dagen.
