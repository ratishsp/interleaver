എൻ്റെ അപ്പാർട്ട്മെൻ്റിൽ ഇതൊരു ശാന്തമായ ചൊവ്വാഴ്ച വൈകുന്നേരമാണ്.
ഞാൻ എൻ്റെ ചെറിയ അടുക്കള മേശ വൃത്തിയാക്കുന്നു.
പാത്രങ്ങൾ കഴുകി, മേശ തുടച്ചു വൃത്തിയാക്കിയിരിക്കുന്നു.
ഓഫീസിലെ നീണ്ട ഒരു ദിവസത്തിന് ശേഷമുള്ള ശാന്തത ഞാൻ ആസ്വദിക്കുന്നു.
എന്നാൽ പെട്ടെന്ന് എനിക്കൊരു പ്രധാനപ്പെട്ട കാര്യം ഓർമ്മവരുന്നു.
എൻ്റെ വൈദ്യുതി ദാതാവിൻ്റെ വെബ്സൈറ്റിൽ എൻ്റെ കോൺടാക്റ്റ് വിവരങ്ങൾ എനിക്ക് അപ്ഡേറ്റ് ചെയ്യേണ്ടതുണ്ട്.
അവരിൽ നിന്നും ഓർമ്മപ്പെടുത്തുന്ന ഒരു ഇമെയിൽ എനിക്ക് ലഭിച്ചിട്ടുണ്ട്.
ആ സന്ദേശത്തിൽ ഇങ്ങനെ പറയുന്നു: "ബുധനാഴ്ചയ്ക്ക് മുമ്പായി നിങ്ങളുടെ വിവരങ്ങൾ അപ്ഡേറ്റ് ചെയ്തിരിക്കണം."
അത് നാളെത്തന്നെയാണല്ലോ!
ഇത് വളരെ മടുപ്പിക്കുന്ന ഒരു ഡിജിറ്റൽ ജോലിയാണ്.
ഞാൻ സാധാരണയായി ഇത്തരത്തിലുള്ള കാര്യങ്ങൾ അവസാന നിമിഷം വരെ മാറ്റിവെക്കാറാണ് പതിവ്.
യഥാർത്ഥത്തിൽ, ഒരു മുന്നറിയിപ്പ് ലഭിക്കുന്നത് വരെ ഇത് പലപ്പോഴും ഞാൻ പൂർണ്ണമായും മറന്നുപോകാറുണ്ട്.
എന്നാൽ ഇന്ന് രാത്രി കാര്യങ്ങൾ നേരത്തെ ചെയ്തു തീർക്കാൻ ഞാൻ ആഗ്രഹിക്കുന്നു.
ഞാൻ ഒരു നിമിഷം ആ ഒഴിഞ്ഞ മേശയിലേക്ക് നോക്കുന്നു.
എൻ്റെ കമ്പ്യൂട്ടർ പുറത്ത് ഇടനാഴിയിലുള്ള എൻ്റെ വർക്ക് ബാഗിലാണുള്ളത്.
അതിപ്പോൾ പോയി എടുക്കാനും ഓണാക്കാനും എനിക്ക് ഒട്ടും വയ്യ.
ഭാഗ്യവശാൽ, ചെറിയ ജോലികൾക്കായി ഞാൻ സാധാരണയായി എൻ്റെ ഫോൺ മാത്രമാണ് ഉപയോഗിക്കാറുള്ളത്.
വലിയൊരു നെടുവീർപ്പോടെ ഞാൻ പോക്കറ്റിൽ നിന്ന് ഫോൺ പുറത്തെടുക്കുന്നു.
ഇനി ഇതൊന്ന് വേഗം ചെയ്തു തീർക്കണം.
