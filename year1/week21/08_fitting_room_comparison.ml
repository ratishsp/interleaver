പുതിയ ഷർട്ടുമായി ഞാൻ ഫിറ്റിംഗ് റൂമിലേക്ക് കയറുന്നു.
എനിക്കിത് ഉടനടി ഇട്ടുനോക്കണം.
ക്യാബിൻ ചെറുതാണ്, പക്ഷേ അവിടെ നല്ലൊരു കണ്ണാടിയുണ്ട്.
ഞാൻ എൻ്റെ ജാക്കറ്റും സ്വെറ്ററും ഊരിമാറ്റുന്നു.
അതിനുശേഷം ഞാൻ ആ നീല ഷർട്ട് ഇടുന്നു.
അത് എനിക്ക് എത്രത്തോളം പാകമാണെന്ന് ഞാൻ കണ്ണാടിയിൽ നോക്കുന്നു.
വലിയ സൈസാണ് കുറച്ചുകൂടി നല്ലത്.
ചുമലുകളുടെ ഭാഗത്ത് ഇതിന് വലിയ ഇറുക്കമില്ല.
ഞാൻ കൈകൾ അല്പം അനക്കി നോക്കുന്നു.
മറ്റേതിനേക്കാൾ വളരെ സുഖപ്രദമാണ് ഈ ഷർട്ട്.
ശനിയാഴ്ചത്തെ ചെറിയ ഷർട്ട് തീരെ ചെറുതായിരുന്നു.
ഈ ഷർട്ട് എനിക്ക് കൃത്യം പാകമാണ്.
ഇതിൻ്റെ നീളവും വളരെ കൃത്യമാണ്.
നിറവും അതുപോലെ തന്നെ മനോഹരമാണ്.
സംതൃപ്തിയോടെ ഞാൻ തലയാട്ടുന്നു.
ഞാൻ ആ ഷർട്ട് വീണ്ടും ഊരിമാറ്റുന്നു.
അതിനുശേഷം, ഞാൻ എൻ്റെ സ്വന്തം വസ്ത്രങ്ങൾ ധരിക്കുന്നു.
പുതിയ ഷർട്ടുമായി ഞാൻ ഫിറ്റിംഗ് റൂമിൽ നിന്ന് പുറത്തിറങ്ങുന്നു.
തീർച്ചയായും എനിക്കിത് എടുക്കണം.
ഇനി എനിക്ക് ജീവനക്കാരനോട് ഒന്നുകൂടി സംസാരിച്ചാൽ മാത്രം മതി.
