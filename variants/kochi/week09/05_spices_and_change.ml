ഞാൻ മാർക്കറ്റിലൂടെ നടക്കുന്നു.
എനിക്ക് സുഗന്ധവ്യഞ്ജനങ്ങളുടെ നല്ല മണം കിട്ടുന്നു.
ഞാൻ ഒരു ചെറിയ കട കാണുന്നു.
മേശപ്പുറത്ത് ഒരു ചെറിയ കാർഡ്ബോർഡ് ബോർഡ് ഉണ്ട്.
അതിൽ വിലകൾ ഉണ്ട്.
ഞാൻ ഏലക്കയുടെ വില നോക്കുന്നു.
ഏലക്കയുടെ വില നൂറ്റിയൻപത് രൂപ ആണ്.
കച്ചവടക്കാരൻ എന്നെ നോക്കുന്നു.
"എന്ത് വേണം?" അയാൾ ചോദിക്കുന്നു.
"എനിക്ക് ഒരു ചെറിയ പാക്കറ്റ് ഏലക്ക വേണം," ഞാൻ പറയുന്നു.
"ഒരു പാക്കറ്റ് തരൂ."
അയാൾ എനിക്ക് ഒരു പാക്കറ്റ് ഏലക്ക തരുന്നു.
ഞാൻ എന്റെ ബാഗിൽ നിന്ന് അഞ്ഞൂറ് രൂപ എടുക്കുന്നു.
ഞാൻ അത് കച്ചവടക്കാരന് കൊടുക്കുന്നു.
അയാൾ പണം വാങ്ങി ബാക്കി എണ്ണുന്നു.
"ഏലക്കയ്ക്ക് നൂറ്റിയൻപത് രൂപ," അയാൾ പറയുന്നു.
"ബാക്കി മുന്നൂറ്റിയൻപത് രൂപ ഇതാ."
അയാൾ എനിക്ക് ബാക്കി പണം തരുന്നു.
ഞാൻ പാക്കറ്റും പണവും ബാഗിൽ വെക്കുന്നു.
ഞാൻ അയാൾക്ക് നന്ദി പറയുന്നു.
