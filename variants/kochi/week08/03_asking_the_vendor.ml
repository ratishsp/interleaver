ഞാൻ ബസിൽ നിന്ന് ഇറങ്ങുന്നു.
ഇതൊരു വലിയ ബസ് സ്റ്റോപ്പാണ്.
ഇവിടെ നല്ല തിരക്കാണ്.
ഞാൻ ചുറ്റും നോക്കുന്നു.
പക്ഷേ, ഞാൻ വെള്ളം കാണുന്നില്ല.
വാക്ക്വേ എവിടെയാണ്?
റോഡരികിൽ ഒരു പഴക്കച്ചവടക്കാരൻ ഉണ്ട്.
ഞാൻ ആ കടയിലേക്ക് നടക്കുന്നു.
ഞാൻ അദ്ദേഹത്തോട് വഴി ചോദിക്കുന്നു.
"ക്ഷമിക്കണം, വാക്ക്വേ എവിടെയാണ്?" ഞാൻ ചോദിക്കുന്നു.
അദ്ദേഹം പ്രധാന റോഡിലേക്ക് കൈ ചൂണ്ടുന്നു.
"ഈ റോഡിലൂടെ നേരെ പോകൂ," അദ്ദേഹം പറയുന്നു.
"റോഡിന്റെ അവസാനം വരെ പോകൂ."
"അവിടെ നിന്ന് വലത്തോട്ട് തിരിയൂ."
"നേരെ, എന്നിട്ട് വലത്തോട്ട്?" ഞാൻ ചോദിക്കുന്നു.
"അതെ, വാക്ക്വേ അവിടെയാണ്," അദ്ദേഹം പറയുന്നു.
"വളരെ നന്ദി," ഞാൻ പറയുന്നു.
അദ്ദേഹം പുഞ്ചിരിക്കുന്നു.
ഞാൻ ആ പ്രധാന റോഡിലൂടെ നേരെ നടക്കുന്നു.
