ഉച്ചയ്ക്ക് ശേഷം ഞങ്ങൾ കാന്റീൻ വരാന്തയിൽ നിൽക്കുകയാണ്.
ഞാനും പ്രകാശും ദീപയുമാണ് അവിടെയുള്ളത്.
ഞങ്ങൾ ചൂട് ചായ കുടിക്കുകയാണ്.
പെട്ടെന്ന് ആകാശം വളരെ കറുത്തു.
"ഇത്രയും കറുത്ത ആകാശം ഞാൻ കണ്ടിട്ടില്ല," ദീപ പറഞ്ഞു.
അപ്പോൾ ശക്തമായ ഒരു മഴ തുടങ്ങി.
ഈ സീസണിലെ ഏറ്റവും വലിയ മഴയാണ് ഇത്.
കാറ്റടിച്ച് വെള്ളം വരാന്തയിലേക്ക് തെറിച്ചു.
ഞങ്ങൾ അല്പം പിന്നിലേക്ക് മാറി.
രാവിലെയും ഇവിടെ മഴ പെയ്തു.
എന്നാൽ ഇപ്പോൾ മഴ വളരെ കൂടിയിട്ടുണ്ട്.
"മഴക്കാലം ശരിക്കും തുടങ്ങിയിട്ടുണ്ട്," പ്രകാശ് പറഞ്ഞു.
ഞാൻ ആദ്യമായിട്ടാണ് ഇത്രയും ശക്തമായ മഴ കാണുന്നത്.
മഴയുടെ വലിയ ശബ്ദം ഞാൻ ശ്രദ്ധിച്ചു.
ഞങ്ങൾ ചായ കുടിച്ച് മഴ നോക്കി നിന്നു.
നല്ല തണുത്ത കാറ്റ് വീശി.
മഴയത്തെ ഈ ചൂട് ചായ എനിക്ക് വളരെ ഇഷ്ടപ്പെട്ടു.
