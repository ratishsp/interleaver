ഞാൻ ഗ്ലാസ് കൗണ്ടറിനടുത്തേക്ക് നടക്കുന്നു.
അതിൽ നിറയെ കേക്കുകളും ബ്രെഡുകളുമാണ്.
ഞാൻ അവിടെയുള്ള ഒട്ടേറെ സാധനങ്ങളിലേക്ക് നോക്കുന്നു.
അവ കാണാൻ വളരെ സ്വാദിഷ്ടമായി തോന്നുന്നു.
കേക്കുകൾക്ക് അടുത്തായി ചെറിയ ബോർഡുകളുണ്ട്.
ആ ബോർഡുകൾ കൈപ്പടയിൽ എഴുതിയതാണ്.
ഞാൻ ആ ബോർഡുകളിലെ പേരുകൾ വായിക്കുന്നു.
അവിടെ പലതരം പേസ്ട്രികളുണ്ട്.
അതിൽ നിന്നും തിരഞ്ഞെടുക്കാൻ ബുദ്ധിമുട്ടാണ്.
അവിടെ വലിയൊരു ചോക്ലേറ്റ് കേക്കുണ്ട്.
എന്നാൽ ഞാൻ മറ്റൊരു പേസ്ട്രിയിലേക്കാണ് നോക്കുന്നത്.
അതൊരു വലിയ സിനമൺ റോളാണ്.
അതിനു മുകളിൽ ധാരാളം പഞ്ചസാരയുണ്ട്.
എനിക്ക് കറുവാപ്പട്ടയുടെ രുചി വളരെ ഇഷ്ടമാണ്.
തണുപ്പുള്ള ഒരു ശീതകാല ദിനത്തിന് ഇത് ഏറ്റവും അനുയോജ്യമാണ്.
എനിക്ക് ആ സിനമൺ റോൾ കഴിക്കാൻ വളരെ ആഗ്രഹമുണ്ട്.
ഇപ്പോൾ ഞാൻ ഓർഡർ ചെയ്യാൻ തയ്യാറാണ്.
