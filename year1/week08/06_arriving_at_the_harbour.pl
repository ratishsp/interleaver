Idę z powrotem cichą ulicą.
Idę prosto.
Wkrótce znów widzę duży plac.
Potem przechodzę przez plac.
Teraz stoję przy muzeum.
Pamiętam słowa kobiety: „Skręć w prawo”.
Przy muzeum skręcam w prawo.
Idę szeroką ulicą.
Patrzę przed siebie.
W końcu widzę coś niebieskiego.
To woda!
Po drodze mijam małą kawiarnię.
Wreszcie idę aż do samej wody.
Teraz jestem w porcie.
Port jest bardzo duży.
Wiatr jest zimny i rześki.
Na wodzie jest wiele łodzi.
Tutaj się zatrzymuję.
Stoję i patrzę na łodzie.
