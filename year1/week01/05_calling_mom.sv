Jag är i vardagsrummet nu.
Det finns en liten soffa.
Jag ringer till min mamma i Mexiko.
"Hej mamma", säger jag.
"Hej Maya", säger min mamma.
"Var är du?" frågar hon.
"Jag är i Köpenhamn", svarar jag.
"Jag är i lägenheten nu."
"Vad bra", säger min mamma.
"Är den stor?" frågar hon.
"Nej, den är liten", svarar jag.
"Men den är mysig, och jag är glad."
"Är det kallt?" frågar hon.
"Ja, det är kallt ute", säger jag.
"Men här inne är det varmt."
"Jag är trygg."
"Det är bra", säger min mamma.
Jag ler.
Danmark är mitt nya hem.
