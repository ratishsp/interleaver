ഞാൻ ക്ലിനിക്കിലെ ഫാർമസിയിലേക്ക് നടക്കുന്നു.
കൗണ്ടറിൽ ഒരു ഫാർമസിസ്റ്റ് ഉണ്ട്.
ഞാൻ ഡോക്ടറുടെ കുറിപ്പ് അയാൾക്ക് കൊടുക്കുന്നു.
അയാൾ ആ കുറിപ്പ് നോക്കുന്നു.
പിന്നെ അയാൾ കുറച്ച് ഗുളികകളും ഒരു കഫ് സിറപ്പും എടുക്കുന്നു.
"ഇതാണ് മരുന്നുകൾ," അയാൾ പറയുന്നു.
"ഈ ഗുളികകൾ എപ്പോൾ കഴിക്കണം?" ഞാൻ ചോദിക്കുന്നു.
"രാവിലെയും ഉച്ചയ്ക്കും രാത്രിയും ഭക്ഷണം കഴിച്ച ശേഷം കഴിക്കണം," അയാൾ പറയുന്നു.
"സിറപ്പോ?" ഞാൻ ചോദിക്കുന്നു.
"സിറപ്പ് ഒരു ദിവസം മൂന്ന് നേരം കുടിക്കണം," അയാൾ മറുപടി പറയുന്നു.
ഞാൻ സമ്മതിച്ച് തലയാട്ടുന്നു.
"ഇതിന് എത്ര രൂപയാണ്?" ഞാൻ ചോദിക്കുന്നു.
"മുന്നൂറ്റി ഇരുപത് രൂപ," അയാൾ പറയുന്നു.
ഞാൻ പണം എടുത്ത് അയാൾക്ക് കൊടുക്കുന്നു.
ഞാൻ മരുന്നുകൾ എന്റെ ബാഗിൽ വെക്കുന്നു.
പുറത്ത് ഇപ്പോഴും മഴ പെയ്യുന്നുണ്ട്.
ഞാൻ എന്റെ കുട എടുത്ത് വീട്ടിലേക്ക് നടക്കുന്നു.
