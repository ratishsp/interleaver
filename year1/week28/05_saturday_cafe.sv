Det är lördag morgon, och jag är på det lokala caféet.
Jag arbetar frivilligt här varje helg.
Caféet är redan fullt av människor.
Jag står bakom den stora trädisken.
Jag torkar av disken med en ren trasa.
En ung man går fram till disken.
"God morgon, jag vill gärna ha en stor kaffe", säger han.
"Och två varma wienerbröd, tack", tillägger han.
"Självklart, det kommer strax", svarar jag med ett leende.
Jag går bort till den stora espressomaskinen.
Jag känner maskinen riktigt bra nu.
Jag gör snabbt en ångande varm kopp kaffe.
Doften av färskt kaffe fyller det lilla rummet.
Efteråt lägger jag två varma wienerbröd i en papperspåse.
Jag räcker kaffet och påsen över disken till honom.
"Det blir femtiofem kronor", säger jag.
Han betalar med sitt kort och tar emot kaffet.
"Ha en trevlig helg", säger han glatt.
"Tack, detsamma", svarar jag.
Jag vinkar fram nästa kund i kön.
