Stále mám na sobě svou tenkou bundu.
Myslím na své studené ruce z dnešního rána.
Potřebuji silné rukavice.
Rozhlížím se po světlém obchodě.
Vidím velký koš.
Koš je plný rukavic.
Nacházím pár černých zimních rukavic.
Jsou velmi silné a měkké.
Nasazuji si rukavice.
Padnou mi perfektně.
Ptám se usmívající se prodavačky.
„Kolik stojí ty černé rukavice?“ ptám se.
„Stojí sto dvacet korun,“ odpovídá.
Sto dvacet korun je dobrá cena.
Moje ruce už jsou teplé.
„Vezmu si je,“ říkám radostně.
Znovu si rukavice sundávám.
Pokládám černé rukavice ke svému červenému svetru a modré šále.
Teď jsem připravená zaplatit.
