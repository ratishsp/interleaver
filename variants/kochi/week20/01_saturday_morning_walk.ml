ഇന്ന് ശനിയാഴ്ച രാവിലെയാണ്.
ഞാൻ ഒരു ചെറിയ കഫേയിലേക്ക് നടക്കുകയാണ്.
അതൊരു കമ്മ്യൂണിറ്റി കഫേയാണ്.
ഇപ്പോൾ പുറത്ത് ചെറിയ മഴയുണ്ട്.
ഞാൻ എന്റെ കുട ചൂടിയാണ് നടക്കുന്നത്.
കൊച്ചിയിൽ ജൂൺ മാസം മഴക്കാലമാണ്.
ഞാൻ മുൻപ് പല തവണ ഈ കഫേയിൽ വന്നിട്ടുണ്ട്.
എന്നാൽ വോളണ്ടിയർ ആയി ഇന്ന് അവിടെ എന്റെ ഒന്നാമത്തെ ദിവസമാണ്.
എല്ലാ ശനിയാഴ്ചയും രാവിലെ അവിടെ ജോലി ചെയ്യാൻ ഞാൻ തീരുമാനിച്ചു.
പുതിയ ആളുകളെ പരിചയപ്പെടാൻ ഞാൻ ആഗ്രഹിച്ചു.
ഈ നഗരത്തെ കൂടുതൽ നന്നായി അറിയാനും ഞാൻ ആഗ്രഹിക്കുന്നു.
പുതിയ കാര്യങ്ങൾ പഠിക്കാൻ എനിക്ക് എപ്പോഴും ഇഷ്ടമാണ്.
ഞാൻ ഇതിനുമുൻപ് കഫേയിൽ ജോലി ചെയ്തിട്ടില്ല.
ഞാൻ ഒരു സോഫ്റ്റ്‌വെയർ എൻജിനീയറാണ്.
അതുകൊണ്ട് എനിക്ക് ചെറിയ പേടിയുണ്ട്.
എങ്കിലും ഈ പുതിയ അനുഭവത്തിനായി ഞാൻ ആകാംക്ഷയോടെ കാത്തിരിക്കുകയാണ്.
കഫേ ഇപ്പോൾ എന്റെ മുന്നിലുണ്ട്.
ഞാൻ മഴയത്ത് നിന്ന് മാറി എന്റെ കുട മടക്കി.
എന്നിട്ട് ഒരു വലിയ ചിരിയോടെ ഞാൻ ഉള്ളിലേക്ക് കയറി.
