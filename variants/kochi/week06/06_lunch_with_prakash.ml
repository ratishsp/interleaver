ഇപ്പോൾ ഉച്ചസമയം ആണ്.
ഞാൻ ഓഫീസിലെ കാൻ്റീനിൽ വിശ്രമിക്കുകയാണ്.
കാൻ്റീനിൽ നല്ല വെളിച്ചം ഉണ്ട്.
ഞാൻ എന്റെ ഉച്ചഭക്ഷണം കഴിക്കുകയാണ്.
ഞാൻ എരിവുള്ള മീൻ കറി കഴിക്കുകയാണ്.
മീൻ കറിക്ക് വളരെ നല്ല രുചിയുണ്ട്.
എന്റെ സഹപ്രവർത്തകൻ പ്രകാശ് ഇങ്ങോട്ട് വരുന്നു.
പ്രകാശ് എന്റെ മേശയ്ക്കരികിൽ ഇരിക്കുന്നു.
പ്രകാശ് എന്നോട് സംസാരിക്കുകയാണ്.
അയാൾ ഒരു തമാശ പറയുകയാണ്.
അതൊരു നല്ല കഥയാണ്.
ഞാൻ ഉച്ചത്തിൽ ചിരിക്കുകയാണ്.
പ്രകാശും സന്തോഷത്തോടെ ചിരിക്കുന്നു.
പ്രകാശ് ഇപ്പോൾ ഭക്ഷണം കഴിക്കുകയാണ്.
ഞങ്ങൾ ഒരുമിച്ച് ഭക്ഷണം ആസ്വദിക്കുന്നു.
ഞാൻ കുറച്ചു വെള്ളം കുടിക്കുകയാണ്.
വിശ്രമസമയം കഴിയുന്നു.
ഞങ്ങൾ തിരികെ ജോലിക്ക് പോകുകയാണ്.
