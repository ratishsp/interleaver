നേരം വൈകി.
കോപ്പൻഹേഗനിലെ എൻ്റെ ആദ്യത്തെ രാത്രിയാണിത്.
ഫ്ലാറ്റ് ശാന്തമാണ്, ഞാൻ വളരെ ക്ഷീണിതയുമാണ്.
മെക്സിക്കോയിലുള്ള എൻ്റെ കുടുംബത്തെ ഞാൻ ചെറുതായിട്ട് മിസ്സ് ചെയ്യുന്നുണ്ട്.
പക്ഷെ ഞാൻ സന്തോഷവതിയാണ്.
കോപ്പൻഹേഗനാണ് ഇപ്പോൾ എൻ്റെ വീട്.
എൻ്റെ അയൽക്കാരിയുടെ പേര് നീന എന്നാണ്.
അവൾ വളരെ സ്നേഹമുള്ളവളാണ്.
ഇവിടെ എൻ്റെ ആദ്യത്തെ സുഹൃത്ത് നീനയാണ്.
നാളെ ഒരു പുതിയ ദിവസമാണ്.
ശുഭരാത്രി, കോപ്പൻഹേഗൻ.
