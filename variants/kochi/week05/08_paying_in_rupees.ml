ഞാൻ ആ ചെറിയ പച്ചക്കറിക്കടയിൽ ആണ്.
ഞാൻ പച്ചക്കറികൾ കച്ചവടക്കാരന് കൊടുക്കുന്നു.
അദ്ദേഹം അത് ഒരു ചെറിയ ത്രാസിൽ വെക്കുന്നു.
അദ്ദേഹം പച്ചക്കറികൾ തൂക്കുന്നു.
എനിക്ക് ഈ പുതിയ പച്ചക്കറികൾ വേണം.
"ഇതിന് എത്ര രൂപയാണ്?" ഞാൻ ചോദിക്കുന്നു.
"ഇരുനൂറ് രൂപ," അദ്ദേഹം പറയുന്നു.
ഞാൻ എന്റെ പഴ്സ് എടുക്കുന്നു.
ഞാൻ അദ്ദേഹത്തിന് ഇരുനൂറ് രൂപ കൊടുക്കുന്നു.
അദ്ദേഹം പച്ചക്കറികൾ എനിക്ക് തരുന്നു.
എനിക്ക് പുതിയ പച്ചക്കറികൾ വളരെ ഇഷ്ടമാണ്.
ഞാൻ എല്ലാം എന്റെ സഞ്ചികളിൽ ശ്രദ്ധിച്ച് വെക്കുന്നു.
ഇപ്പോൾ സഞ്ചികൾക്ക് നല്ല ഭാരമുണ്ട്.
ഞാൻ അദ്ദേഹത്തോട് നന്ദി പറയുന്നു.
ഞാൻ എന്റെ വീട്ടിലേക്ക് നടക്കുന്നു.
