Je sobotní dopoledne a já jsem v kavárně skončila.
Právě jsem utřela poslední stůl.
Rozvazuji si zástěru a pokládám ji na židli.
Dnes jsem měla krátkou směnu.
Minulý týden jsem pracovala do tří hodin.
Ten den jsme měli celý den hodně napilno.
Ale dnes jsme měli jen málo hostů.
Venku svítí slunce a je krásný letní den.
Dnes večer je dole u moře velký oheň.
Moc se těším, až ho uvidím.
Beru si telefon a píšu zprávu Evě.
Ptám se jí: „Stále platí, že se dnes večer sejdeme?“
Píšu jí také, že už mám volno.
„Dnes jsem skončila brzo, takže jsem připravená,“ píšu.
Eva odpovídá téměř okamžitě.
„Ano, samozřejmě!“ odpovídá.
„Zrovna jsem koupila čerstvé jahody.“
„Uvidíme se později na pláži,“ píše.
Usmívám se a beru si tašku.
Pak vycházím ven do teplého letního počasí.
