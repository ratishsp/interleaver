Je klidný úterní večer v mém bytě.
Sklízím svůj malý kuchyňský stůl.
Talíře jsou umyté a stůl je utřený.
Užívám si klid po dlouhém dni v kanceláři.
Ale najednou si vzpomenu na důležitý úkol.
Musím si aktualizovat kontaktní údaje na webových stránkách svého dodavatele elektřiny.
Dostala jsem od nich e-mail s připomínkou.
Ve zprávě se píše: „Vaše údaje musí být aktualizovány do středy.“
Vždyť to je už zítra!
Je to opravdu nudná digitální povinnost.
Takové věci většinou odkládám na poslední chvíli.
Vlastně se na to často úplně zapomene, dokud nedostanu varování.
Ale dnes večer chci být o krok napřed.
Chvíli se dívám na prázdný stůl.
Můj počítač je v pracovní tašce na chodbě.
Nemám teď vůbec energii pro něj jít a zapínat ho.
Naštěstí na drobné úkoly většinou používám jen telefon.
S těžkým povzdechem vytahuji telefon z kapsy.
Teď to prostě musím mít za sebou.
