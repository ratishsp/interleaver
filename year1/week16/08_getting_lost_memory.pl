Teraz śmieję się i opowiadam im o pewnej zagmatwanej sobocie.
To był zimny, sobotni poranek tamtej pierwszej zimy.
Chciałam pójść do portu.
Nina już wcześniej podała mi trasę.
Po drodze usłyszałam ulicznego muzyka.
Pięknie grał na gitarze.
Zatrzymałam się i długo słuchałam.
Potem zupełnie zapomniałam o trasie Niny.
Weszłam w wąską boczną uliczkę.
Były tam tylko małe, ciche domy.
Nagle całkowicie się zgubiłam.
Przede mną szła młoda kobieta z małym psem.
Pies wyglądał zupełnie jak nasza Lola.
„Przepraszam, szukam portu” – powiedziałam.
Uprzejmie wskazała mi drogę z powrotem w stronę placu.
Podziękowałam jej i znalazłam właściwą drogę.
W końcu dotarłam nad wodę.
Mój brat Diego śmieje się głośno na ekranie.
To był głupi błąd, ale dobre wspomnienie.
