ഞാൻ താഴെ കടൽത്തീരത്തേക്ക് നടക്കുന്നു.
വൈകുന്നേരത്തെ പാർട്ടിക്ക് ഇതിനകം തന്നെ ധാരാളം ആളുകൾ എത്തിയിട്ടുണ്ട്.
ഞാൻ ആൾക്കൂട്ടത്തിൽ ഈവയെയും പീറ്ററിനെയും തിരയുന്നു.
പെട്ടെന്ന് ഞാൻ അവരെ താഴെ വെള്ളത്തിനടുത്ത് കാണുന്നു, ഞാൻ വേഗത്തിൽ അങ്ങോട്ടേക്ക് പോകുന്നു.
"നിനക്ക് നല്ലൊരു ജന്മദിനവാരം ലഭിച്ചോ?" പീറ്റർ ചിരിച്ചുകൊണ്ട് ചോദിക്കുന്നു.
"അതെ, ഇത് വളരെ ഗംഭീരമായിരുന്നു," ഞാൻ സന്തോഷത്തോടെ മറുപടി പറയുന്നു.
ഈവ ഒരു ചെറിയ കൊട്ട തുറക്കുന്നു.
"ഇന്ന് രാവിലെ ഞാൻ മാർക്കറ്റിൽ നിന്ന് പുതിയ സ്ട്രോബെറി വാങ്ങി," അവൾ പറയുന്നു.
"ഡാനിഷ് വേനൽക്കാല സ്ട്രോബെറികൾ നീ എപ്പോഴെങ്കിലും രുചിച്ചു നോക്കിയിട്ടുണ്ടോ?"
"ഇല്ല, ഞാൻ ഒരിക്കലും അത് കഴിച്ചുനോക്കിയിട്ടില്ല," ഞാൻ പറയുന്നു, എന്നിട്ട് ഒരെണ്ണം എടുക്കുന്നു.
ഇതിന് വല്ലാത്തൊരു മധുരമുണ്ട്, ഇത് എന്നെ വേനൽക്കാലത്തെ ഓർമ്മിപ്പിക്കുന്നു.
കൃത്യം ആ നിമിഷത്തിൽ, ഒരാൾ ആ വലിയ തീക്കുണ്ഠം കത്തിക്കുന്നു.
തീജ്വാലകൾ വേഗത്തിൽ വളരുകയും ആകാശത്തേക്ക് ഉയരുകയും ചെയ്യുന്നു.
നേരത്തെ തണുപ്പായിരുന്നു, എന്നാൽ ഇപ്പോൾ തീ അന്തരീക്ഷത്തെ ചൂടാക്കിയിരിക്കുന്നു.
തിളങ്ങുന്ന ആ ചൂട് തീരത്തുനിന്നുള്ള തണുപ്പിനെ വേഗത്തിൽ അകറ്റുന്നു.
ഞങ്ങൾ പരസ്പരം ചേർന്നുനിൽക്കുകയും, വളരെനേരം തീജ്വാലകളിലേക്ക് നോക്കിനിൽക്കുകയും ചെയ്യുന്നു.
ഞാൻ ഇപ്പോൾ ഈ നഗരത്തിൽ ജീവിക്കാൻ തുടങ്ങിയിട്ട് ആറുമാസമായല്ലോ എന്ന് ഞാൻ ചിന്തിക്കുന്നു.
ഇവിടുത്തെ എന്റെ ആദ്യത്തെ മാസം ഇരുണ്ടതായിരുന്നു, എന്നാൽ ഈ പ്രകാശമാനമായ വേനൽക്കാല സായാഹ്നം തികച്ചും പരിപൂർണ്ണമാണ്.
