ഞായറാഴ്ച ഉച്ചതിരിഞ്ഞ സമയമാണ്, അപ്പോൾ വാതിലിൽ ഒരു മുട്ട് കേൾക്കുന്നു.
ലുഡ്‌വിഗ് ഇടനാഴിയിലേക്ക് ഓടിവന്ന് സന്തോഷത്തോടെ കുരയ്ക്കുന്നു.
ഞാൻ വാതിൽ തുറക്കുന്നു, അപ്പോൾ നീന അവളുടെ വീക്കെൻഡ് ബാഗുമായി പുറത്ത് നിൽക്കുന്നുണ്ട്.
"ഹായ് മായ, സഹായിച്ചതിന് ഒരുപാട് നന്ദി," എന്ന് പറഞ്ഞ് അവൾ പുഞ്ചിരിക്കുന്നു.
അവൻ വാലാട്ടിക്കൊണ്ട് അവളുടെ മേലേക്ക് ചാടുന്നു.
"താഴെയിറങ്ങ്, ലുഡ്‌വിഗ്," എന്ന് പറഞ്ഞ് നീന അവനെ തലോടുന്നു.
"അവൻ വളരെ നല്ലൊരു നായയായിരുന്നു," ഞാൻ അവളോട് പറയുന്നു.
നീന ചിരിച്ചുകൊണ്ട് ചെറിയ മേശയിൽ നിന്ന് അവന്റെ ഡോഗ് ലീഷ് എടുക്കുന്നു.
"നീ അവനെ ഡോഗ് ഫോറസ്റ്റിൽ നടക്കാൻ കൊണ്ടുപോയോ?" അവൾ ചോദിക്കുന്നു.
"ഉവ്വ്, അവനത് ഒരുപാട് ഇഷ്ടപ്പെട്ടു," ഞാൻ മറുപടി നൽകുന്നു.
ഞാൻ അവൾക്ക് ബാക്കിയുള്ള ഡോഗ് ഫുഡ് കൊടുക്കുന്നു.
"ഇതാ, ഇതാണ് ബാക്കിയുള്ളത്."
"മറ്റൊരിക്കൽ അവനെ വീണ്ടും നോക്കാൻ എനിക്ക് സന്തോഷമേയുള്ളൂ."
"തീർച്ചയായും," നീന പറയുന്നു.
"വാ, ലുഡ്‌വിഗ്, നമുക്ക് വീട്ടിൽ പോകണം," നീന നായയോട് പറയുന്നു.
ഞാൻ അവർക്ക് രണ്ടുപേർക്കും കൈവീശി യാത്ര പറയുന്നു.
അവനില്ലാതെ അപ്പാർട്ട്മെന്റ് പെട്ടെന്ന് വളരെ ശാന്തമായി.
