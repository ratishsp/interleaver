Kort därefter kom nästa beställning.
Jag har redan gjort min första kaffe i dag.
Men den här kunden ville bara ha mat.
Han beställde en fralla med ost.
Jag tog en varm surdegsfralla från korgen.
Surdegsbröd har ofta en hård skorpa.
Men jag har lärt mig att skära itu brödet snabbt.
Därefter lade jag en tjock skiva ost på frallan.
Jag lade upp maten fint på en liten tallrik.
Nu skulle jag lämna den till kunden.
Det stod många människor mitt i caféet.
Jag balanserade tallriken och gick försiktigt fram.
Jag gick långsamt förbi de andra gästerna.
Kunden satt lyckligtvis längst ner i hörnet.
Han väntade vid det fjärde bordet.
Jag ställde tallriken på bordet framför honom.
"Varsågod, en varm fralla med ost", sa jag.
"Tack så mycket", svarade mannen.
Det är härligt att se en nöjd gäst.
