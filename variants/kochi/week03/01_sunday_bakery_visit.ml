ഇന്ന് ഞായറാഴ്ച ആണ്.
കൊച്ചിയിൽ ഇതൊരു ശാന്തമായ പ്രഭാതം ആണ്.
എന്റെ ഫ്ലാറ്റിന്റെ അടുത്ത് ഒരു ചെറിയ ബേക്കറി ഉണ്ട്.
ഞാൻ അവിടേക്ക് നടക്കുന്നു.
ബേക്കറിയിൽ നല്ല തിരക്കുണ്ട്.
കടക്കാരൻ വളരെ തിരക്കിലാണ്.
ഞാൻ ഗ്ലാസ്സ് അലമാരയിലേക്ക് നോക്കുന്നു.
അവിടെ ഒരുപാട് മധുരപലഹാരങ്ങൾ ഉണ്ട്.
"ആരാണ് അടുത്തത്?" കടക്കാരൻ ചോദിക്കുന്നു.
"ഇത് എന്റെ ഊഴമാണ്," ഞാൻ പറയുന്നു.
"നിങ്ങളുടെ ഓർഡർ എന്താണ്?" അദ്ദേഹം ചോദിക്കുന്നു.
ഞാൻ ചുവന്ന ഹൽവ ചൂണ്ടിക്കാണിക്കുന്നു.
"എനിക്ക് ഒരു ചെറിയ പെട്ടി ഹൽവ വേണം," ഞാൻ പറയുന്നു.
അദ്ദേഹം വേഗത്തിൽ ഒരു ചെറിയ പെട്ടി എടുക്കുന്നു.
