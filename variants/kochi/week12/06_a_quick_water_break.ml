ഞങ്ങൾ ആദ്യത്തെ കളി പൂർത്തിയാക്കുന്നു.
ഞങ്ങൾ കോർട്ടിൽ നിന്ന് പുറത്തേക്ക് വരുന്നു.
കളി കാരണം എനിക്ക് നല്ല ക്ഷീണമുണ്ട്.
അതിനാൽ ഞാൻ കുറച്ചു വെള്ളം കുടിക്കാൻ പോകുന്നു.
ഞാൻ എന്റെ വാട്ടർ ബോട്ടിൽ എടുക്കുന്നു.
വിഷ്ണുവും സാറയും കിരണും വെള്ളം കുടിക്കുന്നു.
വിഷ്ണു എന്നെ നോക്കി ചിരിക്കുന്നു.
"മായയ്ക്ക് കൊച്ചി ഇഷ്ടമാണോ?" വിഷ്ണു ചോദിക്കുന്നു.
"ഇവിടെ താമസിക്കാൻ ഇഷ്ടമാണോ?"
"അതെ, എനിക്ക് ഈ നഗരം വളരെ ഇഷ്ടമാണ്," ഞാൻ മറുപടി പറയുന്നു.
"കൊച്ചിയിൽ താമസിക്കാൻ എനിക്ക് വലിയ ഇഷ്ടമാണ്."
"പുതിയ കൂട്ടുകാരെ പരിചയപ്പെടാൻ എനിക്ക് വളരെ ഇഷ്ടമാണ്."
"അത് കേട്ടതിൽ വളരെ സന്തോഷമുണ്ട്," വിഷ്ണു പറയുന്നു.
"നമുക്ക് വീണ്ടും ഒരുമിച്ച് കളിക്കാൻ കഴിയും," കിരൺ പറയുന്നു.
ഞാൻ സന്തോഷത്തോടെ തലയാട്ടുന്നു.
ഞങ്ങൾ എല്ലാവരും കുറച്ചു സമയം വിശ്രമിക്കുന്നു.
പിന്നെ ഞങ്ങൾ വീണ്ടും കളിക്കാൻ പോകുന്നു.
