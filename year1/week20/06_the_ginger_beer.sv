Det var mitt andra lördagspass på kaféet.
Jag har redan lärt mig att göra mycket av arbetet.
Den förmiddagen var det härligt varmt ute.
En kvinna kom fram till disken.
"Jag skulle vilja be om en ginger beer", sa hon.
"Självklart, ett ögonblick", svarade jag.
Jag gick bort till det stora glaskylskåpet bakom disken.
Jag tittade på den tredje hyllan.
Där stod de kalla flaskorna med ginger beer.
Jag hittade en flaska och tog ut den.
Ingefäran låg som ett tjockt moln nere i botten.
Jag har lärt mig att blanda den innan jag öppnar flaskan.
Så jag vände flaskan mycket försiktigt upp och ner.
Jag höll den så i ett par sekunder.
Ingefäran blandade sig långsamt med resten av vätskan.
Nu såg drycken helt rätt ut.
Jag vände på flaskan igen och ställde den på disken.
"Varsågod, det blir trettiofem kronor", sa jag till henne.
Hon betalade, och hon har säkert njutit av sin kalla dryck.
