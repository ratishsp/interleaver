അയാൾ ഒരു ഗ്ലാസ് തണുത്ത വെള്ളം കൊണ്ടുവരുന്നു.
അയാൾ ഗ്ലാസ് മേശപ്പുറത്ത് വെക്കുന്നു.
"നന്ദി," ഞാൻ പറയുന്നു.
ഞാൻ ഗ്ലാസ് എടുക്കുന്നു.
ഞാൻ വേഗത്തിൽ ആ വെള്ളം കുടിക്കുന്നു.
ഇപ്പോൾ എന്റെ ദാഹം മാറി.
ഇനി എനിക്ക് പുറത്തേക്ക് പോകണം.
പുറത്ത് ഇപ്പോഴും നല്ല ചൂടാണ്.
ഞാൻ എന്റെ ബാഗ് എടുത്ത് എഴുന്നേൽക്കുന്നു.
ഞാൻ മുന്നിലെ കൗണ്ടറിലേക്ക് നടക്കുന്നു.
ആ ജോലിക്കാരൻ കൗണ്ടറിലുണ്ട്.
അയാൾ എന്നെ നോക്കി ചിരിക്കുന്നു.
"എനിക്ക് പണം അടയ്ക്കണം," ഞാൻ പറയുന്നു.
"തീർച്ചയായും," അയാൾ പറയുന്നു.
അയാൾ കമ്പ്യൂട്ടറിൽ നോക്കുന്നു.
