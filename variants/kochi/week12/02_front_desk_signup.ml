ഞാൻ സ്പോർട്സ് സെൻ്ററിനുള്ളിലേക്ക് പോകുന്നു.
ഇവിടെ ഒരുപാട് ആളുകൾ ഉണ്ട്.
അവർ ബാഡ്മിൻ്റൺ കളിക്കുകയാണ്.
ഞാൻ ഫ്രണ്ട് ഡെസ്കിലേക്ക് നടക്കുന്നു.
അവിടെ ഒരു മാനേജർ ഇരിക്കുന്നുണ്ട്.
"നമസ്കാരം, എൻ്റെ പേര് മായ," ഞാൻ പറയുന്നു.
"നമസ്കാരം മായ," മാനേജർ പറയുന്നു.
"ഞാൻ ഒരു സോഫ്റ്റ്‌വെയർ കമ്പനിയിൽ ജോലി ചെയ്യുന്നു," ഞാൻ പറയുന്നു.
"എനിക്ക് ഈ ക്ലബ്ബിൽ ചേരാൻ ആഗ്രഹമുണ്ട്."
"എനിക്ക് ബാഡ്മിൻ്റൺ കളിക്കാൻ വളരെ ഇഷ്ടമാണ്."
"ജോലിക്ക് ശേഷം എനിക്ക് ഇവിടെ കളിക്കാൻ കഴിയുമോ?" ഞാൻ ചോദിക്കുന്നു.
"തീർച്ചയായും, നിങ്ങൾക്ക് ഇവിടെ കളിക്കാൻ കഴിയും," മാനേജർ പറയുന്നു.
"ക്ലബ്ബ് എല്ലാ വൈകുന്നേരവും തുറക്കും."
"നിങ്ങളുടെ പേരും ഫോൺ നമ്പറും ഇവിടെ എഴുതുക."
ഞാൻ കടലാസിൽ എൻ്റെ പേര് എഴുതുന്നു.
"എൻ്റെ നമ്പർ ഒൻപത് എട്ട് ഏഴ് ആറ് അഞ്ച്, നാല് മൂന്ന് രണ്ട് ഒന്ന് പൂജ്യം," ഞാൻ പറയുന്നു.
മാനേജർ എന്നെ നോക്കി പുഞ്ചിരിക്കുന്നു.
"ക്ലബ്ബിലേക്ക് സ്വാഗതം," അദ്ദേഹം പറയുന്നു.
ഇപ്പോൾ എനിക്ക് എല്ലാ ദിവസവും ബാഡ്മിൻ്റൺ കളിക്കാൻ കഴിയും.
