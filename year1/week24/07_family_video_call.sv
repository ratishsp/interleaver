På lördagskvällen ligger Ludwig och sover bredvid mig i soffan.
Han är mycket trött efter vår promenad i skogen.
Jag öppnar min dator och ringer ett videosamtal hem till min familj i Mexiko.
Min syster Sofía och min bror Diego sitter redo framför skärmen.
"Ni måste helt enkelt se min lilla gäst", säger jag till dem.
Jag tar datorn och riktar kameran ner mot hunden.
Sofía ler glatt.
"Titta bara på honom!"
"Han är ju riktigt söt", säger Diego.
Ludwig öppnar ena ögat, men han ligger bara kvar.
"Titta på honom."
"Han är ju lika lugn som vår hund Lola där hemma", säger jag.
Diego frågar mig om han är en lätt hund att passa.
"Ja, jag gillar verkligen att passa honom", svarar jag.
"Han måste bara gå i koppel ute på gatan."
"Och så får han absolut inte äta människomat."
"Så jag ger honom bara hans egna godbitar."
Plötsligt hör vi Lola skälla högt i bakgrunden på videon.
Ludwig lyfter på huvudet och tittar mycket förvirrat på skärmen.
"Lägg dig bara ner igen, min vän", säger jag milt och klappar honom.
Jag säger god natt till min familj, så att han kan få ro.
Han stänger ögonen och somnar snabbt igen.
