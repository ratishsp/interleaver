ഞായറാഴ്ച രാവിലെ ആണ്.
ഞാൻ മെക്സിക്കോയിലുള്ള എൻ്റെ കുടുംബത്തെ വീഡിയോ കോൾ ചെയ്യുന്നു.
എൻ്റെ അനിയത്തി സോഫിയ ആണ് ഫോൺ എടുക്കുന്നത്.
"സുഖമാണോ ചേച്ചി?" അവൾ ചോദിക്കുന്നു.
"എനിക്ക് സുഖമാണ്," ഞാൻ പറയുന്നു.
ഞാൻ ക്യാമറ ടോമിയുടെ നേരെ തിരിക്കുന്നു.
ടോമി അവൻ്റെ കിടക്കയിൽ ഉറങ്ങുകയാണ്.
"സോഫിയാ, നോക്കൂ."
"ഇതാണ് ടോമി," ഞാൻ പറയുന്നു.
"അവനെ കാണാൻ നല്ല ഭംഗിയുണ്ട്," സോഫിയ പറയുന്നു.
"ഇവൻ എൻ്റെ അയൽക്കാരി അനിതയുടെ നായയാണ്," ഞാൻ വിശദീകരിക്കുന്നു.
"ഈ വാരാന്ത്യത്തിൽ ഞാൻ അവനെ നോക്കണം."
"കൃത്യസമയത്ത് അവന് ഭക്ഷണം കൊടുക്കണം."
"അവന് മധുരമുള്ള പലഹാരങ്ങൾ കൊടുക്കാൻ പാടില്ല."
അപ്പോൾ സോഫിയ നമ്മുടെ നായ ലോലയെ ക്യാമറയുടെ മുന്നിൽ കൊണ്ടുവരുന്നു.
ലോല ഫോൺ സ്ക്രീനിൽ ടോമിയെ കാണുന്നു.
ഉടനെ അവൾ ഉറക്കെ കുരയ്ക്കുന്നു.
ആ ശബ്ദം കേട്ട് ടോമി പെട്ടെന്ന് ഉണരുന്നു.
ടോമിയും തിരിച്ചു കുരയ്ക്കുന്നു.
"ടോമി, ഇരിക്ക്!"
"നീ ബഹളം ഉണ്ടാക്കാൻ പാടില്ല," ഞാൻ അവനോട് പറയുന്നു.
അവൻ അനുസരണയോടെ എൻ്റെ അരികിൽ ഇരിക്കുന്നു.
"ഇവൻ നല്ലൊരു കുട്ടിയാണ്."
"എനിക്ക് അവനെ വളരെ ഇഷ്ടമാണ്," ഞാൻ സോഫിയയോട് പറയുന്നു.
