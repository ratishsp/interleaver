ഒടുവിൽ ഞാൻ എന്റെ അമ്മയോട് മഞ്ഞുകാലത്തെക്കുറിച്ച് പറയുന്നു.
കാലാവസ്ഥ പെട്ടെന്ന് മാറി.
നല്ല കാറ്റായിരുന്നു, വായു ഐസ് പോലെ തണുത്തതായിരുന്നു.
ജോലിക്ക് പോകുന്ന വഴിയിൽ തണുപ്പ് എന്റെ കവിളുകളെ തുളച്ചുകയറുന്നുണ്ടായിരുന്നു.
എനിക്ക് ചൂടുള്ള ചില വസ്ത്രങ്ങൾ ആവശ്യമായിരുന്നു.
ജോലി കഴിഞ്ഞ്, ഞാൻ ധൃതിയിൽ ഒരു വലിയ കടയിലേക്ക് കയറി.
ഭാഗ്യത്തിന്, അതിനുള്ളിൽ നല്ല ചൂടുണ്ടായിരുന്നു.
വളരെ സൗഹാർദ്ദപരമായി പെരുമാറുന്ന ഒരു ഷോപ്പ് അസിസ്റ്റന്റ് ആ കടയിൽ ജോലി ചെയ്യുന്നുണ്ടായിരുന്നു.
അവർ എന്റെ അടുത്തേക്ക് വന്ന് പുഞ്ചിരിച്ചു.
അവർ ചോദിച്ചു, "നിങ്ങൾ പ്രത്യേകിച്ച് എന്തെങ്കിലുമാണോ തിരയുന്നത്?"
ഞാൻ മറുപടി നൽകി, "അതെ, ഇവിടുത്തെ ഏറ്റവും ചൂടുനൽകുന്ന വിന്റർ ജാക്കറ്റ് എനിക്ക് വാങ്ങണം."
അവർ എനിക്കായി കട്ടിയുള്ള, കടും നീല നിറത്തിലുള്ള ഒരു ജാക്കറ്റ് കണ്ടെത്തി.
ഞാൻ ഉടൻ തന്നെ അത് ഇട്ടുനോക്കി.
അത് നല്ല ചൂടുനൽകുന്നതും, എനിക്ക് കൃത്യമായി പാകമാകുന്നതുമായിരുന്നു.
ഞാൻ മൃദുവായ ഒരു നീല സ്കാർഫും കൂടി എടുത്തു.
ഞാൻ സാധനങ്ങളുമായി ക്യാഷ് കൗണ്ടറിലേക്ക് പോയി പണമടച്ചു.
ആ വസ്ത്രങ്ങൾക്ക് ആയിരത്തി അഞ്ഞൂറ് ക്രോണർ ആയി.
അതിന് അല്പം വില കൂടുതലായിരുന്നു, എന്നാൽ അത് തീർച്ചയായും ആവശ്യമായിരുന്നു.
എന്റെ അമ്മ കൈകൾ കൂട്ടിയടിക്കുന്നു.
എനിക്ക് ഒടുവിൽ നല്ല ചൂട് കിട്ടിയതിൽ അവർക്ക് സന്തോഷമുണ്ട്.
