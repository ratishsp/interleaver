Nu är jag trött.
Jag lägger min bok på bordet.
Jag går ut i badrummet.
Här gör jag mig redo för natten.
Jag tar min tandborste.
Jag borstar tänderna.
Efteråt tvättar jag ansiktet.
Jag torkar mig med en handduk.
Jag går in i sovrummet.
Jag tar på mig pyjamas.
Sedan släcker jag ljuset.
Nu är lägenheten helt mörk.
Jag lägger mig i min säng.
Sängen är varm och mjuk.
Jag drar täcket över mig.
Jag blundar.
Jag är redo för en ny dag.
Jag sover gott.
