Jest sobota rano, godzina siódma.
Wciąż mocno śpię.
Nagle czuję coś zimnego na ramieniu.
Otwieram oczy i widzę Ludwiga.
Szturcha mnie nosem.
„Dzień dobry, Ludwig”, mówię i wstaję.
Idziemy razem do kuchni.
Jest bardzo głodny i skacze na mnie.
„Spokojnie, Ludwig”, mówię do niego.
„Siad”, mówię spokojnie.
Patrzy na mnie i siada na podłodze.
Biorę worek z psią karmą i otwieram go.
Wsypuję karmę do jego miski.
Wstaje, bo chce ją od razu.
„Nie, czekaj”, mówię.
Siada ponownie i grzecznie czeka.
Stawiam miskę przed nim.
Delikatnie głaszczę go po głowie.
„Proszę, jedz”, mówię z uśmiechem.
Merda ogonem i zaczyna jeść.
