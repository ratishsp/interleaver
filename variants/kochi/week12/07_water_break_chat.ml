ഞങ്ങൾ അല്പനേരം വിശ്രമിക്കുന്നു.
ഞങ്ങൾ കോർട്ടിന്റെ വശത്തേക്ക് മാറുന്നു.
കൊച്ചിയിൽ ഇപ്പോൾ നല്ല ചൂടാണ്.
ഞാൻ കുറച്ചു വെള്ളം കുടിക്കുന്നു.
വിഷ്ണുവും സാറയും കിരണും വെള്ളം കുടിക്കുന്നു.
വിഷ്ണു എന്നെ നോക്കി ചിരിക്കുന്നു.
വിഷ്ണു പറയുന്നു, "മായാ, നിങ്ങൾ വളരെ നന്നായി കളിക്കുന്നു."
ഞാൻ ചിരിച്ചുകൊണ്ട് പറയുന്നു, "വളരെ നന്ദി, വിഷ്ണു."
"എനിക്ക് ബാഡ്മിന്റൺ കളിക്കാൻ വലിയ ഇഷ്ടമാണ്."
സാറ ചോദിക്കുന്നു, "നിങ്ങൾക്ക് എല്ലാ ദിവസവും കളിക്കാൻ കഴിയുമോ?"
ഞാൻ മറുപടി പറയുന്നു, "ഇല്ല, എനിക്ക് എല്ലാ ദിവസവും ജോലി ഉണ്ട്."
"ജോലിക്ക് ശേഷം റിലാക്സ് ചെയ്യാൻ എനിക്ക് സ്പോർട്സ് കളിക്കാൻ ഇഷ്ടമാണ്."
കിരൺ പറയുന്നു, "ഞങ്ങൾക്കും വൈകുന്നേരം കളിക്കാൻ ഇഷ്ടമാണ്."
ഞാൻ പറയുന്നു, "എനിക്ക് നിങ്ങളുടെ കൂടെ നന്നായി കളിക്കാൻ കഴിയും."
സാറ സന്തോഷത്തോടെ പറയുന്നു, "അത് വളരെ നല്ലതാണ്."
ഞങ്ങൾ വെള്ളം കുടിച്ചു കഴിഞ്ഞു.
വിഷ്ണു ചോദിക്കുന്നു, "നമ്മൾ വീണ്ടും കളിക്കാൻ പോകുകയാണോ?"
ഞങ്ങൾ കോർട്ടിലേക്ക് തിരികെ നടക്കുന്നു.
ഞങ്ങൾ വീണ്ടും ബാഡ്മിന്റൺ കളിക്കാൻ പോകുന്നു.
