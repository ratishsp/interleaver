"ആ വലിയ കെട്ടിടത്തിലേക്ക് നേരെ പോകൂ," ആ സ്ത്രീ പറഞ്ഞു.
ഞാൻ അവർക്ക് നന്ദി പറയുന്നു.
ഞാൻ നേരെ നടക്കുന്നു.
പെട്ടെന്ന്, ഞാൻ വെള്ളം കാണുന്നു.
ഇത് മറൈൻ ഡ്രൈവ് ആണ്!
ഞാൻ വീതിയുള്ള നടപ്പാതയിലേക്ക് കയറുന്നു.
മുൻപിൽ വലിയ കായൽ ഉണ്ട്.
ഫെബ്രുവരി മാസം നല്ല സമയമാണ്.
ഇവിടെ നല്ല കാറ്റ് ഉണ്ട്.
ഇവിടെ ഒരുപാട് ആളുകൾ ഉണ്ട്.
അവർ കാറ്റ് ആസ്വദിക്കുന്നു.
ചിലർ ഇടത്തോട്ട് നടക്കുന്നു.
ചിലർ വലത്തോട്ട് നടക്കുന്നു.
ഞാൻ നേരെ മുന്നോട്ട് നടക്കുന്നു.
കൊച്ചി വളരെ മനോഹരമാണ്.
എനിക്ക് വളരെ സന്തോഷം ഉണ്ട്.
