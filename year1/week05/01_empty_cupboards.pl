Jest szósta.
Stoję w kuchni.
Jestem głodna.
Otwieram lodówkę.
Jest całkowicie pusta.
Zaglądam do szafki.
W szafce nie ma jedzenia.
Nie mam jedzenia.
Mam tylko trochę wody.
Chciałabym teraz coś zjeść.
Lubię warzywa.
Lubię też chleb.
Ale nic tu nie mam.
Znajduję torbę.
Torba jest czerwona.
Jest dobra na zakupy.
Wychodzę z mieszkania.
Zamykam drzwi.
Jestem gotowa.
Teraz idę do supermarketu.
