"ഞാൻ ജനുവരിയിൽ കൊച്ചിയിൽ വന്നു," ഞാൻ കിരണിനോടും സാറയോടും പറയുന്നു.
"എനിക്ക് ഇവിടെ ഒരു സോഫ്റ്റ്‌വെയർ കമ്പനിയിൽ ജോലി കിട്ടി."
സാറ തലയാട്ടുന്നു.
"ഞാൻ രാവിലെ വിമാനത്താവളത്തിൽ എത്തി."
"എന്റെ കൂടെ രണ്ട് വലിയ ബാഗുകൾ ഉണ്ടായിരുന്നു."
"ഞാൻ പ്രീപെയ്ഡ് ടാക്സി കൗണ്ടറിലേക്ക് നടന്നു."
"ഞാൻ ഒരു ടാക്സി ബുക്ക് ചെയ്തു."
"ഡ്രൈവർ വന്നു, ബാഗുകൾ എടുക്കാൻ എന്നെ സഹായിച്ചു."
"ഞാൻ കാറിൽ കയറി."
"അയാൾ എന്നോട് വിലാസം ചോദിച്ചു."
"എനിക്ക് വഴി അറിയില്ലായിരുന്നു."
"ഞാൻ എന്റെ ബാഗിൽ നിന്ന് ഒരു കടലാസ് എടുത്തു."
"അതിൽ എന്റെ ആദ്യത്തെ മുറിയുടെ വിലാസം ഉണ്ടായിരുന്നു."
"ഞാൻ ആ കടലാസ് അയാൾക്ക് കൊടുത്തു."
"അയാൾ വിലാസം വായിച്ചു."
"പിന്നെ അയാൾ ചിരിച്ചു, കാർ സ്റ്റാർട്ട് ചെയ്തു."
"ഞാൻ ജനലിലൂടെ പുറത്തേക്ക് നോക്കി."
"എല്ലാം പുതിയതായിരുന്നു."
"പക്ഷേ എനിക്ക് വളരെ സന്തോഷം തോന്നി."
