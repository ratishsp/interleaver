Kasper, Sara, Emil i ja graliśmy w badmintona przez prawie dwie godziny.
Teraz mecz się skończył, a my byliśmy przyjemnie zmęczeni.
Podeszliśmy do ławki.
Usiedliśmy razem.
Otworzyłam torbę i znalazłam swoją butelkę z wodą.
Przez długi czas po prostu piliśmy zimną wodę.
„To był ciężki mecz” – powiedział Kasper.
Sara uśmiechnęła się i spojrzała na mnie.
„Przyjechałaś do Danii w styczniu, prawda?” – zapytała.
„Tak, wyjechałam z Meksyku w styczniu” – odpowiedziałam.
Kasper położył swoją rakietę na ławce.
„Jakie były twoje pierwsze dni w tym kraju?” – zapytał.
Wróciłam myślami do mojego pierwszego tygodnia.
Wszystko było wtedy nowe i zupełnie inne.
W ogóle nie znałam miasta.
„Było bardzo zimno” – zaczęłam.
Kasper i Sara głośno się zaśmiali.
„Duńska zima zawsze jest zimna” – powiedziała Sara.
Kasper mnie zapytał.
