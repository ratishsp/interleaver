സമയം ഇപ്പോൾ ഒന്നു കഴിഞ്ഞതേയുള്ളൂ.
ഞാൻ പതുക്കെ മെഡിക്കൽ ക്ലിനിക്കിലേക്ക് നടക്കുന്നു.
ഇതൊരു ചെറിയ യാത്രയാണ്, എങ്കിലും എനിക്ക് ഇപ്പോഴും നല്ല ശരീരവേദനയും ക്ഷീണവുമുണ്ട്.
ഞാൻ എന്റെ മഞ്ഞ ഹെൽത്ത് കാർഡ് പുറത്തെടുക്കുന്നു.
പുറത്ത് സൂര്യൻ പ്രകാശിക്കുന്നുണ്ട്.
എങ്കിലും ഞാൻ സൺഗ്ലാസ് ധരിക്കേണ്ടതായിരുന്നു, കാരണം വെളിച്ചം എന്റെ കണ്ണുകളെ വേദനിപ്പിക്കുന്നു.
ഞാൻ ക്ലിനിക്കിന്റെ റിസപ്ഷനിൽ പ്രവേശിക്കുന്നു.
ചുമരിൽ ഒരു ചെറിയ മെഷീൻ തൂക്കിയിട്ടുണ്ട്.
നിങ്ങൾ എപ്പോഴും നിങ്ങളുടെ മഞ്ഞ ഹെൽത്ത് കാർഡ് ഇവിടെ സ്കാൻ ചെയ്യണം.
ഞാൻ ഡെന്മാർക്കിലേക്ക് താമസം മാറിയപ്പോൾ എനിക്ക് തപാലിലാണ് ഈ കാർഡ് ലഭിച്ചത്.
ഞാൻ മെഷീനിൽ ആ മഞ്ഞ കാർഡ് സ്കാൻ ചെയ്യുന്നു.
അതിൽ നിന്ന് ചെറിയൊരു ശബ്ദം കേൾക്കുകയും പച്ച വെളിച്ചം മിന്നുകയും ചെയ്യുന്നു.
ഞാൻ ഇവിടെ ഉണ്ടെന്ന് ഡോക്ടർക്ക് അറിയാം എന്നാണ് അതിനർത്ഥം.
ഞാൻ വെയിറ്റിംഗ് റൂമിലേക്ക് തന്നെ നടക്കുന്നു.
ഞാൻ ഒഴിഞ്ഞുകിടക്കുന്ന ഒരു കസേരയിൽ ഇരുന്ന് കാത്തിരിക്കുന്നു.
