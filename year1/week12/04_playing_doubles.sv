Jag går över till en badmintonbana.
Det står tre personer på banan.
"Hej, jag heter Kasper," säger en man.
"Och jag heter Sara," säger en kvinna.
Den tredje spelaren heter Emil.
"Jag heter Maya," säger jag.
"Vi brukar spela dubbel," säger Kasper.
"Vill du spela med oss?" frågar han.
"Ja, mycket gärna," svarar jag.
Jag tycker mycket om att spela badminton.
Kasper och jag spelar mot Sara och Emil.
Vi börjar spela med detsamma.
Sara startar matchen.
Fjäderbollen flyger snabbt fram och tillbaka.
Emil slår fjäderbollen högt upp i luften.
Jag älskar att smasha.
Jag hoppar och smashar den hårt över nätet.
Den landar på deras sida av banan.
"Bra slag, Maya!" ropar Kasper.
