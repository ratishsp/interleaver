എന്റെ ആദ്യത്തെ പ്രവൃത്തിദിവസം കഴിഞ്ഞു.
സമയം അഞ്ച് മണിയാണ്.
ഞാൻ എന്റെ ചൂടുള്ള കോട്ട് ധരിക്കുന്നു.
ഞാൻ എന്റെ സഹപ്രവർത്തകരോട് യാത്ര പറയുന്നു.
"നാളെ കാണാം," അവർ പറയുന്നു.
"അതെ, കാണാം," ഞാൻ മറുപടി നൽകുന്നു.
ഞാൻ പുറത്ത് തെരുവിലേക്ക് നടക്കുന്നു.
ജനുവരിയിൽ തണുപ്പാണ്.
ഞാൻ നാലാം നമ്പർ ബസ്സിൽ വീട്ടിലേക്ക് പോകുന്നു.
ഞാൻ ബസ്സിന്റെ ജനാലയിലൂടെ പുറത്തേക്ക് നോക്കുന്നു.
എനിക്കിപ്പോൾ കോപ്പൻഹേഗനിൽ ഒരു ജോലിയുണ്ട്.
ഇത് ശരിക്കും നല്ലൊരു ആദ്യ ദിവസമാണ്.
ഞാൻ ക്ഷീണിതയാണ്, എങ്കിലും ഞാൻ വളരെ സന്തോഷവതിയാണ്.
