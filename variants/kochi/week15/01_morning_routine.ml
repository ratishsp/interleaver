ഞാൻ ഇന്ന് രാവിലെ നേരത്തെ ഉണരുന്നു.
കിടപ്പുമുറിയിൽ ഇളം വെയിൽ നിറയുന്നു.
കട്ടിലിൽ നിന്ന് എഴുന്നേൽക്കുന്നു.
ജനൽ തുറക്കുന്നു.
പുറത്ത് നല്ല കാലാവസ്ഥയാണ്.
പിന്നെ അടുക്കളയിലേക്ക് പോകുന്നു.
വേഗം പ്രഭാതഭക്ഷണം ഉണ്ടാക്കുന്നു.
ഒപ്പം കാപ്പിയും ഉണ്ടാക്കുന്നു.
കസേരയിൽ ഇരുന്ന് ചൂട് കാപ്പി കുടിക്കുന്നു.
പ്രഭാതഭക്ഷണം കഴിക്കുന്നു.
ശേഷം, ഞാൻ കുളിക്കുന്നു.
വസ്ത്രം ധരിക്കുന്നു.
ലാപ്ടോപ്പും ഒരു വെള്ളക്കുപ്പിയും എന്റെ ബാഗിൽ വെക്കുന്നു.
ഇപ്പോൾ സമയം എട്ട് മണിയാണ്.
ഓഫീസിലേക്ക് പോകാൻ ഞാൻ തയ്യാറാണ്.
