ബാരിസ്റ്റ എന്നെ നോക്കി പുഞ്ചിരിക്കുന്നു.
ഞാൻ ടെർമിനലിന് മുകളിൽ എന്റെ കാർഡ് പിടിക്കുന്നു.
മെഷീൻ ബീപ്പ് ചെയ്യുന്നു.
"നിങ്ങൾക്ക് രസീത് വേണോ?" അയാൾ ചോദിക്കുന്നു.
"വേണ്ട, നന്ദി," ഞാൻ മറുപടി നൽകുന്നു.
ഞാൻ ചുമരിനടുത്തേക്ക് നടക്കുന്നു.
ഞാൻ ഒരു കൊളുത്തിൽ നിന്ന് എന്റെ കട്ടിയുള്ള വിന്റർ കോട്ട് എടുക്കുന്നു.
ഞാൻ ആ കോട്ട് ധരിക്കുന്നു.
ഞാൻ എന്റെ സ്കാർഫും ധരിക്കുന്നു.
ഞാൻ എന്റെ ഗ്ലൗസുകളും ധരിക്കുന്നു.
ഇപ്പോൾ ഞാൻ തണുപ്പിന് തയ്യാറാണ്.
ഞാൻ വീണ്ടും ബാരിസ്റ്റയെ നോക്കുന്നു.
"കോഫിക്ക് വളരെ നന്ദി," ഞാൻ പറയുന്നു.
"സന്തോഷം," ഒരു പുഞ്ചിരിയോടെ അയാൾ പറയുന്നു.
"ഒരു ശുഭദിനം നേരുന്നു."
"നിങ്ങൾക്കും," ഞാൻ പറയുന്നു.
ഞാൻ മുൻവാതിലിനടുത്തേക്ക് നടക്കുന്നു.
ഞാൻ ആ ഭാരമുള്ള വാതിൽ തള്ളിത്തുറക്കുന്നു.
കാറ്റിന് തണുപ്പുണ്ട്, പക്ഷേ എനിക്ക് നല്ല സുഖം തോന്നുന്നു.
