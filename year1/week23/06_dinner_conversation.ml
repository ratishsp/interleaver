ഞങ്ങൾ മനോഹരമായ ആ മേശയ്ക്കരികിൽ ഇരിക്കുന്നു.
വർണ്ണാഭമായ പ്ലേറ്റുകളും കത്തിച്ച മെഴുകുതിരികളും വെച്ച് ഈവ മേശ ഒരുക്കിയിട്ടുണ്ട്.
അവൾ ഞങ്ങൾക്കായി ഗംഭീരമായ ഒരു വെജിറ്റേറിയൻ ഭക്ഷണം തയ്യാറാക്കിയിട്ടുണ്ട്.
"നന്ദി ഈവ, ഇത് കാണാൻ വളരെ രുചികരമായി തോന്നുന്നു," ഞാൻ ഒരു പുഞ്ചിരിയോടെ പറയുന്നു.
"ഇതിന് അതിശയകരമായ മണമാണ്."
"അതിലെന്തിരിക്കുന്നു," അവൾ മറുപടി പറയുകയും എനിക്ക് ഒരു പാത്രം സാലഡ് നീട്ടുകയും ചെയ്യുന്നു.
ഞാൻ ഉടനെ ആ ഭക്ഷണം രുചിച്ചു നോക്കുന്നു.
ഇതിലെ ഫ്രഷ് ആയ ചേരുവകൾക്ക് ശരിക്കും നല്ല രുചിയുണ്ടെന്ന് എനിക്ക് തോന്നുന്നു.
"ഇത് അവിശ്വസനീയമാംവിധം രുചികരമാണ്," ഞാൻ അവളോട് പറയുന്നു.
"കൂടുതൽ പ്രാദേശിക വിഭവങ്ങൾ ഉടൻ തന്നെ പാകം ചെയ്യാൻ ഞാൻ ഉദ്ദേശിക്കുന്നുണ്ട്," ഞാൻ പറയുന്നു.
"കൂടുതൽ ഡാനിഷ് പച്ചക്കറികൾ ഉപയോഗിക്കാൻ ഞാൻ വളരെ ആഗ്രഹിക്കുന്നു."
"അതൊരു മികച്ച ആശയമാണെന്ന് തോന്നുന്നു," ഈവ സന്തോഷത്തോടെ പറയുന്നു.
"നമുക്ക് തീർച്ചയായും ഒരു ദിവസം ഒന്നിച്ച് പാകം ചെയ്യാം."
"നമുക്ക് അടുക്കളയിൽ ഒരുപാട് രസിക്കാൻ കഴിയുമെന്ന് ഞാൻ കരുതുന്നു."
"ഞാൻ അത് വളരെ ആഗ്രഹിക്കുന്നു," ഞാൻ മറുപടി നൽകുകയും ഒരു വായ കൂടി കഴിക്കുകയും ചെയ്യുന്നു.
ഞങ്ങൾ ഗ്ലാസുകളിലേക്ക് കുറച്ച് തണുത്ത വെള്ളം ഒഴിക്കുന്നു.
ഈ സായാഹ്നം ഇതിനകം തന്നെ ഒരു വലിയ വിജയമായി എനിക്ക് തോന്നുന്നു.
