ഞാൻ കടയിലെ കസ്റ്റമർ സർവീസ് കൗണ്ടറിലേക്ക് പോകുന്നു.
അവിടെ ഒരു ക്ലാർക്ക് ഉണ്ട്.
ഞാൻ പച്ച ഷർട്ടും രസീതും അയാൾക്ക് കൊടുക്കുന്നു.
അയാൾ രസീത് നോക്കുന്നു.
"എന്താണ് പ്രശ്നം?" അയാൾ ചോദിക്കുന്നു.
ഞാൻ കാര്യം അയാളോട് വിശദീകരിക്കുന്നു.
"ഞാൻ ഇന്നലെ ഈ ഷർട്ട് വാങ്ങി."
"പക്ഷേ ഈ ഷർട്ട് വളരെ ചെറുതാണ്."
"എൻ്റെ അളവ് ഇതിനെക്കാൾ വലുതാണ്."
"ഇത് മാറ്റിത്തരാമോ?" ഞാൻ ചോദിക്കുന്നു.
അയാൾ ചിരിച്ചുകൊണ്ട് തലയാട്ടുന്നു.
"തീർച്ചയായും, ഇത് മാറ്റിത്തരാം," അയാൾ പറയുന്നു.
"ഇതേ ഷർട്ടിൻ്റെ ഇതിനെക്കാൾ വലിയ അളവ് ഉണ്ടോ?" ഞാൻ ചോദിക്കുന്നു.
"ഞാൻ ഒന്ന് നോക്കട്ടെ," അയാൾ പറയുന്നു.
അയാൾ കമ്പ്യൂട്ടറിൽ തിരയുന്നു.
"അതെ, ഇതിനെക്കാൾ വലിയ അളവ് ഇവിടെ ഉണ്ട്," അയാൾ പറയുന്നു.
ആ ഷർട്ട് എടുക്കാൻ അയാൾ അകത്തേക്ക് പോകുന്നു.
ഞാൻ കൗണ്ടറിന് അടുത്ത് കാത്തുനിൽക്കുന്നു.
