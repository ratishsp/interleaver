ഞാൻ ബില്ലിംഗ് കൗണ്ടറിലേക്ക് പോകുന്നു.
എൻ്റെ ഷോപ്പിംഗ് കാർട്ടിൽ ധാരാളം സാധനങ്ങൾ ഉണ്ട്.
കാർട്ടിൽ അരി, പരിപ്പ്, പാൽ, ചായപ്പൊടി, സുഗന്ധവ്യഞ്ജനങ്ങൾ എന്നിവ ഉണ്ട്.
ഞാൻ അവിടെ ഒരു കാഷ്യറെ കാണുന്നു.
അദ്ദേഹം എൻ്റെ സാധനങ്ങൾ ഓരോന്നായി എടുക്കുന്നു.
അദ്ദേഹം എല്ലാം സ്കാൻ ചെയ്യുന്നു.
"ആകെ എണ്ണൂറ്റി അൻപത് രൂപയാണ്," അദ്ദേഹം പറയുന്നു.
ഞാൻ അദ്ദേഹത്തിന് പണം കൊടുക്കുന്നു.
അദ്ദേഹം എനിക്ക് ബിൽ തരുന്നു.
"നിങ്ങൾക്ക് പ്ലാസ്റ്റിക് ബാഗ് വേണമോ?" അദ്ദേഹം ചോദിക്കുന്നു.
"എനിക്ക് പ്ലാസ്റ്റിക് ബാഗ് വേണ്ട," ഞാൻ പറയുന്നു.
"എൻ്റെ കയ്യിൽ ഒരു തുണിസഞ്ചി ഉണ്ട്."
എനിക്ക് തുണിസഞ്ചികൾ വളരെ ഇഷ്ടമാണ്.
ഞാൻ ആദ്യം ഭാരമുള്ള അരിയും പരിപ്പും സഞ്ചിയിൽ വെക്കുന്നു.
പിന്നെ ഞാൻ പാലും ചായപ്പൊടിയും സുഗന്ധവ്യഞ്ജനങ്ങളും വെക്കുന്നു.
ഈ സഞ്ചിക്ക് നല്ല ഭാരമുണ്ട്.
ഞാൻ സാധനങ്ങളുമായി സൂപ്പർമാർക്കറ്റിൽ നിന്ന് പുറത്തേക്ക് പോകുന്നു.
