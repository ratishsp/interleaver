ഞാൻ ആ സ്ത്രീ പറഞ്ഞ വഴിയിലൂടെ നടക്കുന്നു.
ഞാൻ മാർക്കറ്റിൽ നിന്ന് പുറത്തേക്ക് വരുന്നു.
"നേരെ പോകൂ," അവർ പറഞ്ഞു.
ഞാൻ പ്രധാന റോഡിലൂടെ നേരെ നടക്കുന്നു.
മാർക്കറ്റിലെ തിരക്ക് കുറയുന്നു.
ഞാൻ റോഡിന്റെ അവസാനം എത്തുന്നു.
"അവിടെനിന്ന് വലത്തോട്ട് തിരിയൂ," അവർ പറഞ്ഞു.
ഞാൻ വലത്തോട്ട് തിരിയുന്നു.
ഇപ്പോൾ ഞാൻ വലിയ റോഡിലാണ്.
ഞാൻ ആ നടപ്പാതയിലേക്ക് നടക്കുന്നു.
അവിടെ നല്ല കാറ്റ് വീശുന്നു.
ഞാൻ വെള്ളത്തിന്റെ ശബ്ദം കേൾക്കുന്നു.
അവസാനം, ഞാൻ കായൽത്തീരത്ത് എത്തുന്നു.
ഇതൊരു വലിയ നടപ്പാതയാണ്.
ഞാൻ വിശാലമായ കായൽ കാണുന്നു.
ഇവിടെ ഒരുപാട് മരങ്ങളുണ്ട്.
ആളുകൾ ഇവിടെ നടക്കുന്നു.
ഞാൻ കായലിലേക്ക് നോക്കുന്നു.
കൊച്ചി വളരെ മനോഹരമാണ്.
