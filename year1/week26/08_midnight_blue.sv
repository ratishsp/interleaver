Klockan är nästan tolv på natten, men himlen är fortfarande ljus.
Den har en mjuk, blå färg.
Jag går på gatan tillsammans med Eva och Peter.
Vi pratar inte mycket.
Bara våra fotsteg hörs i natten.
Jag tittar på mina vänner.
Eva ler, och Peter ser trött men glad ut.
När jag kom hit kände jag ingen.
Men mycket har förändrats sedan dess.
Jag har fått en bra vardag, och jag har träffat många människor.
Jag har faktiskt hittat riktiga vänner.
Peter var den första kollegan som jag pratade med.
Och Eva bjöd hem mig till sig nyligen.
Nu går vi här tillsammans under den ljusa sommarhimlen.
Jag har precis fyllt trettiotvå år.
Jag har byggt ett liv som jag älskar.
Jag känner mig äntligen helt hemma i min nya stad.
