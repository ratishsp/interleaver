ബസ് ജംഗ്ഷനിൽ എത്തുന്നു.
എനിക്ക് ഇവിടെ ഇറങ്ങണം.
ബസ് നിർത്തുന്നു.
ഞാൻ ശ്രദ്ധിച്ച് ബസ്സിൽ നിന്ന് ഇറങ്ങുന്നു.
ഞാൻ മുന്നിൽ മെട്രോ സ്റ്റേഷൻ കാണുന്നു.
ഞാൻ വേഗം സ്റ്റേഷനിലേക്ക് നടക്കുന്നു.
ഞാൻ സ്റ്റേഷന്റെ ഉള്ളിൽ കയറുന്നു.
അവിടെ വളരെ ശാന്തമാണ്.
ഉള്ളിൽ നല്ല തണുപ്പുമുണ്ട്.
പുറത്തെ ചൂട് ഇവിടെ ഇല്ല.
സ്റ്റേഷനിൽ ഒരുപാട് ആളുകൾ ഉണ്ട്.
പക്ഷേ ഒരു ബഹളവും ഇല്ല.
എനിക്ക് മെട്രോ ട്രെയിനിൽ കയറണം.
ആദ്യം എനിക്ക് ഒരു ടിക്കറ്റ് എടുക്കണം.
