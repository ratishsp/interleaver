ഞാൻ എന്റെ ഫോൺ മേശപ്പുറത്ത് വെച്ച് വിശ്രമിക്കുന്നു.
പെട്ടെന്ന് എന്റെ വാതിലിൽ വേഗത്തിൽ ഒരു മുട്ട് കേൾക്കുന്നു.
അത് എന്റെ ചിന്തകളെ തടസ്സപ്പെടുത്തുന്നു.
ഞാൻ സോഫയിൽ നിന്ന് എഴുന്നേറ്റ് ഹാളിലേക്ക് നടക്കുന്നു.
ഞാൻ വാതിൽ തുറക്കുമ്പോൾ, നീന പുറത്ത് ഇടനാഴിയിൽ നിൽപ്പുണ്ട്.
അവളുടെ കൈകളിൽ ഒരു ചെറിയ കാർഡ്ബോർഡ് പെട്ടിയുണ്ട്.
"ഹായ് മായ, എന്റടുത്ത് നിനക്കുള്ള ഒരു പാഴ്സൽ ഉണ്ട്," അവൾ ചിരിച്ചുകൊണ്ട് പറയുന്നു.
അവൾ ആ പെട്ടി എനിക്ക് നീട്ടുന്നു.
"ഇന്ന് ഉച്ചതിരിഞ്ഞ് ഇത് എന്റെ വീട്ടിലാണ് കൊണ്ടുത്തന്നത്," നീന വിശദീകരിക്കുന്നു.
"പോസ്റ്റ്മാന് അബദ്ധത്തിൽ നമ്മുടെ വാതിലുകൾ മാറിപ്പോയതായിരിക്കും."
ഞാൻ ആ പെട്ടി നോക്കി അതിൽ എന്റെ പേര് കാണുന്നു.
"ഓ!"
"ഇത് എന്റെ പുതിയ കോഫി ബീൻസാണ്!"
"ഞാൻ സാധാരണയായി അവ ഓൺലൈനായാണ് വാങ്ങാറുള്ളത്," ഞാൻ അവളോട് പറയുന്നു.
"സാധാരണയായി പാഴ്സലുകൾ താഴെ ലോബിയിലാണ് വെക്കാറുള്ളത്," നീന പറയുന്നു.
"അതെ, സാധാരണ അവിടെയാണ് വെക്കാറുള്ളത്," ഞാൻ മറുപടി പറയുന്നു.
നിറഞ്ഞ പുഞ്ചിരിയോടെ ഞാൻ ആ കാർഡ്ബോർഡ് പെട്ടി വാങ്ങുന്നു.
അതിൽ നിന്ന് അപ്പോഴേക്കും വറുത്ത കാപ്പിയുടെ നേരിയ സുഗന്ധം വരുന്നുണ്ട്.
"ഇത് ഇങ്ങോട്ട് കൊണ്ടുവന്നതിന് ഒരുപാട് നന്ദി," ഞാൻ പറയുന്നു.
