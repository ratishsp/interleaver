Sedím u svého stolu v kanceláři.
Píšu kód na svém počítači.
Dívám se z okna.
Dnes je velmi špatné počasí.
Obloha je tmavá a těžká.
Venku je úplně šedo.
Déšť neustále naráží do skla.
Také hodně fouká.
Dívám se na hodiny na zdi.
Je teprve brzké odpoledne.
Ale velmi rychle se dělá pošmourno.
Světlo mizí v šedé obloze.
V tomto ročním období se brzy stmívá.
Je to typické zimní odpoledne v Dánsku.
Tam venku ve větru je velká zima.
Ale tady uvnitř je příjemně teplo.
Piju trochu horké kávy ze svého hrnku.
Minutu poslouchám déšť.
Pak se znovu podívám na obrazovku svého počítače.
Pokračuji ve svém kódu.
