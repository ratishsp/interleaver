Jdu do kuchyně.
Dala bych si něco teplého k pití.
Vařím vodu na čaj.
Voda je velmi horká.
Připravuji si velký šálek bylinkového čaje.
Beru si čaj do obýváku.
Sedám si na pohovku.
Je tmavý zimní večer.
Držím teplý šálek v rukou.
Rychle se zahřeju.
Poslouchám vítr venku.
Hodně fouká.
Počasí je dnes večer divoké.
Ale tady uvnitř je velmi útulně.
Lampa v rohu jemně svítí.
Dám si doušek čaje.
Chutná po mátě.
Dlouhý den je u konce.
Teď odpočívám.
