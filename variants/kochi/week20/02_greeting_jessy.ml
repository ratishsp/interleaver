ഞാൻ കഫേയുടെ ഉള്ളിലേക്ക് കയറുന്നു.
അകത്ത് ജെസ്സി ഉണ്ട്.
ജെസ്സി ഇവിടുത്തെ പരിചയസമ്പന്നയായ ജോലിക്കാരിയാണ്.
മുൻപ് ഇവിടെ വന്നപ്പോൾ മുതൽ എനിക്ക് അവരെ അറിയാം.
ജെസ്സി എന്നെ ചിരിച്ചുകൊണ്ട് സ്വാഗതം ചെയ്യുന്നു.
"സ്വാഗതം മായ," അവർ പറയുന്നു.
ഇന്ന് എന്റെ ഒന്നാമത്തെ ഷിഫ്റ്റ് ആണ്.
ജെസ്സി എനിക്ക് വൃത്തിയുള്ള ഒരു ഏപ്രണ്‍ തരുന്നു.
"ഇത് ധരിക്കൂ," ജെസ്സി പറയുന്നു.
ഞാൻ ആ ഏപ്രണ്‍ ധരിക്കുന്നു.
"മായ ഒരു സോഫ്റ്റ്‌വെയർ എഞ്ചിനീയർ ആണല്ലോ, അല്ലേ?" അവർ ചോദിക്കുന്നു.
"അതെ," ഞാൻ മറുപടി പറയുന്നു.
"ഇതിനുമുൻപ് എപ്പോഴെങ്കിലും ഒരു കഫേയിൽ വോളന്റിയർ ചെയ്തിട്ടുണ്ടോ?" അവർ ചോദിക്കുന്നു.
"അല്ലെങ്കിൽ ഒരു അടുക്കളയിൽ ജോലി ചെയ്തിട്ടുണ്ടോ?"
"ഇല്ല, ഇത് എന്റെ ഒന്നാമത്തെ തവണയാണ്," ഞാൻ പറയുന്നു.
"ഞാൻ ഈ ജോലി ചെയ്യാൻ പഠിക്കുകയാണ്," ഞാൻ കൂട്ടിച്ചേർക്കുന്നു.
ജെസ്സി വീണ്ടും ചിരിക്കുന്നു.
"വിഷമിക്കേണ്ട, എല്ലാം വേഗം പഠിക്കാൻ കഴിയും," അവർ എന്നോട് പറയുന്നു.
