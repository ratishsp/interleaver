കോപ്പൻഹേഗനിൽ പ്രഭാതമാണ്.
ഞാൻ ബസ് സ്റ്റോപ്പിലേക്ക് നടക്കുന്നു.
ഇന്ന് കാലാവസ്ഥയ്ക്ക് വളരെ തണുപ്പാണ്.
കാറ്റടിക്കുന്നുണ്ട്.
കാറ്റിന് ഐസ് പോലെ തണുപ്പാണ്.
ഞാൻ തണുത്തുറയുകയാണ്.
ഞാൻ കനം കുറഞ്ഞ ഒരു ജാക്കറ്റാണ് ധരിച്ചിരിക്കുന്നത്.
എന്റെ ജാക്കറ്റിന് ഒട്ടും ചൂടില്ല.
ഞാൻ കനം കുറഞ്ഞ ഷൂസുകളും ധരിച്ചിട്ടുണ്ട്.
ഞാൻ ചൂടുള്ള ഒരു സ്കാർഫ് ധരിച്ചിട്ടില്ല.
എന്റെ കൈകൾ വല്ലാതെ തണുത്തിരിക്കുന്നു.
ഞാൻ വിറയ്ക്കുകയാണ്.
ഡെന്മാർക്കിലെ ശൈത്യകാലം കഠിനമാണ്.
എനിക്ക് ചൂടുള്ള വസ്ത്രങ്ങൾ വേണം.
എനിക്ക് കട്ടിയുള്ള ഒരു സ്വെറ്റർ വേണം.
എനിക്കൊരു വലിയ സ്കാർഫും വേണം.
പിന്നെ എനിക്ക് ചൂടുള്ള ഗ്ലൗസുകളും വേണം.
ഞാൻ വളരെ വേഗത്തിൽ നടക്കുന്നു.
ജോലിക്ക് ശേഷം ഞാൻ ശൈത്യകാല വസ്ത്രങ്ങൾ വാങ്ങും.
