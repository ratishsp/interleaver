Jag reser mig upp och tar min jacka.
Det är sent och jag måste ta bussen hem.
Eva följer mig ut till dörren.
"Ska vi hitta på något nästa månad?" frågar hon plötsligt.
"Jag har tänkt gå på konstmuseum," förklarar hon.
"Vill du kanske följa med?"
Jag nickar entusiastiskt och tar min väska.
"Ja, det vill jag väldigt gärna," svarar jag.
Jag tror att vi helt säkert kommer att ha roligt.
Jag berättar också för henne att jag älskar modern konst.
"Och jag känner att vi alltid pratar så bra ihop," tillägger jag.
Eva ler brett och öppnar ytterdörren för mig.
"Vi ska definitivt göra upp en plan snart," lovar hon.
"Jag skickar dig ett meddelande på måndag," säger jag.
Jag ger henne en kram och kliver ut i trappuppgången.
Jag ser redan fram emot vår tur till museet.
