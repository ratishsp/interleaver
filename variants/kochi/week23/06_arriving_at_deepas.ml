ഓട്ടോറിക്ഷ ദീപയുടെ വീടിനടുത്ത് എത്തുന്നു.
ഞാൻ ഡ്രൈവർക്ക് നൂറ് രൂപ കൊടുക്കുന്നു.
അയാൾ ഇരുപത് രൂപ ബാക്കി തരുന്നു.
ഞാൻ ഗേറ്റ് തുറന്ന് വീടിന്റെ മുറ്റത്തേക്ക് നടക്കുന്നു.
ഇതൊരു വളരെ ഭംഗിയുള്ള വീടാണെന്ന് ഞാൻ കരുതുന്നു.
ഞാൻ വാതിലിനടുത്തേക്ക് പോയി ബെൽ അടിക്കുന്നു.
ദീപ പെട്ടെന്ന് വാതിൽ തുറക്കുന്നു.
അവർ എന്നെ നോക്കി സന്തോഷത്തോടെ ചിരിക്കുന്നു.
"സ്വാഗതം മായ!"
"അകത്തേക്ക് വരൂ," ദീപ പറയുന്നു.
ഞാൻ അകത്തേക്ക് കയറുന്നു.
"നിങ്ങളുടെ ബാഗ് ഇവിടെ വെക്കാം," ദീപ പറയുന്നു.
ഞാൻ അവർക്ക് മധുരപലഹാരങ്ങളുടെ പെട്ടി കൊടുക്കുന്നു.
"ഇതെന്താണ് മായ?" ദീപ ചോദിക്കുന്നു.
"ഇത് നമുക്ക് കഴിക്കാൻ കുറച്ച് ഹൽവയാണ്," ഞാൻ പറയുന്നു.
"ഈ ബേക്കറി വളരെ നല്ലതാണെന്ന് പ്രകാശ് പറഞ്ഞു."
"ഓ!"
"പ്രകാശിന് ഈ ബേക്കറി വളരെ ഇഷ്ടമാണ്," ദീപ ചിരിച്ചുകൊണ്ട് പറയുന്നു.
"നമുക്ക് രാത്രി ഭക്ഷണത്തിന് ശേഷം ഇത് കഴിക്കാം."
ഇന്നത്തെ സായാഹ്നം വളരെ മനോഹരമായിരിക്കുമെന്ന് ഞാൻ കരുതുന്നു.
