ഞങ്ങളുടെ കളി കഴിയുന്നു.
ഞങ്ങൾ എല്ലാവരും ഞങ്ങളുടെ ബാഗുകൾ എടുക്കുന്നു.
എനിക്ക് വളരെ ക്ഷീണമുണ്ട്.
പക്ഷേ എനിക്ക് വലിയ സന്തോഷമുണ്ട്.
സാറ എന്നെ നോക്കി ചിരിക്കുന്നു.
"മായാ, നിങ്ങൾക്ക് നന്നായി കളിക്കാൻ കഴിയും," സാറ പറയുന്നു.
"വളരെ നന്ദി, സാറ," ഞാൻ പറയുന്നു.
"എനിക്ക് ബാഡ്മിന്റൺ കളിക്കാൻ വളരെ ഇഷ്ടമാണ്."
കിരൺ അവന്റെ റാക്കറ്റ് ബാഗിൽ വെക്കുന്നു.
"മായാ, അടുത്ത ആഴ്ച വീണ്ടും വരുന്നോ?" കിരൺ ചോദിക്കുന്നു.
"അതെ, തീർച്ചയായും," ഞാൻ മറുപടി പറയുന്നു.
"എനിക്ക് നിങ്ങളുടെ കൂടെ കളിക്കാൻ ഇഷ്ടമാണ്," ഞാൻ കൂട്ടിച്ചേർക്കുന്നു.
വിഷ്ണു സന്തോഷത്തോടെ ചിരിക്കുന്നു.
"അത് നല്ലതാണ്," വിഷ്ണു പറയുന്നു.
"ഞങ്ങൾക്കും നിങ്ങളുടെ കൂടെ കളിക്കാൻ ഇഷ്ടമാണ്."
ഞാൻ റാക്കറ്റ് തിരികെ കൊടുക്കുന്നു.
ഞങ്ങൾ എല്ലാവരും യാത്ര ചോദിക്കുന്നു.
ഇപ്പോൾ ഞാൻ വീട്ടിലേക്ക് പോകുന്നു.
അടുത്ത ആഴ്ച ഞാൻ വീണ്ടും ബാഡ്മിന്റൺ കളിക്കാൻ പോകുന്നു!
ഇന്ന് രാത്രി എനിക്ക് നന്നായി ഉറങ്ങാൻ കഴിയും!
