വെള്ളിയാഴ്ച ഉച്ചതിരിഞ്ഞ് ഞാൻ വെയിലത്ത് ശാന്തമായി നടക്കുന്നു.
ഞാൻ എന്റെ ഭാരമേറിയ വിന്റർ കോട്ട് കയ്യിൽ പിടിച്ചിട്ടുണ്ട്.
എനിക്ക് ഇനി അതിന്റെ യാതൊരു ആവശ്യവുമില്ല.
ഞാൻ അടുത്തുള്ള ഡ്രൈ ക്ലീനിംഗ് കടയുടെ മുന്നിൽ നിൽക്കുന്നു.
ഞാൻ വാതിൽ തുറന്ന് അകത്തേക്ക് കയറുന്നു.
ആ ചെറിയ കടയിൽ വൃത്തിയുള്ള തുണികളുടെയും സോപ്പിന്റെയും മണമുണ്ട്.
കൗണ്ടറിന് പിന്നിൽ പ്രായമുള്ള ഒരു മനുഷ്യൻ നിൽക്കുന്നുണ്ട്.
"ഹലോ, എനിക്ക് ഈ കോട്ട് ഒന്ന് ക്ലീൻ ചെയ്യണം," ഞാൻ പറയുന്നു.
ഞാൻ ആ വലിയ ജാക്കറ്റ് കൗണ്ടറിലൂടെ കൈമാറുന്നു.
"തീർച്ചയായും," അയാൾ മറുപടി പറയുകയും അതിന്റെ തുണി പരിശോധിക്കുകയും ചെയ്യുന്നു.
"ഇത് ബുധനാഴ്ച റെഡിയാകും," അദ്ദേഹം പറയുന്നു.
"അതിന് ഇരുന്നൂറ്റി അമ്പത് ക്രോണർ ആകും."
ഞാൻ എന്റെ ബാഗിൽ നിന്ന് ഡെബിറ്റ് കാർഡ് പുറത്തെടുക്കുന്നു.
ഞാൻ രജിസ്റ്ററിൽ പണമടച്ച് ഒരു ചെറിയ മഞ്ഞ രസീത് വാങ്ങുന്നു.
"വളരെ നന്ദി, നല്ലൊരു വാരാന്ത്യം ആശംസിക്കുന്നു," ഞാൻ പറയുന്നു.
"നിങ്ങൾക്കും അങ്ങനെ തന്നെയാകട്ടെ," ഒരു പുഞ്ചിരിയോടെ അദ്ദേഹം മറുപടി നൽകുന്നു.
ഞാൻ ആ രസീത് എന്റെ ബാഗിലേക്ക് വെക്കുന്നു.
തുടർന്ന് ഞാൻ വീണ്ടും തിരക്കേറിയ നടപ്പാതയിലേക്ക് ഇറങ്ങുന്നു.
ഇളം ചൂടുള്ള ഉച്ചതിരിഞ്ഞുള്ള വെയിലത്ത് നടക്കുന്നത് ഞാൻ ആസ്വദിക്കുന്നു.
