ഞാൻ കോർട്ടിലേക്ക് കയറുന്നു.
എന്റെ കൂടെ കിരൺ ഉണ്ട്.
സാറയും വിഷ്ണുവും ഞങ്ങൾക്ക് എതിരെ നിൽക്കുന്നു.
കളി തുടങ്ങുന്നു.
ഞങ്ങൾ വേഗത്തിൽ ഓടുന്നു.
ഞങ്ങൾ ചാടുന്നു.
ഷട്ടിൽ വേഗത്തിൽ എന്റെ അടുത്തേക്ക് വരുന്നു.
എനിക്ക് അത് നന്നായി അടിക്കാൻ കഴിയും.
കിരണും നന്നായി കളിക്കുന്നു.
ഞങ്ങൾ എല്ലാവരും ഒരുമിച്ച് ചിരിക്കുന്നു.
സാറ എന്നെ നോക്കുന്നു.
സാറ പറയുന്നു, "മായ, നിങ്ങൾക്ക് വളരെ നന്നായി കളിക്കാൻ കഴിയും."
ഞാൻ പുഞ്ചിരിക്കുന്നു.
ഞാൻ സാറയോട് നന്ദി പറയുന്നു.
ഇപ്പോൾ ഞങ്ങൾ വീണ്ടും കളിക്കാൻ പോകുന്നു.
