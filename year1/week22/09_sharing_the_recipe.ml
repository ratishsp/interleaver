ഞങ്ങൾ മൂന്നുപേർക്കും ഇപ്പോൾ നന്നായി വയറു നിറഞ്ഞു.
മേശപ്പുറത്ത് ഇനി ഭക്ഷണമൊന്നും ബാക്കിയില്ല.
"അതൊരു ഗംഭീര അത്താഴമായിരുന്നു, മായാ," സാറ സന്തോഷത്തോടെ പറയുന്നു.
"കൃത്യമായി പറഞ്ഞാൽ, നിങ്ങൾ എങ്ങനെയാണ് ഈ മീറ്റ്ബോളുകൾ ഉണ്ടാക്കുന്നത്?" അവൾ പിന്നീട് ചോദിക്കുന്നു.
"ഇത് വളരെ ബുദ്ധിമുട്ടുള്ള കാര്യമാണോ?"
"അല്ല, ഇത് ശരിക്കും വളരെ എളുപ്പമാണ്," ഞാൻ മറുപടി നൽകുന്നു.
"ആദ്യം ഉള്ളി അരിയണം, അതിനുശേഷം മാംസം കൂട്ടിക്കലർത്തണം," ഞാൻ വിശദീകരിക്കുന്നു.
"എൻ്റെ ഫോണിൽ ഇതിൻ്റെ വളരെ നല്ലൊരു പാചകക്കുറിപ്പുണ്ട്."
"ഇന്ന് രാത്രി ഞാൻ നിങ്ങൾക്ക് ഒരു ലിങ്ക് അയച്ചുതരാം."
"വളരെ നന്ദി, എനിക്കത് പരീക്ഷിച്ചുനോക്കാൻ താൽപ്പര്യമുണ്ട്," സാറ പറയുന്നു.
ഞങ്ങൾ ആ ചെറിയ കസേരകളിൽ നിന്ന് എഴുന്നേൽക്കുന്നു.
കാസ്പർ ഒഴിഞ്ഞ പ്ലേറ്റുകൾ ശേഖരിക്കാൻ തുടങ്ങുന്നു.
"നമുക്കിപ്പോൾ ഈ പ്ലേറ്റുകൾ അടുക്കളയിലേക്ക് കൊണ്ടുപോകണമോ?" അവൻ ചോദിക്കുന്നു.
"അതെ, എടുത്തോളൂ."
"അവ അടുക്കളയിലെ കൗണ്ടറിൽ വെച്ചാൽ മതി," ഞാൻ പറയുന്നു.
ഞങ്ങൾ ഒരുമിച്ച് വേഗത്തിൽ മേശ വൃത്തിയാക്കുന്നു.
"എന്നാൽ കേട്ടോ, അടുത്ത തവണ എൻ്റെ ഊഴമാണ്," കാസ്പർ പെട്ടെന്ന് പറയുന്നു.
"അതെ."
"അടുത്ത തവണ നിങ്ങൾ ഞങ്ങൾക്കായി ഭക്ഷണം പാകം ചെയ്യണം!"
സാറ ചിരിക്കുന്നു.
"അതുതന്നെ."
"മാത്രമല്ല, അത് നന്നായിരിക്കുമെന്ന് ഞാൻ വാഗ്ദാനം ചെയ്യുന്നു," അവൻ പറയുന്നു.
ഞങ്ങൾ ചിരിച്ചുകൊണ്ട് ബാക്കിയുള്ള സാധനങ്ങൾ അടുക്കളയിലേക്ക് കൊണ്ടുപോകുന്നു.
