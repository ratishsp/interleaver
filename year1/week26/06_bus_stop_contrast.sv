Jag går ensam ner mot stranden.
Det är redan kväll, men himlen är fortfarande mycket ljus.
Solen har inte börjat gå ner ännu.
Jag tittar upp och tänker tillbaka på januari.
Då väntade jag ofta på bussen efter jobbet.
Klockan var bara fyra på eftermiddagen.
Men det var redan kolmörkt överallt.
Jag stod vid busshållplatsen och frös.
Nu har jag bott här i ett halvt år.
Allting har förändrats.
I Mexiko gick solen alltid ner vid nästan samma tid.
Så var det hela året.
Här har jag aldrig upplevt så långa dagar förut.
Ljuset har gett staden ett helt nytt liv.
Jag tar på mig min varma tröja.
Även om himlen är ljus, blåser vinden lite kallt från havet.
Jag ser fram emot att se brasan.
Det blir en härlig kväll med mina vänner.
