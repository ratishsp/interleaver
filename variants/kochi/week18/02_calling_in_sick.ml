ഞാൻ ഓഫീസിലെ മാനേജറെ ഫോണിൽ വിളിക്കുന്നു.
"ഹലോ സുരേഷ്, ഞാൻ മായയാണ്," ഞാൻ പറയുന്നു.
"ഗുഡ് മോർണിംഗ് മായ, എന്താണ് കാര്യം?" അദ്ദേഹം ചോദിക്കുന്നു.
"എനിക്ക് ഇന്ന് ഓഫീസിൽ വരാൻ കഴിയില്ല," ഞാൻ പറയുന്നു.
"എനിക്ക് പനിയുണ്ട്, കൂടാതെ നല്ല തലവേദനയും ഉണ്ട്."
"അതെയോ?"
"നിങ്ങൾ തീർച്ചയായും ഒരു ഡോക്ടറെ കാണണം," അദ്ദേഹം പറയുന്നു.
"അതെ, എന്റെ തൊണ്ടയും വേദനിക്കുന്നുണ്ട്," ഞാൻ മറുപടി പറയുന്നു.
"ഞാൻ ഇന്ന് തന്നെ ഡോക്ടറെ കാണാൻ പോകുന്നുണ്ട്."
"ശരി മായ, നിങ്ങൾ നന്നായി വിശ്രമിക്കണം," മാനേജർ പറയുന്നു.
"പ്രകാശിനോടും ഈ കാര്യം പറയണം," അദ്ദേഹം കൂട്ടിച്ചേർക്കുന്നു.
"ശരി, ഞാൻ പ്രകാശിന് ഒരു മെസ്സേജ് അയക്കാം," ഞാൻ പറയുന്നു.
സംസാരിച്ചതിന് ശേഷം ഞാൻ ഫോൺ വെക്കുന്നു.
ഇനി എനിക്ക് ക്ലിനിക്കിൽ വിളിക്കണം.
