Stojím před budovou číslo dvanáct.
Najdu Evino jméno a zazvoním.
Dveře se otevřou a já jdu po schodech nahoru.
Eva stojí ve dveřích a široce se usmívá.
„Ahoj Mayo, vítej!“ říká a obejme mě.
„Děkuji za pozvání,“ odpovídám.
Vstoupím do jejího bytu.
Je velmi útulný a plný barevného umění.
Dávám jí žluté tulipány.
Doufám, že už na stole nemá vázu s květinami.
Eva se dívá na květiny a vypadá velmi šťastně.
„Jak jsou krásné!“ zvolá.
„Miluji žluté květiny.“
Mám pocit, že často rozumím jejímu kreativnímu vkusu.
„Hned pro ně najdu vázu,“ říká Eva.
„Běž prostě do obýváku,“ pokračuje.
Sundám si boty a jdu tam.
Jídelní stůl je krásně prostřený jemnými skleničkami.
Mám v úmyslu si odpočinout a užít si večer.
