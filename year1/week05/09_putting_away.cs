Jsem zase doma v bytě.
Stojím v kuchyni.
Vyprázdním tašku na kuchyňskou linku.
Vybalím jídlo.
Vezmu mléko.
Dám mléko do lednice.
Pak se podívám na pastinák.
Je to legrační kořen.
Použiju ho do polévky.
Dám pastinák do lednice.
Teď už lednice není prázdná.
Vezmu chléb.
Žitný chléb je velmi těžký.
Dám chléb do skříňky.
Pak vezmu plechovku s fazolemi.
Fazole vydrží dlouho.
Dám plechovku do skříňky.
Teď je ve skříňce jídlo.
Mám docela hlad.
Ráda bych si teď dala večeři.
