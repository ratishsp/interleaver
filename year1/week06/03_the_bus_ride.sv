Ute på gatan väntar jag på min buss.
Det är kallt idag.
Många människor står vid busshållplatsen.
En röd buss kommer.
Dörrarna öppnas.
Jag stiger på bussen.
Här skannar jag mitt resekort.
Busschauffören tittar på mig.
"God morgon", säger chauffören.
"God morgon", svarar jag.
Jag går ner genom bussen.
Jag hittar en ledig plats vid fönstret.
Jag sätter mig ner.
Bussen kör genom staden.
Utanför fönstret ser jag många människor.
De cyklar snabbt på cykelbanan.
Vi kör förbi en vacker park.
I parken promenerar folk.
Nu stannar bussen vid min arbetsplats.
Jag stiger av och går in på kontoret.
