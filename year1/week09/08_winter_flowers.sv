Jag går mot marknadens utgång.
Jag ser ett stort blomsterstånd.
Ståndet har många vackra blommor.
Jag stannar framför ståndet.
Jag tittar på en bunt vintertulpaner.
De är mycket färgglada.
Jag pekar på tulpanerna.
"Hur mycket kostar tulpanerna?" frågar jag säljaren.
Säljaren håller upp tulpanerna.
"De kostar fyrtio kronor," svarar han.
"Jag köper dem," säger jag.
Jag betalar för blommorna.
Säljaren ger mig tulpanerna.
Nu är jag klar på marknaden.
Jag går tillbaka till min lägenhet.
Jag håller de färgglada tulpanerna i min hand.
Jag dricker mitt varma kaffe.
Solen skiner över den livliga marknaden.
