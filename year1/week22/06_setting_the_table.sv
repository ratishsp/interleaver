Medan köttet steker färdigt dukar jag bordet i vardagsrummet.
Min matplats är ganska liten.
Men det finns gott om plats för Kasper, Sara och mig.
Jag tar ut tre tallrikar ur skåpet.
Jag ställer dem på det lilla bordet.
Därefter öppnar jag lådan med bestick.
Jag tar fram gafflar och knivar.
Jag lägger en gaffel och en kniv vid varje tallrik.
Vi kommer också att behöva tre glas till vatten.
Dem hämtar jag ute i köket.
Till sist tar jag några ljusblå pappersservetter ur ett paket.
Jag viker dem fint.
Sedan lägger jag en servett på varje tallrik.
Nu är bordet dukat och redo för gäster.
Jag går tillbaka till spisen.
Köttbullarna fräser fortfarande i den varma pannan.
Jag tar pannan från värmen.
Jag är helt redo att ta emot gäster.
