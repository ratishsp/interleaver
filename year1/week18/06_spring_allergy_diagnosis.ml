ഡോക്ടർ എന്നോട് വായ തുറക്കാൻ ആവശ്യപ്പെടുന്നു.
"ആ എന്ന് പറയൂ," ഒരു പുഞ്ചിരിയോടെ അദ്ദേഹം പറയുന്നു.
അദ്ദേഹം എന്റെ തൊണ്ട ശ്രദ്ധയോടെ നോക്കുന്നു.
അതിനുശേഷം, അദ്ദേഹം എന്റെ ശ്വാസോച്ഛ്വാസം ശ്രദ്ധിക്കുന്നു.
വേറെ എവിടെയെങ്കിലും അസ്വസ്ഥത അനുഭവപ്പെടുന്നുണ്ടോ എന്ന് അദ്ദേഹം ചോദിക്കുന്നു.
എന്റെ തലയും വേദനിക്കുന്നുണ്ടെന്ന് ഞാൻ അദ്ദേഹത്തോട് പറയുന്നു.
"ഇതൊരു ജലദോഷമല്ല," അദ്ദേഹം പറയുന്നു.
"നിങ്ങൾക്ക് വസന്തകാലത്തുണ്ടാകുന്ന ഒരു സാധാരണ അലർജിയാണ്," അദ്ദേഹം വിശദീകരിക്കുന്നു.
ഞാൻ അല്പം അത്ഭുതപ്പെടുന്നു.
എനിക്ക് ഇതിനുമുമ്പ് ഒരിക്കലും അലർജി ഉണ്ടായിട്ടില്ല.
ഇത് തികച്ചും സാധാരണമാണെന്ന് അദ്ദേഹം എന്നോട് പറയുന്നു.
ഇവിടുത്തെ മരങ്ങളും പൂക്കളും എന്റെ ശരീരത്തിന് പുതിയതാണ്.
"നിങ്ങൾ ഫാർമസിയിൽ നിന്ന് വീര്യം കുറഞ്ഞ എന്തെങ്കിലും മരുന്ന് വാങ്ങണം," ഡോക്ടർ പറയുന്നു.
ഇത് വേഗത്തിൽ ആശ്വാസം നൽകുമെന്ന് അദ്ദേഹം ഉറപ്പുനൽകുന്നു.
"അതോടെ നിങ്ങൾക്ക് വീണ്ടും സുഖം തോന്നും," അദ്ദേഹം കൂട്ടിച്ചേർക്കുന്നു.
എനിക്ക് വലിയ ആശ്വാസം തോന്നുന്നു.
എന്റെ തൊണ്ട വേദനിക്കുന്നുണ്ട്, എന്നാൽ ഭാഗ്യവശാൽ ഇത് ഗുരുതരമല്ല.
