എനിക്ക് മുടി വെട്ടണം.
ഞാൻ എപ്പോഴും വൈകുന്നേരം സലൂണിൽ പോകുന്നു.
ഞാൻ പനമ്പിള്ളി നഗറിലെ ഒരു സലൂണിലേക്ക് ഫോൺ വിളിക്കുന്നു.
ഒരു റിസപ്ഷനിസ്റ്റ് ഫോൺ എടുക്കുന്നു.
"ഹലോ, പനമ്പിള്ളി സലൂൺ," അവർ പറയുന്നു.
"ഹലോ, എനിക്ക് ഒരു അപ്പോയിന്റ്മെന്റ് വേണം," ഞാൻ പറയുന്നു.
"ഏത് ദിവസമാണ് വേണ്ടത്?" റിസപ്ഷനിസ്റ്റ് ചോദിക്കുന്നു.
"ബുധനാഴ്ച വേണം," ഞാൻ മറുപടി പറയുന്നു.
"ബുധനാഴ്ച എത്ര മണിക്കാണ്?" അവർ ചോദിക്കുന്നു.
ഞാൻ എന്റെ കലണ്ടർ നോക്കുന്നു.
"വൈകുന്നേരം അഞ്ചരയ്ക്ക്," ഞാൻ പറയുന്നു.
"ശരി, ബുധനാഴ്ച വൈകുന്നേരം അഞ്ചരയ്ക്ക് ബുക്ക് ചെയ്യുന്നു," അവർ പറയുന്നു.
"നിങ്ങളുടെ പേര് എന്താണ്?" അവർ ചോദിക്കുന്നു.
"എന്റെ പേര് മായ," ഞാൻ പറയുന്നു.
"നിങ്ങളുടെ ഫോൺ നമ്പർ എന്താണ്?" അവർ ചോദിക്കുന്നു.
"തൊണ്ണൂറ്റിയെട്ട്, എഴുപത്തിയാറ്, അമ്പത്തിനാല്, മുപ്പത്തിരണ്ട്, പത്ത്," ഞാൻ പറയുന്നു.
"ശരി മായ, നന്ദി," അവർ പറയുന്നു.
"നന്ദി," ഞാൻ പറയുന്നു.
ഞാൻ ഫോൺ വെക്കുന്നു.
