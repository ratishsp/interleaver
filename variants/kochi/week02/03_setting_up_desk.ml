പ്രകാശ് പുതിയ മേശയുടെ അടുത്തേക്ക് നടക്കുന്നു.
ഞാൻ അദ്ദേഹത്തിന്റെ കൂടെ നടക്കുന്നു.
"ഇതാണ് മായയുടെ മേശ," പ്രകാശ് പറയുന്നു.
എനിക്ക് ഈ മേശ ഇഷ്ടമാണ്.
ഞാൻ എന്റെ ബാഗ് മേശപ്പുറത്ത് വെക്കുന്നു.
ഞാൻ ബാഗിൽ നിന്ന് ലാപ്ടോപ്പ് എടുക്കുന്നു.
ഞാൻ ലാപ്ടോപ്പ് തുറക്കുന്നു.
"മായയ്ക്ക് മൗസ് ഉണ്ടോ?" പ്രകാശ് ചോദിക്കുന്നു.
"അതെ, എനിക്ക് മൗസ് ഉണ്ട്," ഞാൻ പറയുന്നു.
ഞാൻ ബാഗിൽ നിന്ന് മൗസ് പുറത്തെടുക്കുന്നു.
"ഒരു പേന ഉണ്ടോ?" പ്രകാശ് ചോദിക്കുന്നു.
"ഇല്ല, എനിക്ക് പേന ഇല്ല," ഞാൻ പറയുന്നു.
പ്രകാശ് എനിക്ക് ഒരു നീല പേന തരുന്നു.
"നന്ദി," ഞാൻ പറയുന്നു.
ഇപ്പോൾ എനിക്ക് എല്ലാ സാധനങ്ങളും ഉണ്ട്.
ഞാൻ കസേരയിൽ ഇരിക്കുന്നു.
ഞാൻ എന്റെ ജോലി തുടങ്ങുന്നു.
