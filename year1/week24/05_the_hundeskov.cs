Ludwig jde rychle vedle mě.
Jsme na cestě do místního psího lesa.
Dnes odpoledne krásně svítí slunce.
Trochu nedočkavě tahá za vodítko.
„Čekej,“ řeknu mu důrazně.
„Pojď, půjdeme hezky.“
Konečně přicházíme k velké brance.
Psí les je oplocený a naprosto bezpečný.
Vejdeme dovnitř a já za námi zavřu branku.
Dřepnu si a podívám se na něj.
Pomalu mu odepnu vodítko z obojku.
„Teď můžeš volně běhat,“ řeknu s úsměvem.
Radostně se na mě podívá a rychle odběhne.
Najdu na zemi dobrý klacek.
„Podívej sem, Ludwigu!“ zavolám a ukážu mu ho.
Hodím klacek daleko mezi stromy.
„Přines!“ řeknu nahlas.
Doběhne ke klacku a vezme ho do tlamy.
„Pojď zpátky,“ zavolám a zatleskám.
Je to opravdu šikovný pes.
