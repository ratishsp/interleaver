Byt je konečně hotový.
Teď je to opravdový domov.
Nina klepe na dveře.
Stojí u dveří s teplým jídlem.
„Mám s sebou dvě pizzy,“ říká.
Jdeme do obýváku.
U okna stojí malá pohovka.
Sedíme spolu na pohovce.
Na konferenčním stolku leží dvě krabice od pizzy.
Krabice leží mezi námi.
Na stole stojí také dvě sklenice.
Jíme teplé pizzy.
„Vítej ve svém novém bytě,“ říká Nina.
„Moc děkuji,“ odpovídám.
Dlouho si spolu povídáme.
Moje nová rostlina stojí v okně.
Moje bačkory leží pod židlí.
Všechno je na svém místě.
Jsem se svým novým domovem velmi spokojená.
