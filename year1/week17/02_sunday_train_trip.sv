Jag skrev i min dagbok om min resa till Odense.
Det var en härlig lördagsmorgon.
Jag vaknade tidigt klockan sju.
Solen sken, och himlen var blå.
Jag packade min lilla, gröna ryggsäck.
Jag lade en anteckningsbok och en kamera i väskan.
Jag tog också med en tjock tröja.
Vårvädret i Danmark kan vara lite kallt.
Därefter tog jag bussen in till den stora stationen i Köpenhamn.
Det var många jäktade människor där inne.
Jag gick fram till en liten kiosk.
Jag köpte en stor, varm kaffe till resan.
Den kostade fyrtiofem kronor.
Jag tittade upp på den stora skärmen.
Jag hittade snabbt mitt tåg på skärmen.
Jag skulle med det snabba tåget till Odense.
Tåget ankom till perrongen precis klockan åtta.
Jag gick in i tåget och hittade min plats vid ett stort fönster.
Jag drack min varma kaffe och såg fram emot utflykten.
