ഞാൻ സ്വീകരണമുറിയിലെ ജനലിനരികിൽ നിൽക്കുന്നു.
ഞാൻ പുറത്ത് നഗരത്തിലേക്ക് നോക്കുന്നു.
ആകാശം ഇനി കറുപ്പല്ല.
അത് പതുക്കെ ചാരനിറമാകുന്നു.
സൂര്യൻ വൈകിയാണ് ഉദിക്കുന്നത്.
ഞാൻ എന്റെ ഫോൺ എടുക്കുന്നു.
ഞാൻ ഇന്നത്തെ കാലാവസ്ഥാ പ്രവചനം വായിക്കുന്നു.
ഇപ്പോൾ വളരെ തണുപ്പാണ്.
രണ്ട് ഡിഗ്രി മാത്രമേയുള്ളൂ.
എന്നാൽ പുറത്ത് ഇപ്പോഴും വരണ്ടിരിക്കുകയാണ്.
പിന്നീട് വളരെ നനവുള്ള കാലാവസ്ഥയാകും.
ഉടൻ മഴ പെയ്യും.
കാറ്റും വീശും.
പകൽ സമയത്ത് പിന്നീട് ശക്തമായ കാറ്റ് വീശും.
ഇതൊരു യഥാർത്ഥ ശൈത്യകാല ദിവസമായി മാറും.
ഞാൻ ഫോൺ മേശപ്പുറത്ത് വെക്കുന്നു.
ഞാൻ ഒന്നുകൂടി ആകാശത്തേക്ക് നോക്കുന്നു.
