ഉച്ചകഴിഞ്ഞ് ഞാൻ അരുണിന്റെ സീറ്റിനടുത്തേക്ക് പോകുന്നു.
അരുൺ ഞങ്ങളുടെ ടീമിലെ സോഫ്റ്റ്‌വെയർ ടെസ്റ്റർ ആണ്.
എനിക്ക് എന്റെ ജോലിയെക്കുറിച്ച് ഒരു സംശയമുണ്ട്.
"എന്റെ ജോലി എങ്ങനെയാണ് പരിശോധിക്കുന്നത്?" ഞാൻ ചോദിക്കുന്നു.
അദ്ദേഹം എന്നെ നോക്കി ചിരിക്കുന്നു.
അരുൺ അദ്ദേഹത്തിന്റെ ജോലി വ്യക്തമായി വിശദീകരിക്കുന്നു.
അദ്ദേഹം ഒരു ചെറിയ പ്ലാൻ എനിക്ക് കാണിച്ചുതരുന്നു.
"മായയുടെ ജോലി കഴിയുമ്പോൾ എന്നെ അറിയിക്കുക," അദ്ദേഹം പറയുന്നു.
"അപ്പോൾ ഞാൻ ഈ പ്ലാൻ വെച്ച് അത് പരിശോധിക്കും."
ഞാൻ അദ്ദേഹം തയ്യാറാക്കിയ പ്ലാൻ നോക്കുന്നു.
ആ പ്ലാൻ വളരെ ലളിതമാണ്.
"അരുൺ എത്ര വർഷമായി ടെസ്റ്റർ ആയി ജോലി ചെയ്യുന്നു?" ഞാൻ ചോദിക്കുന്നു.
"ഞാൻ മൂന്നു വർഷം ഈ ജോലി ചെയ്തിട്ടുണ്ട്," അദ്ദേഹം മറുപടി നൽകുന്നു.
അദ്ദേഹം ഇതിനുമുൻപും വലിയ പ്രൊജക്റ്റുകൾ ചെയ്തിട്ടുണ്ട്.
അരുണിന്റെ വാക്കുകൾ കേട്ട് എന്റെ മനസ്സ് ശാന്തമാകുന്നു.
ഞാൻ അദ്ദേഹത്തോട് നന്ദി പറയുന്നു.
അതിനുശേഷം ഞാൻ എന്റെ സീറ്റിലേക്ക് മടങ്ങുന്നു.
