Sara a já vycházíme ze sportovní haly.
Je pozdě a je chladný zimní večer.
Ale po zápase je mi pořád teplo.
Jdeme spolu na autobusovou zastávku.
Fouká vítr a ulice je tmavá.
„Hraješ taky ráda badminton o víkendu?“ ptám se.
„Ne, badminton hraju jen ve čtvrtek,“ odpovídá Sara.
„Ale ráda sportuju,“ říká.
„Většinou chodím běhat do parku,“ pokračuje.
Je to velmi aktivní a zábavný člověk.
Čekáme v chladu na autobus.
„Můj autobus přijede za deset minut,“ říkám.
„Jedeme stejným autobusem,“ usmívá se Sara.
Jsem za to moc ráda.
Ráda si s ní povídám.
Kasper a Sara jsou zábavní a milí lidé.
Teď mám ve čtvrtek dobrou rutinu.
Jsem unavená, ale mám dobrou náladu.
Autobus konečně přijíždí.
Už se těším na příští čtvrtek.
