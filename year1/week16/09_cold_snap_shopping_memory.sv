Till sist berättar jag för min mamma om vintern.
Vädret ändrades plötsligt.
Det blåste, och luften var iskall.
Kylan bet i mina kinder på väg till jobbet.
Jag behövde lite varma kläder.
Efter jobbet skyndade jag mig in i en stor butik.
Lyckligtvis var det härligt varmt där inne.
En vänlig expedit jobbade i butiken.
Hon kom fram till mig och log.
Hon frågade: "Letar du efter något särskilt?"
Jag svarade: "Ja tack, jag vill gärna köpa er varmaste vinterjacka."
Hon hittade en tjock, mörkblå jacka till mig.
Jag provade den genast.
Den var härligt varm, och den passade perfekt.
Jag tog också en mjuk, blå halsduk.
Jag tog med mig sakerna upp till kassan och betalade.
Kläderna kostade femtonhundra kronor.
Det var lite dyrt, men det var helt nödvändigt.
Min mamma klappar i händerna.
Hon är glad över att jag äntligen hade det varmt.
