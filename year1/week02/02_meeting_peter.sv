Jag är nu inne på det nya kontoret.
Det är ett stort och ljust rum.
En vänlig man står vid dörren.
Han ler mot mig.
"Välkommen!" säger han.
"Jag heter Peter."
Jag skakar hand med honom.
"Hej Peter, jag heter Maya," säger jag.
Peter är en kollega.
Vi går tillsammans genom kontoret.
"Du har ett skrivbord här," säger Peter.
Skrivbordet har nummer sexton.
"Och du har en dator," säger han.
Han ger mig en ny bärbar dator.
Jag tittar på min nya plats.
Jag har en stol och en stor skärm.
"Tack så mycket, Peter," säger jag.
Jag är redo för min första arbetsdag.
