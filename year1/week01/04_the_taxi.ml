ഞാൻ ഒരു ടാക്സി പിടിക്കുന്നു.
"നമസ്കാരം," ഡ്രൈവർ പറയുന്നു.
"നിങ്ങൾ എവിടേക്കാണ് പോകുന്നത്?" അദ്ദേഹം ചോദിക്കുന്നു.
"ഞാൻ ന്യൂവെയ് പന്ത്രണ്ടിലേക്കാണ് പോകുന്നത്," ഞാൻ മറുപടി പറയുന്നു.
ഞങ്ങൾ യാത്ര തിരിക്കുന്നു.
"നിങ്ങൾ കോപ്പൻഹേഗനിൽ പുതിയതാണോ?" അദ്ദേഹം ചോദിക്കുന്നു.
"അതെ, ഞാൻ മെക്സിക്കോയിൽ നിന്നാണ്," ഞാൻ പറയുന്നു.
"നഗരം വലുതാണ്," അദ്ദേഹം ചിരിച്ചുകൊണ്ട് പറയുന്നു.
"അതെ, വളരെ വലുതാണ്," ഞാൻ മറുപടി പറയുന്നു.
ഞാൻ ജനാലയിലൂടെ പുറത്തേക്ക് നോക്കുന്നു.
കാറിൽ നിന്ന് ഞാൻ തെരുവുകൾ കാണുന്നു.
വീടുകൾക്ക് നല്ല ഉയരമുണ്ട്.
