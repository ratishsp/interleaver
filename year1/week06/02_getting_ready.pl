W sypialni otwieram moją szafę.
Patrzę na moje ubrania.
Wybieram niebieską koszulę i czarne spodnie.
Potem się ubieram.
Czeszę włosy przed lustrem.
Teraz idę do kuchni.
Jestem głodna.
Znajduję talerz i kubek.
Robię szybkie śniadanie.
Dzisiaj jem chleb z serem.
Nalewam kawę do kubka.
Kawa jest czarna i mocna.
Siadam przy stole.
Tutaj jem swoje jedzenie.
Smakuje dobrze.
Piję moją kawę.
Na koniec biorę moją torbę i moją kurtkę.
Zamykam drzwi na klucz i wychodzę.
