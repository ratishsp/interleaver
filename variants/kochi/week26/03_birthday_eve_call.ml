നാളെ എന്റെ മുപ്പത്തിരണ്ടാമത്തെ ജന്മദിനമാണ്.
രാത്രി ഞാൻ മെക്സിക്കോയിലെ എന്റെ കുടുംബത്തെ വീഡിയോ കോൾ ചെയ്യുന്നു.
അച്ഛനും അമ്മയും അനിയത്തി സോഫിയയും ചേട്ടൻ ഡീഗോയും സ്ക്രീനിൽ വരുന്നു.
പിന്നിൽ ലോല ഉറക്കെ കുരയ്ക്കുന്നുണ്ട്.
"അവൾ നിന്റെ ശബ്ദം കേട്ടിട്ടുണ്ട്," ഡീഗോ പറയുന്നു.
"മായ, അഡ്വാൻസ് ഹാപ്പി ബർത്ത്ഡേ!" അവർ ഒന്നിച്ച് പറയുന്നു.
ഞങ്ങൾ പഴയ ജന്മദിനങ്ങളെക്കുറിച്ച് ഒരുപാട് സംസാരിക്കുന്നു.
"ഞാൻ ഇന്ന് നിനക്ക് ഇഷ്ടപ്പെട്ട കേക്ക് ഉണ്ടാക്കിയിട്ടുണ്ട്," അമ്മ പറയുന്നു.
"കഴിഞ്ഞ വർഷം ചേച്ചി അത് മുഴുവൻ ഒറ്റയ്ക്ക് കഴിച്ചു!"
സോഫിയ ചിരിക്കുന്നു.
അത് കേട്ട് ഞാനും ഉറക്കെ ചിരിക്കുന്നു.
സ്ക്രീനിലെ അവരുടെ മുഖങ്ങൾ ഞാൻ നോക്കുന്നു.
പെട്ടെന്ന്, എനിക്ക് എന്റെ നാടും വീടും വല്ലാതെ ഓർമ്മ വരുന്നു.
ഞാൻ അവരെ വല്ലാതെ മിസ്സ് ചെയ്യുന്നു.
എന്റെ കണ്ണുകൾ നിറയുന്നു.
"എന്തുപറ്റി?"
"നീ കരയുകയാണോ?" അച്ഛൻ ചോദിക്കുന്നു.
"അല്ല, ഞാൻ വെറുതെ പഴയ കാര്യങ്ങൾ ഓർത്തു," ഞാൻ പറയുന്നു.
അവർ എന്നോട് ഒരുപാട് സ്നേഹത്തോടെ സംസാരിക്കുന്നു.
കുറച്ചു കഴിഞ്ഞ് ഞാൻ കോൾ അവസാനിപ്പിക്കുന്നു.
പുറത്ത് നല്ല മഴയുണ്ട്, നാളെ കൊച്ചിയിലെ എന്റെ ആദ്യത്തെ ജന്മദിനമാണ്.
