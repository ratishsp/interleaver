Moje matka se dívá na obrazovku.
„Je to tvůj pokoj, Mayo?“ ptá se.
„Ano, je to můj pokoj,“ odpovídám.
„Ale je to dočasný pokoj.“
Zvedám svůj počítač.
Ukazuji svůj malý pokoj své rodině.
„Tady je postel,“ říkám.
„A tady je moje nová rostlina.“
„To je velmi pěkná rostlina,“ říká moje matka.
Otáčím svůj počítač.
„A tady je okno,“ říkám.
Moje sestra Sofía se dívá na moje okno.
„Ale je tam velká tma,“ říká.
„Ano, venku je úplně černo,“ odpovídám.
„Ale v létě je tu spousta slunce.“
Je večer a je zima.
„Ale mám svou lampu,“ usmívám se.
„Takže je to dobrý pokoj.“
