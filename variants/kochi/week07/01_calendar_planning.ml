ഇപ്പോൾ ഫെബ്രുവരി മാസമാണ്.
കൊച്ചിയിൽ ഇപ്പോൾ നല്ല കാലാവസ്ഥയാണ്.
ഞാൻ എന്റെ പുതിയ കലണ്ടർ എടുക്കുന്നു.
എനിക്ക് ഈ ആഴ്ചത്തെ കാര്യങ്ങൾ പ്ലാൻ ചെയ്യണം.
തിങ്കളാഴ്ച മുതൽ വെള്ളിയാഴ്ച വരെ എനിക്ക് ജോലിയുണ്ട്.
ഞാൻ എപ്പോഴും രാവിലെ ഒൻപതു മണിക്ക് ഓഫീസിൽ പോകും.
വൈകുന്നേരം ആറു മണിക്ക് ഞാൻ തിരികെ വരും.
ഞാൻ ഈ സമയങ്ങൾ കലണ്ടറിൽ എഴുതുന്നു.
തിങ്കളാഴ്ചകളിൽ ഞാൻ എപ്പോഴും ജിമ്മിൽ പോകും.
ബുധനാഴ്ചകളിലും ഞാൻ ജിമ്മിൽ പോകും.
വൈകുന്നേരം ആറു മണിക്ക് ആണ് എന്റെ ജിം സമയം.
ചിലപ്പോൾ ഞാൻ ശനിയാഴ്ചയും ജിമ്മിൽ പോകും.
