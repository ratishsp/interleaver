ഇത് കൊച്ചിയിലെ എന്റെ പുതിയ ഫ്ലാറ്റ് ആണ്.
ഞാൻ വാതിലിന്റെ അടുത്ത് നിൽക്കുന്നു.
ഞാൻ വാതിൽ തുറക്കുന്നു.
എന്റെ കൈയിൽ ഭാരമുള്ള ബാഗുകൾ ഉണ്ട്.
ഞാൻ പതുക്കെ അകത്തേക്ക് പോകുന്നു.
ഞാൻ വലിയ സ്യൂട്ട്കേസ് മുൻവാതിലിന്റെ അടുത്ത് വെക്കുന്നു.
ഇപ്പോൾ സ്യൂട്ട്കേസ് അവിടെ ഇരിക്കുന്നു.
ഒരു ചെറിയ ബാഗ് തറയിൽ കിടക്കുന്നു.
ഇപ്പോൾ ഞാൻ സ്വീകരണമുറിയിൽ ആണ്.
ഈ മുറിയിൽ നല്ല വെളിച്ചം ഉണ്ട്.
മുറിയിൽ കുറച്ച് ഫർണിച്ചർ ഉണ്ട്.
അവിടെ ഒരു വലിയ സോഫ ഇരിക്കുന്നു.
സോഫയുടെ അടുത്ത് ഒരു ചെറിയ മേശ ഉണ്ട്.
മേശയുടെ മുകളിൽ ഒരു പഴയ പുസ്തകം ഇരിക്കുന്നു.
ഞാൻ ജനലിന്റെ അടുത്ത് പോകുന്നു.
ജനുവരി മാസത്തിലെ നല്ല കാറ്റ് വരുന്നു.
ഞാൻ മുറിയുടെ നടുവിൽ നിൽക്കുന്നു.
ഞാൻ പുതിയ വീട് കാണുന്നു.
ഇത് എന്റെ സ്വന്തം വീട് ആണ്.
