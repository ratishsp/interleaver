Wychodzę do małej kuchni.
Moja torba podróżna stoi na podłodze.
Otwieram torbę.
W torbie jest dużo rzeczy.
Moje ulubione kubki leżą w torbie.
Wyjmuję kubki.
Nad blatem jest szafka.
Wstawiam kubki do szafki.
Teraz stoją na półce.
Mam też czerwony czajnik elektryczny.
Leży w torbie pod grubym swetrem.
Wyjmuję czajnik elektryczny.
Stawiam go na blacie kuchennym.
Teraz tuż przy zlewie stoi czerwony czajnik elektryczny.
W torbie leży też pudełko herbaty.
Biorę pudełko i kładę je przy czajniku elektrycznym.
Teraz kuchnia jest prawie gotowa.
Nie mogę się doczekać, żeby później wypić filiżankę herbaty.
