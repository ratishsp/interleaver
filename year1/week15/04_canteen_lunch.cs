Je dvanáct hodin.
Je čas na oběd.
Peter a já jdeme dolů do kantýny.
Kantýna je velká a světlá.
Máme velký hlad.
Díváme se na dobré jídlo.
Dnes je tu mnoho možností.
Vybírám si klasický obložený chléb.
Je s rybou a citronem.
Peter si bere velký salát.
Jdeme k pokladně.
U pokladny stojí přátelský muž.
„Bude to čtyřicet korun,“ říká mi.
Platím kartou.
„Tady máte,“ říkám.
„Děkuji a dobrou chuť,“ odpovídá.
Nacházíme volný stůl v rohu.
Sedáme si.
Jídlo chutná opravdu dobře.
Povídáme si o našem dni.
