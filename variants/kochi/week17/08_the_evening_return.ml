ഉച്ചയ്ക്ക് ശേഷം ഞാൻ മടക്കയാത്ര തുടങ്ങി.
നാല് മണിക്ക് ഞാൻ ബോട്ട് ജെട്ടിയിൽ തിരിച്ചെത്തി.
ഞാൻ തിരികെ പോകുന്ന ബോട്ടിൽ കയറി.
ബോട്ടിൽ ഒരുപാട് ആളുകൾ ഉണ്ടായിരുന്നു.
ചിലർ അവരുടെ സ്വന്തം ഫോണിൽ നോക്കി ഇരുന്നു.
വൈകുന്നേരത്തെ കാറ്റ് നല്ല തണുപ്പ് ആയിരുന്നു.
അഞ്ച് മണിക്ക് ഞാൻ റെയിൽവേ സ്റ്റേഷനിൽ എത്തി.
ഞാൻ എറണാകുളത്തേക്കുള്ള ട്രെയിനിനായി കാത്തുനിന്നു.
ആറ് മണിക്ക് എന്റെ ട്രെയിൻ വന്നു.
ഞാൻ ട്രെയിനിൽ കയറി ഒരു ജനാലയ്ക്കരികിൽ ഇരുന്നു.
എന്റെ ബാഗ് ഞാൻ സ്വന്തം മടിയിൽ വെച്ചു.
സൂര്യൻ അസ്തമിക്കാൻ തുടങ്ങി.
ആകാശത്ത് മനോഹരമായ നിറങ്ങൾ ഉണ്ടായിരുന്നു.
അത് വെള്ളത്തിലും തിളങ്ങി.
ഞാൻ ജനാലയിൽ തല വെച്ചു.
ഞാൻ ഇന്ന് ഒരുപാട് നടന്നു.
എന്റെ ശരീരത്തിന് നല്ല ക്ഷീണം ഉണ്ടായിരുന്നു.
പക്ഷേ, എന്റെ മനസ്സിന് വലിയ സന്തോഷം ആയിരുന്നു.
രാത്രി ഞാൻ കൊച്ചിയിൽ തിരിച്ചെത്തി.
