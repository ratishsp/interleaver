Jag går fram till bageridisken.
Doften är mycket god.
Jag tycker om kakor.
Och jag tycker verkligen om kanelbullar.
En bagare står bakom disken.
Bagaren tittar på mig.
Han ler.
"Vad vill du ha?" frågar bagaren.
Jag pekar på en kanelbulle.
Bullen ser läcker ut.
"Jag vill gärna ha en kanelbulle, tack," säger jag.
"Ja, självklart," säger bagaren.
Han tar bullen.
Han lägger bullen i en påse.
Han räcker påsen över disken.
"Varsågod," säger han.
Jag tar påsen.
"Tack så mycket," säger jag.
Jag lägger ner påsen i korgen.
