Metro přijíždí a dveře se otevírají.
Nastupuji do vlaku.
Vlak jede bez řidiče.
Jdu úplně dopředu.
Stojím u velkého okna.
Jedu metrem tmou.
Jsme v dlouhém tunelu.
Jedeme velmi rychle.
Světlo letí kolem okna.
Vypadá to fantasticky.
Malý kluk stojí vedle mě.
Také se dívá ven do tmy.
Často jezdím metrem.
Je to rychlá a snadná cesta.
Teď se blížíme k mojí stanici.
Jedu do přístavu.
Moje další cesta je přístavním autobusem.
Těším se, až uvidím vodu.
