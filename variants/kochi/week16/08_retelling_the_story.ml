അമ്മ പുഞ്ചിരിക്കുന്നു.
"നീ അവരോട് എങ്ങനെയാണ് ആ കഥ പറഞ്ഞത്?" അമ്മ ചോദിക്കുന്നു.
"അത് എന്നോട് ഒന്നുകൂടി പറയൂ."
ഞാൻ വീണ്ടും ആ കഥ പറയുന്നു, പക്ഷേ ഇത്തവണ വളരെ ചുരുക്കി.
"ജനുവരിയിൽ ഞാൻ കൊച്ചിയിൽ വന്നു."
"ഞാൻ വിമാനത്താവളത്തിൽ നിന്ന് ഒരു ടാക്സി വിളിച്ചു."
"ആദ്യത്തെ ദിവസം തന്നെ ഞാൻ അനിതയെ കണ്ടു."
അമ്മ എല്ലാം സന്തോഷത്തോടെ കേൾക്കുന്നു.
"എനിക്ക് ആ ജനുവരിയിലെ പ്രഭാതം ഓർമ്മ വരുന്നു," അമ്മ പറയുന്നു.
"മെക്സിക്കോ വിമാനത്താവളത്തിൽ വെച്ച് നീ ഞങ്ങളോട് യാത്ര പറഞ്ഞു."
"നീ ഉള്ളിലേക്ക് പോയി."
"അന്ന് എനിക്ക് വലിയ സങ്കടം തോന്നി."
"ഞാനും നിന്റെ അച്ഛനും കുറച്ചു നേരം അവിടെ നിന്നു."
ഞാൻ അമ്മയുടെ വാക്കുകൾ ശ്രദ്ധയോടെ കേൾക്കുന്നു.
"പക്ഷേ, ഇപ്പോൾ നീ അവിടെ പുതിയ സുഹൃത്തുക്കളെ കണ്ടെത്തി."
"അത് കേൾക്കുമ്പോൾ എനിക്ക് വലിയ സന്തോഷമുണ്ട്," അമ്മ പറയുന്നു.
