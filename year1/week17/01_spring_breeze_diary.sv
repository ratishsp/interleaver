Det är äntligen vår i Köpenhamn.
Jag går fram till fönstret i mitt vardagsrum.
Jag öppnar det och känner den varma brisen.
Luften är frisk och mild i kväll.
Kvällarna är plötsligt mycket ljusare nu.
Solen skiner fortfarande in på mitt bord.
Jag sätter mig på min stol.
Jag tar fram min resedagbok och en blå bläckpenna.
Jag älskar att skriva om mina upplevelser i Danmark.
Jag slår upp en tom sida i boken.
Jag tänker på min fantastiska helg.
Jag var på en lång resa i går.
Jag reste helt ensam till Odense.
Det var min första resa utanför Köpenhamn.
Jag ler, för att jag hade en riktigt bra dag.
Nu vill jag skriva ner allt.
Jag sätter pennan mot papperet och börjar min berättelse.
