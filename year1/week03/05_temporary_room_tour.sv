Min mamma tittar på skärmen.
"Är det ditt rum, Maya?" frågar hon.
"Ja, det är mitt rum," svarar jag.
"Men det är ett tillfälligt rum."
Jag lyfter min dator.
Jag visar mitt lilla rum för min familj.
"Här är en säng," säger jag.
"Och här är min nya växt."
"Det är en mycket fin växt," säger min mamma.
Jag vrider på min dator.
"Och här är ett fönster," säger jag.
Min syster Sofía tittar på mitt fönster.
"Men det är väldigt mörkt," säger hon.
"Ja, det är helt svart där ute," svarar jag.
"Men på sommaren är det massor av sol."
Det är kväll, och det är kallt.
"Men jag har min lampa," ler jag.
"Så det är ett bra rum."
