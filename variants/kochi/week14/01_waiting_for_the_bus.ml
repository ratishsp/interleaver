ഇപ്പോൾ രാവിലെ ആണ്.
വെയിലിന് നല്ല ചൂടുണ്ട്.
ഞാൻ ബസ് സ്റ്റോപ്പിൽ നിൽക്കുകയാണ്.
ഇത് എന്റെ വീടിന് അടുത്താണ്.
റോഡിൽ നല്ല തിരക്കുണ്ട്.
ഒരുപാട് വാഹനങ്ങൾ പോകുന്നുണ്ട്.
ഇന്ന് എനിക്ക് നഗരത്തിൽ ഒരു യാത്രയുണ്ട്.
ആദ്യം എനിക്ക് മെട്രോ സ്റ്റേഷനിലേക്ക് പോകണം.
അതുകൊണ്ട് ഞാൻ ബസ്സിനായി കാത്തുനിൽക്കുന്നു.
എനിക്ക് ബസ്സിൽ കയറണം.
മറ്റ് ചില ആളുകളും ഇവിടെ നിൽക്കുന്നുണ്ട്.
ഞാൻ എന്റെ വാച്ച് നോക്കുന്നു.
സമയം ഒൻപത് മണി ആണ്.
ദൂരെ നിന്ന് ഒരു ബസ് വരുന്നു.
പക്ഷേ അത് എന്റെ ബസ് അല്ല.
ഞാൻ വീണ്ടും കാത്തുനിൽക്കുന്നു.
