Sedám si na pohovku se svým telefonem.
Tyhle věci obvykle vyřizuji večer.
Otevírám webové stránky svého dodavatele elektřiny.
Doufám, že to nebude trvat moc dlouho.
Nejprve se musím přihlásit ke svému účtu.
Kliknu na menu a vyberu „aktualizovat profil“.
Na obrazovce se zobrazí digitální formulář.
Pečlivě si přečtu pokyny.
„Všechna povinná pole musí být vyplněna,“ píše se nahoře.
„Změny se ukládají automaticky,“ pokračuje text.
Sroluji dolů k poli pro kontaktní údaje.
Zadám své nové dánské číslo.
Pro jistotu si ta čísla říkám nahlas.
„Dvanáct, třicet čtyři, padesát šest, sedmdesát osm.“
Ještě jednou zkontroluji čísla na obrazovce.
Všechno vypadá správně, tak stisknu potvrdit.
