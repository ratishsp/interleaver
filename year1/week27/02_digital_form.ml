ഞാൻ എൻ്റെ ഫോണുമായി സോഫയിൽ ഇരിക്കുന്നു.
ഞാൻ സാധാരണയായി ഇത്തരം കാര്യങ്ങൾ വൈകുന്നേരമാണ് ചെയ്യാറുള്ളത്.
ഞാൻ എൻ്റെ വൈദ്യുതി വിതരണക്കാരുടെ വെബ്സൈറ്റ് തുറക്കുന്നു.
ഇതിന് അധികം സമയമെടുക്കില്ലെന്ന് പ്രതീക്ഷിക്കുന്നു.
ആദ്യം, ഞാൻ എൻ്റെ അക്കൗണ്ടിൽ ലോഗിൻ ചെയ്യണം.
ഞാൻ മെനുവിൽ ക്ലിക്ക് ചെയ്ത് "പ്രൊഫൈൽ അപ്ഡേറ്റ് ചെയ്യുക" എന്നത് തിരഞ്ഞെടുക്കുന്നു.
ഒരു ഡിജിറ്റൽ ഫോം സ്ക്രീനിൽ തെളിയുന്നു.
ഞാൻ നിർദ്ദേശങ്ങൾ ശ്രദ്ധാപൂർവ്വം വായിക്കുന്നു.
"ആവശ്യമായ എല്ലാ ഫീൽഡുകളും പൂരിപ്പിക്കണം," എന്ന് മുകളിൽ എഴുതിയിട്ടുണ്ട്.
"മാറ്റങ്ങൾ സ്വയമേവ സേവ് ചെയ്യപ്പെടുന്നതാണ്," വാചകം തുടരുന്നു.
കോൺടാക്റ്റ് വിവരങ്ങൾക്കായുള്ള ഫീൽഡിലേക്ക് ഞാൻ താഴേക്ക് സ്ക്രോൾ ചെയ്യുന്നു.
ഞാൻ എൻ്റെ പുതിയ ഡാനിഷ് നമ്പർ ടൈപ്പ് ചെയ്യുന്നു.
ഉറപ്പുവരുത്താനായി ഞാൻ അക്കങ്ങൾ സ്വയം ഉറക്കെ പറയുന്നു.
"പന്ത്രണ്ട്, മുപ്പത്തിനാല്, അൻപത്തിയാറ്, എഴുപത്തിയെട്ട്."
ഞാൻ സ്ക്രീനിലെ അക്കങ്ങൾ ഒരിക്കൽ കൂടി പരിശോധിക്കുന്നു.
എല്ലാം ശരിയാണെന്ന് തോന്നുന്നു, അതിനാൽ ഞാൻ അംഗീകരിക്കുക എന്നതിൽ അമർത്തുന്നു.
