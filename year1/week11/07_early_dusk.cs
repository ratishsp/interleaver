Pro dnešek jsem s prací skončila.
Balím si tašku.
Loučím se s Peterem v kanceláři.
Vycházím z kancelářské budovy.
Zastavuji se na ulici a dívám se na nebe.
Teď už jsem na to zvyklá.
Je teprve odpoledne.
Ale už je úplná tma.
Pouliční lampy jsou všude rozsvícené.
Město vypadá ve tmě úplně jinak.
Je to hodně jiné než v Mexiku.
Vítr stále silně fouká.
Teď se rychle ochlazuje.
Vytahuji si tlustou šálu výš.
Jdu po ulici ve slábnoucím světle.
Jdu směrem k autobusové zastávce.
Čekám na autobus ve tmě.
