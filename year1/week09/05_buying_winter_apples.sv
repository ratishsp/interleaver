Det är många människor på marknaden i dag.
Jag hittar ett litet fruktstånd.
Det finns många korgar i ståndet.
Korgarna är fulla av mörkröda vinteräpplen.
Jag tittar på en liten påse med äpplen.
"Hur mycket kostar en liten påse?" frågar jag försäljaren.
Han tittar i korgen.
"Priset är tjugo kronor," svarar han.
Jag tittar i min väska efter pengar.
Jag ger honom en femtiokronorssedel.
Försäljaren räcker mig påsen med äpplen.
Sedan ger han mig pengar tillbaka.
Jag får exakt trettio kronor tillbaka i mynt.
Mynten är tjocka och tunga.
Jag stoppar ner de tunga mynten i min kappficka.
Äpplena doftar mycket friskt.
Jag lägger ner påsen i min stora inköpskasse.
