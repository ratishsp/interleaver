ഞാൻ ഓഫീസിൽ പോകാൻ തയ്യാറാകുന്നു.
ഇന്ന് നല്ല ചൂടാണ്.
പുറത്ത് നല്ല വെയിലാണ്.
ഞാൻ എൻ്റെ പുതിയ ഇളം നീല കോട്ടൺ കുർത്ത ധരിക്കുന്നു.
ചൂട് സമയത്ത് ഈ കുർത്ത നല്ലതാണ്.
ഞാൻ എൻ്റെ ബാഗ് എടുക്കുന്നു.
എൻ്റെ കുട മേശപ്പുറത്തുണ്ട്.
ഞാൻ കുടയിലേക്ക് നോക്കുന്നു.
ഇന്ന് മഴ പെയ്യും.
കാലാവസ്ഥാ ആപ്പ് അങ്ങനെ പറയുന്നു.
പക്ഷേ ഇപ്പോൾ നല്ല വെയിലാണ്.
ആകാശത്ത് മേഘങ്ങളില്ല.
വൈകുന്നേരം മഴ പെയ്യുമോ?
ഇല്ല, ഇന്ന് മഴ പെയ്യുകയില്ല.
ഞാൻ കുട മേശപ്പുറത്ത് തന്നെ വയ്ക്കുന്നു.
ഞാൻ കുട ബാഗിൽ എടുക്കുന്നില്ല.
പകരം, ഞാൻ ഒരു വെള്ള കോട്ടൺ സ്കാർഫ് എടുക്കുന്നു.
ഞാൻ അത് ബാഗിൽ വയ്ക്കുന്നു.
വെയിലത്ത് ഈ സ്കാർഫ് വളരെ നല്ലതാണ്.
ഞാൻ ഓഫീസിലേക്ക് ഇറങ്ങുന്നു.
