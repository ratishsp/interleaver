Teď je mi velká zima.
Mám studené ruce.
Rozhlížím se po trhu.
Vidím malý vozík s kávou.
Za vozíkem stojí mladý muž.
Jdu k němu.
Zdravím baristu.
„Dobrý den, kolik stojí černá káva?“ ptám se.
Barista se usmívá.
„Horká černá káva stojí třicet korun,“ odpovídá.
V kapse kabátu mám mince.
Jsou to drobné, které mi vrátili za jablka.
Vyndávám mince ven.
Počítám je.
Mám přesně třicet korun.
„Prosím, tady je třicet korun,“ říkám.
Bere si peníze.
Podává mi horkou kávu.
Káva nádherně voní.
Hřeji si ruce o kelímek.
