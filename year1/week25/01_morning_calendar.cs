Je neděle ráno.
Slunce svítí oknem do mého bytu.
Jdu do kuchyně.
Připravuji si konvici čerstvé kávy.
Vůně kávy je dnes ráno fantastická.
Na zdi mám kalendář.
Otáčím stránku na další měsíc.
Teď je červenec.
V lednu jsem se přestěhovala do Kodaně.
Přijela jsem sem přesně před šesti měsíci.
Čas opravdu rychle utíká.
Můj první den v tomto městě byl velmi chladný.
Ale dnes je počasí teplé a krásné.
Chci oslavit toto malé výročí.
Dnes nemám žádné pevné plány.
Beru si šálek kávy a dívám se ven na ulici.
Chci jít ven a prozkoumat město vlastním tempem.
Těším se, že si tyto světlé hodiny užiji.
