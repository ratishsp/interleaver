ഇന്ന് രാവിലെ നല്ല ചൂടുണ്ട്.
ഞാൻ ഇപ്പോൾ എറണാകുളം മാർക്കറ്റിലാണ്.
ഒരുപാട് ആളുകൾ സാധനങ്ങൾ വാങ്ങുന്നു.
ചുറ്റും വലിയ ശബ്ദമുണ്ട്.
കച്ചവടക്കാർ ഉച്ചത്തിൽ വിളിച്ചു പറയുന്നു.
അവർ പുതിയ പച്ചക്കറികളും പഴങ്ങളും വിൽക്കുന്നു.
എനിക്ക് ഈ ആഴ്ചത്തേക്ക് കുറച്ചു സാധനങ്ങൾ വേണം.
എന്റെ കൈയിൽ തുണി സഞ്ചികൾ ഉണ്ട്.
ഞാൻ ഒരു സഞ്ചി പുറത്തെടുക്കുന്നു.
ഞാൻ മാർക്കറ്റിലൂടെ പതുക്കെ നടക്കുന്നു.
ഇവിടെ പലതരം കടകൾ ഉണ്ട്.
എനിക്ക് ആദ്യം പച്ചക്കറികൾ വാങ്ങണം.
