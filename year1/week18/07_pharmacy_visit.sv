På väg hem från läkaren går jag in på det lokala apoteket.
Jag tar en nummerlapp i automaten och väntar lite.
En vänlig farmaceut ropar upp nummer trettiofem.
Jag går fram till disken och visar mitt gula hälsokort.
Hon hittar mitt recept i datorn.
Farmaceuten ger mig en liten ask med allergipiller.
"Du borde ta ett piller varje morgon", säger hon.
Jag frågar henne om hon har något för min hals.
"Jag har fortfarande ont i halsen", förklarar jag.
Hon nickar och föreslår några söta halspastiller.
"De hjälper när halsen gör ont", säger hon.
"Och du borde också dricka mycket vatten i dag."
Jag tackar henne och köper pillren och pastillerna.
Det kostar åttiofem kronor totalt.
Jag är fortfarande trött och öm, men jag är glad över att ha medicinen.
Nu vill jag bara hem till min egen soffa.
