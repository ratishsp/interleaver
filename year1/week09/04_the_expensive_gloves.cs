Vítr dnes fouká chladně.
Moje ruce jsou velmi studené.
Vidím velký stánek s teplým oblečením.
Jdu k prodavači.
Má na stole mnoho teplých věcí.
Beru do ruky pár silných vlněných rukavic.
Jsou velmi měkké.
„Kolik ty rukavice stojí?“ ptám se.
„Stojí dvě stě korun,“ odpovídá prodavač.
Znovu se na rukavice podívám.
Dvě stě korun je vysoká cena.
To je pro mě příliš drahé.
Pokládám rukavice zpátky na stůl.
„Ne, děkuji,“ říkám zdvořile.
„Mějte hezký den.“
Prodavač přikývne a usměje se.
„Vám také,“ říká.
Jdu dál po trhu.
