Teď jsem unavená.
Pokládám svou knihu na stůl.
Jdu do koupelny.
Tady se připravuji na noc.
Beru si kartáček na zuby.
Čistím si zuby.
Potom si myji obličej.
Utírám se ručníkem.
Jdu do ložnice.
Oblékám si pyžamo.
Pak zhasínám světlo.
Teď je v bytě úplná tma.
Lehám si do postele.
Postel je teplá a měkká.
Přetahuji přes sebe peřinu.
Zavírám oči.
Jsem připravená na nový den.
Spím dobře.
