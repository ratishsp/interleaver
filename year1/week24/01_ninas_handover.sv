Det är fredag kväll, och Nina knackar på min dörr.
Hon har sin hund, Ludwig, med sig.
Han ska bo hos mig över helgen.
Nina ler och ger mig kopplet.
"Tusen tack för hjälpen, Maya", säger hon.
"Det är helt okej", svarar jag glatt.
Hon förklarar ett par saker om honom för mig.
"Ge honom mat klockan sju på morgonen och klockan sex på kvällen", säger Nina.
"Och kom ihåg, han får inte äta människomat."
Jag skrattar och tittar ner på den lilla hunden.
"Nej, Ludwig, min middag är inte för dig", säger jag till honom.
Nina skrattar också och pekar på dörren.
"Håll honom alltid i koppel när ni går nära den stora vägen", säger hon.
"I parken får han gärna springa fritt."
Jag nickar.
"Bara lugn, jag tar väl hand om honom."
Nina kramar mig och säger hejdå till oss.
Hon stänger dörren, och jag står ensam med Ludwig.
Han tittar upp på mig och viftar på svansen.
Jag tycker redan mycket om honom.
