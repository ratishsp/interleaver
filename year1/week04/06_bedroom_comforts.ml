ഞാൻ കിടപ്പുമുറിയിലേക്ക് പോകുന്നു.
ഞാൻ സ്വീകരണമുറിയിൽ നിന്ന് സ്യൂട്ട്കേസ് എടുത്തുകൊണ്ടുവരുന്നു.
ഞാൻ സ്യൂട്ട്കേസ് തുറക്കുന്നു.
ഞാൻ എന്റെ തുണികൾ പുറത്തെടുക്കുന്നു.
ഞാൻ തുണികൾ മടക്കിവെക്കുന്നു.
ഞാൻ അത് അലമാരയിൽ വെക്കുന്നു.
ഇപ്പോൾ എന്റെ സ്വെറ്ററുകൾ അലമാരയിലുണ്ട്.
മുറിയിൽ ഒരു വലിയ കട്ടിലുണ്ട്.
കട്ടിലിൽ ഒരു കട്ടിയുള്ള പുതപ്പുണ്ട്.
ആ പുതപ്പ് മെക്സിക്കോയിൽ നിന്നുള്ളതാണ്.
എനിക്ക് ഒരു ജോടി സ്ലിപ്പറുകൾ കൂടി കിട്ടുന്നു.
അവ വളരെ മൃദുലമാണ്.
ചുമരിനരികെ ഒരു ചെറിയ കസേരയുണ്ട്.
ഞാൻ എന്റെ സ്ലിപ്പറുകൾ തറയിൽ വെക്കുന്നു.
ഇപ്പോൾ അവ കസേരയ്ക്കടിയിലാണ്.
ഇപ്പോൾ സ്യൂട്ട്കേസ് കാലിയാണ്.
ഞാൻ അത് അടച്ച് കട്ടിലിനടിയിൽ വെക്കുന്നു.
