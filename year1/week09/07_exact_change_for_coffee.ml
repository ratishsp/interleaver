എനിക്കിപ്പോൾ വല്ലാതെ തണുക്കുന്നുണ്ട്.
എൻ്റെ കൈകൾ തണുത്തിരിക്കുന്നു.
ഞാൻ ആ മാർക്കറ്റിന് ചുറ്റും നോക്കുന്നു.
ഞാൻ ഒരു ചെറിയ കോഫി കാർട്ട് കാണുന്നു.
ആ കാർട്ടിന് പിന്നിൽ ഒരു ചെറുപ്പക്കാരൻ നിൽക്കുന്നുണ്ട്.
ഞാൻ അയാളുടെ അടുത്തേക്ക് നടന്നുചെല്ലുന്നു.
ഞാൻ ആ ബാരിസ്റ്റയോട് ഹലോ പറയുന്നു.
"ഹലോ, ഒരു ബ്ലാക്ക് കോഫിക്ക് എത്രയാണ് വില?" ഞാൻ ചോദിക്കുന്നു.
ബാരിസ്റ്റ പുഞ്ചിരിക്കുന്നു.
"ചൂടുള്ള ഒരു ബ്ലാക്ക് കോഫിക്ക് മുപ്പത് ക്രോണർ ആണ് വില," അയാൾ മറുപടി പറയുന്നു.
എൻ്റെ കോട്ടിൻ്റെ പോക്കറ്റിൽ നാണയങ്ങളുണ്ട്.
ആപ്പിൾ വാങ്ങിയപ്പോൾ എനിക്ക് ബാക്കി കിട്ടിയ പണമാണത്.
ഞാൻ ആ നാണയങ്ങൾ പുറത്തെടുക്കുന്നു.
ഞാൻ അവ എണ്ണിനോക്കുന്നു.
എൻ്റെ പക്കൽ കൃത്യം മുപ്പത് ക്രോണർ ഉണ്ട്.
"ഇതാ, ഇവിടെ മുപ്പത് ക്രോണർ ഉണ്ട്," ഞാൻ പറയുന്നു.
അയാൾ ആ പണം വാങ്ങുന്നു.
അയാൾ എനിക്ക് ആ ചൂട് കോഫി തരുന്നു.
കോഫിക്ക് വളരെ നല്ല സുഗന്ധമുണ്ട്.
ഞാൻ ആ കപ്പിൽ വെച്ച് എൻ്റെ കൈകൾ ചൂടാക്കുന്നു.
