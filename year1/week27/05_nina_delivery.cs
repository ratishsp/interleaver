Položím telefon na stůl a odpočívám.
Najednou někdo rychle zaklepe na mé dveře.
Přeruší to mé myšlenky.
Zvednu se z pohovky a jdu do předsíně.
Když otevřu dveře, na chodbě stojí Nina.
V rukou má malou papírovou krabici.
„Ahoj Mayo, mám pro tebe balíček,“ říká a usmívá se.
Podává mi krabici.
„Doručili mi ji už dříve odpoledne,“ vysvětluje Nina.
„Pošťák si asi omylem spletl naše dveře.“
Podívám se na krabici a vidím na ní své jméno.
„Jé!“
„To jsou má nová kávová zrna!“
„Většinou je kupuji na internetu,“ říkám jí.
„Normálně se balíčky nechávají dole u vchodu,“ říká Nina.
„Ano, většinou je dávají tam,“ odpovídám.
Převezmu papírovou krabici s velkým úsměvem.
Už teď slabě voní po pražené kávě.
„Moc děkuji, že jsi mi ji přinesla,“ říkám.
