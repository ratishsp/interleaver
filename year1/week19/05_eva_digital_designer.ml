ഉച്ചയ്ക്ക് ശേഷം കുറച്ചു കഴിഞ്ഞ്, ഞാൻ ഇവയുടെ ഡെസ്കിനടുത്തേക്ക് നടന്നു പോകുന്നു.
അവൾ ടീമിലെ ഡിജിറ്റൽ ഡിസൈനർ ആണ്.
ഇന്നുവരെ ഞാൻ അവളോടൊപ്പം ജോലി ചെയ്തിട്ടില്ല.
"ഹായ് മായാ, വന്ന് നോക്കൂ," അവൾ പറയുന്നു.
അവൾ അവളുടെ വലിയ സ്ക്രീനിലേക്ക് ചൂണ്ടിക്കാണിക്കുന്നു.
ഞങ്ങളുടെ പുതിയ സോഫ്റ്റ്‌വെയറിന്റെ മനോഹരമായ ചില രേഖാചിത്രങ്ങൾ ഞാൻ കാണുന്നു.
നിറങ്ങൾ ശാന്തമാണ്, കൂടാതെ ഡിസൈൻ വളരെ വ്യക്തവുമാണ്.
"ഇത് കാണാൻ വളരെ നന്നായിട്ടുണ്ട്," ഞാൻ പറയുന്നു.
"നന്ദി," ഒരു പുഞ്ചിരിയോടെ ഇവ മറുപടി നൽകുന്നു.
അവൾ അവളുടെ ജോലിയെക്കുറിച്ച് എനിക്ക് വിശദീകരിച്ചു തരുന്നു.
"സർവകലാശാലാ കാലം മുതൽ ഞാൻ ഒരു ഡിജിറ്റൽ ഡിസൈനറായി ജോലി ചെയ്യുകയാണ്," അവൾ പറയുന്നു.
"ഞാൻ എപ്പോഴും ഉപഭോക്താവിന്റെ അനുഭവത്തിൽ ശ്രദ്ധ കേന്ദ്രീകരിക്കുന്നു."
പ്രോഗ്രാമിൽ ഉപഭോക്താവ് എങ്ങനെയൊക്കെയാണ് ക്ലിക്ക് ചെയ്യുന്നതെന്ന് അവൾ എനിക്ക് കാണിച്ചു തരുന്നു.
"ഇത് ഉപയോഗിക്കാൻ എളുപ്പവും യുക്തിസഹവും ആയിരിക്കണം," അവൾ വിശദീകരിക്കുന്നു.
ഞാൻ മിക്കപ്പോഴും കോഡിലേക്ക് മാത്രമാണ് നോക്കാറുള്ളത്.
എന്നാൽ പ്രോജക്റ്റിന് അവളുടെ ഡിസൈൻ അങ്ങേയറ്റം പ്രധാനമാണ്.
ഞങ്ങളുടെ പൊതുവായ ജോലികളെക്കുറിച്ച് ഞങ്ങൾ അല്പം കൂടി സംസാരിക്കുന്നു.
അവളുടെ മനോഹരമായ ഡിസൈൻ പ്രോഗ്രാം ചെയ്യാൻ ഞാൻ കാത്തിരിക്കുകയാണ്.
