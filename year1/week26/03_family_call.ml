വൈകുന്നേരം, ഞാൻ എന്റെ കമ്പ്യൂട്ടറുമായി എന്റെ സോഫയിൽ ഇരിക്കുന്നു.
ഞാൻ മെക്സിക്കോയിലുള്ള എന്റെ കുടുംബത്തെ വിളിക്കുന്നു.
സ്ക്രീനിൽ എന്റെ മാതാപിതാക്കളെയും സഹോദരി സോഫിയയെയും സഹോദരൻ ഡീഗോയെയും കാണാം.
ഞങ്ങളുടെ നായ ലോലയും അവിടെയുണ്ട്.
"ജന്മദിനാശംസകൾ!" അവരെല്ലാവരും ചേർന്ന് വിളിച്ചുപറയുന്നു.
സോഫിയ ചോദിക്കുന്നു.
"ഞങ്ങളുടെ പാക്കേജ് നിനക്ക് കിട്ടിയോ?"
"അതെ, ഇന്നലെ പോസ്റ്റിൽ അത് വന്നു," ഞാൻ മറുപടി പറയുന്നു.
"നീ അത് തുറന്നു നോക്കിയോ?" അവൾ ആവേശത്തോടെ ചോദിക്കുന്നു.
ഞാൻ പുഞ്ചിരിച്ചുകൊണ്ട് മേശപ്പുറത്തുനിന്ന് വർണ്ണാഭമായ ഒരു സ്കാർഫ് എടുക്കുന്നു.
"ഞാൻ വീട്ടിൽ വന്നപ്പോൾ അത് തുറന്നു," എന്ന് പറഞ്ഞുകൊണ്ട് ഞാൻ ആ സ്കാർഫ് ഉയർത്തിക്കാണിക്കുന്നു.
"എനിക്ക് ഇതിലെ നിറങ്ങൾ വളരെ ഇഷ്ടമായി."
ഞാൻ ആ സ്കാർഫ് എന്റെ കഴുത്തിൽ ചുറ്റുന്നു.
"ഇത് നിനക്ക് നന്നായി ഇണങ്ങുന്നുണ്ട്," എന്റെ അമ്മ പറയുന്നു.
"ഇന്ന് നിനക്ക് നല്ലൊരു ദിവസമായിരുന്നോ?" എന്റെ അച്ഛൻ ചോദിക്കുന്നു.
"അതെ, നേരത്തെ എന്റെ സഹപ്രവർത്തകർ എനിക്കൊരു കേക്ക് വാങ്ങിത്തന്നിരുന്നു," ഞാൻ വിശദീകരിക്കുന്നു.
ഡീഗോ ലോലയെ ക്യാമറയ്ക്ക് നേരെ ഉയർത്തിപ്പിടിക്കുന്നു.
"ലോലയും കുറച്ച് കേക്ക് കഴിച്ചിട്ടുണ്ട്," അവൻ ചിരിച്ചുകൊണ്ട് പറയുന്നു.
ആ ചെറിയ നായയെ നോക്കി ഞാൻ ഉറക്കെ ചിരിക്കുന്നു.
വീട്ടിൽ നിന്നകലെയുള്ള എന്റെ ആദ്യത്തെ ജന്മദിനമാണിത്, എങ്കിലും അവർ വളരെ അടുത്തുള്ളതായി എനിക്ക് തോന്നുന്നു.
