Przede mną jest duże stoisko z serami.
Na stoisku jest wiele dużych serów.
Przyjazny sprzedawca uśmiecha się do mnie.
Ma mały kawałek sera na drewnianym patyczku.
„Proszę, to mała próbka do spróbowania” – mówi.
Podaje mi patyczek.
Jem żółty ser.
Smakuje naprawdę dobrze.
Patrzę na mały ser.
„Ile kosztuje ten ser?” – pytam.
„Kosztuje pięćdziesiąt pięć koron” – odpowiada sprzedawca.
To dobra cena.
Wskazuję na mały ser.
„Kupię go” – mówię.
Zawija ser w papier.
Daję mu pieniądze.
„Dziękuję bardzo” – mówi.
Ser pachnie mocno i przyjemnie.
